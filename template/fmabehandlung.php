                        <a id="fma"></a>
                        <hr />
                        <h5>Fruktose-Malabsorption &ndash; eine Krankheit?</h5>
                        <hr />
                        Eine Fruktose-Malabsorption kann &ndash; im Gegensatz zu einer Laktose-Intoleranz 
                        &ndash; als Krankheit angesehen werden, vorausgesetzt, die Malabsorption tritt nicht 
                        auf, weil mit der Nahrung viel zuviel Fruchtzucker aufgenommen wird (bitte lesen Sie hierzu 
                        auch die Seite &#187;<a href="wasistfma" target="_blank">Was ist 
                        Fruktose-Intoleranz?</a>&#171;).
                        <br />
                        <br />
                        Heilbar ist die FMA nicht, es kann jedoch mit einer angepassten, fruktosearmen 
                        Ernährung eine weitestgehende Beschwerdefreiheit erreicht werden.
                        <br />
                        <br />
                        Auch eine Ernährung, die möglichst frei von Haushaltszucker ist, ist bei 
                        einer FMA angeraten &ndash; zumindest in der Anfangsphase, bis man herausgefunden hat, 
                        welche Nahrungsmittel einem besser oder schlechter bekommen.
                        <br />
                        <a id="medikamente">&nbsp;</a>
                        <hr />
                        <h5>Medikamente</h5>
                        <hr />
                        Da das fehlende oder nicht ausreichende Transportprotein GLUT5 nicht künstlich 
                        hergestellt und als Medikament verabreicht werden kann, ist es leider nicht möglich, 
                        es &ndash; wie beispielsweise das Laktase-Enzym bei einer Laktose-Intoleranz &ndash; 
                        in Tablettenform zu substituieren (ersetzen/ergänzen).
                        <br />
                        <br />
                        Jedoch ist auffällig, dass bei einer FMA oftmals die Konzentrationen der Aminosäure 
                        Tryptophan, dem Vitamin B9 (Folsäure) und dem Spurenelement Zink im Blut erniedrigt 
                        sind. Durch die Ergänzung dieser Stoffe kann &ndash; bei gleichzeitiger, möglichst 
                        fruktosearmer Ernährung &ndash; unter Umständen eine Beschwerdebesserung 
                        herbeigeführt werden.
                        <br />
                        <a id="darmflora">&nbsp;</a>
                        <hr />
                        <h5>Pflege von Darmflora und Darm</h5>
                        <hr />
                        Zusätzlich zu einer angepassten Ernährung helfen die Pflege der Darmflora 
                        und des Darmes. Hierbei sollte auf eine möglichst naturbelassene Ernährung 
                        geachtet werden. Zwar sind Vollkornprodukte fruktosehaltiger als Produkte aus weißem 
                        Mehl, es ist aber durchaus hilfreich, hier eine gesunde Balance zu finden, denn 
                        die Ballaststoffe in den Vollkornprodukten pflegen die Darmschleimhaut: Wie bei 
                        einem Peeling schmirgeln die harten Schalen die abgestorbenen Zellen der Darmschleimhaut 
                        ab und ermöglichen es so den jungen Zellen, ihre Funktionen optimal zu erfüllen. 
                        <br />
                        <br />
                        In einer so gepflegten Darmschleimhaut können sich nützliche Darmbakterien 
                        bestmöglich vermehren und so krankmachenden Keimen wenig Platz und Nährboden 
                        bieten. Somit bildet sich eine gesund ausbalancierte Darmflora, die zu Ihrem 
                        Wohlbefinden beiträgt.
                        <br />
                        <br />
                        Der oben erwähnte Hinweis auf einen möglichst geringen Verzehr von Haushaltszucker 
                        ist deshalb wichtig, weil sich schädliche Darmbakterien vorrangig von Zucker 
                        ernähren &ndash; und dieser Nährboden sollten ihnen entzogen werden. 
                        Somit haben günstiger wirkende Bakterien die Möglichkeit, sich zu vermehren 
                        und eine gesündere Zusammensetzung der Darmflora zu bewirken.
                        <br />
                        <a id="probiotika">&nbsp;</a>
                        <hr />
                        <h5>Unterstützung der Darmflora mit Pro- und Präbiotika</h5>
                        <hr />
                        Als Probiotika bezeichnet man Darmbakterien, die für den Menschen günstige 
                        Wirkungen entfalten. Hier sind insbesondere Milchsäurebakterien zu nennen, 
                        die neben einer günstigen Wirkung in Bezug auf den Milchzucker insgesamt ein 
                        optimales Milieu im Darm erzeugen. Deshalb eignet sich der verstärkte Verzehr 
                        von milchsauer eingelegtem Gemüse wie Sauerkraut, Roter Beete, Mixed Pickles u.Ä.
                        <br />
                        <br />
                        Als Präbiotika werden Stoffe bezeichnet, die eigentlich für den Menschen 
                        unverdaubar sind, jedoch als &#187;Futter&#171; für die vorteilhaften Darmbakterien 
                        dienen können. Mit dem Verzehr von präbiotischen Nahrungsbestandteilen 
                        wird die Vermehrung der günstigen Darmbakterien unterstützt &ndash; die 
                        Darmflora wird somit mit diesen für den Menschen vorteilhaften Bakterienarten 
                        angereichert, die ungünstiger wirkenden oder gar krank machenden werden 
                        zurückgedrängt. 
                        <br />
                        <br />
                        Viele pflanzliche Nahrungsmittel wie z.B. Chicoree, Schwarzwurzeln oder auch die 
                        Topinamburknolle enthalten einen hohen Anteil an präbiotischen Inhaltsstoffen. 
                        Präbiotika werden auch als Präparate zum Einnehmen in Apotheken oder Reformhäusern 
                        angeboten. Hier ist insbesondere das Inulin zu nennen, das eine günstige, 
                        verstärkende Wirkung auf Probiotika haben kann (nicht zu verwechseln mit dem 
                        Insulin, das für die Zuckerverwertung besonders den Diabetikern bekannt ist). 
                        Oftmals werden Kombipräparate aus Pro- und Präbiotika angeboten. 
                        <b>Für empfindliche Menschen insbesondere solche mit einer Fruktose-Intoleranz 
                        sei jedoch der Hinweis angebracht, dass Präbiotika u.U. selber Unverträglichkeitsreaktionen 
                        hervorrufen können. Eine vorsichtige Dosierung ist also unbedingt angeraten. </b> 
                        <br />
                        <a id="darmgymnastik">&nbsp;</a>
                        <hr />
                        <h5>Darmgymnastik</h5>
                        <hr />

                            <a href="book-darmgymnastik" target="_blank">
                                <img src="<?php echo IMG_PATH; ?>book-darmgymnastik-middle.png" alt="Darmgymnastik" class="inline" /></a>
                        Bei der Behandung und zur Vorbeugung unangenehmer Symptome einer Fruktose-Intoleranz (wie auch einer jeden anderen Nahrungsmittel-Unverträglichkeit 
                        und bakteriellen Fehlbesiedelungen der verschiedenen Darmabschnitte) ist neben allen oben beschriebenen Maßnahmen <b>grundsätzlich die kontinuierliche 
                        Bewegung eine unverzichtbare Komponente</b>. Hier und bei allen Verdauungsbeschwerden ist wichtig, dass der <b>Transport des Speisebreis durch den 
                        Darm so gleichmäßig wie möglich</b> abläuft. Dies wird am besten erreicht mit einer kontinuierlichen Anregung der Verdauungsdrüsen und des Darms. 
                        Dazu eignen sich weniger die wenigen sportlichen Aktivitäten am Abend oder am Wochenende, sondern in möglichst engmaschigen zeitlichen 
                        Abständen durchgeführte Atem- und Bewegungsübungen. 
                        <br />
                        <br />
                        In dem Buch <a href="book-darmgymnastik" target="_blank">&#187;Darmgymnastik &#38; mehr 
                        gegen Verdauungsbeschwerden&#171;</a> finden Sie viele Anregungen dazu. Zusätzlich sind Akupressurpunkte aufgeführt, deren Stimulation bei allen 
                        Verdauungsbeschwerden wirksam sind. Weiterhin werden zusätzliche Hilfsmaßnahmen und Hilfsmittel vorgestellt, die die Behandlung von 
                        Verdauungsproblemen effektiv unterstützen können. Und last, but not least, gibt es ein Kapitel mit Fragen, die in meiner Praxis immer wieder 
                        zu diesem Themenkomplex gestellt werden.                  
                        <br />
                        <br />
                        <a id="entspannung">&nbsp;</a>
                        <hr />
                        <h5>Entspannung</h5>
                        <hr />
                        Häufig wird eine Nahrungsmittel-Intoleranz auch begleitet von einem Reizdarm-Syndrom. 
                        Dieses kann günstig beeinflusst werden durch eine vernünftige Balance 
                        zwischen Anregung und Entspannung. Sollten Ihre Beschwerden sich also trotz konsequenter, 
                        fruktosearmer Ernährung nicht zu Ihrer Zufriedenheit reduzieren, so versuchen Sie (
                        auch in Rücksprache mit Ihrem Arzt), verschiedene Entspannungstechniken zu 
                        erlernen (autogenes Training, progressive Muskelentspannung nach Jacobson, Quigong). 
                        Oftmals sind Entspannungsübungen sehr hilfreich, um Beschwerden bei Fruktose-Intoleranz 
                        günstig zu beeinflussen.
