                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=verdauung" target="_blank">Schwerpunktthema: &#187;Gesunde Verdauung&#171;</a></b>
                        <br />
                        <i>(Menü: Wissensdatenbank/Darmgesundheit/Darmgesundheit &ndash; allgemein/Gesunde Verdauung)</i>
                        <br />
                        Der Beitrag &#187;Gesunde Verdauung&#171; ist bewusst in die Bereiche Beschwerden, Ursachen und M&ouml;gliche Behandlungsoptionen aufgeteilt &ndash; 
                        und zwar in dieser Reihenfolge. Bei Beschwerden schauen Sie sich am besten zuerst an, welche Symptome Sie haben &ndash; und vielleicht ist es ja nicht 
                        nur eine Stelle, die &#187;zwackt&#171;. Meist kommen solche Probleme im Doppel- oder Dreifachpack, und es bestehen auch noch andere Beschwerden, 
                        die Sie noch gar nicht so bewusst wahrgenommen haben. Ich m&ouml;chte in dem Beitrag &uuml;berhaupt nicht den Teufel an die Wand malen, aber es ist 
                        wichtig, genau in sich hinein zu h&ouml;ren. Das erleichtert dann die Analyse des Geschehens. Anschlie&#223;end ziehen Sie Bilanz, welche Ursachen 
                        vorliegen k&ouml;nnten. Das kann eventuell ein wenig anstrengend sein, denn es geh&ouml;rt Ehrlichkeit dazu, wenn wir bef&uuml;rchten, zur 
                        L&ouml;sung unsere liebgewonnenen Gewohnheiten &auml;ndern zu m&uuml;ssen.                        
