                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=stuhlgang" target="_blank">&#187;Stuhlgang &ndash; Probleme und L&ouml;sungen&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: (Menü: Wissensdatenbank/Darmgesundheit/Darmgesundheit &ndash; allgemein/Stuhlgang &ndash; Probleme und L&ouml;sungen)</i>
                        <br />
                        Woher kommt das Wort &#187;Stuhlgang&#171;? W&auml;hrend in fr&uuml;heren Zeiten die &auml;rmeren Bev&ouml;lkerungsschichten ihre Notdurft entweder in 
                        der Natur oder auf dem Misthaufen erledigten, konnten Kaiser und K&ouml;nige den Luxus eines Gangs zum &#187;Kackstuhl&#171; genie&#223;en &ndash; dem 
                        Stuhlgang. Dieser war &ndash; wie der Name sagt &ndash; nichts anderes als ein Stuhl mit einem Loch in der Sitzfl&auml;che, unter dem ganz diskret ein 
                        Eimer angebracht war, den Bedienstete nach dem Stuhlgang ihrer Herrschaften leeren mussten. F&uuml;r den &#187;P&ouml;bel&#171; gab es sp&auml;ter 
                        Plumpsklos. Wassergesp&uuml;lte Klosetts gab es seit dem sp&auml;ten 16. Jahrhundert, modernere WCs wurden 200 Jahre sp&auml;ter entwickelt. 
                        Diese nennen wir die wir heute franz&ouml;sisch-fein Toiletten.  
                        Das Wort Stuhlgang hat sich bis heute gehalten, aber bezieht sich jetzt nicht mehr auf das Badezimmerm&ouml;bel, sondern sowohl auf den Gang zur 
                        Toilette als auch auf den abgesetzten Kot oder auch F&auml;kalien (vom lateinischen Begriff faeces), das Wort &#187;Stuhl&#171; steht f&uuml;r den 
                        abgesetzten Kot, weil es unfein ist, das Kind beim Namen zu nennen. Nur noch Kinder d&uuml;rfen von &#187;Kacka&#171; sprechen.
                        <a href="http://www.dorispaas.de/index.php?page=stuhlgang" target="_blank"> Lesen Sie hier gerne weiter ...</a>
