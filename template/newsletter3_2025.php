                        Liebe Leserin, lieber Leser, es gibt f&uuml;r fast alles einen Gedenktag &ndash; und trotzdem fehlen mir welche: f&uuml;r Kopfschmerzen gibt es einen 
                        Gedenktag am heutigen 5. September, aber es gibt keinen &#187;Gedenktag f&uuml;r Bauchschmerzen&#171;. Jeweils am 7. M&auml;rz gibt es den &#187;Tag 
                        der gesunden Ern&auml;hrung&#171;, jedoch einen &#187;Tag der gesunden Verdauung&#171; vermisse ich. Aber vielleicht konnten wir uns ja mit 
                        dem &#187;Tag des Toilettenpapiers&#171; ein wenig tr&ouml;sten, der am gerade vergangenen 26. August begangen wurde. Bitte verstehen Sie mich nicht falsch: 
                        ich pl&auml;diere nicht ernsthaft für die Einf&uuml;hrung weiterer Gedenktage. Auf jeden Fall aber sollten wir unserer Verdauung und unserem 
                        Stuhlgang mehr Aufmerksamkeit schenken.
