                        <h5>Meine Informationsquellen</h5>
                        <hr />
                        Am Anfang der Corona-Pandemie dachten noch viele &ndash; wie auch ich &ndash; dass die Covid-19-Erkrankung 
                        weniger gravierend als eine &#187;normale&#171; Grippe verlaufen würde. Im Laufe der Zeit kristallisierten sich 
                        jedoch auch für die Wissenschaftler &ndash; für die ja diese Erkrankung ebenfalls Neuland bedeutet &ndash; mehr 
                        und mehr die verschiedenen Facetten und damit auch die Brisanz dieser Lungenerkrankung heraus, und ich bin dankbar 
                        für die zahlreichen seriösen und laufend aktualisierten Informationen, die mittlerweile in den Medien zur 
                        Verfügung gestellt werden.
                        <br />
                        <br />
                        Um diesen Beitrag schreiben zu können, beziehe ich mich auf zahlreiche Quellen, und ich höre, lese und verfolge 
                        täglich für mehrere Stunden die Angebote. Insbesondere sind dies die Artikel in seriösen Tages- und Wochenzeitschriften, 
                        aber auch Beiträge, Sendungen, Interviews und Diskussionsrunden im Fernsehen, Podcasts von Wissenschaftlern wie u.a. 
                        Virologen oder auch Wirtschaftswissenschaftlern. Insbesondere möchte ich Ihnen hier die Namen Christian Drosten mit 
                        seinem <a href="https://www.ndr.de/nachrichten/info/podcast4684.html" target="_blank">&#187;Corona-Virus Update&#171; im NDR</a>
                        , aber auch andere Virologen wie u.a. Jonas Schmidt-Chanasit, Alexander Kekul&#233;, (bedingt) Hendrick Streek, das
                        <a href="https://www.rki.de/DE/Content/InfAZ/N/Neuartiges_Coronavirus/nCoV.html" target="_blank">Robert Koch Institut</a> 
                        und viele andere nennen, die auf den verschiedenen Kanälen oder als geladene Fachleute in Fernsehsendungen sehr genaue 
                        Hintergrundinformationen liefern. Diese Wissenschaftler und Organisationen sind sich durchaus nicht immer bzw. in jedem 
                        Detail einig, aber gerade darum bekommt man ein sehr differenziertes Bild von der Materie. 
                        <br />
                        <br />
                        Auch Beiträge von Pflegepersonal auf Intensiv- und Coronastationen, Rettungssanitätern oder Feuerwehrleuten verfolge 
                        ich mit großem Interesse, denn diese liefern Eindrücke der Vorgänge an &#187;vorderster Front&#171;. Hier möchte ich Ihnen 
                        u.a. die Sendung <a href="https://www.ardaudiothek.de/fighting-corona-mit-tobi-schlegl/74626328" target="_blank">&#187;Fighting 
                        Corona&#171; mit Tobi Schlegl</a> ans Herz legen.
                        <br />
                        <br />
                        Da ich mich auch in den sozialen Netzwerken bewege, sichte ich auch hier die Informationen. Leider tummeln 
                        sich aber gerade hier in erschreckend hohem Maße die Anhänger der diversesten Verschwörungstheorien in ihren Blasen. 
                        Es vermischen sich hier die verschiedensten Interessengruppen zu einer fatalen Gemengelage &ndash; angefangen von den Verleugnern, über die 
                        Impfgegner, Antisemiten und Fremdenhasser bis hin zu rechts- oder linksextremen Gruppierungen, die diese für alle 
                        neue Situation mit nicht belegbaren &#187;Informationen&#171;, teils sogar (lebens-)gefährlichen Heilsversprechen 
                        oder schlichten Fake-News für sich instrumentalisieren wollen. 
                        <br />
                        <br />
                        Aber um mir auch in diesem Bereich ein eigenes Bild machen zu können, sehe ich mir auch einige dieser Beiträge an. 
                        Beispielhaft sind hier Menschen wie der freie Journalist und Antisemit Ken Jebsen, der Fernsehkoch Attila Hildmann aber auch viele andere 
                        nennen, deren &#187;fachliche&#171; Äußerungen zum Thema Corona zumindest nicht auf einer einschlägigen
                        Ausbildung fußen. Es erstaunt mich, mit welchem Aufwand zum großen Teil auch blutige Laien ihr &#187;Wissen&#171; zum Besten 
                        geben und scheinbar Erfolg damit haben, andere von &#187;Tatsachen&#171; zu überzeugen, obwohl man hier eigentlich 
                        auf den ersten Blick erkennen müsste, welcher Unsinn dort verzapft wird. Unglücklicherweise melden sich aber 
                        auch Menschen wie u.a. Wolfgang Wodarg zu Worte, der zumindest kein ausgewiesener Fachmann in Sachen Vorologie ist, 
                        sich aber trotzdem anmaßt, sein Arztsein dazu zu benutzen, dem unkritischen Zuschauer als Fachmann in der Sache 
                        gegenüberzutreten. Und last, but not least, kommen noch all die Menschen in weißen Kitteln ohne belegbare Vita hinzu, die es in 
                        Youtube-Videos vor einem &#187;wissenschaftlich angehauchten&#171;, mit Mikroskopen und Reagenzgläsern bestückten Ambiente schaffen, 
                        ihre &#187;wissenschaftlichen Erkenntnisse&#171; leider sehr überzeugend zu vermitteln &ndash; wenn man 
                        nicht aufpasst und sich umfassender informiert.
                        <br />
                        <br />
                        Immer wieder werden in solchen Internetbeiträgen auch Interviews, Dokumentationen und Fernsehfilme zitiert, die zu einem sehr viel früheren
                        Zeitpunkt und Entwicklungsstand der Pandemie oder sogar auf ähnliche Pandemien mit einem ganz anderen Virus beziehen. Hier muss man schon sehr 
                        genau hinschauen, dass manche Äußerungen eben auf einem anderen Erkenntnisstand basieren und von den Interviewten teilweise
                        nachträglich geändert und zurückgenommen wurden &ndash; was keineswegs eine Schwäche ist, als die sie die Zweifler und Verleugner gerne 
                        hinstellen möchten. Im Gegenteil: es zeugt von Stärke und Sorgfalt, wenn ein Wissenschaftler bei seinen Erkenntnissen den aktuellen 
                        Wissensstand mit berücksichtigt. Trotzdem ist es interessant, sich auch diese teils jahre- oder jahrzehntealten Beiträge anzuschauen, denn
                        bestimmte Fakten &ndash; wie die Verflechtung der Pharmaindustrie und ihr Einfluss auf Entscheidungen der Politik &ndash; sind auch heute 
                        noch aktuell. Z.B. der inzwischen auf Youtube zur Verfügung gestellte Beitrag 
                        &#187;<a href="https://www.youtube.com/watch?v=1--c2SBYlMY" target="_blank">Profiteure der Angst</a>&#171; des Fernsehsenders Arte stammt zwar aus dem Jahr 2009, ist
                        aber bestimmt auch heute noch genauso aktuell. (Hier kommt übrigens auch der oben erwähnte Wolfgang Wodarg zu Worte, der im damaligen 
                        Zusammenhang und seiner damaligen Funktion sicherlich etwas beizutragen hatte. Aber so, wie er sich aktuell in Sachen Corona-Virus äußert, 
                        kann ich dies nur noch als &#187;verbiestert&#171; bezeichnen.) <b>In der Sache der Gefährlichkeit</b> mit dem SARS-CoV-2 werden diese Beiträge 
                        aber nach meinen (derzeitigen) Erkenntnissen instrumentalisiert und haben nichts damit zu tun. <b>Man muss also immer sehr genau hinschauen, wer in welchem 
                        Zusammenhang und zu welchem Zeitpunkt etwas sagt.</b>
                        <br />
                        <br />
                        Jeder, der sich zum Thema &#187;Corona&#171; äußert, sollte seine Quellen nennen &ndash; allein schon auch, um wenigsten ein wenig abschätzen zu können,  
                        wie einseitig oder wie umfassend sich der- oder diejenige informiert hat. Die Hintergründe zu diesem 
                        Virus, seiner Herkunft, seiner Verbreitung, seinem Ansteckungspotenzial, seiner Auswirkung im Krankheitsfalle 
                        und Heilungsmöglichkeiten sind selbst bei den ausgewiesenen Fachleuten &ndash; das sind in meinen Augen 
                        ausschließlich die Virologen und in dieser Fachrichtung ausgebildeten Ärzte &ndash; noch keineswegs abschließend erforscht. 
                        Schon gar nicht kann man sich (allein und überhaupt) auf die Äußerungen von Laien &ndash; und das sind in meinen Augen alle, 
                        die <b>keine</b> Virologen bzw. Fachärzte sind &ndash; belastbar stützen. 
                        <br />
                        <br />
                        Wie Sie unschwer feststellen können, habe ich eine klare Meinung zu den selbsternannten &#187;Fachleuten&#171;, informiere 
                        mich aber trotz allem sehr breit gefächert, um zu wissen, welche Theorien auch in dieser Richtung kursieren, und ich möchte 
                        Sie ausdrücklich ermuntern, sich ebenfalls in <b>alle</b> Richtungen zu  informieren. Erst, wer sich wirklich umfassend informiert
                        und seine Quellen nachvollziehbar nennt, kann und darf für sich in Anspruch nehmen, eine <b>begründete Meinung</b> zu haben.
