                        Es gibt Atem- und Bewegungsübungen, die Sie durchführen können, um all diesen Gefahren begegnen oder sogar vorbeugen zu können. Gemeint sind an dieser Stelle nicht 
                        die allgemein empfohlenen Verhaltensweisen, um eine Ansteckung mit dem Virus zu vermeiden &ndash; deren Befolgung ich Ihnen aber bitte in Ihrem 
                        eigenen Interesse trotzdem zusätzlich ganz dringend ans Herz legen möchte. 
                        <br />
                        <br />
                        Wir alle kennen das: mit einem tiefen Atemzug kann man Anspannung lösen und den Stress quasi herauspusten. Zudem werden mit einem kräftig arbeitenden
                        Zwerchfell &ndash; unserem wichtigsten Atemmuskel &ndash; die Verdauungsdrüsen und der Darm so richtig von oben durchgeknetet. Das optimiert die 
                        Verdauungsleistung und damit auch unsere Gesundheit als Ganzes.
                        <br />
                        <br />
                        Und dann gibt es die Dehnungsübungen. In einer Krisensituation, wie es u.a. die Coronakrise ist, spannen wir automatisch alle unsere Muskeln an
                        und sind im wahrsten Sinne des Wortes erstarrt. Dehnungsübungen können diese Erstarrung lösen und helfen uns nicht nur körperlich, sondern auch psychisch 
                        zu entspannen.
                        <br />
                        <br />
                        Darmgymnastik-Übungen eigen sich auch unabhängig von einer Krisensituation zur Optimierung der Verdauung und bei sämtlichen Verdauungsbeschwerden 
                        als behandlungsbegleitende Maßnahme, aber genauso gut auch &#187;einfach nur&#171; zur Entspannung und Steigerung des Wohlbefindens.
                        <br />
                        <br />
                        In dem Buch <a href="book-darmgymnastik" target="_blank">&#187;Darmgymnastik &#38; mehr 
                        gegen Verdauungsbeschwerden&#171;</a> finden Sie viele Anregungen dazu. Zusätzlich sind Akupressurpunkte aufgeführt, deren Stimulation bei allen 
                        Verdauungsbeschwerden wirksam sind. Weiterhin werden zusätzliche Hilfsmaßnahmen und Hilfsmittel vorgestellt, die die Behandlung von 
                        Verdauungsproblemen effektiv unterstützen können. Und last, but not least, gibt es ein Kapitel mit Fragen, die in meiner Praxis immer wieder 
                        zu diesem Themenkomplex gestellt werden.                  
