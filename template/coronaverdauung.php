                        Sie fragen sich vielleicht: &#187;Was hat denn die Verdauung mit der Corona-Krise zu tun?&#171; 
                        Gerade ein so empfindliches und störanfälliges System wie die Verdauung kann mehr oder weniger 
                        stark beeinträchtigt werden durch die Umstände, die mit einer Krise, mit heftigen und vor allem 
                        ungewohnten Ge- und Verboten für die gesamte Gesellschaft und mit dem damit verbundenen 
                        Stress einhergehen. Insbesondere Menschen, die ohnehin schon Probleme mit der Verdauung haben &ndash; 
                        sei es durch Nahrungsmittel-Unverträglichkeiten oder -Allergien, durch eine Zöliakie oder eine 
                        Chronisch entzündliche Darmerkrankung, durch ein Reizdarm-Syndrom oder eine Dünndarmfehlbesiedelung 
                        oder durch sonstige Verdauungsbeschwerden &ndash; können besonders betroffen sein, denn die 
                        Beschwerden können sich unter solchen widrigen Voraussetzungen verschlimmern. Diese Zusammenhänge 
                        möchte ich an dieser Stelle herausarbeiten.
                        <br />
                        <br />
                        <b>Der Sinn dieses Beitrags soll deshalb nicht darin bestehen, Sie über das Corona-Virus an sich zu informieren oder 
                        Sie von der Gefährlichkeit der Fake-News zu überzeugen</b> &ndash; wobei ich Sie trotzdem inständig bitten möchte, 
                        jede in den Medien kursierende Information genau anzuschauen und die Plausibilität zu hinterfragen. Mit diesem Beitrag möchte ich Ihnen aber 
                        umfassend und korrekt die Zusammenhänge und Hintergründe in Sachen &#187;Verdauung in der Corona-Krise&#171; 
                        erklären. Aus diesem Grunde bitte ich Sie &ndash; unabhängig davon, welche Meinung Sie zu der Corona-Situation 
                        vertreten &ndash; <b>den Beitrag bis zum Schluss zu lesen</b>, denn in Bezug auf die Auswirkungen auf Ihre 
                        Verdauung ist es tatsächlich relativ unerheblich, ob Sie seriösen Quellen oder dubiosen Informationen Glauben schenken.
                        <br />
                        <br />
                        Trotzdem ist es keineswegs unerheblich, zu wissen, auf welcher Basis mein Wissen fußt, denn für jeden &ndash; 
                        unabhängig davon, in welchem Zusammenhang man die Corona-Krise sieht und wie man den Wahrheitsgehalt der Informationen 
                        bewertet &ndash; ergeben sich für <b>alle</b> ähnliche Änderungen, Ängste und Stresssitiationen, die sich auf die 
                        Verdauung auswirken können.
                        <br />
                        <br />
                        Ich bitte Sie herzlich, den Abschnitt &#187;<a href="<?= URL_ROOT ?>coronaverdauung#quellen">Meine Informationsquellen</a>&#187; 
                        am Schluss dieses Beitrag zu lesen.
                        <br />
                        <br />
                        <b>Hinweis:</b> Dieser Beitrag zeigt die typischen Problematiken rund um die Verdauung <b>am Beispiel der Corona-Krise</b> auf. <b>Das Gleiche 
                        gilt aber genauso auch für alle anderen problematischen Lebenssituationen</b>. Corona zeigt uns gerade besonders deutlich wie in einem Brennglas, 
                        was sich alles in einer Krisensituation verändert, vor allem, weil es uns alle betrifft und nicht nur &ndash; vermeintlich &ndash; mich selbst.
                        Alle hier thematisierten Zusammenhänge, Hintergründe und Lösungsansätze können deshalb auch auf andere kritische Lebenssituationen
                        angewendet werden.
