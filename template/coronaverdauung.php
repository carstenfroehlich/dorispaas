                        <br />
                        <hr />
                        <h5>Bewertung der Situation</h5>
                        <hr />
                        Versuchen Sie bitte vor allem, Wege zu finden, Ihren Stress zu minimieren. Ich kann hier an dieser Stelle wenig konkrete Vorschläge dazu 
                        beitragen, denn Ihre eigenen Gegebenheiten sind immer ganz individuell. Hilfreich ist vielleicht jedoch der Tipp, dass Sie versuchen sollten, 
                        nicht allzu sehr mit der Situation zu hadern: Fremdbestimmung &ndash; insbesondere solche, die man nicht einsieht &ndash; wird immer sehr 
                        viel einschneidender empfunden, als wenn man sein Leben zumindest zum großen Teil selbst in die Hand nehmen kann.
                        <br />
                        <br />
                        Vielleicht können Sie sich die Zeit nehmen, einmal Ihren persönlichen Ist-Zustand zu analysieren und zu schauen, welche Alternativen es gibt. 
                        Unter Umständen ergeben sich ja durch die derzeit erforderlichen Umstände ganz neue Möglichkeiten und Perspektiven.
                        <br />
                        <br />
                        Vor allem aber versuchen Sie zu erkennen, ob es nicht auch positive Aspekte in dieser Krise für Sie gibt. Evtl. können Sie durch die 
                        Möglichkeit, zu Hause zu arbeiten, Ihre Mahlzeiten besser organisieren. Vielleicht können Sie entspannter auf die Toilette gehen, weil es 
                        Ihre eigene ist und Sie (und Ihr Darm) über die Entleerungszeiten besser bestimmen können. Ich bin überzeugt, dass auch für Sie etwas 
                        Positives dabei ist: <b>ein halb leeres Glas ist immer auch halb voll!</b>
