                        <a id="gewohnheiten"></a>
                        <br />
                        <hr />
                        <h5>Änderungen der Lebensgewohnheiten</h5>
                        <hr />
                        Einige der am deutlichsten zutage tretenden Probleme sind die zum Teil gravierenden Änderungen der Lebensgewohnheiten. 
                        Dies sind keine selbst gewählten Änderungen, sondern &#187;von oben&#171; verordnete Änderungen. Zusätzlich zu den 
                        Ängsten um die unkalkulierbare Gefahr der Erkrankung an sich kommen die ebenfalls beängstigenden Umstände, die der 
                        Lockdown mit sich bringt, der unser aller Leben aus den Angeln hob und hebt. 
                        <br />
                        <br />
                        Für einige sind dies berufliche Änderungen, sei es, dass Sie nicht mehr an ihre Arbeitsstätten gehen dürfen, 
                        sondern stattdessen im Homeoffice arbeiten müssen, auf Kurzarbeit (mit den entsprechenden Gehaltseinbußen) 
                        gesetzt sind oder &ndash; schlimmer noch &ndash; dass sie als Selbstständige kaum noch ein Einkommen mehr 
                        erzielen können.
                        <br />
                        <br />
                        Wenn Sie Kinder haben, dürfen diese nicht in die Kita oder zur Schule gehen, sondern sollen von Ihnen als Eltern 
                        entweder beschäftigt oder beschult werden &ndash; Aufgaben, die Sie weder gewohnt sind, noch neben einer eventuellen
                        Tätigkeit im Homeoffice befriedigend erledigen können.
                        <br />
                        <br />
                        Hinzu kommen die gesellschaftlichen Einschnitte, nach denen wir &ndash; die wir ja alle soziale Wesen sind &ndash; 
                        nun großen Abstand voneinander halten sollen: kein Händeschütteln und keine Umarmungen sind mehr erlaubt, ja zum 
                        Teil sind sogar die Besuche bei den Lieben untersagt, keine Restaurantbesuche, keine kulturellen Veranstaltungen 
                        und auch keine Sportereignisse mehr möglich. 
                        <br />
                        <br />
                        Wir empfinden dies als Beschneidung unserer Rechte &ndash; was es ja de facto auch ist, aber unter den gegebenen 
                        Umständen nicht zu vermeiden ist. Niemand ist an einer Eskalation der Krankheitswelle und dem Zusammenbruch unseres 
                        Gesundheitssystems interessiert &ndash; oder sollte es zumindest sein. Trotzdem sind all dies Brüche, die seelisch 
                        extrem belasten.
                        <br />
                        <br />
                        Zum derzeitigen Stand werden zwar die allerstrengsten Bestimmungen nach und nach gelockert, in welchem Tempo und mit 
                        welchem Erfolg dies aber geschieht, ist für keinen von uns zuverlässig berechenbar. 
                        <br />
                        <a id="angst"></a>
                        <br />
                        <hr />
                        <h5>Angst und Unsicherheit</h5>
                        <hr />
                        Ich möchte an dieser Stelle betonen, dass ich die vorsichtige Vorgehensweise unserer Regierung bei den Entscheidungen 
                        befürworte und unterstütze, aber ich erlebe es selbst, wie belastend nicht nur die Vorschriften an sich, sondern auch 
                        die Unsicherheit über die Zukunft sind. Durch diese Situation entstehen zwangsläufig Ängste und Unsicherheiten &ndash; 
                        und dies erzeugt Stress, großen Stress.
                        <br />
                        <br />
                        Selbst wenn man zur Anhängerschaft der diversen &#187;Verschwörungstheorien&#171; gehört oder glaubt, was die 
                        selbsterklärten &#187;Heilsbringer&#171; für &#187;einfache&#171; Gegenmittel erklären und deshalb mit den 
                        aufoktroyierten Maßnahmen hadert, bleibt auch hier der Stress. Wenn man nicht bereit ist, diese nicht einsichtigen 
                        Schritte zu akzeptieren, ist der Stress u.U. sogar noch viel größer als bei denjenigen, die diese Einschränkungen 
                        als leider notwendig erachten.
                        <br />
                        <br />
                        Unter Stress kann die Verdauung nicht korrekt arbeiten. Das Verdauungssystem funktioniert leider noch genauso, wie bei 
                        unseren Vorfahren. Wenn die Urmenschen mit einem Stresserlebnis konfrontiert wurden &ndash; beispielsweise der Begegnung 
                        mit einem Säbelzahntiger &ndash; wurden durch die Stresshormone augenblicklich Körperfunktionen hochgefahren, um das nackte 
                        Leben zu retten, sprich: um entweder weglaufen oder angreifen zu können. Die Leber schüttet Energiereserven aus, um die 
                        Leistungsfähigkeit der Bein- und Armmuskulatur zu optimieren. Weniger wichtige Funktionen &ndash; wie u.a. die Verdauung 
                        &ndash; werden heruntergefahren, so dass die Ressourcen nur noch für das Überleben bereitgestellt werden. Damals konnten 
                        die Stresshormone noch durch die Bewegung während der Flucht oder dem Kampf abgebaut werden, und als die Gefahr vorüber 
                        war, kam der Urmensch wieder zur Ruhe und konnte sich entspannen. 
                        <br />
                        <br />
                        Allein schon durch unsere derzeitigen &#187;normalen&#171; Lebensgewohnheiten ist die notwendige Entspannung heutzutage kaum noch 
                        in ausreichendem Maße gewährleistet. Wenn dann noch eine als besonders bedrohlich empfundene Krise hinzukommt, ist dies 
                        oftmals der Tropfen, der das Fass zum Überlaufen bringt. Bitte lesen Sie hierzu auch den Beitrag 
                        &#187;<a href="ganz-entspannung" target="_blank">Entspannung</a>&#171;. 
                        <br />
                        <a id="stressverdauung"></a>
                        <br />
                        <hr />
                        <h5>Verdauung unter Stress</h5>
                        <hr />
                        Eine lang andauernde Krise &ndash; wie die Corona-Krise &ndash; bedeutet Dauerstress und wir stehen ständig unter Druck. Dies 
                        heißt, dass die Stresshormone nicht in ausreichendem Maße abgebaut werden können. Unser Verdauungssystem steht damit ebenfalls 
                        unter Dauerstress und arbeitet nicht korrekt. Der Darm, dessen &ndash; von unserem archaischen Organismus derzeit als 
                        &#187;unwichtig&#171; erachteten (siehe oben) &ndash; Funktionalität durch die Stresshormone nur noch eingeschränkt arbeitet, 
                        transportiert den Speisebrei unzureichend vom Magen zum Ausgang, so dass diverse Probleme wie Verstopfung, aber auch Durchfälle, 
                        Blähungen und Bauchschmerzen vermehrt auftreten bzw. verstärkt werden können. 
                        <br />
                        <a id="haltung"></a>
                        <br />
                        <hr />
                        <h5>Körperhaltung</h5>
                        <hr />
                        Angst, Unsicherheit und Stress erzeugen oftmals eine andere Körperhaltung, als wenn wir entspannt sind. Wir ziehen den 
                        Bauch ein, und die Bauchdecke verkrampft sich. 
                        <br />
                        <br />
                        Für eine gute Verdauung ist aber eine entspannte Haltung und eine aktive Bewegung der Bauchdecke (mit) entscheidend. 
                        Erst durch die Anregung des Bauches wird die Darmmuskulatur (Peristaltik) angeregt, um den Speisebrei im Darm weiter 
                        zu transportieren. Unterbleibt diese Anregung, wird oder bleibt der Darm &#187;faul&#171;, und die Nährstoffe können 
                        nicht optimal verdaut werden. Es bilden sich durch die zu lange Verweildauer vermehrt Gase, die den Darm schmerzhaft 
                        aufblähen und ungesunde Säuren, die Darmschleimhaut reizen können.
                        <br />
                        <a id="atmung"></a>
                        <br />
                        <hr />
                        <h5>Atmung</h5>
                        <hr />
                        Durch die Ängste und den Stress atmen wir auch falsch: wir füllen unsere Lungen nicht mehr in Ruhe vollständig mit Luft, 
                        sondern atmen viel zu flach und hektisch. 
                        <br />
                        <br />
                        Da auch die Atmung unser Verdauungssystem beeinflusst, leidet die Verdauungsleistung zusätzlich. Bei einer tiefen und 
                        entspannten Atmung in Richtung Bauch regt der große Zwerchfellmuskel, der den Brustbereich vom Bauch trennt, die 
                        Verdauungsdrüsen Magen, Leber, Galle und Bauchspeicheldrüse ebenso an wie den Darm selbst. Eine flache und verkrampfte 
                        Atmung behindert die Verdauung, so dass sich bereits bestehende Probleme vergrößern oder neue Beschwerden einstellen. 
                        Bitte lesen Sie auch den Beitrag &#187;<a href="atmen" target="_blank">Atem und Verdauung</a>&#171;.
                        <br />
                        <br />
                        Abgesehen davon kann sich durch eine über einen längeren Zeitraum angewöhnte flachere Atmung die Lungenleistung verschlechtern, 
                        was sich im (hoffentlich nicht eintretenden) Fall einer Covid-19-Erkrankung, die ja vor allem (aber nicht nur) eine Lungenkrankheit  
                        ist, negativ auswirken könnte.
                        <br />
                        <a id="schutzmasken"></a>
                        <br />
                        <hr />
                        <h5>Atemschutzmasken</h5>
                        <hr />
                        Was im asiatischen Raum schon seit Jahren gang und gäbe ist, ist nun auch bei uns Vorschrift: das Tragen einer Atemschutzmaske. 
                        Gemeint sind hier nicht die FFP-Masken mit eingebauten Filtern (Filtering Face Piece), die dem Personal in Krankenhäusern oder 
                        den Rettungsdiensten vorbehalten sein sollten, die mit möglichen oder sogar nachgewiesen infizierten Personen engen Kontakt haben 
                        müssen, sondern ein Mund-Nasen-Schutz. Diese Maßnahme schützt nicht den Träger selbst vor einer Ansteckung &ndash; zumindest nicht
                        primär &ndash; sondern vor allem die anderen, denen wir dann nicht mehr beim Husten, Niesen, Sprechen oder einfach nur beim Atmen 
                        unsere im Erkrankungsfalle mit Viren beladenen Speicheltröpfchen ins Gesicht schleudern. Wenn jedoch jeder eine solche Maske trägt, 
                        die durchaus auch selbstgenäht sein kann, jedoch korrekt vor Mund <b>und</b> Nase getragen werden muss, dann bin auch ich selbst 
                        durch diese Fürsorge der anderen geschützt.
                        <br />
                        <br />
                        Weiterhin schützt eine solche Maske auch davor, sich unbewusst ins Gesicht zu fassen. Erst, wenn Sie die Maske angelegt haben, 
                        merken Sie, wie oft Sie sich mit den Händen im Gesicht berühren. Da Sie bei vielen Gelegenheiten mit den Händen Gegenstände 
                        oder Griffe und Türklinken anfassen, können Ihre Finger mit Viren belastet sein, die Sie dann auf Mund und Nase oder auch in 
                        die Augen übertragen. Auf diese Weise können die Masken dann tatsächlich auch vor einer Eigenansteckung schützen.
                        <br />
                        <br />
                        Bemängelt wird immer wieder, dass der Atem durch eine solche Maske und somit eine optimale Belüftung der Lungen erschwert ist. 
                        Das ist tatsächlich richtig. Zwischen Mund und Nase und dem davor befindlichen Stoff oder Vlies befindet sich ein sogenanntes 
                        &#187;Tot-Volumen&#171;, also eine sauerstoffarme Luftmenge aus der ausgeatmeten Luft, die beim Einatmen gleich wieder in die 
                        Lunge gezogen wird. Auf Dauer ist dies anstrengend, denn um den Organismus mit der ausreichenden Sauerstoffmenge zu versorgen,
                        muss man in schnellerem Rhythmus atmen. Auch ist es schwerer, durch die Stoff- oder Vlieslagen die Frischluft aus der Umgebung 
                        einzuziehen, als ohne eine solche Bedeckung.
                        <br />
                        <br />
                        Vor allem Brillenträger haben ein besonderes Problem, das Stress erzeugt: die Brille beschlägt, weil die feuchte Atemluft durch eine nicht vollständig 
                        abschließende Maske auch nach oben steigt und auf den Gläsern kondensiert. Im Sommer bei wärmeren Temperaturen ist dieses Phänomen 
                        weniger ausgeprägt, im Winter jedoch dürfte es sich verstärken. Somit ist es ratsam, die obere Kante des Mund-Nasenschutzes mit 
                        einem Draht oder Metallbügel zu versehen, den man so biegt, dass er der Gesichtskontur folgt und so die Maske nach oben gut abschließt.
                        <br />
                        <br />
                        Das &#187;Totschlagargument&#171;, das von den Menschen, die die Fremdbestimmungen ablehnen, benutzt wird, ist die schlechtere Belüftung der 
                        Lunge und damit eine Beeinträchtigung des Immunsystems, wenn die Atemschutzmaske ununterbrochen und zu jeder Gelegenheit getragen werden
                        müsse. Dies ist aber keineswegs der Fall! Die Masken sollen in öffentlichen Verkehrsmitteln, in Geschäften, in Arztpraxen und bei den 
                        Gelegenheiten getragen werden, wo es sich nicht vermeiden lässt, dass sich Menschen nahekommen. Ob es sinnvoll ist, die Masken auch 
                        auf der Straße zu tragen, hängt davon ab, wie viele Menschen dort unterwegs sind.
                        <br />
                        <br />
                        Der sicherste Schutz &ndash; für mich selbst und für die anderen &ndash; ist es immer noch, 1,50 bis 2 Meter Abstand einzuhalten.
                        <br />
                        <br />
                        Völlig unsinnig ist es, eine Atemschutzmaske zu tragen, wenn man zu Hause ist, wo man entweder alleine ist oder sich in seiner 
                        häuslichen Gemeinschaft befindet. Auch im Auto eine Schutzmaske zu tragen, ist eher gefährlich, solange man alleine oder mit der 
                        Familie unterwegs ist, denn die Maske kann das Gesichtsfeld und damit die Verkehrssicherheit einschränken. 
                        <br />
                        <br />
                        Und wenn man in der Natur unterwegs ist, wo einem kaum jemand anderes begegnet oder wo zumindest im Normalfall immer der Sicherheitsabstand 
                        eingehalten werden kann, wäre es völlig kontraproduktiv, eine Schutzmaske zu tragen, denn während der aktiven Bewegung kann man gerade 
                        hier den Organismus mit frischem Sauerstoff versorgen und die Lungen entlasten und kräftigen. Bitte lesen Sie hierzu auch den Beitrag 
                        &#187;<a href="bewegung" target="_blank">Bewegung und Sport</a>&#171;.
                        <br />
                        <br />
                        Es ist also nicht das generelle Tragen eines Mund-Nasen-Schutzes vorgeschrieben, sondern das Tragen an bestimmten Orten und zu bestimmten 
                        Gelegenheiten zum größtmöglichen Schutz vor einer Verbreitung des Virus und vor einer Ansteckung. 
                        <br />
                        <br />
                        Auch wenn es zum Teil mühsamer ist, mit einer Schutzmaske zu atmen als ohne, sollte jede, aber auch wirklich jede Möglichkeit genutzt 
                        werden, eine exponentielle Verbreitung des Virus und damit eine Überlastung des Gesundheitssystems, viele schwere Krankheitsverläufe 
                        und Todesfälle zu verhindern. Das Tragen der Masken, wenn man allein unterwegs ist, ist weder vorgeschrieben noch sinnvoll. Wenn Sie 
                        nicht zu jeder möglichen Gelegenheit ohne Maske atmen &ndash; und dies auch wie weiter unten beschrieben in der richtigen Weise &ndash; 
                        bedeutet dies zusätzlichen Stress. Sie erweisen damit Ihrer Verdauung einen Bärendienst und schaden Ihrer Gesundheit.
                        <br />
