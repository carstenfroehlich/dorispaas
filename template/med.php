                        Diese Seite richtet sich an medizinische Fachleute wie &Auml;rzte oder 
                        Fachpersonal in Senioreneinrichtungen, aber auch an Ern&auml;hrungsberater. 
                        Die Alaktasie (Laktose-Intoleranz) ist zwar als Ursache von 
                        Verdauungsst&ouml;rungen inzwischen den meisten &Auml;rzten bekannt, jedoch 
                        leider immer noch nicht ausreichend als m&ouml;gliche Ursache diverser Beschwerden
                        im Bewusstsein verankert. So wird die Diagnose 
                        &#187;Laktose-Intoleranz&#171; h&auml;ufig 
                        erst viel zu sp&auml;t gestellt. Die meisten Alaktasie-Betroffenen klagen 
                        &uuml;ber eine manchmal jahrzehntelange Odyssee, weil Flatulenz, persistierende 
                        Diarrhoe und andere Beschwerden nicht mit einer Milchzucker-Unvertr&auml;glichkeit 
                        in Verbindung gebracht werden. 
                        <br />
                        <br />
                        Das Fachpersonal von Senioreneinrichtungen wie Alten- und Pflegeheimen 
                        ist leider meist &uuml;ber diese Zusammenh&auml;nge viel zu wenig informiert, und 
                        die dort angebotenen Mahlzeiten enthalten viel Milch oder Milchprodukte oder 
                        sind aus milchzuckerhaltigen Convienence-Produkten hergestellt. Dies f&uuml;hrt 
                        bei den Bewohnern regelm&auml;&#223;ig zu abdominellen Beschwerden, die nicht 
                        mit der Laktosezufuhr in Zusammenhang gebracht werden, wobei die 
                        Differenzialdiagnose bei Senioren zu vermehrt auftretenden 
                        Motilit&auml;tsst&ouml;rungen des Darmes nicht ohne weiteres m&ouml;glich ist. 
                        Auch die weit verbreitete Praxis der pharmazeutischen Industrie, bei der 
                        Herstellung von Medikamenten Laktose zu verwenden, kann zur Verschlimmerung 
                        der Symptomatik f&uuml;hren, was bei der Pharmakotherapie alter Menschen 
                        beachtet werden sollte.
                        <br />
                        <br />
                        Ern&auml;hrungsberater, die wegen der geschilderten Beschwerden aufgesucht 
                        werden, raten h&auml;ufig zu einer Ern&auml;hrungsumstellung gem&auml;&#223; 
                        den Grund&auml;tzen vollwertiger Ern&auml;hrung, was prinzipiell bei 
                        Verdauungsproblemen hilfreich sein kann, jedoch wird auch in diesen 
                        F&auml;llen meist aus Unkenntnis der Zusammenhang persistierender Symptome 
                        mit der auch bei Vollwertkost stattfindenen Milchzuckerzufuhr verkannt. 
                        <br />
                        <br />
                        Aus diesem Grunde erscheint es w&uuml;nschenswert, dass sich Fachleute mehr 
                        &uuml;ber die Laktose-Intoleranz informieren, denn zum einen sind die aus den 
                        Symptomen resultierenden Beeintr&auml;chtigungen f&uuml;r die Betroffenen 
                        sehr belastend und zum anderen ist die &#187;Behandlung&#171; sehr einfach.
                        <br />
                        <br />
                        Das Wort &#187;Behandlung&#171; steht hier ganz bewusst in Anf&uuml;hrungszeichen, 
                        denn eine Milchzucker-Unvertr&auml;glichkeit ist keine Krankheit. Etwa 90% der 
                        Weltbev&ouml;lkerung sind laktoseintolerant, weil grunds&auml;tzlich nach dem 
                        Ende der Stillzeit der Verzehr von Milch entbehrlich ist und damit die 
                        Produktion der Laktase nicht mehr zwingend erforderlich ist. Die Natur sieht 
                        keinen Verzehr von Milch mehr vor, und die dann unwirtschaftliche Produktion 
                        des Laktase-Enzyms zur Spaltung des Disaccharides Laktose in die verwertbaren 
                        Monosaccharide Glukose und Galaktose wird eingestellt. Nur in den n&ouml;rdlichen, 
                        sonnen&auml;rmeren Regionen der Erde stellt die bis ins h&ouml;here Lebensalter 
                        persistierende F&auml;higkeit zur Laktaseproduktion einen Selektionsvorteil dar, 
                        da durch die Vitamin D-Zufuhr aus Milch und Milchprodukten die Erkrankungsrate 
                        an Rachitis vermindert wird. Dies ist der Grund, warum in den licht&auml;rmeren, 
                        n&ouml;rdlichen Regionen weniger laktoseintolerante Menschen leben als in 
                        s&uuml;dlicheren, wo die Mehrzahl der Bewohner keine Milch vertragen. 
                        <br />
                        <br />
                        Im fortschreitenden Alter, etwa ab dem siebten Dezenium, verringert sich jedoch 
                        auch bei den meisten zuvor laktosetoleranten Menschen die Laktaseproduktion, 
                        was bei vielen Senioren zu Beschwerden f&uuml;hrt. 
                        <br />
                        <br />
                        Bei uns gibt es wegen der genetischen Ver&auml;nderung etwa 15-20% 
                        laktoseintolerante j&uuml;ngere Menschen und wegen der im Alter 
                        naturgem&auml;&#223; nachlassenden Laktoseproduktion in deutlich h&ouml;herem 
                        Prozentsatz &auml;ltere Menschen, was dazu f&uuml;hrt, 
                        eine Laktose-Intoleranz als krankhaft anzusehen. Sie wird, wenn sie denn 
                        diagnostiziert wird, oftmals als Enzym-Defekt bezeichnet, was ein weit 
                        verbreiteter Irrtum ist. Die Betroffenen werden dadurch pathologisiert und 
                        ihr manchmal aufgrund einer oft versp&auml;teten Diagnosestellung und der 
                        Vermutung einer psychogenen Genese der Symptome m&ouml;glicherweise 
                        l&auml;diertes Selbstbewusstsein untergraben. 
                        <br />
                        <br />
                        Die &#187;Behandlung&#171; der Alaktasie beinhaltet haupts&auml;chlich die 
                        Vermeidung der Milchzuckerzufuhr, was nur durch eine ausreichende Information 
                        der Berater und der Betroffenen m&ouml;glich ist, denn Laktose verbirgt sich 
                        nicht nur in Milch und Milchprodukten. Die Nahrungsmittelindustrie sch&auml;tzt 
                        die Wasser bindenden Eigenschaften der Laktose und hat sie dar&uuml;ber hinaus 
                        als F&uuml;llstoff erkannt, mit dem sich Nahrungsmittel mit geringem 
                        Finanzaufwand strecken lassen &ndash; aus Sicht der Hersteller gute Gr&uuml;nde 
                        f&uuml;r den Zusatz von Laktose. 
                        <br />
                        <br />
                        Es ist m&ouml;glich, den Enzymmangel mithilfe k&uuml;nstlich erzeugter Laktase 
                        zu substituieren und Tabletten, Kautabletten, Kapseln oder auch Pulver zu 
                        laktosehaltigen Mahlzeiten einzunehmen. Es leuchtet jedoch ein, dass die 
                        k&uuml;nstlichen Pr&auml;parate nicht so intensiv wirken k&ouml;nnen, wie 
                        das in den Schleimhautzellen des D&uuml;nndarmes gleichm&auml;&#223;ig 
                        verteilte, nat&uuml;rliche Enzym. Au&#223;erdem enthalten diese Mittel 
                        oftmals unvertr&auml;gliche Zusatzstoffe, so dass auch l&auml;ngere 
                        Versuchsphasen mit unterschiedlichen Pr&auml;paraten oftmals nicht den 
                        erhofften Erfolg bringen. 
                        <br />
                        <br />
                        Dar&uuml;ber hinaus wird eine Alaktasie auch nicht selten von einem 
                        Reizdarm-Syndrom begleitet, das ohnehin eine Nahrungsumstellung und vor allem 
                        auch eine &Auml;nderung bestimmter Lebensgewohnheiten erfordert, um die 
                        dadurch hervorgerufenen Beschwerden zu bessern. Auch dieser Zusammenhang wird 
                        leider oft verkannt und nicht richtig diagnostiziert. Zu schnell wird eine 
                        psychische Ursache vermutet, die manchmal sogar mit Psychopharmaka behandelt 
                        wird. Hier w&uuml;rde eher die Erhebung der so genannten ROM-II-Kriterien 
                        zur korrekten Ursachenfindung und angebrachten Therapie verhelfen. 
                        <br />
                        <br />
                        Die Diagnose der Laktose-Intoleranz erfolgt am einfachsten entweder mithilfe 
                        des H<sub>2</sub>-Atemtests oder mit einem Bluttest. Beim Atemtest wird nach 
                        Ermittlung eines Referenzwertes eine definierte Menge Laktosel&ouml;sung 
                        getrunken und dann mehrfach in regelm&auml;&#223;igen Abst&auml;nden der 
                        Anstieg der Wasserstoffkonzentration im Atem gemessen, da die Laktose 
                        verwertenden Dickdarmbakterien den Milchzucker teilweise zu Wasserstoff 
                        verstoffwechseln, der &uuml;ber den Atem abgegeben wird. Zus&auml;tzlich 
                        werden die bei Vorliegen einer Alaktasie auftretenden Beschwerden 
                        (Tenesmen, Flatulenz, Diarrhoe) ausgewertet. 
                        <br />
                        <br />
                        Beim Bluttest wird nach Abnahme des Referenzwertes und Verzehr der Laktose 
                        in festgelegten Abst&auml;nden der Anstieg des Blutzuckers gemessen. Bleibt 
                        ein signifikanter Anstieg aus (weniger als 20mg/dl Blut), so ist dies der 
                        Beweis, dass keine Aufspaltung der Laktose in Galaktose und Glukose stattfindet, 
                        die den Blutzuckerspiegel steigen l&auml;sst. Beide Diagnose-Methoden, 
                        besonders aber der Bluttest, sind einfach und schnell durchzuf&uuml;hren und 
                        erzielen ein sicheres Ergebnis. 
                        <br />
                        <br />
