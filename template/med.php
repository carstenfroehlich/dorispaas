                        &Auml;rzten &ndash; sich &uuml;ber die Laktose-Intoleranz zu informieren. 
                        Das Fachpersonal in Alteneinrichtungen sollte sehr genau beobachten, ob 
                        h&auml;ufige Durchf&auml;lle oder Bl&auml;hungen nicht mit der Milchzuckerzufuhr 
                        in Verbindung gebracht werden k&ouml;nnen, und ob durch die Eliminierung der 
                        Laktose aus Mahlzeiten und Medikamenten eine Besserung eintritt. 
