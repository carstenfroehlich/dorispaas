                        Liebe Leserin, lieber Leser.
                        <br />
                        Der letzte Newsletter war etwas Besonderes: normalerweise halte ich mich an dieser Stelle mit &Auml;ußerungen zu politischen Entscheidungen zur&uuml;ck, 
                        denn diese sind nicht Kern meiner Website. Trotzdem hatte ich mich in der Herbst-Nachricht sowohl zur Bundestagswahl mit der Bitte um eine Stimme f&uuml;r 
                        eine rot/gr&uuml;ne Regierung an Sie gewandt als auch mit der Aufforderung, dass sich bisher ungeimpfte Leserinnen und Leser &uuml;ber die Pandemie und die 
                        Covid-19-Impfungen informieren sollten und belastbare Quellen aufgef&uuml;hrt. Dies hat zu vielen Reaktionen gef&uuml;hrt, Letzteres nicht nur zu positiven, 
                        sondern sogar auch zu einigen direkten Anfeindungen. Es ist richtig: mein Newsletter soll Ihnen Informationen &uuml;ber die Neuerungen 
                        auf meiner Website geben. Aber ich bin kein unpolitischer Mensch und sehe vor allem oft enge Zusammenh&auml;nge zwischen der Gesundheit und politischen 
                        Entscheidungen. Deshalb fließt eben doch ab und an der eine oder andere Hinweis auf Kausalit&auml;ten ein &ndash; eben auch und insbesondere zu diesen beiden 
                        oberen Themen. Auch in Bezug auf die Impfempfehlung gab es im Newsletter-Vorwort eine solche Erklärung zu den Verbindungen mit Ihrer Gesundheit, so, wie ich 
                        mich immer bem&uuml;he, meine Argumente zu begr&uuml;nden und f&uuml;r Sie nachvollziehbar zu machen. Auf jeden Fall erwarte ich bei allen Reaktionen Fairness 
                        in der Kommunikation, so, wie ich auch Ihnen in meinen Ausführungen Respekt entgegenbringe. 
