                        <hr />
                        <h5>Wasserstoff-Atemtest mit Glukose zur Diagnose oder zum Ausschluss einer Dünndarmfehlbesiedelung (DDFB)</h5>
                        <hr />
                        Der Wasserstoff-Atemtest wird zur Diagnose bzw. zum Ausschluss einer Dünndarmfehlbesiedelung 
                        durchgeführt. Bei der Besiedelung des Dünndarmes mit &#187;normalen&#171;, 
                        Bakterienarten wird Glukose komplett über die Dünndarm-Schleimhaut aufgenommen. 
                        Besteht eine Dünndarmfehlbesiedelung, also eine Besiedelung mit wasserstoffproduzierenden 
                        Bakterienarten im Dünndarm, so steigt der Wasserstoffgehalt beim Glukose-Test 
                        stark an.
                        <br />
                        Der Glukose-Atemtest, bei dem 80g in Wasser gelöste Glukose getrunken werden, 
                        wird durchgeführt, wenn bei Laktose-, Fruktose- oder Sorbit-Atemtests der 
                        stärkste Anstieg der Kurve bereits nach 30 bis 60 Minuten auftritt.
                        <br />
                        <br />
                        <br />
                        <span style="font-weight:bold">Wichtiger Hinweis zu allen Atemtests:</span>
                        <br />
                        Selbstverständlich können Tests mit den verschiedenen Lösungen 
                        (Laktose, Fruktose, Sorit, bzw. Laktulose oder Glukose) nicht ohne eine <b>Zwischenzeit von etwa 2 Wochen</b> 
                        durchgeführt werden! Zuckerreste der jeweiligen Testlösung müssen komplett 
                        verarbeitet bzw. ausgeschieden worden sein, und Darm und Darmflora müssen 
                        sich von der erneuten Belastung erholen.
                        <br />
                        <a id="bluttest">&nbsp;</a>
                        <hr />
                        <h5>Ist bei einer Fruktose-Intoleranz ein Bluttest möglich?</h5>
                        <hr />
                        Bei einer Fruktose-Intoleranz ist es nicht möglich, mit Hilfe eines Bluttests 
                        die Krankheit zu diagnostizieren. Der Bluttest bei einer Laktose-Intoleranz 
                        beruht auf der Tatsache, dass der Milchzucker ein Zweifachzucker ist, der 
                        mit dem Laktase-Enzym aufgepalten werden muss. Fehlt dieses Enzym, entstehen 
                        keine Spaltprodukte, also keine Glukose und keine Galaktose. Ins Blut gelangende 
                        Glukose würde den Blutzuckerspiegel erhöhen, was mit dem Bluttest 
                        gemessen wird. Bleibt dieser Anstieg aus, kann die Diagnose &#187;Laktose-Intoleranz&#171; gestellt werden.
                        <br />
                        Da jedoch der Fruchtzucker ein Einfachzucker ist, der nicht mehr aufgespalten 
                        wird und der auch den Blutzuckerspiegel nicht unmittelbar erhöht, eignet 
                        sich dieser Test nicht zur Diagnose der Fruktose-Intoleranz.
