                        <h5>Achtung: Aspartam!</h5>
                        <br />
                        <br />
                        Im meiner gestrigen Tageszeitung war die Meldung auf Seite 11 gerade mal 5 cm hoch 
                        &ndash; aber für mich trotzdem sehr brisant: Die EU-Lebensmittelbehörde EFSA 
                        behauptet nun ganz offiziell, dass nach einer von ihr durchgeführten Studie der 
                        künstliche Süßstoff &#187;Aspartam&#171; für die Verbraucher ungefährlich sei! 
                        Die erlaubten und &#187;von der Industrie eingesetzten&#171; Mengen seien 
                        unbedenklich &ndash; lediglich für Menschen mit der Stoffwechselerkrankung PKU 
                        (Phenylketonurie) würde eine Verzehrwarnung gegeben.
                        <br />
                        <br />
                        Irgendwie habe ich bei solcher Art Meldungen immer wieder ein Déjà vu &ndash; war 
                        da vor 60 Jahren nicht schon einmal etwas, wo lange Zeit und in mehr als 
                        verhängnisvoller Weise abgestritten wurde, dass ein Schlafmittel für die &#187;bedauerlichen, 
                        aber nur vereinzelt auftretenden Missbildungen von Babies&#171; verantwortlich 
                        sein könnte?
                        <br />
                        <br />
                        Zugegeben, hier gibt es selbstverständlich gravierende Unterschiede im Schweregrad! 
                        Aber ist es nicht immer wieder das gleiche System, wenn einen Verdacht, eine 
                        Substanz könne eventuell die Gesundheit von Verbrauchern beeinträchtigen, immer 
                        wieder zu Gunsten der Hersteller so lange unter den Teppich gekehrt wird, bis 
                        tatsächlich niemand mehr daran vorbei kommt zugeben zu müssen, dass eben doch ein 
                        Zusammenhang nicht mehr von der Hand zu weisen ist?
                        <br />
                        <br />
                        Ja, das Geschrei der Lobbyisten ist immer groß und immer gleich &ndash; es kostet 
                        ja Arbeitsplätze, wenn der mit von den Herstellern hohen Kosten entwickelte Stoff 
                        nicht mehr an den Verbraucher gebracht werden darf! Und Arbeitsplätze für einige 
                        gehen selbstverständlich immer vor Gesundheit von vielen &ndash; zumindest drängt 
                        sich mir diese wirtschaftsfreundliche Einstellung unserer Politiker immer wieder 
                        auf. Aber offensichtlich scheint es nicht zu vermeiden zu sein, denn viele dieser 
                        Politiker &ndash; allen voran unsere (noch) derzeitige Verbraucherministerin &ndash; 
                        zeichnen sich häufig auch in ihrem ureigensten Ressort durch eklatante Wissenslücken 
                        aus. Nicht, dass nicht auch ich Arbeitsplätze für alle (!) wichtig und erstrebenswert 
                        finden würde, aber die könnte man ja durchaus auch mit dem Vertrieb von verträglichen, 
                        ja sogar die Gesundheit fördernden, Produkten schaffen. Aber die werden im Allgemeinen 
                        eben nicht erforscht und erschaffen, sondern uns von der Natur geliefert. Das spült 
                        zwar keinem Fooddesigner Beträge in die Kassen, könnte aber Arbeitsplätze in der 
                        ökologischen Landwirtschaft und vielen anderen Wirtschaftszweigen schaffen &ndash; 
                        wenn man es nur wollte.
                        <br />
                        <br />
                        Es gibt mittlerweile genügend Studien, die beweisen, dass Aspartam (E951) eben 
                        nicht unschädlich ist, wie die Zuteilung der E-Nummer suggerieren mag. Als nur 
                        ein Beispiel sei hier die Veröffentlichung der amerikanischen Zulassungsbehörde 
                        für Lebensmittel und Medikamente (Federal Drug and Food Administration) genannt 
                        (siehe u.a.  <a href="http://www.med1.de/Forum/Ernaehrung/19519/" target="_blank">http://www.med1.de/Forum/Ernaehrung/19519/</a>), 
                        in der man sich über all die möglichen Nebenwirkungen bis hin zum Tod informieren kann.
                        <br />
                        <br />
                        Es mag sein, dass bei nur geringem Verzehr (der ADI-Wert (= acceptable daily intake) 
                        wird mit 40mg pro kg Körpergewicht angegeben) die Schäden weniger gravierend sind.
                        Und großzügiger Weise muss bei den Aspartam-haltigen Produkten (z.B. Colagetränke) 
                        der gesetzliche Hinweis angebracht sein, dass das Produkt &#187;eine Phenylanalinquelle 
                        enthält&#171; &ndash; wo doch jeder weiß, was Phenylanalin ist, welche Probleme es 
                        bereitet, und  &ndash; vor allem! &ndash; wann man die täglich akzeptable Menge 
                        überschreitet! Wir wissen ja auch alle, dass Jugendliche, die diese Getränke und 
                        zusätzlich noch alle anderen mit Aspartam versüßten Produkte konsumieren, diesen 
                        ADI-Wert kennen, ihn mit ihrem Körpergewicht multiplizieren und dann genau an 
                        diesem Grenzpunkt die Flasche absetzen und erst am nächsten Tag zu Ende trinken.
                        <br />
                        <br />
                        Reicht es nicht, dass der Stoff IM VERDACHT steht, Schäden verursachen ZU KÖNNEN? 
                        Müssen erst Hunderte, Tausende von Menschen ernsthafte Schäden erlitten haben, 
                        bevor den Herstellern dieser möglichen &#187;Zeitbomben&#171; der Riegel vorgeschoben wird? 
                        Sagen unsere Gesetze nicht, dass der Verursacher seine UNSCHULD beweisen muss? 
                        Hier scheint es dann wohl eher umgekehrt zu sein: Der Geschädigte scheint beweisen 
                        zu müssen, dass Aspartam an seinen gesundheitlichen Problemen SCHULD sind, in 
                        direktem Zusammenhang stehen. Wie gut für die Verursacher, dass dies für Otto 
                        Normalverbraucher wohl nur in den seltensten Fällen möglich sein wird. Mir scheint, 
                        dass das Schuldprinzip nach Belieben umgekehrt werden darf &ndash; wenn es sich nur um 
                        so etwa Unbedeutendes wie die Gesundheit und Unversehrtheit der Menschen handelt.
                        <br />
                        <br />
                        Leider habe ich es hier und an vielen anderen Stellen schon mehrfach betonen müssen: 
                        Es bleibt uns Verbrauchern nichts anderes übrig, als uns mühsam zu informieren 
                        und dann selbst für unsere Gesundheit zu sorgen. Von den offiziellen Behörden 
                        oder gar unseren Politikern ist wohl keine Hilfe zu erwarten.
