                        <h5>Was sind die Ursachen f&uuml;r ein Reizdarm-Syndrom? </h5>
                        <hr>
                        Die Ursachen f&uuml;r das Auftreten eines Reizdarm-Syndroms sind heute noch immer 
                        nicht ganz gekl&auml;rt. Vermutet wird u.a. eine Beteiligung des Botenstoffes Serotonin, 
                        der bei der Nervenreizleitung f&uuml;r die Steuerung der Darmfunktion und der 
                        Schmerzwahrnehmung mit verantwortlich ist. 
                        <br />
                        <br />
                        Weiterhin ermittelte Prof. Dr. Paul Enck, Forschungsleiter der Abteilung f&uuml;r 
                        Psychosomatische Medizin und Psychotherapie am Universit&auml;tsklinikum T&uuml;bigen, 
                        dass mit gr&ouml;&#223;ter Wahrscheinlichkeit bei der Entwicklung oder Art und 
                        Auspr&auml;gung der Symptome auch in der Vergangenheit durchgemachte schwere infekti&ouml;se 
                        Entz&uuml;ndungen des Darmes eine Rolle spielen k&ouml;nnten, beispielsweise 
                        Infektionen mit Salmonellen oder auch dem Bakterium Camphylobacter, die nicht schnell 
                        und komplett mit geeigneten Mitteln (Antibiotika) behandelt wurden. 
                        <br />
                        <br />
                        Dr. Mark Pimentel, Assistant Professor of Medicine an der University of California, 
                        Los Angeles (UCLA) und Direktor des &#187;Gastrointestinal Motility Program&#171; 
                        im Cedars-Sinai Medical Center ermittelte in dem von ihm geleiteten Projekt, dass 
                        bei rund 80% der von Reizdarm-Syndrom Betroffenen der Dünndarm mit Dickdarmbakterien 
                        fehlbesiedelt ist. Der Großteil seiner in dem Programm entsprechend behandelten 
                        Patienten war danach beschwerdefrei. Je konsequenter sich die Patienten an die 
                        daran anschließenden Ernährungs- und Verhaltensvorschriften hielten, desto seltener 
                        traten Rückfälle auf (lesen Sie hierzu auch den Beitrag &#187;<a href="rds-ursache-sibo" target="_blank">Dünndarmfehlbesiedelung als Ursache des Reizdarm-Syndroms</a>&#171;). 
                        <br />
                        <br />
                        In einer anderen Arbeit haben Forscher der Technischen Universit&auml;t M&uuml;nchen 
                        (Prof. Michael Schemann und sein Team) ermittelt, dass winzige, sogenannte 
                        Mikroentz&uuml;ndungen der Darmschleimhaut ebenfalls ein Reizdarm-Syndrom bzw. 
                        Symptome des Reizdarm-Syndroms bedingen k&ouml;nnen, denn durch diese Mikroentz&uuml;ndungen 
                        werden sogenannte Entz&uuml;ndungs-Mediatoren gebildet, die die Aktivit&auml;t der 
                        Darmnerven beeinflussen k&ouml;nnen. Und &ndash; wie oben beschrieben &ndash; sind die 
                        Darmnerven (auch Bauchhirn genannt) mit daf&uuml;r verantwortlich, ob und in welcher 
                        Intensit&auml;t Darmbewegungen als normal oder als Schmerz empfunden werden. Diese 
                        Mikroentz&uuml;ndungen sind bei bildgebenden Untersuchungen (R&ouml;ntgen, MRT) 
                        nicht erkennbar, und werden auch nur mit Gl&uuml;ck oder durch Zufall bei sorgf&auml;ltig 
                        durchgef&uuml;hrten Darmspiegelungen entdeckt. 
                        <br />
                        <br />
                        Eine Studie von Professor John Hermon-Taylor und seinem Team vom St. George's Hospital 
                        Medical School hat mit einem Testverfahren &#187;eventuell&#171; den Beweis erbracht, 
                        dass Bakterien als Ursache f&uuml;r die Crohn'sche Krankheit (Morbus Crohn) infrage 
                        kommen, denn bei 92% von Betroffenen wurde in Darmschleimhautproben das Bakterium 
                        Mycobacterium avium paratuberculosis (MAP) festgestellt. In einer Kontrollgruppe wurde 
                        in 26% ein positives Ergebnis festgestellt. &#187;Damit d&uuml;rfte eine wesentliche 
                        Rolle des Mycobacterium avium paratuberculosis an der Entstehung des Morbus Crohn 
                        erwiesen sein&#171;, so John Hermon-Taylor und sein Team. 
                        <br />
                        <br />
                        Prof. Hermon-Taylor berichtete mit einem Verweis auf Forschungen in Schweden, dass 
                        der Erreger MAP gegebenenfalls auch am Reizdarm-Syndrom beteiligt ist 
                        (<a href="http://www.probios.ch/html/morbus_crohn.html" target="_blank">www.probios.ch</a>). 
                        <br />
                        Bis der definitive Beweis erbracht worden ist, dass das Bakterium MAP wirklich f&uuml;r 
                        das Reizdarm-Syndrom (mit)verantwortlich ist, wird es mit Sicherheit noch einige 
                        Jahre dauern. Somit kann die Frage, ob MAP (auch) eine Ursache des Reizdarm-Syndroms 
                        sein kann, noch nicht abschlie&#223;end beantwortet werden.
                        <br />
                        <hr>
                        <h5>Ist eine Vorbeugung m&ouml;glich?</h5>
                        <hr>
                        Es gibt keine speziellen Vorbeugema&#223;nahmen, um ein Reizdarm-Syndrom zu verhindern. 
                        Jedoch ist es immer sinnvoll, durch eine gesunde, vollwertige Ern&auml;hrung und eine 
                        insgesamt gesunde Lebensweise ohne Tabak und Alkohol, mit ausreichender Bewegung 
                        und einer guten Balance zwischen Anregung und Entspannung f&uuml;r eine stabile 
                        Gesundheit und insbesondere f&uuml;r eine gesunde Verdauung zu sorgen. Zwar ist 
                        eine solche Lebensweise kein Garant daf&uuml;r, nicht an einem Reizdarm-Syndrom 
                        zu erkranken, jedoch erh&ouml;ht es die Chancen auf eine dauerhafte Darmgesundheit. 
                        <br />
                        <br />
                        Bei Vorliegen von Nahrungsmittel-Unvertr&auml;glichkeiten und/oder 
                        -Allergien ist es besonders wichtig, die unvertr&auml;glichen Stoffe konsequent 
                        zu meiden, um Reizungen des Darmes und somit einen eventuellen Ausbruch eines 
                        Reizdarm-Syndroms zu verhindern.
