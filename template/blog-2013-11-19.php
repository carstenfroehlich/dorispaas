                        <h5>
                            Mehrere Nahrungsmittel-Unverträglichkeiten gleichzeitig &ndash; was kann ich eigentlich noch essen?
                        </h5>
                        
                        Diesen Satz hört und liest man immer häufiger! Denn bei Nahrungsmittel-Unverträglichkeiten 
                        ist es immer das Mittel der Wahl, die unbekömmlichen Lebensmittel weitestgehend zu meiden.
                        <br />
                        <br />
                        Wenn man eine Nahrungsmittel-Unverträglichkeit hat, ist es &#187;relativ einfach&#171;, 
                        sich anhand einer Liste zu orientieren, welche Lebensmittel verträglich sind oder 
                        welche Lebensmittel Probleme verursachen und besser gemieden werden sollten. Es 
                        bleiben immer noch genügend Lebensmittel zur Auswahl, um einen abwechslungsreichen 
                        Speisezettel zusammenstellen zu können.
                        <br />
                        <br />
                        Schwieriger wird es bei zwei Intoleranzen &ndash; und wahrscheinlich gänzlich 
                        unübersichtlich wird es, wenn man an mehreren Unverträglichkeiten leidet. Und 
                        deshalb fragen sich die Betroffenen eben häufig, was denn überhaupt noch möglich 
                        ist, sind wahrscheinlich übervorsichtig und trauen sich kaum noch, irgendetwas 
                        zu essen. Da kann die Auswahl recht schnell eintönig werden, und Demoralisierung 
                        und letztendlich sogar Mangelerscheinungen können die Folge sein.
                        <br />
                        <br />
                        So weit muss es nicht kommen! Ich möchte Ihnen an dieser Stelle die &#187;DorisPaas.de &ndash; 
                        Lebensmittel-Datenbank&#171; vorstellen:
                        <br />
                        <br />
                        In dieser Datenbank sind viele Hundert Lebensmittel zusammengetragen und auf ihre 
                        Verträglichkeit bei verschiedenen Nahrungsmittel-Unverträglichkeiten überprüft 
                        worden: Laktose-, Fruktose-, Sorbit-, Histamin- und Oligosaccharid-Intoleranz, 
                        Gluten-Sensitivität und Zöliakie und das allergene Potenzial. Alle Lebensmittel 
                        sind mit einem einfachen Ampelsystem gekennzeichnet und zusätzlich noch mit einer 
                        genaueren Beschreibung versehen.
                        <br />
                        <br />
                        Mit Hilfe von Filtern kann man sich nun für seine ganz persönliche Kombination 
                        von Unverträglichkeiten diejenigen Nahrungsmittel anzeigen lassen, die entweder 
                        verträglich oder unverträglich sind, oder bei denen es sich lohnen kann, sie in 
                        der Erprobungsphase eventuell auszuprobieren. Zusätzlich erleichert die Einteilung 
                        der Lebensmittel in Kategorien die Zusammenstellung von Mahlzeiten.
                        <br />
                        <br />
                        Die &#187;DorisPaas.de &ndash; Lebensmittel-Datenbank&#171; bietet viele Möglichkeiten, 
                        auch bei mehreren Nahrungsmittel-Unverträglichkeiten einen abwechslungsreichen 
                        Speisezettel zusammenstellen zu können.
                        <br />
                        <br />
                        Darüber hinaus kann die &#187;DorisPaas.de &ndash; Lebensmittel-Datenbank&#171; in 
                        der Ernährungs- und Gesundheitsberatung als wertvolles Werkzeug dienen, um sich 
                        auf der einen Seite auf eine Beratung von betroffenen Klienten vorzubereiten und 
                        um andererseits den Klienten Anregungen zu geben, welche Lebensmittel für eine E
                        rnährung ohne Folgebeschwerden geeignet sind.
