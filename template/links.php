                        <h5>Verbraucherschutz</h5>
                        <hr>
                        <br />
                        <span style="font-weight:bold">&#149; foodwatch</span><br>
                        Immer mehr Lebensmittelskandale erschüttern nicht nur die &Ouml;ffentlichkeit, 
                        sondern auch unser Vertrauen in unsere Nahrung. Bei foodwatch können Sie 
                        sich immer aktuell über solche Skandale und vieles mehr informieren.
                        foodwatch kämpft für die Rechte der Verbraucher und sagt (zu Recht) über 
                        sich selbt: &#187;foodwatch muss und möchte unabhängig vom Staat und 
                        vom staatlichen Verbraucherschutz bleiben. Denn der Staat versagt nicht nur 
                        bei der Anwendung und Durchsetzung bestehender Verbraucherschutzgesetze, sondern 
                        auch bei der Gesetzgebung. Die vom Staat gemachten Gesetze schützen die 
                        Industrie häufig besser als die Verbraucher!&#171;<br />
                        <a href="http://www.foodwatch.de/" target="_blank">www.foodwatch.de</a>
                        <br />
                        <br />
                        <br />
                        <span style="font-weight:bold">&#149; Lebensmittelwarnung</span><br>
                        Leider kommt es immer wieder vor, dass Lebensmittel (neben den aus meiner Sicht 
                        ohnehin enthaltenen, nachteilig wirkenden Inhaltsstoffen) so viele schädliche Stoffe 
                        oder Verunreinigungen enthalten, dass die offensichtlich dem Verbraucher zuzumutenden
                        Grenzen überschritten werden. Wurden früher die Rückruf- und Warnaktionen 
                        der Hersteller quasi noch hinter vorgehaltener Hand und lediglich als Alibi &ndash; 
                        weil gesetzlich vorgeschrieben &ndash; durchgeführt, so werden solche Aktionen 
                        heute doch klarer ersichtlich veröffentlicht &ndash; vor allem nun zusammengefasst 
                        von offizieller Seite, dem Bundesamt für Verbraucherschutz und 
                        Lebensmittelsicherheit. Zumindest der aufgeklärte 
                        Verbraucher, der sich aktiv um seine Gesundheit sorgt und kümmert, hat die 
                        Möglichkeit, z.B. auf dem Internetportal &#187;Lebensmittelwarnung.de&#171; 
                        die verschiedenen Warnungen einzusehen. Ein regelmä&#223;iger Besuch dieses 
                        Portals ist sehr empfehlenswert.
                        <br />
                        <a href="http://www.lebensmittelwarnung.de/" target="_blank">www.lebensmittelwarnung.de</a>
                        
                        
                        
                        
