                        <hr />
                        <h5>Grundsätze für eine gesunde, verträgliche Ernährung</h5>
                        <hr />
                        Das Ziel einer jeden Ernährung sollte nicht nur sein, uns zu ernähren und unserem Körper die 
                        Energie zu geben, die er benötigt, damit die Muskeln und Organe, aber auch das Gehirn funktionieren. 
                        Genauso wichtig ist es auch, dass die Nahrung, die wir zu uns nehmen, unsere Gesundheit fördert.
                        Dies kann heutzutage selbst dann schwierig sein, wenn man keine Einschränkungen wie z.B. 
                        Nahrungsmittel-Unverträglichkeiten oder -Allergien hat.
                        <br />
                        <br />
                        Vieles, was wir in den Lebensmittelabteilungen in den Supermärkten kaufen können, trägt aus meiner Sicht 
                        &ndash; wie oben beschrieben &ndash; vollkommen zu Unrecht die Bezeichnung &#187;<b>Lebens</b>mittel&#171;. 
                        Viel eher sind diese Produkte oftmals eine zusammengepanschte Masse an Chemikalien und Zusatzstoffen. Das dies 
                        unserer Gesundheit förderlich sein soll, will ich hier ausdrücklich in Abrede stellen. 
                        <br />
                        <br />
                        <b>&#111;</b> Ein <b>erster Grundsatz</b> sollte also sein, bei der Auswahl der Lebensmittel so oft wie möglich auf 
                        <b>industriell unbearbeitete Zutaten</b> 
                        zu achten.
                        <br />
                        <br />
                        Weiterhin sollten Sie anstreben, die Palette der verzehrten Lebensmittel so umfangreich wie möglich 
                        zu gestalten. Je mehr Abstriche Sie bei Ihrem Speisezettel machen, desto langweiliger werden die Mahlzeiten nicht nur für Sie, es wird auch 
                        nach und nach die Diversität Ihrer Darmflora eingeschränkt &ndash; mit allen nachteiligen Folgen.
                        Bedenken Sie deshalb, dass Sie so viele Lebensmittel wie möglich essen, jedoch die Notwendigkeiten in Bezug auf 
                        Unverträglichkeiten und Allergien im Auge behalten. 
                        <br />                        
                        <br />
                        <b>&#111;</b> Dabei gilt der <b>zweite Grundsatz</b>: <b>Schränken Sie
                        Ihren Speisezettel nicht ohne triftigen (und eventuell aktuellen) Grund mehr ein, als es unbedingt nötig ist</b>. Andere Beweggründe, die 
                        ja durchaus verständlich sein können, sollten Sie deshalb zumindest vorübergehend hintenanstellen.
                        <br />
                        <br />
                        Viele Menschen, die Verdauungsprobleme haben, berichten, dass Sie &#187;nur noch ganz wenige Lebensmittel vertragen&#171;.
                        Versuchen Sie deshalb, Einschränkungen möglichst bald aufzuweichen. Testen Sie immer wieder aus, ob und ggf. welche Lebensmittel 
                        Sie Ihrem Speisezettel hinzufügen können. Je länger Einschnitte gemacht werden, desto nachteiliger ist dies für Ihre Mikrobiota. 
                        Selbstverständlich ist es auch keine gute Idee, Lebensmittel zu verzehren, die tatsächlich Beschwerden machen, denn in einem 
                        durch Blähungen und ungesunde Säuren überschwemmten Verdauungssystem leiden auch Ihre Darmbakterien. 
                        <br />
                        <br />
                        <b>&#111;</b> Deshalb lautet der <b>dritte Grundsatz</b>: Probieren Sie neue Lebensmittel <b>nur in sehr, sehr kleinen Mengen</b>
                        (z.B. naschen Sie vom Teller anderer Personen am Tisch) und halten Sie die erforderlichen <b>Einschränkungen so lange wie nötig, aber 
                        nur so kurz wie möglich</b> ein. 
                        <br />
                        <br />
                        <b>&#111;</b> Beherzigen Sie dabei den <b>vierten Grundsatz</b>, die &#187;neuen&#171; Lebensmittel in einem <b>Rotationsverfahren</b> zu sich zu nehmen.
                        So geben Sie dem überreizten Immunsystem die Möglichkeit, sich an bisher nicht so bekömmliche Lebensmittel zu gewöhnen und die Verträglichkeit 
                        auf diese Weise zu steigern. Essen Sie an einem Tag eine kleine Menge eines neuen Lebensmittels und pausieren dann für mindestens 4 Tage.
                        Während dieser Zeit essen Sie andere (gerne auch verschiedene neue) Lebensmittel. Danach können Sie das erste wieder verzehren. <b>So werden dem Immunsystem 
                        ganz behutsam nach und nach die neuen Lebensmittel vorgestellt, bis es sie akzeptiert.</b>
                        <br />
                        <br />
                        <b>&#111;</b> Und last but not least <b>ein ganz wichtiger, fünfter Grundsatz</b>: Bitte betrachten Sie Ihre Nahrung nicht mehr als den 
                        &#187;bösen Feind&#171;, der Ihnen schaden will und der Ihr Wohlbefinden beeinträchtigt. Ich möchte Ihnen folgenden Rat auf den 
                        (eventuell etwas längeren) Weg mitgeben: <b>Ihre Nahrung sollte Ihr Freund sein, der Ihrem Körper, Ihrem Geist, Ihrer Darmflora und damit 
                        Ihrer Gesundheit zur Seite steht.</b>
                        <br />
                        <br />
                        <b>&#111;</b> Wenn Sie an Verdauungsproblemen leiden, ist es zunächst einmal gut zu schauen, ob Sie selbst vermeintlichen &#187;Übeltätern&#171;
                        auf die Spur kommen, also Lebensmittel dingfest machen können, die die Symptome verschlimmern. Wenn dies aber nicht in einem absehbaren Zeitraum
                        erfolgreich ist, sollten Sie sich qualifiziert beraten lassen, bevor Sie mehr und mehr Lebensmittel vom Speisezettel streichen &ndash; mit der Folge, 
                        dass Ihre Mikrobiota, wie oben beschrieben, mehr und mehr verarmt. Eine gute Hilfe zur Vorbereitung ist ein <b>Ernährungstagebuch</b>, in dem Sie für 
                        1 &ndash; 2 Wochen eintragen, was Sie verzehren und welche Symptome sich danach zeigen. Eine Vorlage dafür finden Sie auf dieser Website im 
                        <a href="<?= URL_ROOT ?>downloads#tagebuch" target="_blank">Downloadbereich</a>. Mit diesem Hilfsmittel kann ich meist schon recht schnell sehen,
                        wo &#187;der Hase im Pfeffer liegt&#171;.
