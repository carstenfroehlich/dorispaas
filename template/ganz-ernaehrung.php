                        <hr />
                        <h5>Zusätzliche Entscheidungskriterien</h5>
                        <hr />
                        Natürlich gibt es Ernährungsformen, die man weniger unter gesundheitlichen Gesichtspunkten 
                        denn aus Überzeugung einhält. Die meisten Vegetarier bzw. Veganer ernähren sich  
                        ohne Fleisch bzw. frei von jeglichen 
                        tierischen Produkten &ndash; auch wenn deren Herstellung nicht den Tod des Tieres, 
                        nach der Auslegung der Veganer jedoch eventuell deren Ausbeutung bedeutet. 
                        Dies ist selbstverständlich zu respektieren. Ob es jedoch auch gesundheitlich das 
                        Optimum darstellt, steht dann nicht zur Debatte. Ein Veganer würde sich diese Frage 
                        auch nicht stellen, denn er stellt sich als Mensch nicht über sondern auf die gleiche 
                        Stufe wie das Tier. 
                        <br />
                        <br />
                        Sich als Mensch <b>nicht</b> als die &#187;Krone der Schöpfung&#171; zu betrachten,
                        ist auch in meinen Augen richtig. Aber jedes Lebewesen &ndash; gleich ob Mensch 
                        oder Tier &ndash; sollte sich so ernähren dürfen, wie es die Natur vorgesehen hat 
                        und wie es für dieses Lebewesen am gesündesten ist. Dabei sollten jedoch Respekt 
                        und Achtung vor anderen Lebewesen nicht außer Acht gelassen werden.
                        <br />
