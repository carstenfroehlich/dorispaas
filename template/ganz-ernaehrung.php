                        <h5>Welche Kostform ist zu bevorzugen? </h5>
                        <hr />
                        Wenn wir gesund sind, zeigt uns unser Körper leider (oder dankenswerterweise) nicht sofort, 
                        ob uns etwas bekommt oder nicht, was wir gerade verzehrt haben, denn gesundheitliche Folgen 
                        treten bei insgesamt schlechter Kost meistens erst mit einem Zeitversatz von mehreren Jahrzehnten 
                        auf (abgesehen von häufigen Problemen beim Stuhlgang). Hier einen direkten Zusammenhang herzustellen, 
                        ist schwer, und jeder nutzt diese Tatsache in seinem Sinne: Die &#187;Gesundheitsapostel&#171; 
                        warnen, und die Lobbyisten streiten ab. Deshalb sollte aus meiner Sicht in der Regel gelten: 
                        &#187;lieber Vorsicht als Nachsicht&#171;. Wenn wir jedoch an Unverträglichkeiten oder bakteriellen 
                        Fehlbesiedelungen leiden, die ohnehin schon mit Verdauungsbeschwerden einhergehen, folgt 
                        &#187;die Strafe&#171; meist auf dem Fuße, und wir können oft sehr wohl die &#187;Übeltäter&#171; 
                        erkennen. Ist aber das Meiden oft viel zu vieler Lebensmittel des Rätsels letzter Schluss? Auch 
                        und gerade bei Verdauungsbeschwerden gilt es aus verschiedenen Gründen, eine möglichst abwechslungsreiche 
                        Ernährung einzuhalten &ndash; allerdings dürfen hier die Beschwerden nicht aus dem Blick verloren werden.
                        <br />
                        <br />
                        Eine Kost, die überwiegend aus tierischen Produkten wie Fleisch, Wurst, Fisch, 
                        Eiern und Milch und Milchprodukten besteht, ist für unser Verdauungssystem und 
                        für unseren Organismus nicht förderlich &ndash; es sei denn, Sie wohnen in Grönland 
                        und ernähren und vor allem bewegen sich wie ein Inuk. 
                        <br />
                        <br />
                        Auch das andere Extrem, die vegane Kost, ist nur möglich, wenn die Auswahl der 
                        Lebensmittel sehr gut überlegt wird, denn nur bei kluger Zusammenstellung der 
                        verschiedenen Pflanzen kann deren Eiweiß für den menschlichen Organismus vollwertig 
                        genutzt werden. Weiterhin müssen bestimmte Nährstoffe, wie das Vitamin B12, 
                        substituiert, also als Nahrungsergänzungsmittel eingenommen werden, denn 
                        pflanzliche Lebensmittel enthalten dieses Vitamin nicht. 
                        Es wird zwar &ndash; so die Argumentation der Veganer &ndash; von den Bakterien 
                        im Darm synthetisiert, jedoch an einer Stelle im Dickdarm, aus dem so gut wie keine Nährstoffe 
                        mehr vom Körper wieder aufgenommen werden. Ich persönlich halte eine Kostform, 
                        bei der nur ein zusätzlicher Verzehr von künstlichen Vitaminen den Körper gesund 
                        erhält, insgesamt für nicht adäquat. Lesen Sie hierzu gerne auch den Beitrag
                        &#187;<a href="ganz-vegan" target="_blank">Vegane Ernährung &ndash; wie gesund ist sie?</a>&#171;.
                        <br />
                        <br />
                        Vegetarismus &ndash; und hier ist im Gegensatz zum Veganismus eine fleischlose Ernährung aus 
                        pflanzlichen Produkten plus Milch und Milchprodukten (lakto-vegetarisch) oder plus 
                        Eier (ovo-vegetarisch) oder beiden und oftmals auch plus Fisch (pesco-vegetarisch) &ndash; 
                        kann für gesunde Menschen eine gesunde Kostform sein. Vor allem aber ist Vegetarismus 
                        <b>eine</b> Möglichkeit, der Massen- und der nicht artgerechten Tierhaltung ebenso wie 
                        der daraus resultierenden Umweltbelastung und ungerechten Ressourcenverteilung 
                        den Kampf anzusagen.
                        <br />
                        <br />
                        Am ehesten an unser Verdauungssystem angepasst und damit in meinen Augen  
                        die gesündeste Ernährungsform stellt für gesunde Menschen, die möglichst lange 
                        gesund bleiben wollen, folgende Kost dar, die den neu kreierten Namen &#187; 
                        <b>Flexitarismus</b>&#171; trägt (als altmodischer Mensch könnte man genauso gut 
                        &#187;<b>gesunde, abwechslungsreiche, sehr fleischarme Kost</b>&#171; sagen).
                        Hier ist die Nahrung weitestgehend vegetarisch mit Milch, Eiern und/oder Fisch. 
                        Fleisch wird im Allgemeinen nicht gegessen. Lediglich ab und an in sehr geringen 
                        Mengen wird der Speisezettel mit <b>hochwertigem</b> Fleisch aus vernünftiger Tierhaltung 
                        bereichert &ndash; eine Form also, wie sie unsere Großelterngeneration noch praktizierte, 
                        bei der es Fleisch bei reichen Leuten nur als &#187;Sonntagsbraten&#171; gab 
                        &ndash; bei ärmeren Menschen sogar noch seltener als &#187;Festtagsbraten&#171;.
                        <br />
                        <br />
                        Bei einer weltweiten flexitarischen Ernährung in angemessenen Mengen würden die 
                        Menschen gesund (oder zumindest gesünder) bleiben, ernährungsbedingte Erkrankungen 
                        würden weitestgehend zurück gehen, die Umwelt würde (zumindest in Beziehung
                        auf die Erzeugung von Nahrung) geschont, und alle könnten satt werden.
