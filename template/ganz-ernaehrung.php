                        <h5>Was aßen unsere Vorfahren?</h5>
                        <hr />
                        Beschäftigen wir uns nun damit, welche Kost unsere Vorfahren verzehrt haben. In 
                        der Zeit, als sie Sammler und Jäger waren &ndash; also die wirklich ursprüngliche 
                        Form des Menschseins &ndash; verzehrten die Menschen vorwiegend pflanzliche Kost, 
                        vorrangig Früchte. Weiterhin wurden Wurzeln ausgegraben, und am Wegesrand streifte 
                        man auf der Wanderschaft einzelne Körner und Samen von den Halmen. Zur Bereicherung 
                        des Speisezettels dienten Würmer und Insekten, aber auch das eine oder andere gefundene 
                        Vogelei, um die Kost mit tierischen Proteinen anzureichern. Alles wurde natürlich 
                        mangels Feuer roh gegessen.
                        <br />
                        <br />
                        Später dann, als der Mensch das Feuer entdeckte und Waffen erfand, wurden mit 
                        Schleudern zuerst kleinere Tiere wie Hasen gefangen und irgendwann war es ihnen 
                        auch möglich, größere Tiere wie z.B. Mammuts zu erlegen. Die Jagd war aufwändig 
                        und mit großen körperlichen Anstrengungen verbunden. Das Fleisch wurde dann sofort 
                        und dann auch in großen Mengen verzehrt, denn eine Vorratshaltung war damals 
                        nicht möglich, und die wertvolle Energiequelle durfte man nicht verderben lassen. 
                        Danach jedoch war solange wieder pflanzliche Kost angesagt, bis man unter erneuten 
                        Strapazen weitere Beute machen konnte.
                        <br />
                        <br />
                        Menge und Art der Nahrung waren also sowohl den körperlichen Gegebenheiten als 
                        auch der Lebensweise angepasst.
                        <br />
                        <br />
                        Im weiteren Verlauf der Entwicklung wurde der Mensch sesshaft und gewann seine 
                        Lebensmittel als Ackerbauer. Die Feldfrüchte wurden im Laufe vieler Jahrhunderte 
                        durch Zucht immer ertragreicher &ndash; trugen ursprünglich Getreidesorten wie 
                        das Einkorn eben nur ein oder sehr wenige Samenkörner, so wurden mit der Zeit 
                        und &#187;Zucht&#171; die Ähren länger und trugen sehr viel mehr Körner an jedem 
                        Halm. 
                        <br />
                        <br />
                        Hinzu kam später dann die Viehhaltung, um leichter an tierische Zusatzkost zu gelangen. 
                        Aber das Vieh war wertvoll, es wurde nicht einfach so geschlachtet, sondern diente 
                        nur zur gelegentlichen und physiologisch erforderlichen Bereicherung des Speisezettels. 
                        Und auf dem mehrere Jahrtausende umfassenden Zeitstrahl  fast schon in der Gegenwart 
                        kam dann die Milchviehhaltung hinzu, um eben die wertvollen Nutztiere nicht gleich 
                        schlachten zu müssen, wenn man tierisches Eiweiß verzehren wollte. 
                        <br />
                        <br />
                        So weit, so gut, denn immer noch verzehrte der Mensch überwiegend pflanzliche Kost. 
                        Nur die Inuit, die keinen Zugang zu pflanzlichen Produkten hatten, mussten sich auf 
                        die so gut wie rein tierische Kost einstellen, was sich aber mit ihrer Lebensweise 
                        vertrug. Denn in dem kalten Umfeld, in dem sie sich aufhielten, war tierisches Fett 
                        als gehaltvoller Energielieferant lebensnotwenig, und die Fische, die sie fingen, 
                        lieferten ihnen die entsprechenden Vitalstoffe. Die für eine gesunde Verdauung 
                        benötigten Ballaststoffe verschaffte sich der Inuk, indem er den Mageninhalt 
                        seiner Tiere mit verspeiste.
                        <br />
                        <br />
                        In allen anderen Regionen der Welt bestand die übliche Kost aus vollwertiger 
                        pflanzlicher Kost &ndash; in der Menge den jeweiligen Lebensumständen instinktiv 
                        angepasst. 
                        <br />
                        <br />
                        Im Laufe der menschlichen Entwicklung wurde jedes potenzielle Nahrungsmittel nach 
                        dem System von &#187;Versuch und Irrtum&#171; auf seine Wertigkeit und vor allem 
                        auf seine Bekömmlichkeit ausgetestet 
                        &ndash; wobei &#187;Irrtümer&#171; sehr verhängnisvoll sein und sogar mit 
                        dem Leben bezahlt werden konnten. Folglich wurde Unbekömmliches gemieden, denn 
                        die Menschen waren damals noch vernünftig. Isolierten Zucker oder Weißmehl gab 
                        es natürlich genauso wenig wie süße Getränke oder Fruchtsäfte, und selbstverständlich auch 
                        keinerlei künstliche Zusatzstoffe oder sonstige Chemikalien oder gar Giftstoffe, 
                        auf deren Verdauung und Verarbeitung kein menschliches Verdauungssystem eingestellt 
                        ist. Gegessen wurde nicht nur, was das &#187;normale&#171; Verdauungssystem ohne 
                        Schaden für den Gesamtorganismus verdauen konnte, sondern auch, was den Körper 
                        gesund und leistungsfähig erhielt. Die Nahrung diente also nicht nur zum Energiegewinn, 
                        sondern auch der Gesunderhaltung des Menschen.
                        <br />
                        <br />
                        Wurde der Mensch trotz aller Sorgfalt bei der Nahrungsauswahl krank, wurden Kräuter, 
                        Ruhe und liebevoller Zuspruch verwendet, bis der Kranke wieder genesen war. Die 
                        Folgekost war dann wieder die übliche, gesunderhaltende Nahrung.
