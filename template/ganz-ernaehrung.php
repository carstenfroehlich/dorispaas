                        <h5>Und noch ein paar (für mich) wichtige Bemerkungen zum Schluss</h5>
                        <hr />
                        Dieses ist meine ganz persönliche Meinung zu gesunder Ernährung und meine dahin 
                        gehende Entscheidung &ndash; basierend auf einer langjährigen Beschäftigung mit 
                        den wissenschaftlichen Erkenntnissen und der Beobachtung meines eigenen Körpers 
                        und meiner Gesundheit. Trotz dieser Erkenntnisse und trotz der Entscheidung für 
                        <b>meine</b> biologisch basierte, pflanzenbetonte, flexitarische Ernährungsform möchte ich niemanden für eine 
                        von meiner eigenen Entscheidung abweichende Ernährungsform be- oder sogar verurteilen, denn 
                        jede Art von Fanatismus lehne ich ab. Deshalb möchte ich genauso wenig von Menschen, die sich 
                        für davon abweichende Kostformen entschieden haben, angegriffen werden.
                        <br />
                        <br />
                        Letztendlich muss jeder selbst entscheiden, ob und wie viel und in welcher 
                        Weise produzierte Nahrungsmittel er isst. Nur ob die gewählte Ernährungsform gesund 
                        ist oder ob man bei einer fleischlastigeren oder im Gegenteil veganen Ernährung mit womöglich 
                        vielen chemischen Zusatzstoffen nicht irgendwann zum eigenen 
                        Schaden erkrankt und der Allgemeinheit zur Last fällt, ob man mit übermäßigem 
                        Fleischverzehr der Massentierhaltung Vorschub leistet, ob man der 
                        Umwelt Schaden zufügt und Mitmenschen in anderen Regionen der Weltkugel in den 
                        Hunger treibt, muss dann jeder für sich verantworten. 
                        <br />
                        <br />
                        Und es muss auch jeder entscheiden dürfen, Fertiggerichte oder Fleisch zu essen, ohne von anderen 
                        dafür angegriffen zu werden. Gerade Veganer, die sich ja aus tiefstem Herzen und 
                        fester Überzeugung dafür entschieden haben, auf jegliche tierischen Produkte zu 
                        verzichten, neigen leider aus meiner Erfahrung gerne dazu, andere belehren zu wollen 
                        und gebetsmühlenartig auf diversen Plattformen und in zahlreichen Foren zu 
                        missionieren, dass Fleisch- und auch Milchverzehr 
                        ungesund sei. Dies ist so gesagt falsch. Nicht der Fleisch- oder Milchverzehr an 
                        sich ist ungesund &ndash; es ist (wie immer) die Menge, die das Gift macht! 
                        <br />
                        <br />
                        Somit bitte ich jeden, der diesen Beitrag liest &ndash; egal ob Fleisch- oder Pflanzenesser, egal ob 
                        Selbstkochender oder Bevorzugender von industriell hergestellten Fertiggerichten &ndash;
                        Andersdenkende zu tolerieren. Für sich selbst darf jeder 
                        entscheiden, was er isst, zumindest solange es nicht die Rechte anderer oder späterer 
                        Generationen beeinträchtigen würde. Denn auch das gehört zum gesunden Menschsein: die eigene 
                        Entscheidung zu vertreten und trotzdem andere Meinungen zu respektieren.
