                        <hr />
                        <h5>Wie sieht unser Verdauungssystem aus?</h5>
                        <hr />
                        Je nach Wohnort auf der Erde ernähren sich die Menschen völlig unterschiedlich: 
                        Das reicht vom fast ausschließlichen Verzehr von Fleisch und Fisch bei den Inuit auf Grönland 
                        und in Nordkanada bis hin zu der so gut wie <b>vegetarischen</b> Kost in Indien. Und dazwischen 
                        gibt es alle Spielarten. Eine völlig <b>vegane Ernährung</b>, d.h. der Verzicht auf jegliche 
                        tierischen Produkte oder Produkte, zu deren Herstellung tierische Bestandteile 
                        verwendet werden, ist traditionell in keiner Region zu finden. Der Veganismus hat andere als 
                        landestypische und gesundheitsbezogene Gründe und wird später beleuchtet.
                        <br />
                        <br />
                        Um einen Eindruck davon zu bekommen, was <b>für gesunde Menschen</b> gesund sein könnte, 
                        müssen wir uns unseren Körper genauer anschauen und uns überlegen, was unsere 
                        Vorfahren gegessen hatten.
                        <br />
                        <br />
                        Unser <a href="ganz-verdauungssystem" target="_blank">Verdauungssystem</a>, 
                        beginnend bei den Zähnen und endend beim After ist weder auf gänzlich fleischlose 
                        Kost noch auf den ausschließlichen Verzehr tierischer Kost eingerichtet 
                        &ndash; jedoch ist unser Organismus flexibel und kann sich in Grenzen an bestimmte 
                        Gegebenheiten anpassen.
                        <br />
                        <br />
                        Schauen wir zuerst unser Gebiss an &ndash; oder besser: schauen wir uns die Gebisse 
                        von Fleisch- und von Pflanzenfressern an. Fleischfresser <b>(Karnivoren)</b>, 
                        beispielsweise Löwen oder  Hunde, haben im vorderen Bereich spitze Reißzähne 
                        und im hinteren Bereich ebenfalls spitze Zähne, die es ermöglichen, ein Beutetier 
                        festzuhalten, Fleischstücke herauszureißen und diese weitestgehend unzerkaut 
                        hinunterzuschlingen. Die Pflanzenfresser <b>(Herbivoren)</b>, beispielsweise Pferde 
                        oder Hasen, haben vorne relativ scharfe Zähne, um Gras und Pflanzen ausrupfen zu 
                        können und im hinteren Bereich Mahlzähne mit breiten Kauflächen, um das Futter 
                        mit seinen harten Zellwänden zermahlen und so besser verdauen zu können.
                        <br />
                        <br />
                        Auch der Darm unterscheidet sich beim Fleisch- und beim Pflanzenfresser: Fleisch 
                        ist zum einen schnell verdaulich, enthält aber zum anderen auch relativ viele 
                        schädliche Stoffe bzw. kann diese beim Verdauungsprozess entwickeln. Dies erfordert 
                        einen im Vergleich zur Körpergröße kurzen Darm, den Fleischfresser aufzuweisen haben. 
                        Die Nahrung wird rasch verdaut, die Reste können und müssen den Körper so schnell wie möglich wieder verlassen. 
                        Pflanzenfresser hingegen benötigen einen relativ langen Darm, um die festen 
                        Pflanzenzellen aufzuschließen und den Inhalt optimal auszunutzen. Somit haben 
                        Pflanzenfresser bezogen auf ihre Körpergröße immer einen im Vergleich zum Fleischfresser 
                        sehr langen Darm. Darüber hinaus haben sie eine andere Besiedelung mit Darmbakterien, die 
                        dazu erforderlich sind, die eigentlich unverdaulichen, pflanzlichen Bestandteile fermentieren 
                        und so doch noch verwerten zu können.
                        <br />
                        <br />
                        Auch andere Körperorgane wie z.B. die Nieren sind aufgrund der unterschiedlichen Abbauprodukte,
                        die bei der Verdauung aus tierischen oder pflanzlichen Stoffen entstehen, bei Fleisch- bzw. 
                        Pflanzenfressern unterschiedlich ausgelegt und so in der Lage, die verzehrten Nährstoffe aufzuschlüsseln, 
                        zu verwerten und Reste auszuscheiden. Am Besispiel der Nieren allein kann man bereits sehen, dass 
                        eine nicht artgemäße Ernährung auf Dauer diese Organe schädigt: zu viel tierisches Protein kann 
                        beim Menschen, der eben kein Fleisch(fr)esser ist, sogar zu Nierenversagen führen.
                        Und nicht nur die Nieren selbst werden in Mitleidenschaft gezogen, sondern auch andere Bereiche 
                        des Körpers: denken wir nur an die Gicht, die die Menschen befiel und befällt, die zu viel Fleisch 
                        essen (wie früher nur die &#187;reichen&#171; Leute).
                        <br />
                        <br />
                        Dies waren &ndash; zur Verdeutlichung &ndash; die Extreme. Natürlich gibt 
                        es Mischformen, und unser eigenes Verdauungssystem zeigt sowohl beim Gebiss als
                        auch in Bezug auf die Darmlänge eine solche Mischform. Dies klassifiziert uns Menschen somit 
                        als Alles(fr)esser <b>(Omnivoren)</b> oder auch als Früchteesser <b>(Frutarier)</b>.
                        <br />
                        <a id="darmflora"></a>
                        <hr />
                        <h5>Unsere kleinen Mitbewohner</h5>
                        <hr />
                        Nicht nur der Aufbau des Verdauungssystems ist entscheidend dafür, welche Nahrung richtig für 
                        Tier oder Mensch ist, sondern auch die Zusammensetzung der &#187;kleinen Mitbewohner&#171; im Darm 
                        &ndash; landläufig als &#187;Darmflora&#171; bekannt, wissenschaftlich aber mit &#187;Mikrobiota&#171; 
                        oder &#187;Mikrobiom&#171; bezeichnet.
                        <br />
                        <br />
                        Kein Darm, egal, ob von Mensch oder Tier, kann die aufgenommene Nahrung alleine und ohne Hilfe verdauen.
                        Immer sind es <b>Milliarden von Mikroorganismen</b> &ndash; Bakterien, Archaeen, Pilze und Viren &ndash; die den jeweiligen 
                        Darm besiedeln und ihren Wirten bei der Verdauung helfen. Fleisch-, Pflanzen- und Allesfresser haben dabei 
                        eine völlig andere Zusammensetzung der Mikrobiota in ihren Därmen, denn es gilt ja auch, ganz unterschiedliche 
                        Nahrung zu verarbeiten. Allen gemein ist, dass die kleinen Mitbewohner an das Nahrungsangebot angepasst sind: 
                        der Fleischfresser braucht Mikroorganismen, die hauptsächlich Proteinreste verdauen können, der Pflanzenfresser
                        braucht mikrobielle Hilfe beim Aufbrechen von pflanzlichen Zellwänden. Und der Allesfresser braucht von allem etwas.
                        <br />
                        <br />
                        Wirt und Mikroorganismen leben dabei in Symbiose, d.h. jeder profitiert im besten Falle vom anderen. Bakterien und Co.
                        helfen dem Wirt beim Verdauen, und die Bakterien werden mit der aufgenommenen Nahrung gefüttert. Dies funktioniert
                        aber nur, wenn die Nahrung die richtigen Bestandteile für die jeweils arttypischen Mikroorganismen enthält.
                        Wird falsche, sprich artuntypische Nahrung aufgenommen, verändert sich die Zusammensetzung der Mikrobiota &ndash; und 
                        zwar in aller Regel zum Nachteil des Wirts.
                        <br />
                        <br />
                        Isst beispielsweise der Mensch nur wenige Lebensmittel, weil er eventuell eine Diät einhalten muss (oder will),
                        bekommen all diejenigen Darmbakterien nichts mehr zu essen, die sich auf die nun fehlenden Lebensmittel spezialisiert 
                        haben. Die Folge ist, dass die Diversität (Verschiedenheit) unserer 
                        <a href="darmfloragrundsatz" target="_blank">Mikrobiota</a> abnimmt und damit 
                        auch eine der wichtigen Säulen für unsere Gesundheit geschwächt wird.
                        <br />
                        <br />
                        <b>Eine angemessene, unseren körperlichen Voraussetzungen angepasste Ernährung ist deshalb für unsere Mikrobiota ganz essentiell wichtig.</b>
                        <br />
