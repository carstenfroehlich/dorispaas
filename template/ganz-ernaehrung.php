                        Wahrscheinlich lesen Sie diesen Beitrag, weil Sie Verdauungsprobleme haben. Vielleicht sind es
                        <a href="nahrungsmittelunvertraeglichkeiten" target="_blank">Nahrungsmittel-Unverträglichkeiten 
                        oder -Allergien</a>, vielleicht &#187;nur&#171; belastende 
                        Verstopfung, Bauchschmerzen oder Blähungen. Vielleicht aber wurde bereits eine 
                        <a href="duenndarmfehlbesiedelung" target="_blank">Dünndarmfehlbesiedelung (SIBO)</a>
                        diagnostiziert. Bei allen diesen Erkrankungen spielt immer die Ernährung eine ganz entscheidende Rolle.
                        Aus diesem Grunde ist es wichtig, sich einmal mit diesem Thema auseinanderzusetzen. Mit einer 
                        &#187;gesunden&#171; Ernährung kann man nicht nur Krankheiten vorbeugen, sie gehört auch
                        als unverzichtbarer Baustein zu jeder Behandlung von ernährungsassoziierten Erkrankungen dazu.
                        Aber was für den einen gesund ist, muss es nicht zwangsläufig auch für jeden anderen sein. Deshalb 
                        möchte ich dieses Thema an dieser Stelle mit Ihnen betrachten.
                        <br />
                        <br />
                        Es gibt zahlreiche verschiedene Ernährungsformen, und jeder Mensch, der sich gemäß 
                        einer dieser Variationen ernährt, hat seine Gründe dafür. Gleich vorweg: Ich möchte 
                        hier keineswegs dogmatisch für die eine oder gegen eine andere Ernährungsform Partei 
                        ergreifen! Die Rheinische Lebensweisheit &#187;Jeder Jeck ist anders&#171; gilt 
                        selbstverständlich auch für die Art, sich zu ernähren. Ob jedoch alles und  
                        vor allem alles für jeden gesund ist, bleibt dahingestellt.
                        <br />
                        <br />
                        An dieser Stelle möchte ich einmal versuchen, das Für und Wider der verschiedenen 
                        Ernährungsformen zu beleuchten.
