                        <hr />
                        <h5>Was essen wir heute? </h5>
                        <hr />
                        Unsere heutige &#187;zivilisierte&#171; Kost entspricht weder in der Auswahl 
                        der Lebensmittel noch in deren Qualität oder Menge mehr dieser ursprünglichen und 
                        an unser Verdauungssystem angepassten Ernährungsform. Denn auch wenn ich hier in 
                        dieser Beschreibung einen Zeitraum von vielen Tausend Jahren umrissen habe, so hat 
                        sich das Verdauungssystem des Menschen doch keineswegs weiterentwickelt und sieht 
                        immer noch genauso aus, wie in der Zeit der Sammler und Jäger.
                        <br />
                        <br />
                        Abgesehen von dem unstrittigen Verzicht auf Schadstoffe und hochbearbeitete Zutaten 
                        ist es deshalb für gesunde Menschen nach wie vor am besten, sich überwiegend 
                        pflanzlich zu ernähren und den Speisezettel mit wenig tierischen Produkten 
                        anzureichern. Vor allem aber sollten wir die Menge und die Qualität an unsere 
                        meist bewegungsarme Lebensweise anpassen.
                        <br />
                        <br />
                        Was aber tun wir (oder tun zumindest sehr viele Menschen)? Ohne nachzudenken, verzehren 
                        wir in großer Menge Produkte, die uns von verantwortungslosen und gewinngierigen 
                        Herstellern für viel Geld zum Verzehr angedreht werden! Diese Produkte sind in ihren 
                        Inhaltsstoffen und in ihrer Struktur so verändert, dass man sie mit gutem Gewissen 
                        keineswegs mehr als &#187;<b>Lebens</b>mittel&#171; bezeichnen kann. Deshalb ist 
                        es erforderlich, sich selbst zu schützen und gut zu überlegen, welche Nahrungsmittel 
                        für uns geeignet sind, welche tatsächlich Lebensmittel sind, unserer Gesundheit 
                        und damit unserem Leben dienen.
