                    <h5>Buchbeschreibung</h5>
                    <hr />
                    Rumoren im Bauch, Blähungen, Krämpfe oder Durchfälle nach dem Genuss 
                    von Obst, Gemüse und Fruchtsäften &ndash; eine Fruchtzucker-Unverträglichkeit 
                    kann viele quälende Symptome hervorrufen. 
                    <br />
                    Um diese Beschwerden loszuwerden, sollten Sie sich über die Auslöser und 
                    Zusammenhänge und vor allem über die Behandlungsmöglichkeiten informieren. 
                    Aber auch, wenn nicht Sie selbst betroffen sind, sondern ein Familienmitglied, Freund 
                    oder Arbeitskollege, ist es hilfreich, wenn Sie über die Fruchtzucker-Unverträglichkeit 
                    Bescheid wissen.<br />
                    <br />
                    Das Paas'sche Heftchen &#187;Kurz und klar: Fruchtzucker-Unverträglichkeit&#171; erklärt in kurzer 
                    und klarer Form alles Wichtige rund um dieses Thema. Es erläutert darüber 
                    hinaus Ursachen und Hintergründe von Beschwerden. Das Heftchen hilft, Probleme 
                    zu erkennen und zu verstehen und zeigt erste Schritte in die richtige Richtung: 
                    eine gesunde Lebensweise ohne Beschwerden, um sich wohl zu fühlen und bis 
                    ins hohe Alter gesund zu bleiben.
                    <br />
                    Das Heftchen stellt wesentlich mehr Informationen zur Verfügung als eine 
                    Info-Broschüre und versteht sich somit als Vereinigung von Informations-Broschüre 
                    und Sachbuch. Es erhebt bewusst keinen Anspruch auf Ausführlichkeit, sondern 
                    verschafft Ihnen in kurzer, aber korrekter Form einen ersten &Uuml;berblick über das Thema. 
                    Trotz des geringen Umfangs bleibt es jedoch nicht oberflächlich, sondern ist sorgfältig 
                    recherchiert: In rund einer Stunde wissen Sie alles Wesentliche zum Thema &#187;Fruchtzucker-Unverträglichkeit&#171;.
