                        Prinzip wie der Gang des Essens vom Mund &uuml;ber den Magen und durch den Darm bis zum After von Seite zu Seite durch das gesamte Buch. Vertrauenerweckende Frauen und M&auml;nner 
                        nehmen die beiden Kinder, die als Protagonisten durch die Geschichte und das Buch wandern, an die Hand und leiten sie durch Magen, D&uuml;nn- und Dickdarm, so dass sich jeder kleine 
