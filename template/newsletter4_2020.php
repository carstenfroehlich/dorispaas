                        Essen mit den gegessenen Speisen passiert und was dann letztendlich nach einiger Zeit den Körper wieder verl&auml;sst. Dieses toll aufgemachte Buch, erkl&auml;rt die Vorg&auml;nge 
                        der Verdauung anschaulich und kindgerecht, trotzdem aber auch korrekt. Die verwendeten Ausdr&uuml;cke erscheinen dabei zun&auml;chst drastisch, sind aber f&uuml;r Kinder vollkommen 
