                        <h5>Ausgabe 53 (Juli 2020)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2020-04-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Auch wenn die Bedrohung einer durch das Coronavirus SARS-CoV-2 verursachte Covid-19-Erkrankung nach wie vor besteht und die Hygieneregeln weiterhin eingehalten werden sollten,
                        gibt es doch inzwischen einige Lockerungen. So k&ouml;nnen wir uns ganz vorsichtig aus unserem Schneckenhaus hervorwagen und das Leben wieder mehr auskosten.
                        Der Sommer mit angenehmen Temperaturen und sch&ouml;nem Wetter l&auml;dt zum Drau&#223;ensein ein &ndash; und das ist gut so. Denn an der frischen Luft besteht nur eine geringere 
                        Gefahr der &Uuml;bertragung, die ja zu einem hohen Prozentsatz auch durch Aerosole stattfindet. Im Freien halten sich diese mikroskopischen Tr&ouml;pfchen und damit die Lebensf&auml;higkeit 
                        der Viren durch rasches Austrocknen nur f&uuml;r eine sehr kurze Zeitspanne, in geschlossenen R&auml;umen w&auml;re der gleichzeitige Aufenthalt mit anderen Menschen viel problematischer. 
                        Genie&#223;en Sie also bitte die Natur und die Sch&ouml;nheiten, die sie bietet. Es muss keineswegs ein Urlaub in fernen L&auml;ndern sein (die ja derzeit ohnehin gar nicht oder nur mit 
                        Verkehrsmitteln zu erreichen sind, von deren Benutzung ich Ihnen eigentlich lieber abraten m&ouml;chte). Auch G&auml;rten, Parks und selbst kleine Baumscheiben in der Stadt k&ouml;nnen 
                        viele Geheimnisse bereithalten &ndash; wie zum Beispiel die wunderbare Rosenbl&uuml;te mit den Regentropfen auf dem nebenstehenden Foto. Halten Sie die Augen auf!
