                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=stuhlgang" target="_blank">Schwerpunktthema: &#187;Stuhlgang &ndash; Probleme und L&ouml;sungen&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Darmgesundheit/Allgemein/Stuhlgang &ndash; Probleme und L&ouml;sungen)</i>
                        <br />
                        Viele Menschen haben Probleme beim Stuhlgang. Gemeint sind an dieser Stelle nicht Verdauungsprobleme wie z.B. Durchfall oder eine Verstopfung, sondern die Probleme beim Stuhlgang im wahrsten 
                        Sinne des Wortes: wie erleichternd finden Sie das Absetzen Ihres Stuhls, m&uuml;ssen Sie sich dabei &uuml;ber Geb&uuml;hr anstrengen, wie lange dauert der Toilettengang, 
                        f&uuml;hlen Sie sich vollkommen entleert oder meinen Sie, dass noch Stuhlreste im Darm zur&uuml;ckgeblieben sind? In diesem Beitrag finden Sie Informationen &uuml;ber Ihren Kot, 
                        wie er im Idealfall beschaffen sein sollte oder wie Abweichungen zu bewerten und ggf. zu beheben sind. Aber auch der Stuhlgang &ndash; im wahrsten Sinne des Wortes &ndash; wird 
                        thematisiert und geschaut, wie man durch ein korrektes Verhalten beim Stuhlgang verschiedene Probleme verhindern kann. &#187;Normaler&#171; Stuhlgang ist gut geformt, und kann 
                        ohne Pressen abgegeben werden. Das Reinigen auf der Toilette bereitet keine Probleme. Meistens erledigen wir den Stuhlgang regelm&auml;&#223;ig etwa ein- bis zweimal t&auml;glich 
                        &ndash; oftmals sogar zu gleichen Tageszeiten. Es kann jedoch durchaus auch normal sein, wenn Sie nur alle zwei oder drei Tage Stuhlgang haben. H&auml;ufigkeit, Konsistenz, Geruch 
