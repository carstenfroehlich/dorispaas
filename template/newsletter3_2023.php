                        Ern&auml;hrung ist gerade in der heutigen Zeit nichts Einfaches mehr: nicht nur, dass vielen Menschen &ndash; insbesondere, wenn sie berufst&auml;tig sind &ndash; 
                        die Zeit fehlt, um aus frischen unbelasteten Zutaten t&auml;glich eine gesunde Mahlzeit zuzubereiten, es ist auch immer schwieriger, diese Zutaten zu bekommen. 
                        Viel zu viele Bauern spritzen noch ihre Felder mit &#187;Pflanzenschutzmitteln&#171;, die leider noch erlaubt sind, die f&uuml;r unsere Gesundheit aber keineswegs 
                        zutr&auml;glich sind. Aus Zeitmangel wird auch viel zu oft auf Fertiggerichte zur&uuml;ckgegriffen, deren Zutatenliste ellenlang ist und zahlreiche Zusatzstoffe 
                        enth&auml;lt, die unser Verdauungssystem g&uuml;nstigstenfalls nicht kennt. Es wundert deshalb nicht, wenn sich Magen, Darm und die Leber wehren und Verdauungsprobleme 
                        entstehen. Sp&auml;testens wenn Verdauungsbeschwerden auftreten, ist es an der Zeit, seine Ern&auml;hrung einmal zu hinterfragen und zu schauen, welche 
                        M&ouml;glichkeiten man selbst hat, etwas an dieser Situation zu &auml;ndern.
