                        <h5>Ausgabe 66 (Herbst 2023)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2023-03-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Im Herbst finden wieder zahlreiche Feste statt, die mit der Ernte zusammenh&auml;ngen. Damit meine ich nicht die kommerziellen, zu reinem Gewinnstreben verkommenen 
                        Bierzelt-Gelage, sondern z.B. das christlich basierte Erntedankfest. Auch in anderen Religionen finden (nicht immer im Herbst, aber immer mit dem gleichen Hintergrund) 
                        &auml;hnliche Feste statt: wir freuen uns und sind dankbar f&uuml;r eine gute Ernte, die keineswegs selbstverst&auml;ndlich sein muss. Gerade mit Blick auf den 
                        Klimawandel, aber auch wegen der seit einiger Zeit stark steigenden Preise, die nicht mehr jeder so ohne Weiteres schultern  kann, sollte uns bewusst sein, dass 
                        nicht nur ausreichende, sondern vor allem auch gesunde Nahrung ein Privileg ist, f&uuml;r das wir durchaus dankbar sein sollten. Aber es reicht nicht, nur 
                        gen&uuml;gend Gesundes zu essen zu haben, es ist auch wichtig, m&ouml;glichst viele verschiedene Lebensmittel zu verzehren. Insbesondere f&uuml;r Menschen mit mehreren 
                        Unvertr&auml;glichkeiten ist diese wunderbare Vielfalt auf dem Teller oft ein (unerf&uuml;llter) Wunschtraum. Sie versagen sich immer mehr Lebensmittel, weil 
                        sie sie nicht vertragen. Die &Auml;u&#223;erung &#187;Ich vertrage nur noch 20 Lebensmittel&#171; h&ouml;re ich von viel zu vielen meiner Klienten. Dabei ist es 
                        so wichtig, auch bei der Ern&auml;hrung auf Diversit&auml;t zu achten &ndash; genauso wichtig, wie (wieder) Freude am Essen zu haben!
