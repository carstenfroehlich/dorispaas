                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=lebensmittel-datenbank-info" target="_blank">DorisPaas.de &ndash; Lebensmittel-Datenbank &ndash; ein umfangreiches Update</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/DorisPaas.de &ndash; Lebensmittel-Datenbank/Info)</i>
                        <br />
                        Als Entscheidungshilfe f&uuml;r eine m&ouml;glichst umfangreiche Lebensmittel-Palette auch unter schwierigeren Bedingungen m&ouml;chte ich Ihnen die 
                        &#187;DorisPaas.de &ndash; Lebensmittel-Datenbank&#171; empfehlen. Ziel dieser Datenbank ist es, Ihnen aufzuzeigen, wie viele M&ouml;glichkeiten Sie trotz ggf. 
                        mehrerer Einschr&auml;nkungen haben. Die Datenbank, die jetzt seit fast 10 Jahren existiert und st&auml;ndig aktualisiert wird, enth&auml;lt mittlerweile <b>&uuml;ber 
                        1500 Lebensmittel</b>, aus denen Sie w&auml;hlen k&ouml;nnen. Mithilfe von <b>10 verschiedenen Filtern</b> k&ouml;nnen Sie <b>&#187;Ihre&#171; Unvertr&auml;glichkeiten</b> und 
                        Bedingungen individuell sortieren, um die f&uuml;r Sie gr&ouml;&#223;tm&ouml;gliche Auswahl <b>in einem einzigen Fenster</b> angezeigt zu bekommen: keine zig verschiedenen Listen 
                        mehr, die man f&uuml;r die verschiedenen Unvertr&auml;glichkeiten ausgedruckt hat und deren Inhalte viel zu h&auml;ufig kaum Schnittmengen ergeben. Als neuestes Update 
                        gibt es jetzt nicht nur eine zus&auml;tzliche Spalte f&uuml;r den <b>Schwefelgehalt</b> von Lebensmitteln (wichtig u.a. bei einer Schwefelwasserstoff-SIBO), sondern auch 
                        Hinweise auf problematische Lebensmittel wie u.a. <b>Nachtschattengew&auml;chse, Korbbl&uuml;tler oder den Nickelgehalt</b>. Ein solche F&uuml;lle von Auswahlm&ouml;glichkeiten, 
                        um vertr&auml;gliche Lebensmittel anzeigen zu lassen, ist sicherlich eine phantastische Hilfe, den eigenen Speisezettel zu erweitern und das Essen nicht mehr als &#187;den b&ouml;sen 
                        Feind&#171; zu betrachten.
