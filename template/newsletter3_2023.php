                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-ernaehrung" target="_blank">Schwerpunktthema: Gesunde Ern&auml;hrung</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Ern&auml;hrung/Was ist gesunde Ern&auml;hrung?)</i>
                        <br />
                        Eine gesunde Ern&auml;hrung ist nat&uuml;rlich f&uuml;r jeden von uns, aber ganz besonders f&uuml;r Menschen mit Verdauungsbeschwerden wichtig. Hier kommt es vorrangig 
                        auf die Bek&ouml;mmlichkeit der Lebensmittel an, um Probleme zu minimieren, die aufgrund von Nahrungsmittel-Unvertr&auml;glichkeiten, -Allergien und/oder 
                        bakteriellen Fehlbesiedelungen in D&uuml;nn- und Dickdarm beim Verzehr bestimmter Esswaren auftreten. Dann ist die Auswahl nicht nur von der 
                        Ernte, also der Verf&uuml;gbarkeit abh&auml;ngig, sondern eben noch zus&auml;tzlich von der Wirkung auf die Verdauung. Eine gesunde Ern&auml;hrung wird 
                        dann immer schwieriger. Einschr&auml;nkungen sollten aber nur insoweit vorgenommen werden, wie sie tats&auml;chlich erforderlich sind. Dies sind vorrangig 
                        diejenigen Abstriche, die gesundheitliche Nachteile bringen. Andere Beschr&auml;nkungen, deren Berechtigung ich hier an dieser Stelle gar nicht in Abrede 
                        stellen will, sollten aber &ndash; eventuell vor&uuml;bergehend &ndash; zugunsten der Gesunderhaltung des Verdauungssystems und der Darmflora hintenangestellt 
                        werden. <a href="http://www.dorispaas.de/index.php?page=ganz-ernaehrung" target="_blank"> Lesen Sie hier gerne weiter ...</a>
