                        Die &#187;Behandlung&#171; der Oligosaccharid-Unvertr&auml;glichkeit besteht vorrangig 
                        aus dem weitestgehenden Weglassen von oligosaccharidhaltigen Lebensmitteln 
                        (siehe &#187;<a href="oligosaccharide-wasistdas#oi-liste">Welche Lebensmittel enthalten Oligosaccharide?</a>&#171;).
                        <br />
                        <br />
                        Weiterhin ist nat&uuml;rlich <b>auf eventuelle weitere Unvertr&auml;glichkeiten zu 
                        achten</b> und mit einer ad&auml;quaten Ern&auml;hrungsform zu reagieren.
                        <br />
                        <a id="nahrungsmittelauswahl"></a>
                        <hr />
                        <h5>Nahrungsmittel-Auswahl</h5>
                        <hr />
                        Auf jeden Fall aber sollten Sie <b>den &uuml;berm&auml;&#223;igen Verzehr von Milch 
                        und Milchprodukten meiden</b> (auch wenn Sie nicht laktoseintolerant sind), da diese 
                        Lebensmittel geringe Mengen an Oligosacchariden enthalten. Dar&uuml;ber hinaus 
                        sind <b>fruktosereiche Lebensmittel</b> zu <b>reduzieren</b>, auch dann, wenn Sie 
                        keine Fruktose-Intoleranz oder -Malabsorption haben, denn die Kapazit&auml;t der 
                        f&uuml;r eine reibungslose Verwertung erforderlichen Transportproteine ist bei 
                        jedem Menschen begrenzt. Auch die <b>Zuckeralkohole</b> (Sorbit, Xylit, Mannit 
                        und Erythrit) sind unbedingt weitestgehend <b>einzuschr&auml;nken</b>, denn sie 
                        f&uuml;hren bei &uuml;berm&auml;&#223;igen Verzehrmengen immer zu Verdauungsproblemen.
                        <br />
                        <br />
                        Und last, but not least werden Sie die Verzehrmenge der <b>Ballaststoffe</b> 
                        (Polysaccharide) <b>beobachten</b> m&uuml;ssen, da diese immer nur sehr schwer 
                        verdaulich sind und gerade in Verbindung mit einer Oligosaccharid-Unvertr&auml;glichkeit 
                        die Beschwerden verst&auml;rken.
                        <br />
                        <a id="darmpflege">&nbsp;</a>
                        <hr />
                        <h5>Darmpflege</h5>
                        <hr />
                        Ganz wichtig ist bei einer Oligosaccharid-Unvertr&auml;glichkeit die <b>Pflege 
                        der Darmflora</b>, damit durch eine vorteilhafte Zusammensetzung der Keimbesiedelung 
                        m&ouml;glichst viele Bakterienarten vorhanden sind, die zu einer weitestgehend 
                        folgenlosen Aufspaltung der Oligo- und Polysaccharide beitragen k&ouml;nnen.
                        <br />
                        <br />
                        Da sich die Qualit&auml;t von Darmflora und Darmschleimhaut gegenseitig beeinflussen, 
                        sollten Sie auch f&uuml;r eine <b>gesunde Darmschleimhaut</b> sorgen. Normalerweise 
                        ist hier das Mittel der Wahl der verst&auml;rkte Verzehr von Vollkornprodukten &ndash; 
                        wodurch sich nun eine Zwickm&uuml;hlensituation ergibt, denn der &uuml;berm&auml;&#223;ige 
                        Verzehr von Ballaststoffen (Polysacchariden) kann die Symptome einer 
                        Oligosaccharid-Unvertr&auml;glichkeit vervielfachen. Somit ist ein sehr behutsames 
                        Vorgehen und Austesten erforderlich, um die h&ouml;chstm&ouml;gliche, individuell 
                        vertr&auml;gliche Menge an Ballaststoffen zu ermitteln. Bevorzugen Sie dabei Produkte 
                        mit fein vermahlenem Schalenanteil, da dies bek&ouml;mmlicher ist als grobe K&ouml;rner. 
                        Aber auch die fein vermahlenen K&ouml;rner tragen schon zu einer Abtragung der alten, 
                        abgestorbenen Zellen von der Darmschleimhautoberfl&auml;che bei und sorgen dadurch 
                        daf&uuml;r, dass die jungen, leistungsf&auml;higen Zellen ihre Funktion optimal 
                        aus&uuml;ben k&ouml;nnen.
                        <br />
                        <br />
                        Der verst&auml;rkte Verzehr von pr&auml;biotischen Lebensmitteln ist bei einer 
                        Oligosaccharid-Unvertr&auml;glichkeit nicht empfehlenswert, da die darin enthaltenen 
                        Inuline und Oligofuktose-Bestandteile meist nicht vertragen werden. 
                        <br />
                        <br />
                        Sie k&ouml;nnen jedoch die Darmflora mit dem Verzehr von milchsauer vergorenen 
                        Getr&auml;nken wie Kombucha, Wasserkefir, Kwass oder Kanne Brottrunk unterst&uuml;tzen, 
                        denn die dort enthaltenen S&auml;uren (Milch-, Essig- und Glucurons&auml;ure) 
                        f&ouml;rdern ein g&uuml;nstiges Milieu f&uuml;r die n&uuml;tzlichen Darmbakterien 
                        und hemmen dabei gleichzeitig das Wachstum und die &uuml;berm&auml;&#223;ige 
                        Vermehrung der sch&auml;dlichen Keimarten. Beachten Sie unbedingt, dass Sie die 
                        Verzehrmengen dieser Getr&auml;nke einschleichen, d.h. behutsam erh&ouml;hen 
                        m&uuml;ssen, damit sich Ihr empfindliches Verdauungssystem daran gew&ouml;hnen kann.
                        <br />
                        <br />
                        Probiotische Milchprodukte, die Sie mittlerweile in jedem Supermarkt in reichlicher 
                        Auswahl f&uuml;r teures Geld erhalten k&ouml;nnen, sind nicht empfehlenswert, da 
                        zum einen die enthaltenen Bakterienmengen viel zu gering sind und die Keime 
                        dar&uuml;ber hinaus die Magens&auml;ureschranke kaum &uuml;berwinden k&ouml;nnen. 
                        Zum anderen sollten Sie, wie oben erw&auml;hnt, den Verzehr von Milchprodukten 
                        einschr&auml;nken, da Milch Oligosaccharide enth&auml;lt. 
                        <br />
                        <br />
                        Falls Sie probiotische Nahrungserg&auml;nzungsmittel, also Pr&auml;parate mit 
                        lebensf&auml;higen Darmkeimen einnehmen m&ouml;chten, um die Zusammensetzung Ihrer 
                        Darmflora zu unterst&uuml;tzen, gehen Sie auch hier besonders behutsam vor. Auch 
                        Probiotika m&uuml;ssen immer eingeschlichen werden. Bei Pr&auml;paraten in Kapselform 
                        ist dies schwierig, hier sollten Sie ggf. immer die kleinstm&ouml;gliche Dosierung 
                        f&uuml;r den Anfang w&auml;hlen und vorsichtig innerhalb einiger Wochen bis zur 
                        tats&auml;chlich empfohlenen Dosis steigern. 
                        <br />
                        <br />
                        Ich kann Ihnen jedoch ein Probiotikum in Pulverform empfehlen, das nur einen einzigen, 
                        magens&auml;ureresistenten Bakterienstamm (Bacillus coagulans) enth&auml;lt. Vor 
                        allem aber ist es frei von pr&auml;biotischen Zus&auml;tzen. Das Pulver k&ouml;nnen Sie 
                        unproblematisch einschleichen und dann auf die erforderliche Dosierung steigern 
                        (<a href="http://www.laktasekampagne.de" target="_blank">www.laktasekampagne.de</a>). 
                        <br />
                        <a id="naturheilmethoden">&nbsp;</a>
                        <hr />
                        <h5>Naturheilmethoden</h5>
                        <hr />
                        Sie k&ouml;nnen die Intensit&auml;t von Beschwerden, die nach dem Verzehr von 
                        Oligo- und Polysacchariden auftreten, ein wenig mildern, indem Sie geeignete 
                        Naturheilmethoden anwenden.
                        <br />
                        <br />
                        Insbesondere eignen sich hier Kr&auml;utertees, die verhindern, dass sich gebildete 
                        Darmgase festsetzen. Insbesondere sind hier die Standardsorten <b>Anis, Fenchel 
                        und K&uuml;mmel</b> zu nennen, aus deren frisch geschroteten Samen Sie einen 
                        bl&auml;hungsl&ouml;senden Tee bereiten k&ouml;nnen.
                        <br />
                        <br />
                        Die Produktion s&auml;mtlicher Verdauungss&auml;fte k&ouml;nnen Sie mit 
                        <b>Bitterstoffpflanzen</b> anregen &ndash; hier eignen sich Artischocke und 
                        L&ouml;wenzahn als Frischpflanzenpresssaft oder auch Wermut und Enzian als Tee 
                        (wegen des bitteren Geschmacks vorsichtig dosieren!).
                        <br />
                        <br />
                        Versuchen k&ouml;nnen Sie auch, ob vorsichtige <b>Darmmassagen</b> als entspannend 
                        empfunden werden. Dabei kreisen Sie mit den flachen H&auml;nden im Uhrzeigersinn 
                        um den Unterbauch, um so die vorhandenen Gase in Richtung Ausgang zu bef&ouml;rdern.
                        <br />
                        <br />
                        Auch <b>warme Leibwickel oder Leberwickel</b> eignen sich zur Entspannung eines 
                        gereizten Verdauungssystems und zur Unterst&uuml;tzung der Verdauungsfunktionen.
                        <br />
                        <br />
                        Grunds&auml;tzlich ist es immer gut, sich sportlich zu bet&auml;tigen und so durch 
                        <b>ausreichende Bewegung</b> daf&uuml;r zu sorgen, dass auch das Verdauungssystem 
                        so normal wie m&ouml;glich arbeitet. Gemeint ist an dieser Stelle nicht etwa 
                        Leistungssport, sondern einfach nur alles, was Ihnen Spa&#223; macht. Finden Sie 
                        hier Ihre favorisierte Sportart - am besten an der frischen Luft. Empfehlenswert 
                        sind beispielsweise Walken oder Nordic Walking, Wandern, Radfahren, Schwimmen und 
                        vieles mehr.
                        <br />
                        <br />
                        Und selbstverst&auml;ndlich k&ouml;nnen Sie ein &uuml;berreiztes Verdauungssystem 
                        durch <b>Entspannungs&uuml;bungen</b> beruhigen. Es bieten sich hier Autogenes Training, 
                        Progressive Muskelentspannung nach Jacobson, Meditation oder auch Yoga oder Qigong an. 
                        Alle Techniken k&ouml;nnen Sie u.a. in den Volkshochschulen erlernen und dann zu 
                        Hause weiter durchf&uuml;hren. Lesen Sie hier zu auch den Beitrag 
                        &#187;<a href="ganz-magendarm">Ganzheitliche 
                        Betrachtung von Magen-/Darmbeschwerden</a>&#171;
                        <br />
                        <a id="medikamente">&nbsp;</a>
                        <hr />
                        <h5>Medikamente bei Oligosaccharid-Unvertr&auml;glichkeit</h5>
                        <hr />
                        Es gibt keine Medikamente, die eine Oligosaccharid-Unvertr&auml;glichkeit heilen 
                        k&ouml;nnten. Auch gibt es keine Medikamente, die die Beschwerden nachhaltig 
                        urs&auml;chlich beeinflussen k&ouml;nnten. Lediglich bl&auml;hungstreibende Pr&auml;parate 
                        (Wirkstoffgruppe der Carminativa) k&ouml;nnen verhindern, dass sich Darmgase 
                        festsetzen und dadurch schmerzhaft sind. Entweichende Bl&auml;hungen allerdings 
                        k&ouml;nnen Sie nicht verhindern &ndash; die Gase werden nur zu einem Teil von den 
                        Schleimh&auml;uten resorbiert (aufgenommen), die gr&ouml;&#223;eren Teile m&uuml;ssen 
                        auf dem nat&uuml;rlichen Wege entsorgt werden.
                        <br />
                        <a id="enzyme">&nbsp;</a>
                        <hr />
                        <h5>Enzym-Pr&auml;parate</h5>
                        <hr />
                        Die beste Methode zur Behandlung einer Nahrungsmittel-Unvertr&auml;glichkeit ist 
                        immer das Meiden der unvertr&auml;glichen Bestandteile. Dies kann jedoch bei der 
                        Oligosaccharid-Unvertr&auml;glichkeit und dem gleichzeitigen Bestreben nach einer 
                        gesunden Kost manchmal eine Gratwanderung und damit nicht ganz einfach sein.
                        <br />
                        <br />
                        Zur L&ouml;sung dieses Problems bieten sich Enzympr&auml;parate als Unterst&uuml;tzung 
                        an, also frei verk&auml;ufliche Nahrungserg&auml;nzungsmittel, die die fehlenden 
                        Enzyme erg&auml;nzen, die zur Verdauung der Oligosaccharide erforderlich sind.
                        <br />
                        <br />
                        Es gibt derzeit nur wenige Pr&auml;parate auf dem Markt, z.B. 
                        <br />
                        <b>Digest Gold</b> (Internet) (<a href="https://www.supplementa.com/art/32010EA" target="_blank">Enzymedica, erhältlich über Supplementa, NL-9675 JL Winschoten, Niederlande</a>)
                        <br />
                        <b>Oligase 600 Kapseln</b> (Apotheke) (<a href="http://www.oligase.de" target="_blank">www.oligase.de</a>)
                        <br />
                        <b>Sanotact Verdauungsheld Tabletten</b> (Drogeriemarkt) (vormals Biolabor Verdauungsenzym) (<a href="https://sanotact.de/project/verdauungsheld-mini-tabletten-im-klickspender/" target="_blank">www.Sanotact.de</a>)
                        <br />
                        <br />
                        Die letzten beiden Pr&auml;parate enthalten pro Tablette bzw. Kapseln 600 Einheiten Alpha-Galactosidase 
                        (GalU). Bei oligosaccharidreichen Mahlzeiten ist der Verzehr von 2-4 Tabletten bzw. 
                        Kapseln angeraten, wobei die Oligase 600-Kapseln auch ge&ouml;ffnet und der Inhalt 
                        &uuml;ber die Speisen gestreut und so die Wirkung verst&auml;rkt werden kann 
                        (Achtung: nicht bei hei&#223;en Speisen, Enzyme sind hitzeempfindlich!).
                        <br />
                        <br />
                        Das Pr&auml;parat Oligase 600 enth&auml;lt dar&uuml;ber hinaus zus&auml;tzlich zu 
                        der Alpha-Galactosidase noch verschiedene weitere Enzyme, die bei der Verdauung 
                        von anderen Oligo- und Polysacchariden helfen.
                        <br />
                        <br />
                        Digest Gold enthält neben der Alpha-Galactosidase noch weitere Verdauungsenzyme, so dass die drei 
                        Präparate allein von den Inhaltsstoffen nicht vergleichbar sind. Am besten kaufen Sie ggf. kleine 
                        Packungen und testen Sie die Wirkungen aus. 
                        <br />
                        <br />
                        Weitere Informationen zu geeigneten Präparaten finden Sie auf der Seite <a href="praeparatetest">Präparatetests</a>, 
                        auf der verschiedene Präparate von mir getestet und (subjektiv!) bewertet wurden.
                        <br />
                        <br />
                        Nicht nur wegen der zus&auml;tzlichen Enzyme m&ouml;chte ich Ihnen eher die Oligase 
                        600 empfehlen, es ist dar&uuml;ber hinaus auch das preisg&uuml;nstigere Pr&auml;parat.
                        <br />
                        <br />
                        Beide Pr&auml;parate m&uuml;ssen <b>so früh wie möglich</b>, am besten mit dem ersten Bissen der Mahlzeit eingenommen 
                        werden, bei besonders oligosaccharidreichen und auch bei l&auml;ngeren Mahlzeiten 
                        empfiehlt sich die Einnahme einer weiteren Dosis w&auml;hrend des Essens. Die 
                        Enzyme m&uuml;ssen sich im Magen gut mit dem Speisebrei vermischen &ndash; dies 
                        kann nur erfolgen, wenn sie vor oder w&auml;hrend der Mahlzeit eingenommen werden. 
                        Eine nachtr&auml;gliche Einnahme ist so gut wie wirkungslos &ndash; dieses Geld 
                        k&ouml;nnen Sie sich sparen.
                        <br />
                        <br />
                        Sollten in Zukunft weitere Pr&auml;parate auf den Markt kommen, werde ich Sie an 
                        dieser Stelle informieren. Falls Sie neue Pr&auml;parate entdecken, w&uuml;rde 
                        ich mich &uuml;ber eine Nachricht per <a href="mailto:kontakt@dorispaas.de" class="link">eMail</a> 
                        von Ihnen freuen. Auch Herstelleranfragen sind an dieser Stelle willkommen, um 
                        m&ouml;glichst viele Informationen sammeln zu k&ouml;nnen.
