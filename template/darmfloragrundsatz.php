                                <h5>Das &#187;Rundumpaket&#171; für Ihre Mikrobiota</h5>
                                <hr />
                            </div>
                        </div>
                        Für eine gesunde Mikrobiota reicht es nicht, nur ab und an ein (vielleicht sogar 
                        geeignetes) Probiotikum einzunehmen. Es gehört schon sehr viel mehr dazu.
                        <br />
                        <br />
                        Worauf Sie für sich selbst leider keinen Einfluss mehr nehmen können, ist die Art, 
                        wie Sie zur Welt gekommen sind und welche Nahrung Sie von Ihrer Mutter bekommen 
                        haben. Auch können Sie nicht mehr steuern, welcher Keimvielfalt Sie als Kind ausgesetzt 
                        sein durften. 
                        <br />
                        <br />
                        Sie können jedoch mit Ihrer <b>Ernährung</b> und mit der Menge des Konsums von <b>Genussmitteln</b>, 
                        aber auch mit einem klugen <b>Stressmanagement</b> und aktiven <b>Bewegungsverhalten</b> &ndash; z.B. 
                        mit regelmäßiger <a href="darmgymnastik" target="_blank">Darmgymnastik</a> &ndash; einen 
                        gro&#223;en Einfluss auf die Qualität Ihrer Mikrobiota nehmen. Auch Ihr <b>Medikamentenkonsum</b> 
                        und der Gebrauch von <b>Nahrungsergänzungsmitteln</b> sind &ndash; zumindest zum Teil &ndash; 
                        von Ihren Entscheidungen abhängig, <b>wodurch Sie zahlreiche Möglichkeiten in der Hand 
                        haben, Ihre Mikrobiota zu optimieren</b>.
                        <br />
