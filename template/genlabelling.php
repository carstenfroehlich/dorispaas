                        <h5>Gentechnik &ndash; nein danke! </h5>
                        <hr />
                        Deutsche Verbraucher wollen in ganz überwiegender Anzahl keine Nahrungsmittel kaufen 
                        und verzehren, die mit gentechnisch veränderten Organismen (GVO) hergestellt wurden.
                        <br />
                        <br />
                        Leider ist es aber sehr schwer bzw. so gut wie unmöglich, festzustellen, ob ein 
                        Lebensmittel mit GVO hergestellt oder produziert wurde, obwohl eine Deklaration  
                        bereits seit 2003 gesetzlich vorgeschrieben ist. 
                        <br />
                        <br />
                        Das Gesetz lässt nämlich leider 
                        &ndash; wie wir es von vielen anderen Gesetzen kennen &ndash; viele Ausnahmen und 
                        Schlupflöcher zu: Die Vorschrift gilt nur für Lebensmittel, die selbst mit gentechnisch 
                        verändert wurden. Zutaten jedoch, die mit Hilfe von GVO hergestellt wurden, wie 
                        beispielsweise Zusatzstoffe oder Aromen, müssen nicht gekennzeichnet werden.
                        <br />
                        <br />
                        Auch Tiere, deren Fleisch, Milch oder Eier in die Weiterverarbeitung oder aber 
                        auch direkt in die Theken gelangen, dürfen mit gentechnisch verändertem und erzeugten 
                        Futter gemästet werden, ohne dass dies deklariert werden muss.
                        <br />
                        <br />
                        Da derzeit mehr als 3/4 des von der EU importierten Futter-Soja aus gentechnisch 
                        veränderten Sorten besteht, kann man sich leicht ausrechnen, wie hoch der Anteil 
                        des Fleisches, der Milch und der Eier ist, der mit Hilfe von GVO produziert wurde. 
