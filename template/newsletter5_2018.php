                        auf jeden Fall aber beim Genie&#223;en Ihrer gesunden Mahlzeiten und sende Ihnen 
                        bis zum n&auml;chsten Newsletter, den Sie in zwei Monaten, also etwa Mitte November 
                        2018 erhalten, ganz herzliche Gr&uuml;&#223;e aus dem Rheinland 
