                        <h5>Ausgabe 42 (September 2018)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-05-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Vor ein paar Monaten noch haben wir uns den Sommer mit gutem Wetter herbeigesehnt &ndash; 
                        dass er dann aber mit einer solch heftigen und langen Hitzeperiode kam, lie&#223; uns dann doch aufst&ouml;hnen. 
                        N&auml;chte bei mehr als 20 Grad Au&#223;entemperatur und nicht selten  
                        30 Grad und mehr im Schlafzimmer raubte uns den erholsamen Schlaf und l&auml;hmte uns f&uuml;r den 
                        anschlie&#223;enden Tag. Ganz zu schweigen von den katastrophalen Folgen f&uuml;r die Bauern, 
                        deren Arbeit von Wochen und Monaten zunichte gemacht wurde und zu gro&#223;en Ernteausf&auml;llen f&uuml;hrte.
                        Ich denke zwar, dass einiges an diesem Problem auch ein wenig &#187;selbstgemacht&#171; ist und eine 
                        umweltgerechtere Produktionsweise und kl&uuml;gere Fruchtfolge die Sch&auml;den weniger 
                        drastisch h&auml;tten ausfallen lassen k&ouml;nnen, aber auch wir tragen ja durch unser 
                        eigenes Konsumverhalten zumindest zu einem kleinen Teil mit die Verantwortung f&uuml;r 
                        die Entwicklung in der Landwirtschaft und damit u.a. auch f&uuml;r den Klimawandel.
                        Wenn jeder nur wenig von seinen Gewohnheiten &auml;ndert, k&ouml;nnen diese vielen kleinen 
                        Bausteine zusammen genommen sicherlich schon recht viel bewirken. Zumindest aber ist es ein Anfang!
                        <br />
                        <br />
                        <hr>
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-zuckerempfehlung" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-05-zucker.png" alt="Bild Zucker" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149; <a href="http://www.dorispaas.de/index.php?page=ganz-zuckerempfehlung" target="_blank">Schwerpunktthema: &#187;Bewusster s&uuml;&#223;en: Zucker und andere S&uuml;&#223;ungsmittel&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Ern&auml;hrung/Empfehlenswerte S&uuml;&#223;ungsmittel)</i>
                        <br />
                        &#187;Zucker ist ungesund&#171;, &#187;Honig ist gesund&#171;, &#187;Fruchtzucker ist gut bei Diabetes&#171;,
                        &#187;Traubenzucker geht rasch ins Blut und steigert die Leistungsf&auml;higkeit&#171;, 
                        &#187;Xylit ist gut f&uuml;r die Z&auml;hne&#171;, &#187;S&uuml;&#223;stoff erzeugt Krebs&#171;,   
                        &#187;Stevia ist gesund&#171;.
                                                <br />
                        Wie diese gibt es zahlreiche Vorurteile &uuml;ber S&uuml;&#223;ungsmittel &ndash; was aber ist 
                        dran an diesen &Auml;u&#223;erungen, was ist falsch und was entspricht der Wahrheit?
                        Immer wieder werde ich mit diesen Feststellungen konfrontiert und gefragt, welches der 
                        vielen S&uuml;&#223;ungsmittel empfehlenswert oder zumindest am empfehlenswertesten sei.
                        Die G&uuml;ltigkeit der oben angef&uuml;hrten Zitate ist relativ rasch erkl&auml;rt, aber 
                        auf die Frage, welches S&uuml;&#223;ungsmittel am empfehlenswertestens ist, gibt es keine 
                        allgemeing&uuml;ltige Antwort. Trotzdem versuche ich in dem aktuell &uuml;berarbeiteten Beitrag
                        &#187;<a href="http://www.dorispaas.de/index.php?page=ganz-zuckerempfehlung" target="_blank">Welche S&uuml;&#223;ungsmittel sind empfehlenswert?</a>&#171; 
                        die Gr&uuml;nde aufzuzeigen, die f&uuml;r oder gegen die verschiedenen S&uuml;&#223;ungsmittel sprechen. 
                        Lesen Sie zu diesem Thema auch den Artikel &#187;<a href="http://www.dorispaas.de/index.php?page=zuckerkrankheiten" target="_blank">Wird man von Zuckergenuss krank &ndash; und wenn ja, warum?</a>&#171; 
                        und informieren Sie sich im umfangreichen &#187;<a href="http://www.dorispaas.de/index.php?page=lexikonzucker" target="_blank">Lexikon 
                        der Zuckerarten und S&uuml;&#223;ungsmittel</a>&#171; unter dem Men&uuml;punkt &#187;Wissensdatenbank/Lexika&#171;.
