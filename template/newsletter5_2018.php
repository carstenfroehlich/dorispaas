                        <a href="http://www.dorispaas.de/index.php?page=blog#blog-2018-08-14" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-05-obstsack.png" alt="Bild Stoffsack" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=blog#blog-2018-08-14" target="_blank">Mit Stoffs&auml;ckchen Plastikm&uuml;ll vermeiden</a></b>
                        <br />
                        <i>(Men&uuml;: Doris Paas/Blog)</i>
                        <br />
                        Greifen auch Sie beim Obst- und Gem&uuml;seeinkauf immer noch zu den d&uuml;nnen Plastikt&uuml;ten? 
                        Zugegeben, die wiegen zwar fast nichts, aber vergr&ouml;&#223;ern alle zusammen genommen den 
                        Berg von Plastikm&uuml;ll, denn sie werden im Allgemeinen nur einmal benutzt und 
                        dann in den Abfall geworfen. Hier k&ouml;nnen Sie ganz einfach beginnen:
                        Kaufen Sie im Fach- oder Versandhandel Stoffbeutelchen, die Sie 
                        mehrfach immer wieder benutzen k&ouml;nnen. Genausogut aber k&ouml;nnen Sie diese 
                        etwa 28x35cm gro&#223;en Beutel mit ein wenig Geschick aus weichem Gaze- oder 
                        Netzstoff auch selbst n&auml;hen (die Anleitung finden Sie im <a href="http://www.dorispaas.de/index.php?page=blog#blog-2018-08-14" target="_blank">Blog</a>).
                        Beim Wiegen der Fr&uuml;chte sammle ich die Preisschildchen, die leider auf dem Stoff nicht kleben bleiben, 
                        immer am Rand meiner praktischen Einkaufswagentasche und gebe sie dann beim Bezahlen einen nach dem anderen 
                        der Kassiererin zum Einscannen. Die meisten sind interessiert, wo man solche m&uuml;llsparenden Beutel 
                        kaufen kann, und h&auml;ufig entwickelt sich ein nettes Gespr&auml;ch &ndash; entweder 
                        mit den Kassiererinnen oder aber mit den anderen Kunden.
                        <br />
                        <br />
                        <hr>
                        <br />
                        Liebe Leserinnen und Leser, 
                        Sie fragen sich, was S&uuml;&#223;ungsmittel mit den Stoffbeuteln f&uuml;r Gem&uuml;se 
                        und Obst zu tun haben? Auf den ersten Blick zugegebenerma&#223;en wenig. Wenn Sie 
                        jedoch bedenken, dass ein intensiveres Reflektieren &uuml;ber den eigenen Zuckerkonsum 
                        und dar&uuml;ber hinaus auch &uuml;ber ein ges&uuml;nderes Essverhalten insgesamt mit 
                        gro&#223;er Wahrscheinlichkeit auch ein ge&auml;ndertes Einkaufsverhalten 
                        nach sich zieht, dann ist der Zusammenhang schnell klarer. Mehr Mahlzeiten selber 
                        zuzubereiten und dabei gr&ouml;&#223;eres Gewicht auf die Verarbeitung von frischem 
                        Obst und Gem&uuml;se zu legen, f&ouml;rdert nicht nur die Gesundheit, sondern kann 
                        auch richtig Spa&#223; machen. Und wenn Sie dabei mit den Stoffbeutelchen auch noch 
                        etwas Gutes f&uuml;r die Umwelt tun, gibt es mit Sicherheit nur Gewinner.
                        <br />
