                        <h5>Ausgabe 78 (Herbst 2026)</h5>
                        <hr />
                        <br />
                        
                        
                        Liebe Leserin, lieber Leser,
                        <br />
                        <br />
                        der hei&#223;este Sommer seit Beginn der Wetteraufzeichnungen geht zu Ende. M&ouml;gen rechte Parteien auch 
                        hartn&auml;ckig den Klimawandel verleugnen, ist es doch wissenschaftlicher Konsens, dass diese drastischen Temperaturanstiege menschengemacht sind. 
                        Ja, zugegeben, es hat immer nat&uuml;rliche Temperaturschwankungen gegeben, aber die hielten sich in moderaten Grenzen. Die jetzt exponentiell ansteigenden 
                        Temperaturkurven sehen vollkommen anders aus und sollten eigentlich auch den Ignorantesten &uuml;berzeugen. Die nun auch in unsere Gegenden 
                        vordringenden katastrophalen Waldbr&auml;nde haben Tausende von Hilfskr&auml;ften an den Rand ihrer Kapazit&auml;ten gebracht, und die extreme 
                        Wasserknappheit in unseren Fl&uuml;ssen versetzt unserer Wirtschaft einen weiteren Dolchsto&#223; &ndash; ganz zu schweigen von den gesch&auml;tzt mindestens 
                        15.800 Menschen, die aufgrund der Hitze allein in diesem Jahr verstorben sind.
                        <br />
                        <br />
                        Das sind schlechte Nachrichten!
                        <br />
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-rhythmus" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2026-03-titel.png" alt="Bild Rhythmus" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <a href="http://www.dorispaas.de/index.php?page=ganz-rhythmus" target="_blank"><b>In diesem Newsletter hei&#223;t das Schwerpunktthema &#187;Rhythmus&#171;</a>.</b>
                        <b></b>
                        <br />
                        <i>Sie finden diesen Beitrag unter dem Men&uuml;punkt &#187;Wissensdatenbank/Ganzheitliche Gesundheit/Entspannung/Rhythmus&#171;</i>
                        <br />
                        <br />
                        Jetzt ist jeder gefordert, mit seinem ganz pers&ouml;nlichen Zutun alles dazu beizutragen, was m&ouml;glich ist, um weiteres Unheil so klein 
                        wie m&ouml;glich zu halten. Jeder muss dabei selbst entscheiden, was ihm m&ouml;glich ist. Und auch wenn es einem selbst so erscheint, als sei 
                        das eigene Puzzleteilchen nur ganz winzig und unbedeutend, summieren sich viele kleine Puzzleteilchen doch zu einem gr&ouml;&#223;eren Ganzen. 
                        Gar nichts zu tun, ist einfach keine Option mehr!  
                        <br />
                        <br />
                        Ganz wichtig bei allen Bem&uuml;hungen ist aber auch, auf sich zu achten und zu versuchen, in diesen Zeiten nicht unter die R&auml;der zu 
                        kommen. Hier setzt der Gedanke eines Lebens im Einklang mit &auml;u&#223;eren und individuellen Rhythmen an. Wir sind eingebettet in einen 
                        nat&uuml;rlichen Rhythmus von Jahreszeiten mit K&auml;lte und W&auml;rme und in einen Rhythmus von Tageszeiten mit Licht und Dunkelheit. 
                        Auch unser K&ouml;rper befindet sich im Rhythmus &ndash; in einem Rhythmus von Einatmen und Ausatmen, von Wachsein und Schlaf, in einem 
                        Rhythmus von Bewegung und Ruhe, von Anspannung und Entspannung. Kein Moment des Lebens findet in einem Zustand statt, ohne dass er in 
                        einem anderen Augenblick wie auf einer Schaukel in die Gegenrichtung schwingt. Mit unseren Verhaltensweisen k&ouml;nnen wir entscheidend 
                        dazu beitragen, unser Leben in einem ausgewogenen Gleichgewicht halten, um auch in diesen anstrengen Zeiten 
                        gut zu leben. 
                        <br />
                        <br />
                        Und das sind gute Nachrichten!
                        <br />
                        <br />
                        In diesem Sinne w&uuml;nsche ich Ihnen die ersehnte herbstliche Abk&uuml;hlung und eine gute Zeit in Ihrem ganz pers&ouml;nlichen Rhythmus.
                        Und uns allen und unserem Land w&uuml;nsche ich bei den anstehenden Wahlen auch in Sachen &#187;Klimaschutz&#171; einen guten Ausgang. F&uuml;r eine kluge 
                        Entscheidung gibt es keine &#187;Alternative&#171;, die den Klimawandel verleugnet! Statt von Hetzern und Chaoten zerst&ouml;rt zu werden, 
                        m&uuml;ssen unsere Regierungen in den L&auml;ndern und dadurch auch im Bund gest&auml;rkt werden, um endlich vern&uuml;nftigere Beschl&uuml;sse 
                        (auch) in Sachen Klimapolitik treffen zu k&ouml;nnen. Dieses pers&ouml;nliche Puzzleteilchen, mit dem Sie die Wahl zwischen Chaos und Vernunft 
                        haben, ist &uuml;brigens gar nicht so klein und unbedeutend, wie Sie vielleicht denken &ndash; es kann so viel bewegen!
                        <br />
                        <br />
                        Den n&auml;chsten Newsletter erhalten Sie dann, wenn Sie m&ouml;chten, zum kommenden Winter.
                        <br />
                        <br />
                        Ganz herzliche Gr&uuml;&#223;e
                        <br />
                        Ihre
