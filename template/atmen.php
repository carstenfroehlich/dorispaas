                        <hr />
                        <h5>Darmgymnastik</h5>
                        <hr />

                            <a href="book-darmgymnastik" target="_blank">
                                <img src="<?php echo IMG_PATH; ?>book-darmgymnastik-middle.png" alt="Darmgymnastik" class="inline" /></a>
                        Bei der Behandung und zur Vorbeugung unangenehmer Symptome einer jeden Nahrungsmittel-Unverträglichkeit, bakteriellen Fehlbesiedelungen der 
                        verschiedenen Darmabschnitte oder allen anderen Verdauungsproblemen ist <b>grundsätzlich die kontinuierliche 
                        Bewegung eine unverzichtbare Komponente</b>. Es ist wichtig, dass der <b>Transport des Speisebreis durch den 
                        Darm so gleichmäßig wie möglich</b> abläuft. Dies wird am besten erreicht mit einer kontinuierlichen Anregung der Verdauungsdrüsen und des Darms. 
                        Dazu eignen sich weniger die wenigen sportlichen Aktivitäten am Abend oder am Wochenende, sondern in möglichst engmaschigen zeitlichen 
                        Abständen durchgeführte <b>Atem- und Bewegungsübungen</b>. 
                        <br />
                        <br />
                        In dem Buch <a href="book-darmgymnastik" target="_blank">&#187;Darmgymnastik &#38; mehr 
                        gegen Verdauungsbeschwerden&#171;</a> finden Sie viele Anregungen dazu. Zusätzlich sind Akupressurpunkte aufgeführt, deren Stimulation bei allen 
                        Verdauungsbeschwerden wirksam sind. Weiterhin werden zusätzliche Hilfsmaßnahmen und Hilfsmittel vorgestellt, die die Behandlung von 
                        Verdauungsproblemen effektiv unterstützen können. Und last, but not least, gibt es ein Kapitel mit Fragen, die in meiner Praxis immer wieder 
                        zu diesem Themenkomplex gestellt werden.                  
