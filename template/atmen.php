                        Atmen &ndash; das geht doch ganz automatisch, denken wir. Im Prinzip ist das richtig: solange wir leben, atmen 
                        wir &ndash; und das meist, ohne dass wir uns Gedanken darüber machen müssen. Wir atmen bei Tag und auch während 
                        der Nacht, wenn wir schlafen.
                        <br />
                        <br />
                        Die Atemfrequenz beträgt beim Erwachsenen im Mittel etwa 15 Atemzüge pro Minute. Dies bedeutet, dass wir pro 
                        Tag über 20.000 Mal ein- und ausatmen. Wenn wir uns anstrengen, geht der Atem schneller, wenn wir ruhen oder 
                        schlafen, verlangsamt sich die Frequenz. Sobald durch Anstrengung mehr Sauerstoff vom Organismus, also unseren 
                        Muskeln und unserem Gehirn, benötigt wird, reagiert unserer Atemsystem mit schnellerem Atmen. Ist bei Ruhe und 
                        Entspannung weniger Sauerstoff erforderlich, atmen wir langsamer.
                        <br />
                        <br />
                        <a id="funktion"></a>
                        <hr>
                        <h5>Wie funktioniert der Atem?</h5>
                        <hr>
                        Zum Atmen wird nicht nur die Lunge benutzt. Viele Muskeln, insbesondere der große Zwerchfellmuskel unter der Lunge, 
                        aber auch die vielen kleineren Rippenmuskeln ziehen die Lunge auf, die ja eigentlich nur ein schlaffer &#187;Sack&#171; 
                        und eben kein Muskel ist. Dabei füllt sie sich mit der Umgebungsluft. Entspannt sich die Atemmuskulatur, schrumpft 
                        auch die Lunge wieder zusammen, so dass der Atem entweicht.
                        <br />
                        <br />
                        Beim Atmen wird über die Lungenbläschen Sauerstoff aus der Atemluft aufgenommen und ins Blut übergeführt. Im Gegenzug 
                        wird Kohlendioxid aus dem Blut aufgenommen und beim Ausatmen in die Umgebung abgegeben. Gleichzeitig werden auch andere 
                        Gase wie z.B. Wasserstoff oder Methan, die von unseren Darmbakterien produziert werden, abgeatmet (siehe hierzu auch 
                        den Beitrag &#187;<a href="atemtest" target="_blank">Grundlagen zu Atemtests</a>&#171;). Weitere Abfallprodukte werden 
                        ebenfalls über die Lunge entsorgt, denn sie ist wie die Leber, die Nieren oder die Haut eines unserer großen Entgiftungsorgane.
                        <br />
                        <br />
                        Normalerweise schwingt die Ein- und Ausatmung ganz automatisch in einem harmonischen Rhythmus (lesen Sie hierzu gerne den Beitrag 
                        &#187;<a href="ganz-rhythmus" target="_blank">Rhythmus</a>&#171;). Zusätzlich zu der automatischen 
                        Atmung können wir unseren Atem auch ganz bewusst steuern. Wir können flacher atmen oder die 
                        Luft anhalten &ndash; zumindest so lange, bis unser Körper akuten Sauerstoffmangel signalisiert und wir automatisch wieder Atem 
                        schöpfen müssen. Wir können aber auch bewusst schneller oder auch tiefer atmen. Dies kann sogar zu einer sogenannten 
                        Hyperventilation führen, weil dann die Balance zwischen Sauerstoffaufnahme und Kohlendioxidabgabe kippt. Wir merken 
                        dies zum Beispiel, wenn wir ein Kinderschwimmbecken aufpusten: es kann uns schwindelig werden, und wir müssen eine 
                        Weile pausieren, bis sich das Sauerstoff- und Kohlendioxidgleichgewicht wieder eingependelt hat. Aber auch Stress oder 
                        Angst kann zu Hyperventilation führen, weil wir dann zu hektisch ein- und nicht ordentlich ausatmen. 
                        <br />
                        <br />
                        <a id="vorfahren"></a>
                        <hr>
                        <h5>Atem &ndash; früher und heute</h5>
                        <hr>
                        Wenn wir einmal überlegen, wir unsere Vorfahren lebten, können wir feststellen, dass diese sich einen großen Teil des Tages bewegten. 
                        Sie streiften durch ihre Umgebung und liefen weite Strecken. Sie bückten sich, um Wurzeln auszugraben, rannten (oft erfolglos) 
                        einem Beutetier hinterher, um es zu erlegen oder kletterten auf Bäume, um Vogeleier aus den Nestern zu holen. Das Leben war 
                        anstrengend, die Atmung deswegen gut und trainiert. 
                        <br />
                        <br />
                        Unser heutiges Leben spielt sich zum großen Teil auf dem (Büro-)Stuhl oder dem Sofa ab, und auch die Autofahrt in den Supermarkt 
                        ist nicht wirklich anstrengend, so dass sich unsere Atemfrequenz kaum einmal erhöht.
                        <br />
                        <br />
                        <a id="atemundverdauung"></a>
                        <hr>
                        <h5>Atem und Verdauung</h5>
                        <hr>
                        Dies hat weitreichende Folgen &ndash; vor allem für unser Verdauungssystem. Denn der Atem spielt bei unserer Verdauung eine 
                        entscheidende Rolle. Schauen Sie sich doch bitte einmal unser Verdauungssystem an: 
                        <a href="ganz-verdauungssystem" target="_blank">hier finden Sie eine Abbildung</a>. Sie sehen 
                        dort, dass der große Zwerchfellmuskel (in der Abbildung mit der Nummer 3 gekennzeichnet) den Raum unter der Lunge (14) und 
                        über Leber (4) und Gallenblase (5), Bauchspeicheldrüse (6), Magen (7), Dünndarm (9) und Dickdarm (10) begrenzt. Sämtliche 
                        Organe im Bauch sind dicht gepackt &ndash; kein bisschen Freiraum ist dazwischen. Wenn wir einatmen, bewegt sich das 
                        Zwerchfell nach unten und drückt auf unsere Verdauungsorgane. Beim Ausatmen wird der Druck zurückgenommen &ndash; Magen, 
                        Verdauungsdrüsen und Darm werden also mit der Ein- und Ausatmung richtig durchgeknetet. Und das ist gut so! Wie alle diese 
                        Organe, ist insbesondere aber unser Dickdarm faul und benötigt u.a. Anregung von außen, um zu funktionieren und den Stuhl 
                        in Richtung Ausgang zu bewegen.
                        <br />
                        <br />
                        Es ist also einsehbar, dass eine tiefe und sorgfältige Atmung die Darmtätigkeit im besten Sinne anregen kann, damit unsere 
                        Verdauung optimal funktioniert.
                        <br />
                        <br />
                        <a id="probleme"></a>
                        <hr>
                        <h5>Atem und Verdauungsprobleme</h5>
                        <hr>
                        Sämtliche Probleme &ndash; seien es Blähungen, Verstopfung oder auch Durchfall, aber auch Schmerzen können mit einer bewussten Atmung 
                        günstig beeinflusst werden. Lesen Sie hierzu auch gerne den Beitrag &#187;<a href="krisenverdauung" target="_blank">Krisen und ihre Auswirkungen auf die Verdauung</a>&#171;.
                        <br />
                        <br />
                        Es ist gut, wenn die Darmmuskulatur gut durchblutet wird, weil wir durch tiefes Atmen ausreichend 
                        Sauerstoff aufnehmen. Allein aber auch die mechanische Anregung vom Zwerchfell und der Bauchdecke führt zu einer besseren Tätigkeit 
                        der Darmmuskulatur (Peristaltik), wodurch der Darminhalt kontinuierlicher weitertransportiert wird. Läge der Darminhalt durch eine 
                        gebremste Peristaltik länger in den einzelnen Darmabschnitten &ndash; insbesondere im Dickdarm, hätten die Darmbakterien sehr viel 
                        mehr Zeit, sich über die Nährstoffreste herzumachen und dabei auch mehr Abfallstoffe in Form von Gasen und Säuren zu produzieren. 
                        Diese machen dann Probleme in Form von Blähungen und Bauchschmerzen. Aber auch die restliche, im Speisebrei befindliche Flüssigkeit 
                        kann vermehrt wieder über die Dickdarmschleimhaut aufgenommen und resorbiert werden. Der Stuhl dickt über Gebühr ein, und wir haben 
                        Verstopfung. Ein Teufelskreis setzt ein, denn festerer Stuhl kann vom Darm nur schwer weitertransportiert werden, die Darmbakterien 
                        haben länger Zeit &ndash; usw., usw.
                        <br />
                        <br />
                        Insgesamt verändert sich auch die Gesundheit unserer Darmschleimhaut zum Negativen, denn deren Qualität und Funktionsfähigkeit 
                        wird ja auch maßgeblich mitbestimmt von der Zusammensetzung unserer Darmflora (Mikrobiota). Dies kann u.a. auch zur Folge haben, 
                        dass durch mangelhaft versorgte Zellen die Darmschleimhaut undicht und durchlässig wird (Leaky Gut &ndash; siehe auch 
                        &#187;<a href="darmfloragrundsatz" target="_blank">Grundsätzliches über die Darmflora</a>&#171;) oder aber auch weniger 
                        Verdauungsenzyme im Dünndarm gebildet werden, wodurch die Wahrscheinlichkeit bzw. die Ausprägung von Nahrungsmittel-Unverträglichkeiten 
                        steigen. Auch das sogenannte Reizdarm-Syndrom kann hiermit in Zusammenhang gebracht werden (siehe auch 
                        &#187;<a href="rds-wasistdas" target="_blank">Reizdarm-Syndrom &ndash; was ist das?</a>&#171;). Lesen Sie hierzu bitte auch den 
                        Beitrag &#187;<a href="darmgesundheit" target="_blank">Darmpflege</a>&#171; und alle anderen Beiträge zum Thema 
                        &#187;Darmgesundheit&#171; unter dem Menüpunkt &#187;<a href="wissensdatenbank" target="_blank">Wissensdatenbank</a>&#171;.
                        <br />
                        <br />
                        Auch Sodbrennen oder sogar ein Reflux &ndash; also das Zurückfließen der beißenden Magensäure in die Speiseröhre &ndash; können durch 
                        eine mangelhafte Verdauung gefördert werden. Wenn der Darm durch Gase aufgebläht ist und deshalb von unten gegen den Magen drückt, 
                        kann die Säure aufsteigen und diese Probleme begünstigen. Im Beitrag &#187;<a href="reflux" target="_blank">Sodbrennen und Reflux</a>&#171; 
                        können Sie mehr über diese belastende und schmerzhafte Erkrankung lesen.
                        <br />
                        <br />
                        <a id="gesunderatem"></a>
                        <hr>
                        <h5>Gesunder Atem &ndash; gesunde Verdauung</h5>
                        <hr>
                        Da wir unseren Atem bewusst beeinflussen können, haben wir mit Atemübungen auch ein wunderbares Mittel an der Hand, unsere Verdauung 
                        beeinflussen zu können.
                        <br />
                        <br />
                        Jede Frau, die bereits ein Kind geboren hat, kennt die Atemtechniken von Grantly Dick-Read oder Ferdinand Lamaze. Mit beiden Techniken, 
                        die sich zwar etwas unterscheiden aber im Grunde dasselbe bewirken, kann man Schmerzen bei den Geburtswehen sehr günstig beeinflussen.
                        <br />
                        <br />
                        Auch Bauchschmerzen, Blähungen und alle ihre Folgen durch eine gestörte Verdauungstätigkeit kann man mit geeigneten Atemtechniken 
                        &#187;weg atmen&#171; bzw. wesentlich mildern.
                        <br />
                        <br />
                        Dabei ist es Ihnen überlassen, ob Sie (wie Dick-Read es empfiehlt) kontinuierlich tief in den Bauch und zu den Blähungen und Schmerzen 
                        hin atmen, oder ob Sie (wie Lamaze es vorschlägt) die Tiefe des Atems der Intensität der Beschwerden anpassen. Alles, was Sie als 
                        angenehm und wohltuend empfinden, nützt dem Erfolg. Wenn Sie sich und Ihre Verdauung mit den Übungen hingegen überfordern, 
                        erweisen Sie sich einen Bärendienst.
                        <br />
                        <br />
                        <a id="atemuebungen"></a>
                        <hr>
                        <h5>Atemübungen</h5>
                        <hr>
                        Die Atemübungen zur Optimierung Ihrer Verdauung bzw. zur Behebung von Störungen sind ganz einfach und kein Hexenwerk.
                        <br />
                        <br />
                        Leider hat zumindest meine Generation noch den Grundsatz &#187;Bauch rein, Brust raus&#171; verinnerlichen müssen. Dies ist falsch! 
                        Auf diese Weise würden wir erstens nur mit den Rippenmuskeln nach oben und zweitens viel zu flach atmen und womöglich noch die Schultern 
                        hochziehen. Und zu guter Letzt wären wir vollkommen verspannt, was die Verdauung ebenfalls ungünstig beeinflusst. Für den Darm bedeutet 
                        dies, dass er von der Atmung kaum etwas mitbekommt und die anregende Wirkung ausbleibt.
                        <br />
                        <br />
                        Richtig ist es, hauptsächlich mit dem Zwerchfell tief in den Bauch zu atmen und die Rippenmuskulatur dabei mitzubenutzen. Die 
                        Schultern bleiben unten. So wird sanfter Druck auf das gesamte Verdauungssystem mit all seinen Organen wie Magen, Darm und alle 
                        Verdauungsdrüsen ausgeübt, so dass sich die Verdauungstätigkeit optimieren und Beschwerden verschwinden können.
                        <br />
                        <br />
                        Richtiges Atmen will &ndash; wenn man es nicht beherrscht, gelernt sein. Beobachten Sie sich zunächst, wie Sie atmen. Legen Sie die 
                        Hände auf den Bauch und schauen Sie, ob sich beim Einatmen die Bauchdecke nach außen bewegt. Dies soll nicht durch eine aktive 
                        Tätigkeit der Bauchmuskulatur geschehen &ndash; also aktives Herein- und Hinausbewegen, sondern passiv durch den Druck von innen. 
                        Achten Sie darauf, dass die Schultern locker hängen bleiben und nicht in Richtung Ohren gezogen werden.
                        <br />
                        <br />
                        Das Einatmen gehört genauso zu einer optimalen Atmung wie das Ausatmen. Eine gute Übung ist es, kräftig durch die Nase einzuatmen, 
                        während sich die Bauchdecke deutlich wölbt und langsam wieder auszuatmen. Letzteres ist zunächst gar nicht so einfach. Spitzen Sie 
                        die Lippen, als wenn Sie pfeifen wollten und atmen Sie nun gegen diese &#187;Lippenbremse&#171; aus. Dadurch verlängert sich 
                        automatisch die Ausatemzeit, zusätzlich wird wesentlich effektiver ausgeatmet und die Lunge besser geleert. Der Rhythmus sollte 
                        bei Ausatmen etwa zwei- bis dreimal so lange dauern, wie bei Einatmen. Eine kurze Pause zwischen Ein- und Ausatmen ergibt sich 
                        nach einiger Übungszeit meist von selbst.
                        <br />
                        <br />
                        Diese Basisübung können Sie mehrmals täglich bewusst durchführen. Sie wird Ihnen dann nach einigen Wochen in Fleisch und Blut 
                        übergehen und so die richtige Atmung zur Gewohnheit werden. 
                        <br />
                        <br />
                        Es gibt zahlreiche weitere Übungen, die helfen, die Verdauung zu optimieren &ndash; insbesondere in Stress-Situationen. Lesen Sie hierzu 
                        gerne auch den Beitrag &#187;<a href="coronaverdauung" target="_blank">Verdauung in der Corona-Krise</a>&#171;, in dem einige Atemübungen 
                        und eine Dehnungsübung mit Zeichnungen erklärt sind. Diese eignen sich nicht nur in der Corona-Krise, sondern helfen generell, bei Ängsten 
                        und Stress die Verdauung zu optimieren.
                        <br />
                        <br />
                        Bei Verdauungsbeschwerden führen Sie diese Atemübung gezielt durch &ndash; Sie werden die wohltuende Wirkung mit Sicherheit rasch verspüren.
                        Eine gute Ergänzung kann es sein, die Übungen mit dem Pressen oder Klopfen von geeigneten Akupressurpunkten zu ergänzen und zu unterstützen.
                        Bitte lesen Sie hierzu den Beitrag &#187;<a href="akupressur" target="_blank">Akupressur zur Beeinflussung von Magen-/Darmproblemen</a>&#171;.
                        <br />
                        <br />
                        Ggf. empfehle ich Ihnen, weitere Übungen zusammen mit einer Atemtherapeutin zu erlernen oder sich von einer Ernährungs- und 
                        Gesundheitsfachkraft beraten und anleiten zu lassen.
                        <br />
                        <br />
                        <a id="weiteres"></a>
                        <hr>
                        <h5>Weitere Möglichkeiten</h5>
                        <hr>
                        Es gibt neben den Atemübungen viele weitere Möglichkeiten, den Atem und damit die Verdauung zu optimieren &ndash; und dabei noch richtig 
                        Spaß zu haben.
                        <br />
                        <br />
                        Beim Sport zum Beispiel atmen Sie ganz automatisch richtig. Es ist also vorteilhaft, sich so oft wie möglich am besten an der frischen 
                        Luft aktiv zu bewegen. Eine sehr gute Art &ndash; auch für den Ungeübten &ndash; ist das Nordic Walking. Hierbei werden neben den zum 
                        Laufen benötigten Beinmuskeln auch die Arme und alle Muskeln des Oberkörpers mitbenutzt. Dies fördert zusätzlich die tiefe und richtige 
                        Atmung, so dass sich dies besonders gut auf die Verdauungstätigkeit auswirken kann.
                        <br />
                        <br />
                        Was zunächst kaum jemand weiß, ist, dass auch das Singen perfekt zum besseren Atmen(lernen) ist. Sie atmen dabei nicht nur tiefer ein, 
                        sondern beim Halten der Töne auch länger und kontrollierter aus. Und den Spaß gibt es hier garantiert dazu, wenn Sie sich einen Chor 
                        aussuchen, der Ihrem Können und Anspruch angemessen ist. (Nicht nur) zur Not bringt es auch das Singen in der Badewanne oder unter der 
                        Dusche. 
