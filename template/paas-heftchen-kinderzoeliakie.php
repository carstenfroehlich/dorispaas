                    <h5>Buchbeschreibung</h5>
                    <hr />
                    Zöliakie! Der Arzt hat bei Ihrem Kind die Diagnose Zöliakie genannt? Oder Sie 
                    vermuten, dass es Probleme mit Gluten hat? Dann tauchen jetzt viele Fragen auf:
                    <br />
                    <br />
                    Was ist eigentlich Gluten, und was ist eine Zöliakie? Ist sie heilbar, und gibt 
                    es Medikamente? Was darf mein Kind essen, wobei muss es aufpassen? Was passiert, 
                    wenn es ab und an Gluten erwischt? Welche Maßnahmen müssen zusätzlich ergriffen 
                    werden? Was kann ich tun, damit es meinem Kind wieder gut geht? Wie nehme ich 
                    Großeltern und Freunde, Lehrer und Erzieherinnen mit ins Boot?  Auf alle Fragen 
                    gibt Ihnen dieses Buch erste Antworten.
                    <br />
                    <br />
                    Die Paas‘schen Heftchen behandeln Themen aus dem Gesundheits-bereich. Sie erläutern 
                    jeweils in kurzer und klarer Form die Ursachen und Hintergründe von Beschwerden. 
                    Sie helfen, Probleme zu erkennen und zu verstehen und zeigen erste Schritte in 
                    die richtige Richtung: eine gesunde Lebensweise ohne Beschwerden, um sich wohl 
                    zu fühlen. 
                    <br />
                    <br />
                    Kurz und klar &ndash; der Name ist Programm: Die Heftchen erheben bewusst keinen Anspruch 
                    auf Ausführlichkeit, sondern verschaffen Ihnen in kurzer, aber korrekter Form 
                    einen ersten Überblick über einen Sachverhalt. Trotz des geringen Umfangs sind 
                    sie jedoch nicht oberflächlich und immer sorgfältig recherchiert: In rund einer 
                    Stunde wissen Sie alles Wesentliche zum Thema. 
