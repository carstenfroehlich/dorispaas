                        Liebe Leserin, lieber Leser.
                        <br />
                        Wieder neigt sich ein Jahr dem Ende zu &ndash; und leider war es ein in (zu) vieler Hinsicht nicht gutes Jahr. Die politischen Z&auml;nkereien verhinderten 
                        es &uuml;ber lange Strecken, dass echte Fortschritte f&uuml;r eine gute Zukunft erarbeitet wurden, und sie gipfelten dann letztendlich darin, dass unsere 
                        Regierung nun noch handlungsunf&auml;higer wurde. Auch die Wahlergebnisse f&uuml;r die Pr&auml;sidentschaft und die Kongress- und Senatsh&auml;user in den 
                        USA lassen Schlimmstes bef&uuml;rchten. Und als ob das alles nicht genug w&auml;re, konnte sich die diesj&auml;hrige Klimakonferenz zwar auf einen 
                        symbolischen Kompromiss einigen, aber sie machte im Vergleich zu den vorherigen Konferenzen mit diesem &#187;Ergebnis&#171; 
                        sogar noch R&uuml;ckschritte. Dass nun auch noch Putins Krieg in der Ukraine zu eskalieren droht, ist ebenfalls ein sehr 
                        beunruhigender Zustand. Und leider ist dieser Krieg ja beileibe kein Einzelfall &ndash; Kriege und Aggressionen gibt es &uuml;berall und zunehmend auf 
                        der ganzen Welt. Ungl&uuml;cklicherweise machen diese zahlreichen Krisen nur wenig Hoffnung auf einen friedlichen Jahresausklang &ndash; und das bedeutet 
                        f&uuml;r uns alle Stress pur.
