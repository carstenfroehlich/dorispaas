                        das Essen problematisch, weil (zu) viele Lebensmittel nicht vertragen werden. Diese alle wegzulassen und immer eingeschr&auml;nkter zu essen, macht 
                        keinen Spaß &ndash; schon gar nicht in der Winter- und Feierzeit, in denen man es sich am gedeckten Tisch gem&uuml;tlich machen will. Auch Gew&uuml;rzen 
