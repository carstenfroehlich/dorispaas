                        <a href="http://www.dorispaas.de/index.php?page=paas-heftchen-fu" target="_blank"><img src="http://www.dorispaas.de/images/nl-2017-05-fma.png" alt="" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=paas-heftchen-fu" target="_blank">Kurz und klar: Fruchtzucker-Unvertr&auml;glichkeit &ndash; neue, &uuml;berarbeitete Auflage</a></b>
                        <br />
                        Eine der verschiedenen Nahrungsmittel-Unvertr&auml;glichkeiten, die mit einem 
                        Atemtest diagnostiziert werden k&ouml;nnen, ist die 
                        <a href="http://www.dorispaas.de/index.php?page=wasistfma" target="_blank">Fruktose-Malabsorption</a>. 
                        Diese Unvertr&auml;glichkeit des Fruchtzuckers kann &ndash; wie alle anderen 
                        Nahrungsmittel-Intoleranzen auch &ndash; sehr unangenehme Beschwerden wie 
                        z.B. Bl&auml;hungen, Bauchschmerzen, Durchfall oder Verstopfung, aber auch 
                        M&uuml;digkeit, Kopfschmerzen oder sogar Depressionen nach sich ziehen. 
                        Fruchtzucker ist zwar ein Einfachzucker, der nicht mehr in verschiedene, kleinere 
                        Bausteine aufgespalten werden muss, er ben&ouml;tigt jedoch ein Transportprotein, 
                        um zwischen den Zellen der D&uuml;nndarmschleimhaut hindurch ins Blut geschleust 
                        zu werden. Dieses Transportprotein tr&auml;gt den Namen GLUT5. Steht nur eine 
                        GLUT5-Menge zur Verf&uuml;gung, die der verzehrten Fruchtzuckermenge nicht angepasst ist,  
                        gelangt nicht verarbeiteter Fruchtzucker in den Dickdarm, wo er von den Bakterien 
                        der Darmflora verstoffwechselt wird. Dies f&uuml;hrt zu den beschriebenen Beschwerden. 
                        Es wichtig, alle Zusammenh&auml;nge und Hintergr&uuml;nde rund um die 
                        Fruchtzucker-Unvertr&auml;glichkeit zu verstehen, um dann mit geeigneten Ma&#223;nahmen 
                        zu erreichen, sich trotz dieses Problems wieder so richtig wohl f&uuml;hlen zu 
                        k&ouml;nnen. 
                        <br />
                        <br />
                        In dem B&uuml;chlein &#187;<a href="http://www.dorispaas.de/index.php?page=paas-heftchen-fu" target="_blank">Kurz 
                        und klar: Fruchzucker-Unvertr&auml;glichkeit</a>&#171; (ISBN 978-3-7448-4099-6)  
                        aus der Paas&#039;schen Heftchenreihe lesen Sie in rund einer Stunde das Wichtigste zu diesem Thema.
