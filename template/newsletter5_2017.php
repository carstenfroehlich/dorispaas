                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=atemtest" target="_blank">Atemgastests</a></b>
                        <br />
                        Was ist ein Atemgastest? Wie funktioniert er und wie wird er durchgef&uuml;hrt? 
                        Bei welchen Erkrankungen kann ein solcher Test eingesetzt werden und wie belastbar 
                        ist eine Diagnose? Wie werden die Werte interpretiert und welche Fehler sollte man 
                        vermeiden? Die meisten Menschen stellen sich bzw. ihrem Arzt diese und viele weitere 
                        Fragen, die der Beitrag versucht zu beantworten.
                        <br />
                        <br />
                        Ein Atemtest kann in spezialisierten Hausarztpraxen, bei einem Gastroenterologen 
                        oder auch als ambulante Untersuchung in einem Krankenhaus durchgef&uuml;hrt werden. 
                        Es gibt aber auch Sets f&uuml;r einen Heimtest, den Sie sich bei bestimmten Laboren 
                        bestellen und dann zu Hause machen k&ouml;nnen. 
                        In Arztpraxen und Krankenh&auml;usern werden meist Messeger&auml;te benutzt, 
                        in die man pustet und an denen man sofort an einer Anzeige den entsprechenden Wert 
                        ablesen kann.
                        F&uuml;r den Heimtests bekommen Sie mehrere R&ouml;hrchen und ein Mundst&uuml;ck 
                        zugeschickt. W&auml;hrend des Tests wird in bestimmten Zeitintervallen jeweils in 
                        ein R&ouml;hrchen gepustet, das ein wenig der Atemluft aufnimmt. Die R&ouml;hrchen 
                        m&uuml;ssen dann an das Labor zur&uuml;ck geschickt werden, wo die enthaltene Luft dann 
                        mithilfe von Messger&auml;ten analysiert werden kann.
                        Beide Testmethoden haben Vor- und Nachteile, und es ist wichtig, gut dar&uuml;ber 
                        Bescheid zu wissen, bevor Sie sich f&uuml;r die eine oder andere Methode entscheiden.
                        <br />
                        <br />
                        Vor allem aber werden sowohl bei den Heimtests als auch leider viel zu oft bei den 
                        Tests in der Arztpraxis viel zu h&auml;ufig Fehler gemacht, so dass die Ergebnisse 
                        dann nur eine beschr&auml;nkt belastbare oder sogar g&auml;nzlich unbrauchbare Diagnose 
                        ergeben. Oder aber es werden durch eine unzureichende Durchf&uuml;hrung nicht 
                        alle diagnostischen M&ouml;glichkeiten ausgesch&ouml;pft, so dass u.U. belastende 
                        Folgeuntersuchungen erforderlich werden.
                        <br />
                        <br />
                        Der Beitrag &#187;<a href="http://www.dorispaas.de/index.php?page=atemtest" target="_blank">Grundlagen 
                        von Atemtests zur Diagnose von Nahrungsmittel-Unvertr&auml;glichkeiten und 
                        D&uuml;nndarmfehlbesiedelung</a>&#171; erkl&auml;rt ausf&uuml;hrlich s&auml;mtliche 
                        relevanten Fakten, damit Sie dann die geeigneten Entscheidungen treffen und damit 
                        Sie auch bei Ihrem Arzt die richtigen Fragen stellen k&ouml;nnen. Sie wissen ja: 
                        die meisten &Auml;rzte haben leider viel zu wenig Zeit. Wenn Sie aber in dieser Sache 
                        als selbstbewusster, kompetenter Gespr&auml;chspartner auftreten, k&ouml;nnen Sie 
                        f&uuml;r Ihre Gesundheit optimale Ergebnisse erzielen.
