                    <h5>Buchbeschreibung</h5>
                    <hr />
                    Die Gesundheit liegt im Darm. Diese Redensart hat durchaus ihre Berechtigung, denn 
                    wenn Sie Verdauungsbeschwerden haben, fühlen Sie sich insgesamt schlecht oder 
                    sogar krank &ndash; und spätestens jetzt ist es  Zeit, etwas für eine gesunde 
                    Verdauung zu tun. Selbst wenn Sie meinen, Sie seien gesund, k&ouml;nnen Sie selbst 
                    sehr viel dafür tun, dass dies so bleibt, indem Sie für eine gesunde 
                    Verdauung sorgen. <br />
                    <br />
                    Das Paas'sche Heftchen &#187;Kurz und klar: Gesunde Verdauung&#171; erklärt in kurzer 
                    und klarer Form alles Wichtige rund um dieses Thema. Es erläutert darüber 
                    hinaus Ursachen und Hintergründe von etwaigen Beschwerden. Das Heftchen hilft, Probleme 
                    zu erkennen und zu verstehen und zeigt erste Schritte in die richtige Richtung: 
                    eine gesunde Lebensweise ohne Beschwerden, um sich wohl zu fühlen und bis 
                    ins hohe Alter gesund zu bleiben.
                    <br />
                    Das Heftchen stellt wesentlich mehr Informationen zur Verfügung als eine 
                    Info-Broschüre und versteht sich somit als Vereinigung von Informations-Broschüre 
                    und Sachbuch. Es erhebt bewusst keinen Anspruch auf Ausführlichkeit, sondern 
                    verschafft Ihnen in kurzer, aber korrekter Form einen ersten &Uuml;berblick über das Thema. 
                    Trotz des geringen Umfangs bleibt es jedoch nicht oberflächlich, sondern ist sorgfältig 
                    recherchiert: In rund einer Stunde wissen Sie alles Wesentliche zum Thema &#187;Gesunde Verdauung&#171;.
