                        <h5>Wer entscheidet über die Zulassung? </h5>
                        <hr />
                        In den Gremien, die über eine Zulassung oder Ablehnung für ein Produkt 
                        entscheiden, sitzen in der Regel natürlich keine Fachleute, die sich wirklich 
                        selbst ein Bild von einer eventuellen Unbedenklichkeit machen können. Somit 
                        sind sie auf Studien und Urteile anderer Behörden oder Personen, aber auch auf 
                        Studien, die die Herstellerfirmen selbst mit ihren Produkten durchführen, angewiesen 
                        &ndash; und genau hier liegt der Hase im Pfeffer! Eine objektive Bewertung 
                        könnte nur von unabhängigen Personen oder Institutionen getroffen werden, 
                        denn jegliche &#187;Forschung&#171; an Mitteln kann nur ernstgenommen werden, wenn 
                        sie nicht in irgendeiner Weise von den Herstellern selbst durchgeführt oder gesponsert 
                        wird. Jeder Hersteller ist natürlich grundsätzlich daran interessiert, sein Produkt 
                        gewinnbringend zu vertreiben, und jede Studie, die etwas anderes als den 
                        uneingeschränkten Nutzen belegen würde, wäre kontraproduktiv. 
                        <br />
                        <br />
                        Hinzu kommt, dass die EU-Kommission ja mit den Entscheidern aus derzeit noch 28 Ländern 
                        besetzt ist, und es hat sich gezeigt, dass hier unglücklicherweise nicht immer 
                        das Wohl und Wehe dieser gro&#223;en Gemeinschaft entscheidend ist, sondern häufig
                        eher nationale Eigeninteressen eine nicht unbeträchtliche Rolle spielen. Und 
                        leider liegt oft auch nicht selten das Hauptaugenmerk auf der Gesundheit der Bürger, 
                        sondern es stehen schlichtweg wirtschaftliche Interessen im Vordergrund. Hat ein 
                        gro&#223;er Hersteller von Produkten seinen Sitz in einem Mitgliedsland, dem durch 
                        die Förderung des Umsatzes auch einen guten Batzen Steuern in die Landeskassen 
                        gespült bekommt, dann wird eben dieses Land den Zulassungsantrag wahrscheinlich
                         gerne unterstützen.
