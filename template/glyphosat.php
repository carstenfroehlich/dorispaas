                        <hr />
                        <h5>Wirkt Glyphosat krebserregend? </h5>
                        <hr />
                        Einige Studien wollen beweisen, dass Gyphosat beim Menschen krebserregend wirkt. 
                        Nun, wir Menschen werden nicht mit Glyphosat besprüht, aber über den 
                        Nahrungskreislauf nehmen wir es alle auf. So werden Glyphosatgehalte z.B. in Trinkwasser, 
                        in Kaffee und Tee oder Bier, in vielen Getreideprodukten und Backwaren wie in Mehl, 
                        Brot oder auch in Tierfutter und deshalb auch in Milch gefunden. Und so gelangt das Herbizid in unser 
                        Verdauungssystem und kann z.B. im Urin nachgewiesen werden &ndash; und dies nicht 
                        nur vereinzelt, sondern bei der überwiegenden Zahl der getesteten Personen.
                        <br />
                        <br />
                        Einige Studien sagen, Glyphosat sei &#187;wahrscheinlich krebserregend&#171;, 
                        andere bestreiten dies und erklären die Unbedenklichkeit dieser Substanz.
                        <br />
                        <br />
                        Wie in einem Beitrag der Zeitschrift &#187;Der Spiegel&#171; (Ausgabe 43 vom 21.10.2017) 
                        zu lesen ist, hat selbst Monsanto nachweislich nachteilige Studienergebnisse verschwiegen 
                        bzw. hat zur Unbedenklichkeit in Bezug auf eine krebserregende Wirkung für Roundup 
                        gar keine Studien durchgeführt.
                        <br />
                        <br />
                        Ich persönlich wei&#223; nicht, ob Glyphosat krebserregend ist. Ich stehe 
                        aber auf dem Standpunkt, dass hier der Grundsatz &#187;Im Zweifel gegen den 
                        Angeklagten&#171; gelten sollte. Solange, wie nicht zweifelsfrei bewiesen ist, 
                        dass Glyphosat nicht krebserregend ist, solange nicht zweifelsfrei bewiesen ist, 
                        dass Glyphosat nicht tier- und umweltgefährdend ist, solange darf es keine 
                        Zulassung geben. Ich erinnere nur an den Skandal um das Mittel Contergan, das 
                        zunächst wegen unzureichender Forschungen und später wegen der monatelangen, 
                        unverantwortlichen Vertuschung der Hersteller, nachdem sie schon von den verheerenden 
                        Folgen zumindest ahnten, zu zahlreichen schweren Missbildungen von Babys führte!
                        <br />
                        <br />
                        Im Amerika jedoch gibt es bereits eine größere Anzahl Menschen, die an einer 
                        bestimmten Form von Lymphdrüsenkrebs, dem Non-Hodgkin-Lymphom, erkrankt sind und 
                        diese Erkrankung mit der Kontamination mit Glyphosat in Verbindung bringen. 
                        U.a. auch, weil die Internationale Agentur für Krebsforschung (IARC), die unter 
                        dem Dach der Weltgesundheitsorganisation arbeitet, Glyphosat als &#187;wahrscheinlich 
                        krebserregend für den Menschen&#171; einstufte, gibt es bereits erste Sammelklagen 
                        gegen den Konzern. 
                        <br />
                        <br />
                        Jedoch gerade bei Unkrautvernichtungsmitteln 
                        ist es sicherlich besonders schwer, einen direkten Zusammenhang beweisen zu können, 
                        da die erkrankten Menschen ja immer auch mit anderen Stoffen in Berührung kommen 
                        und mit Sicherheit auch anderen widrigen Umständen ausgesetzt sind. Dies wird sich 
                        jeder Hersteller zunutze machen und versuchen, die &#187;Schuld&#171; von sich zu 
                        schieben. Bei Contergan war der Zusammenhang sehr viel leichter zu beweisen, und 
                        trotzdem hat es (viel zu) viele Monate gedauert, bis dieses Mittel vom Markt genommen 
                        wurde. Gelernt haben wir aber nichts daraus. Die Kommissionen in Brüssel schielen 
                        aus meiner Sicht immer noch viel zu sehr zum Hersteller und entscheiden nicht 
                        für den Verbraucher.
                        <br />
                        <br />
                        Ich möchte nicht missverstanden werden: Ich gehöre nicht zu den ewig 
                        Gestrigen, die jedes neue Produkt ablehnen. Aber es darf nicht der Grundsatz gelten, 
                        dass ein neues Mittel, vor dessen Kontaminierung sich niemand schützen kann, 
                        auf den Markt kommen darf, ohne dass zuvor die Unbedenklichkeit zweifelsfrei 
                        bewiesen wurde. Es ist jedem unbenommen, seine Gesundheit auf eigenes Betreiben 
                        zu fördern oder auch zu schädigen. Wenn es sich um Produkte handelt, 
                        deren Konsum oder Nichtkonsum in meinen eigenen Händen liegt, habe ich eine 
                        tatsächliche Wahl. Wenn mir aber diese Entscheidungsmöglichkeit genommen 
                        ist, und ich bestimmte Stoffe über das Trinkwasser oder Grundnahrungsmittel 
                        zwangsläufig zu mir nehmen muss, muss eine Prüfung peinlichst genau 
                        durchgeführt werden. 
                        <br />
                        <br />
                        Selbstverständlich werden alle Prüfungen immer nur auf dem derzeitigen 
                        Wissenstand basieren, und es kann durchaus sein, dass sich später neue 
                        Erkenntnisse ergeben. Wenn aber bereits heute Zweifel &ndash; und zwar nicht unberechtigte 
                        Zweifel &ndash; an der Unbedenklichkeit eines Stoffes bestehen, dürfen diese 
                        nicht aus Gewinnsucht unter den Teppich gekehrt werden.
