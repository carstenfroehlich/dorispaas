                        <h5>Wie werden Studien durchgeführt? </h5>
                        <hr />
                        Zunächst einmal führt jeder Hersteller selbst Studien mit seinen Produkten durch. 
                        Dies ist normal und selbstverständlich auch legitim. Es soll ja ermittelt werden, 
                        ob und wie eine Substanz wirkt und ob es sich lohnt, weitere Mittel in die Fortführung 
                        der Entwicklung zu stecken. 
                        <br />
                        <br />
                        Meist werden diese Forschungen nur an einzelnen Substanzen durchgeführt. 
                        In der Regel bestehen Produkte wie u.a. eben Herbizide und auch Roundup aus einem 
                        Gemisch vieler verschiedener Substanzen. Hier können sich die Wirkungen der einzelnen 
                        Inhaltsstoffe gegenseitig beeinflussen &ndash; sie können sich abschwächen, verstärken 
                        oder auch zusammen ganz andere, neue Wirkungen entfalten. 
                        <br />
                        <br />
                        Darüber hinaus können die Umstände, unter denen Mittel ausgebracht werden, wie z.B. 
                        Wetterbedingungen oder nicht immer vermeidbare minimale Abweichungen von Anwendungsanweisungen, 
                        dazu führen, dass im Labor gerade noch tolerable Werte im wirklichen Gebrauch 
                        plötzlich ganz anders aussehen. Da solche Unwägbarkeiten jedoch nur sehr schwer 
                        nachzustellen sind, wird eben im Normalfall nur der isolierte Wirkstoff und dieser 
                        unter Idealbedingungen getestet.
                        <br />
                        <br />
                        Wird nun zu irgend einem Zeitpunkt festgestellt, dass die 
                        Substanz wirkungslos oder eventuell schädlich ist, werden die Projekte gestoppt &ndash; 
                        oder es sollte zumindest so sein. Hat der Hersteller aber zu diesem Zeitpunkt bereits 
                        sehr viel Geld in die Entwicklung investiert, kann es sein, dass Bedenken vom Tisch 
                        gewischt, verschwiegen oder vertuscht werden, um die bisherigen Inventitionen nicht 
                        umsonst getätigt zu haben. Denn hier geht es nicht um &#187;Peanuts&#171;, sondern 
                        um richtig viel Geld!
                        <br />
                        <br />
                        Natürlich reicht es &ndash; eben aus den beschriebenen Gründen &ndash; nicht aus, 
                        nur auf Studien zurückzugreifen, die ein Hersteller selbst durchgeführt hat. Es 
                        ist immer erforderlich, weitere Studien von externen Institutionen und unabhängigen 
                        Wissenschaftlern hinzuzuziehen, um die Wirkung und Unbedenklichkeit eines Produktes 
                        objektiv beurteilen zu können. Aber auch
                        externe Studien kosten viel Geld &ndash; Geld, das staatliche oder auch überregionale 
                        Gremien in der Regel nicht unbegrenzt zur Verfügung haben. Und damit sind 
                        wieder die Hersteller im Boot: sie haben im Vorfeld gro&#223;e Geldbeträge in 
                        die Entwicklung von Produkten gesteckt und sind nun daran interessiert, dass dieses 
                        Geld nicht für die Katz gewesen ist, weil eine Zulassung nicht erteilt wird. 
                        So pumpen sie weiteres Geld in Institutionen und sponsern Wissenschaftler, die 
                        die geeignete Studien durchführen. Aber wie werden die in einem solchen 
                        System erwarteten Ergebnisse aussehen? Wer wird wohl die Hand bei&#223;en, die einen 
                        füttert? Wer kennt nicht den Spruch &#187;Wes Brot ich ess, des Lied ich 
                        sing&#171;? Und somit ist ziemlich klar, zu welchen Schlussfolgerungen solche 
                        Studien führen müssen.
                        <br />
                        <br />
                        Natürlich gibt es auch Institutionen, die auf den ersten Blick unabhängig 
                        erscheinen und es vielleicht sogar sind &ndash; wobei es bei vielen Institutionen 
                        lohnt, genauer hinzuschauen, so dass über Umwege doch oftmals teils versteckte, 
                        teils sogar offensichtliche Interessenskonflikte und Verstrickungen zu Tage 
                        gefördert werden können.
                        <br />
                        <br />
                        Aber auch für wirklich unabhängige Forscher haben die Hersteller meist 
                        Lösungen parat: Diese Wissenschaftler werden nach alter Marktschreiermanier
                        behandelt und ihre Ergebnisse teils angezweifelt oder sogar lächerlich gemacht. 
                        Manch ein Wissenschaftler verlor in der Vergangenheit auf diese Weise schon seine 
                        Reputation. So überlegt man es sich als angesehener Wissenschaftler vielleicht 
                        zweimal, ob man seine Stimme gegen die Mächtigen dieser Welt erhebt.
                        <br />
                        <br />
                        Aber nicht nur die Forscher selbst kann ein Hersteller beeinflussen. Es gibt ja 
                        noch die Lobbyisten, die flei&#223;ig in den Gremien dafür werben, wie wunderbar 
                        die Produkte sind. Ob dabei Geld flie&#223;t und wenn ja, in welcher Höhe, 
                        wage ich gar nicht zu beurteilen. Korruption ist ja schlie&#223;lich verboten! 
                        <br />
                        <br />
                        Natürlich gibt es für jedes neue Produkt auch immer die notorischen Neinsager, 
                        die alles und jedes verteufeln. Das muss nicht immer und zwangsläufig bei jedem 
                        Mittel so sein, und es kann durchaus auch Produkte geben, die entweder tatsächlich 
                        (nach derzeitigem Wissensstand) unbedenklich sind, oder bei denen man nach einer 
                        Abwägung von Schaden und Nutzen trotz geringer (!) Bedenken zu dem Schluss kommt, 
                        dass man ein Mittel eventuell für einen eingegrenzten Anwendungsbereich unter 
                        bestimmten Bedingungen zulassen kann.
                        <br />
                        <br />
                        Es wird also immer sich widersprechende Bewertungen und Studien geben, und hier 
                        die Spreu vom Weizen zu trennen und zu einer wirklich objektiven Beurteilung zu 
                        kommen, ist bestimmt nicht einfach.
                        <br />
                        <br />
                        Wenn nun ein Organ wie die EU-Kommission sich auf positive und negative Studienergebnisse 
                        stützt und mit Sicherheit auch von dem einen oder anderen Lobbyisten über die 
                        Unbedenklichkeit eines 
                        Mittels &#187;informiert&#171; worden ist, wird es nie einfach sein, eine 
                        objektive und für Mensch, Tier und Umwelt wirklich richtige Entscheidung zu 
                        treffen. Aber es ist nicht unmöglich! Bei der Abstimmung für oder gegen eine Zulassung 
                        müssten sich dann nur noch die Vertreter der 28 Mitgliedsstaaten einigen &ndash; 
                        ein wahrhaft ambitioniertes Vorhaben!
