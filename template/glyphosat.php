                        <hr />
                        <h5>Glyphosat und unser Mikrobiom</h5>
                        <hr />
                        Auch aus einem anderen Blickwinkel möchte ich den Unkrautvernichter noch 
                        einmal betrachten, ohne hier ausreichende Beweismittel vorlegen zu können. Es 
                        ist ja nicht nur unser eigener Stoffwechsel, den wir betrachten und auf den wir 
                        sorgsam achten müssen. In und auf uns leben mit unserem Mirkobiom, also der 
                        Darmflora und den Bakterien, die unsere Haut, unsere Lunge und unseren Urogenitaltrakt 
                        besiedeln, zehnmal mehr Mikroorganismen als wir selber Körperzellen haben. 
                        Die meisten dieser Bakterien sind förderlich für unsere Gesundheit, 
                        und wir könnten ohne sie gar nicht leben. Die Bakterien der Darmflora 
                        beispielsweise stärken nicht nur unser Immunsystem, sondern helfen uns bei 
                        der Nahrungsverwertung, unterstützen unsere Vitaminversorgung und haben 
                        zahlreiche weitere, wichtige Aufgaben. Auch diese Bakterien sind Lebewesen &ndash; 
                        zwar klein, aber eben unverzichtbar für uns. Und wie alle Lebewesen haben 
                        sie einen Stoffwechsel. Ob und ggf. in welcher Weise dieser Stoffwechsel durch 
                        die Kontamination mit einem Unkrautvernichter wie Glyphosat beeinträchtigt 
                        werden kann, ist bisher nur in sehr wenigen Studien bedacht worden. 
                        <br />
                        <br />
                        Eine Leipziger Veterinärmedizinerin berichtet von ihrer Beobachtung, dass sich das Mikrobiom
                        im Pansen von Kühen nach der Verabreichung von glyphosathaltigem Futter verändert 
                        hat, was Auswirkungen auf deren Gesundheit hatte. Auch, wenn das Bundesinstitut 
                        für Risikoforschung (BfR), das u.a. in der EU für die Bewertung von Glyphosat 
                        zuständig ist, diesen Ergebnissen widerspricht, erscheint es mir doch sehr einleuchtend, 
                        dass neben Pflanzen auch andere Organimen durch ein solches Mittel nicht unbeeinträchtigt 
                        bleiben.
                        <br />
                        <br />
                        Auch ist unklar, ob und ggf. in welcher Weise und Ausprägung eine Kontamination 
                        mit Glyphosat auf die Zellen unserer Darmschleimhaut wirken könnte. Die Darmschleimhaut 
                        ist nicht nur für die Abgrenzung des Darminhalts gegenüber unserem Körperinneren
                        zuständig. Die Zellen stellen auch die zahlreichen Enzyme und Transportproteine 
                        her, die für die Aufspaltung  der Nahrungsbestandteile und für die Aufnahme der 
                        Nährstoffe erforderlich sind. Darüber hinaus aber bildet die Darmschleimhaut das 
                        Bett für die Darmbakterien. Eine gesunde Darmschleimhaut fördert eine gesunde 
                        Darmflora &ndash; und umgekehrt. Und beides fördert unsere menschliche Gesundheit.
                        Ohne gesunde Darmbakterien und eine gesunde Darmschleimhaut können wir nicht überleben.
                        <br />
                        <br />
                        Wer nun bereits aus anderen Gründen an einem Leaky-Gut-Syndrom &ndash;einem Siebdarm&#171; 
                        leidet, dessen Abgrenzungsmechanismus funktioniert nicht mehr so, wie er soll.
                        Der Erkrankte ist noch mehr als andere gefährdet, dass Nahrungsbestandteile, 
                        Bakterien oder eben auch aufgenommene Umweltgifte ungefiltert in den Organismus 
                        gelangen. Und diese Erkrankung ist leider gar nicht so selten. Hier ist eine gesunde, 
                        schadstofffreie Kost eine der Grundvoraussetzungen für die Ausheilung der Krankheit. 
                        Die Schleimhaut wird dann mehr und mehr geschädigt, und die Darmbakterien sind mit betroffen.
                        <br />
                        <br />
                        Die Erforschung unserer Darmschleimhaut und unserer Darmflora steckt noch in den 
                        Kinderschuhen, aber die Erkenntnis, dass generell die Aufnahme von Umweltgiften 
                        einen gro&#223;en Einfluss auf die Qualität der Zusammensetzung unserer Darmbakterien 
                        und die Funktionalität unseres gesamten Verdauungssystems hat, ist unbestritten. Ob 
                        und in welcher Weise dies auch auf Roundup und hier insbesondere auf Glyphosat 
                        zutrifft, ist noch nicht abschließend bewiesen. Aber bis nicht eindeutige Erkenntnisse 
                        zu dieser Problematik zur Verfügung stehen, möchte ich möglichst kein Glyphosat 
                        zu mir nehmen müssen.
                        <br />
                        <br />
                        Alle Menschen mit Verdauungsbeschwerden &ndash; seien sie durch 
                        Nahrungsmittel-Unverträglichkeiten oder -Allergien verursacht, durch eine 
                        Dysbiose des Dickdarms oder eine bakterielle Fehlbesiedelung des Dünndarms, 
                        durch ein Leaky- Gut-Syndrom oder einen der zahlreichen anderen Gründe &ndash; 
                        sollte daran interessiert sein, alles zu vermeiden, was eventuell eine (weitere) 
                        Schädigung von Darmflora und/oder Darmschleimhaut begünstigen könnte. Und dazu gehört 
                        mit Sicherheit unter vielem anderen auch eine weitestgehend unbelastete Nahrung 
                        und reines Trinkwasser.
                        <br />
