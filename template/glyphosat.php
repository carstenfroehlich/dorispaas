                        Glyphosat ist einer von mehreren Inhaltsstoffen des unter dem Namen &#187;Roundup&#171; 
                        vertriebenen Unkrautvernichtungsmittels des amerikanischen Agrarkonzerns Monsanto, 
                        der wahrscheinlich in Kürze von dem deutschen Chemie- und Pharmakonzern Bayer AG aufgekauft werden wird.
                        Neben Herbiziden produziert die Firma mit Hauptsitz in St. Louis im Bundesstaat 
                        Missouri und Niederlassungen in zahlreichen anderen Ländern auch Saatgut.
                        Wie alle Herbizide und Pestizide benötigt auch Roundup, das sowohl in der kommerziellen 
                        Landwirtschaft wie auch in privaten Obst- und Gemüsegärten Verwendung findet,
                        in der EU eine Zulassung, die erteilt wird, sofern die EU-Kommission 
                        der Meinung ist, diese Mittel seien für Mensch, Tier und Umwelt unbedenklich. 
                        Nur zugelassene Mittel dürfen verkauft und eingesetzt werden, ohne eine 
                        Zulassung sind der Vertrieb und die Ausbringung in der gesamten EU verboten. Liegt 
                        eine Zulassung vor, ist es den einzelnen Mitgliedsstaaten allerdings immer noch 
                        unbenommen, per Sonderregelung den Einsatz im eigenen Land zu untersagen. Umgekehrt 
                        ist es jedoch nicht möglich, eine fehlende EU-Zulassung in einzelnen Ländern 
                        aufzuheben. Die derzeitige Frist für die Zulassung von Glyphosat erlischt am 
                        15. Dezember 2017 &ndash; sofern nicht rechtzeitig eine Folgezulassung erteilt wird.
