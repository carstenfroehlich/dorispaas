                        <h5>Fazit</h5>
                        <hr />
                        Falls keine Fristverlängerung beschlossen wird, erlischt die Zulassung von 
                        Glyphosat am 15. Dezember 2017. Der Stoff darf dann nur noch weitere sechs Monate, 
                        also bis Sommer 2018 verwendet werden. Derzeit (heute ist der 31.Oktober 2017) 
                        streiten sich die Gremien darüber, ob eine Fristverlängerung um zehn 
                        Jahre oder nur eingeschränkt um vier oder fünf Jahre erteilt oder ob die 
                        Verwendung ganz verboten werden soll.
                        <br />
                        <br />
                        Viel hängt dabei von der Stimme Deutschlands ab, denn mit seiner Einwohnerzahl 
                        hat unser Land ein gro&#223;es Gewicht. Leider hat sich unser Land in der Vergangenheit 
                        bei vielen vergleichbaren Entscheidungen nicht sehr verbraucherfreundlich gezeigt 
                        und oftmals eher im Sinne der Wirtschaft gestimmt als sich wirklich Gedanken um 
                        die Gesundheit der Bürgerinnen und Bürger zu machen.
                        <br />
                        <br />
                        Somit halte ich es für wichtig, meine Stimme zu erheben und deutlich zu machen, 
                        dass ich nicht möchte, dass die Zulassung für Glyphosat verlängert 
                        wird &ndash; weder für zehn, noch für fünf oder vier Jahre, sondern 
                        solange nicht, bis von unabhängigen Stellen zweifelsfrei bewiesen wurde, dass 
                        Glyphosat tatsächlich unbedenklich ist.
