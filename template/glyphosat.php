                        <hr />
                        <h5>Wie wirkt Glyphosat? </h5>
                        <hr />
                        Roundup wurde in den 1970er Jahren als Herbizid, also als Unkrautvernichtungsmittel 
                        von der Firma Monsanto entwickelt. Es gelangt über die Blätter in die 
                        Pflanzen und hemmt dort bestimmte Stoffwechselvorgänge, so dass die Pflanzen 
                        absterben.
                        <br />
                        <br />
                        Dies beträfe eigentlich alle Pflanzen, und ein unkrautfreies Feld, auf dem 
                        auch die Kulturpflanzen wie z.B. das Getreide absterben, würde dem Bauern 
                        nichts nützen. Schlauerweise hat Monsanto gleichzeitig auch Getreidesorten 
                        gezüchtet, die unempfindlich gegen Glyphosat sind. Das Saatgut dieser Getreidesorten 
                        hat sich Monsanto gleich mitpatentieren lassen, so dass nun doppelt abkassiert 
                        werden kann: zum einen beim Vertrieb des Unkrautvernichters und zum anderen durch 
                        den Verkauf des genveränderten Saatguts.
                        <br />
                        <br />
                        Der Bauer hat es nun einfach: das mühsame Unkrautjäten entfällt, 
                        und die Ernte wird einfacher. Es gibt aber auch Pflanzensorten wie z.B. den Raps oder Kartoffeln, 
                        die nicht genverändert ist und empfindlich auf Glyphosat reagiert. Aber kein 
                        Problem: auch hier hat Monsanto flugs eine Anwendungsempfehlung: spritzt man Roundup 
                        kurz vor der Ernte auf die Raps- oder Kartoffelpflanzen, sterben sie ab, was aber 
                        den Rapssamen oder die unterirdisch wachsenden Kartoffelknollen, 
                        die ja den Ertrag bringen, nicht beeinträchtigt &ndash; zumindest 
                        oberflächlich betrachtet. Die verdorrten Pflanzen können leichter geerntet 
                        werden als die noch lebenden, und der Bauer hat weniger Arbeit. Unerheblich davon, 
                        ob Glyphosat im Laufe des Wachstums oder erst kurz vor der Ernte versprüht wird, 
                        verbleiben mehr oder weniger gro&#223;e Reste auf den Feldfrüchten &ndash; 
                        und gelangen so auch in unser Verdauungssystem. Und ob und in welcher Menge sich 
                        die verbleibenden Wirkstoffreste in der Erde verhalten und ggf. bei der nächsten 
                        Saat in die Pflanzen geraten und so letztendlich auch noch in die Nahrungskette 
                        gelangen, ist noch gar nicht erwiesen.
                        <br />
                        <br />
                        Ob und wie sich Glyphosat, das ja in den Stoffwechsel von Organismen eingreift, 
                        wirklich nur auf Pflanzen wirkt oder nicht doch Tiere oder sogar Menschen, ist 
                        noch nicht abschließend erforscht. Einige Ergebnisse jedoch dringen bereits an die Öffentlichkeit. 
                        Nehmen wir als nur ein Beispiel die Bienen, deren sukzessives Verschwinden immer 
                        deutlicher wird: in Versuchen hat man nachgewiesen, dass Bienen, deren Futter Glyphosat 
                        in Konzentrationen zugesetzt wurde, die denen auf mit dem Herbizid gespritzten 
                        Feldern entsprechen, Orientierungsprobleme bekamen. Und da sich Bienen zum einen auf dem 
                        Rückweg zu ihrem Stock orientieren müssen um heimzufinden und sie zum 
                        anderen bei der Informationsweitergabe an ihre Bienenkolleginnen, wo sich Futterquellen 
                        befinden, auf ihren Orientierungssinn angewiesen sind, ist leicht verständlich, 
                        dass u.a. auch auf diese Weise rasch die Stärke und damit die Überlebensfähigkeit 
                        eines Bienenvolkes beeinträchtigt werden kann.
                        <br />
                        <br />
                        Und wenn bei einer Tierart Beeinträchtigungen beobachtet werden können, 
                        warum dann nicht auch bei anderen?
                        <br />
