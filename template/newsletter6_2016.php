                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=praeparatetest" target="_blank">Aktualisierung der Pr&auml;parate-Tests</a></b>
                        <br />
                        Der Markt um Enzym-Pr&auml;parate ver&auml;ndert sich mit rasantem Tempo. Somit 
                        ist es so gut wie unm&ouml;glich, hier wirklich immer &#187;auf dem Laufenden&#171; zu bleiben! 
                        Beinahe t&auml;glich kommen neue Produkte hinzu &ndash; wobei ich der festen &Uuml;berzeugung 
                        bin, dass die allermeisten wahrscheinlich entbehrlich sind. Leider findet man 
                        auch genauso oft neue und bislang unbekannte Hersteller, und es ist sehr schwierig, hier  
                        seri&ouml;se Firmen von den schwarzen Schafen zu trennen. Der Enzymmarkt verspricht 
                        n&auml;mlich reichlichsten Gewinn f&uuml;r die Verk&auml;ufer, sind doch die verzweifelten 
                        Betroffenen nur allzu h&auml;ufig bereit, den Werbeversprechen viel zu schnell und 
                        viel zu un&uuml;berlegt Glauben zu schenken. Immer mehr vor allem neue Produkte 
                        werden aggressiv oder zumindest penetrant sogar in den sozialen Neztwerken 
                        insbesondere auf Foren von und f&uuml;r Betroffene 
                        beworben, indem angebliche &#187;Erfahrungsberichte&#171; gepostet werden &ndash; 
                        hier ist ganz besondere Aufmerksamkeit geboten!
                        Doch erfreulicherweise gibt es auch Pr&auml;parate, die wirklich halten, 
                        was sie versprechen. Aber wie kann man, ohne ein hohes Lehrgeld zahlen zu m&uuml;ssen, 
                        unterscheiden, welche Mittel tats&auml;chlich f&uuml;r einen selbst geeignet oder eben 
                        nicht gut und ob sie wirklich ihr Geld wert sind? 
                        <br />
                        Auf der Seite f&uuml;r die Pr&auml;parate-Tests stelle ich Ihnen meine ganz 
                        pers&ouml;nlichen Bewertungen diverser Nahrungserg&auml;nzungsmittel &ndash; geordnet 
                        nach Rubriken &ndash; vor. Sobald ich von Produkten erfahre, die mir interessant 
                        erscheinen oder aber deren Werbeaussagen mir allzu vollmundig erscheinen, 
                        kaufe ich die Pr&auml;parate oder fordere Proben von den Herstellern an und teste 
                        die Mittel. Teilweise werden mir von den Firmen auch unaufgefordert Proben zugesandt, 
                        wodurch ich mich aber keineswegs in meinem Urteil beeinflussen lasse (lesen Sie 
                        hierzu bitte auch die Erl&auml;uterungen zu meiner Maxime &#187;<a href="http://www.dorispaas.de/index.php?page=guterrat" target="_blank">Grunds&auml;tzlich werbefrei</a>&#171;).
                        In den letzten Wochen sind einige sehr vielversprechende Enzym-Pr&auml;parate hinzugekommen, 
                        die u.U. eine wirksame Hilfe gerade f&uuml;r diejenigen sein k&ouml;nnten, denen 
                        bisher andere Mittel nicht oder zumindest nicht ausreichend geholfen haben. Beachten 
                        Sie bitte auch die neu hinzugekommene Rubrik 
                        &#187;<a href="http://www.dorispaas.de/index.php?page=praeparatetest#rubrik-gluten" target="_blank">Enzym-Erg&auml;nzungsmittel 
                        bei Gluten-Sensitivit&auml;t</a>&#171;. 
