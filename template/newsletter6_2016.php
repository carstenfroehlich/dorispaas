                        Liebe Leserin, lieber Leser.
                        <br />
                        <br />
                        Schon wieder neigt sich das Jahr dem Ende zu. Haben auch Sie den Eindruck, dass der 
                        Zeitablauf immer schneller zu gehen scheint? Umso wichtiger ist es, dass wir uns 
                        immer wieder ganz bewusst Zeit f&uuml;r uns und die sch&ouml;nen Dinge des Lebens 
                        nehmen! Und welche Zeit eignet sich da besser als die dunkle Jahreszeit. Alle 
                        Arbeiten im Garten sind erledigt, und der &#187;Hausputz&#171; steht erst im 
                        Fr&uuml;hjahr an (zumindest f&uuml;r all diejenigen, die das noch wie unsere M&uuml;tter 
                        machen). Genug Zeit also, sich zu besinnen und jeden Tag wenigstens ein paar Minuten 
                        ganz f&uuml;r sich zu reservieren. Nicht auf das schauen, was &ndash; nicht zuletzt auch 
                        in diesen Tagen mit ihren sehr beunruhigenden politischen Ereignissen &ndash; nicht so optimal 
                        l&auml;uft, sondern sich &uuml;ber die Dinge freuen, die uns guttun &ndash; und 
                        die wir doch so oft als nebens&auml;chlich oder sogar selbstverst&auml;ndlich hinnehmen.
                        <br />
                        Gerade jetzt kann zum Beispiel eine kleine Lichtmeditation ein gutes Mittel 
                        sein: Suchen Sie sich einen ruhigen Ort in Ihrer Wohnung und einen Zeitpunkt, an 
                        dem Sie nicht gest&ouml;rt werden. Z&uuml;nden Sie eine Kerze an, stellen Sie sie 
                        sicher auf und nehmen einen bequemen Sitz vor dem Lichtlein ein (die Gelenkigen 
                        unter uns m&ouml;gen den Lotossitz bevorzugen, f&uuml;r alle anderen empfiehlt es 
                        sich, sich mit geradem R&uuml;cken auf die Vorderkante eines Stuhls zu setzen).
                        Schauen Sie nun in das Licht und konzentrieren Sie sich vollst&auml;ndig auf die 
                        Flamme. Gedanken, die kommen, lassen Sie getrost wieder gehen, so dass Ihr Kopf 
                        bald v&ouml;llig frei ist. Sie werden merken, dass Sie sich schon nach kurzer Zeit
                        frei und erholt f&uuml;hlen werden und das Positive besser wahrnehmen 
                        k&ouml;nnen.
