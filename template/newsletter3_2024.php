                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=enzyme" target="_blank">Schwerpunktthema: Enzyme</a></b>
                        <br />
                        <i>(Menü: Wissensdatenbank/Pr&auml;parate/Enzyme)</i>
                        <br />
                        Enzyme steuern unser Leben. Bei einem Mangel an einem oder mehreren Enzymen treten Probleme auf, weil die entsprechenden Prozesse nicht oder in nicht ausreichendem 
                        Ma&#223;e ablaufen. Dies f&uuml;hrt nicht nur zu Einschr&auml;nkungen, die direkt mit diesen bestimmten Enzymen in Zusammenhang stehen, sondern es kann u.U. auch eine 
                        Kaskade von nachgeschalteten Reaktionen verursachen. Eine ausreichende Produktion aller Enzyme ist deshalb sehr wichtig &ndash; und daf&uuml;r kann jeder auch selbst 
                        eine Menge tun. Die verschiedenen Enzyme werden je nach ihrer Funktion im Organismus in mehrere Gruppen eingeteilt: dies sind erstens die Verdauungsenzyme, die 
                        beispielsweise in den Zellen der Darmschleimhaut gebildet werden. Zweitens gibt es Enzyme, die in den Verdauungsdr&uuml;sen (Speicheldr&uuml;sen, Magen, Leber, Galle 
                        und Bauchspeicheldr&uuml;se) gebildet werden. Die Enzyme dieser beiden Gruppen wirken (vor allem) auf die Verdauung. Und drittens gibt die systemisch wirkenden Enzyme, 
                        die nicht nur im Verdauungssystem gebildet werden und wirken, sondern ihre Funktionen an den verschiedensten Orten im K&ouml;rper haben. Und last, but not least, gibt 
                        es viertens unz&auml;hlige Enzyme, die nicht von unserem eigenen K&ouml;rper gebildet, sondern mit der Nahrung aufgenommen werden. Auch solche Enzyme k&ouml;nnen unsere 
                        Organfunktionen unterst&uuml;tzen. 
