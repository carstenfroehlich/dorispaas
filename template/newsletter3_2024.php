                        Liebe Leserin, lieber Leser.
                        <br />
                        Der Sommer neigt sich dem Ende zu, und an den bunter werdenden Bl&auml;ttern erkennt man bereits den Herbst. In den G&auml;rten bl&uuml;hen vielfarbige Blumen, und die 
                        Gr&auml;ser zeigen sich von ihrer sch&ouml;nsten Seite. &#187;Stehlen&#171; Sie hier gerne einen gro&#223;en Strau&#223; voller Eindr&uuml;cke, und nehmen Sie die Farben, 
                        Formen und D&uuml;fte im Kopf mit nach Hause. Und wenn Sie auf einem Spaziergang oder mit dem Fahrrad an einer Streuobstwiese vorbeikommen, sammeln Sie doch einen 
                        Apfel oder auch eine Birne auf. Solches Obst schmeckt um L&auml;ngen besser als die zwar makellosen, aber doch langweiligen Fr&uuml;chte aus dem Supermarkt und haben 
                        einen wesentlich h&ouml;heren Gehalt an Vitaminen, Mineralien und auch an Enzymen. Und gerade deshalb sind solche &#187;wilden Fr&uuml;chtchen&#171; nicht nur deutlich 
                        ges&uuml;nder, sondern oft auch f&uuml;r Menschen mit Unverträglichkeiten oder sogar mit leichten Allergien bek&ouml;mmlicher. Vielleicht m&ouml;gen schon kleinere Druckstellen 
                        vorhanden sein, aber dann nehmen Sie doch auch gerne zwei oder drei St&uuml;cke mit und schneiden die schadhaften Teile ab. Sie behalten dann immer noch genug &uuml;brig. 
                        Aber Vorsicht: es kann sein, dass auch schon ein hungriges und m&ouml;glicherweise stachelbewehrtes Insekt Interesse hat, deshalb achten Sie darauf, wo Sie hinfassen!
