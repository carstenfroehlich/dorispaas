                        <br style="clear: left;" />
                        Sie sind bereits als Gesundheits- oder Ernährungsberater, Heilpraktiker, 
                        Entspannungstherapeut, Coach oder als Spezialist in einem verwandten Berufsfeld 
                        selbstständig? Oder Sie nutzen Ihre Ausbildung bisher &#187;nur&#171; für sich 
                        selbst und liebäugeln mit einer selbstständigen Tätigkeit in Ihrem Berufsfeld? 
                        Oder Sie wollen erst demnächst eine solche Ausbildung beginnen?
                        <br />
                        <br />
                        Egal, ob Sie (noch) gar nicht an eine Selbstständigkeit denken oder aber in 
                        absehbarer Zeit ein neues (kleines) Unternehmen gründen wollen oder ob Sie schon 
                        richtig im Geschäft sind &ndash;  für alle ist das Buch &#187;Der Leitfaden&#171; 
                        von Thomas Bannenberg eine wahre Fundgrube von Tipps!
                        <br />
                        <br />
                        In diesem Ratgeber, der regelmäßig aktualisiert wird und hier in seiner 4. Auflage 
                        vorliegt, gibt es Hilfestellungen bei der Herausarbeitung der eigenen Motivation 
                        und Stärken; Empfehlungen zum Gründen; Ratschläge und Hinweise zum Marketing, 
                        aber auch wichtige Fingerzeige zu Finanziellem, Gewinn, Steuern und Versicherungen 
                        &ndash; jeder Vorschlag und jede Anregung ist gut verständlich, nachvollziehbar 
                        und in meinen Augen Gold wert. Gerade beim Finanziellen empfiehlt der Verfasser &ndash; 
                        der übrigens vieles aus eigener Erfahrung schildert &ndash;  nicht nur Wichtiges, 
                        er klopft auch ab, was eher überflüssig ist, und wo man bares Geld sparen kann.
                        <br />
                        <br />
                        Eben weil &#187;Der Leitfaden&#171; speziell auf eine bestimmte Art von Berufsfeldern 
                        zugeschnitten ist, findet man in diesem Buch nicht weit hergeholte Rastschläge, 
                        mit denen man gar nichts anfangen kann. Jede Empfehlung zeigt auf, was man vor, 
                        bei und nach einer Gründung alles bedenken könnte, sollte oder muss. Man kann 
                        diesen Ratgeber nutzen, um zu entscheiden, ob man sich überhaupt selbstständig 
                        machen möchte, welche Gesichtspunkte man bei einer Gründung beachten muss und was 
                        man eventuell auch (lange) nach diesem Schritt noch verbessern kann.
                        <br />
                        <br />
                        So sind all die Hinweise nicht nur dazu geeignet, einmal unverbindlich zu schauen, 
                        welche Optionen einem zur Verfügung stehen. Sie sind auch unerlässlich dafür, 
                        Fehler zu vermeiden, wenn man sich zur Gründung entschließt. Und last, but not 
                        least, sind sie auch wertvoll für diejenigen, die bereits in einem der aufgeführten 
                        Bereiche tätig sind, so dass man Versäumtes nachholen oder Unvollkommenes optimieren 
                        kann. Ich selbst führe schon einige Zeit eine eigene Beratungs-Praxis und habe 
                        noch viele wertvolle Hinweise gefunden, die ich nachträglich bedenken sollte. 
                        Ich kann dieses Buch allen nur wärmstens empfehlen.
                        <br />
