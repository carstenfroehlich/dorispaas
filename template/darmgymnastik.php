                        zu Verdauungsproblemen führt. 
                        <br />
                        <br />
                        Ein Darm ist nämlich faul &ndash; und zwar jeder Darm! Ohne Anregung bewegt sich ein Darm wenig und transportiert die Speisen nur sehr 
                        unzureichend, was sich nachteilig auf eine gesunde Verdauung auswirkt. Die Anregung des Darms erfolgt zum 
                        einen durch die Dehnung durch die verzehrten Speisen von 
                        innen. Je voluminöser der Speisebrei &ndash; beispielsweise durch den Verzehr von ausreichend Ballaststoffen &ndash; desto intensiver wirkt sich 
                        das auf die Darmperistaltik aus, also die Bewegungen der Muskulatur, die das Darmrohr umhüllt und den Darminhalt in Richtung Ausgang bewegt. Zum 
                        anderen regt aber auch bei aktiver Körperbewegung die Tätigkeit der Bauchmuskulatur die Darmperistaltik von außen an. Und zusätzlich massiert bei der 
                        <a href="atmen" target="_blank">Atmung</a>
                        die Auf- und Abbewegung des Zwerchfells Darm und <a href="verdauungsdruesen" target="_blank">Verdauungsdrüsen</a> von oben, so dass der Speisebrei vom
                        Magen durch den gesamten Dünn- und Dickdarm weiterbefördert wird. <b>Je häufiger diese Anregungen sind, desto besser und desto gleichmäßiger wird der 
                        Darminhalt weiterbefördert.</b> Schauen Sie sich hierzu gerne die <a href="ganz-verdauungssystem" target="_blank">Abbildung des gesamten Verdauungssystems</a> an.
                        <br />
                        <br />
                        Erfolgen die Anregungen nur sporadisch, bleiben die Speisen viel zu lange an einer Stelle liegen. Dies kann unter Umständen zu erheblichen Beschwerden 
                        führen, allem voran zum sogenannten <a href="rds-wasistdas" target="_blank"><b>Reizdarm-Syndrom</b></a> mit allen seinen Symptomen wie u.a. zu <b>Verstopfung</b>,  
                        <b>Blähungen</b>, <b>Bauchschmerzen und -krämpfen</b> oder auch <b>bakteriellen Fehlbesiedelungen</b> 
                        (<a href="duenndarmfehlbesiedelung" target="_blank"><b>Dünndarmfehlbesiedelung/SIBO</b></a> bzw. <b>Dysbiose</b>) und sogar Schäden 
                        wie <b><a href="darmschleimhaut" target="_blank">Mikroentzündungen an der Darmschleimhaut</a></b>. Auch den unangenehmen, mitunter sogar angsteinflößenden Symptomen 
                        des sogenannten <b><a href="lexikon-darmerkrankungen#roemheld" target="_blank">Roemheld-Syndroms</a></b> wird vorgebeugt. 
                        <br />
                        <br />
