                        <h5>Vorbeugung und Therapieunterstützung</h5>
                        <hr />
                        Ganz anders als unsere Vorfahren bewegen wir uns heute kaum noch. Zur Fortbewegung benutzen wir das Auto, und die allermeisten Menschen sitzen viel zu viel. 
                        &#187;Das Sitzen ist das neue Rauchen&#171; &ndash; also das neue &#187;Gift&#171;, heißt es heute unglücklicherweise. Dies hat leider nicht nur für unsere Haltung, 
                        für unsere Muskulatur und unsere Knochen sehr nachteilige Folgen, sondern auch für unsere Verdauung, und viele Krankheiten und Probleme &ndash; sei es die oben 
                        erwähnte Verstopfung oder Fehlbesiedelungen von Dünn- oder Dickdarm und viele andere mehr &ndash; könnten durch eine ausreichende und vor allem <b>kontinuierliche 
                        Bewegung</b> verhindert bzw. in ihrer Ausheilung günstig beeinflusst werden. 
                        <br />
                        <br />
                        Noch einmal zum Thema &#187;Sitzen&#171;: während des Sitzens bewegt sich im Unterleib gar nichts &ndash; 
                        der Darm ist gefangen in einem starren Panzer zwischen den Beckenknochen, der unbewegten Bauchmuskulatur und dem sich kaum bewegenden Zwerchfell. Zu allem Übel 
                        kommt dann noch hinzu, dass wir meist das Falsche essen und kaum Ballaststoffe zu uns nehmen. Dass sich bei einer solchen Lebensweise in Bezug auf die Darmbewegungen, 
                        in Bezug auf die intestinale Mikrobiota (Darmflora) und damit in Bezug auf eine gesunde Verdauung und damit auf einen 
                        <a href="stuhlgang" target="_blank">gesunden Stuhlgang</a> nichts tut &ndash; zumindest nichts Positives &ndash; muss einleuchten. 
                        Leider hilft da die eine oder vielleicht auch andere sportliche Stunde am Wochenende nur relativ wenig. Es ist natürlich unbestritten: 
                        <a href="bewegung" target="_blank">Sport</a> ist gut, auch wenn er &#187;nur&#171; 
                        am Wochenende ausgeführt wird. <b>Für den Darm aber zählen die stündlichen oder sogar halbstündlichen Übungen</b>. Und diese müssen auch keineswegs schweißtreibend und 
                        zeitraubend sein, <b>etwa 3 Minuten</b> pro Übung reichen, nachdem Sie die Übung etwas intensiver erlernt haben und Ihnen die Ausführung geläufig ist.
