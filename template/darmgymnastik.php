                        <h5>Darmgymnastik &ndash; ein Allheilmittel?</h5>
                        <hr />
                        Ist die Darmgymnastik also ein &#187;Allheilmittel&#171;? Nun, alleine heilen diese Maßnahmen Ihre Beschwerden nicht. Aber Bewegung <b>unterstützt</b> die jeweils spezifische 
                        Behandlung bei der Heilung von Verdauungsbeschwerden &ndash; <b>und diese Unterstützung ist unverzichtbar</b>. Ansonsten ist nicht nur <b>die Heilung in Frage gestellt</b>, 
                        es sind auch <b>Rückfälle vorprogrammiert</b>. Mit der kontinuierlichen Bewegung haben Sie es also in der Hand &ndash; und zwar im wörtlichen Sinne in der eigenen Hand, 
                        um Erkrankungen des Verdauungssystems und Beschwerden sowohl symptomatisch als auch ursächlich günstig beeinflussen oder ihnen sogar wirksam vorbeugen zu können.
