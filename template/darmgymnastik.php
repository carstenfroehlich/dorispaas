                        <a id="uebungen"></a>
                        <br />
                        <hr />
                        <h5>Welche Übungen gibt es?</h5>
                        <hr />
                        Zunächst einmal sind hier die <b>Atemübungen</b> zu nennen. Allein schon ein vertiefter Atem ist geeignet, um die Verdauungsdrüsen und den Darm zu massieren und anzuregen.
                        Dann gibt es die <b>Dehnungsübungen</b>. Wenn wir sitzen, krümmen wir den Rücken und beugen uns automatisch nach vorne, winkeln die Hüfte an und quetschen so die 
                        Brust und den Bauch ein. So können wir nur flach atmen, und die Verdauungsorgane sind in ihrer Bewegungsfreiheit behindert. Dehnungsübungen helfen, die Muskulatur
                        wieder zu entspannen und so dem Verdauungssystem Platz zum Funktionieren zu geben.
                        <br />
                        <br />
                        Dann gibt es <b>Lockerungsübungen</b>. Wir neigen dazu, bei Schmerzen und Stress unsere willkürliche Muskulatur, wie z.B. die Atem- und die Bauchmuskulatur, anzuspannen. 
                        Aber auch unsere unwillkürliche Muskulatur wie u.a. die Darmmuskulatur verkrampft sich, ohne dass wir dies direkt darauf einwirken können. Da sich beide Systeme gegenseitig 
                        beeinflussen, können wir über die Lockerung der willkürlichen Muskulatur auch die Muskulatur unseres Verdauungssystems beeinflussen.
                        <br />
                        <br />
                        Die ganz wichtigen <b>entblähenden Übungen</b> haben eine große Wirkung gegen Bauchschmerzen oder sogar Krämpfe. Aber auch Verstopfung und Durchfälle können so günstig beeinflusst 
                        werden. Die in den Übungen vorgenommenen Körperhaltungen reduzieren den Platz im Bauchraum, so dass die Gase im gesamten Verlauf des Darms effektiv weitertransportiert 
                        und &#187;entsorgt&#171; werden können.
                        <br />
                        <br />
                        Genauso unentbehrlich sind auch <b>Stärkungsübungen</b>, denn nur mit gleichmäßig gestärkten Muskeln können wir eine aufgerichtete, gesunde Körperhaltung einnehmen, die
                        nicht nur unsere Verdauungsleistung stärkt, sondern auch unser Selbstbewusstsein.
                        <br />
                        <br />
                        Ganz wichtig sind auch <b>Entspannungsübungen</b>, denn Stress ist ein wichtiger Trigger für Verdauungsprobleme. Unser &#187;Bauchhirn&#171; &ndash; also das Nervengeflecht,
                        das unseren gesamten Darm umgibt und ihn und seine Funktionen steuert &ndash; wird ebenso durch Stress bzw. eben auch Entspannung beeinflusst, wie das Gehirn in unserem Kopf. 
                        Und da die meisten Menschen leider nicht auf der idyllischen Insel leben sondern in hektischen und stressigen Zeiten, ist es umso wichtiger, diesem Stress mit geeigneten 
                        Entspannungsübungen entgegenzuwirken &ndash; zum Wohle unseres Darms und unserer Verdauung.
