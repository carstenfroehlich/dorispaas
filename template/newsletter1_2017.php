                        Liebe Leserin, lieber Leser.
                        <br />
                        Nach dem vergangenen Jahr, das in vieler Hinsicht mit traurigen Rekorden aufwarten 
                        konnte, hat leider auch das Jahr 2017 nicht nicht gut begonnen: nach gerade 
                        mal einer guten Stunde gab es bereits den ersten Terroranschlag, auf den bis heute 
                        bereits mehrere gefolgt sind. In Griechenland leiden viele Tausend Fl&uuml;chtlinge 
                        in unbeheizten Zelten unter der K&auml;lte, und Worte und Taten des designierten 
                        Pr&auml;sidenten der USA lassen Schlimmes f&uuml;r die 
                        kommenden Jahre bef&uuml;rchten. Dies alles w&auml;re Anlass 
                        genug, sich zu fragen, ob die Welt nun total aus den Fugen ger&auml;t. Trotzdem oder 
                        gerade vor diesem Hintergrund m&ouml;chte ich Ihren Blick darauf lenken, dass es 
                        auch vieles gibt, wof&uuml;r wir dankbar sein d&uuml;rfen. Dankbar zum Beispiel 
                        f&uuml;r die trotz des Berliner Anschlags doch relativ sicheren Verh&auml;ltnisse, 
                        in den wir leben d&uuml;rfen. Dankbar auch daf&uuml;r, dass wir genug zu essen 
                        haben und nicht frieren m&uuml;ssen. Und dankbar auch daf&uuml;r, dass es uns, 
                        auch wenn wir vielleicht selbst einige Beschwerden haben, gut geht &ndash; sehr gut 
                        zumindest vor dem Hintergrund der o.a. Tatsachen. Mit Ihnen hoffe ich, dass sich 
                        das Jahr 2017 trotz seines unguten Starts im weiteren Verlauf nicht so 
                        fortsetzt, wie es begonnen hat. Tun wir alle unser Bestes daf&uuml;r, auch wenn 
                        die Bausteinchen, die jeder dazu beitragen kann, noch so klein sind.
