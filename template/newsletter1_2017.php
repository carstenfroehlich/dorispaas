                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=darmsanierung" target="_blank">Aktualisierung des Beitrags &#187;Sanierung der Darmflora&#171;</a></b>
                        <br />
                        In manchen F&auml;llen &ndash; beispielsweise bei schweren entz&uuml;ndlichen 
                        Darmerkrankungen oder einer D&uuml;nndarmfehlbesiedelung, nach wiederholten 
                        Antibiotikatherapien, oder nach Chemo- oder Bestrahlungstherapien kommt es 
                        h&auml;ufig vor, dass die Darmflora schwerst gesch&auml;digt ist und gr&uuml;ndlich 
                        saniert werden muss. Die Bakterienst&auml;mme der obligaten &ndash; also Ihrer 
                        ganz individuellen und eigentlich dauerhaften &ndash; Darmflora k&ouml;nnen sich 
                        nur regenerieren, wenn noch ein ausreichender Grundstock der vielen verschiedenen 
                        Bakterienarten vorhanden ist. Sind hier die Mengen massiv dezimiert oder aber 
                        teilweise sogar so gut wie ganz ausgerottet, kann sich die gesunde Gesamtbalance 
                        nicht wieder einstellen, ohne dass von au&#223;en die Keime in gr&ouml;&#223;erer 
                        Anzahl zugef&uuml;hrt werden, oder aber die bestehende Darmflora mit geeigneten 
                        Mitteln wie z.B. Vitalpilzen bei der Regeneration unterst&uuml;tzt wird.<br />
