                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=gewichtsreduktion" target="_blank">Gewichtsreduktion</a></b>
                        <br />
                        Es geh&ouml;rt zur guten alten Tradition, an Neujahr gute Vors&auml;tze zu fassen. 
                        Ob und welche der Vors&auml;tze letztendlich umgesetzt werden, ist meist fraglich, 
                        aber die eine oder andere &Auml;nderung wird dann schlie&#223;lich doch zumindest 
                        begonnen. Ganz oben auf der Liste der meistgenannten Vors&auml;tze steht h&auml;ufig eine 
                        Gewichtsreduktion, und somit begegnet uns das Thema gerade jetzt &uuml;berall 
                        &ndash; sei es in Frauenzeitschriften, aber auch allen anderen Bl&auml;ttern im 
                        Medienwald. Nach den Weihnachtsfeiertagen sind die Zeitschriften voll mit 
                        gro&#223;artigen Wunderdi&auml;ten, mit Werbung f&uuml;r verschiedenste Pr&auml;parate 
                        und nat&uuml;rlich auch mit Berichten von Menschen, die zig Kilos auf diese Weise 
                        verloren haben wollen. Und wer kennt sie nicht, die vorher- und nachher-Bilder, 
                        in denen diese Leute stolz zeigen, wie viel zu gro&#223; ihr Hosenbund jetzt ist! 
                        In einem neuen Beitrag unter der Rubrik &#187;Ganzheitliche Gesundheit&#171; habe versucht, 
                        zusammenzustellen, welche Ma&#223;nahmen zum Abnehmen sinnvoll und erfolgversprechend 
                        sind &ndash; und welche nicht.<br />
