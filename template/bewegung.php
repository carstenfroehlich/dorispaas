                        Die Gesundheit eines Menschen steht auf zahlreichen Säulen (bitte lesen Sie hierzu auch den 
                        Beitrag &#187;<a href="ganz-saeulenmodell" target="_blank">Die Säulen der Ganzheitlichen 
                        Gesundheit</a>&#171;) wie die Ernährung, Verdauung, Stress, Rauchen und Alkoholkonsum und 
                        vieles andere mehr. Eine der (mit) wichtigsten Säulen ist eine ausreichende Bewegung. 
                        Allgemein ist bekannt, dass die &#187;Couch-Potatoes&#171;, also Menschen, die viel Zeit 
                        auf ihrer Couch verbringen und sich sehr wenig bewegen, nicht nur zu Übergewicht neigen, 
                        sondern auch einen insgesamt schlechteren Gesundheitszustand aufweisen.
                        <br />
                        <br />
                        Auf der anderen Seite stehen die extremen Leistungssportler, die zwar in jüngeren Jahren 
                        meist schlank sind und gesund aussehen, oftmals aber nicht, wie man erwarten könnte, 
                        ein hohes Alter erreichen. Probleme mit den Gelenken oder sogar ihren Organen durch die 
                        permanente Überlastung sind hier keine Seltenheit.
                        <br />
                        <br />
                        Wie also verhält man sich gesund, was ist sinnvoll, um den Körper optimal zu stärken und zu 
                        unterstützen und &ndash; vor allem &ndash; wie kann man das erklären?
                        <br />
                        <br />
                        <a id="bewegung"></a>
                        <hr />
                        <h5>Bewegung ist gesund</h5>
                        <hr />
                        Schauen wir einmal zurück zu unseren Vorfahren, denn sowohl unser Bewegungsapparat mit all 
                        seinen Knochen, Muskeln und Sehnen, als auch das Verdauungssystem und sämtliche Organe sind 
                        im Grunde noch genauso aufgebaut wie die Körper der Menschen vor vielen Tausend Jahren.
                        <br />
                        <br />
                        Diese Menschen waren den ganzen Tag in Bewegung: sie mussten sich ihre Nahrung selbst 
                        sammeln &ndash; einen Supermarkt, in dem man sich alles in großer Auswahl einfach in 
                        den Einkaufswagen legen und mit dem Auto nach Hause fahren kann, gab es nicht. Auch ihre 
                        Behausungen mussten sie mit großem Energieaufwand selber bauen, und oft rissen widrige 
                        Wetterbedingungen diese wieder ein, so dass sie erneuert werden mussten. Wenn die 
                        Nahrungsquellen in der Umgebung versiegten, mussten wie weiterwandern und ihr Lager an 
                        einem anderen Ort neu aufschlagen. So waren Übergewicht und Rückenschmerzen durch 
                        diese Lebensweise, die alle Teile des <b>Bewegungsapparates</b> beanspruchte, eher 
                        nicht an der Tagesordnung.
                        <br />
                        <br />
                        Auch ihre <b><a href="verdauung" target="_blank">Verdauung</a></b> wird mit Sicherheit 
                        besser funktioniert haben als bei den meisten von uns. Sie aßen ja nicht nur eine sehr 
                        viel gesündere Kost (Verknüpfung!) mit hauptsächlich pflanzlichen und wenig tierischen 
                        Anteilen und damit sehr viel größeren Ballaststoffmengen, als wir es heute gewohnt sind. 
                        Auch ihr Darm arbeitete sehr viel effektiver, denn für einen optimalen Transport der 
                        Speisen durch Magen und Darm ist eine kontinuierliche Bewegung des ganzen Körpers unerlässlich. 
                        Jeder Darm &ndash; sowohl der des vorzeitlichen Menschen als auch der unsrige &ndash; ist 
                        faul. Erst die Bewegungen der Bauchmuskulatur und der Atmung mit dem Zwerchfell regen den 
                        Darm zu der erforderlichen Bewegung (Peristaltik) an, um den Speisebrei zum Ausgang zu befördern.
                        <br />
                        <br />
                        Und nur eine optimale Verdauung bedingt auch eine gesunde 
                        <b><a href="darmschleimhaut" target="_blank">Darmschleimhaut</a></b> 
                        und &ndash; damit zusammenhängend &ndash; eine gute Balance unserer 
                        <b><a href="darmfloragrundsatz" target="_blank">Darmflora</a></b>.
                        <br />
                        <br />
                        Sich einfach nur auf die Couch zu legen und zu erwarten, dass die Verdauung von alleine funktioniert 
                        und unsere Darmflora (und damit auch unser <a href="ganz-immun" target="_blank">Immunsystem</a>) 
                        gesund ist und bleibt, ist illusorisch.
                        <br />
                        <br />
                        Auch die <b>Atmung</b> ist im wahrsten Sinne des Wortes nur durch Bewegung richtig in Bewegung. 
                        Wenn wir liegen, atmen wir wesentlich flacher, als wenn wir uns bewegen. Je mehr wir uns 
                        anstrengen, desto tiefer wird die Atmung: die frische Luft gelangt bis in die untersten 
                        Lungenspitzen und die verbrauchte Luft wird effektiv ausgeatmet. Unsere Lunge ist genauso 
                        wie Leber, Niere oder Haut ein Entgiftungsorgan, und nur mit einer tiefen Atmung können die 
                        Giftstoffe mit der Ausatemluft entsorgt werden. Bei einer flachen Atmung würden diese Stoffe 
                        im Körper verbleiben und alle Körperfunktionen belasten.
                        <br />
                        <br />
                        Gleichzeitig reichert die tiefere Atmung das Blut mit mehr Sauerstoff an, wodurch sowohl 
                        alle Körperzellen als auch das Gehirn besser versorgt und leistungsfähiger werden.
                        <br />
                        <br />
                        <a id="menge"></a>
                        <hr />
                        <h5>Wie viel Bewegung ist gesund? </h5>
                        <hr />
                        Weder zu wenig noch zu viel Bewegung ist förderlich für die Gesundheit. Aus den oberen Ausführungen 
                        geht bereits hervor, dass ein gesundes Mittelmaß offensichtlich das Beste für den Körper ist und 
                        wo dieses Mittelmaß liegt, ist auch keineswegs genormt und für alle Menschen gleich. Es leuchtet ein, 
                        dass jüngere Menschen sich mehr bewegen können und sollen als alte Menschen. Aber es gibt ja durchaus 
                        auch in den verschiedenen Altersgruppen deutliche Unterschiede wie z.B. die &#187;fitten Alten&#171; 
                        oder die Gebrechlicheren. Jeder muss also sein eigenes Optimum finden, darf sich hierbei allerdings 
                        ruhig die Latte ein wenig höher legen und sich nach und nach aus der &#187;Wohlfühlzone&#171; heraus 
                        BEWEGEN.
                        <br />
                        <br />
                        Die Betonung liegt hier ganz bewusst auf BEWEGUNG und nicht auf Sport. Sicherlich ist es für viele 
                        Menschen schön, sich ab und an so richtig auszupowern, aber für manche von uns ist ein solcher Gedanke 
                        nicht reizvoll und auch nicht möglich. Tägliche, kleinere Bewegungssequenzen können nicht nur in der 
                        Summe ebenso viel bedeuten, wie ein oder zwei Stunden Sport in der Woche. Diese kontinuierlichen 
                        Bewegungen bringen insbesondere für den Darm sogar einen sehr viel deutlicheren Effekt: wie oben 
                        gesagt, benötigt der faule Darm kontinuierliche Anregung, um die gesunde, tägliche Ausscheidung zu 
                        gewährleisten. Es ist nicht genug, wenn Sie nur einige wenige Male Sport treiben &ndash; auch 
                        wenn Sie sich hier so richtig anstrengen &ndash; denn es reicht ja auch nicht, nur ein oder zwei 
                        Mal pro Woche <a href="stuhlgang" target="_blank">Stuhlgang</a> zu haben.
                        <br />
                        <br />
                        Ich will Sie von Ihren Besuchen im Fitnessstudio nicht abhalten. So lange Sie es nicht übertreiben 
                        und Ihnen diese sportliche Tätigkeit gefällt, ist sie positiv zu bewerten. Die <b>kontinuierliche 
                        Bewegung</b> &ndash; im Idealfalle alle halbe oder alle Stunde &ndash; können diese Besuche zwar 
                        schön ergänzen, aber nicht vollständig ersetzen.
                        <br />
                        <br />
                        <a id="zeiten"></a>
                        <hr />
                        <h5>Der richtige Zeitpunkt für Bewegung</h5>
                        <hr />
                        Um effektiv zu sein, sollten möglichst viele, gerne auch kleinere Bewegungseinheiten über den Tag 
                        verteilt werden. Jede und jeder, die oder der unter Bewegung den Besuch eines Fitnessstudios oder 
                        das Fußballtraining am Wochenende versteht, tut schon einmal mehr als jemand, der sich gar nicht bewegt. 
                        Aber, wie gesagt, es ist die Kontinuität, die Bewegung so effektiv macht. Aus diesem Grunde ist 
                        es zu überlegen, welche Möglichkeiten man hat, um eben diese Stetigkeit zu erreichen und dies 
                        auch noch in den eigenen Tagesablauf einzubauen. 
                        <br />
                        <br />
                        Wenn man z.B. berufstätig ist, sind andere Voraussetzungen gegeben, als wenn man Schüler/in, 
                        Student/in, Hausfrau/mann oder Rentner/in ist. Alleinstehende haben einen anderen Tagesrhythmus 
                        als Familienmenschen &ndash; jeder muss also zunächst einmal schauen, wie sich Bewegung in die 
                        tägliche Routine einbauen lässt. Diese Überlegung muss natürlich kombiniert werden mit der 
                        Frage nach der Art der Bewegung.
                        <br />
                        <br />
                        <a id="art"></a>
                        <hr />
                        <h5>Die richtige Art von Bewegung</h5>
                        <hr />
                        Diese Frage kann man nicht allgemeingültig beantworten, denn jeder kann nur für sich selbst die für 
                        ihn optimale Bewegung finden. Für jeden allerdings ist wichtig, dass Bewegung nicht nur den eigenen 
                        Vorlieben, sondern, wie oben ausgeführt, auch den eigenen Möglichkeiten angepasst sein sollte. 
                        Jede sich selbst unter Zwang und Pflichtbewusstsein auferlegte Bewegung bedeutet <b>Stress</b> 
                        &ndash; und Stress ist für die Gesundheit kontraproduktiv (bitte lesen Sie hierzu auch den Beitrag 
                        &#187;<a href="ganz-entspannung" target="_blank">Entspannung</a>&#171;).
                        <br />
                        <br />
                        Bewegung, die wirklich Spaß macht, wirkt entspannend und hat die Chance, über lange Zeit erfolgreich 
                        durchgehalten zu werden.
                        <br />
                        <br />
                        Somit kann die für den einen die in halbstündigen Frequenzen durchgeführte, kleine Atemübung das 
                        Richtige sein, für den anderen eine gelegentliche gymnastische Übungen. Und die sattsam bekannte 
                        Nutzung der Treppe statt des Auszuges ist sicherlich für fast alle eine hervorragende Möglichkeit 
                        (unter vielen anderen). 
                        <br />
                        <br />
                        Es darf auch die Fahrt mit dem Fahrrad (natürlich gerne auch ohne Blümchen) 
                        zur Arbeit sein &ndash; und sei es nur bei schönem Wetter, 
                        und selbstverständlich eignen sich das Fahrrad oder auch die eigenen Füße auch zum Brötchenholen 
                        sehr viel besser. Dass hierbei kostenlos auch noch die Umwelt geschont wird, steht auf einem ganz 
                        anderen Blatt.
                        <br />
                        <br />
                        Aber auch Wandern, Schwimmen, (Nordic) Walking, Skaten und viele weitere Möglichkeiten sind 
                        gegeben &ndash; man muss sich nur einmal hinsetzen und überlegen, 
                        was einem Spaß machen könnte.
                        <br />
                        <br />
                        <a id="darmgymnastik"></a>
                        <hr />
                        <h5>Darmgymnastik</h5>
                        <hr />
                        Neben dem Sport, den man normalerweise nur gelegentlich, beispielsweise am Feierabend oder am Wochenende durchführt,
                        ist es aber für einen geregelten Stuhlgang erforderlich, auch zwischendurch im Laufe des Tages immer wieder Bewegungen
                        für den Darm durchzuführen. Erfolgen die Anregungen durch den (sehr zu befürwortenden) Sport nämlich nur sporadisch, bleiben 
                        die Speisen viel zu lange an einer Stelle liegen. Dies kann auf Dauer zu erheblichen Beschwerden (nicht nur) der Verdauung führen. 
                        <br />
                        <br />
                        Deshalb ist das &#187;Geheimnis&#171; einer geregelten Verdauung nicht nur die &#187;normale&#171; sportliche Betätigung für die 
                        allgemeine körperliche Fitness und natürlich auch der Verzehr einer ballaststoffreichen Nahrung mit einem überwiegenden Anteil an 
                        pflanzlichen Lebensmitteln. Auch ein kontinuierliches Bewegungsverhalten, bei dem mindestens alle 30 &ndash; 60 Minuten wenigstens 
                        kleine Atem- und/oder Bewegungsübungen ausgeführt werden, gehören neben den spezifischen Behandlungsmitteln und -maßnahmen zur Behandlung 
                        einer jeden Verdauungstörung und selbstverständlich auch zur Prophylaxe, um gar nicht erst zu erkranken. Das Ganze nennt 
                        sich &#187;Darmgymnastik&#171;. Lesen Sie hierzu gerne 
                        den Beitrag &#187;<a href="darmgymnastik" target="_blank">Darmgymnastik</a>&#171; auf dieser Website. Sehr viel mehr zu diesem Thema ist in dem Buch
                        <a href="book-darmgymnastik" target="_blank">&#187;Darmgymnastik &ndash; Bewegung &#38; bei Verdauungsbeschwerden&#171;</a> zusammengetragen.
                        <br />
                        <br />
                        <a id="sozial"></a>
                        <hr />
                        <h5>Bewegung als sozialer Faktor</h5>
                        <hr />
                        Doch, Sie haben richtig gelesen: Bewegung kann Ihre sozialen Kontakte fördern. Der eine mag es vielleicht, 
                        für sich alleine spazieren zu gehen, andere brauchen Gesellschaft und sind dann u.U. in einem 
                        Verein Gleichgesinnter gut aufgehoben.
                        <br />
                        <br />
                        Auch wenn Sie alleine spazieren gehen, werden Sie den einen oder anderen Gleichgesinnten treffen, 
                        und nach und nach können sich daraus ganz neue Kontakte ergeben: zunächst grüßt man sich, wenn 
                        man sich mehrmals begegnet ist, dann hält man ein wenig Small Talk, und später kann es sein, 
                        dass man sich verabredet. Wenn man Kinder hat oder einen Hund besitzt, ist man auf jeden Fall 
                        viel draußen &ndash; Eltern und Hundebesitzer kommen immer ins Gespräch.
                        <br />
                        <br />
                        In Vereinen haben die Mitglieder ohnehin die gleichen Interessen, so dass sich hier sehr 
                        viele Gesprächsthemen ergeben.
                        <br />
                        <br />
                        Je mehr Sie sich bewegen und je aktiver Sie sind &ndash; insbesondere draußen an der frischen Luft 
                        &ndash; desto zugewandter werden Sie auch Ihren Mitmenschen gegenüber sein und diese Ihnen 
                        Interesse entgegen bringen.
                        <br />
                        <br />
                        Es ist erwiesen, dass Menschen, die über ein ausgeprägtes soziales Umfeld verfügen, gesünder sind 
                        als solche, die in ihren eigenen vier Wänden vereinsamen. Für manche Menschen kann es eine große 
                        Überwindung bedeuten, aus ihrem Haus und damit aus sich selbst herauszukommen &ndash; die Bewegung 
                        ist dafür ein wunderbares Mittel!
                        <br />
                        <br />
                        <a id="fazit"></a>
                        <hr />
                        <h5>Fazit</h5>
                        <hr />
                        Jede Art und jede Menge von Bewegung nützt der Gesundheit &ndash; zu jeder Gelegenheit. Ziehen Sie eine 
                        Bilanz, wie und wie viel Sie sich bisher bewegt haben, wie Sie diese Einheiten steigern können und 
                        wie Sie dies sinnvoll in Ihren Tagesablauf einbauen können.
                        <br />
                        <br />
                        Welche Bewegung &ndash; sei es in Form von moderaten kleinen Übungen zwischendurch oder eher als 
                        &#187;sportliche&#171; Betätigung &ndash; ist möglich UND würde Ihnen gefallen? Testen Sie verschiedene 
                        Möglichkeiten. Das, was keinen Spaß macht, hat wenig Chance, beibehalten zu werden. Also probieren 
                        Sie andere Alternativen. Schauen Sie doch einmal, was Ihre Freunde in dieser Richtung machen und 
                        schließen Sie sich für ein erstes Kennenlernen an. Nicht alles, was Sie versuchen, ist in Stein 
                        gemeißelt, aber vielleicht bringt der eine oder andere Versuch ganz neue Erkenntnisse.
                        <br />
                        <br />
                        Übrigens: auch jede Art von Tätigkeit, die man bisher im Sitzen (oder gar Liegen) verrichtet hat, 
                        lässt sich auch im Stehen oder Gehen erledigen. Warum müssen Sie denn die Akteure des Fußballspiels 
                        im Fernsehen von der Couch aus anfeuern? Versuchen Sie das, zumindest in besonders spannenden Momenten, 
                        doch mal im Stehen: Sie haben einen wesentlich größeren Aktionsradius und &ndash; vielleicht &ndash; 
                        verhilft es ja zum Tor. Ganz bestimmt aber hilft es Ihrer Gesundheit, denn jedes bisschen mehr an Bewegung 
                        ist gesund.
