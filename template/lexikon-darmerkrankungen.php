                                <td class="q">
                                    Darmspiegelung
                                </td>
                                <td class="a">
                                    Endoskopische Untersuchung des Dickdarms. 
                                    <br />
                                    Vorbereitung: Gründliche Darmreinigung (meistens mit Glaubersalz). 
                                    Der Patient muss nüchtern sein und darf mindestens 10 Stunden vorher 
                                    nicht rauchen.
                                    <br />
                                    Durchführung: Der Patient liegt auf der Behandlungsliege auf der 
                                    Seite. Der Arzt (günstigstenfalls der Gastroenterologe) führt 
                                    ein so genanntes Koloskop (Sichtgerät) durch den After in den 
                                    Darm ein und schiebt dieses vorsichtig nach oben. Mit einer Darmspiegelung 
                                    gelangt der Arzt maximal bis in das letzte Stück des Dünndarms 
                                    (durch die Ileozökal-Klappe) und folgt dabei vorsichtig jeder 
                                    Windung des Darms. Auf diesem &#187;Hinweg&#171; erfolgt eine erste, 
                                    grobe Sichtung. Anschließend wird das Sichtgerät dann langsam 
                                    wieder zurückgezogen, wobei eine sehr viel gründlichere 
                                    Sichtung und Kontrolle erfolgt.
                                    <br />
                                    Mit geeigneten Geräten, die mit dem Sichtgerät zusammenhängen, 
                                    können ggf. Proben der Darmschleimhaut entnommen werden oder auch 
                                    Polypen (--> siehe dort) entfernt werden.
                                    <br />
                                    Eine Darmspiegelung kann sowohl mit als auch ohne Sedierung (Beruhigungsspritze) 
                                    durchgeführt werden. Wird auf die Sedierung  verzichtet, können 
                                    interessierte Patienten die Aufnahmen des Sichtgerätes auf 
                                    einem Bildschirm mitverfolgen. 
                                    <br />
                                    Die Darmspiegelung gilt als hervorragende Darmkrebsprophylaxe (--> siehe 
                                    Darmkrebs), da im Zuge einer Darmspiegelung kleine Polypen, die ggf. 
                                    zu Krebs entarten könnten, rechtzeitig erkannt und entfernt werden 
                                    können.
                                    <br />
                                    Im Anschluss an eine Darmspiegelung darf sofort wieder Nahrung aufgenommen 
                                    werden. Nach einer Sedierung darf der Patient frühestens nach 24 
                                    Stunden wieder Auto fahren und/oder Maschinen bedienen!
                                </td>
