                                    in den Dünndarm aufsteigen. Die Ileozökalklappe soll dieses 
                                    Aufsteigen eigentlich mit ihrer Ventilfunktion verhindern. Beispielsweise 
                                    bei ständigen Blähungen jedoch wird die Klappe aufgedrückt, 
                                    und Bakterien können in den Dünndarm wandern. Diese Bakterien, 
                                    deren Funktionen im Dickdarm meist sinnvoll sind, arbeiten im Dünndarm, 
                                    der völlig andere Aufgaben als der Dickdarm hat, kontraproduktiv, 
                                    wodurch Beschwerden entstehen. Diese können neben einer Schädigung 
                                    der Dünndarmschleimhaut und deren Zotten und Mikrozotten auch 
                                    Verdauungsbeschwerden wie Blähungen und Durchfälle sein, die 
                                    keinen Nahrungsmittel-Unverträglichkeiten oder -Allergien zugeordnet 
                                    werden können.
                                    <br />
                                    Weitere Bezeichnungen der DDFB sind &#187;small bowel bacterial overgrowth&#171; 
                                    und &#187;small intestinal bacterial overgrowth syndrome (SIBO)&#171;.
                                    <br />
                                    Diagnose: Die Diagnose der DDFB erfolgt über eine Wasserstoff-Atemtest 
                                    mit Glukose-Lösung und evtl. durch die Interpretation des Verlaufs 
                                    der Messkurve bei Atemtests aufgrund verschiedener Kohlenhydrat-Malabsorptionen.
                                    <br />
                                    Behandlung: Die Behandlung einer DDFB erfolgt meist mit Antibiotika, 
                                    die die Bakterien abtöten sollen. Es gibt jedoch auch erprobte alternative 
