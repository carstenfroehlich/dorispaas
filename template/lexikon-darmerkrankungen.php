                                    Vorsorge (Darmspiegelung --> siehe dort), bei der die noch völlig 
                                    unproblematischen Polypen abgetragen werden.
                                    <br />
                                    Risikofaktoren können eine genetische Veranlagung sein, weiterhin 
                                    chronisch Entzündliche Darmerkrankungen (Morbus Crohn --> siehe dort), 
