                                <td class="q">
                                    Divertikel (hier des Darms)
                                </td>
                                <td class="a">
                                    Sackförmige Ausstülpungen aus der Darmwand &ndash; meistens 
                                    im Dickdarm. Sie entstehen durch Schleimhaut, die sich durch Lücken 
                                    in der Darmwandmuskulatur nach außen drängt. Ursache kann 
                                    hier neben einer Veranlagung und fortgeschrittenem Alter auch eine 
                                    falsche Ernährung mit zu wenig Ballaststoffen sein.
                                    <br />
                                    Divertikel bleiben meist ohne Beschwerden, erst wenn sich Stuhl in 
                                    den Divertikeln ansammelt und sie sich entzünden, können 
                                    sie teils heftige Beschwerden erzeugen.
                                    <br />
                                    Eine ballaststoffreiche Ernährung und optimale Stuhlkonsistenz 
                                    stellen eine gute Prophylaxe gegen Beschwerden dar. Bei andauernden 
                                    Schmerzen und Beschwerden müssen die Divertikel u.U. operativ 
                                    entfernt werden.
                                    <br &>
                                    Das beschwerdefreie Vorhandensein von Divertikeln nennt sich Divertikulose, 
                                    eine Entzündung der Divertikel ist die Divertikulitis.
