                                <td class="q">
                                    Darmflora
                                </td>
                                <td class="a">
                                    (Fachbegriffe: Mikrobiom, Mikrobiota) Bakterien, die den Darm besiedeln. 
                                    Die Darmflora enthält nützliche, 
                                    aber auch krankmachende Bakterien und Pilze. In einer gesunden Darmflora 
                                    überwiegen die nützlichen Arten, die durch ihre Übermacht 
                                    die krankmachenden Arten unter Kontrolle halten, so dass diese ihr 
                                    krankheitserregendes Potenzial nicht entfalten können.
                                    <br />
                                    Die Darmflora besteht aus der so genannten Leitkeimflora, die aus der 
                                    um die Geburt herum erworbenen Keimbasis besteht und den obligaten 
                                    Keimen &ndash; also den lebenslang als ganz individuelle Keimbasis 
                                    vorhandenen Mikroorganismen und darüber hinaus den passageren 
                                    Keimen, die durch Nahrung und/oder Infektion aufgenommen werden. Die 
                                    passageren Keime besiedeln die Darmflora nur mehr oder weniger vorübergehend.
                                </td>
