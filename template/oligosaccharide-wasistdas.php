                        Wie bei den bekannten Unvertr&auml;glichkeiten von Laktose (Milchzucker) und Fruktose 
                        (Fruchtzucker) gibt es auch eine Unvertr&auml;glichkeit von bestimmten 
                        Mehrfachzuckern &ndash; den Oligosacchariden. 
                        <br />
                        <br />
                        Oligosaccharide sind aus 3-9 Einfachzuckern (Monosacchariden) gleicher oder 
                        verschiedener Art zu Ketten zusammengesetzt. Wie alle Mehrfachzucker (Disaccharide, 
                        Oligosaccharide und Polysaccharide) sind f&uuml;r die Verdauung von Oligosacchariden 
                        Enzyme erforderlich, die daf&uuml;r sorgen, dass diese Kohlenhydrate in die einzelnen 
                        Bausteine (Monosaccharide) aufgespalten werden, um durch die Zellzwischenr&auml;ume 
                        der D&uuml;nndarmschleimhaut aufgenommen und ins Blut gelangen zu k&ouml;nnen. 
                        <br />
                        <br />
                        Fehlen diese f&uuml;r jeden Mehrfachzucker spezifischen Enzyme oder sind sie nicht 
                        in einer der Verzehrmenge entsprechenden Menge vorhanden, gelangen die unaufgespaltenen 
                        Nahrungsbestandteile in den Dickdarm, wo sie von Darmbakterien vergoren werden. 
                        Dabei entstehen mehr oder weniger gro&#223;e Mengen von Gasen und S&auml;uren als 
                        Abfallprodukte. Dies f&uuml;hrt zu den f&uuml;r alle Nahrungsmittel-Unvertr&auml;glichkeiten 
                        typischen Beschwerden wie Bl&auml;hungen, Bauchschmerzen und Durchf&auml;lle. Manche 
                        Menschen haben mehr, andere weniger Probleme, was wahrscheinlich mit der Zusammensetzung 
                        der individuellen Darmflora zusammenh&auml;ngt.
                        <br />
                        <br />
                        Insbesondere die Verdauung der Fruktane (Verbindungen aus einem Saccharose- und 
                        mehreren Fruktosemolek&uuml;len) und der Galaktane (Verbindungen aus mehreren 
                        Galaktose-Bausteinen) ist problematisch - ganz besonders bei der Raffinose, Stachyose 
                        und Verbascose, denn f&uuml;r diese kurzkettigen Oligosaccharide werden im menschlichen 
                        Verdauungssystem keine Enzyme gebildet. Diese Mehrfachzucker sind in allen Kohlsorten 
                        und den H&uuml;lsenfr&uuml;chten enthalten &ndash; und wer kennt nicht Spr&uuml;che 
                        wie &#187;Jedes B&ouml;hnchen gibt ein T&ouml;nchen&#171; und &auml;hnliche?
                        <br />
                        <br />
                        <br />
                        <hr />
                        <h5>Bekanntheitsgrad der Oligosaccharid-Unvertr&auml;glichkeit</h5>
                        <hr />
                        Die Unvertr&auml;glichkeiten von Laktose, aber auch von Fruktose und Sorbit sind 
                        gl&uuml;cklicherweise bereits gut im Bewusstsein der &Auml;rzte angekommen. Damit 
                        werden auch schnellere Diagnosen bei den Betroffenen gestellt als noch vor einigen 
                        Jahren. Die Oligosaccharid- Unvertr&auml;glichkeit ist jedoch in Europa leider 
                        noch so gut wie unbekannt. 
                        <br />
                        <br />
                        In Australien gibt es Untersuchungen der &Auml;rztin Dr. Sue Shepheard, die die 
                        Gruppe der Oligosaccharide und verschiedene, f&uuml;r Unvertr&auml;glichkeiten 
                        h&auml;ufig verantwortliche Mono- und Disaccharide, aber auch die Polysaccharide 
                        (Ballaststoffe) unter dem Oberbegriff FODMAPS&#153; zusammenfasst und eine entsprechende 
                        Di&auml;t empfiehlt, um Beschwerden vorzubeugen (<a href="http://shepherdworks.com.au/disease-information/low-fodmap-diet" target="_blank">http://shepherdworks.com.au/disease-information/low-fodmap-diet</a>).
                        <br />
                        <br />
                        Da aber auch bei uns immer mehr Menschen Probleme mit diesen Kohlenhydraten haben, 
                        wird es Zeit, auch hier die Oligosaccharid-Unvertr&auml;glichkeit ins Licht der 
                        &Ouml;ffentlichkeit zu r&uuml;cken, um den Patienten lange Leidenswege zu ersparen.
                        <br />
