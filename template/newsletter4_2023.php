                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Entspannung/Entspannung)</i>
                        <br />
                        Gerade der Winter l&auml;dt dazu ein, uns zu entspannen. Vieles in unserem Umfeld steht dem aber entgegen. Angefangen mit dem trotz der zur&uuml;ckgestellten 
                        Uhren oft (zu) fr&uuml;hen Aufstehen und den Wegen zur und von der Arbeit im Dunkeln. Auch die K&auml;lte kann stressen &ndash; drau&#223;en, weil die Sonne seltener 
                        scheint und weniger wärmt und in der Wohnung, weil wir (berechtigterweise) Energie sparen und die Thermostate um ein paar Grad herunterdrehen. Nat&uuml;rlich 
                        k&ouml;nnen Sie sich nicht den ganzen Winter lang unter die Decke und in »Ihre H&ouml;hle« zur&uuml;ckziehen und nicht mehr Ihren Pflichten nachgehen. Sie sollten 
                        aber immer dort, wo es m&ouml;glich ist, Ihren Bed&uuml;rfnissen folgen und ggf. den Tagesablauf dem nat&uuml;rlichen Biorhythmus anpassen. Auch bei der 
                        Ern&auml;hrung gibt es M&ouml;glichkeiten, trotz Verdauungsproblemen, Unvertr&auml;glichkeiten oder bakteriellen Fehlbesiedelungen gelegentlich ohne gro&#223;e Reue 
                        den weihnachtlichen Gel&uuml;sten nachzugeben.  Mit vielen kleinen, vor allem aber klugen Schritten k&ouml;nnen auch Sie &#187;Ihre kleine Winterruhe&#171; bekommen.
