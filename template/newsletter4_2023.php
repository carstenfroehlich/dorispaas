                        (Nicht nur) zur Winterzeit: Wenn Sie tats&auml;chlich einmal ein scheinbar unbezwingbares Bed&uuml;rfnis &uuml;berkommt, ein &#187;verbotenes&#171; Nahrungsmittel 
                        essen zu wollen, d&uuml;rfen Sie ab und an durchaus auch einmal &#187;s&uuml;ndigen&#171; &ndash; insbesondere, wenn Sie ansonsten im Gro&#223;en und 
                        Ganzen konsequent sind und es Ihnen und Ihrem Darm im Allgemeinen gut geht. Nat&uuml;rlich muss Ihnen bewusst sein, dass auf ein gelegentliches &#187;alle F&uuml;nfe 
                        gerade sein Lassen&#171; dann eventuell Beschwerden folgen k&ouml;nnen (aber durchaus nicht immer zwangsl&auml;ufig folgen m&uuml;ssen). Aber w&auml;gen Sie ab, 
                        ob sich das &#187;Kosten-Nutzen-Verh&auml;ltnis&#171; lohnt &ndash; sprich: das Verh&auml;ltnis von m&ouml;glichen Symptomen und ausgekostetem Genuss. 
                        Wenn Sie meinen, dass ein wenig Bauchgrummeln, das vielleicht einen Tag lang anh&auml;lt, es wert ist, eine Mahlzeit mit einem eher unvertr&auml;glichen Lebensmittel 
                        zu verzehren, dann essen Sie dieses Lebensmittel. Sie &#187;f&uuml;ttern&#171; damit auch Ihre Seele &ndash; und die hat einen gro&#223;en Einfluss auf Ihren Bauch.
