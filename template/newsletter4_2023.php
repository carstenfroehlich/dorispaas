                        <h5>Ausgabe 67 (Winter 2023)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2023-04-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Es ist wieder soweit: die Kraniche sind in ihr Winterquartier gezogen, um in warmen Gegenden Nahrung zu finden. Tiere wie z.B. die sprichw&ouml;rtlichen Murmeltiere oder 
                        Siebenschl&auml;fer halten Winterschlaf. Sie senken ihre K&ouml;rpertemperatur ab und reduzieren so ihren Energieverbrauch, um mit den im Herbst angefressenen Fettreserven 
                        bis zum n&auml;chsten Fr&uuml;hjahr &uuml;berleben zu k&ouml;nnen. Andere Tiere, wie u.a. die B&auml;ren oder die Eichh&ouml;rnchen halten zumindest eine Winterruhe, aus 
                        der sie nur sporadisch f&uuml;r kurze Zeit aufwachen, um ein wenig Futter zu sich zu nehmen. Auch wir Menschen sehnen uns danach, uns in der kalten Jahreszeit unter eine warme Decke 
                        zu kuscheln, einen hei&#223;en Tee zu genie&#223;en oder zu d&ouml;sen, und wir haben vermehrt das Bed&uuml;rfnis, kalorienreiche Winterspezialit&auml;ten zu essen. All dies ist ganz 
                        tief in unseren Genen verankert: die Sehnsucht nach n&auml;hrenden Speisen, w&auml;rmender Kleidung und Decken und nach Entspannung. Auch wenn wir beim Essen normalerweise 
                        unsere Gewohnheiten haben, um nicht zu viel Gewicht zuzulegen oder weil wir aufgrund von eventuellen Erkrankungen 
                        oder Unvertr&auml;glichkeiten nur einen eingeschr&auml;nkten Speisezettel haben,  überf&auml;llt uns jetzt mit sch&ouml;ner Regelm&auml;&#223;igkeit die Lust auf Gehaltvolles,
                        S&uuml;&#223;es und Fettiges &ndash; und wenn wir dem (zu) oft nachgeben, beschwert sich schon bald der Bauch. Tun wir dies aber nicht, kann (zu) viel Disziplin auch Stress bedeuten, 
                        der sich leider ebenfalls &uuml;ber unsere Verdauung melden kann.
