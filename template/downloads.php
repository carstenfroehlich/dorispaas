                    <h5>Bilanz-Protokoll</h5> 
                        <hr />
                        <a href="<?php echo FILES_PATH; ?>bilanzprotokoll-www-dorispaas-de.pdf">
                            <img src="<?php echo IMG_PATH; ?>bilanzprotokoll.png" alt="Bilanzprotokoll" class="left" />
                        </a>
                        <br />
                        Viel zu oft bewerten wir unser Befinden einseitig und nehmen am Ende eines Tages eher wahr, wenn wir uns 
                        nicht so gut gefühlt haben, als wenn es uns gut ging. Hier ist es hilfreich, ein Bilanzprotokoll zu führen.
                        Bitte ziehen Sie an jedem Abend eine Bilanz, wie Ihr Tag war. Erinnern Sie sich nicht nur an eventuelle 
                        Beschwerden, sondern auch an die guten Erlebnisse und die guten Gefühle. Bilden Sie daraus einen Mittelwert 
                        zwischen 1 (für sehr schlecht) und 10 (für richtig gut) und tragen ein Kreuzchen in das entsprechende Tagesfeld ein. 
                        Anhand des sich daraus ergebenden Kurvenverlaufs 
                        können Sie überprüfen, wie sich Ihre Beschwerden entwickeln. Beachten Sie, dass kleine &#187;Einbrüche&#171; 
                        normal sind und freuen sich über die Aufwärtsbewegungen der Kurve.
