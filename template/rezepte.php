                        <h3>Crunchy-Erdnussbutter ohne Palmöl</h3> 
                        <br />
                        Ärgern Sie sich auch, dass in den meisten Erdnussbutter-Produkten neben vielen anderen Zutaten 
                        meist auch Palmöl enthalten ist? Dann machen Sie doch Ihre Erdnussbutter selbst ohne 
                        überflüssige Zutaten und Zusätze &ndash; und das auch noch in Bioqualität! Das Rezept ist mehr
                         als simpel und in wenigen Minuten zubereitet:
                        <br />
                        <br />
                        <b>Zutaten</b>
                        <br />
                        <b>&#149;</b> 250g (1 kleines Glas) Bio-Erdnussmus
                        <br />
                        <b>&#149;</b> 100g Bio-Erdnüsse, gesalzen und geröstet
                        <br />
                        <b>&#149;</b> 1/2 gestrichener Teelöffel Salz
                        <br />
                        <br />
                        <b>Zubereitung</b>
                        <br />
                        <b>&#149;</b> Die Erdnüsse in einem leistungsfähigen Mixer klein hacken
                        (im Thermomix 1 &ndash; 2 Sekunden). 
                        <br />
                        Je gröber (kürzer) Sie die Nüsse hacken, 
                        desto mehr Crunchy-Effekt wird erzielt. Ggf. reicht es auch, die Nüsse in einer 
                        festschließenden Tüte mit dem Nudelholz kleinzuhacken.
                        <br />
                        <b>&#149;</b> Das Nussmus in einen Behälter füllen und mit einem langen Löffel 
                        gründlich mit den Nüssen und dem Salz vermischen.
                        <br />
                        Wenn Sie ein Schraubgefäß verwendet haben, kann die Erdnussbutter gleich 
                        in diesem in den Kühlschrank gestellt und aufbewahrt werden. Ansonsten 
                        füllen Sie die Masse in ein Deckelgefäß, das Sie in den Kühlschrank 
                        stellen können.
                        <br />
                        <br />
                        Probieren Sie doch mal die amerikanische Variante: bestreichen Sie ein Brot mit Erdnussmus 
                        und fügen ein wenig Erdbeermarmelade (nicht zu viel!) darüber &ndash; ein besonders leckers Geschmackserlebnis!
