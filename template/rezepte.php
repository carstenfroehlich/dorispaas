                        <h3>Gluten-, laktose-, weizen- und zuckerfreies Brot</h3> 
                        <br />
                        <b>Zutaten</b>
                        <br />
                        <b>&#149;</b> 660 g Mehlmischung (ca. 50% Vollkorn-Buchweizenmehl, 30% Erdmandelmehl, 20% geschrotete Leinsamen)
                        <br />
                        <b>&#149;</b> 1/2 Päckchen Weinstein-Backpulver o.Ä.
                        <br />
                        <b>&#149;</b> 660 ml Pflanzenmilch (Reismilch schmeckt besonders gut, weil leicht süßlich)
                        <br />
                        <b>&#149;</b> 2 TL Salz
                        <br />
                        <br />
                        <b>Zubereitung</b>
                        <br />
                        <b>&#149;</b> Mehlmischung erstellen und das Backpulver untermischen
                        <br />
                        <b>&#149;</b> Kastenbackform gut mit Pflanzenöl (z.B. Rapsöl) einfetten (danach löst sich das Brot besonders leicht aus der Form)
                        <br />
                        <b>&#149;</b> Ofen auf 180°C vorheizen, am besten Umluft
                        <br />
                        <b>&#149;</b> Schrittweise Mehlmischung und Milch mit den Knethaken des Handrührgeräts verrühren
                        <br />
                        <b>&#149;</b> Danach noch einmal kurz mit dem Handquirl oder Kochlöffel rühren
                        <br />
                        <b>&#149;</b> Masse in die Kastenform füllen, glattstreichen und in die mittlere Schiene des Ofens stellen
                        <br />
                        <b>&#149;</b> Ca. 30 min. backen
                        <br />
                        <br />
                        <b>Tipps</b>
                        <br />
                        <b>&#149;</b> Zwischendurch immer mal wieder die Kruste überprüfen (sie soll nicht 
                        schwarz werden, daher besser auch keine Ober-/Unterhitze einstellen) 
                        und mit einen Holzstäbchen einstechen und testen, 
                        wie feucht das Brot noch von innen ist.
                        <br />
                        <b>&#149;</b> Nicht wundern, das Brot geht nicht sehr auf, das ist ok.
                        <br />
                        <b>&#149;</b> Das Tolle ist, dass man diese Zutaten lagern kann. Man kann 
                        also spontan ein Brot backen und muss nicht frische Hefe, 
                        Eier etc. haben. Also auch etwas für stark Eingespannte sowie 
                        für Leute mit &#187;Knet-Phobie&#171;.
                        <br />
                        <br />
                        Ich danke meiner Klientin Frau M. ganz herzlich für dieses tolle Rezept!
