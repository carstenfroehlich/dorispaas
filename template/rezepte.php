                    schneiden (das ist eine sehr glibberige Angelegenheit) und das Gel in ein hohes Rührgefäß geben. Mit einem Passierstab 
                    gründlich verflüssigen (wenn noch kleinste Stückchen in der Flüssigkeit bleiben, werden einem diese dann nach 
                    dem Eincremen im Gesicht kleben &ndash; das sieht nicht wirklich gut aus!). Bitte sehr sauber arbeiten und frische 
                    Lappen und Handtücher benutzen, um möglichst wenige Keime in diese Zutat zu bringen.
                    <br />
                    <br />
                    Das Rührgefäß für einige Zeit in den Kühlschrank stellen, bis sich der Schaum auflöst. Dann die Flüssigkeit in einen 
                    Eiswürfelbehälter füllen und einfrieren. Wenn die einzelnen Töpfchen zu groß sind, den Behälter nur zur Hälfte befüllen, 
                    so dass später mit den Würfeln die erforderliche Kleinmenge entnommen werden kann. Wenn die Aloe gefroren ist, kann man 
                    die Würfel in einen Beutel füllen und fest verschlossen in der Tiefkühltruhe aufbewahren. Ggf. den Eiswürfelbehälter dann 
                    mit dem Rest des flüssigen Gels befüllen und die zweite Fuhre später zur ersten in den Beutel füllen. Auf diese Weise 
                    hat man den Aloe vera-Rohstoff für viele Cremetiegelchen in Vorrat.
                    <br />
                    <br />
                    <b>Herstellung der Creme:</b>
                    <br />
                    <b>&#149; </b> 8g Mandelöl und
                    <br />
                    <b>&#149; </b> 2,2g Lamecreme (bitte genau wiegen)
                    <br />
                    in dem kleinen Glas-Messbecher im Wasserbad auf ca. 70°C erwärmen, bis sich die Lamecreme-Kügelchen komplett aufgelöst 
                    haben. Dabei mit einem Eierlöffel umrühren.
                    <br />
                    <br />
                    <b>&#149; </b> 30g Aloe Vera
                    <br />
                    in dem größeren Glas-Messbecher ebenfalls im Wasserbad auf ca. 70°C erwärmen 
                    <br />
                    <br />
                    Beide Bechergläser aus dem Wasserbad nehmen und vorsichtig und langsam die Ölmischung in das größere Becherglas 
                    mit der Aloe vera gießen, während man das Ganze mit einem Milchaufschäumer kontinuierlich durchrührt.
                    <br />
                    <br />
                    Wenn das Öl komplett vermischt ist, 
                    <br />
                    <b>&#149; </b> 3,5g Sheabutter
                    <br />
                    hinzufügen und mit dem Milchaufschäumer gründlich verrühren. Die Sheabutter bitte nicht mit dem Öl zusammen 
                    erwärmen, da die konsistenzgebenden Eigenschaften bei zu großer Hitze verloren gehen würden.
                    <br />
                    <br />
                    <b>Optional können noch folgende Zutaten mit dem Milchaufschäumer untergerührt werden:</b>
                    <br />
                    <b>&#149; </b> 5 &ndash; 10 Tropfen ätherisches Öl (z.B. Zitrone) 
                    <br /> 
                    <b>&#149; </b> 5 &ndash; 10 Tropfen Biogard 221 (anderenfalls die Creme im Kühlschrank aufbewahren)
                    <br /> 
                    <b>&#149; </b> 5 &ndash; 10 Tropfen natürliches Vitamin E
                    <br />
                    <br />
                    Wer eine sehr empfindliche Haut hat, sollte auf diese optionalen Zutaten zunächst verzichten und die Creme nur 
                    aus den Basis-Zutaten zubereiten. Später können dann bei Bedarf die eine oder andere optionale Zutat ausgetestet werden.
                    <br />
                    <br />
                    Zum Schluss die Creme in einen verschließbaren Tiegel füllen und für einige Stunden im Kühlschrank fest werden lassen. 
                    Geeignete Tiegel gibt es entweder zu kaufen oder Sie können bereits im Vorfeld leere Tiegelchen von gekauften Cremes 
                    aufbewahren, bis Ihre Aloe vera-Pflanze ausgewachsen ist. 
                    <br />
                    <br />
                    Wenn Sie kein Konservierungsmittel verwendet haben, bitte die Creme weiter im Kühlschrank aufbewahren, ansonsten ist sie 
                    für 1 &ndash; 2 Monate (je nach Menge des Konservierungsmittels) auch bei Zimmertemperatur haltbar.
                    <br />
                    <br />
                    Die Crememenge reicht für 1 &ndash; 2 Wochen. Viel Spaß beim Ausprobieren. 
