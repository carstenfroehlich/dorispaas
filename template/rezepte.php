                        <h3>Selbstgemachter Joghurt</h3> 
                        <br />
                        Joghurt wird aus <a href="milch" target="_blank">Milch</a> hergestellt, der Milchsäurebakterien zugegeben werden. Nach einer Reifezeit von mehreren Stunden fermentieren 
                        die Bakterien die in der Mich enthaltenen Kohlenhydrate und bilden als &#187;Abfallprodukt&#171; Milchsäure. Diese Säure lässt das 
                        Milcheiweiß gerinnen, wobei es fest wird. Je nach Art der Milchäurebakterien entsteht ein relativ säuerlicher oder auch ein eher milder 
                        Geschmack. Der Joghurt kann beim Reifen entweder ruhig stehen oder auch gerührt werden, was Konsistenzen von stichfest oder cremig ergibt. 
                        <br />
                        <br />
                        Joghurt können Sie in jedem Supermarkt kaufen. Es gibt ihn in seiner natürlichen Form, aber auch mit Früchten. Meist jedoch 
                        wissen Sie nicht wirklich, was für Zutaten enthalten sind, denn es gibt zahlreiche Hintertürchen, um Zusätze zu verschleiern.
                        Vor allem aber weiß man (außer vielleicht bei gutem Biojoghurt aus dem Bioladen oder Reformhaus) nicht, ob tatsächlich noch lebende
                        Milchsäurebakterien enthalten sind, denn diese werden vom Hersteller gerne abgetötet, weil sich der Joghurt sonst 
                        nicht so lange hält bzw. im Geschmack zu sauer wird, was Otto-Normalverbraucher angeblich nicht schätzt.
                        <br />
                        <br />
                        Aus diesem Grunde bin ich dazu übergegangen, meinen Joghurt selbst aus Frischmilch zuzubereiten. Da ich laktoseintolerant bin, benutze ich dazu 
                        laktosefreie Milch. Zur Impfung der Milch mit Michsäurebakterien kann man entweder Milchsäurebakterien als so genannte Starterkultur kaufen, oder 
                        aber man gibt wie ich einige Teelöffel voll gekauften Joghurt in die Milch. Dieser Joghurt darf ruhig laktosehaltig sein, denn bei 
                        dem im Verhältnis zur Gesamtmenge kleinen Anteil fällt der Laktosegehalt nicht ins Gewicht, zumal durch die Milchsäurebakterien während des 
                        Reifeprozesses die enthaltene Laktose soweit aufgespalten wird, dass ich keinerlei Probleme habe. Später kann man auch einige Löffel von dem 
                        vorigen Joghurt als Starterkultur verwenden, jedoch habe ich die Erfahrung gemacht, dass dies nur etwa 2-3 Generationen gelingt. Danach muss man 
                        wieder neuen gekauften Joghurt zum Ansetzen verwenden.
                        <br />
                        <br />
                        Je  nachdem, ob man einen säuerlicheren oder milderen Geschmack bevorzugt, kann man den entsprechenden Starterjoghurt auswählen &ndash; 
                        probieren Sie ruhig verschiedene Sorten aus.
                        <br />
                        <br />
                        <b>Utensilien</b>
                        <br />
                        <b>&#149;</b> Joghurtbereiter (z.B. vom <a href="https://www.waschbaer.de/shop/joghurt-bereiter-22909?F=10" target="_blank">Waschbärversand</a>)
                        <br />
                        <b>&#149;</b> Kochtopf
                        <br />
                        <b>&#149;</b> Schneebesen
                        <br />
                        <br />
                        <b>Zutaten</b>
                        <br />
                        <b>&#149;</b> 1 Liter frische Vollmilch (ggf. laktosefrei)
                        <br />
                        <b>&#149;</b> 3 gehäufte Teel. Vollmilch-Joghurt
                        <br />
                        <br />
                        <b>Zubereitung</b>
                        <br />
                        <b>&#149;</b> Die Milch in einem Kochtopf gut handwarm erwärmen 
                        <br />
                        <b>&#149;</b> 3 gehäufte Teelöffel von einem gekauftem Joghurt entnehmen (oder eine Starterkultur verwenden) und in 
                        den Joghurt-Behälter des Joghurtbereiters füllen (der Rest des gekauften Joghurts hält sich mit gut geschlossenem Deckel so lange 
                        im Kühlschrank, dass er für weitere Ansätze benutzt werden kann).
                        <br />
                        <b>&#149;</b> Die warme Milch langsam in den Joghurtbehälter füllen und dabei gut mit dem Schneebesen verrühren.
                        <br />
                        <b>&#149;</b> Den Joghurtbehälter in den Bereiter einsetzen und den Zwischenraum mit gut warmem Wasser auffüllen.
