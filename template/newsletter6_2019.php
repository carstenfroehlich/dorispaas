                        <h5>Ausgabe 49 (November 2019)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-06-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Nach der Umstellung der Uhren beginnt wieder die lichtarme Zeit. Wenn Sie das Haus verlassen ist es noch nicht richtig hell, und abends, wenn Sie heimkehren, ist es schon wieder
                        dunkel. Und auch alle diejenigen, die nicht t&auml;glich zur Arbeit gehen m&uuml;ssen, vermissen das Sonnenlicht und die (nicht nur f&uuml;r die Seele) angenehme W&auml;rme wahrscheinlich genauso.
                        Auch wenn sich vielleicht der eine oder andere Sonnenstrahl noch in unsere Regionen verirrt, ist es doch im Gro&#223;en und Ganzen k&auml;lter und eher weniger verlockend, nach drau&#223;en zu gehen. 
                        Aber das Rausgehen sollten wir trotzdem nicht ganz unter den Tisch fallen lassen. Selbst, wenn es drau&#223;en derzeit weniger einladend ist, tut die frische Luft gut und st&auml;rkt 
                        das Immunsystem. Und wenn wir wieder zur&uuml;ckkehren, macht es stolz, den &#187;inneren Schweinehund&#171; &uuml;berwunden zu haben. Und dann sollten wir es uns zu Hause so richtig gem&uuml;tlich 
                        machen: eine Kerze anz&uuml;nden, einen leckeren Tee bereiten, ein gutes Buch lesen und sich in die Kissen kuscheln. Die beiden im Folgenden f&uuml;r diesen Newsletter ausgew&auml;hlten 
                        Themen eignen sich, um sich gerade jetzt mithilfe von zwei f&uuml;r Sie vielleicht neuen Aspekten noch zus&auml;tzlich um die Gesundheit zu k&uuml;mmern: &#187;Atem und Verdauung&#171; und 
                        &#187;Selbstgemachte Hautpflegeprodukte&#171;. Ich w&uuml;nsche Ihnen viel Spa&#223; beim Lesen.
                        <br />
                        <br />
                        <hr />
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=atmen" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-06-atem.png" alt="Bild Atem" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=atmen" target="_blank">Schwerpunktthema: &#187;Atem und Verdauung&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Darmgesundheit/Hilfreiche Ma&#223;nahmen/Atem und Verdauung</i>
                        <br />
                        Der Atem spielt bei unserer Verdauung eine entscheidende Rolle: mit einer tiefen und sorgf&auml;ltigen Atmung kann man die Darmt&auml;tigkeit im besten Sinne anregen, damit die 
                        Verdauung optimal funktioniert. S&auml;mtliche Probleme &ndash; seien es Bl&auml;hungen, Verstopfung, Durchfall oder auch Schmerzen &ndash; sie alle k&ouml;nnen mit einer 
                        bewussten Atmung g&uuml;nstig beeinflusst werden. Es ist gut, wenn die Darmmuskulatur gut durchblutet wird, weil wir durch tiefes Atmen ausreichend Sauerstoff aufnehmen. 
                        Allein aber auch die mechanische Anregung durch das Zwerchfell und die Bauchdecke f&uuml;hrt zu einer besseren T&auml;tigkeit der Darmmuskulatur, wodurch der Darminhalt kontinuierlicher 
                        weitertransportiert wird. Sogar Sodbrennen und das Zur&uuml;ckflie&#223;en der bei&#223;enden Magens&auml;ure in die Speiser&ouml;hre (Reflux) k&ouml;nnen durch 
                        richtiges Atmen positiv beeinflusst werden. Atem&uuml;bungen k&ouml;nnen zwar an jedem beliebigen Ort durchgef&uuml;hrt werden, aber starten Sie Ihre ersten Versuche doch gerade 
                        jetzt beim gem&uuml;tlichen &#187;L&uuml;mmeln&#171; auf dem Sofa.
                        <br />
                        <br />
                        <hr />
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=hautpflege" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-06-hautpflege.png" alt="Hautpflege" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 10px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=hautpflege" target="_blank">Selbstgemachte Hautpflegeprodukte</a></b>
                        <br />
                        <i>(Men&uuml;: Videos/Rezepte f&uuml;r Hautpflegeprodukte</i>
                        <br />
                        Gerade wenn man an Nahrungsmittel-Unvertr&auml;glichkeiten, -Allergien, einem Reizdarm-Syndrom oder sonstigen Verdauungsbeschwerden leidet, ist es nicht nur wichtig, 
                        auf die Auswahl der Lebensmittel zu achten, sondern auch alle m&ouml;glichen anderen reizenden Stoffe zu meiden, um die Toleranzschwelle des K&ouml;rpers nicht 
                        &uuml;berzustrapazieren. Alle Organe und Systeme im K&ouml;per h&auml;ngen zusammen, und wenn an einem Ende etwas Belastendes passiert, betrifft dies immer auch das 
                        Gesamtsystem. Somit sollte man neben der Ern&auml;hrung auch bewusst auf m&ouml;gliche weitere Beeintr&auml;chtigungsquellen wie u.a. Umweltbelastungen, Chemikalien in 
                        Kleidung oder in den Hautpflegeprodukten achten. Bestimmt stehen in Ihrem Badezimmer zahlreiche Tuben, D&ouml;schen und Tiegel. Nicht nur die Frauen, sondern auch 
                        die Herren der Sch&ouml;pfung benutzen heute meist so einige Produkte zum Pflegen der verschiedenen Hautpartien an H&auml;nden, Gesicht, K&ouml;rper und F&uuml;&#223;en. 
                        Da sogar in den k&auml;uflichen Bioprodukten in den meisten F&auml;llen viel zu viele und viel zu unberechenbare Inhaltsstoffe verarbeitet sind, finden Sie hier Rezepte 
                        zum Selbermachen mit nur ganz wenigen Zutaten.
                        <br />
                        <br />
                        <hr />
                        <br />
                        Liebe Leserinnen und Leser, schon wieder neigt sich ein Jahr dem Ende zu. Bei uns im Lande m&uuml;ssen wir den derzeit eher unsch&ouml;nen Ver&auml;nderungen im 
                        Parteiengef&uuml;ge zusehen. Auch mit den zahlreichen Dramen, die die egoistischen und gef&auml;hrlichen Politclowns auf der Weltb&uuml;hne auff&uuml;hren, hat das 
                        vergangene Jahr nicht wirklich Gutes gebracht. Schon viel l&auml;nger und nicht erst in den letzten Monaten m&uuml;ssen wir auch feststellen, dass sich der Umgangston 
                        zwischen den Menschen ver&auml;ndert: Bei der Kommunikation insbesondere im &ndash; anonymen &ndash; Internet gehen viele immer unpers&ouml;nlicher, ja sogar 
                        r&uuml;cksichtsloser miteinander um. Viele verstecken sich hinter einem Pseudonym, so dass man dem anderen nicht sein Gesicht zeigen muss. Es w&auml;re anders 
                        und &ndash; aus meiner Sicht &ndash; sch&ouml;ner, wenn die Menschen offener und ehrlicher miteinander umgehen w&uuml;rden und wir (wieder) das pers&ouml;nliche 
                        Miteinander pflegen.
                        <br />
                        <br />
                        Ich selbst erlebe in meinem Familien- und Freundeskreis viele wunderbare Augenblicke, in denen jeder f&uuml;r den anderen da ist und in denen man dankbar das 
                        Miteinander genie&#223;t. Auch die zahlreichen positiven Erlebnisse mit Ihnen, meinen Klienten und Lesern, geben mir immer wieder Ansporn und Freude an der Arbeit. 
                        Daf&uuml;r bedanke ich mich ganz herzlich.
                        <br />
                        <br />
                        Ich w&uuml;nsche Ihnen einen friedlichen Jahresausklang und eine gute Zeit. Im neuen Jahr freue ich mich dann wieder auf Sie &ndash; sei es in Form einer Mail oder auch 
                        bei einem Beratungsgespr&auml;ch, aber auf jeden Fall mit dem n&auml;chsten Newsletter, den Sie, wenn Sie m&ouml;chten, im Januar 2020 erhalten werden. Bis dahin sende 
                        ich Ihnen ganz herzliche Gr&uuml;&#223;e aus dem Rheinland
