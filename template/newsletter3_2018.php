                        zubereiten und statt des Honigs Reissirup verwenden und die Korinthen weglassen, k&ouml;nnen 
                        Sie unbedenklich auch in Rahmen einer FODMAP-Di&auml;t morgens einen L&ouml;ffel 
                        voll zu Ihrem Fr&uuml;hst&uuml;cksjoghurt geben. Der hohe Anteil an K&ouml;rnern  
