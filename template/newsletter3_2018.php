                        <h5>Ausgabe 40 (Mai 2018)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-03-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Mit dem Mai ist endlich auch der Fr&uuml;hling zu uns gekommen. Damit einher geht 
                        fast immer mehr Lebensfreude, und die Lust am Genie&#223;en w&auml;chst &ndash; am 
                        Genie&#223;en der Natur, aber auch an der Lust auf frische, gesunde Lebensmittel.
                        Nutzen Sie, wenn m&ouml;glich, jeden Sonnentag, um sich an der frischen Luft bei Sport 
                        und Spiel zu bewegen oder einfach nur, um einen ausgiebigen Spaziergang (ggf. auch mit Regenschirm) zu unternehmen.
                        Laufen oder fahren Sie (z.B. mit dem Rad) mit offenen Augen durch die Natur. Die 
                        Bl&auml;tter der B&auml;ume haben zahlreiche Gr&uuml;nt&ouml;ne, und die vielen 
                        Blumen zeigen die verschiedensten Formen und Farben: die wei&#223;en 
                        Maigl&ouml;ckchen (wie auf dem Titelbild dieses Newsletters), die roten, wei&#223;en 
                        und gelben Pfingstrosen, und an den Z&auml;unen ranken die interessantesten Clematisarten.
                        <br />
                        Aber auch Ihr Essen wird mit dem Fr&uuml;hling abwechslungsreicher und leckerer. 
                        Und selbst, wenn Sie an einer Nahrungsmittel-Unvertr&auml;glichkeit leiden, gibt 
                        es jetzt nach und nach immer mehr frische Auswahl auf Ihrem Teller. &Uuml;brigens: 
                        Je mehr Sie Ihre Zeit genie&#223;en, desto h&ouml;her wird auch die Toleranz 
                        gegen&uuml;ber bisher unvertr&auml;glichen Lebensmitteln werden, denn mit der 
                        Entspannung stabilisiert sich auch Ihr Verdauungssystem, was sich f&ouml;rderlich 
                        auf die Darmflora und die Darmschleimhaut, und damit auch auf die Enzymproduktion 
                        auswirkt. Nat&uuml;rlich alles nur in Ma&#223;en, aber die eine oder andere kleine (!) 
                        S&uuml;nde wird jetzt wahrscheinlich weniger Folgen nach sich ziehen als bisher. 
                        Wagen Sie es doch einmal!
