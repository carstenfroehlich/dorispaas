                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=fodmaps" target="_blank">Schwerpunktthema &#187;FODMAP-Di&auml;t&#171;</a></b>
                        <br />
                        Bei manchen Menschen mit Nahrungsmittel-Unvertr&auml;glichkeiten, Reizdarm-Syndrom 
                        und/oder einer D&uuml;nndarmfehlbesiedelung zeigen die &#187;&uuml;blichen&#171; 
                        Di&auml;ten nicht den gew&uuml;nschten Erfolg. Auch wenn die einzelnen unbek&ouml;mmlichen 
                        Stoffe gemieden werden, gehen in diesen F&auml;llen Beschwerden wie Bauchschmerzen, 
                        Bl&auml;hungen, Durchf&auml;lle und/oder Verstopfung und viele andere nicht auf 
                        ein akzeptables Ma&#223; zur&uuml;ck.
                        <br />
                        Hilfreich kann dann neben der erforderlichen Reduzierung der unvertr&auml;glichen 
                        Stoffe zus&auml;tzlich die Einhaltung einer Di&auml;t mit einem geringeren Anteil 
                        an bestimmten Kohlenhydraten sinnvoll sein. Diese Ern&auml;hrung ist leichter verdaulich, 
                        und sch&auml;dlichen Darmbakterien wird mit dem geringeren Ballaststoffanteil die 
                        Lebensgrundlage entzogen.
                        <br />
                        Gerade hier aber kann der Teufel im Detail stecken: Ballaststoffe sind nicht nur 
                        einfach &uuml;berfl&uuml;ssiger Ballast, sondern stellen f&uuml;r die Verdauung 
                        ganz wichtige Bestandteile dar. Werden diese nun im Rahmen einer FODMAP-Di&auml;t 
                        weitestgehend gemieden, bleiben die stuhlregulierenden Eigenschaften der Ballaststoffe 
                        aus &ndash; der Stuhl wird fester und die Transportgeschwindigkeit verlangsamt. 
                        Dadurch hat der Dickdarm noch l&auml;nger Zeit, dem Stuhl Fl&uuml;ssigkeit zu entziehen, 
                        wodurch sich die ohnehin schon festere Konsisten noch weiter verschlechtert. Auch 
                        wenn die FODMAP-arme Di&auml;t ein gutes Mittel ist, Ruhe in den Darm zu bekommen, 
                        gibt es doch so einiges zu beachten.
