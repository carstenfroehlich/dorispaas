                        <hr />
                        <h5>Warum ist ein vertrauensvolles Verhältnis zwischen Ihnen und mir für den Behandlungserfolg unverzichtbar?</h5>
                        <hr />
                        Für mich ist es selbstverständlich, mir nicht nur <b>ausreichend Zeit für Sie</b> zu nehmen, sondern auch <b>auf Augenhöhe</b> mit Ihnen zu sprechen. 
                        Ein Verhalten, wie es früher die &#187;Halbgötter in Weiß&#171; an den Tag legten, um dem Patienten ihre (selbstverständlich in jedem Falle unumstößliche) 
                        Meinung überzustülpen, ist mir schon, so lange ich denken kann, äußerst fremd. Ich erarbeite grundsätzlich Konzepte nur <b>mit Ihnen gemeinsam</b> und 
                        schaue dabei genau hin, was Sie bereit sind mitzutragen.
                        <br />
                        <br />
                        Nur so kann ein Konzept zum Erfolg führen. Selbst, wenn ich als Beraterin der Meinung wäre, ein anderes Konzept sei vielversprechender, so kann doch ein 
                        anderes, das für mich vielleicht nur die zweitbeste Lösung darstellt, <b>für Sie genau die richtige Lösung</b> sein, weil es sehr viel besser in Ihren Lebensalltag 
                        passt. Einzig Sie als Klientin oder Klient haben zu entscheiden, was Sie für sich selbst annehmen möchten &ndash; das ist für mich nicht nur Wertschätzung 
                        und Respekt, sondern bietet Ihnen die größte Chance auf einen erfolgreichen Weg aus Ihrer derzeitigen Situation.
