                    <b>Mit Stoffsäckchen Plastikmüll vermeiden</b> 
                    <br />
                    Die Hitzewelle der vergangenen Wochen hatte neben der Belastung für uns selbst auch
                    katastrophalen Folgen für die Bauern, deren Arbeit von Monaten zunichte 
                    gemacht wurde und zu großen Ernteausfällen führte.
                    Ich denke zwar, dass einiges an diesem Problem &#187;selbstgemacht&#171; ist und eine 
                    umweltgerechtere Produktionsweise und klügere Fruchtfolge die Schäden weniger 
                    drastisch hätten ausfallen lassen können, aber auch wir tragen ja durch unser 
                    eigenes Konsumverhalten zumindest zu einem kleinen Teil mit die Verantwortung 
                    für die Entwicklung in der Klimawende. Wenn jeder nur wenig von seinen 
                    Gewohnheiten ändert, können diese vielen kleinen Bausteine zusammen genommen 
                    sicherlich schon recht viel bewirken. 
                    <br />
                    <br />
                    Greifen auch Sie beim Obst- und Gemüseeinkauf immer noch zu den dünnen Plastiktüten? 
                    Zugegeben, die wiegen zwar fast nichts, aber vergrößern alle zusammen genommen den 
                    Berg von Plastikmüll, denn sie werden im Allgemeinen nur einmal benutzt und 
                    dann in den Abfall geworfen. Hier können Sie ganz einfach beginnen:
                    Kaufen Sie im Fach- oder Versandhandel Stoffbeutelchen, die Sie 
                    mehrfach immer wieder benutzen können. Genausogut aber können Sie diese 
                    etwa 28x35cm großen Beutel mit ein wenig Geschick aus weichem Gaze- oder Netzstoff auch selbst nähen.
                    Zwei Nachteile haben diese Beutel allerdings: sie haben zum einen ein 
                    nennenswertes Gewicht, so dass ich mein Obst und Gemüse zunächst ohne 
                    Beutel wiege und es erst anschließend in den Beutel stecke, damit ich nicht 
                    jeweils das Stoffgewicht mit bezahlen muss. Und zum anderen bleiben die Preisschilder 
                    aus der Waage nicht auf dem Beutel kleben. Ich sammle die Schildchen immer am Rand meiner 
                    Einkaufswagentasche und gebe sie dann beim Bezahlen einen nach dem anderen 
                    der Kassiererin. Ich habe noch nie erlebt, dass sich einer der Mitarbeiterinnen 
                    beschwert hätte &ndash; im Gegenteil: die meisten waren interessiert,
                    und häufig entwickelt sich dabei ein nettes Gespräch &ndash; entweder 
                    mit den Kassiererinnen oder aber mit den anderen Kunden.
                    <br />
                    <br />
                    &#187;Kleinvieh macht auch Mist&#171; sagt ein kluger Spruch. Je nachdem, wie 
                    oft und wie viel Obst und Gemüse Sie einkaufen, können Sie mit diesen Beuteln 
                    im Laufe eines jeden Jahres einen mehr oder weniger großen Beitrag dazu leisten, 
                    die Plastikmüllberge nicht übermäßig anwachsen zu lassen, ohne dabei auf Ihren 
                    gewohnten Komfort zu verzichten. 
