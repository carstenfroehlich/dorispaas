                        Verdauungsbeschwerden k&ouml;nnen neben Nahrungsmittel-Unvertr&auml;glichkeiten 
                        und/oder -Allergien viele weitere Ursachen haben &ndash; und nicht immer ist es einfach, 
                        diesen auf die Spur zu kommen. Wenn die Tests auf unvertr&auml;gliche Lebensmittel 
                        zu keinem oder zu keinem befriedigenden Erfolg f&uuml;hren, sollten Sie auch an 
                        Ihre Schilddr&uuml;se denken, denn eine mangelhafte Schilddr&uuml;senfunktion kann 
                        Verdauungsprobleme wie Verstopfung, Durchf&auml;lle oder Bauchschmerzen (mit-)verursachen. 
                        <br />
                        <a id="physiologie"></a>
                        <hr />
                        <h5>Physiologie</h5>
                        <hr />
                        Die Schilddr&uuml;se (Glandula thyreoidea) ist ein kleines Organ, das in einem 
                        komplizierten und feinf&uuml;hligen Zusammenspiel mit vielen anderen Dr&uuml;sen 
                        im K&ouml;rper die Hormonproduktion und damit die K&ouml;rperfunktionen steuert. 
                        Sie ist mit ihren zwei &#187;Lappen&#171; geformt wie ein Schmetterling und liegt 
                        im Hals vor der Luftr&ouml;hre in H&ouml;he des Kehlkopfes (&#187;Adamsapfel&#171;). Die 
                        Gr&ouml;&#223;e einer gesunden Schilddr&uuml;se eines Erwachsenen liegt (je nach Alter 
                        und Geschlecht) etwa zwischen der einer Walnuss bis maximal der Gr&ouml;&#223;e einer 
                        kleinen Mandarine (Frauen: 13-18ml, M&auml;nner 15-25ml). 
                        <br />
                        <a id="funktionen">&nbsp;</a>
                        <hr />
                        <h5>Funktionen der Schilddr&uuml;se</h5>
                        <hr />
                        Drei verschiedene Hormone werden in der Schilddr&uuml;se gebildet: Thyroxin (T4), 
                        Trijodthyronin (T3) und Calcitonin. Das Calcitonin f&ouml;rdert den Einbau von 
                        Kalzium und Phosphat in die Knochen und hemmt dem Knochenabbau, indem es die 
                        knochenabbauenden Osteoklasten beeinflusst.
                        <br />
                        <br />
                        T4 und T3 sind f&uuml;r das Wachstum zust&auml;ndig und deshalb bereits im S&auml;uglings-, 
                        Kinder- und Jugendalter besonders wichtig. Aber auch f&uuml;r Erwachsene sind diese 
                        Hormone bedeutsam, denn sie steuern zus&auml;tzlich u.a. den Energiestoffwechsel 
                        im K&ouml;rper, regulieren Herzfrequenz, Blutdruck und K&ouml;rpertemperatur. 
                        <br />
                        <br />
                        <b>Und ganz wichtig zu wissen:</b> Die Schilddr&uuml;senhormone beeinflussen die 
                        Reizleitung der Nerven (nicht nur) des Magen-Darmtrakts und regulieren so auch 
                        die Motorik des Darms (Darmperistaltik). Dadurch k&ouml;nnen sie (mit-)verantwortlich 
                        sein f&uuml;r Verstopfung (bei Unterversorgung) oder Durchf&auml;lle (bei 
                        &Uuml;berversorgung), dar&uuml;ber hinaus k&ouml;nnen als Folge Bauchschmerzen 
                        und viele weitere Symptome auftreten.
                        <br />
                        <br />
                        Die Schilddr&uuml;se ist ein sehr wichtiges Organ: Aufgrund ihrer vielf&auml;ltigen 
                        Funktionen kann man sie als &#187;Steuerungszentrale&#171; betrachten, 
                        denn fast alle hormonellen K&ouml;rperfunktionen werden letztendlich durch die 
                        Schilddr&uuml;se gesteuert und kontrolliert. Zwar muss sich die Schilddr&uuml;se 
                        noch mit der Hypophyse (Hirnanhangsdr&uuml;se) &#187;abstimmen&#171;, 
                        letztendlich ist es aber die Schilddr&uuml;se, die die meisten Hormondr&uuml;sen 
                        im K&ouml;rper steuert. So ist beispielsweise auch der weibliche Hormonzyklus 
                        mit von einer korrekten Schilddr&uuml;senfunktion abh&auml;ngig, denn die 
                        Eierst&ouml;cke, in denen die weiblichen Hormone gebildet werden, werden von der 
                        Schilddr&uuml;se geregelt. Auch der Schlaf-Wach-Rhythmus, der durch das in der 
                        Zirbeldr&uuml;se gebildete Hormon Melatonin gesteuert wird, wird ebenfalls von den 
                        Schilddr&uuml;senhormonen &uuml;berwacht. Eine Schilddr&uuml;senunterfunktion kann 
                        sich deshalb auch durch verst&auml;rkte M&uuml;digkeit bemerkbar machen, eine 
                        &Uuml;berfunktion hingegen durch Schlafprobleme oder Nervosit&auml;t. 
                        <br />
                        <a id="hormone">&nbsp;</a>
                        <hr />
                        <h5>Bildung von Schilddr&uuml;senhormonen</h5>
                        <hr />
                        Zur Bildung der Schilddr&uuml;senhormone Thyroxin und Trijodthyronin ist der 
                        Mineralstoff Jod erforderlich. Da der Organismus dieses Spurenelement nicht selbst 
                        bilden kann, muss es mit der Nahrung aufgenommen werden. Insbesondere bei erh&ouml;htem 
                        Bedarf wie beispielsweise einer Schwangerschaft und der Stillzeit aber auch bei 
                        intensiver sportlicher Bet&auml;tigung muss aufmerksam auf eine ausreichende 
                        Jodversorgung geachtet werden, damit f&uuml;r das wachsende Kind und die Mutter, 
                        f&uuml;r den Sportler und f&uuml;r jeden Menschen ausreichend Schilddr&uuml;senhormone 
                        zur Verf&uuml;gung stehen.
                        <br />
                        <a id="erkrankungen">&nbsp;</a>
                        <hr />
                        <h5>Schilddr&uuml;senerkrankungen</h5>
                        <hr />
                        Bei einer Unterfunktion der Schilddr&uuml;se, bei der nicht gen&uuml;gend Hormone 
                        gebildet werden, w&auml;chst die Schilddr&uuml;se, um mit mehr Dr&uuml;sengewebe 
                        mehr Hormon bilden und so den Bedarf decken zu k&ouml;nnen. Der Halsumfang wird 
                        nach und nach dicker, in Extremf&auml;llen kann man dies an dem so genannten &#187;Kropf&#171; 
                        (Struma) erkennen. Durch die mangelnde Versorgung mit Schilddr&uuml;senhormonen 
                        werden alle K&ouml;rperfunktionen langsamer &ndash; auch der Darm wird tr&auml;ge, 
                        und in der Folge k&ouml;nnen Verstopfung  und dadurch eventuell verursachte 
                        Bauchschmerzen auftreten.
                        <br />
                        <br />
                        Bei einer &Uuml;berfunktion wird zuviel Hormon gebildet, und alle diejenigen 
                        K&ouml;rperfunktionen, die durch die Schilddr&uuml;senhormone gesteuert werden, 
                        laufen schneller ab – z.B. eine gesteigerte Herzfrequenz oder auch eine gest&ouml;rte 
                        Verdauung mit Durchf&auml;llen und/oder Bauchschmerzen k&ouml;nnen durch die 
                        gesteigerte Darmperistaltik die Folgen sein. 
                        <br />
                        <br />
                        Neben der &Uuml;ber- und Unterfunktion gibt es viele weitere Erkrankungen der 
                        Schilddr&uuml;se, beispielsweise eine Entz&uuml;ndung (Thyreoiditis). Verbreitet 
                        sind Entz&uuml;ndungen mit autoimmunen Komponenten, bei denen der K&ouml;rper das 
                        Schilddr&uuml;sengewebe als &#187;fremd&#171; einstuft und bek&auml;mpft. Hierbei 
                        kann es zur &Uuml;berfunktion (Morbus Basedow) oder auch zu einer Unterfunktion 
                        (Hashimoto Thyreoiditis) kommen. Bitte lesen Sie hierzu auch die Antwort auf die 
                        Frage <a href="faq#frage101">Ich leide an einer Hashimoto-Thyreoiditis. 
                        Ich habe gelesen, dass diese Krankheit h&auml;ufiger mit einer Laktose-Intoleranz 
                        einhergeht. Ist das richtig?</a>
                        <br />
                        <br />
                        Weiterhin sind die gutartigen, so genannten kalten oder hei&#223;en Knoten sehr 
                        verbreitet. Ein kalter Knoten ist ein Areal in der Schilddr&uuml;se, das keine Hormone 
                        produziert &ndash; egal, wie viele Anst&ouml;&#223;e der Bereich von der Hypophyse 
                        bekommt. Ein hei&#223;er Knoten produziert im Gegenteil st&auml;ndig Hormone, 
                        selbst wenn die Hypophyse signalisiert, es sei genug. Hei&#223;e Knoten sind eher 
                        unproblematisch, m&uuml;ssen nur beobachtet werden, damit insgesamt keine 
                        &Uuml;berproduktion von Schilddr&uuml;senhormonen entsteht. Kalte Konten m&uuml;ssen 
                        nicht, k&ouml;nnen aber entarten und b&ouml;sartig werden, somit m&uuml;ssen auch 
                        sie in regelm&auml;&#223;igen Abst&auml;nden kontrolliert werden.
                        <br />
                        <a id="diagnose">&nbsp;</a>
                        <hr />
                        <h5>Diagnostik von Schilddr&uuml;senfunktionsst&ouml;rungen</h5>
                        <hr />
                        Zur Diagnostik reicht f&uuml;r den Anfang das Abtasten durch den Arzt und eine 
                        Blutprobe, bei der im Labor die 
                        Schilddr&uuml;senwerte bestimmt werden. Ggf. kann zus&auml;tzlich eine 
                        Ultraschalluntersuchung durchgef&uuml;hrt werden, um die Gr&ouml;&#223;e und Beschaffenheit 
                        der Schilddr&uuml;se zu ermitteln.
                        <br />
                        <br />
                        Bei Bedarf kann Sie der Hausarzt auch zu einem auf Schilddr&uuml;senerkrankungen 
                        spezialisierten Nuklearmediziner (Radiologen) &uuml;berweisen, der ein Szintigramm erstellt. 
                        Hierbei wird nach der Verabreichung harmloser radioaktiver Bestandteile, die sich 
                        in der Schilddr&uuml;se ansammeln, die Gr&ouml;&#223;e und Funktionsf&auml;higkeit der 
                        beiden Schilddr&uuml;senlappen optisch dargestellt und bewertet.
                        <br />
                        <br />
                        Wenn Sie jetzt Vorbehalte wegen der Radioaktivit&auml;t haben, kann ich dies gut 
                        verstehen. Es ist richtig, dass gerade das Schilddr&uuml;sengewebe ganz empfindlich 
                        auf radioaktive Strahlung reagiert &ndash; nach Tschernobyl h&auml;uften sich dort 
                        die Krebserkrankungsf&auml;lle. Trotzdem m&ouml;chte ich zu bedenken geben, dass 
                        zumindest f&uuml;r mich die Risiko-/Nutzenabw&auml;gung ergibt, dass eine gr&uuml;ndliche 
                        Diagnostik und die daraus resultierende Behandlung vorteilhaft sind. Die radioaktiven 
                        Stoffe haben eine extrem kurze Halbwertszeit, so dass sie nach wenigen Stunden 
                        vollst&auml;ndig abgebaut sind. Nach Aussage der Nuklearmediziner besteht f&uuml;r 
                        diese kurze Zeit der wirklich minimalen und &uuml;berhaupt nicht mit der 
                        Strahlungsintensit&auml;t von Tschernobyl vergleichbaren Strahlung f&uuml;r das 
                        Gewebe keine Gefahr. Eine eventuelle Entscheidung pro oder contra Szintigramm muss 
                        jedoch jeder f&uuml;r sich selbst treffen.
                        <br />
                        <a id="behandlung">&nbsp;</a>
                        <hr />
                        <h5>Behandlung</h5>
                        <hr />
                        Schilddr&uuml;senfunktionsst&ouml;rungen sind relativ h&auml;ufig und k&ouml;nnen 
                        mit Medikamenten gut behandelt werden. Meist wird hier das Hormon L-Thyroxin verschrieben, 
                        das die Schilddr&uuml;se in ihrer Arbeit unterst&uuml;tzt und entlastet. Medikamente 
                        mit Thyroxin m&uuml;ssen <b>immer</b> eingeschlichen werden, damit sich der 
                        &#187;entw&ouml;hnte&#171; Organismus langsam wieder mit den richtigen Mengen 
                        auseinandersetzen kann. Auch wenn die &Auml;rzte dies wissen, k&ouml;nnen die 
                        Ratschl&auml;ge f&uuml;r darmempfindliche Patienten manchmal nicht ausreichend sein. 
                        Haben Sie den Mut, Ihren Arzt zu bitten, die Dosierungen anfangs weitestgehend 
                        zu minimieren und die Dosis wirklich nur sehr langsam zu steigern. Die kleinste 
                        Steigerungsrate ist mit Tropfen zu erreichen, die es (eigentlich f&uuml;r Kinder) gibt: 
                        ein Tropfen enth&auml;lt hier 5 &#181;g L-Thyroxin. Nicht viele &Auml;rzte wissen, 
                        dass es L-Thyroxin auch in Tropfenform gibt &ndash; fragen Sie ggf. gezielt danach. 
                        <br />
                        <br />
                        Weiterhin m&uuml;ssen Sie nat&uuml;rlich &ndash; wie bei allen Medikamenten &ndash; darauf achten, 
                        dass keine unvertr&auml;glichen Zusatzstoffe wie beispielsweise Laktose enthalten 
                        sind. Bitten Sie Ihren Arzt nach der Auswahl eines geeigneten Pr&auml;parates um 
                        das <b>&#187;aut idem&#171;-Kreuzchen</b> auf dem Rezept, damit Sie in der Apotheke 
                        kein billigeres Ersatz-Pr&auml;parat bekommen, das eventuell dann doch 
                        unvertr&auml;gliche Zusatzstoffe enth&auml;lt.
                        <br />
                        <br />
                        Nach einer behutsamen Gew&ouml;hnung an die erforderliche Thyroxindosis erzeugt 
                        dieses Medikament keine Nebenwirkungen.
                        <br />
                        <br />
                        Noch ein Hinweis f&uuml;r Menschen, die gerne Sojaprodukte verzehren: Zwischen 
                        der Einnahme von L-Thyroxin-Pr&auml;paraten und dem Verzehr von Soja ist eine 
                        Zeitspanne von mindestens 2 Stunden einzuhalten, da Soja Thyroxin in seiner 
                        Wirkung beeintr&auml;chtigt. Bitte lesen Sie hierzu auch die Antwort auf die Frage
                        &#187;<a href="faq#32">Sie empfehlen, die Milch durch 
                        Sojaprodukte zu ersetzen. Ich habe geh&ouml;rt, dass Soja die Kropfbildung der 
                        Schilddr&uuml;se beg&uuml;nstigt. Stimmt das?</a>&#171;
                        <br />
                        <a id="jod">&nbsp;</a>
                        <hr />
                        <h5>K&uuml;nstlich zugef&uuml;hrtes Jod</h5>
                        <hr />
                        H&auml;ufig wird bei leichten Unterfunktionen Jod in Tablettenform verschrieben, 
                        weil davon ausgegangen wird, dass dieses Spurenelement, das zur Bildung der 
                        Schilddr&uuml;senhormone erforderlich ist, und u.U. nicht in ausreichender Menge 
                        zur Verf&uuml;gung steht. Die k&uuml;nstliche Zufuhr von Jod als Medikament oder 
                        auch in jodiertem Speisesalz ist nicht ganz unumstritten &ndash; besser ist es aus 
                        meiner Sicht, Jod ausschlie&#223;lich mit einer gesunden Ern&auml;hrung aufzunehmen. 
                        <br />
                        <br />
                        Besonders wichtig ist auch der Hinweis, dass bei Schilddr&uuml;senentz&uuml;ndungen 
                        &ndash; auch den autoimmunen Formen &ndash; kein Jod in Tablettenform oder als 
                        jodiertes Speisesalz gegeben werden darf, denn Jod kann die Entz&uuml;ndungen 
                        f&ouml;rdern. 
                        <br />
                        <a id="ernaehrung">&nbsp;</a>
                        <hr />
                        <h5>Jod in der Ern&auml;hrung</h5>
                        <hr />
                        Mit ein wenig Aufmerksamkeit kann man den Jodbedarf f&uuml;r eine gesunde 
                        Schilddr&uuml;senfunktion leicht &uuml;ber die Nahrung decken. Jod ist insbesondere 
                        in Seefisch enthalten &ndash; 1-2 Portionen pro Woche geh&ouml;ren zu einer gesunden 
                        Ern&auml;hrung. Auch Milch, Leber, Eier und Erdn&uuml;sse enthalten viel Jod. 
                        Der Jodgehalt von Getreide und Gem&uuml;se ist abh&auml;ngig vom Jodgehalt des 
                        Bodens im Anbaugebiet. Eine ausreichende Versorgung ist bei uns mit einer 
                        abwechslungsreichen, vollwertigen Ern&auml;hrung mit Fisch, Eiern und ggf. 
                        Milchprodukten (sofern vertr&auml;glich) in den allermeisten F&auml;llen auch 
                        in den seefernen, so genannten Jodmangelgebieten gesichert. <br />
                        <br />
                        Auch bei Schilddr&uuml;senentz&uuml;ndungen ist die mit der Nahrung aufgenommene 
                        Jodmenge nicht bedenklich, allerdings sollte der Verzehr des besonders jodhaltigen 
                        Seefischs in diesem Falle nicht &uuml;bertrieben und auf eine kleine Portion pro 
                        Woche beschr&auml;nkt werden. 
                        <br />
                        <a id="verdauungsbeschwerden">&nbsp;</a>
                        <hr />
                        <h5>Verdauungsbeschwerden </h5>
                        <hr />
                        Ziehen Sie bitte bei Verdauungsbeschwerden immer eine Schilddr&uuml;senfunktionsst&ouml;rung 
                        in Betracht. Bei immer wiederkehrender Verstopfung sollten Sie Ihren Halsumfang 
                        aufmerksam beobachten und messen &ndash; eine einfache Methode, Unterfunktionen rechtzeitig 
                        zu erkennen. Eine &Uuml;berfunktion kann man allerdings nicht am Halsumfang erkennen.
                        <br />
                        <br />
                        <b>In jedem Fall sollten Sie bei Verdauungsproblemen auch immer Ihren Hausarzt um 
                        die Untersuchung Ihrer Schilddr&uuml;se bitten. </b>
