                        Sie fragen sich vielleicht: &#187;Was hat denn die Verdauung mit Krisen-Situationen zu tun?&#171; Gerade ein so empfindliches und 
                        störanfälliges System wie die Verdauung kann mehr oder weniger stark beeinträchtigt werden durch die Umstände, die mit einer Krise 
                        und mit dem damit verbundenen Stress einhergehen. Insbesondere Menschen, die ohnehin schon Probleme mit der Verdauung haben &ndash; 
                        sei es durch <a href="nahrungsmittelunvertraeglichkeiten" target="_blank">Nahrungsmittel-Unverträglichkeiten oder -Allergien</a>, durch eine 
                        <a href="gluten" target="_blank">Zöliakie</a> oder eine Chronisch entzündliche Darmerkrankung, durch ein <a href="rds-wasistdas" target="_blank">Reizdarm-Syndrom</a>
                        oder eine <a href="duenndarmfehlbesiedelung" target="_blank">Dünndarmfehlbesiedelung</a> oder durch sonstige Verdauungsbeschwerden &ndash; können 
                        besonders betroffen sein, denn die Beschwerden können sich unter solchen widrigen Voraussetzungen verschlimmern. Diese Zusammenhänge 
                        möchte ich an dieser Stelle herausarbeiten. 
                        <br />
                        <a id="physiologie"></a>
                        <br />
                        <hr />
                        <h5>Physiologische Zusammenhänge</h5>
                        <hr />
                        <b>Unter Stress kann die Verdauung nicht korrekt arbeiten.</b> Das Verdauungssystem funktioniert auch nach Tausenden von Jahren, also einem 
                        Wimpernschlag in der menschlichen Evolution, noch genauso, wie bei unseren Vorfahren. Wenn die Urmenschen mit einem Stresserlebnis 
                        konfrontiert wurden &ndash; beispielsweise der Begegnung mit einem Säbelzahntiger &ndash; wurden durch die Stresshormone augenblicklich 
                        Körperfunktionen hochgefahren, um das nackte Leben zu retten, sprich, um entweder weglaufen oder angreifen zu können (&#187;fight and 
                        flight&#171;): Die Leber schüttet Energiereserven aus, um die Leistungsfähigkeit der Bein- und Armmuskulatur zu optimieren. Die Atmung 
                        geht schneller, um mehr Sauerstoff im Blut aufnehmen zu können und die Herzfrequenz erhöht sich, um diesen Sauerstoff zu den Muskeln 
                        transportieren zu können. Sogar die Blutgerinnungsfähigkeit ändert sich, um eventuelle Wunden schneller schließen zu können. Das 
                        Blickfeld verengt sich, um den Angreifer fokussieren zu können. Was rechts und links liegt, wird ausgeblendet. 
                        <br />
                        <br />
                        Weniger wichtige Funktionen &ndash; wie u.a. die Verdauung &ndash; werden heruntergefahren, so dass die Ressourcen nur noch für das 
                        Überleben bereitgestellt werden. 
                        <br />
                        <br />
                        Damals konnten die Stresshormone noch durch die Bewegung während der Flucht oder dem Kampf abgebaut werden, und wenn die Gefahr 
                        vorüber war, kam der Urmensch wieder zur Ruhe und konnte sich entspannen &ndash; und verdauen (&#187;rest and digest&#171; ). 
                        <br />
                        <br />
                        All dies wird geregelt durch unser <b>autonomes Nervensystem</b>, also das Nervensystem, das wir nicht willentlich beeinflussen können. 
                        Es sind hier die beiden Gegenspieler <b>Sympathikus</b> und <b>Parasympathikus</b>, die diese Körperreaktionen steuern. Der Sympathikus 
                        ist für die Stressregulierung zuständig, der Parasympathikus für den Ruhemodus. Beide Nervensysteme arbeiten ausschließlich, d.h. es gibt 
                        keine Gleichzeitigkeit oder Zusammenarbeit. Entweder ist man im Stressmodus oder im Ruhemodus.
                        <br />
                        <br />
                        Für die Verdauung hat dies sehr entscheidende Konsequenzen: Steht man den ganzen Tag unter Stress, arbeitet der Darm auch den ganzen Tag 
                        gerade mal auf Sparflamme. Kommt jetzt noch ein schlechter Schlaf hinzu, weil einen die Tageserlebnisse nicht zur Ruhe kommen lassen, 
                        gibt es überhaupt keine Zeitspanne, innerhalb derer die Nahrung korrekt verarbeitet werden kann. Dass dies <b>nicht förderlich für eine 
                        gut funktionierende Verdauung</b> sein kann, ist einleuchtend. 
                        <br />
                        <a id="stresssituationen"></a>
                        <br />
                        <hr />
                        <h5>Stress-Situationen</h5>
                        <hr />
                        Natürlich begegnen wir heute keinem &#187;echten&#171; Säbelzahntiger mehr. Aber unsere &#187;heutigen Säbelzahntiger&#171; heißen unter 
                        anderem Arbeitsbelastung, Lärm, Verkehrschaos, ständiges Internet oder sonstige, tägliche An- bzw. Überforderungen. Auch die Doppel- und 
                        Mehrfach-Eindrücke, denen wir uns zudem noch freiwillig aussetzen, tragen zur Stressbelastung bei: Wir lassen den Fernseher im Hintergrund 
                        laufen oder schalten das Radio ein. Dies nehmen wir zwar nur unterschwellig wahr, es beansprucht aber immer einen Teil unserer 
                        Aufmerksamkeits-Ressourcen und steigert damit Stress. Kein Mensch ist &#187;multitaskingfähig&#171;! Unser Gehirn muss zwischen den 
                        Erfordernissen hin und herspringen &ndash; und das ist anstrengend. 
                        <br />
                        <br />
                        Kein Wunder also, wenn wir alle an jedem Tag und zu jeder Stunde einem mehr oder weniger hohen &#187;<b>Stress-Grundrauschen</b>&#171; 
                        ausgesetzt sind, selbst wenn wir es nicht immer bewusst wahrnehmen. 
                        <br />
                        <br />
                        Unter Umständen hat man dann zusätzlich noch einen <b>individuellen &#187;Rucksack&#171;</b> zu tragen, gefüllt mit belastenden Familiensituationen, 
                        Trennungen, Todesfällen oder anderen persönlichen Katastrophen. All dies lässt keinen unberührt und maximiert die Summe der Belastungen. 
                        <br />
                        <br />
                        Und als wäre dies nicht genug, nehmen auch die <b>gesellschaftlichen Probleme</b> immer mehr überhand: nach über 75 Jahren Frieden rücken nun 
                        auch wieder Kriege im wahrsten Sinne des Wortes näher an uns heran. Nicht erst in deren Folge nehmen Aggressivität und Gewalt, Fremdenfeindlichkeit, 
                        Rassismus und Antisemitismus zu, und kaum einer fühlt sich mehr sicher vor Hass und Anfeindungen. Auch die <a href="krisenverdauung" target="_blank">Corona-Pandemie</a> 
                        steckt uns noch in den Knochen. Viele Kinder, Jugendliche und ältere Menschen, die besonders zurückstecken mussten, leiden noch immer unter 
                        den Nachwehen. Und über allem schwebt die Klimakrise, die uns Menschen und unseren ganzen Planeten bedroht. Wildgewordene Autokraten und 
                        Regierungskrisen, durch die jahrelang keine vernünftigen Entscheidungen mehr getroffen werden, lassen uns verzweifeln und uns unserer 
                        Machtlosigkeit bewusst werden. Egal, mit welcher Konfliktpartei Sie dabei sympathisieren, es wird ja immer ein Gegner da sein, dessen 
                        Meinung oder Taten Sie nicht gutheißen. All dies bedeutet auf jeden Fall Stress!  
                        <br />
                        <br />
                        Verstärkt wird solcher Stress auch dadurch, wenn man keine unabhängigen und umfassenden &ndash; gerne auch gegensätzlichen &ndash; Meinungen 
                        einholt, sondern sich nur in seiner &#187;Blase&#171; bewegt, in der sich die Mitglieder immer weiter in ihrer Meinung bestärken und das 
                        &#187;Feindbild&#171; und damit das Stresslevel immer weiter vergrößern. 
                        <br />
                        <br />
                        Hinzu kommen dann noch &ndash; last but not least, um das Stress-Fass noch weiter zu füllen &ndash; <b>unsere Verdauungsbeschwerden</b>. Wenn einem 
                        der Bauch wehtut, wenn Blähungen das soziale Leben stören, wenn die Toilettengänge nicht mehr zuverlässig planbar sind, wenn der Schlaf durch 
                        ein rebellierendes Verdauungssystem unterbrochen wird, dann zahlt dies alles weiter auf das Stresskonto ein. Wie oben erläutert, sind diese 
                        Beschwerden zu einem nicht unbeträchtlichen Teil durch den Stress (mit)verursacht &ndash; und erhöhen nun ihrerseits das Stresslevel. 
                        Ein Teufelskreis also, aus dem nur sehr schwer wieder herauszukommen ist. 
                        <br />
                        <br />
                        <b>Spätestens jetzt läuft das Stress-Fass über!</b> 
                        <br />
                        <a id="loesungsmoeglichkeiten"></a>
                        <br />
                        <hr />
                        <h5>Lösungsmöglichkeiten</h5>
                        <hr />
                        Allein schon durch unsere derzeitigen &#187;normalen&#171; Lebensgewohnheiten ist die notwendige Entspannung heutzutage kaum noch in ausreichendem
                        Maße gewährleistet. Wenn dann noch eine als besonders bedrohlich empfundene Krise hinzukommt, ist dies eben oftmals der Tropfen, der das 
                        Fass zum Überlaufen bringt. 
                        <br />
                        <br />
                        Ein erster Schritt ist hier zunächst eine möglichst genaue <b>Analyse der Ausgangssituation</b>: was belastet mich?, was belastet mich derzeit 
                        ganz besonders?, welche Belastungen sind nicht änderbar &ndash; zumindest derzeit nicht?, welche Belastungen kann ich abstellen oder minimieren?, 
                        welchen Zeitrahmen sollte ich realistischerweise dafür einplanen?
                        <br />
                        <br />
                        Es sollte klar sein, dass man nicht alle Baustellen gleichzeitig angehen kann. Was können Sie (als erstes) ändern &ndash; ggf. auch über 
                        längere Zeiträume &ndash; und was können Sie zumindest derzeit nicht ändern. <b>Definieren Sie Prioritäten</b> und gehen in kleinen Schritten vor. 
                        <br />
                        <br />
                        Ich kann hier an dieser Stelle wenig konkrete Vorschläge dazu beitragen, denn Ihre eigenen Gegebenheiten sind selbstverständlich immer ganz 
                        individuell. Hilfreich ist vielleicht jedoch der Tipp, dass Sie versuchen sollten, nicht allzu sehr mit der Situation zu hadern: 
                        Fremdbestimmung &ndash; insbesondere solche, die man nicht einsieht &ndash; wird immer sehr viel einschneidender empfunden, als wenn man 
                        <b>sein Leben selbst in die Hand nehmen</b> kann &ndash; zumindest zu einem Teil. 
                        <br />
                        <a id="haltung"></a>
                        <br />
                        <hr />
                        <h5>Körperhaltung</h5>
                        <hr />
                        Angst, Unsicherheit und Stress erzeugen oftmals eine andere Körperhaltung, als wenn wir entspannt sind. Wir ziehen den Bauch ein, und die Bauchdecke 
                        verkrampft sich. 
                        <br />
                        <br />
                        Für eine gute Verdauung ist aber eine entspannte Haltung und eine aktive Bewegung der Bauchdecke (mit) entscheidend. Erst durch die Anregung des 
                        Bauches wird die Darmmuskulatur (Peristaltik) angeregt, um den Speisebrei im Darm weiter zu transportieren. Unterbleibt diese Anregung, wird oder 
                        bleibt der Darm &#187;faul&#171;, und die Nährstoffe können nicht optimal verdaut werden. Es bilden sich durch die zu lange Verweildauer vermehrt 
                        Gase, die den Darm schmerzhaft aufblähen und ungesunde Säuren, die Darmschleimhaut reizen können. Bitte lesen Sie hierzu auch den Beitrag 
                        &#187;<a href="darmgymnastik" target="_blank">Darmgymnastik</a>&#171;. 
                        <br />
                        <a id="atmung"></a>
                        <br />
                        <hr />
                        <h5>Atmung</h5>
                        <hr />
                        Durch die Ängste und den Stress atmen wir falsch: Wir füllen unsere Lungen nicht mehr in Ruhe vollständig mit Luft, sondern atmen flach und hektisch. 
                        <br />
                        <br />
                        Da auch die Atmung unser Verdauungssystem entscheidend mit beeinflusst, leidet die Verdauungsleistung zusätzlich. Bei einer <b>tiefen und entspannten 
                        Atmung</b> in Richtung Bauch regt der große Zwerchfellmuskel, der den Brustbereich vom Bauch trennt, die 
                        <a href="verdauungsdruesen" target="_blank">Verdauungsdrüsen</a> Magen, Leber, Galle und Bauchspeicheldrüse ebenso an wie den Darm selbst. Eine 
                        flache und verkrampfte Atmung behindert die Verdauung, so dass sich bereits bestehende Probleme vergrößern oder neue Beschwerden einstellen. Bitte 
                        lesen Sie auch den Beitrag &#187;<a href="atmen" target="_blank">Atem und Verdauung</a>&#171;. 
                        <br />
                        <a id="stressverdauung"></a>
                        <br />
                        <hr />
                        <h5>Verdauung unter Stress</h5>
                        <hr />
                        Wie oben beschrieben, bedeuten psychischer Dauerstress, Ängste, falsche Körperhaltung und Atmung, dass unser Verdauungssystem ebenfalls unter 
                        Dauerstress steht und vom Sympathikus auf ein Minimum herunterreguliert wird. Der Darm transportiert den Speisebrei unzureichend vom Magen zum 
                        Ausgang, so dass diverse Probleme wie Verstopfung, aber auch Durchfälle, Blähungen und Bauchschmerzen vermehrt auftreten bzw. verstärkt werden 
                        können. Die Verdauungsdrüsen produzieren weniger Enzyme, wodurch die Nährstoffe nicht mehr korrekt verarbeitet werden können. Unter solchen 
                        Bedingungen hält sich dann auch keine <a href="darmfloragrundsatz" target="_blank">gesunde Mikrobiota</a>, und das Gleichgewicht der 
                        Darmbakterien verändert sich &ndash; leider hin zu einer ungünstigeren Besiedelung. Dies wiederum hat gravierende Konsequenzen für die 
                        <a href="darmschleimhaut" target="_blank">Darmschleimhaut</a>, die auf gesunde Mikroorganismen angewiesen ist. Alles keine guten 
                        Voraussetzungen für eine gut funktionierende Verdauung!
                        <br />
                        <a id="bewertung"></a>
                        <br />
                        <hr />
                        <h5>Bewertung der Situation</h5>
                        <hr />
                        Ganz wichtig ist es, wie Sie die jeweilige Situation bzw. die jeweiligen <b>Situationen bewerten</b> und deren (derzeitigen) Stellenwert einordnen.
                        <br />
                        <br />
                        Am belastendsten finden wir Situationen, denen wir uns schutzlos ausgeliefert sehen. Und ja, an vielen Umständen können wir tatsächlich nichts oder 
                        nur wenig ändern. Hier hilft nur, die Einstellung dazu zu ändern. Ein Beispiel: die Klimakrise ist mit großer Wahrscheinlichkeit kaum noch zu stoppen. 
                        Aber trotzdem kann ich mit meinem Verhalten dazu beitragen, das Fortschreiten zu verlangsamen, <b>selbst wenn mein eigener Beitrag verschwindend 
                        gering erscheint</b>. Erstens können jedoch Milliarden kleinster Beiträge zu einem sehr, sehr großen Ganzen zusammenwachsen, zweitens aber &ndash; 
                        und das ist für Sie ganz wichtig &ndash;: es gibt es Ihnen das Gefühl, doch etwas tun zu können. Es macht Mut, mit dem eigenen Konsumverhalten zu 
                        diesem Großen und Ganzen beitragen zu können. Und wir haben das Recht (und aus meiner Sicht auch die Pflicht), unsere demokratischen, 
                        gesellschaftlichen Möglichkeiten beispielsweise bei Wahlen zu nutzen, um die richtigen politischen Parteien zu wählen, von denen man annehmen 
                        darf, dass ihnen das Weltklima wichtig ist. Es gibt <b>zahlreiche andere Optionen</b>, Einfluss zu nehmen. Vielleicht müssen wir uns hier ein wenig aus 
                        unserer Wohlfühlzone begeben, aber die Augen zu verschließen, wird bitterere Konsequenzen haben.
                        <br />
                        <br />
                        Ein weiteres Beispiel wäre der Tod eines Angehörigen: nein, an diesem Verlust können Sie nichts ändern. Aber Sie können und dürfen sich Zeit geben, 
                        zu trauern und lernen, sich an die gemeinsame Zeit zu erinnern. Durch diese aktive Trauerarbeit <b>nehmen Sie die Verantwortung für sich wieder in 
                        die eigene Hand</b>.
                        <br />
                        <br />
                        Es gäbe zahlreiche weitere Stresssituationen, zu deren Lösung man mit größeren oder kleineren Verhaltensänderungen beitragen kann. 
                        <br />
                        <a id="verdauungsprobleme"></a>
                        <br />
                        <hr />
                        <h5>Analyse der Verdauungsprobleme</h5>
                        <hr />
                        Sie alle werden wahrscheinlich, da Sie hier auf dieser Website schnuppern, Verdauungsprobleme haben, die für Sie belastend sind.
                        <br />
                        <br />
                        Auch hier hilft die <b>genaue Analyse</b>: wann haben die Probleme begonnen?, können bestimmte Lebensmittel mit den Beschwerden in Verbindung 
                        gebracht werden?, ändern sich die Intensitäten der Symptome im Laufe der Tageszeiten oder Wochentage?
                        Lesen Sie hierzu gerne auch den Beitrag &#187;<a href="stuhlgang" target="_blank">Stuhlgang &ndash; Probleme und Lösungen</a>&#171;.
                        <br />
                        <br />
                        Und gerade hier gibt es schon <b>viele Tipps und Stellschrauben</b>, die es wert sind, darüber nachzudenken: Evtl. können Sie durch die Möglichkeit, 
                        zu Hause zu arbeiten statt ins Büro zu müssen, Ihre Mahlzeiten besser organisieren. Vielleicht können Sie entspannter auf die Toilette gehen, 
                        weil es Ihre eigene ist und Sie (und Ihr Darm) über die Entleerungszeiten besser bestimmen können. Es ist vernünftig bei den Lebensmitteln zu 
                        schauen, besondere Beschwerdeauslöser testweise wegzulassen. Dies aber bitte nicht über längere Zeiträume, sondern nur zur Untermauerung einer 
                        Diagnose. Vor allem aber wird eine solche Maßnahme nur dann zielführend sein, wenn sich das Stresslevel insgesamt dadurch minimiert. Wenn die 
                        Diät allerdings zu zusätzlichem Stress führt, muss geschaut werden, dass man das Problem anders löst.
                        <br />
                        <br />
                        Viele Betroffene arbeiten auch mit <b>Nahrungsergänzungsmitteln</b>. Ich möchte jedoch ausdrücklich davor warnen, diese Mittel als allein selig 
                        machende zu verstehen. Damit begäbe man sich in die Abhängigkeit solcher Mittel, die im Zweifelsfalle nicht das halten können, was sie versprechen. 
                        Diese können als Therapiebegleitung durchaus sinnvoll sein, aber die Verantwortung für Ihre eigene Verdauung kann nicht auf ein (oder mehrere) 
                        Mittel allein abgewälzt werden. Bitte lesen Sie hierzu auch den Beitrag &#187;<a href="nahrungsergaenzungsmittel" target="_blank">Grundsätze 
                        von Nahrungsergänzungsmitteln</a>&#171;.
                        <br />
                        <a id="stressmanagement"></a>
                        <br />
                        <hr />
                        <h5>Stressmanagement</h5>
                        <hr />
                        Oft ist es nicht möglich, Stesssituationen abzustellen, und die Möglichkeiten, Stresshormone durch Bewegung abzubauen, sind heutzutage ja 
                        eher begrenzt. Wer kann schon vor seinem Chef davonlaufen oder ihn gar angreifen, so wie der Urmensch dies mit dem Säbelzahntiger tat? Hier hilft nur 
                        die <b>Kompensation</b>: Glücklicherweise reagiert unsere Parasympathikus auch darauf, wenn wir im Anschluss an Stress ganz gezielt für Entspannung 
                        sorgen &ndash; sei es durch gezielte Übungen oder auch &#187;nur&#171; durch einen Spaziergang, Musikhören, ein schönes Bad oder was auch immer 
                        Sie als entspannend empfinden. Hilfreich kann z.B. auch eine Meditation sein. Schauen und hören Sie sich doch einmal die auf dieser 
                        Website befindliche &#187;<a href="videos#darmbakterienmeditation" target="_blank">Darmbakterien-Meditation</a>&#171; an.
                        Und lesen Sie hierzu auch gerne die Beträge &#187;<a href="ganz-entspannung" target="_blank">Entspannung</a>&#171; und 
                        &#187;<a href="akupressur" target="_blank">Akupressur zur Beeinflussung von Magen-/Darmproblemen</a>&#171;.
                        <br />
                        <br />
                        <b>Stressmanagement</b> ist etwas ganz anderes als Stressvermeidung oder Stressreduktion. Ein völlig stressfreies Leben ist erstens nicht erreichbar und 
                        zweitens auch gar nicht anzustreben &ndash; wobei hier an dieser Stelle ja immer der negative Stress (Disstress) gemeint ist. Positiver Stress 
                        (Eustress) beflügelt uns und regt uns an und weckt unser Interesse und unsere Neugier.
                        <br />
                        <br />
                        Stressmanagement bedeutet zu erkennen, was ist mein Antriebsmotor und was hemmt mich. Und in letzter Kategorie bedeutet es abzuwägen: was kann ich 
                        vermeiden?, was kann ich minimieren? und was kann ich kompensieren? Dies alles zusammen ergibt eine wirkungsvolle Maßnahme, <b>konstruktiv mit 
                        Stress umzugehen</b>. 
                        <br />
                        <a id="einstellung"></a>
                        <br />
                        <hr />
                        <h5>Einstellung ändern</h5>
                        <hr />
                        Manchmal hilft es auch, <b>die eigene Einstellung zu bestimmten Situationen zu ändern</b>. Auch Verdauungsbeschwerden können erträglicher werden, 
                        wenn ich einiges gelassener hinnehme und nicht mehr dagegen Sturm laufe. Durchfall ist selbstverständlich nicht erträglich, aber ein wenig Blubbern 
                        im Bauch ist nicht so schlimm und muss nicht unbedingt und automatisch zu größeren Problemen führen. Blähungen sind ebenfalls belastend, aber ab 
                        und an etwas Luft abzulassen, ist ganz normal. Ggf. hilft ja hier auch ein kleiner Spaziergang, um die Gassitutation im Darm unauffälliger zu klären.
                        <br />
                        <br />
                        Ich kann verstehen, dass dauerhafte Verdauungsprobleme zermürben, und kenne dies ja auch selbst. Aber ich bin überzeugt, dass auch für Sie 
                        etwas Positives dabei sein kann: <b>ein halb leeres Glas ist immer auch halb voll</b>! Und wenn Ihr persönliches Glas nicht halbvoll ist, so 
                        sollte doch zumindest ein kleiner, aber vielversprechender und ausbaufähiger Bodensatz an Positivem enthalten sein. 
                        <br />
                        <br />
                        Dieses Positive verdient es, adäquat bewertet zu werden. Nicht immer und vor allem nicht nur die Negativen Erlebnisse sind es, die unseren Tag ausmachen.
