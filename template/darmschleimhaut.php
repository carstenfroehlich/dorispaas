                        <a id="funktionen"></a>
                        <hr />
                        <h5>Funktionen der Darmschleimhaut</h5>
                        <hr />
                        Haut und Schleimhäute haben die Funktion, eine Barriere nach au&#223;en zu bilden, um das Körperinnere zu schützen. Die Darmschleimhaut hat auf der 
                        einen Seite die Aufgabe, <b>unverdauten Bestandteilen, Schad- und Giftstoffen den Eintritt in den Körper verwehren</b>, um Beeinträchtigungen vom 
                        Organismus fernzuhalten. Diese Barrierefunktion gehört übrigens zu unserem &#187;angeborenen Immunsystem&#171;, das im Gegensatz zum &#187;erworbenen 
                        Immunsystem&#171;, das sich erst im Laufe unseres Lebens mit den Kontakten mit Krankheitserregern ausbildet, bereits mit unserer Geburt vorhanden ist.
                        <br />
                        <br />
                        Auf der anderen Seite aber soll die Darmschleimhaut <b>verdaute Nährstoffe ins Körperinnere hineinlassen</b>, damit diese dort ins Blut gelangen und 
                        zu den Körperzellen bzw. den weiterverarbeitenden Organen befördert werden können. Dies ist die Verdauungsfunktion, die unsere Darmschleimhaut zu 
                        erledigen hat.
                        <br />
                        <br />
                        Eigentlich ist dies die Quadratur des Kreises &ndash; und doch kann eine gesunde Schleimhaut genau dies leisten.
                        <br />
                        <br />
                        Da die Schleimhaut dies alleine nicht bewerkstelligen kann, bedient sie sich der Hilfe der Darmbakterien, die untrennbar mit der Funktionsfähigkeit 
                        der Darmschleimhaut verbunden sind. Auch wenn hier von den &#187;Darmbakterien&#171; gesprochen wird, sind hier alle Mikroorganismen gemeint, also 
                        auch verschiedene andere Einzeller und Pilze. Salopp spricht man von der Darmflora, korrekt hei&#223;t es heute jedoch <b>Mikrobiota</b>. Die Darmschleimhaut kann 
                        als &#187;Nest&#171; für die Darmbakterien angesehen werden, und es ist einsichtig, dass sich die Darmbewohner in einem ungemütlichen Nest nicht wohlfühlen würden. 
                        <br />
                        <br />
                        Aber die Darmbakterien tun auch von ihrer Seite aus alles Erdenkliche, um ihr eigenes Zuhause schön &#187;einzurichten&#171;: bestimmte Arten wie u.a. 
                        verschiedene H<sub>2</sub> O<sub>2</sub>-bildende Laktobazillen lösen zunächst den alten Schleim an. Andere Bakterien wie Akkermansia muciniphila und Faekalibacterium 
                        prausnitzii fressen ihn &ndash; wobei diese Arten durchaus zum &#187;Sattwerden&#171; auch noch Ballaststoffe aus der Nahrung benötigen &ndash; und 
                        sondern Stoffwechselprodukte wie u.a. die Buttersäure ab. Diese Stoffwechselprodukte stellen neben dem Darmschleim selbst auch <b>Nährstoff für die 
                        Schleimhautzellen</b> dar. Zusätzlich aber regen sie auch die so genannten Becherzellen in der Schleimhaut an, neuen Schleim zu bilden. Erst durch 
                        diesen Kreislauf ist die Gesundheit und damit die optimale Funktion der Darmschleimhautzellen gewährleistet. 
                        Man sieht, dass dies alles ein kompliziertes Zusammenspiel von verschiedenen Faktoren in diesem lebenden Gebilde ist, und wenn auch nur an einer Stelle 
                        diese Kooperation hakt, funktioniert auch alles andere nicht gut. 


