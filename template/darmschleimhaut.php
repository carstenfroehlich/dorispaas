                        <a id="schutzstoffe"></a>
                        <hr />
                        <h5>Produktion von Schutzstoffen</h5>
                        <hr />
                        Neben der oben geschilderten Barrierefunktion &ndash; eines der Hauptelemente unseres angeborenen Immunsystems &ndash; werden in der Darmschleimhaut auch 
                        <b>Schutzstoffe</b> wie das &#187;sekretorische Immunglobulin A&#171; (sIgA) gebildet, die 
                        für die Gesunderhaltung der Schleimhaut erforderlich sind. Und nicht nur für die Gesunderhaltung der Schleimhaut im Darm, denn diese Schutzstoffe werden im gesamten 
                        Körper verteilt auf allen anderen Schleimhäuten, also im Darm, in Bronchien und Lunge, im Nasen-Rachenraum, in den Augen und im Urogenitaltrakt. 
                        <br />
                        <br />
                        Weiterhin gibt es Stoffe wie u.a. das &#187;Beta-Defensin&#171; oder das &#187;Lysozym&#171;, die wie <b>körpereigene Antibiotika</b> um und innerhalb der
                        Schleimhaut wirken und krankheitserregende Keime inaktivieren oder sogar abtöten können. Neben diesen erwähnten Beispielen gibt es viele weitere Stoffe, die 
                        für die Gesunderhaltung der Schleimhautzellen und damit für eine optimale Funktion sorgen.


                        <br />
                        <br />
                        <a id="enzymproduktion"></a>
                        <hr />
                        <h5>Produktion von Enzymen und Transportproteinen</h5>
                        <hr />
                        Eine weitere wichtige Aufgabe der Schleimhautzellen ist die Bildung von <b><a href="enzyme" target="_blank">Enzymen</a></b>. Diese Enzyme werden benötigt, 
                        um komplexere Kohlenhydrate in der Nahrung 
                        wie Zweifachzucker (Disaccharide, z.B. die Laktose, die das Enzym Laktase benötigt), Mehrfachzucker (Oligosaccharide, z.B. Raffinose oder Stachyose), Vielfachzucker 
                        (Polysaccharide, also Ballaststoffe) oder Stärke in ihre Bausteine aufzuspalten und dafür zu sorgen, dass sie durch die Darmschleimhaut hindurchgelangen können. Die 
                        Enzyme werden nicht in den Nahrungsbrei abgegeben, sondern verbleiben in oder direkt auf den Zellen und lassen nur kleine &#187;Fühler&#171; in den Speisebrei hinaushängen. 
                        Berührt nun ein Zucker einen Fühler für sein speziell benötigtes Verdauungsenzym, wird der <b>Aufspaltungsvorgang katalytisch</b> in Gang gesetzt. Katalytisch bedeutet, 
                        dass sich das Enzym nicht aufbraucht, sondern mehrere Spaltvorgänge anregen kann. Jedoch brechen die kleinen Fühler durch die Beanspruchung der vorbeirutschenden 
                        Speisen rasch ab. Aber mit den sich häufig erneuernden Zellen stehen dann auch wieder neue und funktionsfähige Enzyme zur Verfügung.
                        <br />
                        <br />
                        Einfachzucker benötigen zwar keine Enzyme zum Aufspalten, da sie ja nur aus jeweils einem Baustein bestehen. Manche Einfachzucker benötigen jedoch <b>Transportproteine</b> 
                        (Glukosetransporter), um durch die Schleimhaut &#187;getragen&#171; zu werden. Die Fruktose zum Beispiel benötigt die Transportproteine GLUT2 und GLUT5. Auch diese 
                        Substanzen werden in den Darmschleimhautzellen gebildet.
                        <br />
                        <br />
                        Und auch für andere Stoffe, die keine Kohlenhydrate sind, werden in den Schleimhautzellen des Dünndarms Enzyme gebildet, um diese Stoffe abzubauen. 
                        Zu nennen wäre hier u.a. das Histamin, das zum einen ein vom Körper selbst gebildeter Botenstoff ist, zum anderen aber auch mit der Nahrung aufgenommen wird. Um nicht 
                        überhand zu nehmen, muss das Histamin durch das Enzym Diaminoxidase (DAO) abgebaut und die zirkulierende Menge in einem optimalen Rahmen gehalten werden.
                        <br />
                        <br />
                        Werden in gereizten, entzündeten oder unterernährten Schleimhautzellen zu wenige Enzyme gebildet, führt dies je nach Funktionseinschränkung zu mehr oder weniger 
                        ausgeprägten <a href="<?= URL_ROOT ?>darmschleimhaut#unvertraeglichkeiten">Nahrungsmittel-Unverträglichkeiten</a>.
 


