                        <a id="immunsystem"></a>
                        <hr />
                        <h5>Das Immunsystem</h5>
                        <hr />
                        Bereits bei unserer Geburt verfügen wir über ein <b>angeborenes Immunsystem</b>. Dieses besteht aus einer gesunden Schleimhaut, die durch ihre <b>Barrierefunktion</b> 
                        verschiedenen Keimen den Eintritt in den Körper verwehrt.
                        <br />
                        <br />
                        Andere Erreger erkennt zwar das kindliche Immunsystem noch nicht selbst, aber durch den so genannten &#187;Nestschutz&#171;, der sich durch die Antikörper, die 
                        der Embryo im Mutterleib übertragen bekommen hat, ergibt sich für einige Monate ein erweiterter Schutz. Weitere Abwehrstoffe werden mit der mit der Muttermilch 
                        aufgenommen, so dass der Säugling gegen alle die Krankheiten geschützt ist, die die Mutter durchgemacht und gegen die sie Antikörper entwickelt hat.
                        <br />
                        <br />
                        Im Laufe des Lebens entwickelt sich dann ein eigenes Immunsystem. Sobald der Organismus mit Krankheitserregern in Berührung kommt, entwickelt er die Fähigkeit, 
                        diese als Antigene zu erkennen und Antikörper dagegen zu bilden. Dieses <b>erworbene Immunsystem</b> speichert die Beschaffenheit dieser Antigene und kann bei 
                        erneuter Exposition rasch genügend <b>Antikörper</b> bilden, damit wir nicht erneut oder zumindest nicht so heftig erkranken.
                        <br />
                        <br />
                        Um sich mit bisher noch unbekannten Erregern auseinandersetzen zu können, ist es vorteilhaft, wenn dies zunächst behutsam geschieht. Dazu gibt es in der 
                        Darmschleimhaut bestimmte Bereiche, die &ndash; entgegen der gro&#223;en Gesamtheit der Schleimhaut &ndash; ein wenig durchlässiger sind. Man kann sich diese 
                        so genannten <b>Peyer‘schen Plaques</b> wie ein kleines, engmaschiges Sieb vorstellen, durch die die eigentlich ja unerwünschten und in grö&#223;eren Mengen 
                        gefährlichen Krankheitserreger in kleiner Anzahl hindurchgelassen werden. Hinter diesen Stellen treffen die wenigen Keime jetzt auf die T-Zellen, die sie nun 
                        kennenlernen und entsprechende Informationen an die B-Zellen weitergeben können, die wiederum lernen, die Antikörper herzustellen. Wie bei einer Impfung, bei 
                        der ja auch nur kleinste, meist inaktivierte Erregermengen oder Teile derselben in den Körper gebracht werden, kann sich dieser Teil des Immunsystems an die 
                        neuen Erreger gewöhnen und die Produktion der Antikörper verinnerlichen. 
                        <br />
                        <br />
                        Das angeborene Immunsystem ist zwar nicht so spezifisch wie das erworbene, aber bereits dieses ist schon eine starke Waffe im Kampf gegen Krankheiten. Wenn 
                        Krankheitserregern durch eine intakte Schleimhautbarriere der Eintritt in den Körper verwehrt wird, können diese nicht so viel ausrichten, als wenn sie diese 
                        Schranke überwinden und in die Körperzellen eindringen könnten. 
                        <br />
                        <br />
                        Aber auch hier gilt: nur eine intakte Schleimhaut stellt ein funktionierendes angeborenes Immunsystem dar. In einer gesunden Schleimhaut gibt es eine ausreichende 
                        Anzahl von Peyer‘schen Plaques, die dafür sorgen, dass sich auch das erworbene Immunsystem korrekt entwickeln kann. <b>Beide Immunsysteme hängen eng miteinander 
                        zusammen, und alles steht und fällt mit der Qualität der Darmschleimhaut</b>.


                        <br />
                        <br />
                        <a id="krankheiten"></a>
                        <hr />
                        <h5>Erkrankungen der Darmschleimhaut</h5>
                        <hr />
                        Wie oben erwähnt, können grundsätzlich nur gut genährte, gesunde Schleimhautzellen die an sie gestellten Anforderungen erfüllen, denn unterernährte oder gar entzündete 
                        Zellen sind dünn und rücken somit weiter auseinander. Entstehen bei dünneren Zellen grö&#223;ere Zwischenräume, können sich die beiden Seiten dieser Klettverschlüsse 
                        nicht mehr berühren und zusammenhalten und bleiben ständig geöffnet &ndash; Tür und Tor sind für alles, ob es nun eigentlich gut oder schlecht ist, weit offen, egal 
                        wie hoch der Zonulin-Spiegel ist. Dies ist das so genannte &#187; <b>Leaky-Gut-Syndrom</b>&#171; (leaky = leck, undicht, engl.; gut = Darm, engl.) &ndash; mit den oben 
                        geschilderten Folgen.
                        <br />
                        <br />
                        Es gibt verschiedene Ursachen, warum sich Darmschleimhautzellen entzünden können. Hier sind z.B chemische Schadstoffe oder auch Medikamente zu nennen, die wir aufnehmen 
                        und die die Zellen reizen. Aber auch eine entgleiste Mikrobiota kann mit den dann in unangemessener Menge entstehenden Stoffwechselprodukten wie Säuren und Gasen der 
                        Schleimhaut zusetzen. Das Gleiche gilt bei zu geringem Verzehr von Ballaststoffen, da dann die schleimerneuernden Bakterien (muconutritive Flora) in nicht ausreichender 
                        Zahl vorhanden sind. Und natürlich erst recht bei einem unangemessenem Verzehr <a href="<?= URL_ROOT ?>darmschleimhaut#unvertraeglichkeiten">unverträglicher Nahrungsmittel</a> oder 
                        bei <a href="<?= URL_ROOT ?>darmschleimhaut#allergien">Allergien</a>. Diese Entzündungen sind meist nicht im Zuge einer Darmspiegelung zu erkennen &ndash; es handelt 
                        sich hier i.d.R. um kleinere <b>Mikroentzündungen</b>, die jedoch die Funktion des Systems durchaus gravierend beeinträchtigen können.
                        <br />
                        <br />
                        Weiterhin gibt es die <b>chronisch entzündlichen Darmerkrankungen</b> (CeD) wie <a href="<?= URL_ROOT ?>ced">Morbus Crohn oder Colitis ulcerosa</a>, bei sich in Teilen des Darms die Schleimhaut sehr 
                        stark entzünden kann. Diese schweren Entzündungen sind, wenn sie im Dickdarm auftreten, in der Spiegelung gut sichtbar, die Schleimhaut kann sogar bluten, was man am 
                        Stuhl mit blo&#223;em Auge erkennen kann (da Darmspiegelungen nur den Dickdarm erfassen, können Entzündungsprozesse der Schleimhaut im Dünndarm auf diesem Wege nicht 
                        erkannt werden). Chronisch entzündliche Darmerkrankungen treten oft schubweise auf und gehen oft mit stärksten Beschwerden einher. Die Diagnostik und Behandlung gehören 
                        auf jeden Fall in ärztliche Hände.
                        <br />
                        <br />
                        Manche Menschen erkranken an der Autoimmunkrankheit <b><a href="<?= URL_ROOT ?>zoeliakie" target="_blank">Zöliakie</a></b>. Hier reagiert das Immunsystem auf das Klebereiwei&#223; Gluten, 
                        das in Weizen, Roggen, Gerste und deren Unterarten enthalten ist. Sobald Gluten verzehrt wird, beginnt das Immunsystem, die Darmschleimhautzotten zu zerstören &ndash; mit 
                        den daraus resultierenden Folgen. Wird das Gluten strikt gemieden, kann sich die Darmschleimhaut erholen, und bei konsequenter Karenz erscheint der Betroffene vollkommen 
                        gesund. Die Krankheit an sich ist erblich, es ist jedoch noch nicht abschlie&#223;end erforscht, ob, wann und warum sie ausbricht.
                        <br />
                        <br />
                        Sehr häufig kann man bei Menschen mit CeD und auch mit einer Zöliakie eine mehr oder weniger <b>eingeschränkte Vielfältigkeit</b> (Diversität) der Mikrobiota feststellen, 
                        was zeigt, wie eng die Qualität der Darmschleimhaut mit der Qualität der Mikrobiota zusammenhängt. Dies bedeutet jedoch nicht, dass man eine Zöliakie oder eine CeD entwickelt, 
                        wenn die Darmflora entgleist ist, denn es gibt viele weitere Faktoren &ndash; teils auch noch gar nicht erforschte &ndash; die bei der Ausbildung dieser Darmerkrankungen 
                        ausschlaggebend sind. Tatsache ist jedoch, dass eine ungenügende Zusammensetzung der Darmflora Schübe von CeD begünstigen kann und &ndash; im Gegenzug &ndash; eine stabile 
                        Mikrobiota mit möglichst vielen verschiedenen Bakterienarten die Anzahl und/oder Schwere und Dauer von Schüben verringern kann.
 

                        <br />
                        <br />
                        <a id="allergien"></a>
                        <hr />
                        <h5>Nahrungsmittel-Allergien</h5>
                        <hr />
                        Bei <b>Nahrungsmittel-Allergien</b> reagiert unser Immunsystem auf Nahrungsmittel, die normalerweise vollkommen unproblematisch sind. Dies können Milch, Eier, Äpfel oder Nüsse 
                        sein, aber auch jedes andere Lebensmittel, das den meisten Menschen gut bekommt.
                        <br />
                        <br />
                        Zur Ausbildung einer Allergie braucht es eine Sensibilisierungsphase, in der nach einem ersten Kontakt mit dem Allergen innerhalb einer Zeitspanne das <b>Immunsystem</b> 
                        (fälschlicherweise) lernt, dass es sich hier um eine zu bekämpfende Substanz handelt. Werden danach diese Stoffe &ndash; es ist nie das Lebensmittel in Gänze, sondern nur 
                        kleinere Proteinteile &ndash; erneut aufgenommen, fährt das Immunsystem nun die Schutzarmada auf und bekämpft mit allen Mitteln die vermeintlichen &#187;Schadstoffe&#171;. 
                        <br />
                        <br />
                        Bestandteile von Nahrungsmitteln, auf die man allergisch reagiert und die die Schleimhautbarriere überwinden und in den Körper eindringen, werden selbstverständlich besonders 
                        bekämpft, denn dort können sie dem Organismus wesentlich &#187;gefährlicher&#171; werden, als Stoffe, die an der Körperoberfläche bleiben.
                        <br />
                        <br />
                        Eine intakte Darmschleimhaut kann vor Allergien bzw. zumindest vor der Schwere der allergischen Reaktionen schützen. Dies hei&#223;t keinesfalls, dass Menschen, die bereits 
                        schwere allergische Reaktionen wie einen <b>anaphylaktischen Schock</b> hatten, nach einer Sanierung der Darmschleimhaut nun unbedenklich ihr Allergen verzehren könnten. 
                        Aber Allergien mit einem weniger ausgeprägten Beschwerdebild können bei einer intakten Schleimhaut, die mit ihrer Barrierefunktion das Eindringen der Allergene wirksam 
                        verhindert, in ihrer Häufigkeit und ihrer Intensität gemildert werden.
                        <br />
                        <br />
                        Es ist zudem zu beobachten, dass Allergien meist infolge einer <b>Exposition mit mehreren Störfaktoren</b> auftreten &ndash; seien es mehrere verschiedene Allergene oder auch 
                        das eine oder andere Allergen und eine zusätzliche Unverträglichkeit. Wenn durch eine lädierte Schleimhaut schon mehrere verschiedene Stoffe in den Körper gelangt sind 
                        &ndash; u.U. ohne dass sich bis dahin Symptome gezeigt haben &ndash; kann dann ein weiteres Allergen oder eine grö&#223;ere Menge das Fass zum Überlaufen bringen. Ggf. 
                        können auch Nahrungsmittel, die bisher keine Probleme bereitet haben, die defekte Schleimhautbarriere überwinden, ohne korrekt verdaut worden zu sein und belasten dann 
                        das System zusätzlich.
                        <br />
                        <br />
                        Eine gesunde Darmschleimhaut kann also auch vor Allergien bzw. der Intensität der Reaktionen schützen. Übrigens gilt dies nicht nur für die Nahrungsmittel-Allergien, bei 
                        denen die Allergene über das Verdauungssystem aufgenommen werden, sondern durchaus auch für alle anderen Allergien. Wie oben erwähnt, wird der in der Darmschleimhaut 
                        gebildete Schutzstoff sIgA auf den Schleimhäuten im gesamten Körper verteilt, also z.B. auch auf die Schleimhäute von Bronchien und Lunge. Die hier eindringenden 
                        &#187;respiratorischen&#171; Allergene wie z.B. Pollen können bei so geschützten Schleimhäuten weniger ausrichten.


                        <br />
                        <br />
                        <a id="unvertraeglichkeiten"></a>
                        <hr />
                        <h5>Nahrungsmittel-Unverträglichkeiten</h5>
                        <hr />
                        Neben den Allergien, bei denen das Immunsystem auf Proteinbestandteile aus den Nahrungsmitteln reagiert, gibt es die <b>Nahrungsmittel-Unverträglichkeiten</b>. Hier ist 
                        das Immunsystem nicht beteiligt. Bei einer Unverträglichkeit <b>mangelt es an Enzymen oder Transportproteinen</b> zur Verarbeitung. Da durch diesen Mangel die entsprechenden 
                        Kohlenhydrate oder auch Botenstoffe nicht (ausreichend) aufgespalten, abgebaut oder transportiert werden können, gelangen die unverarbeiteten Kohlenhydrate in den Dickdarm 
                        bzw. reichern sich die Botenstoffe wie das Histamin im Körper an.
                        <br />
                        <br />
                        Unaufgespaltene Nahrungszucker werden von den Bakterien im Dickdarm vergoren, wobei Gase und Säuren als Abfallprodukte entstehen. Erstere werden als Blähungen wahrgenommen, 
                        und die Gase reizen die Schleimhaut.
                        <br />
                        <br />
                        In einer gereizten Schleimhaut, in der ein ungünstiges Säuremilieu herrscht, fühlen sich die vorteilhaften Darmbakterien nicht richtig wohl &ndash; die &#187;schlechten&#171;, 
                        die robuster sind, können sich überproportional fortpflanzen und nach und nach die &#187;guten&#171; verdrängen. Die Balance der Dickdarmflora entgleist, die dann ihre 
                        eigentlichen Aufgaben wie u.a. auch die Ernährung der Schleimhautzellen immer weniger wahrnehmen kann.
 

                        <br />
                        <br />
                        <a id="sibo"></a>
                        <hr />
                        <h5>Dünndarmfehlbesiedelung (SIBO)</h5>
                        <hr />
                        Wenn auf eine (oder mehrere) Unverträglichkeit(en) nicht mit der angepassten Ernährung reagiert wird und zu viele unbekömmliche Stoffe in den Dickdarm gelangen, können kleinere 
                        Mengen der entstehenden Gase durch die Ileozökalklappe &ndash; eine Engstelle zwischen Dünn- und Dickdarm &ndash; hindurchgedrückt werden und Dickdarmbakterien nach oben tragen. 
                        Wenn diese &#187;normalen&#171; <b>Dickdarmbewohner im Dünndarm</b> weiter nach oben gelangen, entwickelt sich dort eine so genannte 
                        <a href="<?= URL_ROOT ?>duenndarmfehlbesiedelung" target="_blank">Dünndarmfehlbesiedelung</a> oder SIBO (small intestine bacterial overgroth, engl.).
                        <br />
                        <br />
                        Sobald die Bakterien im Dünndarm abgetötet oder &ndash; besser noch &ndash; an ihren eigentlichen Wirkort im Dickdarm zurückgedrängt wurden, verschwinden auch die für diese 
                        Erkrankung typischen Beschwerden wie der aufgeblähte Bauch, Schmerzen, Bauchgrummeln, Völlegefühl und vieles mehr.
 

                        <br />
                        <br />
                        <a id="pflege"></a>
                        <hr />
                        <h5>Pflege und Sanierung der Darmschleimhaut</h5>
                        <hr />
                        Bei Erkrankungen des Darmes, einem schlecht funktionierenden Immunsystem, nach Antibiotika- oder Bestrahlungstherapien oder aber nach besonderen Stresssituationen ist es meist 
                        erforderlich, die Darmgesundheit wiederherzustellen. Hierzu gehören neben der Pflege der Darmflora auch die Gesunderhaltung der Darmschleimhaut. 
                        <br />
                        <br />
                        Bei Erkrankungen, die die Qualität der Darmschleimhaut beeinträchtigen, sind hier zuallererst die entsprechenden Ursachen auszuschalten. Und da die Qualität der Darmschleimhaut 
                        ganz eng mit der Qualität der Mikrobiota verbunden ist, gehört die Betrachtung der &#187;<a href="darmfloragrundsatz" target="_blank">Mikrobiota</a>&#171;
                        selbstverständlich auf jeden Fall auch mit zur Betrachtung der Darmschleimhaut. All dem muss immer eine korrekte Diagnose vorausgehen, so dass man die Gründe für die Beschwerden 
                        erkennen und gezielt abstellen kann.
                        <br />
                        <br />
                        Zur Unterstützung der Ausheilung stehen auch <b>geeignete Präparate</b> zur Verfügung, es ist aber weder möglich noch dauerhaft zielführend, sich allein auf diese Mittel 
                        verlassen zu wollen, denn wenn die Ursachen für die Erkrankung weiterhin vorhanden sind, kann sich die Schleimhaut weder ausreichend noch dauerhaft erholen. Auch wenn viele 
                        gute Präparate rezeptfrei zu bekommen sind, ist es trotzdem sehr wichtig, sich <a href="beratung" target="_blank">fachlich beraten</a> zu lassen und einen 
                        <b>individuell auf Ihre Bedürfnisse zugeschnittenen Plan</b> auszuarbeiten. Ohne die erforderlichen Hintergründe zu kennen, wäre es höchst leichtsinnig, an dem ebenso empfindlichen 
                        wie lebenswichtigen Organ &#187;Darmschleimhaut&#171; herumzudoktern.
                        <br />
                        <br />
                        Trotzdem können Sie bereits vom ersten Tage an einen gro&#223;en Teil zur Sanierung und auch generell zur Pflege Ihrer Darmschleimhaut <b>selbst beitragen</b>. 
                        <br />
                        <br />
                        Eine optimale Pflege der Darmschleimhaut erreichen Sie recht einfach durch den weitgehenden <b>Verzicht auf industriell verarbeitete Produkte</b> und Sü&#223;es und durch die 
                        <b>Reduzierung von Genussmitteln</b> auf ein vernünftiges Ma&#223; und &ndash; sofern verträglich &ndash; den Umstieg auf eine <b>naturbelassene Vollwertkost</b>.
                        <br />
                        <br />
                        Lassen Sie sich <b>für einen eventuellen Umstieg auf vollwertige Nahrungsmittel genügend Zeit</b>, denn zum einen kann ein kränkliches Verdauungssystem eine abrupte Änderung übel 
                        nehmen und mit verstärkten Beschwerden wie Durchfällen und Blähungen reagieren, und zum anderen <b>ändern sich jahrelang eingeschliffene Vorlieben nicht von heute auf morgen</b>. 
                        Eine plötzliche Umstellung Ihrer Ernährung würde mit gro&#223;er Sicherheit aufgrund der auftretenden Beschwerden und der Vergewaltigung Ihrer Gewohnheiten zum Scheitern verurteilt 
                        sein. 
                        <br />
                        <br />
                        Wenn Sie an Nahrungsmittel-Unverträglichkeiten oder -Allergien leiden, sind die <b>unbekömmlichen Stoffe ab sofort so weit wie möglich zu meiden</b>, bis Sie beschwerdefrei sind. 
                        Bitte lesen Sie hierzu die entsprechenden Beiträge auf dieser Website  unter dem Menüpunkt &#187;<b>Wissendatenbank/Unverträglichkeiten</b>&#171;.
                        <br />
                        <br />
                        Unter diesen verbesserten Bedingungen können sich sowohl die Darmschleimhautzellen als auch die Mikrobiota erholen. Es versteht sich von selbst, dass die Erholungsphase Zeit 
                        benötigt &ndash; je länger zuvor ungünstige Bedingungen geherrscht haben, desto mehr Zeit benötigt auch die Erholung.
                        <br />
                        <br />
                        Mit dem Verzehr von immer mehr vollwertigen Nahrungsmitteln mit ihren rauhen Pflanzenfasern werden die alten, verhornten und abgestorbenen Zellen an der Oberfläche der 
                        Darmschleimhaut abgetragen, und die Schleimhaut verjüngt sich. Der Verzicht auf industriell verarbeitete Produkte und Sü&#223;es unterstützt die Regeneration der Darmflora, 
                        die nun wiederum mit ihren Schutzfunktionen der Darmschleimhaut hilft. 
                        <br />
                        <br />
                        Da insbesondere das Rauchen alle Schleimhäute und somit auch die Darmschleimhaut durch die zahlreichen enthaltenen Chemikalien und Schadstoffe stark belastet, sollten Sie &ndash; 
                        falls Sie an dieser Sucht leiden &ndash; einen Weg finden, sich <b>das Rauchen abzugewöhnen</b>. Mit der gleichzeitigen Reduzierung von weiteren schädlichen Genussmitteln wie u.a. 
                        auch <b>Alkohol</b> werden die Zellen in der Darmmuskulatur wieder ausreichend mit Nährstoffen versorgt. Auf diese Weise verbessert sich auch der Nahrungstransport, was sich 
                        wiederum günstig auf den Stuhlgang und damit auf die Zellen der Darmschleimhaut und auch auf die Mikrobiota auswirkt. 
                        <br />
                        <br />
                        <b>Trinken Sie ausreichend</b> stille oder kohlensäurearme Mineralwässer, Leitungswasser, Kräuter- oder Früchtetees und ab und an auch verdünnte Fruchtsäfte, damit zum 
                        einen die Flüssigkeitsversorgung der Zellen gewährleistet ist und zum anderen die <a href="stuhlgang" target="_blank">Beschaffenheit des Stuhlganges</a> nicht zu fest wird. 
                        Auf diese Weise wird die Arbeit des Darmes erleichtert, der Stuhl wird zügig durch den Darm befördert und eine zu intensive Einwirkung von Gift- und Schadstoffen auf die 
                        Darmschleimhaut unterbleibt. 
                        <br />
                        <br />
                        <b>Bewegen Sie sich möglichst viel</b> &ndash; vor allem aber kontinuierlich und treiben Sie <b>leichten Sport</b>, um die <b>Darmperistaltik zu fördern</b>, denn auch 
                        die Darmmuskulatur kann, wie die übrige Muskulatur, durch mangelhafte Bewegung verkümmern und Beschwerden verstärken. Zudem kann nur ein Darm, der von au&#223;en durch 
                        Bewegung und Sport angeregt wird, den Speisebrei gleichbleibend durch den Darm befördern. Wenn der Transport stockt, führt dies zu mehr oder weniger hartem Stuhl, und 
                        der Darm hat es schwerer. <b>Meiden Sie deshalb Verstopfung</b>, die für eine gesunde Verdauung und damit für eine gesunde Schleimhaut und Mikrobiota sehr schädlich ist. 
                        Gehen Sie dazu möglichst oft an die frische Luft, denn die Aufnahme von Sauerstoff fördert eine gute Durchblutung des gesamten Verdauungssystems, zudem leistet auch die 
                        aktive Bewegung des Zwerchfellmuskels, mit dem wir atmen, einen großen Beitrag zur Anregung der Darmmotorik..
                        <br />
                        <br />
                        Und &ndash; last but not least &ndash; ist auch die <b>Psyche</b> zu einem gro&#223;en Teil am optimalen Funktionieren Ihres Verdauungssystems und damit auch an der Qualität 
                        Ihrer Darmschleimhaut beteiligt. Deshalb sollte dieser Gesichtspunkt auf jeden Fall auch den angemessenen Raum in Ihrem Therapieplan einnehmen. Mit Sicherheit lässt sich 
                        einiges an Stress vermeiden, aber wahrscheinlich ist nicht jedes Stresserlebnis auszuschalten, ggf. aber lässt sich einiges kompensieren. Beachten sie deshalb, diesem 
                        Stress genügend <b>Entspannungsmomente</b> entgegenzusetzen &ndash; ein vernünftiges <b>Stressmanagement</b> trägt deshalb auch seinen Teil zur Pflege und zur Sanierung 
                        der Darmschleimhaut bei.
