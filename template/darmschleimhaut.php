                        <a id="tightjunctions"></a>
                        <hr />
                        <h5>Steuerung der Tight Junctions</h5>
                        <hr />
                        Der Transport vorbereiteter Nährstoffbausteine bzw. die Abwehr von ungeeigneten Bestandteilen werden durch die so genannten <b>Tight Junctions</b> ermöglicht oder verhindert.
                        <br />
                        <br />
                        Nachdem die Nährstoffe mithilfe der Enzyme in kleine Bausteine aufgespalten worden sind, passen sie durch die Zellzwischenräume hindurch. Mit Steuerungsproteinen wie dem 
                        Zonulin werden Impulse an die Tight Junctions gegeben, die Zwischenräume zu öffnen, so dass die <b>Nährstoffbausteine in den Blutkreislauf</b> gelangen können. 
                        <br />
                        <br />
                        Die Nährstoffe, die mit den verschiedenen Transportproteinen direkt durch die Zellen geschleust werden, umgehen zwar die Verschlussfunktion der Tight Junctions, 
                        können aber ohne die geeigneten Transportproteine auch nicht ins Körperinnere gelangen. Sowohl die Zellen selbst als auch die Zellverbünde haben also die Aufgabe, 
                        die verschiedenen Nährstoffe zielgerichtet für den Transport in den Körper weiterzuleiten.
                        <br />
                        <br />
                        Neben den geeigneten Nährstoffen können aber auch Schadstoffe oder Krankheitserreger diese Schranke überwinden &ndash; vorausgesetzt, die Steuerung der Tight 
                        Junctions funktioniert nicht korrekt. Wenn der Zonulin-Spiegel zu hoch ist, bekommen die Tight Junctions ständig das Signal, die Zwischenräume zu öffnen, so dass 
                        die Schadstoffe ungehindert durch diese &#187;Einfallstore&#171; gelangen können. 
                        <br />
                        <br />
                        Es versteht sich von selbst, dass auch unterernährte, gereizte oder sogar entzündete Zellen weder eine ausreichende Enzym-Produktion noch die Barriere- bzw. 
                        die Weiterleitungsfunktionen korrekt und in dem erforderlichen Rahmen aufrechterhalten können.


