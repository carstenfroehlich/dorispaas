                        Unsere Gesundheit steht und fällt mit dem Zustand unserer Darmschleimhaut. Sicherlich haben auch Sie schon einmal die Zahl 
                        80% gehört &ndash; im Zusammenhang damit, dass 80% unseres Immunsystems im Darm liege. Ob dies nun genau 80% sind, kann man 
                        mit Sicherheit nicht so genau sagen, aber die Tatsache, dass das <b>Immunsystem</b> zu einem sehr gro&#223;en Teil im Darm lokalisiert 
                        ist, ist unbestritten.
                        <br />
                        <br />
                        Aber nicht nur die Funktionsfähigkeit des Immunsystems hängt mit der Qualität der Darmschleimhaut zusammen, vor allem auch 
                        ein gro&#223;er Teil der <b>Verdauung</b> findet im Darm statt, und die Darmschleimhautzellen leisten hier einen entscheidenden 
                        Beitrag (schauen Sie sich hierzu gerne auch die &#187;<a href="ganz-verdauungssystem" target="_blank">Abbildung des Verdauungssystems</a>&#171; an).
                        <br />
                        <br />
                        Um alle diese Zusammenhänge richtig erfassen zu können, möchte ich Ihnen in diesem Beitrag den Aufbau und die Funktionen 
                        der Darmschleimhaut erklären. 
                        <br />
                        <br />
                        Übrigens: Eine objektive Betrachtung der Darmschleimhaut ist nicht möglich ohne die gleichzeitige Betrachtung der Darmflora 
                        (Mikrobiota), denn beide Systeme hängen untrennbar miteinander zusammen. Aus diesem Grunde bitte ich Sie, sich auch den Beitrag 
                        &#187;<a href="darmfloragrundsatz" target="_blank">Grundsätzliches über die Darmflora</a>&#171; durchzulesen.
                        <br />
