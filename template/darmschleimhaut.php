                        <a id="aufbau"></a>
                        <hr />
                        <h5>Aufbau der Darmschleimhaut</h5>
                        <hr />
                        Um zu verstehen, wie die Darmschleimhaut funktioniert, muss man zunächst ihren Aufbau kennen. Die Haut, die unseren Körper an Kopf 
                        und Rumpf und den Armen und Beinen umhüllt, ist aus mehreren Schichten aufgebaut und mit etwa 1,5 bis 4 mm im Vergleich zu unseren 
                        Schleimhäuten sehr dick. Die Schleimhaut des Darms nämlich ist nur so dünn wie eine Klarsichtfolie, also viel weniger als einen Millimeter 
                        dick. Sie besteht lediglich aus <b>einer einzigen Zellschicht</b>, in der jeweils nur eine Zelle neben der anderen liegt. Die 
                        Darmschleimhaut trennt das Körperäu&#223;ere vom Körperinneren.
                        <br />
                        <br />
                        Vielleicht sollte an dieser Stelle zunächst einmal erläutert werden, was das Innere und was das Äu&#223;ere des Organismus eigentlich 
                        ist. Dazu können Sie sich vorstellen, dass unser Körper wie ein eingestülpter Handschuhfinger aussieht. Im Inneren liegen alle Organe, die 
                        Muskeln und das Blut. Das Äu&#223;ere hingegen ist die Haut, aber &ndash; wie eben bei dem eingestülpten Schlauch &ndash; auch der Darm bzw. 
                        dessen Oberfläche, das so genannte Darmlumen. Alle Au&#223;enhüllen kommen mit körperfremden Stoffen aus der Umwelt in direkten Kontakt 
                        &ndash; die Haut augenfällig mit der Luft und allem, was wir berühren können. Die Schleimhäute im Darm, aber auch in Mund und Nase, den Bronchien und 
                        in der Lunge, kommen ebenfalls mit diesen Stoffen in Kontakt: mit Luft und &ndash; im Darm &ndash; mit Nahrung, die ja ebenfalls Körperfremdes darstellt.
                        <br />
                        <br />
                        <img src="<?php echo IMG_PATH; ?>darmschleimhautzellen.png" alt="Schema der Darmschleimhautzellen" class="left" />
                        Direkt hinter der Darmschleimhaut beginnt das Körperinnere &ndash; sie trennt also die eine Welt gegen die andere ab. Da die Darmschleimhaut 
                        &ndash; wie gesagt &ndash; nur aus einer Schicht von Zellen (in der nebenstehnden <i>Abbildung 2</i> mit der Nummer 1 gekennzeichnet) besteht, müssen diese eng 
                        nebeneinander liegen, um dicht zum Körperinneren hin abschlie&#223;en zu können. Die einzelnen Zellen sind durch eine Art Verschlussstücke 
                        &ndash; die so genannten &#187;<b>Tight Junctions</b>&#171; (2) verbunden. Sie können sich diese Tight Junctions (tight = dicht, engl.; 
                        junction = Verbindung, engl.) wie kleine Klettverschlüsse vorstellen, denn um erwünschte Stoffe hindurchzulassen, müssen die Zwischenräume 
                        zwischen den Zellen kurzzeitig geöffnet und anschlie&#223;end wieder verschlossen werden können. Dieses Öffnen und Schlie&#223;en der Tight 
                        Juctions wird durch bestimmte Steuerungs-Proteine wie Zonulin geregelt.
                        <br />
                        <br />
                        Durch die Berührung mit den Bestandteilen aus dem Speisebrei sind die Darmschleimhautzellen stark beansprucht und sowohl mechanischen als 
                        auch chemischen Reizen ausgesetzt: die raue Oberfläche der Speisebestandteile und die Zusammensetzung von Speisen und anderen Stoffen wie 
                        Chemikalien oder sonstigen Fremdstoffen setzt den Zellen sehr zu. Stellen Sie sich vor, Sie würden ständig in einem Brei aus mehr oder weniger 
                        groben Bestandteilen und chemischen Zusätzen baden &ndash; selbst Ihrer viel robusteren Au&#223;enhaut würde dies nicht so gut bekommen.
                        <br />
                        <br />
                        Aus diesem Grunde erneuern sich die Zellen der Darmschleimhaut alle 3 &ndash; 4 Tage, um immer frisch und gesund zu bleiben. Hier ergibt sich 
                        aber ein Problem: so schnell kann keine neue Ader wachsen, um die junge Zelle mit Nährstoffen aus dem Blut zu ernähren. Deshalb beziehen die 
                        Darmschleimhautzellen ihre Nährstoffe aus dem Darmschleim (3), der in einer relativ dicken Schicht über den Zellen liegt. &#187;Relativ&#171; 
                        hei&#223;t hier etwa ½ mm &ndash; also im Vergleich zur Dicke der Zellschicht recht viel.
                        <br />
                        <br />
                        Der <b>Darmschleim</b> gehört untrennbar ebenfalls zum &#187;System Darmschleimhaut&#171; dazu, denn ohne eine ausreichend dicke Schicht von 
                        frischem Darmschleim ist die Darmschleimhaut weder funktions- noch überlebensfähig.
                        Dieser Schleim hat neben der Ernährung der Schleimhautzellen auch die Aufgabe, sie rein mechanisch gegen das Eindringen von (unerwünschten) 
                        Keimen zu schützen. Allerdings kann nur frischer Schleim diese Aufgaben gut erledigen und muss deshalb ebenfalls ständig erneuert werden. Alter, 
                        klebriger Schleim würde die Darmschleimhautzellen eher ersticken, als sie zu nähren und zu schützen.
                        <br />
                        <br />
                        Hinter der Darmschleimhaut, also bereits im Körperinneren, zirkulieren verschiedene Zellen &ndash; u.a. <b>Immunzellen</b> wie z.B. T- und 
                        B-Zellen (4) und viele andere mehr &ndash; die die Art der eingedrungenen Substanzen prüfen: sind es Nährstoffe, sind es Bakterien oder sind 
                        es Schadstoffe? Je nach dem Ergebnis dieser Prüfung werden die Stoffe dann zu den Organen weitergeleitet und entsprechend ihrer Art be- und 
                        verarbeitet.
                        <br />
                        <br />
                        Es gibt noch weitere Schichten des Darms: direkt hinter dieser Schicht verlaufen <b>Blut- und Lymphbahnen</b>, die Nährstoffe aufnehmen und 
                        weitertransportieren und eventuell eingedrungene Schadstoffe zu den Entgiftungsorganen können.
                        <br />
                        <br />
                        Weiter gibt es ein Netz von Nerven, die die Funktionen des Darms und die Interaktion des Darms mit dem übrigen Nervensystem steuern. Dieses 
                        Nervengeflecht wird auch als &#187;enterisches Nervengeflecht&#171; oder auch als &#187;<b>Darmhirn</b>&#171; bezeichnet, das entwicklungsgeschichtlich 
                        wesentlich älter ist als unser Kopfhirn und ebenso leistungsfähig wie dieses.
                        <br />
                        <br />
                        Abschlie&#223;end zum Körperinneren liegt die <b>Darmmuskulatur</b>, die die Bewegungen des Darms ermöglicht und den Speisebrei vom Magenausgang 
                        bis zum After befördert. 
                        <br />
                        <br />
                        Weder die Blut- und Lymphbahnen, noch das Nervengeflecht und die Muskulatur gehören zur Darmschleimhaut, jedoch hängen alle diese Systeme &ndash; 
                        wie auch die übrigen Schleimhäute, die Haut am Körper und überhaupt alle unsere Zellen &ndash; eng zusammen und kommunizieren miteinander, um das 
                        reibungslose Funktionieren des &#187;System Mensch&#171; zu ermöglichen.
                        <br />
                        <br />
                        <i>Hinweis zu den Abbildungen: Die Details sind zum besseren Verständnis schematisch dargestellt, deshalb entsprechen die Grö&#223;enverhältnisse nicht 
                        der Wirklichkeit.</i>
 
