                        <a id="ausdehnung"></a>
                        <hr />
                        <h5>Ausdehnung der Darmschleimhaut</h5>
                        <hr />
                        Ein wichtiger Faktor, um alle Aufgaben erfüllen zu können, ist die Ausdehnung der Darmschleimhaut &ndash; insbesondere im Dünndarm. Wie in <i>Abbildung 1</i> oben auf dieser Seite 
                        schematisch dargestellt, ist die Darmschleimhaut des Dünndarms in Schleimhautzotten (1) aufgefaltet und diese Zotten jeweils weiter in die so genannten 
                        Mikrovilli (2), um eine <b>grö&#223;tmögliche Fläche zur Aufnahme der Nährstoffe</b> zu erreichen. Wegen des Aussehens dieser grö&#223;eren und kleineren 
                        Zotten wird die Schleimhaut im Dünndarm auch als &#187;Bürstensaum&#171; bezeichnet. Da der Dünndarm insgesamt etwa 5 bis 6 Meter lang ist, würde die 
                        Schleimhaut, wenn man alle ihre Zotten und Mikrovilli auffalten würde, mit geschätzten 400 m<sub>2</sub> die Fläche eines Tennisplatzes bedecken können.
                        <br />
                        <br />
                        Die Schleimhaut im etwa 1,5 Meter langen Dickdarm ist gemä&#223; der dortigen Funktionen nicht mehr so stark aufgefaltet, weil in diesen Abschnitt in der 
                        Regel nur noch kleinere Reste von unverdauten Nährstoffen gelangen, die dann von den Dickdarmbakterien aufgeschlüsselt und mit der Flüssigkeit über die 
                        Dickdarmschleimhaut aufgenommen werden. Aber auch diese Schicht ist dünn und von schützendem Schleim überzogen.
                        <br />
                        <br />
                        Werden die Mikrovilli oder gar die Zotten durch <a href="<?= URL_ROOT ?>darmschleimhaut#krankheiten">Erkrankungen</a> geschädigt und dadurch die Oberfläche der Schleimhaut 
                        verkleinert, kann sie ihre Aufgaben nicht oder nur noch in einem mehr oder weniger stark eingeschränkten Rahmen bewältigen &ndash; was sich zwangsläufig drastisch 
                        auf unsere Gesundheit auswirken kann.
