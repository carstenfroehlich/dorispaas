                        <h5>Gibt es das auch in laktosefrei?</h5>                       
                            erschienen in der Zeitschrift &#187;TOP-Magazin Bonn&#171;
                        <br />
                            Ausgabe Dezember 2017 (1.12.2017)
                        <hr />
                        Dass das Problem mit Nahrungsmittel-Unverträglichkeiten 
                        kein neues ist, beweist Ötzi, der vor mehr als 5.000 Jahren 
                        gelebt hat. Aus seinen Erbanlagen konnte man ablesen, 
                        dass er unter anderem unter einer Milchzucker-Unverträglichkeit, 
