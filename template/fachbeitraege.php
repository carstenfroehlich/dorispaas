                        <b>Neuer Ansatz in der Reizdarm-Therapie</b>
                        <br />
                        <h5>Fehlbesiedelung lässt den Darm rebellieren </h5>
                            erschienen in der Zeitschrift &#187;Naturarzt&#171;
                        <br />
                            Ausgabe 10/2016 (1.10.2016)
                        <hr />
                        Bis heute stellt die Therapie von Reizdarmbeschwerden Patienten und Behandler vor 
                        Probleme. Lässt sich jedoch eine Fehlbesiedelung des Dünndarms mit Dickdarmbakterien 
                        nachweisen, stehen die Chancen gut, dass die Beschwerden nach entsprechender 
                        Behandlung dauerhaft ver-schwinden. Eine sorgfältige Diagnostik klärt die 
                        Zusammenhänge und bereitet den Weg für eine erfolgreiche Therapie.<br />
                        <br />
                        <br />
                        Viele Menschen klagen über häufig wiederkehrende Verdauungsbeschwerden wie 
                        Bauchschmerzen und -krämpfe, Blähungen, Durchfälle, Verstopfung, Völlegefühl und 
                        Übelkeit. Manchmal können die Symptome mit bestimmten Nahrungsmitteln in Verbindung 
                        gebracht werden, oft aber scheinen sie völlig unabhängig davon aufzutreten.
                        <br />
                        <br />
                        Vielfach erhielten diese Patienten die Diagnose „Reizdarm-Syndrom“. Die Ärzte betonten, 
                        dass die Beschwerden großteilig psychisch bedingt seien, und tatsächlich schienen 
                        sich die Symptome in Ruhezeiten wie an Wochenen-den oder im Urlaub zu bessern. 
                        Die Behandlung erfolgte &ndash; den vorherrschenden Beschwerden entsprechend &ndash; 
                        eher symptomatisch und konnte so an der Ursache wenig ändern.
