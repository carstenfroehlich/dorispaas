                        <h5>Ernährung älterer Menschen mit Nahrungsmittelunverträglichkeiten</h5>                       
                            erschienen in der Zeitschrift &#187;Ernährung &amp; Medizin&#171;
                        <br />
                            Ausgabe 1/2011 (16.3.2011)
                        <hr />
                        Nahrungsmittel-Unverträglichkeiten können gerade bei älteren Menschen 
                        Verdauungsbeschwerden auslösen, die sowohl die Gesundheit als auch die soziale 
                        Integration negativ beeinflussen können. Senioren, die sich noch selbst versorgen 
                        und die mit einer Ernährungsumstellung ohne die nötige Anleitung überfordert 
                        wären, sollte mit der Diagnosestellung eine Ernährungsberatung verordnet 
                        werden. Bei den Patienten, die über Menüdienste oder in Senioren- oder 
                        Pflegeheimen beköstigt werden, ist es wichtig, das Personal von den Erfordernissen 
                        zu unterrichten. Somit sind ärzte und Ernährungsfachleute gleicherma&#223;en 
                        gefordert.
                        <br />
                        <br />
                        Häufige Verdauungsbeschwerden wie vor allem Blähungen, Durchfälle 
                        und/oder Verstopfung können gravierende Konsequenzen für die Senioren 
                        haben, u.a. Mangelernährung. Ebenso schwerwiegend kann eine schleichende 
                        Vereinsamung sein: Mit unkalkulierbaren Stuhlgängen geht man nicht mehr so 
                        gerne aus dem Haus und schon gar nicht unter Menschen. Auch Flatulenzen (besonders 
                        in Zusammenhang mit der im Alter meist schwächer werdenden Beckenbodenmuskulatur) 
                        sind nicht gesellschaftsfähig &ndash; und so kann sich sehr schnell eine mehr oder 
                        weniger ausgeprägte soziale Isolation entwickeln. Erschwerend kommt die nachlassende 
                        Geschicklichkeit beim An- und Auskleiden hinzu, denn im Falle eines Falles muss es 
                        schnell gehen.
