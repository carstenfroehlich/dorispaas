                        <br />
                            Ausgabe Herbst 2016 (20.9.2016)
                        <hr />
                        Eine gesunde Darmflora hat maßgeblichen Einfluss auf unser Wohlbefinden. &#187;Schade 
                        also, dass wir so wenig über sie wissen&#171;, meint die Troisdorfer Ernährungs- 
                        und Gesundheitsexpertin Doris Paas und nimmt sich des delikaten, aber unheimlich 
                        spannenden Themas an.
                        <br />
                        <br />
                        Darmflora: das klingt irgendwie anrüchig und gar nicht salongfähig. Immerhin
                        handelt es sich um Bakterien im Darm. Wenn uns jemand von seinen Herzbeschwerden
                        erzählt, nehmen wir gerne Anteil und unterhalten uns meistens ausführlich
                        über etwaige Beschwerden. Heißt es aber: &#187;Meine Darmflora ist nicht in Ordnung&#171;,
                        sind wir mitunter peinlich berührt und möchten nicht näher darauf eingehen.
                        Warum ist das so? Immerhin hat unsere Darmflora genauso wichtige Aufgaben
                        wie unser Herz, und niemand könnte ohne sie überleben. Häufig wird sie daher
                        &ndash; ebenso wie das Herz oder die Lunge &ndash; als Organ bezeichnet. Seit einigen Jahren
                        rückt sie langsam ins Bewusstsein der Forschung, den wenigsten Menschen ist
                        aber bewusst, was sie tatsächlich Großartiges für uns leistet. Nun ist es an der Zeit,
                        das zu ändern! Denn spätestens seit Giulia Enders‘ Bestseller &#187;Darm mit Charme&#171;
                        können wir endlich ungezwungener über das Thema Verdauung sprechen.
