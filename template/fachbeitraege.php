                        <h5>Oligosaccharid-Unverträglichkeit: Wenn gesundes Essen Beschwerden verursacht</h5>                       
                            erschienen in der Zeitschrift &#187;Naturarzt&#171;
                        <br />
                            Ausgabe 9/2012 (22.8.2012)
                        <hr />
                        Immer mehr Menschen haben Probleme nach dem Verzehr bestimmter Lebensmittel. 
                        Bauchschmerzen, Blähungen, Durchfälle oder Verstopfung sind häufige,
                        unliebsame Begleiter ihres Lebens. Eine Reihe von Unverträglichkeiten kann 
                        heute treffsicher diagnostiziert werden. Noch weitgehend unbekannt ist aber die
                        Oligosaccharid-Unverträglichkeit, die eine mögliche Erklärung unklarer 
                        Beschwerden liefert.
                        <br />
                        <br />
                        Neben Allergien nehmen Unverträglichkeiten (Intoleranzen) bestimmter 
                        Nahrungsmittel-Bestandteile immer weiter zu: Milchzucker- (Laktose-Intoleranz) 
                        und Fruchtzucker-Unverträglichkeit (Fruktose-Intoleranz oder -Malabsorption)
                        betreffen viele Menschen. Auch die Unverträglichkeit bestimmter Zuckeralkohole 
                        wie z.B. Sorbit kommt häufig vor. Die Histamin-Intoleranz, eine Pseudo-Allergie, 
                        ist zumindest den diagnostizierenden ärzten ein Begriff, so dass hier bei der 
                        Ursachensuche oftmals in die richtige Richtung geschaut wird.
