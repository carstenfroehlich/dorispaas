                        <h5>Selbsttests bei Nahrungsmittel-Unverträglichkeiten &ndash; eine sinnvolle Alternative zum Arztbesuch?</h5>                       
                            erschienen in der Zeitschrift &#187;Ernährung im Fokus&#171;
                        <br />
                            Ausgabe 9-10/2014 (1.9.2014)
                        <hr />
                        Menschen mit Verdauungsproblemen berichten häufig, dass es nicht einfach ist, 
                        schnell und vor allem zuverlässig die Ursache ihrer Beschwerden ermitteln zu können. 
                        Zudem gibt es für eine Diagnose oftmals lange Wartezeiten bei den Ärzten. Häufig 
                        suchen sie deshalb nach anderen Informationsquellen: sie sprechen mit Freunden 
                        und Bekannten und forschen im Internet. Wie glaubhaft und belastbar diese Informationen 
                        sind, ist für den Laien schwer zu beurteilen. Gleichzeitig überschwemmen seit einigen 
                        Monaten Tests auf Nahrungsmittel-Unverträglichkeiten für den Hausgebrauch den Markt. 
                        Betroffene greifen diese Selbsttests als vermeintlich gute Alternative zu einem 
                        Arztbesuch auf, denn die Hersteller veröffentlichen auf ihren Websites Gebrauchsanleitungen, 
                        die suggerieren, dass gar nichts schief gehen kann. Die Zusicherung, das Testergebnis 
                        schon nach wenigen Tagen per Post zu erhalten, ist vielversprechend und der Preis 
                        in der Regel moderat.  
