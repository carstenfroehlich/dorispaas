                        <h5>Meine Vita</h5>
                        <img src="<?php echo IMG_PATH; ?>vita.png" alt="" class="right" />
                        <p>
                            Im Jahr 1952 wurde ich in Berlin geboren, wo ich auch aufgewachsen und zur Schule gegangen bin. 
                            Nach dem Abschluss meines <b>Lehrerstudiums mit dem Schwerpunkt Ernährungslehre</b> 
                            arbeitete ich in verschiedenen Krankenhäusern. Nach <b>zusätzlichen Fortbildungen</b> 
                            konnte ich dort im Laufe der Jahre umfangreiche medizinische Kenntnisse aufbauen und vertiefen.
                        </p>
                        <p>
                            1980 zog ich ins Rheinland und widmete mich in einer intensiven Familienphase 
                            drei eigenen und zeitweilig zwei Tages-Pflegekindern &ndash; ich leitete ein (gar nicht 
                            so) kleines Familienunternehmen, wie es die Werbung so schön ausdrückt. 
                            Anschließend war ich lange Jahre in der <b>Erwachsenenbildung</b> selbständig 
                            und landete irgendwann in einem Versicherungskonzern, in dem ich über 13 Jahre arbeitete.
                        </p>
                        <p>
                            Eine <b>Laktose-Intoleranz</b>, die von meinen behandelnden Ärzten nicht als solche 
                            erkannt wurde, zwang mich, mich näher mit den Hintergründen und den 
                            Ursachen meiner Beschwerden zu befassen. Leider gab es zu dieser Zeit keine 
                            für mich ausreichend befriedigende Literatur zu diesem Thema, so dass ich meine Informationen 
                            über viele Jahre aus den verschiedensten Quellen recherchieren und nach 
                            Lösungen suchen musste. Die Zeit der Selbstbeobachtung, die schließliche 
                            Diagnose und auch die folgende Zeit der Ernährungsumstellung brachten mir viele 
                            wertvolle Erkenntnisse über diese Nahrungsmittel-Unverträglichkeit, und ich 
                            erarbeitete mir mithilfe meiner Vorbildung auf diese Weise nach und nach ein fundiertes Wissen 
                            über <b>gesunde Ernährung</b> im Allgemeinen und <b>Nahrungsmittel-Intoleranzen und -Allergien</b> 
                            im Besonderen.
                        </p>
                        <p>
                            So entwickelte sich aus meinen beruflichen Schwerpunkten und einer 
                            &#187;pädagogischen Ader&#171; 2005 die Idee, ein Sachbuch über die Laktose-Intoleranz 
                            zu schreiben, obwohl (oder vielleicht auch gerade weil) in der Schule an jedem meiner Deutsch-Aufsätze 
                            mit dicker, roter Lehrertinte &#187;Umgangssprache!&#171; stand ;-). Im September 2007 
                            ist als Ergebnis <a href="book-laktoseintoleranzbuch" target="_blank">&#187;Das Laktose-Intoleranz Buch - 
                            Alles, was Sie über die Milchzucker-Unverträglichkeit wissen möchten&#171;</a> 
                            in der ersten Auflage erschienen. Wegen großen Interesses wurden im 
                            Mai 2008 die zweite und im August 2009 die dritte Auflage vom Verlagshaus 
                            Monsenstein und Vannerdat gedruckt.
                        </p>
                        <p>
                            Im Oktober 2008 kam das Buch <a href="book-nmu" target="_blank">&#187;Nahrungsmittelallergien 
                            und -unverträglichkeiten &ndash; Genussvoll essen &ndash; unbeschwert leben&#171;</a> 
                            auf den Markt. Es entstand in Zusammenarbeit mit Dr. med. Erich Krämer (Facharzt 
                            für Allgemeinmedizin mit Schwerpunkten Akupunktur, Homöopathie und 
                            Ernährungsberatung (DGE)) und wurde vom Compact-Verlag 
                            innerhalb der Reihe &#187;Gesundheit aktuell&#171; in Kooperation mit dem BKK Bundesverband 
                            verlegt.
                        </p>
                        <p>
                            Weil immer wieder die Bitte an mich herangetragen wurde, die Sachverhalte über 
                            Nahrungsmittel-Unverträglichkeiten, das Reizdarm-Syndrom und ganz allgemein 
                            über gesunde Ernährung und gesunde Verdauung für Menschen, die sich rasch einen 
                            ersten Überblick verschaffen wollen oder auch für nicht Betroffene 
                            in kurzer Form zugänglich zu machen, entstand im September 2009 der Anfang der 
                            <a href="paas-heftchen-gesamt" target="_blank">&#187;Paas&#039;schen Heftchenreihe&#171;</a>. 
                            Die Heftchen eignen sich zum Selberlesen oder auch zur Weitergabe an Verwandte, Bekannte, Freunde oder 
                            Arbeitskollegen, die sich in rund einer Stunde über das jeweilige Thema schlau 
                            machen können. Diese Reihe wird kontinuierlich mit weiteren Themen fortgeführt.
                        </p>
                        <p>
                            Wie auch in &#187;Das Laktose-Intoleranz Buch&#171; basieren sämtliche Themen 
                            der &#187;Paas&#039;schen Heftchenreihe&#171; auf eigenen Erfahrungen, denn mittlerweile 
                            kamen leider zu meiner Laktose-Intoleranz auch noch eine <b>Fruktose- und 
                            Sorbit-Unverträglichkeit</b>, eine <b>Oligosaccharid-Intoleranz</b> 
                            und ein <b>Reizdarm-Syndrom</b> hinzu, die ich aber schon lange sehr gut im Griff habe. 
                            Vor allem aber wurde bei meiner Tochter 
                            eine <b>Zöliakie</b> diagnostiziert, die uns zwang, ihre Ernährung und unser Verhalten 
                            in Küche und Vorratsschrank und am Esstisch völlig neu zu überdenken.
                            Ich glaube, dass gerade ein Betroffener den Umgang 
                            mit einer Unverträglichkeit oder einer Krankheit am besten beschreiben und 
                            Tipps geben kann. Ich hoffe, dass mir dies in meinen Büchern und auf dieser 
                            Website gelungen ist.
                        </p>
                        <p>
                            Neben den Büchern gibt es auch diverse Publikationen in verschiedenen 
                            Fachzeitschriften. <a href="fachbeitraege">Lesen Sie hier eine Auswahl.</a>
                        </p>
                        <p>
                            Während der Beschäftigung mit den Nahrungsmittel-Intoleranzen wurde mir 
                            immer deutlicher, wie wichtig nicht nur bei Unverträglichkeiten die adäquate 
                            Ernährung ist. Es kristallisierte sich dabei auch immer mehr heraus, 
                            dass neben einer generell gesunden Ernährung auch körperliche Bewegung 
                            und viele andere Aspekte zu einer ganzheitlichen Gesundheit beitragen, die 
                            letztendlich dazu führt, dass wir uns als Mensch ganz und heil und vor 
                            allem wohl fühlen. Um diese Richtung weiter zu verfolgen, nahm ich 
                            an der Akademie für Gesundes Leben in Oberursel an einer umfassenden und fundierten Ausbildung 
                            zur <b>Gesundheitsberaterin für ganzheitliche Gesundheit</b> teil, die ich 
                            2012 mit einer IHK-Prüfung abschloss. 
                        </p>
                        <p>
                            Seit dieser Zeit arbeite ich als <b>Ernährungs- und Gesundheitspädagogin</b>  
                            in einer eigenen <b><a href="beratung" target="_blank">Praxis für Ganzheitliche 
                            Gesundheit und Prävention</a></b> und setze dabei meinen 
                            Schwerpunkt auf die ernährungsbedingten Einschränkungen und Erkrankungen. In 
                            diesem Rahmen biete ich in meiner Praxis persönliche und im gesamten deutschsprachigen Raum 
                            auch telefonische und online-Beratungen und Vorträge zu den entsprechenden Themen an.
                        </p>
