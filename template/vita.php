                        <p>
                            Seit ich im Rahmen meiner Praxistätigkeit immer mehr gute Erfahrungen mit der Anwendung 
                            von Vitalpilzen gesammelt habe, habe ich im Jahr 2016 eine Ausbildung als
                            &#187;<b>Mykoberaterin</b>&#171; absolviert. Nun kann ich bei bestimmten Beschwerden auch diese 
                            Präparate mit einbeziehen.
                        </p>
                        <p>
                            Weil das Thema &#187;<b>Dünndarmfehlbesiedelung</b>&#171; in meiner Praxis immer häufiger auftauchte, habe 
                            ich mich auch in diesem Bereich gründlich eingearbeitet. Das Ergebnis war dann das 2016 erschienene und 
                            schließlich in der 3. überarbeiteten Auflage vorliegende Buch 
                            <a href="book-ddfb" target="_blank">&#187;Dünndarmfehlbesiedelung &ndash; erkennen, verstehen, erfolgreich behandeln&#171;</a>.
                        </p>
                        <p>
                            Und nachdem ich festgestellt hatte, dass das große Thema &#187;<b>intestinale Mikrobiota</b>&#171; 
                            (früher als auch Darmflora bezeichnet) gerade bei bakteriellen Fehlbesiedelungen, aber auch insgesamt 
                            bei der Therapie der meisten Verdauungsbeschwerden immer wichtiger wird und vor allem nach und nach auch 
                            immer mehr erforscht ist, habe ich mich auch in diesem Bereich fortgebildet und 2020 einen zertifizierten Abschluss als 
                            &#187;<b>Spezialistin für Mikrobiologische Therapie</b>&#171; erworben und diese Kenntnisse 2024 mit einem Zertifikat 
                            als &#187;<b>Mikrobiomspezialistin</b>&#171; aufgefrischt und aktualisiert. So kann ich meine Beratungen auf ein 
                            noch breiteres Fundament stellen.
                        </p>
                        <p>
                            Ein weiteres &ndash; und bis dato letztes &ndash; Buch erschien in einer ersten Auflage im Jahr 2022 (und in der dritten und letzten Auflage 2023): 
                            <a href="book-darmgymnastik" target="_blank">&#187;Darmgymnastik &ndash; Bewegung &#38; mehr gegen Verdauungsbeschwerden&#171;</a>.
                            Bei vielen meiner Klienten stellte ich fest, dass sie teils seit Jahren an ihren Beschwerden herumdoktern,
                            ohne einen dauerhaften Erfolg zu erzielen. Es fehlte offensichtlich grundsätzlich eine <b>entscheidende Komponente</b> in ihrem
                            Behandlungskonzept: <b>die Bewegung</b>, und so &#187;predigte und predige&#171; ich bei so gut wie jeder Beratung, wie wichtig 
                            die kontinuierliche Bewegung als Begleitmaßnahme ist. Das Buch kann nun ein wertvolles Hilfmittel für alle Betroffenen sein &ndash;
                            auch für alle diejenigen, die (noch) keine Beratungsstunde bei mir gebucht haben.
                        </p>
                        <p>
                            Da neben individuellen Beratungen von Klienten auch immer mehr Beratungen von und 
                            in Unternehmen zur Betrieblichen Gesundheitsförderung (BGF) und insgesamt auch zu einem umfassenden 
                            Gesundheitsmanagement (BGM) angefragt werden, habe ich diese Bereiche im Rahmen einer 
                            Zusatzausbildung als &#187;<b>Betriebliche Gesundheitsmanagerin</b>&#171; vertieft.
                            Gerade im Arbeitsbereich kann so viel mit einer guten <b>Prävention</b> &ndash; also der 
                            Vorbeugung vor Krankheiten &ndash; erreicht werden! Nicht allein, dass Mitarbeiter 
                            sich besser und gesünder fühlen, sie sind auch motivierter und leistungsfähiger.
                            Auch Krankenstände können mit BGF-Maßnahmen signifikant gesenkt werden.
                            Es ist deshalb sowohl im Interesse der Arbeitnehmer als auch im Interesse eines 
                            jeden Arbeitgebers, ein Konzept für ein BGM einzuführen.
                            Bitte setzen Sie sich mit mir in Verbindung, wenn Sie für ein kleines, mittleres
                            oder auch größeres Unternehmen eine Beratung zum Betrieblichen Gesundheitsmanagement 
                            und/oder einzelnen Modulen der Betrieblichen Gesundheitsförderung wünschen.
                        </p>
