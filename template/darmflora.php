                        <b>Bitte lesen Sie zunächst den Beitrag &#187;<a href="darmfloragrundsatz">Grundsätzliches über die Darmflora</a>&#171;</b>
                        <hr />
                        <br />
                        Für eine optimale Gesundheitsvorsorge ist es wichtig, den Darm zu pflegen. 
                        Besonders aber bei einem schlecht funktionierenden Immunsystem, nach Antibiotikatherapien 
                        oder auch nach besonderen Stresssituationen ist es erforderlich, sich um die Pflege 
                        der Darmflora zu kümmern, da dieses empfindliche Organ durch viele ungünstige 
                        Einflüsse beeinträchtigt werden kann. 
                        <br />
                        <br />
                        Im Darm sitzt ein Großteil unseres Immunsystems &ndash; teils durch die Barrierefunktion 
                        einer dichten Schleimhaut mit einem Schleimüberzug, wodurch Krankheitserregern 
                        in Form einer Barriere der Eintritt in das Gewebe verwehrt wird. Anderenteils aber 
                        bilden Millionen von Darmbakterien einen Schutzwall gegen unerwünschte &#187;Eindringlinge&#171;. 
                        Diese Darmbakterien &ndash; die Darmflora oder Mikrobiota &ndash; sollte aus überwiegend nützlichen 
                        Bakterienstämmen bestehen. Natürlich enthält sie auch immer weniger 
                        nützliche, teils sogar schädliche Keime, letztere werden aber in einer 
                        intakten Darmflora immer durch die guten Arten in Schach gehalten, so dass sie 
                        sich nicht übermäßig vermehren und ihr krankmachendes Potenzial 
                        entfalten können.
                        <br />
                        <br />
                        Durch eine aus dem Gleichgewicht geratene Darmflora können sich jedoch verstärkt 
                        Krankheitserreger vermehren und die Gesundheit des Menschen gefährden. So können 
                        sich z.B. Pilze wie Candida albicans einnisten und sogar in der Schleimhaut verankern. 
                        Von hier aus können sie bis in andere Körperregionen wuchern und beispielsweise 
                        Nagel- oder Scheidenpilz-Erkrankungen verursachen. Sind vom Arzt oder Heilpraktiker 
                        Darmpilze festgestellt worden, ist eine konsequent zucker- und weißmehlfreie 
                        Diät einzuhalten, um die Schädlinge auszuhungern, denn Pilze lieben schnell 
                        verfügbare Kohlenhydrate. Eine systematische Ansiedelung 
                        von Lacto- und Bifidobacillen unterstützt diesen Prozess, denn sie verarbeiten 
                        bereits in den oberen Darmabschnitten eventuell vorhandene Glukose, die dann den 
                        Pilzen in den unteren Darmbereichen nicht mehr zur Verfügung steht. Darüber 
                        hinaus erzeugen diese Milchsäurebakterien ein günstiges, leicht saures Milieu, 
                        in dem die Pilze nur schwer überleben können. Übermäßiger 
                        Zuckergenuss lockt zudem die eigentlich im Dickdarm ansässigen Bakterien nach 
                        oben in den Dünndarm, wo sie mit ihren unangepassten Stoffwechselvorgängen 
                        Abfallprodukte wie z.B. kurzkettige Fettsäuren erzeugen, die die Darmschleimhaut 
                        schädigen. 
                        <br />
                        <br />
                        Neben der <a href="darmschleimhaut">Pflege der Darmschleimhaut</a> 
                        wird der Aufbau der Darmflora idealerweise unterstützt mit probiotischen 
                        (enthalten lebende Bakterienkulturen) oder präbiotischen Nahrungsmitteln 
                        (enthalten schwer verdauliche Oligosaccharide (Mehrfachzucker) und 
                        unverdauliche Polysaccharide (Vielfachzucker), also Kohlenhydrate, die von der menschlichen 
                        Verdauung nicht so ohne Weiteres verwertet werden können, jedoch den Darmbakterien als &#187;Futter&#171; 
                        dienen). Die meisten pro- und präbiotischen Nahrungsmittel sind auf Milchbasis 
                        hergestellt, meist (Frucht-)Joghurtprodukte &ndash; hier hat die Nahrungsmittelindustrie 
                        einen riesigen Markt entdeckt: Die entsprechenden Produkte (&#187;funktionelle 
                        Lebensmittel&#171;) werden von vielen Verbrauchern gekauft, die meinen, ihrer Gesundheit 
                        damit etwas Gutes tun zu können. Beachtet werden muss jedoch, dass die (wenigen) 
                        Bakterien, die diesen Nahrungsmitteln zugesetzt wurden, größtenteils bereits 
                        im Magen durch die Magensäure abgetötet werden und den Dickdarm, wo sie 
                        eigentlich wirken sollten, gar nicht erst erreichen. Für Menschen mit Laktose-Intoleranz 
                        und auch für Menschen mit Fruktose-Intoleranz sind sie wegen des Milchzucker- 
                        und Fruchtzuckergehalts nicht geeignet &ndash; und kosten darüber hinaus auch eine 
                        schöne Stange Geld.
                        <br />
                        <br />
                        Gut geeignet hingegen ist milchsauer eingelegtes Gemüse, das Sie am besten 
                        im Bioladen oder aus dem Reformhaus besorgen. Dort bieten sich Sauerkraut, saure 
                        Gurken, Rote Beete oder Mixed Pickles an. Auch in Brottrunk, den Sie dort bekommen, 
                        sind Milchsäurebakterien enthalten. Darüber hinaus enthält auch der mit dem 
                        so genannten &#187;Teepilz&#171; angesetzte Kombucha-Trunk (sprich: Kombuhtscha) 
                        verschiedene nützliche Bakterien- und Hefepilzarten und ist zur Darmpflege 
                        bestens geeignet (siehe Link unten). Vor allem aber enthalten diese Lebensmittel 
                        viele Enzyme und einen hohen Anteil an Milch- und/oder 
                        Essigsäure und weitere Bestandteile, die die Verdauung unterstützen 
                        und helfen, dass sich nützliche Darmbakterien optimal entwickeln können, 
                        die Vermehrung von schädlichen Mikroorganismen dabei jedoch eher hemmen. 
                        <br />
                        <br />
                        Die in diesen Lebensmitteln enthaltenen Inhaltsstoffe &ndash; vor allem aber ihre 
                        für unseren Organismus optimale Kombination &ndash; sind wesentlich bekömmlicher 
                        als die in den industriellen Produkten enthaltenen. Natürlich kann auch 
                        ein Teil der hier enthaltenen Bakterien die Magensäureschranke nicht überwinden, 
                        jedoch kommt es hier eben auf die Reichhaltigkeit der Inhaltsstoffe an. 
                        Übrigens: auch diese natürlichen Lebensmittel können Blähungen oder sogar Durchfälle erzeugen, besonders 
                        beim Verzehr größerer Mengen. Es ist deshalb sehr 
                        wichtig, die Verzehrmengen dieser Lebensmittel, vor allem von Sauerkraut, grundsätzlich 
                        langsam einzuschleichen, d.h. Sie müssen behutsam die Verzehrmengen steigern, 
                        um das Verdauungssystem an die neuen, nützlichen &#187;Mitbewohner&#171; und 
                        die weiteren wertvollen Inhaltsstoffe zu gewöhnen.
                        <br />
                        <br />
                        In Apotheken und Reformhäusern gibt es zusätzlich Präparate mit 
                        getrockneten Milchsäure- und/oder Bifidobakterien, die die Zusammensetzung 
                        der Darmflora günstig beeinflussen. Meist enthalten sie zusätzlich Präbiotika 
                        wie Inulin oder Oligofruktose, die die Vermehrung der Bakterien begünstigen. 
                        Darüber hinaus können Sie, falls sich die Beschwerden nicht nach einigen 
                        Wochen bessern, in der Apotheke Präparate mit &#187;entschärften&#171; 
                        Escherichia coli- oder Enterococcus faecialis-Bakterien erwerben. 
                        <br />
                        <br />
                        Auch <a href="vitalpilze" target=_blank">Vitalpilze</a> sind eine ganz hervorragende 
                        Möglichkeit, Darmschleimhaut, Darmflora 
                        und die Verdauung gesund zu erhalten. Sie enthalten u.a. einen hohen Anteil an 
                        Polysacchariden, die ausgleichend und regulierend wirken.
                        Hauptsächlich jedoch haben die verschiedenen Vitalpilz-Arten 
                        die diverse Wirkungen auf unseren Organismus, die in der 
                        Traditionellen Chinesischen Medizin (TCM) schon seit Jahrtausenden 
                        bekannt sind. Seit einiger Zeit jedoch etabliert sich dieses 
                        Wissen auch in unserer westlichen Welt, und geschulte Mycotherapeuten 
                        oder Mycoberater empfehlen geeignete Arten u.a. auch erfolgreich bei Verdauungsproblemen. 
                        <br />
                        <br />
                        <b>Sprechen Sie 
                        diese Maßnahme jedoch immer mit Ihrem Arzt, Heilpraktiker oder Gesundheitsberater 
                        ab &ndash; das Herumdoktern mit allen diesen Präparaten ist oftmals eher schädlich 
                        als nützlich. </b>
                        Auch wenn früher und auch heute noch die Präbiotika einen großen 
                        Stellenwert bei den Gesundheitssuchenden (und natürlich erst recht bei den Herstellern)
                        einnehmen, sind diese Präparate  mittlerweile nicht mehr unumstritten. Es wird 
                        diskutiert, ob die enthaltenen Bakterienarten, die als so genannte &#187;passagere Keime&#171;
                        ja nur vorübergehend in den Darm geschleust werden, die obligate Darmflora, 
                        also die dauerhaft dem Darm angesiedelten Bakterienarten verdrängen, die für 
                        die Gesunderhaltung des Organismus eine unersetzliche Rolle spielen. Wenn dann 
                        nach Absetzen der Präparate die passageren Keime zurück gehen, kann 
                        sich die dezimierte eigentliche Darmflora nicht &ndash; oder zumindest nicht ausreichend 
                        und nicht schnell genug &ndash; regenerieren. Somit möchte ich vor allzu 
                        leichtfertigem Einnehmen von Probiotika unbedingt warnen.
                        <br />
                        <br />
                        Lesen Sie hierzu bitte auch den Beitrag <a href="darmsanierung">Sanierung der Darmflora</a>. 
                        Nach dem erfolgreichen Umstieg auf vollwertige Kost kann sich die Darmflora dann 
                        von allein erhalten und muss nicht lebenslang mit künstlich zugeführten 
                        Mitteln unterstützt werden (siehe Link unten). 
                        <br />
                        <br />
                        Lassen Sie sich für den Aufbau der Gesundheit Ihres Darmes viel Zeit: Rechnen 
                        Sie mit mehreren Monaten für die Regeneration, je nach dem, in welchen Zustand 
                        sich Ihr Darm zuvor befunden hat. Mit Sicherheit werden sich mit der Sanierung 
                        Ihr körperliches und auch Ihr seelisches Befinden verbessern, Ihre Beschwerden 
                        werden zurückgehen, und Sie werden sich leistungsfähig und gesund fühlen. 
                        
