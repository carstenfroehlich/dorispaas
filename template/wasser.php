                        <br />
                        <hr>
                        <h5>Wasser zur Hygiene</h5>
                        <hr>
                        Wasser ist jedoch nicht nur zum Trinken wichtig. Auch für die Hygiene benötigt man Wasser. Mit Wasser waschen wir unsere Kleidung, 
                        so dass wir sie, nachdem sie zuvor verschmutzt und verschwitzt war, schon nach wenigen Tagen wieder frisch anziehen können.
                        <br />
                        <br />
                        Insbesondere seit der Corona-Pandemie ist uns allen die Wichtigkeit der Handhygiene wieder mehr ins Bewusstsein gebracht worden und 
                        den meisten von uns in Fleisch und Blut übergegangen. Mit Wasser (und Seife) werden die meisten übertragbaren Keime abgespült und 
                        somit unschädlich gemacht.
                        <br />
                        <br />
                        Vor allem aber nutzen wir das Wasser, um unseren Körper von Schweiß und Anhaftungen jeglicher Art zu säubern. Hier in unserer 
                        Region haben wir das Glück, dass uns Wasser dankenswerterweise (fast) unbegrenzt zur Verfügung steht. So beginnen meisten Menschen 
                        den Tag mit einer reinigenden Dusche oder einem Bad. 
                        <br />
                        <br />
                        Waschen wir uns nicht ausreichend und verschmutzt unser Körper, ist dies nicht nur für uns selbst und unsere Gesundheit nachteilig, 
                        sondern kann durchaus auch unsere Mitmenschen beeinträchtigen. Dabei kann diskutiert werden, ob Duschen tatsächlich jeden Tag 
                        erforderlich ist, oder ob nicht eine gelegentlich alternative, aber wassersparendere Waschung denselben Zweck erfüllt. Vor allem 
                        aber sollte sparsam mit Seife und Waschlotionen umgegangen werden, damit der gesunde Säureschutzmantel der Haut nicht geschädigt wird. 
                        Wasser allein aber ist wichtig, um eine gesunde Körperhygiene einhalten zu können.


