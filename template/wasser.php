                        &#187;Wasser des Lebens&#171;, &#187;Jungbrunnen&#171;, &#187;Lebensquell&#171; &ndash; es gab schon immer Begriffe, 
                        die deutlich machten, wie wichtig Wasser für uns Menschen ist. Aber auch für alle Tiere, alle Pflanzen und insgesamt 
                        für unsere Umwelt ist Wasser DAS Lebenselixier. Erst durch Wasser konnte auf unserem durch das Wasser blau erscheinenden 
                        Planeten Leben entstehen. Viele, viele Jahrtausende gab es Leben ausschließlich im Wasser, bevor die ersten Wesen an Land 
                        krochen. Aber auch dort können sie in all ihren mittlerweile vorhandenen Formen nur mithilfe des Wassers existieren. 
                        Hier in diesem Beitrag möchte ich über die Bedeutung des Wassers für uns Menschen sprechen.
                        <br />
                        <br />
                        <a id="trinken"></a>
                        <hr />
                        <h5>Wasser trinken</h5>
                        <hr />
                        Der menschliche Körper besteht durchschnittlich (je nach Alter) zu rund 70 bis 85 % aus Wasser. Wenn der Wassergehalt sinkt, 
                        macht sich dies rasch durch den Ausfall verschiedener Funktionen bemerkbar, beispielweise kognitive Einschränkungen oder eine 
                        unzureichende Entgiftungsleistung. Da wir durch die Atmung, Schweiß, Urin und Kot ständig Flüssigkeit ausscheiden, ist es zunächst 
                        einmal geboten, die Bilanz durch Wasseraufnahme möglichst rasch wieder auszugleichen. Trinken, um den Durst zu löschen, ist also wichtig. 
                        <br />
                        <br />
                        Genauso bedeutsam wie das regelmäßige und ausreichende Trinken ist die richtige Auswahl der Getränke. Unsere tierischen 
                        und menschlichen Vorfahren kannten keine andere Flüssigkeit, um ihren Durst zu stillen: es gab keine Limonade oder Cola, 
                        es wurde ausschließlich Wasser aus Quellen, Flüssen und Seen oder Regenwasser getrunken. Heute ist &ndash; dankenswerterweise 
                        &ndash; in unseren Breiten das Wasser ein gesundes Lebensmittel, das uns ausreichend zur Verfügung steht. Natürlich kann man 
                        aus Wasser neben den nicht empfehlenswerten zuckrigen Alternativen auch zu Tee oder auch (in Maßen) Kaffee zubereiten, aber die 
                        beste Wahl ist immer noch frisches Wasser. Dabei müssen wir keineswegs immer nach Wasser aus Flaschen greifen, sondern es darf 
                        gerne das bei uns in der Regel bestens kontrollierte Trinkwasser sein (lesen Sie hierzu bitte auch den Beitrag 
                        &#187;<a href="trinkwasser" target="_blank">Chlor im Trinkwasser</a>&#171;).
                        <br />
                        <br />
                        Eine Mengenempfehlung, wie viel man trinken sollte, ist schwierig, denn sie hängt sowohl von den individuellen Gewohnheiten ab 
                        (wie viel bewege ich mich, wie heftig atme ich dabei, wie intensiv schwitze ich) als auch von den Außentemperaturen. Je heißer es 
                        ist, desto mehr muss man trinken, denn der Körper kann seine Temperatur nur durch vermehrtes Schwitzen halten und die Körpertemperatur 
                        so ggf. herunterregulieren.
                        <br />
                        <br />
                        Die landläufig übliche Mengenangabe von etwa 1,5 Litern Wasser ist also nur bedingt allgemeintauglich &ndash; schon bei sommerlicheren 
                        Temperaturen reicht diese Menge keineswegs mehr aus. Hier darf es dann gerne auch ein Liter mehr sein. Günstig wäre es, wenn man es gar 
                        nicht erst zu Durstgefühlen kommen lassen würde, denn der Durst zeigt ja bereits den Mangel an. Da insbesondere ältere Menschen kein 
                        ausgeprägtes Durstgefühl mehr haben, auf dass sie sich verlassen können, ist es insbesondere für diese Altersgruppe erforderlich, eine 
                        regelmäßige und ausreichende Flüssigkeitszufuhr zu einer festen Gewohnheit werden zu lassen. 
                        <br />
                        <br />
                        Ein dauerndes Durstgefühl kann ein Hinweis auf eine Diabetes-Erkrankung sein, denn der Körper versucht, den durch eine mangelhafte 
                        Insulinproduktion erhöhten Blutzuckerspiegel mit einer vermehrten Flüssigkeitsaufnahme verdünnen und ausscheiden zu können. Sollten 
                        Sie oft unter verstärktem Durst leiden, lassen Sie das bitte rasch von Ihrem Hausarzt abklären.
                        <br />
                        <br />
                        Natürlich gibt es Ausnahmen, bei denen nicht so viel getrunken werden darf. Wenn beispielsweise die Nieren eine deutlich eingeschränkte 
                        Funktion haben, ist auf eine streng limitierte Flüssigkeitszufuhr zu achten &ndash; aber dies sind Sonderfälle, die in die Hand des 
                        Facharztes gehören.
                        <br />
