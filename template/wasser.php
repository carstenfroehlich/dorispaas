                        <a id="wasserundmehr">&nbsp;</a>
                        <br />
                        <hr>
                        <h5>Wasser und mehr</h5>
                        <hr>
                        Neben der lebensnotwenigen Flüssigkeitszufuhr und der für uns fast ebenso wichtigen Reinigung kann Wasser aber noch sehr viel mehr 
                        für unsere Gesundheit tun.
                        <br />
                        <br />
                        Schon die dem Arzt Johann Siegmund Hahn zugeschriebene Wassermedizin oder Hydrotherapie gründete auf Anwendungen mit Wasser, die 
                        er u.a. in seinem ersten, 1732 erschienenen, Buch &#187;Der Perswälder Gesundbrunnen&#171; veröffentlichte. Der 1799 geborene 
                        Naturheiler Vincenz Prießnitz arbeitete dann mit feuchten Wickeln, deren Anwendungen sich zumindest bei ganzheitlich denkenden 
                        Therapeuten bei den verschiedensten Erkrankungen bis in unsere heutige Zeit erhalten haben.
                        <br />
                        <br />
                        Am bekanntesten ist jedoch der &#187;Wasserpfarrer&#171; Sebastian Kneipp, der vor allem mit kalten Güssen zunächst die Heilung 
                        seiner eigenen Erkrankung unterstützte, was später zu einer verbreiteten und anerkannten Gesundheitsbewegung mit Güssen, Wassertreten 
                        und Wickeln führte.
                        <br />
                        <br />
                        Auf der ganzen der Welt haben sich diese Grundätze großenteils schon lange vor diesen Lehren etabliert: die in vielen Gebieten der 
                        Erde üblichen &#187;Schwitzhütten&#171; sind nur ein Beispiel dafür, ebenso wie die finnische (Dampf-) Sauna, und das kalte Bad in 
                        Flüssen und Seen &ndash; mangels der Möglichkeit, Wasser zu erwärmen &ndash; war schon immer nicht nur zur Reinigung, sondern 
                        &#187;ganz nebenbei&#171; auch zur Abhärtung an der Tagesordnung. All dies sind Möglichkeiten, auch unter unwirtlichen 
                        Klimabedingungen gesund zu bleiben.
                        <br />
                        <br />
                        Auch wenn einige Menschen diesen Lehren nicht ihre Überzeugung entgegenbringen wollen, so wird doch jeder von uns die Dusche am Morgen 
                        als &#187;erfrischend&#171; oder das Bad am Abend als &#187;entspannend&#171; empfinden &ndash; ein Beweis dafür, dass Wasser eben nicht 
                        nur zum Trinken oder Waschen gut ist.



