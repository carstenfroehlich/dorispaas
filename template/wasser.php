                        <hr>
                        <h5>Wasser zur Linderung von Verdauungsbeschwerden</h5>
                        <hr>
                        Wasser kann auch zur Linderung von Verdauungsbeschwerden eingesetzt werden. Abgesehen von den Anwendungen als Hals- oder Wadenwickel hilft das Wasser
                        auch in Form eines <a href="lexikon-naturheilmethoden#l" target="_blank">Leberwickels</a>. Diese Anwendung kann die <b>Leistungsfähigkeit der 
                        Verdauungsdrüsen steigern</b> und wirkt darüber hinaus entspannend.
                        <br />
                        <br />
                        Ein Glas warmes Wasser, gleich nach dem Aufstehen auf nüchternen Magen getrunken, kann ein wunderbares und vor allem nebenwirkungsfreis Mittel sein,
                        um einer <b>trägen Verdauung ein wenig auf die Beine zu helfen</b>. Überhaupt ist die Trinkmenge ganz entscheidend für eine gute Verdauung. Wird zuwenig getrunken,
                        dickt der Speisebrei im Darm ein und kann nicht mehr so gut transportiert werden. Die Transitzeit ist jedoch ein ganz wichtiger Faktor für die 
                        Konsistenz des Stuhls, denn je langsamer die Nahrung durch den Darm transportiert wird, desto mehr Zeit bleibt dann im Dickdarm, um dem Speisebrei 
                        die Flüssigkeit zu entziehen. Wer zu Verstopfung neigt, kann deshalb allein durch das Trinken von mehr Wasser die Qualität der Verdauung verbessern.
                        <br />
                        <br />
                        Ein wenig aus der Mode gekommen sind die Trinkkuren, bei denen Kranke in Heilbädern bestimmte Quellwässer tranken. Die Heilbäder gibt es auch heute noch,
                        nur ist es natürlich nicht immer möglich, einen solchen Ort aufzusuchen. Es gibt <b>Heilwasser</b> aber auch in Flaschen, die mit den enthaltenen Mineralien die 
                        verschiedensten Wirkungen versprechen. Gestalten Sie sich doch einmal Ihre ganz persönlich Kur, indem Sie es sich an einem Wochenende mit einem Heilwasser
                        zu Hause gemütlich machen. Das wirkt auf jeden Fall entspannend und kommt auch Ihrer Verdauung zugute.
                        <br />
                        <br />
                        <b>Bauchschmerzen und Krämpfen</b> kann man auch mit einem <b>warmen Bad</b> zuleibe rücken. Allein die Temperatur hilft, die verspannten Muskeln rund um den Darm
                        zu entspannen. Steigern kann man diese Wirkung noch durch Badezusätze wie Melisse, Hopfen oder Lavendel &ndash; hierbei sind aber oft auch die 
                        persönlichen Vorlieben mitentscheidend.
                        <br />
                        <br />
                        Es gibt zahlreiche weitere Anwendungen mit Wasser, die vorteilhaft und lindernd bei Verdauungsbeschwerden wirken. Selbst, wenn es &#187;nur&#171; <b>der 
                        Effekt auf Ihre Psyche</b> ist, der entspannend wirkt und ein überempfindliches Verdauungssystem beruhigt, so ist doch jedes Mittel recht, wenn es hilft.
                        Probieren Sie es aus!



