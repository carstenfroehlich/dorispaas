                        <hr>
                        <h5>Gesundheit durch Wasser </h5>
                        <hr>
                        Noch viel zu wenig bekannt ist, <b>warum</b> Wasser &ndash; abgesehen von der Flüssigkeitszufuhr oder der Hygiene &ndash; so viel 
                        Gutes für unsere Gesundheit tun kann.
                        <br />
                        <br />
                        Anwendungen mit Wasser wirken vor allem durch die Kälte- und Wärmereize, die u.a. das Immunsystem anregen. Aber auch die Stimulierung 
                        bestimmter Hautpartien und den dort liegenden Nerven hilft bei den verschiedensten Beschwerden &ndash; oder &#187;einfach nur&#171; 
                        vorbeugend, stärkend und oder stabilisierend. So wirkt z.B. eine Anwendung mit kaltem Wasser an der Halspartie auf den dort langlaufenden 
                        <b>Vagusnerv</b>, dem größten Nerv des parasympathischen Systems, auf die <b>inneren Organe des Körpers</b>. Somit können Sie ganz einfach nach 
                        der täglichen Dusche mit einem kurzen Schwall richtig kalten Wassers über Gesicht und Hals u.a. die <b>gesunde Tätigkeit Ihres Verdauungssystem 
                        anregen</b> &ndash; einfacher geht es kaum. Auch das Wassertreten insbesondere jetzt zur warmen Jahreszeit sind ist beste Vorbeugung vor und 
                        Behandlung bei schmerzenden, geschwollenen Beinen. Ein weiteres Beispiel sind die wunderbaren 
                        <a href="lexikon-naturheilmethoden#leberwickel" target="_blank">Leberwickel</a>, bei denen eine halbstündig 
                        aufgelegte feuchtwarme Kompresse auf der Lebergegend nicht nur die <b>Funktionsfähigkeit aller Verdauungsdrüsen</b> anregt, sondern gleichzeitig 
                        noch eine hervorragende <b>Entspannungsübung</b> darstellt.
                        <br />
                        <br />
                        Insbesondere im Sommer ist Wasser DAS Mittel der Wahl, um den Temperaturhaushalt zu unterstützen, vor allem, wo die Sommer durch den 
                        Klimawandel immer heißer werden. Automatisch machen die meisten Menschen es richtig, indem sie in dieser Jahreszeit mehr trinken und 
                        auch öfters baden oder duschen. Und gerade in dieser Jahreszeit kann man sich daran gewöhnen, jeden Tag eine Wasseranwendung &ndash; 
                        sei es unter der Dusche, im Schwimmbad oder auch im eigenen Gartenpool &ndash; zu genießen. 
                        <br />
                        <br />
                        Behalten Sie diese Gewohnheit ruhig auch bis in die kalte Jahreszeit bei. Also bitte nicht den eigenen Pool beim ersten kühleren Lüftchen 
                        fürs nächste Jahr einmotten, sondern ruhig tapfer weiter ins kalte Wasser springen. Oder, wenn Sie wie wahrscheinlich die meisten Menschen 
                        keinen Pool besitzen, so lange wie möglich ins Freibad gehen und die tägliche kalte Dusche beibehalten, auch, wenn man dann irgendwann 
                        wieder wärmebedürftiger ist. Es ist ein wunderbares 
                        Gefühl, sich auch im Winter kurz das kalte Wasser über den Körper laufen zu lassen und sich anschließend an der Luft trocknen zu lassen. Sie 
                        glauben gar nicht, wie erfrischt und im wahrsten Sinne des Wortes belebt Sie sich hinterher fühlen werden. Und warm wird Ihnen dann ganz von 
                        alleine, denn der gesunde Körper reguliert die Temperatur durch diesen Reiz gleich wieder hoch. Durch die Gegenregulation des Körpers wird das 
                        <b>Immunsystem</b> angeregt. Zudem wird der <b>Stoffwechsel</b> angeregt und der <b>Kreislauf</b> stabilisiert. Besonders gesund sind auch kalte Gesichtsgüsse, denn 
                        sie regen die Durchblutung der Schleimhäute an. Und da alle Schleimhäute im Körper miteinander in Verbindung stehen, wirkt sich dies auch auf 
                        <b>die Schleimhäute in Ihrem Verdauungssystem</b> aus und kann die Verdauungsfunktionen stärken (bitte lesen Sie hierzu auch den 
                        Beitrag &#187;<a href="darmschleimhaut" target="_blank">Aufbau, Funktion, Pflege und Sanierung der Darmschleimhaut</a>&#171;)
                        <br />
                        <br />
                        Wenn Sie jedoch kränkeln und sich fröstelig fühlen, dürfen Sie bis zur Besserung keine kalten Wasseranwendungen machen. Kaltes Wasser bitte immer 
                        nur auf den warmen Körper geben &ndash; wenn man gesund ist, also am besten nach dem Aufstehen, wenn man noch bettwarm ist. Das Wohlgefühl danach 
                        wirkt sich noch weit in den Tag hinein aus.
                        <br />
                        <br />
                        Es ließen sich unzählige weitere Beispiele nennen. Ich möchte Ihnen deshalb empfehlen, sich einmal ausgiebiger mit diesem Thema zu beschäftigen, 
                        denn auf jeden Fall sind Wasseranwendungen bei den geeigneten Indikationen oftmals den Medikamenten ebenbürtig. Vor allem aber haben diese 
                        Anwendungen &ndash; sofern sie von geschulten Spezialisten empfohlen werden &ndash; keine Neben-, sondern nur positive Wirkungen.


 
