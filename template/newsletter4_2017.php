                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=reflux" target="_blank">Schwerpunktthema: Sodbrennen und Reflux</a></b>
                        <br />
                        Reflux bedeutet &#187;R&uuml;ckfluss&#171; &ndash; und hier ist 
                        der R&uuml;ckfluss von Magens&auml;ure in die Speiser&ouml;hre gemeint. Da die 
                        Schleimhaut der Speiser&ouml;hre nicht wie der Magen durch eine widerstandsf&auml;hige 
                        Schleimschicht gesch&uuml;tzt ist, kann die aggressive Magens&auml;ure die 
                        empfindliche Schleimhaut in der Speiser&ouml;hre reizen oder sogar dazu f&uuml;hren, dass 
                        sie sich schmerzhaft entz&uuml;ndet. Diese Reizungen und Entz&uuml;ndungen werden als Brennen 
                        hinter dem Brustbein wahrgenommen &ndash; dem so genannten Sodbrennen.
                        <br />
                        <br />
                        Magens&auml;ure kann aus verschieden Gr&uuml;nden in die Speiser&ouml;hre zur&uuml;ckflie&#223;en. 
                        Diese Situationen werden in dem ausf&uuml;hrlichen neuen Beitrag genau erkl&auml;rt. 
                        Mehrere Bilder stellen die anatomischen Gegebenheiten dar, so dass Sie 
                        sich genau vorstellen k&ouml;nnen, wie es in Ihrem K&ouml;rper aussieht und Sie 
                        leicht nachvollziehen k&ouml;nnen, was bei den Problemen eigentlich passiert.
                        <br />
                        <br />
                        Es gibt viele probate Mittel gegen Sodbrennen, die die Magens&auml;ure als erste
                        Hilfe neutralisieren, aber ungl&uuml;cklicherweise empfehlen heute
                        viel zu viele &Auml;rzte viel zu h&auml;ufig &#187;modernere&#171; Mittel, die so 
                        genannten Protonenpumpenhemmer. Diese auch unter der Abk&uuml;rzung PPI (f&uuml;r Protonenpumpeninhibitoren) 
                        gef&uuml;hrten Mittel neutralisieren die Magens&auml;ure nicht, sondern unterbinden deren Produktion und 
                        sollten unter keinen Umst&auml;nden dauerhaft eingenommen werden. Sie finden deshalb 
                        in dem Beitrag auch eine kritische Betrachtung dieser problematischen Medikamente.
                        <br />
                        <br />
                        Aber was k&ouml;nnen Sie selber tun, ohne sich und Ihrem K&ouml;rper dabei zu schaden? 
                        Anhand von mehr als 20 Tipps bekommen Sie wirksame Mittel und einfache M&ouml;glichkeiten 
                        an die Hand, die Symptome von Sodbrennen und Reflux zu lindern und ihnen auf Dauer sogar vorzubeugen. 
                        <br />
                        <br />
                        Und was haben die nebenstehend abgebildeteten Str&uuml;mpfe mit Sodbrennen und Reflux 
                        zu tun? Soviel will ich Ihnen an dieser Stelle schon verraten: sie dienen als Anschauungsmatarial, 
                        denn wer kann sich schon den nicht ganz unkomplizierten Aufbau der Speiser&ouml;hre 
                        vorstellen? Mit den beiden Socken aber kann hervorragend demonstriert werden, wie  
                        die Speiser&ouml;hre aussieht und wie eine leichte, aber effektive &Uuml;bung den 
                        R&uuml;ckfluss von Magens&auml;ure in die Speiser&ouml;hre verhindern kann. 
                        Wenn Sie nun neugierig geworden sind, lade ich Sie herzlich ein zum Lesen des 
                        interessanten Artikels.
