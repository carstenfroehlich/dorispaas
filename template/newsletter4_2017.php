                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=verdauung" target="_blank">Gesunde Verdauung</a></b>
                        <br />
                        Ein ganz wichtiger Baustein zur Verh&uuml;tung und/oder Vorbeugung von Sodbrennen und 
                        Reflux ist eine gesunde Verdauung. Insbesondere Verstopfung kann dazu f&uuml;hren, 
                        dass der Nahrungstransport schon weiter oben stockt und so verhindert wird, dass 
                        die Speisen z&uuml;gig aus dem Magen zuerst in den D&uuml;nndarm und dann in den 
                        Dickdarm gelangen. Es gibt sogar einen Reflex &ndash; den so genannten gastrokolischen 
                        Reflex &ndash; bei dem der Magen ein Signal an den Darm sendet, damit durch eine 
                        Darmentleerung Platz geschaffen wird, um neue Speisen im Verdauungssystem aufnehmen 
                        und optimal verarbeiten zu k&ouml;nnen.
                        <br />
                        <br />
                        F&uuml;r eine gesunde Verdauung ist es wichtig, dass Sie Ihr Verdauungssystem 
                        richtig verstehen. So vermeiden Sie Fehler, die letztendlich zu Problemen f&uuml;hren 
                        k&ouml;nnen, die Sie eigentlich nicht haben wollen.
                        Welche Aspekte gilt es hierbei zu beachten? Nat&uuml;rlich ist dies zuerst einmal 
                        Ihre Ern&auml;hrung. Bek&ouml;mmlich sollte sie sein, aber auch gesund und vor allem 
                        schmackhaft. Weiterhin sind die Zeitpunkte wichtig, wann Sie etwas essen. Mit einem 
                        vollen Bauch ins Bett zu gehen, f&uuml;hrt nicht nur zu Verdauungsproblemen, sondern 
                        kann zum Beispiel Sodbrennen und Reflux, aber auch regelrechte Schlafprobleme ausl&ouml;sen.
                        Und dann gibt es noch viele weitere Punkte, die es zu beachten gilt. Hier sind unter 
                        anderem ein gesundes Bewegungsverhalten oder auch ein vern&uuml;nftiges Stressmanagement 
                        zu nennen. Die Gesundheit liegt also buchst&auml;blich in Ihren eigenen H&auml;nden &ndash; 
                        Sie m&uuml;ssen nur wissen, wie es geht. 
                        Ich empfehle Ihnen das B&uuml;chlein &#187;<a href="http://www.dorispaas.de/index.php?page=paas-heftchen-gv" target="_blank">Kurz und klar: Gesunde Verdauung</a>&#171; 
                        (ISBN 978-3-86582-921-4), das Sie auch gerne &uuml;ber meine Website bestellen k&ouml;nnen.
