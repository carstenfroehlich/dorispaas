                        Liebe Leserin, lieber Leser, leider sind die Nachrichten, die uns derzeit erreichen, furchtbar: in und um Bayern &uuml;berschwemmen zu rei&#223;enden Wassermassen 
                        angeschwollene B&auml;che und Fl&uuml;sschen wieder ganze Ortschaften und nehmen den dort Wohnenden Hab, Gut und Existenz und fordern Menschenleben. Von einem 
                        &#187;Jahrhundert-Ereignis&#171; kann man nun wirklich nicht mehr sprechen, nachdem gerade mal vor drei Jahren im Ahrtal genau das gleiche passiert ist. Niemand kann 
                        jetzt mehr die Augen davor verschlie&#223;en, was der durch uns verursachte Klimawandel anrichtet &ndash; und zwar nicht nur in weit entfernten Gebieten, in denen durch die 
                        Verhaltensweisen von uns, den reichen Staaten, den Menschen die Lebensgrundlage genommen wird, so dass sie zu uns fl&uuml;chten m&uuml;ssen, um &uuml;berleben 
                        zu k&ouml;nnen, sondern nun direkt vor unserer Haust&uuml;r. Sp&auml;testens jetzt m&uuml;ssen wir endlich auch in dieser Beziehung Verantwortung &uuml;bernehmen! 
                        Jeder einzelne von uns muss sich ab sofort genau &uuml;berlegen, welche klimasch&auml;dlichen Verhaltensweisen ge&auml;ndert werden k&ouml;nnen. Das m&uuml;ssen 
                        nicht immer die 100%-L&ouml;sungen sein, aber wir k&ouml;nnen uns mit gutem Willen Schritt f&uuml;r Schritt an neue Wege gew&ouml;hnen. Auch der noch so kleinste 
                        Beitrag eines jeden geht in die richtige Richtung. Nicht nur beim Heizen und der Planung f&uuml;r eine sp&auml;tere neue Anlage ist Vorausschau angesagt, auch 
                        das gesamte Konsumverhalten von Reisen, &uuml;ber den Kauf von Kleidung bis hin zum Essen geh&ouml;rt auf den Pr&uuml;fstand. Ich bitte Sie ganz herzlich, sich 
                        auch hier Ihre Verantwortung bewusst zu machen &ndash; die Verantwortung f&uuml;r unser Klima und letztendlich f&uuml;r unser &Uuml;berleben auf diesem Planeten. 
