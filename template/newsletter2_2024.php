                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=reisetipps" target="_blank">Reisen und der Umgang mit Nahrungsmittel-Unvertr&auml;glichkeiten</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Reisen/Allgemeine Reisetipps)</i>
                        <br />
                        Zu Hause haben Sie Ihre Nahrungsmittel-Unvertr&auml;glichkeiten und Ihre Verdauung vielleicht im Griff &ndash; Sie wissen, welche Lebensmittel Sie vertragen und welche Sie besser 
                        meiden sollten. Sie haben Ihre Einkaufsquellen, wo Sie die Produkte bekommen, die Ihnen gut bekommen. Auch wenn Sie zur Arbeit gehen, haben Sie einen Weg gefunden, 
                        sich mit vertr&auml;glichen Speisen zu versorgen, und selbst der eine oder andere Restaurantbesuch bereitet Ihnen keine Schwierigkeiten. So weit so gut! Was aber, 
                        wenn Sie verreisen wollen? F&uuml;r viele Menschen beginnen hier die Komplikationen: Habe ich hier die M&ouml;glichkeit, mich so zu ern&auml;hren, dass ich keine 
                        Verdauungsprobleme bekomme und mir einen Teil der wertvollen Urlaubstage verderbe? Welche Art der Unterkunft und Reiseart ist f&uuml;r mich die geeignetste? Was ist 
                        in Bezug auf die An- und Abreise zu bedenken? Welche Lebensmittel sollte man als &#187;Notration&#171; mitnehmen? Welche Mittel geh&ouml;ren in die Reiseapotheke? 
                        Eine gute Vorbereitung hilft, dass Sie Ihren Urlaub auch unterwegs entspannt genie&#223;en k&ouml;nnen.
