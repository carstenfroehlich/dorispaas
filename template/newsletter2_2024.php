                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=verantwortung" target="_blank">Schwerpunktthema: Verantwortung f&uuml;r die eigene Verdauung &uuml;bernehmen</a></b>
                        <br />
                        <i>(Menü: Wissensdatenbank/Darmgesundheit/Hilfreiche Ma&#223;nahmen/Verantwortung)</i>
                        <br />
                        Bei Verdauungsproblemen nehmen sich Betroffene selten die Zeit, zun&auml;chst die Ursachen zu ergr&uuml;nden und dann die Verantwortung zur L&ouml;sung zu &uuml;bernehmen. Viel 
                        zu oft wird versucht, diese Verantwortung einer Tablette zu &uuml;bertragen: &#187;Wenn ich diese Pille/Kapsel/Tropfen nehme, werden meine Beschwerden verschwinden&#171;. 
                        Wodurch die Symptome ausgel&ouml;st wurden, wird nicht oder zumindest nicht ausreichend hinterfragt. Genau das aber ist wichtig. Es ist eben nicht &ndash; und schon gar nicht 
                        dauerhaft &ndash; zielf&uuml;hrend, die Verantwortung f&uuml;r die eigene Verdauung auf ein Mittel oder auch den Arzt &uuml;bertragen zu wollen. Die Betroffenen m&uuml;ssen 
                        diese Verantwortung selbst &uuml;bernehmen. Dazu ist es nat&uuml;rlich unerl&auml;sslich, das System zu 
                        verstehen. Eine Ursache kann nur erkannt werden, wenn sich der Zusammenhang mit den Symptomen erschlie&#223;t: nur was ich verstehe, kann ich &auml;ndern. Verantwortung hei&#223;t 
                        deshalb in einem ersten Schritt zu schauen, wie das Verdauungssystem funktioniert und an welcher Stelle es &#187;hakt&#171;. Nur so k&ouml;nnen wirksame Schritte zur Ver&auml;nderung 
                        in Angriff genommen werden, die dann auch nachhaltig wirken k&ouml;nnen.
