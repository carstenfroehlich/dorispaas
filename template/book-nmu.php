                        <h5>Vorwort der BKK</h5> 
                        <hr />
                        Sozialer Wohlstand, moderne Technik und die Fortschritte der Medizin haben den Gesundheitszustand der Bevölkerung spürbar verbessert 
                        und ermöglichen ein längeres Leben mit weniger gesundheitlichen Beeinträchtigungen. Es wird aber immer deutlicher, welch großen Einfluss 
                        jeder Einzelne selbst auf seine Gesundheit oder auf den Verlauf einer Krankheit hat. Regelmäßige Bewegung, gesunde und ausgewogene 
                        Ernährung, eine nikotinfreie Lebensweise und die aktive Bewältigung von Stress halten gesund oder unterstützen zumindest dort, wo die 
                        Gesundheit bereits angeschlagen ist. Häufig bieten auch Selbsthilfegruppen Unterstützung, deren Arbeit wiederum aktiv von der BKK gefördert 
                        wird. Nicht immer sind wir uns dieser Einflussmöglichkeiten bewusst. Gesundes Verhalten wirkt &ndash; ebenso wie gesundheitsschädliches 
                        Verhalten &ndash; oft erst zeitverzögert. Ein gesunder Lebensstil wird daher (leider) häufig erst zum Thema, wenn Beschwerden oder Erkrankungen 
                        die Betroffenen wachgerüttelt haben. Aber auch dann gibt es noch Chancen: Bewegung, gesunde Ernährung und Entspannung stärken Ihre Gesundheit 
                        und verbessern Ihr Wohlbefinden in jedem Lebensabschnitt, in jeder Lebenssituation. Oft sind es ganz einfache Veränderungen im Alltag, die schon 
                        Verbesserungen bringen, ohne mit größeren Kosten oder Mühen verbunden zu sein.
                        <br />
                        <br />
                        Die BKK hat dies schon lange erkannt und sich in allen Lebenswelten &ndash; bei der Arbeit wie in der Freizeit &ndash; als engagierter Vorreiter 
                        für Gesundheitsförderung und Prävention etabliert. Krankheiten vorzubeugen, wo es immer geht, ist eines ihrer vordringlichsten Ziele. Im Falle 
                        einer Krankheit bietet die BKK ihren Versicherten deshalb über die qualitätsgesicherte Versorgung hinaus Hilfen an, um durch Veränderung des 
                        eigenen Lebensstils gesundheitliche Einschränkungen zu vermindern und ein möglichst unbelastetes Leben führen zu können. Einen Beitrag hierzu 
                        liefert auch die vorliegende Ausgabe des Buches &#187;Nahrungsmittelallergien und -unverträglichkeiten &ndash; Genussvoll essen &ndash; unbeschwert 
                        leben&#71;. Details zu weiteren Angeboten erhalten Sie bei Ihrem Ansprechpartner in einer der rund 170 Betriebskrankenkassen in Deutschland oder 
                        im Internet auf der Homepage des BKK Bundesverbands unter der Adresse www.bkk.de.
