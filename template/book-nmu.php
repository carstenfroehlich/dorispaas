                        <h5>Buchbeschreibung:</h5>
                        <hr />
                        Wenn Sie an Verdauungsstörungen wie Bauchschmerzen, Durchfällen, Blähungen oder auch Krämpfen usw. leiden, können Nahrungsmittel die Ursache sein. 
                        Hierbei kann es sich um eine Nahrungsmittelallergie oder auch um eine Nahrungsmittelunverträglichkeit handeln.
                        <br />
                        <br />                        
                        Das in Zusammenarbeit mit dem Allgemeinmediziner und Ernährungsberater (DGE) Dr. med. Erich Krämer entstandene Buch »Nahrungsmittelallergien und 
                        -unverträglichkeiten« zeigt zuerst die generelle Abgrenzung zwischen Allergien und Unverträglichkeiten auf und erklärt die Ursachen. Es hilft, 
                        sich ein Bild von der eigenen Erkrankung zu machen, zwischen einer Nahrungsmittelallergie und einer Unverträglichkeit zu unterscheiden und bietet 
                        Ihnen Hilfestellungen, um den Verursachern Ihrer unangenehmen Verdauungsstörungen oder anderen, mit Nahrungsmitteln in Verbindung stehenden Beschwerden 
                        auf die Spur zu kommen.
                        <br />
                        <br />                        
                        In weiteren Kapiteln erfahren Sie, welche Diagnosemethoden Ihnen und Ihrem Arzt im Falle einer Nahrungsmittelallergie zu Verfügung stehen und welche 
                        Vor- und Nachteile die verschiedenen Tests haben. Sie lernen, wie Sie Allergieauslöser erkennen und meiden können und welche Ernährung für Sie günstig ist.
                        <br />
                        <br />                        
                        Sie erfahren, welche Formen der Intoleranzen es gibt: Milchzuckerunverträglichkeit (Laktoseintoleranz), Fruchtzuckerunverträglichkeit (Fruktoseintoleranz), 
                        Sorbitintoleranz, Haushaltszuckerunverträglichkeit (Saccharoseintoleranz), Histaminintoleranz oder andere sogenannte Pseudoallergien. Sie werden sehen, 
                        welche Diagnosemethoden jeweils geeignet sind, um »Ihre« Beschwerdeverursacher zu ermitteln, und Sie lernen in mehreren Schritten, welche Nahrungsmittel 
                        Sie verzehren dürfen, um beschwerdefrei zu werden.
                        <br />
                        <br />                        
                        Zu jeder Intoleranz finden Sie umfangreiche Listen mit Nahrungsmitteln und Nahrungsmittelgruppen, die Sie verzehren dürfen; Nahrungsmittel, bei denen eine 
                        erhöhte Vorsicht empfohlen wird; oder auch Nahrungsmittel, die Sie meiden sollten, um nicht wieder Beschwerden zu bekommen.
                        <br />
                        <br />                        
                        Sie erfahren viel über eine generell gesunde Ernährung und Lebensweise, die für Ihren Körper, für Ihre Seele und für Ihr Immunsystem am vorteilhaftesten sind, 
                        und es gibt viele Tipps und Hinweise zu Vorbeugemaßnahmen und Behandlungsmöglichkeiten, damit Sie sich wieder so richtig wohlfühlen können.
                        <br />
                        <br />                        
                        Das Buch war im Compact-Verlag, München, in der Ratgeber-Reihe »Gesundheit aktuell« erschienen, die in Kooperation mit dem BKK Bundesverband herausgegeben wird. 
                        Derzeit ist dieses Buch dort jedoch vergriffen und nur noch über meinen Shop erhältlich.                     
