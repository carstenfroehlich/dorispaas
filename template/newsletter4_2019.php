                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-reisedurchfall" target="_blank">Schwerpunktthema: &#187;Reisedurchfall (Reisediarrhoe)&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/St&ouml;rungen/Reisedurchfall)</i>
                        <br />
                        Reisedurchf&auml;lle kommen meist genauso schnell, wie sie auch vergehen. D.h. sie sind selbst limitierend und vergehen &ndash; so unangenehm sie sind &ndash; 
                        in den meisten F&auml;llen von selber. Eine &auml;rztliche Behandlung ist meist nicht n&ouml;tig. Trotzdem m&uuml;ssen nat&uuml;rlich bestimmte Regeln eingehalten werden, 
                        um keine gesundheitlichen Sch&auml;den davon zu tragen und um Ihre intestinale Mikrobiota (Darmflora) zu sch&uuml;tzen. Dies soll selbstverst&auml;ndlich 
                        keinesfalls bedeuten, dass Sie in schweren F&auml;llen &ndash; insbesondere wenn Kinder betroffen sind, nicht sofort &auml;rztliche Betreuung in Anspruch 
                        nehmen sollen. Leichtere Verl&auml;ufe jedoch sind mit einfachen Selbsthilfema&#223;nahmen in der Regel gut zu handhaben. Vor allem aber kann man vorbeugen 
                        und auf diese Weise verhindern, von &#187;Montezumas Rache&#171; heimgesucht zu werden und auch, wenn Sie in Risikogebiete wie den Mittleren Osten, nach 
                        S&uuml;d- und S&uuml;dostasien, Zentralamerika und Afrika reisen, die lang ersehnten Urlaubstage mit gro&#223;er Sicherheit genie&#223;en k&ouml;nnen.      
