                        Liebe Leserinnen und Leser, 
                        welche Jahreszeit eignet sich mehr zum Genießen als der Hochsommer? Alles gr&uuml;nt und bl&uuml;ht, das gute Wetter l&auml;dt uns ein, 
                        nach drau&#223;en zu gehen, uns mit Freunden zu treffen und uns aktiv zu bewegen. Das alles &ndash; die gute Laune, das herrliche Wetter 
                        und die vielen Aktivit&auml;ten &ndash; f&ouml;rdern unsere Gesundheit. Ich m&ouml;chte Sie deshalb herzlich ermuntern, 
                        diese Zeit bewusst zu gestalten und zu intensiv genie&#223;en. Das geht &uuml;brigens auch, wenn Sie keinen Urlaub haben und 
                        diesen eventuell erst sp&auml;ter nehmen wollen oder k&ouml;nnen. Denn der Sommer macht ja nicht am Abend Schluss &ndash; auch nach der 
                        Arbeit k&ouml;nnen Sie noch die eine oder andere Stunde unter freiem Himmel verbringen. Lassen Sie es sich deshalb auf jeden Fall so gut 
                        gehen wie m&ouml;glich. Und wenn Ihr Urlaub erst sp&auml;ter geplant ist, so können Sie die Vorfreude darauf noch ein wenig auskosten.
