                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-04-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Es ist wieder soweit: die Ferien beginnen, und wahrscheinlich haben Sie schon Pläne für diese Tage gemacht. Egal, was Sie vorhaben &ndash; ob Sie 
                        in ferne Länder reisen oder einen Kurztripp in die nähere Umgebung machen wollen, die Natur genie&#223;en,
                        eine St&auml;dtetour planen, Kultur schnuppern wollen oder Ihre freien Tage auf Balkonien verbringen &ndash; ich wünsche Ihnen auf jeden Fall 
                        gute Erholung! Einige unter Ihnen schauen jedoch vielleicht mit etwas gemischen 
                        Gef&uuml;hlen auf diese Zeit, denn mit Nahrungsmittel-Unvertr&auml;glichkeiten oder anderen Problemen, die mit einer eventuell unkalkulierbaren Verdauung 
                        einhergehen, kann eine Reise manchmal auch im wahrsten Sinne des Wortes Bauchschmerzen verursachen. &#187;Wo ist die n&auml;chste Toilette und kann ich sie, 
                        auch wenn es eilig ist, rechtzeitig erreichen? Wie kann ich mir helfen, wenn ich Verstopfung habe und tagelang nicht aufs Klo kann? Und was ist, wenn ich 
                        Durchfall bekomme? Gerade dies kann &uuml;brigens jedem passieren, vollkommen unabh&auml;ngig davon, ob man einen empfindlichen 
                        Darm hat oder nicht. Aus diesem Anlass habe ich den Reisedurchfall als Schwerpunktthema dieses Newsletters gew&auml;hlt. Es ist n&auml;mlich durchaus 
                        m&ouml;glich, dieser unangenehmen und st&ouml;renden Erkrankung vorzubeugen.
