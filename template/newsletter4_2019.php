                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=blog#blog-2019-07-05" target="_blank">Auch mit der Kleidung kann man Gutes für die Gesundheit tun</a></b>
                        <br />
                        <i>(Men&uuml;: Doris Paas/Blog)</i>
                        <br />
                        Unsere Haut ist nicht nur ein gro&#223;es Ausscheidungsorgan, sondern sie nimmt auch viele Stoffe auf, mit der sie in Ber&uuml;hrung 
                        kommt. Dies ist auch der Grund, warum man neue Kleidungsst&uuml;cke vor dem ersten Tragen unbedingt waschen sollte. Auch die Qualit&auml;t 
                        der Kleidung ist mit entscheidend f&uuml;r die Unbedenklichkeit oder aber auch die Gefahr für unsere Gesundheit. Billigkleidung kann 
                        h&auml;ufig stark mit Chemikalien belastet sein, die die schlechte Stoffqualit&auml;t kaschieren sollen. Sind die Impr&auml;gnierungen 
                        herausgewaschen, sehen diese Sachen schnell aus wie Putzlappen. Um die Haut vor diesen Substanzen zu sch&uuml;tzen, ist es wichtig, sie 
                        vor dem Anziehen so weit wie m&ouml;glich aus der W&auml;sche zu entfernen. Gute Kleidung ben&ouml;tigt weniger chemische Ausr&uuml;stung, 
                        was nicht nur f&uuml;r die Umwelt, sondern auch f&uuml;r die eigene Gesundheit vorteilhafter ist.
                        Dar&uuml;ber hinaus werden zur Herstellung neuer Kleidungsst&uuml;cke viele Rohstoffe verwendet. Und hier sind nicht nur die  
                        Baumwolle oder &ndash; schlimmer noch &ndash; Erd&ouml;l f&uuml;r die verschiedensten synthetischen Fasern gemeint, sondern 
                        auch das Wasser, das bei der Produktion in großer Menge verbraucht wird. 
