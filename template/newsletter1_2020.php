                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-vitamine" target="_blank">Schwerpunktthema: &#187;Vitamine und Mineralstoffe&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Ern&auml;hrung/Vitamine und Mineralstoffe</i>
                        <br />
                        &#187;Vitamine und Mineralstoffe sind gesund&#171;, das wei&#223; man. Gemeint waren damit urspr&uuml;nglich die Vitamine und Mineralstoffe, die nat&uuml;rlicherweise 
                        in unserer Nahrung enthalten sind. Soweit ist dem nichts hinzuzuf&uuml;gen. Gesunde, frische Lebensmittel enthalten die gesamte Palette der bisher bekannten Vitamine, 
                        Mineralien in Form von Mengen- und Spurenelementen; und die pflanzlichen Lebensmittel dar&uuml;ber hinaus auch noch jede Menge der so genannten sekund&auml;ren 
                        Pflanzenstoffe, deren genaue Wirkungsweisen teilweise noch gar nicht abschlie&#223;end untersucht worden sind. Alle diese Substanzen werden unter dem Begriff 
                        &#187;Vitalstoffe&#171; zusammengefasst. Diese wertvollen N&auml;hrstoffe sind &ndash; zumindest nach westlicher Lehre &ndash; f&uuml;r die Gesundheit unverzichtbar, 
                        denn alle Stoffwechselvorg&auml;nge ben&ouml;tigen Vitalstoffe. Keine Funktion eines lebenden Organismus kann auf Dauer ohne diese Stoffe ordnungsgem&auml;&#223; 
                        ablaufen und mit den anderen Prozessen des Lebens ineinandergreifen. Ob und ggf. wann es sinnvoll ist, trotz der guten Versorgung durch die Nahrung Vitalstoffe durch 
                        Pr&auml;parate zu erg&auml;nzen, soll dieser Beitrag beleuchten.
