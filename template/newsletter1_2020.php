                        <h5>Ausgabe 50 (Januar 2020)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2020-01-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Ein neues Jahr &ndash; ein neues Jahrzehnt &ndash; hat begonnen. Weltpolitisch sieht es derzeit nicht wirklich gut aus, trotzdem hoffe ich, dass bei den M&auml;chtigen dieser 
                        Welt doch noch Vernunft einkehrt. Bei uns in Europa haben wir zumindest derzeit weniger zu bef&uuml;rchten. Wenn wir aber l&auml;ngerfristig und global denken, m&uuml;ssen wir uns alle  
                        auf jeden Fall Gedanken machen: Gedanken um den Frieden, Gedanken um den Klimawandel, Gedanken um die Entwicklung in der Parteienlandschaft und vieles mehr. Dies wird viele Entscheidungen 
                        brauchen, bei denen jeder f&uuml;r sich seinen Beitrag leisten werden muss. Hierbei sollte jeder so viel beisteuern, wie er kann. Bei manchen ist dies ein sehr kleiner Beitrag, bei 
                        anderen kann er sehr viel gr&ouml;&#223;er sein. Alle diese Beitr&auml;ge zusammen ergeben dann (hoffentlich) die &Auml;nderungen, die uns als Gemeinschaft weiterbringen. Wie 
                        leistungsf&auml;hig jeder ist, h&auml;ngt nicht nur von seinem Verm&ouml;gen und von seiner Einsicht in das gro&#223;e Ganze ab, sondern auch von seiner Kooperationsbereitschaft,
                        etwas zum Wohle Aller beizusteuern. Alle Beitr&auml;ge zusammen &ndash; die kleinen und die gro&#223;en &ndash; n&uuml;tzen uns als Gesellschaft, n&uuml;tzen unserer Welt. 
                        An Neujahr fassen viele Menschen gute Vors&auml;tze. Aus Erfahrung wei&#223; man, dass die meisten dieser Vorhaben kaum die erste Woche &uuml;berleben &ndash; vielleicht liegt 
                        dies daran, dass wir uns &uuml;berfordern. Teilen wir jedoch das, was wir erreichen wollen, in kleine Abschnitte auf, erscheint die Aufgabe schon nicht mehr so schwer. Sich 
                        in kleinen Schritten an ein Ziel heranzutasten, kann oftmals der richtigere Weg sein &ndash; sei es f&uuml;r persönliche Ziele oder f&uuml;r ein Gemeinschaftsziel. Ich w&uuml;nsche 
                        Ihnen und uns allen viel Erfolg!
