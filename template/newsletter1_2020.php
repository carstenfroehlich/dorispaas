                        <a href="http://www.dorispaas.de/index.php?page=ganz-vitamin-d" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2020-01-sonne.png" alt="Vitamin D" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 10px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-vitamin-d" target="_blank">Vitamin D und Sonne</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Ern&auml;hrung/Vitamin D und Sonne</i>
                        <br />
                        Vitamine und Mineralstoffe kann unsere K&ouml;rper nicht selbst bilden, so dass wir diese Vitalstoffe mit der Nahrung aufnehmen m&uuml;ssen. Es gibt jeoch eine Ausnahme: 
                        Das Vitamin D kann unser K&ouml;rper &ndash; zumindest zum Teil &ndash; selber bilden. Hierzu ist jedoch Sonnenlicht erforderlich, das in ausreichender Menge und unter 
                        bestimmten Voraussetzungen (u.a. der Einstrahlwinkel) in unserer Haut gebildet werden kann. In sehr sonnenreichen Gegenden (um den &Auml;quator) reicht diese Bildung 
                        allemal aus, in sonnen&auml;rmeren Gebieten versorgt sich der K&ouml;rper mit dem zus&auml;tzlichen Vitamin D aus der Nahrung. Nur bei ung&uuml;nstigen Bedingungen 
                        (zu wenig Sonne, unzureichende Nahrung, Darmerkrankungen oder bestimmten Bekleidungsvorschriften) kann eine Erg&auml;nzung durch geeignete Pr&auml;parate hilfreich sein.
                        Gerade im Winter ist es deshalb sinnvoll, den Vitamin-D-Spiegel vom Arzt &uuml;berpr&uuml;fen und sich ggf. ein geeignetes Pr&auml;parat empfehlen zu lassen.
