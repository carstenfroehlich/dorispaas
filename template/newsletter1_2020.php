                        Liebe Leserinnen und Leser, die oben erw&auml;hnte Strategie der kleinen Schritte m&ouml;chte ich Ihnen aus eigener Eerfahrung ans Herz legen.
                        &#187;Es ist noch kein Meister vom Himmel gefallen&#171; &ndash; dieses Sprichwort kennen wir alle und beherzigen es doch viel zu selten. Nat&uuml;rlich ist es 
                        nur allzu verst&auml;ndlich, dass wir ungeduldig sind, wenn es uns schlecht geht und wir Beschwerden haben, dass wir diese so schnell wie m&ouml;glich wieder loswerden 
                        wollen. Es n&uuml;tzt aber herzlich wenig, eventuell in einer Beratung ausgearbeitete &Auml;nderungen alle auf einmal umsetzen zu wollen. So &uuml;berfordern wir uns in der Regel. 
                        Deshalb empfiehlt es sich, sich langsam an das (gerne auch hochgesteckte) Ziel heranzutasten. Jeder kleine Teilerfolg ist ein Schritt in die richtige Richtung, sollte
                        mit Stolz erf&uuml;llen und motivieren zu weiteren (Fort-)Schritten. Auch in Sachen Umwelt sind schon kleine Verhaltens&auml;nderungen Beitr&auml;ge zum dringend 
                        erforderlichen Erfolg. Und um bei diesem Thema zu bleiben: Inzwischen ist mir die Herstellung einer tollen 
                        <a href="http://www.dorispaas.de/index.php?page=hautpflege#seife" target="_blank">Haarseife</a> gelungen, die sich gleichzeitig auch f&uuml;r den K&ouml;rper eignet und mit der sich 
                        jede Menge Plastikm&uuml;ll vermeiden l&auml;sst. Probieren Sie das Rezept doch einmal aus.
                        
