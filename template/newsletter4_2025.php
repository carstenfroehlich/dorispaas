                        Liebe Leserin, lieber Leser.
                        <br />
                        &#187;Apfel, Nuss und Mandelkerne duften wieder durch das Haus. An dem Ofen sitzt man gerne und der Nordwind tobt sich aus&#171; hei&#223;t es in einem Lied, 
                        das wir in der Winterzeit und zu Weihnachten singen. Auch in vielen anderen Liedern werden N&uuml;sse und Mandeln erw&auml;hnt, weil sie traditionell in der winterlichen 
                        K&uuml;che verzehrt werden. Wie alle Samen, die im Sommer und Herbst gesammelt wurden, lassen sie sich gut aufbewahren. Sie enthalten neben Vitaminen und Mineralien auch viele 
                        Ballaststoffe als Futter f&uuml;r die Darmbakterien und wertvolle &Ouml;le mit antientz&uuml;ndlicher Wirkung. Zahlreiche Pl&auml;tzchen- und 
                        Lebkuchenrezepte enthalten als Zutaten N&uuml;sse und Samen, die solche Knabbereien auch zu einer gesunden Leckerei machen. Abgesehen von dem enthaltenen Zucker, 
                        der f&uuml;r niemanden wirklich zutr&auml;glich ist, vertragen einige Menschen aber die N&uuml;sse und Mandeln nicht oder zumindest nicht in jeder Menge. 
                        Dies k&ouml;nnte an den Oxalaten liegen, die in diesen Lebensmitteln in sehr reichlicher Menge enthalten sind. Was es damit auf sich hat, ist das 
                        Schwerpunktthema dieses Newsletters.
