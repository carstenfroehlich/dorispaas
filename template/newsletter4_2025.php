                        <br />
                        <i>(Menü: Wissensdatenbank/Unvertr&auml;glichkeiten/Oxalatbelastung)</i>
                        <br />
                        Eine noch sehr unbekannte Nahrungsmittel-Unvertr&auml;glichkeit ist die Oxalatproblematik. Bisher nur Thema bei den Nephrologen, den Fach&auml;rzten f&uuml;r 
                        Nierenkrankheiten, sind die Oxalate aber bekannt daf&uuml;r, zu Nierensteinen und den damit verbundenen Komplikationen zu f&uuml;hren. Dass die Oxalate auch 
                        <b>Verdauungsbeschwerden</b> wie <b>Bauchschmerzen</b>, <b>Bl&auml;hungen</b>, <b>Durchf&auml;lle</b> oder <b>Verstopfung</b>, aber auch <b>Entgleisungen 
                        der bakteriellen Besiedelung</b> oder das <b>Leaky-Gut-Syndrom</b> verursachen k&ouml;nnen und genauso eher unspezifische Symptome wie <b>M&uuml;digkeit</b>, 
                        <b>Kopfschmerzen</b> oder <b>Brainfog</b> nach sich ziehen k&ouml;nnen, ist noch viel zu wenig verbreitetes Wissen. Gerade wenn Sie sich schon mit verschiedenen 
                        Unvertr&auml;glichkeiten auseinandergesetzt haben, wom&ouml;glich mehr und mehr Lebensmittel von Ihrem Speisezettel gestrichen haben, ohne wirklich endlich 
                        den Durchbruch erzielt zu haben, lohnt es sich, sich einmal mit dem Thema &#187;Oxalate&#171; zu besch&auml;ftigen.                        
