                    <h5>Buchbeschreibung</h5>
                    <hr />
                    Sie ernähren sich gesund und haben trotzdem immer wieder Beschwerden wie 
                    Bauchschmerzen, Blähungen, Übelkeit, Durchfall oder Verstopfung? 
                    <br />
                    Sie haben eventuell andere Nahrungsmittel-Unverträglichkeiten, essen eigentlich 
                    nur &#187;Erlaubtes&#171; und haben trotzdem immer wieder diese quälenden Symptome? 
                    <br />
                    Der Arzt hat vielleicht aus diesen Gründen ein Reizdarm-Syndrom bei Ihnen 
                    diagnostiziert, und Sie sind schon ganz verzweifelt, was Sie überhaupt noch 
                    essen dürfen?
                    <br />
                    Hier könnten Oligosaccharide &ndash; eine Gruppe von Mehrfachzuckern &ndash; 
                    schuld an Ihren Problemen sein.
                    <br />
                    Mit den hier vorliegenden Informationen über die in Europa noch so gut wie 
                    unbekannte Oligosaccharid-Unverträglichkeit und vielen Tipps und Tricks können 
                    Sie endlich wieder beschwerdefrei werden.
                    <br />
                    <br />
                    Die Paas&#039;schen Heftchen behandeln Themen aus dem Gesundheitsbereich. Sie erläutern 
                    jeweils in kurzer und klarer Form die Ursachen und Hintergründe von Beschwerden. 
                    Sie helfen, Probleme zu erkennen und zu verstehen und zeigen erste Schritte in die 
                    richtige Richtung: eine gesunde Lebensweise ohne Beschwerden, um sich wohl zu fühlen. 
                    <br />
                    Die Heftchen erheben bewusst keinen Anspruch auf Ausführlichkeit, sondern 
                    verschaffen Ihnen in kurzer, aber korrekter Form einen ersten &Uuml;berblick über 
                    einen Sachverhalt. Trotz des geringen Umfangs sind sie jedoch nicht oberflächlich 
                    und immer sorgfältig recherchiert: In rund einer Stunde wissen Sie alles 
                    Wesentliche zum Thema.<br />
