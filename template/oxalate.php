                        <h5>Literatur in Deutschland</h5>
                        <hr>
                        Bei Vorliegen eines Oxalatproblems ist es empfehlenswert, sich mit geeigneter Fachliteratur schlau zu machen. Es gibt zahlreiche medizinische Fachbücher, 
                        die sich auf den Zusammenhang zwischen Oxalaten und Nierenproblemen beziehen. Im Zusammenhang mit Verdauungsproblemen jedoch ist der deutschsprachige Markt 
                        sehr dünn.
                        <br />
                        <br />
                        Wie bei so vielem sind uns die USA auch bei Oxalaten in Bezug auf Verdauungsprobleme voraus, und dort findet man einiges an Informationen. Deutschland ist 
                        hier leider (noch) ein Entwicklungsland. Eines der wenigen ins Deutsche übersetzten Bücher stammt von der Amerikanerin Sally K. Norton und trägt den Titel 
                        &#187; <b>Gefährliche Superfoods? </b>Warum der hohe Oxalat-Gehalt bestimmter Lebensmittel uns krank machen kann&#171;. Weil es aus einer amerikanischen 
                        Feder stammt, ist vieles auf amerikanische Verhältnisse zugeschnitten. Grundlegendes jedoch ist auch für uns brauchbar, so dass es sich lohnt, das Buch zu 
                        lesen &ndash; vorausgesetzt, man betrachtet es mit dem gebotenen Abstand. Lesen Sie gerne meine 
                        <a href="kurzinfos#kurzinfo-2025-11-23" target="_blank">ausführliche Buchrezension</a> auf der Seite Kurzinfos.
