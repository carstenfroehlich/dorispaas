                        <a id="vegan"></a>
                        <hr>
                        <h5>Vegane Ernährung</h5>
                        <hr>
                        Da sich praktisch keine Oxalate in tierischen Lebensmitteln befinden, jedoch viele pflanzliche Lebensmittel stark belastet sind, stellt dies insbesondere 
                        für alle <b>vegan lebenden Menschen</b> ein Problem dar. Wenn der gesamte Bereich der tierischen Produkte ausgeklammert wird, summiert sich das Oxalat in 
                        den dann ausschließlich verzehrten pflanzlichen Bestandteilen umso mehr.
                        <br />
                        <br />
                        Wie an anderer Stelle bereits kritisch beleuchtet, möchte ich vor allem all jenen Menschen, die Oxalatprobleme haben und sich bisher vegan ernährt haben, 
                        empfehlen, sich unter diesen Gesichtspunkten noch einmal mit Ihrer Entscheidung zu befassen. Bitte lesen Sie hierzu auch den Beitrag
                        <a href="ganz-vegan" target="_blank">&#187;Wie gesund ist vegane Ernährung&#171;</a>.
                        <br />
                        <br />
                        <a id="ernaehrung"></a>
                        <hr>
                        <h5>Oxalatbewusste Zubereitungsarten von Lebensmitteln</h5>
                        <hr>
                        Nicht nur die Auswahl der Lebensmittel hat Einfluss auf ein eventuelles Oxalatproblem. Auch die <b>Zubereitungsart</b> kann einen optimalen Abbau und damit 
                        die Verträglichkeit von Oxalaten beeinträchtigen.
                        <br />
                        <br />
                        Grundsätzlich gilt, dass je gröber die verzehrten Pflanzenteile sind, desto weniger kann das enthaltene Oxalat herausgelöst werden und verlässt das 
                        Verdauungssystem auf natürlichem Wege. Im Umkehrschluss heißt das: je feiner zerkleinert die pflanzlichen Lebensmittel sind, desto intensiver kann das 
                        Verdauungssystem die Oxalate aus dem Nahrungsbrei herauslösen.
                        <br />
                        <br />
                        Das heißt nun aber nicht, dass Sie Ihr Essen nicht mehr kauen, sondern in groben Brocken hinunterschlingen sollen. Es gilt immer noch und ohne jeden Abstrich: 
                        &#187; <b>Gut gekaut ist halb verdaut! </b>&#171;
                        <br />
                        <br />
                        Aber eine häufig im Zusammenhang mit &#187;gesunder Ernährung&#171; und insbesondere auch mit der veganen Ernährungsform übliche Zubereitungsart, die 
                        <b>Smoothies</b> &ndash; und hier oft die &#187;grünen Smoothies&#171; ist im Zusammenhang mit Oxalat erwähnenswert. Hierbei werden grüne Blätter wie u.a. 
                        Spinat mit Hochleistungsmixern so weit zerkleinert, wie es kein Gebiss kann. Auf diese Weise werden sämtliche Inhaltsstoffe der Pflanzenzellen bis zum 
                        allerkleinsten Rest dem Verdauungssystem zugänglich gemacht. Und dies trifft eben auch auf die Oxalate zu, die, wenn die Lebensmittel &#187;nur gekaut&#171; 
                        werden, in größtenteils noch intakten Zellen den Darm passiert und ausgeschieden werden. Konsumiert als Smoothie, der noch dazu rasch getrunken und nicht 
                        häppchenweise eingespeichelt und verzehrt wird, rauscht die Flüssigkeit in und durch den Darm, und die Oxalate können dort vollständig aus dem Speisebrei 
                        extrahiert werden.
                        <br />
                        <br />
                        <b>Gekochte Lebensmittel</b> enthalten oft weniger Oxalate, wenn das Einweich- und Kochwasser weggegossen wird. Eine gesunde Vorgehensweise bei Kochen gebietet 
                        aber, möglichst kein Kochwasser, in dem ja auch Mineralien und Vitamine gelöst sind, eben nicht wegzugießen, sondern möglichst mit zu verarbeiten. Ein 
                        Dilemma also! Die Lösung würde hier zwischen den Möglichkeiten liegen: im Allgemeinen sollte den Vitaminen und Mineralien zuliebe das Kochwasser mitverzehrt 
                        werden. Bei stark oxalathaltigen Lebensmitteln wie z.B. vor allem Bohnen jedoch sollte das Einweich- und Kochwasser weggeschüttet werden, um den Oxalatgehalt 
                        zu senken.
                        <br />
                        <br />
                        Es kann also auch die Zubereitungsart sein, die das Ausmaß von Problemen beeinflusst. Deshalb empfehle ich Ihnen bei einem Oxalatproblem dringend, sich intensiv 
                        sowohl in Bezug auf die Lebensmittelauswahl als auch auf die Zubereitungsart mit Ihrer Ernährung zu beschäftigen.
                        <br />
                        <br />
                        <a id="menge"></a>
                        <hr>
                        <h5>Die Menge macht das Gift</h5>
                        <hr>
                        Wie ganz oben erwähnt, stellt eine kleinere, angemessene Menge an Oxalaten selten ein Problem dar. Diese treten erst auf, wenn die <b>Verzehrmengen</b> zu 
                        groß bzw. deren Abbau und Ausleitung sich nicht die Waage halten.
                        <br />
                        <br />
                        Deshalb kann man zumindest verhindern, dass ein Oxalatproblem auftritt, indem man ein Gefühl dafür entwickelt, welche Lebensmittel die &#187;Hauptübeltäter&#171; 
                        sind und deren Verzehr auf ein vernünftiges Maß reduzieren. Die Betonung liegt hier auf &#187;reduzieren&#171;, denn es ist nicht erforderlich, ganz auf 
                        &#187;Oxalatbomben&#171; zu verzichten. Ab und an Spinat auf den Speisezettel zu setzen, ist vernünftig, gesund und lecker. Jeden Tag Spinat zu verzehren 
                        &ndash; womöglich noch in einem Smoothie kleinstgehäckselt &ndash; ist definitiv keine gute Idee.
                        <br />
                        <br />
                        <a id="behandlung"></a>
                        <hr>
                        <h5>Behandlung des Oxalatproblems</h5>
                        <hr>
                        Ist tatsächlich eine Belastung festgestellt, sollte man zum einen die Zufuhr der Oxalate reduzieren und zu andern deren Bindung und Ausleitung zu fördern. 
                        <br />
                        <br />
                        Auf jeden Fall ist es eine gute und leicht durchzuführende Präventionsmaßnahme, <b>ausreichend zu trinken</b>. Dies ist die einfachste und beste Maßnahme zur 
                        <b>Förderung der Ausleitung</b> aufgenommener und ggf. auch bereits eingelagerter Oxalate.
                        <br />
                        <br />
                        Zur <b>Verringerung der Zufuhr</b> von Oxalaten gehört dann aber auch die <b>Ernährung</b> auf den Prüfstand. Bei der Reduktion ist es wichtig, nicht zu 
                        drastisch vorzugehen und abrupt von heute auf morgen auf sämtliche oxalathaltigen Lebensmittel zu verzichten. In einem solchen Falle könnte das sogenannte 
                        &#187;<b>Oxalatdumping</b>&#171; auftreten. Durch die Reduzierung des &#187;Nachschubs&#171; wird die Freisetzung von im Körper angereicherten Oxalaten angeregt. 
                        Diese freien Oxalate führen dann zu vermehrten Symptomen.
                        <br />
                        <br />
                        Um ein solches Oxalatdumping zu vermeiden, muss man die Zufuhr vorsichtig nach und nach herunterfahren. Zunächst sollte man diejenigen Lebensmittel, die am meisten 
                        Oxalate enthalten und die am häufigsten und in den größten Mengen verzehrt werden, Woche um Woche moderat reduzieren. Stellen sich Probleme ein, die man mit den 
                        Oxalaten in Verbindung bringt, ist die Geschwindigkeit der Reduktion zu verlangsamen. 
                        <br />
                        <br />
                        Kommt man hingegen gut und ohne vermehrte Probleme voran, sollte man die Zufuhr der Oxalate weiter und weiter reduzieren, bis eine gute Balance zwischen 
                        Oxalatminimierung und einer trotzdem noch ausreichenden Abwechslung auf dem Teller erreicht ist.
                        <br />
                        <br />
                        <b>Hinweis</b>: Man sollte nicht vergessen, dass ein Oxalatproblem über Jahre entstanden ist. Zu erhoffen oder zu erwarten, dass sich dieses innerhalb von wenigen 
                        Wochen bereinigen lässt, ist vermessen. Geduld ist hier mit Sicherheit der beste Verbündete.
                        <br />
                        <br />
                        Zur Förderung der Ausleitung von freien Oxalaten sollte man zu oxalatreichen Lebensmitteln immer </b>gleichzeitig</b> ein <b>kalziumreiches Lebensmittel</b> in 
                        einer Mahlzeit kombinieren. Tee beispielsweise kann man, wie es in England üblich ist, mit Milch trinken. Dann werden die Oxalate im Tee bereits in der Tasse 
                        &#187;entschärft&#171;. Den Spinat &#187;mit Blubb&#171; zu verfeinern, hat den gleichen Effekt. Das allein ist selbstverständlich allein nicht ausreichend, 
                        trägt aber zumindest zu einem Teil zur Lösung bei. 
                        <br />
                        <br />
                        Aber nicht nur Milch und Milchprodukte enthalten viel Kalzium. Es gibt auch zahlreiche pflanzliche Lebensmittel, u.a. Brokkoli, Grünkohl oder Rukola, um nur 
                        einige wenige zu nennen, die sehr kalziumreich sind und deren Aufnahme in den Speisezettel die Oxalatsituation verbessern können. 
                        <br />
                        <br />
                        Es ist empfehlenswert, sich zu einmal die Zeit zu nehmen und zu schauen, welche Lebensmittel wie viel Kalzium genau enthalten, denn eine ausreichende Wirkung 
                        auf die Oxalatbindung erfordert etwa <b>500-1000mg Kalzium pro Mahlzeit</b>, was aber mit der &#187;richtigen&#171; Auswahl von Lebensmittel durchaus erreichbar 
                        ist &ndash; später dann selbstverständlich auch ohne das zeitaufwändige Wälzen von Listen.
                        <br />
                        <br />
                        Natürlich kann man auch </b>Kalzium-Präparate</b> einnehmen und so das Mineral supplementieren. Bitte begeben Sie sich hier nicht selbst auf die Suche im 
                        unübersichtlichen Dschungel des Internets, sondern lassen Sie sich geeignete Präparate von Fachleuten empfehlen. Nicht jede Kalziumverbindung ist in gleicher 
                        Weise geeignet.
                        <br />
                        <br />
                        Eine solche Fachberatung benötigen Sie ohnehin für sämtliche Maßnahmen, die zur <b>Behandlung der Ursachen</b> erforderlich sind. Falls eine chronisch 
                        entzündliche Darmerkrankung (CeD) vorliegt, sind diese ärztlicherseits zu behandeln. 
                        <br />
                        <br />
                        Liegen Schädigungen der Darmschleimhaut vor, die nicht auf eine CeD zurückzuführen ist, müssen auch hier geeignete Maßnahmen ergriffen werden. Hier sind 
                        wahrscheinlich eher ein Heilpraktiker oder ein spezialisierter Ganzheitlicher Gesundheitsberater der richtige Ansprechpartner &ndash; genauso wie bei 
                        Vorliegen und der Behandlung einer <a href="duenndarmfehlbesiedelung" target="_blank">Dünndarmfehlbesiedelung</a>.
                        <br />
