                        Viele pflanzliche Lebensmittel enthalten Oxalate. Das Wort &#187;Oxalate&#171; ist hier in der Mehrzahl geschrieben, weil es sich dabei um verschiedene 
                        chemische Verbindungen der Oxalsäure handeln kann. 
                        Pflanzen bilden diese natürlichen Stoffe zum einen für ihr Wachstum, denn die länglichen, harten Kristalle stützen die hochwachsenden Stängel und Triebe.
                        Zum anderen aber wirken Oxalate als Schutzstoffe vor Fressfeinden. Oxalate gelangen mit dem Blut in alle Organe und können dort Schaden anrichten. Da die 
                        Kristalle teils nadelspitz sind, beeinträchtigen sie den Organismus allein durch ihre Struktur, haben aber auch toxische Wirkungen.
                        <br />
                        <br />
                        <a id="symptome"></a>
                        <hr>
                        <h5>Symptome bei Oxalatbelastung</h5>
                        <hr>
                        Oxalate stören zahlreiche Funktionen im Organismus. Hier ist beispielsweise die Beeinträchtigung der <b>Wirkung von Vitaminen, Mineralien und Enzymen</b> 
                        zu nennen, wenn die Oxalate mit diesen Stoffen Verbindungen herstellen, so dass sie in ihrer reinen Form nicht mehr für den Stoffwechsel zur Verfügung stehen.
                        <br />
                        <br />
                        Weiterhin wirken Oxalat-Verbindungen toxisch und <b>behindern den Stoffwechsel</b> und damit auch die Verdauung von Tieren und Menschen, und es entstehen 
                        bei demjenigen, der solche Pflanzen verzehrt, zahlreiche, teils auch unspezifische Probleme. 
                        <br />
                        <br />
                        Auch <b>hormonelle Wirkungen</b> können mit einer Oxalatbelastung einhergehen, genauso wie die Störung einer optimalen <b>Mitochondrienfunktion</b>. 
                        <br />
                        <br />
                        Rein mechanische Probleme können entstehen, wenn die spitzen Oxalatkristalle die Zellwände durchbohren oder als zusammengeballte Kristalle 
                        größere &#187;Klumpen&#171; bilden. Schon seit Jahrzehnten ist der Zusammenhang von Oxalaten und <b>Nierenproblemen</b> bekannt, wenn das Oxalat als 
                        Nierensteine auskristallisiert, deren Oberflächen sehr rau sind und so das empfindliche Nierengewebe verletzen können. Darüber hinaus können sie die 
                        feinen Nierengänge verstopfen und zu äußerst schmerzhaften Koliken führen. 
                        <br />
                        <br />
                        Und auch in der Gallenblase können sich aus Oxalatkristallen die sogenannten <b><a href="ganz-galle" target="_blank">Gallensteine</a></b> bilden.
                        <br />
                        <br />
                        Leider immer noch viel zu wenig bekannt ist, dass auch <b>Verdauungsbeschwerden</b> wie <b>Bauchschmerzen</b>, <b>Blähungen</b>, <b>Durchfälle</b> oder 
                        <b>Verstopfung</b>, aber auch <b>Entgleisungen der bakteriellen Besiedelung</b> oder das <b>Leaky-Gut-Syndrom</b> auftreten können, aber genauso auch 
                        können u.a. <b>Müdigkeit</b>, <b>Kopfschmerzen</b>, <b>Brainfog</b> (&#187;Gehirnnebel&#171;) oder auch <b>Gelenkprobleme</b> die Folge von Oxalaten in 
                        der Nahrung sein. Sogar </b>Osteoporose</b> kann mit einem übermäßigen Oxalatverzehr in Verbindung gebracht werden, weil Oxalate Kalzium binden, das 
                        dann nicht mehr für den gesunden Knochenstoffwechsel zur Verfügung steht. 
                        <br />
                        <br />
                        Es gibt zahlreiche körperliche und in der Folge dann auch psychische Probleme, die bei genauerem Hinsehen durch Oxalate in der Nahrung (mit) verursacht 
                        werden können. Leider werden diese Symptome in der Regel aber viel zu lange nicht mit den Oxalaten als Verursacher in Verbindung gebracht.
                        <br />
                        <br />
                        <a id="abbau"></a>
                        <hr>
                        <h5>Oxalatabbau im Darm </h5>
                        <hr>
                        Oxalate aus Lebensmitteln stellen kein Problem dar, solange sie erstens in vernünftigen Mengen verzehrt werden und zweitens, wenn sie im Darm &#187;unschädlich&#171; 
                        gemacht und ausgeschieden werden.
                        <br />
                        <br />
                        Sobald aber das Verhältnis zwischen Aufnahme und Abbau und Ausscheidung nicht ausgewogen ist, weil mit der Nahrung mehr Oxalate verzehrt werden und/oder 
                        die Oxalate nicht ausreichend abgebaut oder gebunden und ausgeschieden werden, reichern sich sie im Körper an und können ihren schädlichen Einfluss ausüben.
                        <br />
                        <br />
                        Für den Abbau von Oxalaten ist z.B. das Darmbakterium <b>Oxalobacter formigenes</b> zuständig. Befinden sich ausreichend dieser Mikroorganismen im Darm, 
                        können auch angemessene Mengen an Oxalaten abgebaut werden. Fehlt dieser Keim bzw. mangelt es an der ausreichenden Menge, verbleiben Oxalate im Darm.
                        <br />
                        <br />
                        Eine weitere Reduktion von zunächst schädlichen, freien Mengen an Oxalaten geschieht durch deren <b>Bindung an Kalzium</b>. Die Verbindungen von Oxalaten und 
                        Kalzium ergeben feste, unauflösliche Strukturen, die über den natürlichen Weg ausgeschieden werden. Ist zu wenig freies Kalzium im Darm vorhanden, können auch 
                        nicht alle Oxalate ausgeschieden werden und werden vom Organismus aufgenommen.
                        <br />
                        <br />
                        Ein weiteres Problem kann im Darm auftreten, wenn ein <b>Gallensäureverlustsyndrom</b> vorliegt. Gallensäuren werden, nachdem sie ihre Aufgaben im Dünndarm 
                        erledigt haben, normalerweise im letzten Bereich des Dünndarms (dem terminalen Ileum) rückresorbiert und anschließend recycelt. U.a. bei einer 
                        <b>Dünndarmfehlbesiedelung</b> (SIBO/IMO) und/oder einer Schädigung der Schleimhaut u.a. bei <b>chronisch entzündlichen Darmerkrankungen</b> (CeD) kann diese 
                        Rückresorbierung unterbleiben, so dass die Gallensäuren in den Dickdarm gelangen. Dann binden die Gallensäuren ihrerseits das dort vorhandene Kalzium, das 
                        dann nicht mehr für die Oxalatbindung zur Verfügung steht.
                        <br />
                        <br />
                        Weiterhin können <b>zu geringe Trinkmengen</b> die Oxalatausscheidung behindern. In bestimmtem Maße werden auch ungebundene Oxalate ausgeschieden &ndash; 
                        teils über die Nieren, teils aber auch mit dem Stuhl. Wird zu wenig getrunken, werden die Nieren unzureichender durchspült und der Stuhl ist fester 
                        und der Transit durch den Darm langsamer. All dies führt dazu, dass sich die Oxalatkristalle einerseits in größerem Maße zu Nierengrieß oder Nierensteinen 
                        zusammenballen können. Andererseits können sie auch einen größeren Einfluss auf die Darmschleimhaut ausüben. 
                        <br />
                        <br />
                        Durch die längere Verweildauer wird auch die Aufnahme über das Blut in den Organismus intensiviert, so dass ein größerer Anteil der Oxalate zu den Organen 
                        transportiert werden und sich dort ablagern kann.
                        <br />
                        <br />
                        Es ist also wichtig, dass das Verhältnis zwischen Aufnahme und Abbau bzw. Bindung und Ausscheidung ausgeglichen ist.
                        <br />
                        <br />
                        <a id="mastzellen"></a>
                        <hr>
                        <h5>Zusammenhang von Oxalat, Mastzellen und Histamin</h5>
                        <hr>
                        Oxalate können in hohem Maße die <b>Mastzellen aktivieren</b>. Mastzellen gehören zur Gruppe der Immunzellen, die für die Abwehrfunktion des Organismus 
                        zuständig sind. Da Oxalate vom Körper als zu bekämpfende Stoffe bewertet werden, werden diese Zellen aktiviert, um den Organismus vor Schaden zu schützen.
                        <br />
                        <br />
                        Aktivierte Mastzellen schütten zahlreiche Botenstoffe wie u.a. <b>Histamin</b> aus. Wenn die Produktion des Histamin-abbauenden Enzyms Diaminoxidase (DAO) 
                        in der Darmschleimhaut so gut wie unverändert bleibt &ndash; oder sich wegen der Schädigung der Zellen wo möglich sogar noch verringert &ndash; stimmt 
                        das erforderliche Verhältnis nicht mehr, so dass ein Histaminproblem aufgrund eines erhöhten Histaminspiegels die Folge ist.
                        <br />
                        <br />
                        Histamin führt nicht nur zu den allergieähnlichen Erscheinungen einer sogenannten &#187;<b>Pseudoallergie</b>&#171;. Es wirkt auch entzündungsfördernd, 
                        und so folgen durch einen erhöhten Histaminspiegel <b>Entzündungen</b> auf allen möglichen Ebenen im Körper. Dies können sogenannte &#187;stille 
                        Entzündungen&#171; (silent inflammations) sein, die oberflächlich als solche kaum wahrgenommen werden, aber auch deutlichere Entzündungen wie u.a. in 
                        Gelenken oder in den Blutadern, wo sie dann mehr oder weniger langsam zu augenfälligeren Symptomen und Erkrankungen führen.
                        <br />
                        <br />
                        <a id="diagnose"></a>
                        <hr>
                        <h5>Diagnostik eines Oxalatproblems</h5>
                        <hr>
                        Die Diagnostik eines Oxalatproblems sollte bei jeder Vermutung aufgrund der bisher beschriebenen Symptome durchgeführt werden. 
                        <br />
                        <br />
                        Zunächst gehört dazu der <b>Speisezettel auf den Prüfstand</b>: anhand eines <b>Ernährungstagebuchs</b> und der Beschreibung der üblicherweise bevorzugten 
                        und in größeren Mengen verzehrten Lebensmittel kann man eine erste Einschätzung darüber bekommen, ob und wie wahrscheinlich eine Oxalatbelastung ist. 
                        Dazu muss den Betroffenen und dem Diagnostiker klar sein, welche Lebensmittel viele Oxalate enthalten und wie oft und in welchen Mengen diese Lebensmittel 
                        verzehrt werden. Stehen wenige bzw. nur kleine Mengen oxalathaltige Lebensmittel auf dem Speiseplan, ist ein Oxalatproblem eher unwahrscheinlich und die 
                        Ursache von Symptomen wahrscheinlich woanders zu suchen. Eine Vorlage für ein Ernährungs- und Symptomtagebuch finden Sie im 
                        <a href="downloads#tagebuch" target="_blank">Downloadbereich</a> auf dieser Website.
                        <br />
                        <br />
                        Mit einem geeigneten <b>Stuhltest</b> kann man schauen, ob das Darmbakterium Oxalobacter formigenes in ausreichender Menge im Stuhl vorhanden ist. Ist dies 
                        nicht der Fall, liegt die Schlussfolgerung nahe, dass der Abbau der Oxalate zumindest auf diesem Wege nicht ausreichend ist.
                        <br />
                        <br />
                        In einem solchen Stuhltest kann man auch ein Gallensäureverlustsyndrom erkennen. Liegt dieses vor, ist die Kalziumbindung gestört, was Oxalatprobleme fördert. 
                        Ggf. ist die Ursache des Gallensäureverlustsyndroms mit geeigneten Tests zu klären.
                        <br />
                        <br />
                        Darüber hinaus gibt der Stuhltest auch Auskunft über die Entzündungsparameter und auch über eine eventuelle Barrierestörung wie das Leaky-Gut-Syndrom.
                        <br />
                        <br />
                        Selbstverständlich muss auch das <b>Stuhlverhalten</b> mit betrachtet werden: Verstopfung kann, wie oben beschrieben, eine Oxalatbelastung fördern.
                        <br />
                        <br />
                        Und last but not least kann man anhand eines <b>24-Stunden-Urintests</b> die Oxalatausscheidung im Urin messen. Da die Ausscheidung von Oxalaten über den 
                        Tag sehr stark schwankt, reicht eine einzelne Urinprobe nicht aus. Somit muss man den Urin über den Zeitraum von 24 Stunden in einem Gefäß sammeln 
                        und dann daraus eine Probe entnehmen und einsenden.
                        <br />
                        <br />
                        Es sei jedoch darauf hingewiesen, dass auch diese Sammlung nicht wirklich aussagekräftig ist, denn die Ausscheidung kann sich auch über Tage, Wochen oder 
                        sogar Monate ändern, so dass man mit einem solchen Urintest nur eventuell einen Eindruck gewinnt, keinesfalls jedoch verbindliche Aussagen über die Ausprägung.
                        <br />
                        <br />
                        Bis verlässlichere Tests gefunden werden, verlangt die Diagnose eines Oxalatproblems folglich noch sehr viel Erfahrung und Einfühlungsvermögen.
                        <br />
                        <br />
                        <a id="nahrungsoxalate"></a>
                        <hr>
                        <h5>Oxalate in der Nahrung</h5>
                        <hr>
                        Es gibt zwei Lebensmittel, die die Liste der &#187;gehaltvollsten&#171; Probanden anführen: dies sind der <b>Spinat</b> und der <b>Rhabarber</b>. Aber auch 
                        zahlreiche andere pflanzliche Lebensmittel können auf unserem täglichen Speisezettel stehen, die stark oxalathaltig sind. Dazu gehören unter vielen anderen 
                        <b>Nüsse</b> und <b>Mandeln</b>, <b>Süßkartoffeln</b>, <b>Buchweizen</b>, <b>Amaranth</b>, <b>Quinoa</b> und <b>Weizen</b>, <b>Vollkorngetreide</b>, <b>Kurkuma</b>, 
                        <b>schwarzer Pfeffer</b> und weitere beliebte Zutaten von sich &#187;gesund&#171; ernährenden Menschen. Aber auch <b>schwarzer und grüner Tee</b> und 
                        <b>Schokolade</b> stehen auf der &#187;roten Liste&#171;.
                        <br />
                        <br />
                        <b>Ein ganz wichtiger Hinweis</b>: Dies heißt jetzt keinesfalls, dass Sie sämtliche oxalathaltigen Lebensmittel ab sofort meiden sollten wie der Teufel das 
                        Weihwasser, denn das würde Ihren Speisezettel viel zu stark einschränken. In kleinen Mengen sind Oxalate, die ja in sehr vielen gesunden pflanzlichen Lebensmitteln 
                        enthalten sind, nicht problematisch, und ein stabiles Verdauungssystem kann mit solchen Mengen umgehen. Es wäre gar nicht erstrebenswert, jedes Pflänzchen, 
                        dass ein wenig Oxalat enthält, vom Speisezettel zu streichen &ndash; es würde kaum noch etwas zu essen übrigbleiben.
                        <br />
                        <br />
                        An zahlreichen Stellen auf dieser Website weise ich darauf hin, dass die <b>Diversität Ihrer Mikrobiota</b> (Darmflora) und damit Ihrer Gesundheit eng 
                        verknüpft ist mit dem <b>Abwechslungsreichtum auf Ihrem Teller</b>. 
                        <br />
                        <br />
                        Lesen Sie hier z.B. die Beiträge &#187;<a href="multiunvertraeglichkeit" target="_blank">Multiple Nahrungsmittel-Unverträglichkeiten</a>&#171; oder auch 
                        &#187;<a href="darmfloragrundsatz" target="_blank">Grundsätzliches über die Mikrobiota</a>&#171;.
