                        Derzeit gibt es noch keine Tests (beispielsweise analog zum Wasserstoff-Atemtest zur 
                        Diagnose von Laktose-, Fruktose- und Sorbit-Intoleranz), mit denen eine 
                        Oligosaccharid-Intoleranz diagnostiziert werden k&ouml;nnte. Dies liegt zum 
                        einen daran, dass die Pharmafirmen noch nicht f&uuml;r dieses Problem sensibilisiert 
                        sind und zum anderen daran, dass hier ja eine ganze Gruppe von verschiedenen 
                        Kohlenhydraten vorliegt, die Beschwerden verursachen.
                        <br />
                        <br />
                        Somit bleibt nur die M&ouml;glichkeit der <b>Ausschluss-Di&auml;t</b>, mit der der 
                        Betroffene selbst herausfinden kann, ob bestimmte Oligosaccharide Probleme machen.
                        <br />
                        <br />
                        Dazu muss zuerst f&uuml;r einige Tage eine Basiskost aus gesch&auml;ltem Reis 
                        verzehrt werden, bis man beschwerdefrei ist. Danach wird &uuml;ber eine Zeitspanne 
                        von ca. 2 Wochen nach und nach im Abstand von 2-3 Tagen je ein Lebensmittel dem 
                        Speiseplan hinzugef&uuml;gt, das keine oder nur verschwindend geringe Mengen 
                        Oligosaccharide enth&auml;lt &ndash; also vorrangig tierische Lebensmittel wie 
                        mageres Fleisch, Fisch und Eier. Aller Wahrscheinlichkeit nach treten hier keine 
                        Probleme auf &ndash; anderenfalls ist das betreffende Lebensmittel wegzulassen, 
                        bis man wieder symptomfrei ist.
                        <br />
                        <br />
                        Anschlie&#223;end f&uuml;gt man dem Speisezettel vorsichtig nach und nach geringe 
                        Mengen an oligosaccharidhaltigen Lebensmitteln hinzu (siehe Liste) und testet aus, 
                        welche Lebensmittel bek&ouml;mmlich sind und welche Probleme bereiten.
                        <br />
                        <br />
                        Innerhalb von ca. 6 Wochen kann man auf diese Weise gut herausarbeiten, ob und in 
                        welcher Auspr&auml;gung oligosaccharidhaltige Lebensmittel Beschwerden verursachen 
                        und ob eine Oligosaccharid-Unvertr&auml;glichkeit naheliegt. Unerl&auml;sslich dabei 
                        ist das F&uuml;hren eines Verzehr- und Symptomtagebuchs. Einen 
                        <a href="downloads#tagebuch">Vordruck</a> k&ouml;nnen 
                        Sie hier kostenlos downloaden.
                        <br />
                        <br />
                        Die genaue Vorgehensweise bei der Ausschluss-Di&auml;t ist in dem Buch &#187;Kurz 
                        und klar: Oligosaccharid-Unvertr&auml;glichkeit&#171; beschrieben.
