                        <br />
                        <br />
                        <span style="font-style:italic">Weniger differenziert sieht es die Europaabgeordnete 
                        der CDU, Christa Klaß, Winzerin von Beruf, und schiebt die 
                        Verantwortung dem Benutzer der gefährlichen Stoffe zu: &#187;Informationen 
