                        <br />
                        <a id="immunsystem"></a>
                        <hr />
                        <h5>Das Immunsystem</h5>
                        <hr />
                        Unser Immunsystem fungiert als &#187;Körperpolizei&#171; und registriert zunächst einmal alles als fremd, 
                        was in unseren Körper eindringt. Diese Fremdlinge (Antigene) werden nun in Bezug auf die 
                        &#187;Gefährlichkeit&#171; für den Organismus bewertet und ggf. abgewehrt oder sogar unschädlich gemacht. 
                        Es gibt ein angeborenes Immunsystem, mit dem die Säuglinge auf die Welt kommen. Hierzu zählt z.B. die 
                        natürliche Barrierefunktion der Schleimhäute mit der darüber liegenden Schleimschicht, die unerwünschten 
                        Stoffen und Mikroorganismen das Eindringen in das Körperinnere weitestgehend verwehren. Weiterhin ist 
                        das angeborene Immunsystem in der Lage, grobe Strukturen von Bakterien zu erkennen und diese zerstören 
                        zu können. Es ist jedoch nicht auf bestimmte Krankheitserreger spezialisiert, so dass es wirklich gefährlichen 
                        Erregern nicht in der erforderlichen Wirksamkeit begegnen kann.
                        <br />
                        <br />
                        Das erworbene Immunsystem, das der Mensch nach und nach während des Heranwachsens entwickelt, kann sehr viel 
                        spezifischer zwischen den verschiedenen Krankheitserregern unterscheiden. Jedes Mal, wenn ein unbekannter 
                        Keim eindringt, setzt sich das Immunsystem nicht nur mit generellen Strukturen auseinander, sondern tastet 
                        auch die ganz individuellen Charakteristika dieser Mikroorganismen ab und lernt so, speziell zugeschnittene Antikörper 
                        zu bilden. Dieser Prozess dauert einige Tage, das Gedächtnis für diese Antikörperbildung bleibt dann aber über 
                        längere Zeit &ndash; teilweise sogar das ganze Leben &ndash; gespeichert. Dringen nun zu einem späteren Zeitpunkt 
                        erneut Keime dieser Art in den Körper ein, kann die Bildung der geeigneten Antikörper unverzüglich in Gang gesetzt 
                        und der Feind erfolgreich bekämpft werden. Lesen Sie hierzu bitte auch den Beitrag 
                        &#187;<a href="ganz-immun" target="_blank">Das Immunsystem &ndash; ganzheitlich betrachtet</a>&#171;.
                        <br />
                        <br />
                        Da der weitausgrößte Teil des Immunsystems im Darm lokalisiert ist, kann es ein robustes Immunsystem natürlich 
                        auch nur in einem gesunden Darm und insbesondere in einer gesunden Darmschleimhaut geben. Ist die Schleimhaut 
                        hingegen in einem desolaten Zustand, kann auch unsere Immunabwehr nur mangelhaft arbeiten. Sind also beispielsweise 
                        die Schleimhautzellen schlecht ernährt oder die so genannten &#187;Tight Junctions&#171;, also die Verschlussstücke, 
                        die die Zellen untereinander verbinden, zu dünn oder vielleicht so gut wie gar nicht mehr vorhanden, wird die 
                        Schleimhautbarriere insgesamt durchlässiger, so dass Fremdkörper und/oder Bakterien die natürliche Immunbarriere 
                        überwinden und ins Körperinnere eindringen und Krankheiten auslösen können. Oder ist die Schleimschicht, die die 
                        Zellen zum einen ernährt und zum anderen schützt, zu dünn oder auch zu alt und zu einem sogenannten 
                        &#187;Biofilm&#171; verklebt, folgt daraus ebenfalls eine 
                        Verschlechterung der optimalen Funktionsfähigkeit der Schleimhautzellen. Dies nennt man das &#187;Leaky-Gut-Syndrom&#171;. 
                        (Lesen Sie hierzu auch den Beitrag &#187;<a href="darmfloragrundsatz" target="_blank">Grundsätzliches über die Darmflora</a>&#171;).
                        <br />
                        <br />
                        <a id="impfung"></a>
                        <hr />
                        <h5>Das Wirkprinzip bei Impfungen</h5>
                        <hr />
                        Das Immunsystem benötigt einige Zeit, um sich mit den verschiedenen Antigenen &#187;bekannt zu machen&#171;. 
                        Dies nennt man die &#187;Sensibilisierungs-Phase&#171;. Nach dieser Zeit, die einige Tage bis Wochen in Anspruch 
                        nehmen kann und in der es lernt, die ganz spezifischen Antikörper zu bilden, kann das Immunsystem bei einer 
                        erneuten Berührung mit den entsprechenden Antigenen fast unverzüglich die geeigneten Antikörper in größeren 
                        Mengen produzieren und so Erreger rasch unschädlich machen und Krankheiten erfolgreich abwehren &ndash; man 
                        ist immun gegen diesen Erreger.
                        <br />
                        <br />
                        Dieses Prinzip machen sich auch die Impfungen zunutze. Hierbei werden kleinere Mengen deaktivierter Keime, z.B. 
                        der Polioerreger, der die gefährliche Kinderlähmung verursacht, in das Körperinnere gebracht (z.B. durch eine 
                        Spritze). Nun kann sich unser Immunsystem mit diesen Erregern, denen man ja vorsichtshalber 
                        &#187;die Zähne gezogen hat&#171; auseinandersetzen und lernen, sie zunächst zu erkennen und dann die 
                        geeigneten Antikörper zu bilden. Sollte nun später tatsächlich ein Kontakt mit Polioerregern stattfinden, 
                        kennt der Organismus diese schon und kann unverzüglich die geeignete Abwehr zur Verfügung stellen. Impfungen 
                        können so schwerwiegende Erkrankungen, die nicht nur ein hohes Erkrankungsrisiko bergen, sondern auch schwere 
                        Begleiterscheinungen und Spätfolgen haben können, erfolgreich verhindern.
                        <br />
                        <br />
                        Leider jedoch können selbst Impfungen, die von der offiziellen &#187;Ständigen Impfkommission&#171; (STIKO) 
                        empfohlen werden, Nebenwirkungen haben. Nicht nur unproblematische, vorübergehende Impfreaktionen wie eine 
                        leichte Entzündung oder ein Jucken an der Impfstelle sind häufiger zu beobachten, auch schwerwiegendere 
                        Spätfolgen werden beobachtet. Selten wird eine ganz offensichtlich mit der Impfung in Zusammenhang zu bringende 
                        Komplikation als Folge einer Impfung anerkannt, aber auch Probleme wie unentdeckte Entzündungen des Gehirns, 
                        Autismus oder Demenz  sollen mit Impfungen in Verbindung gebracht werden können. Die Impfstoffe enthalten nicht 
                        nur die abgeschwächten Keime, sondern zusätzlich auch so genannte &#187;Adjuvanzien&#171; (Zusatz- und Hilfsstoffe) 
                        wie z.B. Aluminium, die die Wirksamkeit des Serums verstärken sollen. Insbesondere diese Adjuvanzien, aber auch 
                        die Impfsera selbst werden deshalb von einigen Menschen kritisch bewertet. 
                        <br />
                        <br />
                        Somit haben sich zwei in den meisten Fällen unversöhnliche Lager von Impfbefürwortern und Impfgegnern gebildet. 
                        Aus meiner Sicht wäre es sehr unvernünftig, generell gegen Impfungen zu sein, denn mit dieser Maßnahme ist es 
                        möglich, Krankheiten vorzubeugen, die früher insbesondere viele Kinder dahingerafft oder aber viele Spätfolgen 
                        nach sich gezogen haben. Auf der anderen Seite aber finde ich, dass man die in meinen Augen nicht ganz 
                        unberechtigten Bedenken gegen die Nebenwirkungen nicht so einfach von Tisch wischen sollte. Es sollte deshalb 
                        eine <b>sorgsamere Abwägung der Vor- und Nachteile</b> stattfinden, so dass eine <b>individuelle Entscheidung</b> 
                        für oder gegen <b>eine spezielle Impfung in einem speziellen Fall und zu einem ganz speziellen Zeitpunkt</b> 
                        möglich wird. Generell zu sagen, man wolle weder seine Kinder noch sich selbst impfen lassen, wäre aus meiner 
                        Sicht genauso leichtsinnig, wie alle und jede Impfung vornehmen zu lassen, ohne dass ein reelles 
                        Erkrankungsrisiko vorliegt.
                        <br />
                        <br />
                        Besonders bemerkenswert ist, dass bei Impfungen bis auf wenige Ausnahmen, bei denen die Substanzen per Schluckimpfung 
                        verabreicht werden, bewusst die Schutzmechanismen des darmassoziierten Immunsystems umgangen und die Sera wie 
                        &#187;mit der Brechstange&#171; direkt ins Körperinnere gespritzt werden. Ob und in welcher Ausprägung diese Vorgehensweise 
                        Sinn macht und ob und in welcher Ausprägung es eine Gefahr darstellt bzw. darstellen könnte, wage ich nicht 
                        zu beurteilen. Ich halte es jedoch für nicht unwichtig, auch diese Gesichtspunkte bei den persönlichen 
                        Entscheidungen mit einzubeziehen und mit einem Arzt zu besprechen, der Impfungen unvoreingenommen bewertet.
                        <br />
                        <br />
                        <a id="autovaccinen"></a>
                        <hr />
                        <h5>Autovaccinen</h5>
                        <hr />
                        Unabhängig davon, wie man zu Impfungen insgesamt und/oder zur Risikobewertung einzelner Impfungen steht, ist es 
                        sicherlich Konsens, jedes Risiko für Erkrankungen so gering wie möglich zu halten und trotzdem einen bestmöglichen 
                        Einfluss auf das Immunsystem zu nehmen. Welche Möglichkeiten <b>außer einer Impfung</b> hier zur Verfügung stehen, 
                        finden Sie im Beitrag &#187;<a href="ganz-immun" target="_blank">Das Immunsystem &ndash; ganzheitlich betrachtet</a>&#171;.
                        <br />
                        <br />
                        Zusätzlich gibt es jedoch noch einen weiteren Weg, und das ist die oben angesprochene Anwendung von <b>Autovaccinen</b>.
                        <br />
                        <br />
                        Autovaccinen &ndash; insbesondere die erregerspezifischen Autovaccinen &ndash; arbeiten nach einem ähnlichen Prinzip 
                        wie die Impfungen, wobei sich ja der Name auch aus diesem 
                        Prinzip erklärt. Der Fachbegriff &#187;Vakzination&#171; für Impfung entstand, weil die ersten Impfungen gegen 
                        Pocken mit Material aus den wesentlich ungefährlicheren Kuhpocken gewonnen wurde, weshalb sich der Fachbegriff 
                        aus dem lateinischen &#187;vacca&#171; (für Kuh) ableitete. Der andere Teil des Wortes, &#187;auto&#171;, kommt 
                        von dem griechischen &#187;autos&#171;, der &#187;selbst&#171; bedeutet.
                        <br />
                        <br />
                        Eine Autovaccine ist also ein Impfstoff, der nicht aus fremden Keimen hergestellt wird, sondern aus eigenen 
                        Organismen &ndash; wobei streng genommen eigentlich doch fremdes Material benutzt wird, denn die Autovaccinen 
                        werden nicht aus eigenen Körperzellen hergestellt, sondern aus Material von (allerdings eigenen) Darmkeimen, 
                        so genanntem &#187;autologen Material&#171; (lesen hierzu den Abschnitt 
                        &#187;<a href="<?= REQUEST_URI ?>#herstellung" class="faqmenu">Herstellung und Anwendung von Autovaccinen</a>&#171; 
                        weiter unten auf dieser Seite). Mit den Autovaccinen wird kein (echtes) Fremdmaterial verwendet, sondern die 
                        Darmbakterien, die dem eigenen Körper ja bekannt sind. Dies bietet neben den &#187;normalen&#171; Impfungen 
                        eine sehr potente Möglichkeit <b>für ganz bestimmte Einsatzgebiete</b>.
                        <br />
                        <br />
                        <b>Wichtige Hinweise:</b> An dieser Stelle möchte ich ganz klar hervorheben, dass der Einsatz von Autovaccinen 
                        kein Ersatz für in meinen Augen wichtige Impfungen gegen gefährliche Krankheiten wie Kinderlähmung, Diphtherie, 
                        Tetanus, Mumps und Masern (und einigen anderen) darstellt, sondern als Ergänzung zur <b>allgemeinen</b> 
                        Stärkung des Immunsystems zur Anwendung kommt. Nur in bestimmten Fällen könnten Autovaccinen u.U. als Ersatz 
                        für Impfungen angesehen werden, beispielweise als Grippeprophylaxe durch 
                        die Stärkung der körpereigenen Abwehrkräfte bei Personen, die <b>nicht durch schwere Erkrankungen oder 
                        fortgeschrittenes Alter beeinträchtigt</b> sind. Trotzdem können Autovaccinen <b>zusätzlich</b>  
                        auch bei dieser Personengruppe angewendet werden, denn sie wirken im Gegensatz zur Grippeschutzimpfung 
                        auch gegen die so genannten grippalen Infekte, die nichts mit einer &#187;richtigen&#171; Grippe zu tun haben. 
                        Bitte lassen Sie sich hier auf jeden Fall von einem neutral über Impfungen urteilenden Arzt beraten.
                        <br />
                        <br />
                        Weiterhin eignen sich Autovaccinen <b>nur bedingt für Kinder unter 3 Jahren</b>, denn bei 
                        Kleinkindern befindet sich das Immunsystem noch in der Entwicklung, die erst nach diesem Alter 
                        weit genug fortgeschritten ist. Hier bitte auf jeden Fall einen spezialisierten Kinderarzt zurate ziehen.
                        <br />
                        <br />
                        Das System der Autovaccinen beruht auf der Tatsache, dass bestimmte Keime aus der patienteneigenen Mikrobiota 
                        im Darm (AutoColiVaccinen), Zahnfleischtaschen oder auch von infizierten Wunden (erregerspezifische Autovaccinen) 
                        im Labor vermehrt werden. Ist eine ausreichende Menge an Keimen entstanden, werden diese abgetötet und in 
                        eine über einige Wochen haltbare Lösung gebracht. Diese Lösung wird nun in mehreren Schritten verdünnt. 
                        <br />
                        <br />
                        Autovaccinen können in verschiedener Weise in den Körper eingebracht werden: so gibt es die Möglichkeit, die 
                        Lösung unter bzw. in die Haut zu spritzen (Injektionsanwendung), sie kann per Spray auf die Nasen- (nasale Anwendung) 
                        oder Rachenschleimhaut gesprüht (orale Anwendung) werden, oder aber auch in der Armbeuge 
                        auf die Körperhaut gesprüht und eingerieben (perkutane Anwendung) werden. Jede Applikationsform hat ihre 
                        Einsatzgebiete und Berechtigungen.
                        <br />
                        <br />
                        <a id="autovaccinenprinzip"></a>
                        <hr />
                        <h5>Das Wirkprinzip von AutoColiVaccinen</h5>
                        <hr />
                        Je nachdem, aus welchen Körperregionen das Ausgangsmaterial für die Autovaccinen gewonnen und in welcher Weise 
                        sie eingenommen oder appliziert werden, kann das Immunsystem auf diese Stoffe reagieren.
                        <br />
                        <br />
                        <b>In meiner Praxis empfehle ich ausschließlich AutoColiVaccinen, die aus bestimmten Keimen aus der Darmflora 
                        gewonnen werden, insbesondere als potentes Mittel bei Verdauungsproblemen. Die Anwendung über Schleimhäute 
                        oder die Haut (nasale, orale oder perkutane AutoColiVaccinen) ist einfach zu Hause selbst durchführbar. 
                        Aus diesem Grunde beziehe ich mich bei den Ausführungen zum Wirkprinzip 
                        ausschließlich auf diese Anwendungsbereiche. </b>
                        <br />
                        <br />
                        Eine intakte Darmschleimhaut bildet mit ihren dicht zusammenhängenden Schleimhautzellen und dem aufliegenden 
                        Schleim eine mechanische Barriere, so dass unerwünschte Keime nicht ins Körperinnere dringen können. 
                        Eine gesunde Darmflora besteht aus (in der Mehrzahl) nützlichen, aber immer auch aus (i.d.R. wenigen) 
                        krankheitserregenden Bakterien und anderen Mikroorganismen. Auch wenn es sich zunächst so anhört, als 
                        wenn es doch eigentlich erstrebenswert sein sollte, dass ausschließlich &#187;gute&#171; Darmbakterien 
                        enthalten sein sollten, so haben die &#187;schlechten&#171; doch durchaus eine wichtige Aufgabe, denn auch sie 
                        trainieren das Immunsystem. Durch spezielle, gewollt undichte Stellen in der Darmschleimhaut, den 
                        &#187;Peyer&#39;schen Plaques&#171;, können (und sollen) Krankheitserreger genauso wie die &#187;guten&#171; 
                        Bakterien aus der Darmflora in begrenzter Menge in 
                        das Körperinnere eindringen und sich dort mit den speziellen Immunzellen auseinandersetzen. Hier finden 
                        dann im Prinzip ähnliche Vorgänge wie bei einer Impfung statt: das (noch) untrainierte Immunsystem kann 
                        sich mit den wenigen Erregern &#187;in Ruhe&#171; auseinandersetzen, die Oberflächenstrukturen abtasten, 
                        sie so kennenlernen und die Fähigkeit entwickeln, Antikörper bilden zu können.
                        <br />
                        <br />
                        AutoColiVaccinen allerdings sind in engerem Sinne keine Impfung, die ja eine Immunität ganz gezielt 
                        gegen einen einzelnen Erregertyp erzeugen soll. Hingegen wird bei der Behandlung mit AutoColiVaccinen
                        so gut wie keine Antikörperbildung beobachtet, jedoch erzeugen sie eine ganz <b>allgemeine</b> 
                        Modulation des Immunsystems, also eine allgemeine Stärkung. Gleichzeitig findet aber auch 
                        eine Regulation statt, also auch eine Beruhigung von unangepassten, überschießenden Reaktionen wie z.B. 
                        bei Allergien oder auch Autoimmunerkrankungen.
                        <br />
                        <br />
                        Diese Wirkweise basiert auf der Tatsache, dass AutoColiVaccinen ein aus der Balance geratenes Gleichgewicht 
                        zwischen bestimmten Immunzellen regulieren, den so genannten T-Helferzellen Th1 und Th2. Durch diese 
                        Verbesserung können die von den verschiedenen Zellarten produzierten Immunbotenstoffe (Zytokine) 
                        wieder im optimalen Verhältnis gebildet werden. Diese Botenstoffe sind für die Informationsübertragung 
                        zwischen den verschiedenen Immunzellen zuständig und können deren Aktivität anregen oder bei Bedarf 
                        auch bremsen. Eine ausgeglichene Balance ist wichtig, um einerseits eine funktionsfähige Abwehr zu 
                        ermöglichen (Stärkung des Immunsystems), auf der anderen Seite aber Überreaktionen (bei Allergien) 
                        zu verhindern.
                        <br />
                        <br />
                        Patienteneigene AutoColiVaccinen sind an &#187;ihren Spender&#171; und seine ganz individuellen 
                        Besonderheiten angepasst und deshalb nicht mit industriell hergestellten Bakterienpräparaten vergleichbar. 
                        Durch die Verwendung der individuellen Bakterien und die anfänglich hohe Verdünnung, die langsam gesteigert 
                        wird, finden auch so gut wie keine spezifischen Antikörpereffekte gegen die eigenen Mikroorganismen statt.
                        
                        Da inzwischen unstreitig anerkannt ist, dass das Immunsystem eng mit der Qualität der Darmflora und der 
                        Darmschleimhaut zusammenhängt, wirkt sich jede Veränderung des Immunsystems (sowohl in Richtung 
                        &#187;besser&#171; als auch &#187;schlechter&#171;) auch auf die Qualität von Darmflora und Darmschleimhaut 
                        aus &ndash; und umgekehrt.
                        <br />
                        <br />
                        Die Anwendung von AutoColiVaccinen stellt somit eine <b>ursächliche (kausale) Behandlungform</b> dar, 
                        da zum einen die Qualität der Darmflora verbessert als auch das schleimhautassoziierte (mucosa-assoziierte) 
                        Immunsystem (MIS) gestärkt wird. Auf diese Weise wirkt der Einsatz von AutoColiVaccinen langfristig und 
                        doktert nicht nur kurzfristig an Symptomen herum.
                        <br />
                        <br />
                        <a id="autovaccinen-immunsystem"></a>
                        <hr />
                        <h5>AutoColiVaccinen zur Regulierung des Immunsystems</h5>
                        <hr />
                        Die Anwendung von AutoColiVaccinen fördert die Eigenregulationsfähigkeit des Organismus &ndash; 
                        und stellt somit keine kurzfristige symptomatische Behandlung dar, sondern ermöglicht eine 
                        <b>langfristige</b> Besserung.
                        <br />
                        <br />
                        Auf diese Weise sind Wirkungen in Richtung Stärkung und Aktivierung möglich, z.B. bei immer 
                        wieder auftretenden (rezidivierenden) Infekten wie Erkältungen, grippalen Infekten (nicht 
                        zu verwechseln mit einer &#187;echten&#171; Grippe!), Nasennebenhöhlenentzündungen (Sinusitis), 
                        Bronchitiden oder auch bei Harnwegsinfekten.
                        <br />
                        <br />
                        Die Regulierung kann das Immunsystem aber auch in der entgegensetzten Richtung bei Erkrankungen 
                        des atopischen Formenkreises beruhigen. Neigt der Patient also zu Heuschnupfen, allergischem 
                        Ekzem oder auch Nahrungsmittel-Allergien, stellt die Behandlung mit AutoColiVaccinen über 
                        einen längeren Zeitraum eine vielversprechende Therapiemöglichkeit dar. Am besten beginnt 
                        man hier die Anwendung in der Zeitspanne, in der möglichst wenige Antigene zu erwarten sind, 
                        so dass die Behandlung in eine symptomarme Phase fällt.
                        <br />
                        <br />
                        Ggf. kann eine Behandlung mit AutoColiVaccinen nach einem längeren Zeitabschnitt wiederholt 
                        werden, um den Erfolg zu festigen.
                        <br />
                        <br />
                        <a id="autovaccinen-verdauungsprobleme"></a>
                        <hr />
                        <h5>AutoColiVaccinen als wirksame Hilfe bei Verdauungsproblemen</h5>
                        <hr />
                        Noch weniger als zur Stärkung des Immunsystems und bei Allergieneigung ist der Einsatz von 
                        AutoColiVaccinen bei den verschiedensten Magen-/Darmbeschwerden bekannt.
                        <br />
                        <br />
                        In Studien mit Patienten u.a. mit unklaren Magenschmerzen, Reizdarm, Durchfällen und/oder 
                        Verstopfung konnte nach der Anwendung von AutoColiVaccinen nicht nur eine (eventuell subjektiv empfundene) 
                        Besserung der Beschwerden beobachtet, sondern ein objektiv nachweisbarer Rückgang von für 
                        entzündliche Prozesse charakteristischen Blutparametern gemessen werden. Dieser Zusammenhang ist 
                        stimmig: Ein höherer Grad von Entzündungen (auch der so genannten &#187;stillen&#171; und Mikro-Entzündungen)
                        führt immer zu mehr Beschwerden als ein niedrigerer Entzündungsgrad.
                        <br />
                        <br />
                        Der Wirkmechanismus einer Behandlung mit AutoColiVaccinen setzt insbesondere am 
                        schleimhaut-assoziierten Immunsystem an. Sämtliche Schleimhäute bilden die Grenzfläche 
                        zwischen Außen- und Innenwelt, und eine intakte Schleimhaut, deren gesunde Zellen 
                        durch funktionsfähige Tight Junctions zusammengehalten werden, kann allein durch 
                        ihre Barrierewirkung das Eindringen von Antigenen, Fremdkörpern und Giftstoffen in 
                        das Körperinnere verhindern. Zudem werden Schutzstoffe wie ß-Defensine oder 
                        sekretorisches Immunglobulin A (sIgA) gebildet, die u.a. vor Entzündungen schützen.
                        <br />
                        <br />
                        <b>Die AutoColiVaccinen stärken die Integrität aller Schleimhäute &ndash; auch der 
                        Darmschleimhaut &ndash; und senken die Entzündungsbereitschaft</b>, wodurch die Durchlässigkeit 
                        der Schleimhäute verringert wird. Es gelangen weniger Fremdkörper und Giftstoffe, unverdaute 
                        Nahrungsbestandteile und Bakterien ins Körperinnere, so dass der Organismus deutlich entlastet 
                        wird und Nahrungsmittel besser verdaut werden können.
                        <br />
                        <br />
                        Die in bestimmten Bereichen der Schleimhaut befindlichen Mastzellen enthalten Botenstoffe wie 
                        z.B. das Histamin, die bei Bedarf ausgeschüttet werden, die bei einer Überproduktion aber 
                        auch Entzündungen verursachen können.
                        <b>Durch die Behandlung mit AutoColiVaccinen werden die Mastzellen stabilisiert</b>, so 
                        dass diese nicht mehr überreagieren. Es werden nur noch die erforderlichen Mengen an 
                        Botenstoffen ausgeschüttet und kein überschüssiges Histamin freigesetzt. Da das Histamin 
                        nicht nur die Entzündungsbereitschaft fördert, sondern auch für die Schmerzübertragung 
                        zuständig ist, werden <b>entzündliche Prozesse gestoppt und eine unangemessene Schmerzbewertung 
                        im Darm normalisiert</b>.
                        <br />
                        <br />
                        Da die Darmschleimhaut das &#187;Nest&#171; für die Darmflora darstellt und sich beide Systeme 
                        gegenseitig beeinflussen, ist es logisch, dass sich nur in einer gesunden Darmschleimhaut auch eine 
                        gesunde Mikrobiota entwickeln und halten kann. (Lesen Sie hierzu auch den Beitrag 
                        &#187;<a href="darmfloragrundsatz" target="_blank">Grundsätzliches über die Darmflora</a>&#171;).
                        Was also den ursprünglich angedachtenen Wirkmechanismus der AutoColiVaccinen ausmacht &ndash; die Stärkung des Immunsystems 
                        durch die Stabilisierung von Darmschleimhaut und Darmflora &ndash; nützt deshalb auch all denjenigen, die 
                        Verdauungsprobleme haben, denn so gut wie alle Verdauungsprobleme basieren auf einer mangelhaften 
                        Darmschleimhaut und einer ungesunden Darmflora &ndash; entweder als eigentlicher Grund oder &#187;nur&#171; 
                        als Verstärker der Beschwerden. <b>Eine Verbesserung von Darmschleimhaut und Darmflora ist eine essentielle 
                        Voraussetzung, Verdauungsbeschwerden dauerhaft bessern oder sogar ganz abstellen zu können. AutoColiVaccinen 
                        sind hierfür ein vielversprechendes Mittel!</b>
                        <br />
                        <br />
                        Auch, wenn einige Therapeuten AutoColiVaccinen in Form von Injektionen verabreichen, bevorzugen 
                        andere (wie auch ich) die Anwendung über die Schleimhaut. Aufgrund der embryonalen Entwicklung, 
                        bei der sich sämtliche Schleimhäute aus ein- und demselben Keimblatt gebildet haben, hängen 
                        alle Schleimhäute als so genanntes &#187;Schleimhautorgan&#171; zusammen. AutoColiVaccinen 
                        wirken also auch auf die Schleimhaut des Verdauungssystems, wenn sie in Form von Nasen- oder 
                        Rachenspray aufgebracht werden. Dieser Weg entspricht ja auch den normalen physiologischen 
                        Vorgängen, bei denen Bakterien über Nase oder Mund in den Organismus gelangen. Da sowohl die 
                        Nasenschleimhaut als auch die Rachenschleimhaut eine sehr große Fläche darstellen, eignen sich 
                        die orale und nasale Verabreichung besonders gut zur Anwendung von AutoColiVaccinen. Bei dieser 
                        Applikationsform werden zudem die dort befindlichen lymphatischen Gewebe wie der Waldeyer&#39;sche 
                        Rachenring direkt mit den AutoColiVaccinen in Berührung gebracht, so dass sie direkt auf das 
                        Immunsystem Einfluss nehmen können.
                        Bei sehr magen-/darmempfindlichen oder (gegenüber &#187;Darmkeimen&#171;) skeptischen Erwachsenen 
                        stellt die perkutane Anwendung über die Haut in der Armbeuge ebenfalls eine akzeptable Verabreichungsform dar.
                        <br />
                        <br />
                        <a id="herstellung"></a>
                        <hr />
                        <h5>Herstellung von AutoColiVaccinen</h5>
                        <hr />
                        AutoColiVaccinen sind, weil sie aus patienteneigenen Stoffen hergestellt und nur diesem 
                        Patienten/Klienten auch wieder verabreicht werden, nicht rezeptpflichtig und werden als sogenannte 
                        &#187;Individualarzneimittel&#171; bezeichnet. Trotzdem entsprechen die Vorschriften für die 
                        Herstellung denen von zulassungspflichtigen Medikamenten, und der Hersteller muss die Regeln 
                        der &#187;Good Manufacturing Practice (Gute Herstellungspraxis)&#171; einhalten und nachweisen.
                        <br />
                        <br />
                        <img src="<?php echo IMG_PATH; ?>autovaccinen-stuhlprobe.png" alt="Stuhlprobe" class="right" />
                        Zur Herstellung werden aus einer Stuhlprobe (Faeces), die der Patient abgibt und an den Hersteller 
                        versendet, bestimmte Formen (humane Rauhformen) von nicht-pathogenen (nicht krankheitserregenden) 
                        Escherichia coli-Bakterien gewonnen, die zu den so genannten &#187;immunmodulierenden Darmbakterien&#171;
                        gehören. Diese Bakterien werden über mehrere Tage vermehrt und anschließend 
                        inaktiviert, denn für den Wirkmechanismus der AutoColiVaccinen ist 
                        nur die Oberflächenstruktur von Zellwandbestandteilen der Bakterien entscheidend, nicht das 
                        lebende Bakterium.
                        <br />
                        <br />
                        <i>Das nebenstehende Bild zeigt ein Set zum Versenden einer Stuhlprobe.</i>
                        <br />
                        <br />
                        Zum Schluss werden die gewonnenen Bakterien in eine isotonische Kochsalzlösung gebracht und 
                        in mehreren Schritten verdünnt. Jede Lösungskonzentration wird aufbewahrt. Die Lösung mit der 
                        höchsten Bakterienkonzentration erhält die Nummernkennzeichnung 1, die mit der nächst niedrigeren 
                        Konzentration erhält die 2. Auf diese Weise entstehen bis zu zehn unterschiedliche Konzentrationen. 
                        Dabei enthält das Fläschchen mit der Kennzeichnung 1 zehnmal mehr Bakterienbestandteile als das 
                        Fläschchen mit der 2, das mit der 3 zehnmal mehr als das mit der 4 usw.
                        <br />
                        <br />
                        Jedes Fläschchen ist mit einer Nummer entsprechend ihrem Verdünnungsschritt beschriftet, so 
                        dass sofort unterscheidbar ist, welche Flasche eine höhere und welche eine niedrigere 
                        Wirkstoffkonzentration enthält.
                        <br />
                        <br />
                        Erregerspezifische Autovaccinen werden analog dazu mithilfe von Abstrichen aus den relevanten 
                        Körperbereichen, die von den Therapeuten entnommen und in entsprechenden Behältern versendet werden, 
                        hergestellt.
                        <br />
                        <br />
                        In Deutschland werden Autovaccinen und AutoColiVaccinen derzeit (Stand Jan. 2019) ausschließlich von der Firma 
                        <a href="https://www.symbiovaccin.de/" target="_blank">SymbioVaccin GmbH</a> in Herborn hergestellt.
                        <br />
                        <br />
                        Es ist weder sinnvoll noch möglich, dass ein Patient aus eigenem Antrieb eine Stuhlprobe zur 
                        Herstellung von AutoColivaccinen einsendet, da hierzu ein Auftrag eines Therapeuten oder geschulten 
                        Beraters erforderlich ist. Der Patient/Klient erhält von diesem ein Set für eine Stuhlprobe und den 
                        vorbereiteten Auftrag, unterschreibt den Auftrag und versendet die Stuhlprobe nach Herborn. 
                        <br />
                        <br />
                        <a id="anwendung"></a>
                        <hr />
                        <h5>Anwendung von AutoColiVaccinen</h5>
                        <hr />
                        Da ich in meiner Praxis ausschließlich die Spray-Anwendung empfehle, erhalten Sie Ihre persönliche
                        AutoColiVaccine direkt zu sich nach Hause geliefert. Wenn Sie für bestimmte Indikationen, 
                        bei denen eine Injektionsanwendung erforderlich ist, bei einem anderen Therapeuten in Behandlung 
                        sind, werden die Autovaccinen an die auftraggebende Praxis versandt. Ihr Therapeut wird Sie dann 
                        informieren und zu den Injektionen einbestellen.
                        <br />
                        <br />
                        Sie erhalten Ihre AutoColiVaccine etwa 4 Wochen nach dem Versand der 
                        Stuhlprobe. Diese Zeit wird für den Herstellungsprozess benötigt und kann nicht beschleunigt werden.
                        <br />
                        <br />
                        Unter Umständen kann gleich im Anschluss an die Stuhlprobenentnahme diese Wartezeit genutzt werden, ein 
                        geeignetes Probiotikum einzunehmen, das bestimmte Laktobazillen enthält, die u.a. schon die Funktion 
                        der Tight Junctions stärken können. Bis Ihre AutoColiVaccine eingetroffen ist, hat man auf 
                        diese Weise schon eine gute &#187;Vorarbeit&#171; geleistet. Bitte tun Sie dies nur in enger 
                        Abstimmung mit Ihrem Therapeuten oder Berater, der mit Ihnen bespricht, ob die Einnahme überhaupt sinnvoll
                        und ggf. welches Probiotikum geeignet ist. Ein ungeeignetes Präparat könnte eventuell sogar kontraproduktiv wirken.
                        <br />
                        <br />
                        Die Sendung mit der AutoColiVaccine enthält i.d.R. zwei Fläschchen, die je nachdem, ob für Sie 
                        die Anwendung über die Nasen- oder über die Rachenschleimhaut oder die Haut sinnvoller ist (Ihr Therapeut oder 
                        Berater hat dies im Vorfeld mit Ihnen abgeklärt), mit einem Nasen- oder Rachensprühaufsatz 
                        versehen sind (letzterer wird auch für die Anwednung auf der Haut verwendet).
                        <br />
                        <br />
                        <i>Das Bild ganz oben auf dieser Seite zeigt je ein Fläschchen mit einem Rachensprühaufsatz (links) 
                        und einem Nasensprühaufsatz (rechts).</i>
                        <br />
                        <br />
                        <img src="<?php echo IMG_PATH; ?>autovaccinen-konzentrationen.png" alt="Konzentrationen" class="right" />
                        Die Fläschchen sind mit zwei unterschiedlichen Nummern gekennzeichnet, beispielweise 3 und 4. In der 
                        Flasche mit der höheren Nummer (in diesem Beispiel die 4) befindet sich die Lösung mit der höheren 
                        Verdünnung, d.h. es ist eine geringere Konzentration an Zellbestandteilen enthalten. In der Flasche 
                        mit der niedrigeren Nummer (im Beispiel die mit der 3) befindet sich die Lösung mit der nächst 
                        niedrigeren Verdünnung, d.h. es ist eine um das 10fach höhere Konzentration an Zellbestandteilen 
                        enthalten. 
                        <br />
                        <br />
                        <i>Das nebenstehende Bild zeigt die Systematik der ansteigenden Konzentrationen bei 
                        abnehmender Verdünnung und die zugehörigen Kennzahlen der Fläschchen.</i> 
                        <br />
                        <br />
                        Bei der Anwendung der AutoColiVaccinen wird zunächst immer eine höhere Verdünnungsstufe, also die Lösung mit einem 
                        geringeren Gehalt an abgetöteten Keimen verabreicht. Nach einem festgesetzten Zeitschema, 
                        das Ihr Therapeut mit Ihnen gemäß Ihrer Beschwerden ausgearbeitet hat, werden die Dosen von i.d.R. einer auf 
                        mehrere Dosen gesteigert. Später wird dann die nächst niedrigere Verdünnungsstufe in einer Dosis verwendet und 
                        dann auch diese Anzahl der Sprühstöße nach und nach erhöht. Auf diese Weise muss sich der Körper mit stetig steigenden Mengen der 
                        Vaccinen auseinandersetzen und kann sich so behutsam wie möglich an den Stoff gewöhnen. Aus diesem Grunde gibt es meist auch 
                        zwischen den Anwendungen einen oder mehrere anwendungsfreie Tage.
                        <br />
                        <br />
                        Besprechen Sie zunächst <b>mit Ihrem Therapeuten oder Berater</b> das genaue Vorgehen und lassen 
                        Sie sich einen genauen Plan aushändigen, an welchen Tagen (mit Datum) Sie wie viele Sprühstöße in 
                        Mund bzw. Rachen oder auf die Haut sprühen.
