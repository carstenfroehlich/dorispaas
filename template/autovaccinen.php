                        <br />
                        <br />
                        Obwohl die Therapie mit Autovaccinen bereits seit mehr als 100 Jahren erfolgreich angewendet wird, 
                        wird sie bis heute von der Wissenschaft nicht anerkannt. Es liegen auch keine für eine solche Anerkennung 
                        erforderlichen (Doppel-)Blind-Studien vor, bei denen das Verfahren an verschiedenen Patientengruppen 
                        getestet wird. Trotzdem arbeiten zahlreiche naturheilkundlich orientierte Ärzte und Therapeuten seit 
                        Jahrzehnten erfolgreich mit dieser Methode.
                        <br />
                        <br />
                        Die Idee der Autovaccinen lässt sich bis ins Jahr 1902 zurückverfolgen, als der britische Immunologe 
                        Sir Almroth Wright eine Arbeit zu diesem Thema veröffentlichte. In der Regel werden Autovaccinen eingesetzt, 
                        um <b>das Immunsystem zu stärken</b> bzw. <b>allergische Reaktionen zu mindern</b>. Grundsätzlich 
                        <b>regulieren Autovaccinen das Immunsystem</b>, d.h. sie wirken harmonisierend sowohl bei schwacher Immunleistung 
                        als auch bei überschießenden Reaktionen. Der Großteil des Immunsystems befindet sich im Darm, und die Wirkmechanismen 
                        von Autovaccinen setzen eben an genau dieser Stelle an. 
                        <br />
                        <br />
                        Die meisten Verdauungsprobleme &ndash; sei es eine 
                        <b>Dysbiose</b>, also eine entgleiste Bakterienbalance im Dickdarm oder eine (häufig daraus folgende) 
                        <b>Dünndarmfehlbesiedelung</b>, eine <b>Nahrungsmittel-Unverträglichkeit oder -Allergie</b>, ein &#187;<b>Leaky-Gut-Syndrom</b>&#171;  
                        oder aber sonstige, <b>unerklärliche Verdauungsprobleme</b>  wie Bauchschmerzen, Blähungen, Durchfälle 
                        und/oder Verstopfung &ndash; und natürlich das bis heute von vielen Ärzten leider noch vollkommen 
                        falsch bewertete <b>Reizdarm-Syndrom</b>  &ndash; werden durch eine gestörte Darmflora und eine 
                        desolate, entzündete Darmschleimhaut entweder (mit) verursacht, zumindest aber immer verstärkt.
                        <br />
                        <br />
                        Darüber hinaus haben gerade Menschen mit diesen Problemen häufig auch eine regelrechte 
                        &#187;Antibiotika-Karriere&#171; hinter sich, entweder, um die Verdauungsprobleme zu bekämpfen 
                        oder aber, weil sie aufgrund anderer Infektionen Antibiotika eingenommen haben. Häufige Folge 
                        sind in beiden Fällen gestörte Abwehrkräfte mit wiederkehrenden Infektionen, weil durch diese 
                        Medikamente unweigerlich Darmflora und Darmschleimhaut und so eben auch das Immunsystem ruiniert 
                        werden. 
                        <br />
                        <br />
                        Was liegt also näher, als ein Mittel zur Hand zu haben, mit dem man alle diese Probleme, deren 
                        Ursachen ja sehr eng zusammenhängen, gleichzeitig bekämpfen kann?
                        <br />
                        <br />
                        <b>Autovaccinen verbessern die Funktionalität der Darmschleimhaut und Darmflora.   
                        Was also eigentlich ursprünglich &#187;nur&#171; zur Stärkung des Immunsystems gedacht war, kann 
                        deshalb auch Menschen helfen, die Probleme mit der Verdauung haben, man schlägt gewissermaßen 
                        &#187;zwei Fliegen mit einer Klappe&#171;</b>. 
                        <br />
                        <br />
                        Um die Wirkmechanismen dieser alten und derzeit wieder eine Renaissance erlebenden Behandlungsmethode 
