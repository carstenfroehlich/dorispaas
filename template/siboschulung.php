                        <h5>Schulung &ndash; warum?</h5>
                        <hr>
                        Noch vor etwa 10 &ndash; 15 Jahren war die Laktose-Intoleranz auch unter den 
                        Schulmedizinern ein wenig bekanntes Thema, und die Betroffenen durchliefen oft 
                        eine Odyssee, bis der Grund für Ihre Beschwerden endlich erkannt wurde. 
                        <br />
                        <br />
                        Das hat sich im Laufe der Zeit glücklicherweise geändert. Das Wissen um weitere 
                        Nahrungsmittel-Unverträglichkeiten, aber auch die Zöliakie konnte sich danach schon 
                        schneller etablieren. Somit bekommen Betroffene heute in diesen Fällen sehr viel 
                        schneller eine qualifizierte Diagnose. 
                        <br />
                        <br />
                        Nach der ersten Behandlung fühlen sich Schulmediziner im (immer notwendigen) 
                        weiteren Verlauf dann jedoch meist nicht mehr verantwortlich 
                        und verweisen die Patienten ggf. an beratende Fachkräfte. Auch wenn Ernährungsberater, 
                        Heilpraktiker und Ganzheitliche Gesundheitsberater &ndash; sofern sie auf diese 
                        Problematik spezialisiert sind &ndash; nach der erfolgten Diagnose den Betroffenen 
                        eine sehr gute Unterstützung bieten können, bleiben die Beschwerden doch häufig nach 
                        einer eventuellen anfänglichen Besserung mehr oder weniger bestehen. Der Patient 
                        verzweifelt zunehmend, geht wieder zu Ärzten und Beratern und bekommt letztendlich 
                        nicht selten den Rat, psychologische Unterstützung in Anspruch zu nehmen.
                        <br />
                        <br />
                        In vielen Fällen liegt hier &ndash; oft neben einer oder mehreren Unverträglichkeiten 
                        &ndash; eine bakterielle Fehlbesiedelung des Dünndarms (SIBO) vor, die äußerst 
                        quälende Beschwerden verursachen kann und die auch der Fachmann teils nur mit viel 
                        Erfahrung von den Symptomen der Nahrungsmittel-Unverträglichkeiten unterscheiden kann.
                        <br />
                        <br />
                        Das Buch &#187;<a href="book-ddfb" target="_blank">Dünndarmfehlbesiedelung 
                        &ndash; erkennen, verstehen, erfolgreich behandeln</a>&#187;, das sich in erster 
                        Line an die Betroffenen selbst richtet (das durchaus aber auch eine lesenswerte 
                        Lektüre für den interessierten Fachmann darstellt), vermittelt den Lesern zwar die Kenntnisse 
                        über die Hintegründe und Zusammenhänge und vor allem auch über die erforderlichen 
                        Maßnahmen, mit denen sie selbst zur Heilung dieser Erkrankung beitragen können und müssen. 
                        Dies bedeutet aber nicht, dass die Patienten dann &#187;in Eigenregie&#171; die 
                        Dünndarmfehlbesiedelung behandeln können. Es ist immer sinnvoll, einen qualifizierten 
                        Diagnostiker und Berater für die eigene, individuelle Situation hinzuzuziehen.
                        <br />
                        <br />
                        Leider ist das Wissen über bakterielle Fehlbesiedelungen noch nicht sehr verbreitet 
                        bzw. noch nicht ausreichend vertieft, und viel zu oft werden die Patienten auf der Suche nach 
                        den Ursachen durch eine umfangreiche, u.U. teure, vor allem aber in der Regel sehr belastende 
                        Diagnostik geschickt, die durchaus nicht immer erforderlich ist. Eine Weiterbildung 
                        aller Fachkräfte in diagnostischen, behandelnden und beratenden Berufen würde 
                        allen Beteiligten helfen: Patienten würden unnötige Untersuchungen erspart, Kassenärzte 
                        könnten sogar ihr Budget schonen und &ndash; vor allem &ndash; könnte eine verlässlichere 
                        Diagnose und damit auch eine wirksamere Behandlung den Patienten einen langen Leidensweg ersparen.
                        <br />
                        <br />
                        Aus diesem Grunde biete ich allen mit dieser Thematik befassten Fachkräften individuell
                        gestaltete Schulungen an, um ihre Kenntnisse in diesem Bereich zu vertiefen und 
                        ihren Patienten/Klienten eine optimale Hilfe geben zu können.
