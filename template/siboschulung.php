                        <h5>Mögliche Schulungsthemen</h5>
                        <hr>
                        <b>Verdauung</b>
                        <br />
                        Mund, Magen, Verdauungsdrüsen, Dünn- und Dickdarm, Ileozökalklappe, 
                        Darmbarriere, Darmschleimhaut und Darmbakterien, Bauchhirn und Darm-Hirn-Achse, 
                        Magen-Darm-Reflex, Reinigungs-Wellenbewegung
                        <br />
                        <br />
                        <b>Darmbakterien und ihre Aufgaben</b>
                        <br />
                        Bakterienarten in Dünn- und Dickdarm, weitere mögliche Mikroorganismen
                        <br />
                        Aufgaben: Barrierefunktion, Immunsystem, Ernährung der Darmschleimhautzellen, 
                        Energiereserven, Vitamin-Synthese, Regulierung des Stuhlgangs, Beeinflussung der Psyche
                        <br />
                        <br />
                        <b>Was ist Dünndarmfehlbesiedelung</b>
                        <br />
                        Definition, allgemeine und spezifische Ursachen der Dünndarmfehlbesiedelung, mögliche 
                        Zusammenhänge mit anderen Erkrankungen, typische Beschwerden bei Dünndarmfehlbesiedelung, 
                        typische Beschwerden bei Dysbiosen, Abgrenzung anhand der Symptome
                        <br />
                        <br />
                        <b>Diagnose</b>
                        <br />
                        Ernährungs-und Symptomtagebuch, Wasserstoff-Atemtest (Test mit Messgerät, Test 
                        zum Einsenden, Vorbereitung und Information des Patienten, Testsubstanz, Testintervalle, 
                        Bewertung), Stuhldiagnostik (welche Parameter), Differenzialdiagnostik
                        <br />
                        <br />
                        <b>Behandlung</b>
                        <br />
                        Drei Phasen der Behandlung: Antibiose (allopathische oder natürliche Antibiotika), 
                        Sanierung der Darmschleimhaut (warum, wie), Sanierung der Darmflora (warum, wie), 
                        Präparate zur Behandlung
                        <br />
                        <br />
                        <b>Psyche</b>
                        <br />
                        Auslöser? Verstärker? Auf jeden Fall wichtig!
                        <br />
                        <br />
                        <b>Behandlungsbegleitende Maßnahmen und Gesunderhaltung der Darmflora</b>
                        <br />
                        Ernährung, Bewegung, Stressmanagement, Sonstiges, Eigenverantwortung des Patienten
