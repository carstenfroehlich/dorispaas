                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=autovaccinen" target="_blank">Schwerpunktthema: &#187;Autovaccinen &ndash; auch als wirksame Hilfe bei Verdauungsproblemen&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Darmgesundheit/Autovaccinen)</i>
                        <br />
                        Haben Sie schon einmal von den so genannten &#187;Autovaccinen&#171; geh&ouml;rt? Nein? 
                        Die Idee der Autovaccinen l&auml;sst sich bereits &uuml;ber Hundert Jahre zur&uuml;ckverfolgen, 
                        und zahlreiche naturheilkundlich orientierte &Auml;rzte und Therapeuten arbeiten seit 
                        Jahrzehnten erfolgreich mit dieser Methode. In der Regel werden Autovaccinen eingesetzt, 
                        um das Immunsystem zu st&auml;rken bzw. allergische Reaktionen zu mindern, denn sie wirken 
                        harmonisierend bei schwacher Immunleistung und bei &uuml;berschie&#223;enden Reaktionen. 
                        Der Gro&#223;teil des Immunsystems befindet sich im Darm, und die Wirkmechanismen von Autovaccinen 
                        setzen eben an genau dieser Stelle an. Die meisten Verdauungsprobleme &ndash; sei es eine Dysbiose 
                        im Dickdarm oder eine (h&auml;ufig daraus folgende) D&uuml;nndarmfehlbesiedelung, eine 
                        Nahrungsmittel-Unvertr&auml;glichkeit oder -Allergie, ein &#187;Leaky-Gut-Syndrom&#171; oder 
                        aber sonstige, unerkl&auml;rliche Verdauungsprobleme wie Bauchschmerzen, Bl&auml;hungen, Durchf&auml;lle 
                        und/oder Verstopfung &ndash; und nat&uuml;rlich das bis heute von vielen &Auml;rzten leider noch 
                        vollkommen falsch bewertete Reizdarm-Syndrom &ndash; werden durch eine gest&ouml;rte Darmflora und eine 
                        desolate, entz&uuml;ndete Darmschleimhaut entweder (mit) verursacht, zumindest aber immer verst&auml;rkt. 
                        Autovaccinen verbessern die Funktionalit&auml;t der Darmschleimhaut und Darmflora. Was also eigentlich 
                        urspr&uuml;nglich &#187;nur&#171; zur St&auml;rkung des Immunsystems gedacht war, kann deshalb auch Menschen 
                        helfen, die Probleme mit der Verdauung haben.
