                        <h5>Buchbeschreibung:</h5>
                        <hr />
                        <p><span style="font-weight:bold">Dünndarmfehlbesiedelung</span>
                        <br />
                        erkennen, verstehen, erfolgreich behandeln
                        </p>
                        <br />
                        Sie leiden immer wieder unter Verdauungsproblemen wie Bauchschmerzen, Krämpfen, 
                        einem aufgeblähten Bauch, Durchfällen oder Verstopfung, Völlegefühl und Sodbrennen? 
                        Dann besteht die Möglichkeit, dass eine bakterielle Fehlbesiedelung des Dünndarms 
                        vorliegt. 
                        <br />
                        <br />
                        Die Dünndarmfehlbesiedelung ist wahrscheinlich derzeit eine der am häufigsten 
                        verkannte und auch unterschätzte Erkrankung des Verdauungssystems. Und weil die  
                        quälenden Beschwerden kaum mit dem Verzehr bestimmter Lebensmittel in 
                        Verbindung gebracht werden können, ist sie so schwer &#187;zu packen&#171;. Dass 
                        die Dünndarmfehlbesiedelung oft in enger Beziehung mit Nahrungsmittel-Unverträglichkeiten 
                        und auch mit der bisher als &#187;Reizdarm-Syndrom&#171; bezeichneten Problematik 
                        steht, ist mittlerweile zwar nachgewiesen, aber leider noch nicht im allgemeinen 
                        medizinischen Bewusstsein verankert. 
                        <br />
                        <br />
                        Wenn man einmal die Zusammenhänge erkannt und verstanden hat, wie sich die 
                        langanhaltenden und belastenden Beschwerden begründen, ist es möglich, eine 
                        Dünndarmfehlbesiedelung zu erkennen und dauerhaft zu beseitigen.
                        <br />
                        <br />
                        Vor einer erfolgreichen Behandlung steht immer eine korrekte Diagnose &ndash; und
                        diese sollte auf der einen Seite alle erforderlichen Maßnahmen umfassen, auf 
                        der anderen Seite aber belastende und oft auch überflüssige und vielleicht 
                        sogar kostenträchtige Untersuchungen vermeiden. 
                        <br />
                        <br />
                        Eine zielführende Therapie 
                        erfolgt dann in mehreren Phasen, wobei verschiedene Mittel und Möglichkeiten 
                        zur Verfügung stehen. Auch die gleichzeitig erforderlichen behandlungs-
                        begleitenden Maßnahmen und allgemeinen Regeln zur Gesunderhaltung der 
                        Darmflora werden thematisiert. Nur die konsequente Einhaltung aller notwendigen
                        Schritte kann zu einem dauerhaften Erfolg führen und die größtmögliche
                        Sicherheit vor Rückfällen gewährleisten.
                        <br />
                        <br />
                        Sie lernen alle möglichen Ursachen, Diagnosemethoden und 
                        Behandlungsalternativen kennen und werden das Zusammenspiel aller 
                        Therapiekomponenten verstehen. Als Betroffene können Sie letztendlich durch Ihr 
                        eigenes Verhalten einen dauerhaften Behandlungserfolg sicherstellen. 
                        Und natürlich erhalten Sie die Möglichkeit, gemeinsam mit Ihren Ärzten und Beratern 
                        auf Augenhöhe zu sprechen und darüber entscheiden zu können, welche der 
                        Behandlungsalternativen für Sie die geeignetste ist.
                        <br />
                        <br />
                        Dieses Buch soll in erster Linie die Betroffenen 
                        selbst ansprechen: Jeder, der vermutet, an einer Dünndarmfehlbesiedelung zu leiden,
                        sollte dieses Buch lesen, ebenso wenn Nahrungsmittel-Unverträglichkeiten vorliegen 
                        und die Diät, bei der die entsprechenden Lebensmittel gemieden werden, nicht zu 
                        der gewünschten Beschwerdefreiheit führt oder aber wenn immer wieder auftretende 
                        Reizdarm-Probleme quälen. Der Text ist verständlich geschrieben, Fachausdrücke 
                        werden weitestgehend vermieden, trotzdem jedoch erwähnt und erklärt, damit diese bei einem 
                        Arztgespräch verstanden werden können.
                        <br />
                        <br />
                        Der sorgfältig recherchierte, umfassende Titel sollte aber auch in keiner ärztlichen 
                        Praxis und auf keinem Schreibtisch von Heilpraktikern und Ernährungs- und 
                        Gesundheitsberatern fehlen.
