                        <a href="http://www.dorispaas.de/index.php?page=blog#blog-2018-02-25" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-02-schoellkraut.png" alt="" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=blog#blog-2018-02-25" target="_blank">Ein wichtiger Hinweis zum Pr&auml;parat &#187;Iberogast&reg;&#171;</a></b>
                        <br />
                        Im Zusammenhang mit den oben erw&auml;hnten Verbraucherrechten m&ouml;chte ich 
                        auf ein Pr&auml;parat &ndash; das Iberogast&reg; &ndash; hinweisen, das in bestimmten 
                        F&auml;llen gerne von vielen Menschen bei Magen-/Darmproblemen verwendet wird. 
                        Dieses Mittel enth&auml;lt u.a. 
                        Sch&ouml;llkraut, das schon seit einiger Zeit im Verdacht steht, bei 
                        h&ouml;herer Dosierung und l&auml;ngerer Einnahmedauer Lebersch&auml;den verursachen 
                        zu k&ouml;nnen. Und &ndash; wen wundert es &ndash; dieser Verdacht wird
                        vom Hersteller Bayer in Leverkusen nicht nur nicht an die gro&#223;e Glocke geh&auml;ngt, sondern 
                        auch bis zum heutigen Tage im Beipackzettel verschwiegen. Aus diesem Grunde habe ich einen Beitrag zu 
                        diesem Thema in meinem Blog geschrieben und m&ouml;chte Ihnen empfehlen, sich diesen 
                        aufmerksam durchzulesen. Auch wenn ich mit meinen Beratungen grunds&auml;tzlich 
                        versuche, Probleme urs&auml;chlich und ganzheitlich zu betrachten und zu verbessern, 
                        kann es manchmal hilfreich sein, zun&auml;chst Symptome zu lindern und dies 
                        gelegentlich auch mit geeigneten Mitteln zu unterst&uuml;tzen. Iberogast&reg;
                        ist trotz des Gehalts an Sch&ouml;llkraut nicht grunds&auml;tzlich schlecht, aber 
                        es ist wichtig zu wissen, dass es sich hier nur um ein Akutmittel f&uuml;r eng umrissene 
                        Anwendungsgebiete handelt und keineswegs um ein Pr&auml;parat, das &uuml;ber l&auml;ngere 
                        Zeitr&auml;ume eingenommen werden kann oder soll. Schade, dass der Hersteller den 
                        Verbraucher hier nicht ausreichend informiert! 
                        
                        <br />
                        <br />
                        <hr>
                        <br />
                        Liebe Leserinnen und Leser, es ist schwierig, aus der Flut von Informationen, die 
                        uns &uuml;ber die verschiedenen Medien erreichen, die f&uuml;r uns wichtigen und &ndash; 
                        vor allem &ndash; die &#187;richtigen&#171; herauszufiltern. Was entspricht wirklich 
                        den Tatsachen und wann werden wir im wahrsten Sinne des Wortes an der Nase herumgef&uuml;hrt?
                        Wie oben erw&auml;hnt, scheint es noch ein sehr weiter Weg zu sein, bis es ein wirklich 
                        verl&auml;ssliches Verbraucherschutzgesetz gibt, das seinen Namen auch verdient.
                        Ich bitte Sie herzlich, mit allen Ihnen zur Verf&uuml;gung stehenden Mitteln daran 
                        mitzuarbeiten, dass wir uns irgendwann einmal darauf verlassen k&ouml;nnen, von 
                        den Herstellern und Produzenten &uuml;ber die Produkte umfassend informiert zu werden.
                        Der derzeit wirksamste Weg scheint mir zu sein, dass wir &#187;mit den F&uuml;&#223;en 
                        abstimmen&#171; &ndash; sprich, dass wir allein schon im eigenen Interesse keine Produkte kaufen, 
                        deren Auszeichnung unbefriedigend ist und nur solche Waren ausw&auml;hlen, die ehrlich 
                        deklariert sind. Ich wei&#223;, das ist nicht einfach und zumindest am Anfang 
                        etwas umst&auml;ndlich, aber ich hoffe, dass steter Tropfen den Stein h&ouml;hlt.
