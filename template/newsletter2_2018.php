                        <h5>Ausgabe 39 (März 2018)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="<?php echo IMG_PATH; ?>nl-2018-02-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 20px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        <br />
                        am 15. M&auml;rz findet weltweit der &#187;Internationale Weltverbrauchertag&#171; 
                        statt. Dies ist ein Aktionstag, den wir dem ehemaligen amerikanischen Pr&auml;sidenten John 
                        F. Kennedey verdanken, der am 13.3.1962, also vor sage und schreibe 56 Jahren, 
                        vor dem Kongress drei auch heute noch 
                        brandaktuelle Grundrechte f&uuml;r Verbraucher proklamierte. Dies sind erstens das 
                        Recht auf <b>Schutz vor betr&uuml;gerischer und irref&uuml;hrender Kennzeichnung von 
                        Waren oder Werbung f&uuml;r Produkte</b>, zweitens das Recht, <b>vor unwirksamen oder sogar 
                        gef&auml;hrlichen Medikamenten gesch&uuml;tzt zu werden</b> und drittens das Recht, 
                        unsere <b>Produkte aus einer breiten Palette mit marktgerechten Preisen ausw&auml;hlen 
                        zu k&ouml;nnen</b>. Unsere deutsche Regierung mit den Ministern f&uuml;r Verbraucherschutz, 
                        Landwirtschaft und Gesundheit haben mich mit ihren Entscheidungen bisher leider 
                        (noch) nicht davon &uuml;berzeugt, dass wir uns durch diese sehr sinnvollen 
                        Grunds&auml;tze gesch&uuml;tzt sehen k&ouml;nnten. Aber auch die Amerikaner und 
                        eigentlich alle anderen L&auml;nder der Welt haben in dieser Richtung noch einen 
                        weiten Weg vor sich. Umso wichtiger ist es, dass wir bei bzw. vor allen unseren 
                        Entscheidungen f&uuml;r oder gegen einen Kauf oder Verbrauch <b>die Augen aufmerksam 
                        offen halten</b>, um nicht Gefahr zu laufen, dass unsere Gesundheit 
                        ernsthaften Schaden nehmen kann. Zwei Beispiele (unter leider viel zu vielen) habe 
                        ich in den beiden Beitr&auml;gen dieses Newsletters f&uuml;r Sie zusammengestellt. 
                        Solange keine ausreichenden gesetzlichen Regelungen 
                        zum wirksamen Schutz der Verbraucher geschaffen werden, m&uuml;ssen wir die Hersteller 
                        mit unseren Kaufentscheidungen (be)zwingen und sch&auml;dliche Produkte so weit 
                        wie m&ouml;glich in den Regalen liegen lassen oder zumindest durch st&auml;ndiges, 
                        hartn&auml;ckiges Einfordern von unbedenklichen Lebensmitteln, Waren und Leistungen unsere 
                        Bed&uuml;rfnisse im Sinne der &uuml;ber 50 Jahre alten Verbraucherrechte lauthals 
                        kundtun &ndash; und zwar nicht nur am Internationalen Weltverbrauchertag, sondern 
                        an jedem Tag des Jahres.

