                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=trinkwasser" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-02-wasserfilter.png" alt="Bild Fasten" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=trinkwasser" target="_blank">Schwerpunktthema &#187;Chlor im Trinkwasser&#171;</a></b>
                        <br />
                        Unser Trinkwasser ist nicht nur unser wichtigstes, sondern auch eines der am besten 
                        kontrollierten Lebensmittel. Obwohl die Qualit&auml;t durch die Trinkwasserverordnung 
                        gesetzlich garantiert sein sollte, hei&#223;t dies aber nicht, dass es zwangsl&auml;ufig 
                        auch immer f&ouml;rderlich f&uuml;r unsere Gesundheit ist. Es kann durch 
                        verschiedene Umst&auml;nde nicht nur Schadstoffe wie u.a. Nitrat oder Schwermetalle 
                        enthalten, sondern auch mit Keimen belastet sein. Die Wasserwerke m&uuml;ssen aber aufgrund 
                        der gesetzlichen Vorschriften unbedenkliches Trinkwasser liefern und da eine 
                        biologische Entkeimung teuer ist, greift man dort lieber zur chemischen Keule 
                        in Form von Chlor. 
                        <br />
                        <br />
                        Auch in unserer Darmflora befinden sich Keime &ndash; teils sch&auml;dliche, 
                        in einer gesunden Mikrobiota aber wesentlich mehr n&uuml;tzliche Keime. Diese haben 
                        vielf&auml;ltige Aufgaben wie vor allem die St&auml;rkung des Immunsystems. Die 
                        Darmkeime unterst&uuml;tzen uns aber auch bei der Verarbeitung eigentlich unverdaulicher 
                        Stoffe oder produzieren bestimmte Vitamine, die unser eigener K&ouml;rper nicht 
                        herstellen kann. Ohne unsere Darmflora h&auml;tten wir keine normale Verdauung, 
                        ja wir w&auml;ren &uuml;berhaupt nicht lebensf&auml;hig! Wenn wir nun mit dem 
                        Trinkwasser gr&ouml;&#223;ere Mengen Chlor aufnehmen, wirkt sich dies nat&uuml;rlich 
                        auch auf die Zusammensetzung unserer Darmflora aus. Es findet eine dauerhafte 
                        Belastung der Keimbalance durch das Trinken chlorhaltigen Wassers statt, und im 
                        Laufe der Zeit verschlechtert sich die Qualit&auml;t der f&uuml;r unsere Gesundheit 
                        so wichtigen Mikrobiota immer mehr. 
