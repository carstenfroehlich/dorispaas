                        <h3>Stärkung des Immunsystems</h3>
                        Erkrankungen des Verdauungssystems können sich u.a. auch gravierend auf unser 
                        Immunsystem und damit auf unsere Gesundheit insgesamt auswirken. Und nat&uuml;rlich 
                        kann auch umgekehrt ein robustes Immunsystem günstige Auswirkungen auf das 
                        Verdauungssystem haben. Deshalb ist es wichtig, das Immunsystem kennenzulernen 
                        und uns diese Zusammenhänge klar zu machen. Gerade auch bei Problemen mit dem 
                        Verdauungssystem können wir selbst viel dafür tun, unser Immunsystem zu 
                        st&auml;rken und gute Abwehrkräfte gegen Krankheiten zu entwickeln und damit 
                        letztendlich dazu beitragen, dass die Verdauungsprobleme minimiert werden.
                        <br />
