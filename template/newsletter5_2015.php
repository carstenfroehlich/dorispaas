                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-immun" target="_blank">Ganzheitliche St&auml;rkung des Immunsystems</a></b>
                        <br />
                        <br />
                        (Nicht nur) f&uuml;r Menschen, die Probleme mit ihrem Verdauungssystem haben, ist 
                        es ganz wichtig zu bedenken: Auch Erkrankungen des Verdauungssystems k&ouml;nnen 
                        sich gravierend auf unser Immunsystem und damit auf unsere Gesundheit insgesamt 
                        auswirken. Und nat&uuml;rlich kann auch umgekehrt ein robustes Immunsystem g&uuml;nstige 
                        Auswirkungen auf das Verdauungssystem haben. Deshalb ist es wichtig, das Immunsystem 
                        kennenzulernen und uns diese Zusammenh&auml;nge klar zu machen. Gerade auch bei 
                        Problemen mit dem Verdauungssystem k&ouml;nnen wir selbst viel daf&uuml;r tun, 
                        unser Immunsystem zu st&auml;rken und gute Abwehrkr&auml;fte gegen Krankheiten zu 
                        entwickeln. So k&ouml;nnen wir viel dazu beitragen, dass die Verdauungsprobleme 
                        minimiert werden und K&ouml;rper, Seele und Geist ins Gleichgewicht kommen. 
