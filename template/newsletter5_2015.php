                        Besonders wirksam k&ouml;nnen Sie die M&ouml;glichkeiten zur Ganzheitlichen St&auml;rkung 
                        des Immunsystems unterst&uuml;tzen mit verschiedenen Ma&#223;nahmen zur aktiven 
                        Entspannung. Das h&ouml;rt sich jetzt f&uuml;r Sie paradox an &ndash; aktiv und 
                        entspannen? Nein, das ist es keineswegs, denn ein sinnvolles Stressmanagement zur 
                        Entspannung in stressigen Zeiten braucht schon etwas &Uuml;berlegung und Planung.
                        Im Beitrag &#187;Entpannung&#171; finden Sie zahlreiche Tipps zu all den f&uuml;r 
                        eine aktive Entspannung relevanten Faktoren.
