                        Liebe Leserin, lieber Leser.
                        <br />
                        <br />
                        Schade! Der Sommer ist nun schon fast vorbei &ndash; nur noch ab und an lugt die 
                        Sonne zwischen den Wolken hervor. Meistens ist es tr&uuml;be und grau oder es 
                        regnet sogar. Umso wichtiger ist es nun f&uuml;r uns alle, auch jetzt auf unsere Gesundheit zu achten
                        und unser Immunsystem zu st&auml;rken. Hier haben wir viele M&ouml;glichkeiten zur 
                        Verf&uuml;gung, und die meisten kosten nichts. Nur ein wenig nachdenken muss man, 
                        um Krankheiten vorzubeugen. Und auch wenn es Ihnen vielleicht 
                        widersinnig erscheint, kurz nach der Urlaubszeit auf das Thema &#187;Entspannung&#171; 
                        zu sprechen zu kommen, greife ich es ganz bewusst auf, denn viele Menschen kommen 
                        aus Ihrem Urlaub eben leider nicht wirklich erholt zur&uuml;ck. Sie haben zwar 
                        viele sch&ouml;ne Dinge erlebt, aber so richtig gut f&uuml;hlen sie sich nicht. Deshalb 
                        ist jetzt genau der richtige Augenblick, noch einmal genauer auf dieses Thema zu schauen. 
