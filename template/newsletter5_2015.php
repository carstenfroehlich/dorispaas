                        Allen, die ihren Urlaub noch vor sich haben und noch kein Reiseziel festgelegt haben, 
                        kann ich Polen als Reiseland nur w&auml;rmstens empfehlen. Grunds&auml;tzlich ist 
                        Polen ein wundersch&ouml;nes Land. Alles ist auff&auml;llig sauber, nirgendwo liegt 
                        weggeworfener Abfall. Auf dem Land sind alle Felder bestellt und bewirtschaftet, 
                        nichts liegt brach wie bei uns. Die Menschen sind sehr freundlich, viele sprechen 
                        Deutsch, fast alle Englisch, so dass man keine Probleme hat, sich zu verst&auml;ndigen. 
                        Die Speisekarten sind durchgehend zweisprachig (polnisch und englisch), so dass 
                        man trotz der (f&uuml;r deutsche Augen und Ohren) schwierigen Landessprache auch 
                        beim Bestellen im Restaurant nicht an Sprachschwierigkeiten scheitert.<br />
