                        <h5>Ziele und Zweck dieser Website:</h5>
                        <hr />
                        Diese Website soll Sie über alle Zusammenhänge rund um 
                        Nahrungsmittel-Unverträglichkeiten, das Reizdarm-Syndrom, 
                        gesunde Ernährung und gesunde Verdauung in ganzheitlichem 
                        Zusammenhang informieren. Darüber hinaus finden Sie Informationen 
                        zu den von mir verfassten Büchern, die ebenfalls diese Themen 
                        zum Inhalt haben. Die Website richtet sich vor allem an Betroffene, 
                        die sich vor oder zusätzlich zu ärztlichen Ratschlägen 
                        informieren wollen, aber auch an deren Angehörige und Freunde. 
                        Herzlich eingeladen sind auch medizinische Fachleute wie Ärzte, 
                        Fach- und Pflegepersonal in Senioreneinrichtungen, aber auch an 
                        Heilpraktiker, Ernährungs- und Gesundheitsberater, die Hinweise 
                        in Ergänzung zu den eigenen Fachgebieten sammeln möchten, 
                        ebenso Schüler und Studenten, die für die entsprechenden 
                        Gebiete recherchieren.<br />
                        Die Inhalte dieser Website basieren gro&#223;teilig auf eigenen 
                        Erfahrungen, ergänzende Inhalte sind so sorgfältig wie nur 
                        möglich recherchiert. Sollten Sie Fehler entdecken oder aber 
                        ergänzende Hinweise geben wollen, bin ich dankbar, wenn 
                        Sie mir eine <a href="email-anfrage" target="_blank">eMail</a> senden.
