                    <br />
                    Ein Köperpflegeöl ist ein Öl, ist ein Öl, ist ein Öl &ndash; oder nicht? Leider eben nicht, denn selbst Bioprodukte gleichen eher 
                    einem Chemiebaukasten, als einem reinen Öl. Die Herstellung eines Öls zur Körperpflege und/oder Massage ist denkbar einfach und 
                    mit einer oder maximal zwei Zutaten in wenigen Minuten erledigt. Als Grundlage dient ein pflanzliches Öl, beispielsweise Mandel- 
                    oder Reisöl. Da das Reisöl etwas dünnflüssiger ist, bevorzuge ich dieses für die tägliche Körperpflege. Das Mandelöl eignet sich 
                    insbesondere als Massageöl, da es nicht so schnell von der Haut aufgenommen wird, wie das Reisöl. Wer es mag, kann sein Körperöl 
                    mit einigen Tropfen ätherischem Öl &#187;parfümieren&#171;.  
                    <br />
                    <br />
                    <br />
                    <b>Zutaten:</b>
                    <br />
                    <b>&#149; </b> 100ml pflanzliches Öl (z.B. Mandel- oder Reisöl)
                    <br />
                    <b>&#149; </b> optional: 25-50 Tropfen ätherisches Öl (z.B. Zitronenöl)
                    <br />
                    <br />
                    <b>Utensilien:</b>
                    <br />
                    <b>&#149; </b> Flasche (Fassungsvermögen etwa 100ml)
                    <br />
                    <br />
                    <b>Herstellung:</b>
                    <br />
                    Das pflanzliche Öl am besten zunächst ohne Zugabe eines ätherischen Öls verwenden. Insbesondere bei einer Veranlagung zu Kontaktallergien  
                    das ätherische Öl nur vorsichtig zunächst an einer sehr kleinen Menge Pflanzenöl austesten, um den teuren Grundstoff nicht unbrauchbar 
                    zu machen. Auf jeden Fall aber sollten Sie ätherische Öle grundsätzlich nicht zu hoch dosieren und keinesfalls in reiner Form auf der Haut 
                    verwenden, da diese konzentriert immer agressiv auf die Haut wirken.
