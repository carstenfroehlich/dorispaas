                    <h5>Körper- und Massageöl</h5> 
                    <hr />
                    <div class="oneline">
                        <div class="left" style="width: 148px">
                        <img src="<?php echo IMG_PATH; ?>koerperoel.png" alt="Körperöl" class="inline" />
