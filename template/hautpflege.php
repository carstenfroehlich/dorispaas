                    <br />
                    Selbst in Fettstiften zur Lippenpflege sind mir in allen Sorten, die ich in den vergangenen Jahren ausprobiert habe, viel zu viele &ndash; und 
                    für mich unberechenbare &ndash; Inhaltsstoffe enthalten. Selbst bei den &#187;ökologischen&#171; Produkten aus dem Bioladen oder Refomhaus wiesen die 
                    Zutatenlisten mindestens 15 Inhaltsstoffe aus! Weder die zugefügten angeblich glättenden, heilenden und geschmacklichen Zutaten sind in meinen 
                    Augen erforderlich, geschweige denn etwa Farb- oder Konservierungsstoffe. Reines Fett muss nicht konserviert werden, denn in der Zeit, die bei 
                    mir ein Fettstift reicht, verdirbt dieses nicht. Hier ein Rezept für einen Lippenpflegestift aus drei Zutaten:
                    <br />
                    <br />
                    <br />
                    <b>Zutaten:</b>
                    <br />
                    <b>&#149; </b> Kokosöl
                    <br />
                    <b>&#149; </b> gereinigtes Bienenwachs
                    <br />
                    <b>&#149; </b> Sheabutter
                    <br />
                    <br />
                    <b>Utensilien:</b>
                    <br />
                    <b>&#149; </b> Feinwaage mit 0,1g Teilbereichen                   
                    <br />
                    <b>&#149; </b> 1 kleiner Glas-Messbecher (Fassungsvermögen ca. 50ml)
                    <br />
                    <b>&#149; </b> Eierlöffel                   
                    <br />
                    <b>&#149; </b> 1 alte Hülle eines leeren Pflegestifts oder eine neue gekaufte Hülle                   
                    <br />
                    <br />
                    <b>Herstellung:</b>
                    <br />
                    <b>&#149; </b> 2,3g Kokosöl und
                    <br />                   
                    <b>&#149; </b> 2,5g Bienenwachs
                    <br />
