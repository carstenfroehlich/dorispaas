                    <h5>Palmölfreie Hautcreme mit Aloe Vera</h5> 
                    <hr />
                    <div class="oneline">
                        <div class="left" style="width: 148px">
                        <img src="<?php echo IMG_PATH; ?>blog-aloe.png" alt="Aoe Vera" class="inline" />
                    </div>
                    </div>
                    Neben dem Austüfteln des Rezepts musste ich die ultimative Herstellung dieser Creme von längerer Hand planen, denn einer der 
                    Haupt-Inhaltsstoffe ist das Gel der Aloe Vera barbadensis. Das Gel spendet der Haut Feuchtigkeit und glättet sie. 
                    Da ich diese Zutat nicht als gebrauchsfertige Zubereitung kaufen will, weil hier dann  auf jeden Fall Konservierungsstoffe 
                    enthalten sein müssen (und ich diese  &ndash; wie z.B. Benzoesäure &ndash; nicht vertrage), habe ich mir die 
                    Pflanzen besorgt und im Sommer in meinem Garten und im Winter in einem geschützten Innenraum groß werden 
                    lassen. Nach zwei Jahren war es dann soweit: ich konnte die ersten Blätter ernten. Es ist übrigens auch möglich und 
                    eine durchaus ebenfalls empfehlenswerte Alternative, für die ersten Versuche über das Internet bei verschiedenen Händlern
                    (insbesondere aus Spanien) die ganzen Blätter im Internet zu bestellen. Es gibt sie bei entsprechender Suche sogar als Bioware. 
                    Zeitweilig habe ich die Aloe Vera-Blätter sogar bei uns im Bioladen gesehen. In dieser Form ist das enthaltene Gel natürlich 
                    nicht konserviert. Für die dauerhafte Herstellung lohnt sich aber auf jeden Fall die Eigenzucht.
                    <br />
                    <br />
                    <b>Ein wichtiger Hinweis:</b> Das Gel der Aloe Vera enthält neben Glukose, Mannose, Galaktose und Xylose, Vitaminen und 
                    Mineralien auch Salicylsäure. Es wird zum Einnehmen in vielerlei Darreichungsformen angeboten und als &#187;Superfood&#171; 
                    mit zahlreichen, angeblich gesundheitfördernden Eigenschaften beworben. Gerade bei Nahrungsmittel-Unverträglichkeiten und 
                    Vedauungsproblemen würde ich davon abraten, eines der meist mit zahlreichen anderen Zutaten verbrämten industriellen Produkte 
                    einzunehmen, da die Wirkungen unkalkulierbar sind. Zusätzlich kann nicht ausgeschlossen werden, dass Bestandteile des stark 
                    abführenden Aloe Vera Safts (auch Aloe Latex genannt) aus den äußeren Blattschichten das Gel verunreinigen und zu weiteren 
                    unerwünschten Nebenwirkungen führen.  
                    <br />
                    <br />
                    In Bezug auf die Emulgatoren habe ich sehr viel herumprobiert, bis ich die (für mich) optimale Mischung herausgefunden hatte. 
                    Emulgatoren sind in der Creme erforderlich, um die fettigen und wässrigen Substanzen dauerhaft zu verbinden. Zunächst hatte ich
                    Lamecreme verwendet, bis ich zu meinem gr0ßen Ärger festgestellt hatte, dass dieser Emulgator, der an sich eine tolle Creme erzeugte,
                    Palmöl enthält. Palmöl ist aber für mich ein &#187;No-Go&#171; (lesen Sie hierzu bitte auch den entsprechenden Beitrag in meinem 
                    <a href="blog#blog-2019-08-16" target="_blank">Blog</a>). Nun testete ich einige andere Emulgatoren und auch einige Kombinationen,
                    bis ich letztendlich zu der im folgenden Rezept angegebenen Mischung aus Montanov 68 und Fluidlecithin Super HT gelangte. Mit dieser 
                    Mischung erhöht sich zwar die Anzahl der Inhaltsstoffe, aber es ergibt sich eine wunderbare Konsistenz. Für den Anfänger ist es durchaus
                    möglich, nur Manotov 68 zu verwenden, diese Creme ist aber fester und &#187;schwerer&#171;. Falls Sie sich für diese Variante entschließen, 
                    verwenden Sie 2,2g Montanov 68.
                    <br />
                    <br />
                    <b>Zutaten:</b>
                    <br />
                    <b>&#149; </b> 30g Aloe Vera Gel
                    <br />
                    <b>&#149; </b> 8g Mandelöl
                    <br />
                    <b>&#149; </b> 0,4g Fluidlecithin Super HT
                    <br />
                    <b>&#149; </b> 2,0g Montanov 68 
                    <br />
                    <b>&#149; </b> 3,5g Sheabutter 
                    <br />
                    <br />
                    und optional:
                    <br />
                    <b>&#149; </b> 5 &ndash; 10 Tropfen natürliches Vitamin E (Antioxidans, entzündungshemmend)
                    <br />
                    <b>&#149; </b> 5 &ndash; 10 Tropfen ätherisches Öl (zur Verbesserung des Dufts, z.B. Zitrone)
                    <br />
                    <b>&#149; </b> 5 &ndash; 10 Tropfen Biogard 221 (natürlicher Konservierungsstoff)
                    <br />
                    <br />
                    <b>Utensilien:</b>
                    <br />
                    <b>&#149; </b> Passierstab zum Zerkleinern des Aloe-Gels                   
                    <br />
                    <b>&#149; </b> Eiswürfelbehälter zum portionsgerechten Einfrieren der Aloe                   
                    <br />
                    <b>&#149; </b> Feinwaage mit 0,1g Teilbereichen                   
                    <br />
                    <b>&#149; </b> 1 kleiner Glas-Messbecher (Fassungsvermögen ca. 50ml)                   
                    <br />
                    <b>&#149; </b> 1 großer Glas-Messbecher (Fassungsvermögen ca. 100 &ndash; 150ml)                   
                    <br />
                    <b>&#149; </b> Milchaufschäumer                   
                    <br />
                    <b>&#149; </b> Eierlöffel                   
                    <br />
                    <b>&#149; </b> geeigneter, verschließbarer Tiegel                   
                    <br />
                    <br />
                    <b>Zubereitung des Aloe Vera-Gels (reicht für viele Creme-Portionen):</b>
                    <br />
                    Ein oder zwei große Aloe Vera-Blätter werden vorsichtig von der Pflanze geschnitten und gründlich gewaschen.
                    Dann die zackigen Ränder längs der Blattkanten abschneiden und die Blätter quer in etwa 1 &ndash; 2 cm breite Scheiben schneiden.
                    Nun von den Scheiben mit einem scharfen Küchenmesser die grüne Schale sorgfältig und komplett von dem Gelkern 
                    schneiden (das ist eine sehr glibberige Angelegenheit) und das Gel in ein hohes Rührgefäß geben. Mit einem Passierstab 
                    gründlich verflüssigen (wenn noch kleinste Stückchen in der Flüssigkeit bleiben, werden einem diese dann nach 
                    dem Eincremen im Gesicht kleben &ndash; das sieht nicht wirklich gut aus. Sie lassen sich aber nach einem Blick in den  
                    Spiegel mit einem Tuch leicht entfernen). Bitte sehr sauber arbeiten und frische Lappen und Handtücher
                    benutzen, um möglichst wenige Keime in diese Zutat zu bringen.
                    <br />
                    <br />
                    Das Rührgefäß für etwa eine Stunde in den Kühlschrank stellen, bis sich der Schaum auflöst. Dann die Flüssigkeit in einen 
                    Eiswürfelbehälter füllen und einfrieren. Wenn die einzelnen Töpfchen zu groß sind, den Behälter nur zur Hälfte befüllen, 
                    so dass später mit den Würfeln die erforderliche Kleinmenge entnommen werden kann. Wenn die Aloe gefroren ist, kann man 
                    die Würfel in einen Beutel füllen und fest verschlossen in der Tiefkühltruhe aufbewahren. Ggf. den Eiswürfelbehälter dann 
                    mit dem Rest des flüssigen Gels befüllen und die zweite Fuhre später zur ersten in den Beutel füllen. Auf diese Weise 
                    hat man den Aloe Vera-Rohstoff für viele Cremetiegelchen in Vorrat. Achten Sie darauf, dass die gesamte Flüssigkeitsmenge
                    nach spätestens 12 Stunden eingefroren sein muss, damit sie nicht oxydiert (erkennbar an einer rötlichen Färbung).
                    <br />
                    <br />
                    <b>Herstellung der Creme:</b>
                    <br />
                    Mandelöl Montanov 58 und Fluidlecithin Super HT in dem größeren Glas-Messbecher im Wasserbad auf ca. 70°C erwärmen, bis sich 
                    die Montanov-Kügelchen komplett aufgelöst haben. Dabei mit einem Eierlöffel umrühren. (Ein Thermometer ist nicht unbedingt 
                    erforderlich &ndash; wenn die Emulgator-Kügelchen aufgelöst sind, ist die Temperatur richtig.)
                    <br />
                    <br />
                    Aloe Vera Gel in dem kleineren Glas-Messbecher ebenfalls im gleichen Wasserbad auf ca. 70°C erwärmen 
                    <br />
                    <br />
                    Beide Bechergläser aus dem Wasserbad nehmen und vorsichtig und langsam das Aloe Vera-Gel in das größere Becherglas 
                    mit der Öl-/Emulgatormischung gießen, während man das Ganze mit einem Milchaufschäumer kontinuierlich durchrührt.
                    <br />
                    <br />
                    Wenn die Substanzen komplett vermischt sind, die Sheabutter hinzufügen und mit dem Milchaufschäumer gründlich solange verrühren,
                    bis die Creme nur noch lauwarm ist (mindestens 5 Minuten). Das gründliche Rühren ist erforderlich, damit sich alle Zutaten dauerhaft 
                    verbinden und später keine Entmischung stattfindet. 
                    <br />
                    <br />
                    Hinweis: Die Sheabutter nicht mit dem Öl zusammen erwärmen, da die konsistenzgebenden Eigenschaften 
                    bei zu großer Hitze verloren gehen würden.
                    <br />
                    <br />
                    Zusätzlich können die optionalen Zutaten mit dem Milchaufschäumer untergerührt werden.
                    Wer eine sehr empfindliche Haut hat, sollte aber zunächst auf diese optionalen Zutaten verzichten und die Creme nur 
                    aus den Basis-Zutaten zubereiten. Später können dann bei Bedarf die eine oder andere optionale Zutat ausgetestet werden.
                    <br />
                    <br />
                    Zum Schluss die Creme in einen verschließbaren Tiegel füllen und im Kühlschrank fest werden lassen. Die optimale Konsistenz 
                    hat die Creme nach etwa 1 &ndash; 2 Tagen und kann dann im Bad aufbewahrt und benutzt werden.
                    <br />
                    <br />
                    Wenn Sie kein Konservierungsmittel verwendet haben, bitte die Creme weiter im Kühlschrank aufbewahren, ansonsten ist sie 
                    für 1 &ndash; 2 Monate (je nach Menge des Konservierungsmittels) auch bei Zimmertemperatur haltbar.
                    <br />
                    <br />
                    Die Crememenge reicht für 1 &ndash; 2 Wochen. Viel Spaß beim Ausprobieren. 
