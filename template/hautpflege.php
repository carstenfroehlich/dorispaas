                    <h5>Lippenpflegestift mit Kokosöl</h5> 
                    <hr />
                    <div class="oneline">
                        <div class="left" style="width: 148px">
                        <img src="<?php echo IMG_PATH; ?>lippenpflegestift.png" alt="Lippenpflegestift" class="inline" />
