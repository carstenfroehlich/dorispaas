                    <h5>Deo-Creme</h5> 
                    <hr />
                    <div class="oneline">
                        <div class="left" style="width: 148px">
                        <img src="<?php echo IMG_PATH; ?>deo.png" alt="Deo" class="inline" />
                    </div>
                    </div>
                    <br />
                    Bei meinen Versuchen, ein selbstgemachtes Deo herzustellen, bin ich auf größere Schwierigkeiten gestoßen. Erstens 
                    sollten &ndash; wie bei allen anderen Hautpflegeprodukten auch &ndash; nur möglichst wenige Zutaten enthalten sein, 
                    andererseits sollte das Ergebnis aber auch wirklich sicher und wirkungsvoll sein. Im Handel gibt es meist die Varianten 
                    als Spray oder als Roll-on &ndash; beides hielt ich für schwierig herzustellen und vor allem beim Roll-on, die Flasche 
                    zu besorgen. Da ich schon seit längerer Zeit eine Deo-Creme aus dem Bioladen verwendete (leider eben auch diese mit viel 
                    zu vielen Inhaltsstoffen), entschied ich mich für diese Anwendungsform.
                    <br />
                    <br />
                    Für den eingefleischten Sprayer oder Roller bedeutet die Creme-Anwendung zunächst ein wenig Umstellung, denn man muss mit dem Finger 
                    aus dem Töpfchen eine kleine Creme-Menge entnehmen und diese unter den Achseln verteilen. Anschließend ist Händewaschen angesagt 
                    &ndash; das ist es aber auch schon. Vor allem die vielen Verpackungen, die dadurch eingespart werden können, lohnen diese kleine Mühe.
                    Auf jeden Fall von Vorteil ist, dass man nach dem Auftragen nicht abwarten muss, bis das Spray oder Roll-on getrocknet ist, bevor man 
                    sich ankleiden kann &ndash; nach dem Auftragen der Creme die Haut sofort trocken. 
                    <br />
                    <br />
                    Es gibt für die Selbstherstellung verschiedene Varianten von Deo-Cremes &ndash; mit und ohne Natron. Jede Form hat ihre Vor- und
                    Nachteile. Letztendlich habe ich mich für die Variante mit Natron entschieden, obwohl sich die Textur ein wenig &#187;sandig&#171; anfühlt. 
                    Dieses Gefühl kann man abmildern, indem man die Creme auf die noch duschfeuchte Haut aufträgt. Dabei lösen sich die Natronkörnchen 
                    in der Feuchtigkeit, was sehr angenehm ist. 
                    Ich finde diese Variante aber im Gegensatz zur wärmeren und &#187;schwereren&#171; Deo-Creme ohne Natron frischer und leichter auf der Haut, 
                    zudem ist sie sehr viel leichter herzustellen. 
                    <br />
                    <br />
                    Im Sommer halte ich mich an die u.a. Zutaten, im Winter kann man ggf. die Kakaobutter durch die gleiche Menge Kokosöl ersetzen, so dass mit dem dann 
                    1 Teel. Kokosöl insgesamt eine Zutat weniger enthalten ist. Da jedoch das Kokosöl bei sommerlichen Temperaturen flüssig wird, braucht es in dieser 
                    Jahreszeit die Zugabe der festeren Kakaobutter.
                    <br />
                    <br />
                    Wählen Sie ein ätherisches Öl nach Ihren Duftvorlieben, wobei ich persönlich die Frische des Zitronenöls bevorzuge.
                    <br />
                    <br />
                    <b>Zutaten:</b>
                    <br />
                    <b>&#149; </b> 0,5 gestr. Teel. Kokosöl
                    <br />
                    <b>&#149; </b> 0,5 gestr. Teel. Kakaobutter
                    <br />
                    <b>&#149; </b> 0,5 gestr. Teel. Sheabutter
                    <br />
                    <b>&#149; </b> 1 gestr. Teel. weiße Tonerde (Kaolin)
                    <br />
                    <b>&#149; </b> 1,5 gestr. Teel. Natron
                    <br />
                    <b>&#149; </b> 1 Messerspitze voll Zinkoxid
                    <br />
                    <b>&#149; </b> 3 &ndash; 4 Tropfen ätherisches Öl nach Wahl (z.B. Zitrone)
                    <br />
                    <br />
                    <b>Utensilien:</b>
                    <br />
                    <b>&#149; </b> kleiner Porzellan-Mörser mit Stößel
                    <br />
                    <b>&#149; </b> Eierlöffel                   
                    <br />
                    <b>&#149; </b> Tiegel                  
                    <br />
                    <br />
                    <b>Herstellung:</b>
                    <br />
                    Alle Zutaten in den Porzellan-Mörser geben und gründlich mit dem Stößel verreiben.
                    Beim Durcharbeiten wird die Masse, die zunächst eher bröckelig ist, nach und nach geschmeidig und pastös.
                    <br />
                    <br />
                    Die Masse in den Tiegel füllen und einen Tag stehen lassen. Danach ist das Deo cremeartig fest.
                    Bitte nicht in den Kühlschrank stellen, sonst wird das Deo steinhart. Sollte dies der Fall sein, einen Tag
                    bei Zimmertemperatur stehen lassen, dann wird die Deo-Creme wieder geschmeidig.
