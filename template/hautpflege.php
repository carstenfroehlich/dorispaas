                    <h5>Haarseife (festes Shampoo) und Duschseife</h5> 
                    <hr />
                    <div class="oneline">
                        <div class="left" style="width: 148px">
                        <img src="<?php echo IMG_PATH; ?>seife.png" alt="Seife" class="inline" />
                    </div>
                    </div>
                    <br />
                    Insbesondere in der Dusche ärgert mich die Plastikflaschenflut. Für die Haare benutze ich deshalb eine <b>feste Haarseife</b>, 
                    die lange Zeit reicht und keinerlei Verpackung benötigt. 
                    Geeignete Produkte gibt es mittlerweile nicht nur im Internet, sondern in vielen Bioläden oder teils auch im Reformhaus. 
                    Und falls Sie einen &#187;Unverpackt-Laden&#171; in Ihrer Nähe haben, lohnt es sich, auch dort einmal nachzuschauen.
                    <br />
                    <br />
                    Nach einigen (Fehl-)Versuchen habe ich aber auch ein schönes und &ndash; vor allem &ndash; sehr einfaches
                    Rezept zum Selbermachen ausgetüftelt.
                    Man braucht dazu ein möglichst mildes Tensid, einen Füllstoff und etwas Öl oder Butter (z.B. Shea- oder Kakaobutter).
                    Optional kann man für den guten Duft auch etwas ätherisches Öl hinzufügen &ndash; es geht aber auch vollkommen pur.
                    <br />
                    <br />
                    Ein Duschgel selber herzustellen, würde zwar im Hinblick auf die Inhaltsstoffe sehr wohl Sinn machen, in Bezug auf die Plastikvermeidung 
                    allerdings weniger, da ja die (flüssigen) Zutaten meist in Kunsstoffflaschen geliefert werden.
                    Da sich die feste Haarseife aber für <b>sowohl für die Haare als auch für den Körper</b> eignet, benutze ich sie auch für den Körper, 
                    wenn es denn überhaupt erforderlich ist. Meist reicht es nämlich, sich unter dem Wasserstrahl den Körper abzureiben, die häufige 
                    Seifenverwendung trocknet die Haut aus und schädigt den natürlichen Säureschutzmantel.
                    <br />
                    <br />
                    <b>Zutaten für 3 Seifenstücke:</b>
                    <br />
                    <b>&#149; </b> 100g SCI-Tensid
                    <br />
                    <b>&#149; </b> 100g Kartoffelstärke
                    <br />
                    <b>&#149; </b> 12,5g Sheabutter 
                    <br />
                    <b>&#149; </b> 12,5g Klettenwurzelöl 
                    <br />
                    <br />
                    und optional:
                    <br />
                    <b>&#149; </b> 50 Tropfen ätherisches Öl (z.B. Limetten- oder Zitronenöl)
                    <br />
                    <br />
                    <b>Herstellung:</b>
                    <br />
                    Ein Porzellanschälchen (z.B. ein Müslischälchen) mit kochendem Wasser füllen, so dass es heiß wird. Das Wasser ausleeren und 
                    die Schale gut abtrocknen. 
                    <br />
                    <br />
                    Danach die Schale auf eine Waage stellen und zunächst das Klettenwurzelöl abwiegen. Dann die Sheabutter hinzufügen.
                    Weil die Wärme der Schale Öl und Butter erwärmt, können diese beiden Zutaten mit einem Löffel gut gemischt werden.
                    <br />
                    <br />
                    Danach Tensid und Kartoffelstärke hinzufügen. Falls Sie nur sogenannte SCI-Nadeln bekommen, diese zuvor in einem Porzellanmörser zu
                    einem feinen Pulver zermahlen. Wer einen leistungsfähigen Mixer besitzt, kann die Nadeln und die Kartoffelstärke dort zu gleichen Teilen 
                    mixen und dann von dieser Mischung 200g verwenden. <b>Achtung: bei der Verwendung des Tensids unbedingt mit Mundschutz arbeiten und über 
                    den Mixer ein Handtuch legen, um keinen Staub aufzuwirbeln und einzuatmen!</b>
                    <br />
                    <br />
                    Ggf. das ätherische Öl hinzugeben.
                    <br />
                    <br />
                    Die Mischung mit dem Löffel gut verrühren, bis eine einigermaßen homogene Masse entstanden ist.
                    <br />
                    <br />
                    Diese Masse nun auf eine glatte Arbeitsfläche kippen und mit sauberen Händen wie einen Kuchenteig kneten, bis keine Klümpchen mehr 
                    vorhanden sind.
                    <br />
                    <br />
                    Den &#187;Teig&#171; in 3 Stücke teilen, diese zu Kugeln formen und ein wenig platt drücken. 
                    <br />
                    <br />
                    Diese Seifenstücke müssen nun <b>mindestens 2 Wochen trocknen und fester werden</b>. Legen Sie sie dazu auf ein Küchenkrepp, das Sie auf einen 
                    Kuchenrost legen. Die Seife trocknet am besten an einem zimmerwarmen, ruhigen Ort.
                    Auch nach dem Trocknen bleiben sie noch etwas formbar &ndash; das 
                    war für mich zunächst etwas ungewohnt, denn ich erwartete eigentlich ein vollkommen festes Seifenstück. Diese Konsistenz hat jedoch 
                    durchaus Vorteile, denn man kann auch später noch die kleiner werdenden Seifenreste in eine gut in der Hand liegende Form kneten.
                    <br />
                    <br />
                    Übrigens: Ein solches Seifenstück eignet sich auch gut als Geschenk &ndash; denken Sie nur daran, dass Sie die Trockenzeit einrechnen und das 
                    Geschenk rechtzeitig herstellen.
