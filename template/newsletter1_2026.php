                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-entspannung" target="_blank">Schwerpunktthema: Entspannung &ndash; auch und gerade in Krisenzeiten</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Entspannung/Entspannung)</i>
                        <br />
                        Stress wirkt sich nicht nur negativ auf unser Wohlbefinden aus. Unter Stress kann unsere Verdauung nicht korrekt arbeiten. Das Verdauungssystem 
                        funktioniert auch nach Tausenden von Jahren, also einem Wimpernschlag in der 
                        menschlichen Evolution, noch genauso, wie bei unseren Vorfahren. In Stresssituationen werden nur all jene Funktionen aufrechterhalten, die zum &Uuml;berleben 
                        wichtig sind. Weniger wichtige Funktionen &ndash; wie u.a. die Verdauung &ndash; werden heruntergefahren, so dass die Ressourcen nur noch f&uuml;r die 
                        Bew&auml;ltigung der aktuellen Umst&auml;nde bereitgestellt werden. All dies wird geregelt durch unser autonomes Nervensystem, also das Nervensystem, 
                        das wir nicht willentlich beeinflussen k&ouml;nnen. Es sind hier die beiden Gegenspieler Sympathikus und Parasympathikus, die diese K&ouml;rperreaktionen 
                        steuern. Der Sympathikus ist f&uuml;r die Stressregulierung zust&auml;ndig, der Parasympathikus f&uuml;r den Ruhemodus. Beide Nervensysteme arbeiten 
                        ausschlie&#223;lich, d.h. es gibt keine Gleichzeitigkeit oder Zusammenarbeit. Entweder ist man im Stressmodus oder im Ruhemodus. Mit aktiver Entspannung 
                        k&ouml;nnen wir auch in stressigen Zeiten &ndash; wie auch den derzeitigen &ndash; dazu beitragen, in den Ruhemodus zu kommen und u.a. f&uuml;r eine 
                        gesunde Verdauung sorgen.
