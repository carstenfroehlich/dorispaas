                    <h5>Buchbeschreibung</h5>
                    <hr />
                    Unsere Ernährung ist die Basis für unsere Gesundheit. Viele &ndash; ja sogar 
                    wahrscheinlich die meisten &ndash; Krankheiten würden gar nicht erst entstehen, 
                    wenn wir uns gesund ernähren und ausreichend bewegen würden. Die Ernährung 
                    kann einen ebenso entscheidenden Beitrag zur Gesundheit des Menschen leisten 
                    wie eine insgesamt gesunde Lebensweise. Und dies muss mitnichten Askese und Verzicht 
                    nach sich ziehen &ndash; ganz im Gegenteil: Gesunde Ernährung kann auch in unserer 
                    heutigen Zeit Genuss, Freude und Vergnügen bedeuten.
                    <br />
                    <br />
                    Das Paas'sche Heftchen &#187;Kurz und klar: Gesunde Ernährung&#171; erklärt in kurzer 
                    und klarer Form alles Wichtige rund um dieses Thema. Es erläutert darüber 
                    hinaus Ursachen und Hintergründe von etwaigen Beschwerden. Das Heftchen hilft, Probleme 
                    zu erkennen und zu verstehen und zeigt erste Schritte in die richtige Richtung: 
                    eine gesunde Lebensweise ohne Beschwerden, um sich wohl zu fühlen und bis 
                    ins hohe Alter gesund zu bleiben.
                    <br />
                    Jedes Heftchen stellt wesentlich mehr Informationen zur Verfügung als eine 
                    Info-Broschüre und versteht sich somit als Vereinigung von Informations-Broschüre 
                    und Sachbuch. Es erhebt bewusst keinen Anspruch auf Ausführlichkeit, sondern 
                    verschafft Ihnen in kurzer, aber korrekter Form einen ersten &Uuml;berblick über das Thema. 
                    Trotz des geringen Umfangs bleibt es jedoch nicht oberflächlich, sondern ist sorgfältig 
                    recherchiert: In rund einer Stunde wissen Sie alles Wesentliche zum Thema &#187;Gesunde Ernährung&#171;.
