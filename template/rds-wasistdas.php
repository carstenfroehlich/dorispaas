                        Das Reizdarm-Syndrom wird definiert als Funktionsst&ouml;rung 
                        des Verdauungstrakts mit chronischen Beschwerden wie Bauchschmerzen, Stuhlunregelm&auml;&#223;igkeiten 
                        (Wechsel zwischen Durchfall und Verstopfung) und Bl&auml;hungen. 
                        <br />
                        <br />
                        Der menschliche Darm ist auf seiner gesamten L&auml;nge von einem empfindlichen 
                        Nervengeflecht durchsetzt und umgeben, das jede Bewegung registriert und zur Bewertung 
                        an das Gehirn weitergibt. Bei Vorliegen eines RDS werden teilweise ganz normale 
                        Darmbewegungen, die andere Menschen nur als leichtes &#187;Bauchgrummeln&#171; 
                        registrieren, von Betroffenen als Schmerzen wahrgenommen oder mit Verstopfung 
                        und/oder Durchf&auml;llen beantwortet. 
                        <br />
                        <br />
                        Der Arzt kann keine krankhaften Organver&auml;nderungen feststellen. Die Diagnose 
                        wird nach dem sorgfältigen Ausschluss aller weiteren infrage kommenden Erkrankungen (chronisch 
                        entz&uuml;ndliche Darmerkrankungen, Nahrungsmittel-Unvertr&auml;glichkeiten, bakterielle 
                        Fehlbesiedelungen, b&ouml;sartige Erkrankungen etc.) gestellt. Oftmals jedoch 
                        sind Nahrungsmittel-Unverträglichkeiten und vor allem eine Dünndarmfehlbesiedelung 
                        die Ursache der Beschwerden (lesen Sie hierzu bitte auch den Beitrag 
                        &#187;<a href="duenndarmfehlbesiedelung" target="_blank">Dünndarmfehlbesiedelung und ihre Behandlung></a>&#171;.
                        <br />
                        <br />
                        Erst wenn diese Möglichkeiten definitiv ausgeschlossen 
                        bzw. adäquat behandelt wurden, kann wirklich ein Reizdarm-Syndrom diagnostiziert werden. 
                        Dazu dient die Abfrage der so genannten ROM-Kriterien, einem Fragenkatalog, 
                        der genau festlegt, wann, wie oft, 
                        in welchen Abst&auml;nden welche Beschwerden auftreten (lesen Sie hierzu auch den Beitrag
                        &#187;<a href="rds-diagnose">Diagnose des Reizdarm-Syndroms</a>&#171;). 
                        <br />
                        <br />
                        Die Behandlung des Reizdarm-Syndroms muss den jeweiligen vorrangigen Symptomen 
                        (Durchfall (Diarrhoe), Verstopfung (Obstipation), Wechsel zwischen Durchfall und 
                        Verstopfung oder Bauchschmerzen angepasst werden. (Lesen Sie dazu auch den Beitrag
                        &#187;<a href="rds-behandlung">Behandlung des Reizdarm-Syndroms</a>&#171;).
                        <br />
                        <br />
                        <hr>
                        <h5>Wie unterscheidet man die Beschwerden von denen 
                        einer Nahrungsmittel-Unverträglichkeit?</h5>
                        <hr>
                        Zur Abgrenzung zu einer Nahrungsmittel-Unvertr&auml;glichkeit dient die Tatsache, 
                        dass die Beschwerden, die durch das Reizdarm-Syndrom hervorgerufen werden, in 
                        Entspannungs-Situationen (Wochenenden, Urlaub) und nachts deutlich besser werden 
                        oder sogar ganz verschwinden. Dies ist bei einer Nahrungsmittel-Unvertr&auml;glichkeit 
                        nicht der Fall. Werden bei Intoleranzen abends unvertr&auml;gliche Mahlzeiten verzehrt, 
                        so treten die Beschwerden auch in der Nacht auf.
                        <br />
                        <br />
                        Das RDS tritt auch sehr h&auml;ufig als Begleiterscheinung bei Nahrungsmittel-Unvertr&auml;glichkeiten 
                        auf, so dass die Abgrenzung schwierig ist, welche Beschwerden nun von der Unvertr&auml;glichkeit 
                        und welche durch das Reizdarm-Syndrom hervorgerufen werden.
