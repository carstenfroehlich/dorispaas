                        <h5>Ausgabe 62 (Herbst 2022)</h5>
                        <hr />
                        <br />
                        
                        
<a href="http://www.dorispaas.de/index.php?page=book-darmgymnastik" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2022-03-book-darmgymnastik.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Viele, die meine Website und meine Arbeit kennen, wissen, dass ich schon einige B&uuml;cher zu meinen Schwerpunkthemen geschrieben habe.
                        Jetzt gibt es <b>ein neues Buch</b>, das ich allen Betroffenen mit Verdauungsproblemen empfehlen m&ouml;chte und f&uuml;r das ich mit diesem Newsletter 
                        ein wenig die Werbetrommel r&uuml;hren m&ouml;chte. Der Titel ist &#187;<a href="http://www.dorispaas.de/index.php?page=book-darmgymnastik" target="_blank">Darmgymnastik &ndash; 
                        Bewegung &#38; mehr gegen Verdauungsprobleme</a>&#171;.
                        <br />
                        <br />
                        Bei meinen Beratungen und auf meinen Streifz&uuml;gen durch die einschl&auml;gigen Foren im Internet stelle ich immer wieder fest, dass Betroffene 
                        teils jahre- oder sogar jahrzehntelang an Verdauungsproblemen leiden, ohne dass sie mit den diversen Behandlungen dauerhafte Erfolge erzielen konnten. 
                        Die verbreitete Einstellung, allein die Einnahme von Pillen k&ouml;nne helfen, dass man gesund bleibt oder Krankheiten lediglich mit diesen Mitteln 
                        heilen k&ouml;nnte &ndash; und das auch noch schnell und dauerhaft, ist ein verh&auml;ngnisvoller Trugschluss. Es fehlt bei diesen Menschen n&auml;mlich  
                        in der Regel eine ganz entscheidende Komponente in ihrem Behandlungskonzept: die Bewegung!
                        <br />
                        <br />
                        Ein Mangel an Bewegung ist bei allen Verdauungsbeschwerden mit einer der h&auml;ufigsten Fehler. &Auml;ndert man hier etwas und bewegt sich 
                        mehr, kann man nicht nur die Symptome g&uuml;nstig beeinflussen, sondern gleichzeitig eine der wichtigsten Ursachen beheben. 
                        <a href="http://www.dorispaas.de/index.php?page=darmgymnastik" target="_blank">Kontinuierliche Bewegung</a> &ndash; und damit ist <b>etwas ganz anderes als der Sport</b> 
                        gemeint &ndash; ist die beste und wirksamste &#187;Medizin&#171; gegen Verdauungsprobleme, die es gibt. 
                        <br />
                        <br />
                        In dem Buch sind deshalb zahlreiche <b>Atem- und Bewegungs&uuml;bungen</b> f&uuml;r einen gesunden Darm ohne Verdauungsbeschwerden zusammengestellt, und 
                        Strichmenschlein zeigen Ihnen die Bewegungsabl&auml;ufe. Es gibt aber auch die erforderlichen Erkl&auml;rungen zu den Zusammenh&auml;ngen, denn nur, was man 
                        versteht, kann man auch mit &Uuml;berzeugung und in ausreichendem Ma&#223;e durchf&uuml;hren &ndash; und durchhalten. 
                        Dar&uuml;ber hinaus sind bestimmte Punkte auf dem K&ouml;rper dargestellt, die mithilfe der <b>Akupressur</b> stimuliert werden k&ouml;nnen, wodurch die 
                        Bewegungs&uuml;bungen ideal erg&auml;nzt werden. Weiterhin werden <b>zus&auml;tzliche Hilfsma&#223;nahmen und Hilfsmittel</b> vorgestellt, die die Behandlung 
                        von Verdauungsproblemen effektiv unterst&uuml;tzen. Und last, but not least, gibt es ein Kapitel mit <b>h&auml;ufig gestellten Fragen</b> zu diesem Themenkomplex.
                        Die Antworten k&ouml;nnen sicherlich auch Ihnen weiterhelfen. 
                        <br />
                        <br />
                        Zusammengenommen haben Sie mit diesem Baukasten zahlreiche M&ouml;glichkeiten in der Hand &ndash; und zwar im w&ouml;rtlichen Sinne in der eigenen Hand, 
                        um Erkrankungen des Verdauungssystems und Beschwerden sowohl symptomatisch als auch urs&auml;chlich g&uuml;nstig beeinflussen oder ihnen sogar wirksam 
                        vorbeugen zu k&ouml;nnen. 
                        <br />
                        <br />
                        &#187;Ein Allheilmittel also?&#171; Nun, nicht so ganz. Alleine heilen diese Ma&#223;nahmen Ihre Beschwerden nicht. Aber Bewegung in Kombination mit der 
                        Akupressur und die zus&auml;tzlichen Ma&#223;nahmen und Hilfsmittel <b>unterst&uuml;tzen</b> die jeweils spezifische Behandlung bei der Heilung von Verdauungsbeschwerden 
                        &ndash; und diese Unterst&uuml;tzung ist unverzichtbar. <b>Ansonsten ist nicht nur die Heilung in Frage gestellt, es sind auch R&uuml;ckf&auml;lle vorprogrammiert</b>.

                        <br />
                        <br />
                        <hr />
                        <br />
                        Liebe Leserin, lieber Leser, das Thema &#187;Darmgymnastik&#171; ist mir so wichtig, dass ich mich in dieser Ausgabe des DorisPaas.de-Newsletters einzig darauf beschr&auml;nken 
                        m&ouml;chte. Nat&uuml;rlich bin ich nach mehr als einj&auml;hriger Arbeit auch ein wenig stolz auf das <a href="http://www.dorispaas.de/index.php?page=book-darmgymnastik" target="_blank">Buch</a> 
                        und die begleitende <a href="http://www.dorispaas.de/index.php?page=darmgymnastik" target="_blank">Website</a>. Vor allem aber m&ouml;chte ich deutlich machen, wie essentiell die 
                        kontinuierliche Bewegung als Begleitma&#223;nahme bei der Behandlung eines jeden Verdauungsproblems ist. Viele Leidenswege k&ouml;nnten um Wochen, Monate oder sogar um Jahre 
                        verk&uuml;rzt werden, und zahlreiche (Folge-)Erkrankungen würden gar nicht erst entstehen, wenn man sich um mehr Bewegung f&uuml;r den Darm k&uuml;mmern w&uuml;rde. Es gilt der 
                        Grundsatz &#187;<b>Bewegung ist nicht alles, aber ohne Bewegung ist alles nichts</b>&#171;.
                        <br />
                        <br />
                        In diesem Sinne w&uuml;nsche ich Ihnen einen darmbewegten Herbst &ndash; wenn Sie mögen, mit der Lektüre des Buches und viel Spaß und Erfolg bei und mit den Übungen. 
                        Den n&auml;chsten Newsletter erhalten Sie dann, wenn Sie m&ouml;chten, zum Beginn des kommenden Winters.
