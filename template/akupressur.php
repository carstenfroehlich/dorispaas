                        <h3>&rarr; Schmerz-Masterpunkt (Di 4)</h3>
                        <br />
                        <img src="<?php echo IMG_PATH; ?>akupressur-dickdarm4.png" alt="Dickdarm 4" class="left" />
                        <b>Wirkung:</b> lindernd bei allen Schmerzzuständen
                        <br />
                        <b>Lage:</b> Der Punkt liegt auf dem Dickdarm-Meridian (Di4) und befindet sich auf dem Wulst zwischen Daumen und Zeigefinder.
                        <br />
                        <b>Auffinden:</b> Wenn Sie den Daumen an die restliche Handfläche drücken, ensteht zwischen Daumen und Zeigefingerwurzelknochen ein Wulst. 
                        Der Akupressurpunkt befindet sich auf dem höchsten Punkt dieses Wulstes. 
                        <br />
                        <br />
                        <b>Technik:</b> Lösen Sie den Daumen von der Handfläche, so dass der Wulst verschwindet. Drücken Sie mit dem Daumen der anderen Hand 
                        an der Stelle des Akupunkturpunktes gegen den Handwurzelknochen des Zeigefingers. Sie fühlen evtl. einen leichten Druckschmerz. 
                        Nun einige Minuten kräftig massieren bzw. den Punkt an dieser Stelle klopfen.
