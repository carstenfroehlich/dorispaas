                        <h3>&rarr; Reizdarm (Ma 37)</h3>
                        <br />
                        <img src="<?php echo IMG_PATH; ?>akupressur-magen37.png" alt="Magen 37" class="left" />
                        <b>Wirkung:</b> beruhigend bei allen Reizdarmbeschwerden und Durchfall
                        <br />
                        <b>Lage:</b> Der Punkt liegt auf dem Magen-Meridian (Ma37) und befindet sich kurz über der Mitte zwischen dem Knie und dem Fuß außen neben dem Schienbein.
                        <br />
                        <b>Auffinden:</b> Suchen Sie ihr Schienbein und legen am Unterschenkel eine gedachte senkrechte Hilfslinie etwa 2 cm nach außen. Auf dieser Hilfsline 
                        liegt der Akupressurpunkt 3 Fingerbreit über der Mitte der Länge des Unterschenkels.
                        <br />
                        <br />
                        <b>Technik:</b> Suchen Sie den Punkt und massieren bzw. klopfen den Punkt kräftig einige Minuten.
