                        Wahrscheinlich hat jeder schon einmal von der der <b>Akupunktur</b> gehört, einer in der Traditionellen 
                        Chinesischen Medizin (TCM) verankerten Methode. Dabei werden feine Nadeln in bestimmte Punkte auf 
                        unserer Körperoberfläche gestochen, um den Energiefluss zu harmonisieren oder auch um die Produktion 
                        körpereigener Stoffe zu produzieren. Diese Technik wird von geschulten TCM-Therapeuten durchgeführt, 
                        die &ndash; günstigstenfalls in China &ndash; geschult werden, u.a. um die genaue Lage der geeigneten 
                        Punkte auffinden zu können.
                        <br />
                        <br />
                        Unser Körper ist nicht nur mit Nervenbahnen durchzogen, die Reize weiterleiten können, sondern auch 
                        von den sogenannten Meridianen (Leitbahnen), in denen nach der TCM-Lehre die Lebensenergie, das Qi, fließt. 
                        Die Meridiane sind unseren Organen zugeordnet. So gibt es u.a. den den Dickdarm-Meridian (Di), den Milz-Meridian (Mi)
                        oder den Magen-Meridian (Ma) und andere. Zusätzlich gibt es weitere Leitbahnen wie z.B. das sogenannte Konzeptionsgefäß 
                        (Ren Mai) und das Lenkergefäß (Du Mai), deren Namen keinen direkten Organbezug erkennen lassen. Die Akupunkturpunkte sind
                        auf den Meridianen durchnummeriert und entsprechend ihrer Lage z.B. mit &#187;Di 4&#171;, &#187;Ma 37&#171; oder 
                        &#187;Ren 6&#171; bezeichnet.
                        <br />
                        <br />
                        Ist der Energiefluss gestört, können Krankheiten die Folge sein. Insbesondere chronische Erkrankungen 
                        können durch die Aktivierung des Energieflusses günstig beeinflusst werden. Dabei werden die Körperorgane 
                        nicht immer oder nicht ausschließlich über den dem Organ zugeordneten Meridian erreicht, es können durchaus 
                        auch Punkte auf anderen Meridianen manipuliert werden, um einen optimalen Effekt zu erzielen.
                        <br />
                        <br />
                        Aber nicht nur der Energiefluss kann durch die Akupunktur normalisiert werden, es kann auch direkt die 
                        Produktion von verschiedenen Stoffen wie z.B. &#187;Schmerzmitteln&#171; angeregt werden, die sich dann 
                        günstig auf Missempfindungen auswirken können. Es ist beispielsweise sogar möglich (und wird in China auch gehandhabt), 
                        das mit der Akupunktur Schmerzempfinden soweit auszuschalten, dass Operationen ohne eine weitere Anästhesie durchgeführt 
                        werden können. In Deutschlandsind wir hier noch nicht so weit, aber für bestimmte Indikationen wie z.B. bei chronischen 
                        Schmerzen im Knie oder an der Lendenwirbelsäule werden die Kosten für Akupunkturbehandlungen von den Krankenkassen übernommen.
                        <br />
                        <br />
                        Bei der Akupunktur, werden, wie oben erwähnt, feine dünne Nadeln direkt in die dicht unter der Haut liegenden 
                        Punkte eingestochen. Die Punkte können aber auch mit Werkzeugen (wie z.B. Akupunkturstiften) oder auch mit den 
                        Fingern gedrückt werden &ndash; diese Technik heißt <b>Akupressur</b>. Bei beiden Techniken ist die exakte Kenntnis der 
                        Lage der Punkte wichtig, weil schon kleinere Abweichungen den Erfolg infrage stellen. 
                        <br />
                        <br />
                        Für den ungeübteren Anwender ist die <b>Klopftechnik</b> eine gute Einstiegs-Alternative, bei der die entsprechenden Punkte 
                        leicht mit den Fingerspitzen geklopft werden. Da durch das Klopfen eine Vibration über dem Punkt und auch ein wenig darum 
                        herum entsteht, kann auch bei leichten Abweichungen eine Wirkung erzielt werden.
                        <br />
                        <br />
                        <a id="akupressur"></a>
                        <hr>
                        <h5>Akupressur</h5>
                        <hr>
                        Bei der Akupressur wird der jeweils den Beschwerden entsprechende Punkt mit einer Fingerspitze, dem Daumen oder einem Hilfsmittel 
                        (wie z.B. einem festen Schaumstoffball) mehr oder weniger kräftig gedrückt. Dabei den Finger oder das Hilfsmittel ein wenig auf 
                        dem Punkt kreisen lassen und den Akupunkturpunkt massieren. Die Massagedauer sollte etwa 2 bis 5 Minuten pro Punkt betragen. Es 
                        ist wichtig, dass Sie keinesfalls Ihre Schmerzgrenze überschreiten, manchmal kann es jedoch sein, dass der Druck ein wenig unangenehm 
                        ist. Optimal unterstützen können Sie die Akupressur mit geeigneten Atemtechniken. Lesen Sie hierzu bitte den Beitrag 
                        &#187;<a href="atmen" target="_blank">Atem und Verdauung</a>&#171;.
                        <br />
                        <br />
                        <a id="klopftechnik"></a>
                        <hr>
                        <h5>Klopftechnik</h5>
                        <hr>
                        Bei der Klopftechnik wird leicht mit den Kuppen von zwei Fingern auf den Akupunkturpunkt geklopft. Ein mehrmaliges kurzes, 
                        leichtes Anstupsen der Haut über dem Punkt und sofortiges Zurückfedern genügt &ndash; etwa zwei- bis dreimal pro Sekunde 
                        für ca. 2 bis 5 Minuten. Mit welcher Hand Sie auf welcher Seite klopfen, ist für die Wirkung unerheblich, die Punkte sind 
                        symmetrisch auf beiden Körperseiten angeordnet.
                        <br />
                        <br />
                        <a id="magendarmpunkte"></a>
                        <hr>
                        <h5>Akupunktur-Punkte für Magen-/Darmbeschwerden</h5>
                        <hr>
                        Gerade Verdauungsbeschwerden lassen sich mit der Akupressur oder Klopftechnik günstig beeinflussen und es lohnt sich auf 
                        jeden Fall, sich mit der Lage der geeigneten Akupunkturpunkte vertraut zu machen. So kann man grundsätzliche, <b>ausgleichende 
                        Effekte</b> für die Funktionen von Magen, Dünn- und Dickdarm erreichen &ndash; vor allem auch bei den verschiedensten 
                        <a href="rds-behandlung">Reizdarm-Beschwerden</a>. Mit der Bearbeitung spezieller Punkte kann man sich auch bei Blähungen 
                        im Oberbauch, bei Flatulenzen, Durchfall, Verstopfung, Übelkeit und Völlegefühl oder <a href="reflux">Sodbrennen und Reflux</a> 
                        Erleichterung verschaffen.
                        <br />
                        <br />
                        Es gibt mehrere Punkte am Rumpf, an den Beinen und Füßen, deren Aktivierung einen generell harmonisierenden 
                        Einfluss auf Magen und Darm haben. Diese Punkte sollten Sie standardmäßig mindestens dreimal am Tag nacheinander 
                        massieren oder klopfen. Weiterhin gibt einen Punkt, den man am Morgen zur Aktivierung und einen Abendpunkt zur Beruhigung bearbeiten kann.
                        Zusätzlich sind hier Punkte aufgeführt, die im Notfall weiterhelfen können.
                        <br />
                        <br />
                        Beginnen Sie mit einem oder zwei Punkten, die Sie auffinden und bearbeiten sollten. An den darauffolgenden Tagen nehmen Sie 
                        jeweils einen weiteren Punkt hinzu, bis Sie alle Punkte sicher lokalisieren können. Üben Sie die Akupressur dieser Punkte immer 
                        mal wieder, um sie im Ernstfalle rasch finden zu können. 
                        <br />
                        <br />
                        Zur Harmonisierung und Beruhigung Ihres gesamten Verdauungssystems ist es günstig, alle Standardpunkte täglich mehrfach nacheinander zu 
                        bearbeiten. Zu diesem Standar-Programm kommen am Morgen der Morgenpunkt zur Aktivierung der Energie bzw. am Abend ein beruhigender Punkt.
                        Bei akutem Durchfall, Panik oder Schmerzen massieren oder klopfen Sie zusätzlich den entsprechenden Notfallpunkt. 
                        Lage und Wirkbereich dieser Punkte sind hier abgebildet. Zusätzlich wird die Lage beschrieben, und Sie finden eine Anleitung, wie Sie 
                        die Punkte mithilfe von gedachten Hilfslinien am besten auffinden können. 
                        <br />
                        <br />
                        Es gibt für die verschiedenen Verdauungsprobleme noch wesentlich mehr geeignete Akupunkturpunkte, als in der folgenden Aufstellung beschrieben. 
                        Für den Anfang jedoch können die unten dargestellten Punkte schon einmal sehr hilfreich sein. Lassen Sie sich trotzdem bitte am besten von  
                        einer geschulten Therapeutin oder einem Therapeuten anleiten, damit Sie zum einen die Lage der verschiedenen Akupunkturpunkte und die 
                        angemessene Intensität erlernen und die Akupressur dann zu Hause erfolgreich durchführen und die optimale Wirkung erzielen können.
                        Zum anderen können Sie sich weitere Punkte zeigen lassen, die für Ihre individuellen Probleme geeignet sind.
