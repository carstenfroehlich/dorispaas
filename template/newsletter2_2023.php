                        Liebe Leserin, lieber Leser.
                        <br />
                        Auch wenn ich keine eifrige Nutzerin der social media bin, lese ich doch ab und an in einschl&auml;gigen Foren die Beitr&auml;ge von Betroffenen. Oft bin ich erstaunt, dass dort 
                        leider trotz des gro&#223;en Informationsangebots, das man im Internet finden k&ouml;nnte, viel Wissen fehlt. Aber zugegebenerma&#223;en ist es schwer, die Spreu vom Weizen zu 
                        trennen, und viel zu oft wird gerade Falsches aufgegriffen &ndash; und dann auch noch verbreitet. Dies f&uuml;hrt h&auml;ufig dazu, dass sich Leidenswege 
                        (unn&ouml;tig) verl&auml;ngern k&ouml;nnen. Deshalb gebe ich in diesen Foren ab und an allgemeine Ratschl&auml;ge, in der Hoffnung, durch diese Tipps helfen zu k&ouml;nnen. Vor 
                        allem aber auf meiner Website gibt es auf den zahlreichen Themenseiten geballtes Wissen, so dass ich hoffe, Irrt&uuml;mer und Fehleinsch&auml;tzungen richtigstellen zu k&ouml;nnen. 
                        In diesem Newsletter greife ich aus gegebenem Anlass noch einmal das Thema &#187;Antibiotika und Darmgesundheit&#171; auf, gerade weil dies in den Foren (leider) ein Dauerbrenner ist. 
                        Sei es, dass sich durch die Einnahme von verordneten Antibiotika die Darmflora drastisch verschlechtert, oder dass Menschen mit Verdauungsbeschwerden versuchen, eine vermeintlich 
                        entgleiste Mikrobiota mit den frei verk&auml;uflichen, nat&uuml;rlichen Antibiotika selbst zu behandeln. Ich hoffe, dass ich in meinem Beitrag das n&ouml;tige Hintergrundwissen 
                        liefern kann, um Sie so zu bef&auml;higen, vorteilhafte Entscheidungen f&uuml;r Ihre Gesundheit zu treffen.
