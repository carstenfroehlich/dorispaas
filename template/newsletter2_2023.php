                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=vitalpilze" target="_blank">Vitalpilze</a></b>
                        <br />
                        <i>(Menü: Wissensdatenbank/Darmgesundheit/Hilfreiche Ma&#223;nahmen/Vitalpilze)</i>
                        <br />
                        Vitalpilze k&ouml;nnen vorbeugend, aber auch heilend eingesetzt werden. Vor allem aber ist es ihre ausgleichende, regulierende Wirkung, die sie besonders wertvoll machen. 
                        Vitalpilze sind auch ein interessanter Ersatz f&uuml;r Probiotika, denn oft ist der Einsatz dieser Pr&auml;parate, die lebende Mikroorganismen enthalten, eher ein Versuch, 
                        bei dem geschaut wird, ob die erw&uuml;nschte Wirkung eintritt. Vitalpilze hingegen unterst&uuml;tzen, dass die Mikrobiota (Darmflora) selbst wieder zu ihrer gesunden 
                        Balance zur&uuml;ckfindet. So haben sie ihr Einsatzgebiet ganz besonders auch bei Fehlbesiedelungen des Darms, den D&uuml;nndarmfehlbesiedelungen (SIBO/IMO) und/oder 
                        Dickdarmfehlbesiedelungen (Dysbiose). Durch ihre zahlreichen Anwendungsgebiete kann mit der Gabe von Vitalpilzen erreicht werden, dass Erkrankungen erst gar nicht entstehen 
                        und so der Einsatz von Antibiotika minimiert werden kann. Aber in einigen F&auml;llen kann die Einnahme von geeigneten Vitalpilzarten in R&uuml;cksprache mit dem Arzt und 
                        unter dessen Aufsicht auch anstelle eines Antibiotikums erwogen werden.
