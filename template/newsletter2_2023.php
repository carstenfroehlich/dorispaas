                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=antibiotika" target="_blank">Schwerpunktthema: Antibiotika und Darmgesundheit</a></b>
                        <br />
                        <i>(Menü: Wissensdatenbank/Darmgesundheit/St&ouml;rungen/Antibiotika und Darmgesundheit)</i>
                        <br />
                        Die &#187;Erfindung&#171; der Antibiotika ist Segen und Unsegen zugleich. Segen, weil sie vielen Krankheiten, die bis vor wenigen Jahrzehnten noch den Tod bedeuten konnten, 
                        den Schrecken genommen haben. Unsegen jedoch, weil sie in immer h&auml;ufigeren F&auml;llen wirkungslos geworden sind. Durch den massenhaften Missbrauch der vom Arzt 
                        verschriebenen, den in der Tiermast verwendeten chemischen Antibiotika und den in Eigenregie eingenommenen nat&uuml;rlichen Antibiotika haben sich die Bakterien, die 
                        diese Mittel eigentlich bek&auml;mpfen und abt&ouml;ten sollen, an die Substanzen &#187;gew&ouml;hnt&#171;. Durch die st&auml;ndige Kontaminierung kommt unsere Darmflora 
                        je nach Art und Menge der verzehrten Nahrung fortgesetzt mit Antibiotika in Kontakt &ndash; und es sind gerade die sensiblen, n&uuml;tzlichen Darmbakterien, denen dadurch 
                        in unserem inneren &Ouml;kosystem das (&Uuml;ber-)Leben schwer gemacht wird. Kein Wunder also, dass zahlreiche Krankheiten immer mehr zunehmen, weil unser eigenes Immunsystem nicht mehr richtig funktionieren kann. Aber welche Alternativen gibt es?
