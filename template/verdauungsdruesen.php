                        <a id="zusammenspiel"></a>
                        <hr />
                        <h5>Zusammenspiel aller Verdauungsdrüsen</h5>
                        <hr />
                        Nur wenn, wie oben erwähnt, das Zusammenspiel <b>aller</b> Verdauungsdrüsen reibungslos funktioniert, kann auch der gesamte Verdauungsprozess ohne Probleme ablaufen. Hängt auch 
                        nur ein einziges Rädchen in diesem System, führt dies unweigerlich zu mehr oder weniger ausgeprägten Symptomen. 
                        <br />
                        <br />
                        Es mag sein, dass kleinere und vor allem vorübergehende Funktionseinschränkungen einer der Verdauungsdrüsen temporär nur weniger ausgeprägte Folgen in Bezug auf die Verdauung 
                        nach sich ziehen und deshalb unentdeckt bleiben. Bleiben diese Dysfunktionen jedoch bestehen oder verstärken sich sogar, merkt man dies unweigerlich an den verschiedensten 
                        Verdauungsstörungen. Zudem beeinträchtigt eine mangelhafte Funktion einer Verdauungskomponente oft nach und nach auch alle anderen Organe, so dass dies nur den Beginn einer 
                        immer größer werdenden Problematik darstellt und deshalb möglichst frühzeitig entdeckt und behandelt werden sollte.
                        <br />
                        <br />
                        Das Problem ist aber meistens, dass man Verdauungsprobleme zunächst nicht mit Funktionseinschränkungen der Verdauungsdrüsen in Verbindung bringt und &ndash; oft in Eigenregie 
                        &ndash; an den falschen Stellschrauben dreht. Dies ist mit ein Grund, warum die Hersteller von Abführmitteln, Säureblockern (Protonenpumpenhemmern) und unzähligen 
                        Nahrungsergänzungsmitteln viel Geld verdienen, ohne dass dies den Betroffenen wirklich hilft.
 

                        <br />
                        <br />
                        <a id="verbesserungen"></a>
                        <hr />
                        <h5>Maßnahmen zur Verbesserung der Leistungsfähigkeit der Verdauungsdrüsen</h5>
                        <hr />
                        Selbstverständlich kann ein Arzt mit Hilfe von Blut- und Stuhltests viele Parameter ermitteln, die die Leistungsfähigkeit der Verdauungsdrüsen anzeigen. Es ist aber auch 
                        überhaupt nicht falsch, bei Verdauungsproblemen <b>immer</b> auch an die Verdauungsdrüsen zu denken und mit verschiedenen Hausmitteln <b>vorbeugend</b> die Leistungsfähigkeit 
                        anzuregen und zu verbessern.
                        <br />
                        <br />
                        Schon vor knapp 2500 Jahren sagte der griechische Arzt Hippokrates: &#187;<b>Eure Nahrungsmittel sollen eure Heilmittel sein und eure Heilmittel sollen eure Nahrungsmittel 
                        sein</b>&#171; und u.a. mit der richtigen Auswahl von Nahrungsmitteln kann man gerade in Bezug auf die Verdauungsdrüsen sehr, sehr viel erreichen. Leider enthält aber 
                        unsere heutige Nahrung in den meisten Fällen nicht mehr die Bestandteile, die heilend auf unsere Verdauungsdrüsen wirken können. Deshalb ist es wichtig, einmal den Blick 
                        auf bestimmte Lebensmittel zu lenken, die die Leistungsfähigkeit der Verdauungsdrüsen steigern können.
                        <br />
                        <br />
                        Allen voran sind hier die <b>Bitterstoffe</b> zu nennen, die die Tätigkeit der Speicheldrüsen im Mund und von Leber, Galle und Bauchspeicheldrüse anregt. Wenn sie 
                        bittere Nahrungsmittel verzehren, merken Sie gleich, dass die Speichelproduktion steigt. Den bitteren Geschmack assoziiert der Körper mit &#187;schädlich&#171; oder 
                        sogar &#187;giftig&#171;, und solche Stoffe sollen schnellstmöglich unschädlich gemacht und rasch durch das Verdauungssystem hindurch geschleust und ausgeschieden werden. 
                        <br />
                        <br />
                        Da der bittere Geschmack jedoch auch vom Essenden weniger geschätzt wird, haben die Agrarwissenschaftler ihn aus den meisten Lebensmitteln herausgezüchtet. Musste man früher 
                        noch aus Chicorée unten einen Keil herausschneiden, in dem sich besonders viele Bitterstoffe ansammelten und die Chicoréeblätter wässern, um den bitteren Geschmack ein 
                        wenig zu mildern, so ist dies bei den neueren Züchtungen nicht mehr erforderlich. Auch Spargel schmeckt heute nicht mehr bitter, sondern &#187;mild&#171;, (was in meinen 
                        Augen eher langweilig bedeutet).
                        <br />
                        <br />
                        Glücklicherweise müssen es trotzdem keine Nahrungsergänzungsmittel sein, mit denen man sich heute seine Portion Bitterstoffe zuführen kann. Es gibt immer noch reichlich 
                        Lebensmittel, die Bitterstoffe enthalten und mit denen man seinen Verdauungsdrüsen ein wenig auf die Sprünge helfen kann: Es gibt <b>Brokkoli, Rosenkohl, Endivien, Radicchio, 
                        Rucola, Löwenzahn, Artischocke, Grapefruit, Pfefferminze und Schafgarbe</b>, die man in den Speisezettel einbauen oder als Tee zubereiten kann und viele Kräuter wie <b>Thymian, 
                        Majoran, Oregano, Liebstöckel, Sauerampfer, Lorbeer und Rosmarin</b>, mit denen man seine Gerichte schmackhafter &ndash; und bitterstoffreicher &ndash; machen kann. Und 
                        übrigens: auch das bereits erwähnte Feierabendbier enthält durch den zur Herstellung erforderlichen Hopfen Bitterstoffe. Ob allerdings die Anregung durch die Bitterstoffe 
                        oder die Belastung durch den enthaltenen Alkohol schwerer wiegt, ist die Frage &ndash; es wird wohl immer die Menge ausschlaggebend sein. Vielleicht ist aber grundsätzlich 
                        die alkoholfrei Variante die bessere Wahl.
                        <br />
                        <br />
                        Einer der vielen Grundsätze der traditionellen chinesischen Medizin (TCM) ist es zum Beispiel, mit jedem Gericht, das man zubereitet, immer Komponenten aller 
                        Geschmacksrichtungen (süß, sauer, bitter, scharf und salzig) beizufügen. Dies hat durchaus seine Berechtigung, denn jede der Geschmacksrichtungen regt das gesunde Zusammenspiel 
                        aller Verdauungsorgane an. Versuchen Sie doch einmal, in jedem Gericht wenigstens eine winzig kleine Menge von Zutaten mit den verschiedenen Eigenschaften beizufügen &ndash; 
                        es sollte natürlich in den Gesamtgeschmack passen und nicht herauszuschmecken sein.
                        <br />
                        <br />
                        Ganz wichtig ist es auch, die Nahrung <b>ausreichend zu kauen</b>. Nicht nur durch den Geschmack, auch durch die Kaubewegungen werden die Speicheldrüsen angeregt, viel 
                        Speichel zu produzieren &ndash; der erste Schritt in einem guten Verdauungsprozess. Oder nein, das stimmt nicht ganz, denn bereits das Anschauen und Vorbereiten der 
                        Speisen lässt einem &#187;das Wasser im Mund zusammenlaufen&#171;. Gehen Sie deshalb sowohl bei der Zubereitung als auch bei Essen achtsam vor, damit nicht nur die 
                        Speicheldrüsen im Mund, sondern auch alle anderen Verdauungsdrüsen bereits vor und spätestens gleich zu Beginn der Mahlzeit angeregt werden.
                        <br />
                        <br />
                        Ebenso wichtig ist darüber hinaus eine <b>ausreichende Flüssigkeitszufuhr</b> und dabei natürlich die richtige Auswahl der Getränke. Das Non plus ultra ist und bleibt 
                        Wasser &ndash; es versorgt den Körper mit Flüssigkeit ohne jegliche weiteren Makronährstoffe (Eiweiß, Fett und Kohlenhydrate). Je nach Herkunft kann es mehr oder weniger 
                        Mineralstoffe in verschiedenen Zusammensetzungen enthalten, die u.U. auch verdauungsanregende Wirkungen haben können. Für eine reibungslose Verdauung und für eine Entlastung 
                        der Verdauungsdrüsen ist eine ausreichende Flüssigkeitszufuhr wichtig.
                        <br />
                        <br />
                        Wie bei den meisten anderen Körperfunktionen ist es auch für die Funktion aller Verdauungsdrüsen sehr vorteilhaft, sich <b>sportlich zu betätigen</b>. Durch die Bewegung 
                        und die daraus folgende »Massage« der inneren Organe wird die Durchblutung gefördert. Die sportliche Betätigung bewirkt darüber hinaus eine tiefere Atmung, was eine bessere
                        Sauerstoffversorgung der Organe zur Folge hat. Dies kann dazu beitragen, u.a. auch die Funktion zu optimieren. In dem Beitrag 
                        &#187;<a href="coronaverdauung" target="_blank">Verdauung in der Corona-Krise</a>&#171; gibt es den Abschnitt 
                        &#187;<a href="coronaverdauung#uebungen" target="_blank">Atem- und Dehnungsübungen</a>, die auch als ausgezeichnete Hilfe für die Verdauungsdrüsen dienen können. 
                        Probieren Sie das doch einmal aus.
                        <br />
                        <br />
                        Und last but not least hilft es, eventuelle psychische Belastungen durch ein kluges <b>Stressmanagement</b> zu regulieren. Jedes Stresserlebnis belastet auch alle Organe 
                        &ndash; auch die Verdauungsdrüsen. Mit Entspannung können Sie nicht nur Ihre Psyche stabilisieren, sondern tun gleichzeitig auch etwas für die Verdauungsdrüsen. Als besonders 
                        wirksam hat sich hier eines der bewährten Naturheilverfahren, der <b>Leberwickel</b> erwiesen, mit dem Sie neben der Leber auch alle anderen Verdauungsdrüsen anregen und 
                        gleichzeitig dabei auch wunderbar entspannen können. Eine Anleitung finden Sie im &#187; &#187;<a href="lexikon-naturheilmethoden" target="_blank">Lexikon der 
                        Naturheilmethoden</a>&#171;.
                        <br />
                        <br />
                        Wie so oft, führt bei Problemen eine isolierte Betrachtung eines einzigen Organes selten zum Erfolg. Es ist immer die <b>ganzheitliche Betrachtung</b> aller Komponenten, die 
                        zielführend ist. Aus diesem Grunde sollten Sie sich qualifiziert beraten lassen, um Verdauungsprobleme entweder gar nicht erst entstehen zu lassen oder bei (noch) kleinerer 
                        Ausprägung die Ursachen schon im Anfang richtig erkennen und beheben zu können. 


 

