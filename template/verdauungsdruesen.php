                        <br />
                        <a id="bauchspeicheldruese"></a>
                        <hr />
                        <h5>Die Bauchspeicheldrüse</h5>
                        <hr />
                        Die Bauchspeicheldrüse (Fachbegriff Pankreas) (<i>in der oberen Abbildung mit der Nummer 6 gekennzeichnet</i>) ist ein Organ, das vielen Laien kaum bekannt ist. Herz, Lunge und Magen sind bekannt und zumindest auch deren ungefähre Lage 
                        im Körper. Aber wo, bitte, liegt die Bauchspeicheldrüse? Dieses etwa 20cm lange Organ liegt quer im Oberbauch zwischen Leber, Milz und Magen. 
                        <br />
                        <br />
                        Der Pankreas hat zweierlei Funktionen: Zum einen <b>werden Hormone gebildet</b> und ins Blut abgegeben (endokrine, nach innen abgebende Produktion). Das bekannteste Hormon ist 
                        das <b>Insulin</b>, das in speziellen Zellen der Bauchspeicheldrüse, den Langerhans’schen Inseln gebildet wird und zusammen mit dem Glucagon den Blutzuckerspiegel reguliert.
                        <br />
                        <br />
                        Zum anderen werden in der Bauchspeicheldrüse über einen Verbindungsgang direkt in den Dünndarm <b>Enzyme abgegeben</b>, mit denen <b>Eiweiß, Fette und Kohlenhydrate aufgespalten</b> 
                        und verarbeitet werden können (und da der Darminhalt keineswegs die innere, sondern die Außenwelt des Körpers darstellt, ist dies eine exokrine, nach außen abgebende Produktion).
                        Bitte lesen Sie hierzu auch den Beitrag 
                        &#187;<a href="ganz-pankreas" target="_blank">Funktionsstörungen der Bauchspeicheldrüse als Ursache von Verdauungsbeschwerden</a>&#171;. 
 

