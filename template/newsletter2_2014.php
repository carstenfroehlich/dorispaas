                        <br />
                        All denjenigen, die entweder in den vergangenen Wochen &#187;&uuml;ber 
                        die Str&auml;nge geschlagen haben&#171; oder aber f&uuml;r alle, die die 
                        Fastenzeit ernst nehmen, empfehle ich den Beitrag zum Thema <b>Fasten</b>.
