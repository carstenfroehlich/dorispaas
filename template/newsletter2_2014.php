                        die Vorgehensweise unterscheidet sich aber nicht, wenn man einfach &#187;nur&#171; 
                        deshalb fasten will, um sich von altem Ballast &ndash; sei es angefuttertem oder 
                        psychischem Ballast &ndash; befreien m&ouml;chte. Auf jeden Fall werden es Ihnen 
                        Ihr gesamtes Verdauungssystem, Ihre Darmflora und auch Ihre Seele danken, wenn 
                        Sie nach Zeiten des &Uuml;berflusses einige Fastentage einlegen. Beachten Sie dabei
                        aber unbedingt den Warnhinweis, f&uuml;r wen das Fasten geeignet ist und f&uuml;r wen nicht.
