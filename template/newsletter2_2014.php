                        Liebe Leserin, lieber Leser.
                        <p>
                        Nein, das war wirklich kein richtiger Winter. Alle, die den Schnee lieben, sind (zumindest 
                        bis jetzt) leider nicht auf ihre Kosten gekommen. Die Karnevals-Jecken hier im 
                        Rheinland jedoch wird es gefreut haben: strahlender Sonnenschein und angenehme 
                        Temperaturen haben sicherlich den einen oder anderen vor Erk&auml;ltungen und 
                        Blasenentz&uuml;ndungen bewahrt. 
                        <br />
                        Meine Empfehlung f&uuml;r Sie aus dem letzten Newsletter, Ihr Immunsystem vielleicht 
                        mit einem t&auml;glichen Spaziergang zu st&auml;rken, um so gesund durch den Winter zu kommen, 
                        war vor diesem Hintergrund nur scheinbar obsolet. Denn auch &ndash; oder gerade &ndash;, wenn das Wetter Kapriolen 
                        schl&auml;gt und der Fr&uuml;hling nun scheinbar richtig Einzug h&auml;lt, ist 
                        es immer sinnvoll, an ein robustes Immunsystem zu denken. 
                        <br />
                        Insbesondere Menschen, die Probleme mit ihrer Verdauung haben, sollten neben der 
                        Bedeutung von Bewegung an der frischen Luft aber auch immer 
                        daran denken, dass der gr&ouml;&#223;te Teil unseres Immunsystems im Darm angesiedelt 
                        ist. Eine ad&auml;quate Ern&auml;hrung hilft nicht nur, Sie  
                        vor Erk&auml;ltungserkrankungen zu sch&uuml;tzen, sondern st&auml;rkt 
                        auch Ihre Darmflora. So k&ouml;nnen nicht nur die Symptome minimiert werden, die durch Ihre 
                        Nahrungmittel-Unvertr&auml;glichkeiten bedingt sind, sondern eben auch Ihr Immunsystem stabilisieren.
