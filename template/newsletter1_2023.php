                       <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2023-01-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Oftmals kommen Klienten mit Verdauungsproblemen in meine <a href="http://www.dorispaas.de/beratung" target="_blank">Praxis</a>, die bereits eine (jahre-)lange Odyssee hinter 
                        sich haben. Sie haben viele &Auml;rzte, Heilpraktiker und Ern&auml;hrungsberater aufgesucht, zahlreiche, teils belastende und auch sehr kostentr&auml;chtige Untersuchungen 
                        vornehmen lassen und sind letztendlich doch keinen Schritt weitergekommen. Auch das stundenlange, aufmerksame Verfolgen von Beitr&auml;gen in einschl&auml;gigen 
                        Internetforen hat keine wirklichen Erkenntnisse gebracht und die Symptome nicht lindern k&ouml;nnen. Die vielen Versuche mit den dort propagierten Mitteln haben 
                        die Situation entweder nicht oder nicht dauerhaft verbessern k&ouml;nnen &ndash; wenn diese sich nicht sogar noch verschlimmert hat. Letzteres liegt mit Sicherheit 
                        auch daran, dass die in den Foren gegebenen Ratschl&auml;ge, die in der Regel von (wenn auch manchmal informierten) Laien gegeben werden, f&uuml;r diese Menschen selbst zwar 
                        vielleicht hilfreich gewesen sind, f&uuml;r die Ratsuchenden aber keineswegs passen m&uuml;ssen. Ein weiterer Grund kann sein, dass die bisherigen Berater f&uuml;r 
                        Sie bzw. f&uuml;r Ihr Problem nicht die passenden Kompetenzen mitgebracht haben. Deshalb m&ouml;chte ich mich Ihnen heute mit meiner Arbeit vorstellen und Ihnen 
                        erl&auml;utern, warum es ein sinnvolles Behandlungskonzept braucht und wie ein solches Konzept aussehen muss, um Erfolg zu versprechen.
