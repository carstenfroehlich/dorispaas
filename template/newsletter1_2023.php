                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ggb-behandlungskonzept" target="_blank">Schwerpunktthema: Bausteine (m)eines erfolgreichen Behandlungskonzepts</a></b>
                        <br />
                        <i>(Menü: Praxis/Bausteine (m)eines erfolgreichen Behandlungskonzepts)</i>
                        <br />
                        Zu jeder Behandlung von Krankheiten und deren Symptomen geh&ouml;rt immer ein individuell ausgearbeitetes Konzept mit verschiedenen Bausteinen, um erfolgreich und 
                        m&ouml;glichst dauerhaft wirken zu k&ouml;nnen. Es gibt keine Null-acht-f&uuml;nfzehn-Behandlung f&uuml;r alle und jeden, denn was bei dem einen wirkt, muss beim 
                        anderen mitnichten passen &ndash; die Ursachen f&uuml;r ein Problem sind immer 
                        individuell. Genauso individuell, wie die k&ouml;rperlichen Voraussetzungen sind, auf deren Basis Mittel wirken sollen. Und nicht zu vergessen sind die individuellen 
                        M&ouml;glichkeiten und die Akzeptanz für Ma&#223;nahmen, so dass eine Vorgehensweise, die f&uuml;r den einen optimal ist, f&uuml;r den anderen aber v&ouml;llig 
                        unannehmbar sein kann. Neben der Erfahrung des Beraters ist auch eine vertrauensvolle und konstruktive Zusammenarbeit mit dem Patienten oder Klienten erforderlich. 
                        Ein Behandlungskonzept, das seinen Namen verdient, besteht also nicht nur aus verschiedenen, f&uuml;r das Problem geeigneten Mitteln und Ma&#223;nahmen, sondern es muss 
                        immer ganz individuell nur f&uuml;r die eine betroffene Person zugeschnitten werden. 
