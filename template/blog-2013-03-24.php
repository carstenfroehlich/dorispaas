                        <h5>Laktoseunvertr&auml;glichkeit: Kampf mit dem Milchzucker</h5>
                        <br />
                        Mein Kommentar (in der Kommentarliste unter den Nummern 76 und 77):<br />
                        <br />
                        &#187;Es ist schade, dass hier offensichtlich immer wieder einer vom anderen abschreibt, 
                        ohne wirklich einmal selbst korrekt zu recherchieren, bzw. ohne die wirklich 
                        relevanten Tatsachen herauszustellen und den weniger wichtigen den ihnen zustehenden 
                        Stellenwert zuzuweisen. Gerade vom Spiegel h&auml;tte ich mir hier Sorgfalt gew&uuml;nscht.
                        <br />
                        <br />
                        Ja, es ist richtig, dass die meisten Menschen auf der Welt laktoseintolerant sind 
                        und wir hier bei uns &#187;nur&#171; aufgrund einer Genver&auml;nderung den Milchzucker 
                        (Laktose) auch noch im Erwachsenenalter vertragen. Somit ist schon einmal 
                        klargestellt, dass weder das eine (Laktosetoleranz) noch das andere (Laktoseintoleranz) 
                        besser oder schlechter ist oder gar einen Krankheitswert hat. Es beschreibt 
                        lediglich eine Eigenschaft &ndash; so wie beispielsweise die braune oder blaue Augenfarbe. 
                        <br />
                        <br />
                        V&ouml;lliger Unsinn ist es jedoch zu behaupten, &#187;dass nach einigen Wochen 
                        Gew&ouml;hnung sogar Menschen mit einer Laktoseunvertr&auml;glichkeit Milchprodukte 
                        in Ma&#223;en problemlos essen k&ouml;nnen&#171;. Es ist korrekt, dass in der 
                        individuellen Vertr&auml;glichkeit angemessenem Ma&#223;e (!) verzehrter Milchzucker 
                        die rudiment&auml;re Laktaseproduktion l&auml;nger aufrecht zu erhalten hilft &ndash; den 
                        kontinuierlichen Niedergang jedoch kann das letztendlich jedoch nicht aufhalten. 
                        Und was ist schon &#187;individuell angemessen&#171;? Diese eigene Grenze zu 
                        kennen, ist schon für den aufgekl&auml;rten Laktoseintoleranten nicht einfach. Und 
                        ganz klar gilt: Verzehrt man zu viel Laktose, also mehr als die individuelle Grenze 
                        zul&auml;sst, ist dies in jedem Falle nicht nur sehr unangenehm, sondern definitiv 
                        sch&auml;dlich, denn dadurch wird u.a. die gesunde Balance der Darmflora gesch&auml;digt 
                        (mit allen daraus resultierenden Folgen). 
                        <br />
                        <br />
                        Zu behaupten, der Verzehr von Milchzucker w&uuml;rde die Laktose-Intoleranz verbessern 
                        oder &ndash; wie ein leider sehr bekannter Medizinjournalist in einem seiner 
                        B&uuml;cher tats&auml;chlich behauptet &ndash; gar &#187;heilen&#171; zu k&ouml;nnen, 
                        ist noch gr&ouml;&#223;erer Unfug. Ob dieser Autor hier vielleicht von der 
                        Milchindustrie gesponsert wird, die nicht m&uuml;de wird zu behaupten, dass der 
                        Verzehr von Milch unerl&auml;sslich f&uuml;r die Kalziumversorgung sei, vermag ich 
                        nicht zu beurteilen. Ich gebe in diesem Zusammenhang jedoch zu bedenken, dass die 
                        (fast) korrekt in diesem Spiegel-Beitrag wiedergegebenen 2/3 der Weltbev&ouml;lkerung, 
                        die laktoseintolerant sind (nach meinen Informationen sind es etwa 85%) und die 
                        eben keine oder nur weniger (in diesem Falle dann durch sorgf&auml;ltige Verg&auml;rung 
                        laktosefrei gemachte) Milchprodukte verzehren, nicht samt und sonders schw&auml;chlich 
                        und kr&auml;nklich und mit Kalzium unterversorgt sind. Somit muss es klar sein, 
                        dass es au&#223;er Milch noch ausreichend andere Kalziumquellen gibt &ndash; insbesondere 
                        in unserer &Uuml;berflussgesellschaft!
                        <br />
                        <br />
                        Den immer wieder suggerierten Krankheitswert (wenn man es denn so bezeichnen m&ouml;chte) 
                        bekommt die Laktoseintoleranz erst, wenn trotz allem Milchzucker verzehrt wird und 
                        dieser Beschwerden bereitet, weil die (nat&uuml;rlicherweise) im D&uuml;nndarm 
                        nicht oder nicht ausreichend vorhandene Laktase die Milchzuckerbausteine nicht 
                        aufspalten kann, und die Laktose dann im Dickdarm von den Darmbakterien vergoren 
                        wird, wobei Gase und S&auml;uren entstehen. Selbstverst&auml;ndlich gibt es 
                        Abstufungen, und bei manchen Menschen wird noch mehr oder weniger eigene Laktase 
                        gebildet, was zur Vertr&auml;glichkeit mehr oder weniger kleiner Laktose-Mengen 
                        f&uuml;hrt. Diese sind jedoch mit den 12g, die in diesem Beitrag ziemlich pauschalisiert 
                        genannt werden, sehr h&auml;ufig zu hoch angegeben und eben doch sehr individuell. 
                        Somit ist es f&uuml;r Menschen mit Laktose-Intoleranz sehr vorteilhaft, laktosefreie 
                        Produkte kaufen zu k&ouml;nnen.
                        <br />
                        <br />
                        Hier sollte ein guter Pressebeitrag ansetzen: Laktoseintolerante Menschen empfinden 
                        es als eine Erleichterung, wenn Nahrungsmittel als laktosefrei gekennzeichnet sind! 
                        Bedauerlich ist es nur, dass dies &uuml;berhaupt erforderlich ist, denn normalerweise 
                        geh&ouml;rt der Milchzucker in Nahrungsmittel, die keine Milchprodukte sind, 
                        &uuml;berhaupt nicht hinein. Erst die Praxis der Nahrungsmittelhersteller, Milchzucker 
                        in alle m&ouml;glichen und unm&ouml;glichen Nahrungsmittel zu panschen, macht es 
                        erforderlich, ganz normale Produkte zu kennzeichnen, in denen man eigentlich 
                        niemals Laktose vermuten w&uuml;rde.
                        <br />
                        <br />
                        Und diese dann auch noch teurer als die naturgem&auml;&#223; belassenen zu verkaufen, 
                        ist ein weiterer Kritikpunkt, der zu gro&#223;em Unmut Anlass geben sollte. Und 
                        besonders &auml;rgerlich ist, dass es wahrscheinlich genau diese Hersteller sind, 
                        die mit ihrem Verhalten den Verbraucher in dem Glauben unterst&uuml;tzen &ndash; 
                        oder diesen Glauben zumindest nicht gerade r&uuml;cken &ndash; dass laktosefreie 
                        Produkte einen h&ouml;heren Gesundheitswert h&auml;tten als laktosehaltige. Hier 
                        sollte ein seri&ouml;ser Presse-Beitrag einmal einhaken.
