                                <td class="q">
                                    primäre <br />Laktose-Intoleranz
                                </td>
                                <td class="a">
                                    Laktose-Intoleranz, die auf den Erbanlagen festgelegt ist. Bis zum Ende der 
                                    Stillzeit wird Laktase im Darm produziert, um den Milchzucker aus der 
                                    Muttermilch aufspalten und verdauen zu können. Im späteren 
                                    Kindesalter und im Erwachsenenalter wird die Laktase-Produktion mehr 
                                    und mehr heruntergefahren. 85-90% der Weltbevölkerung sind laktoseintolerant. 
                                    Wird - wie in den den Ländern mit hohem Anteil &ndash; nach dem Abstillen 
                                    keine Milch oder keine Milchprodukte ohne eine laktosespaltende Behandlung 
                                    (Sauermilchprodukte) mehr verzehrt, so treten keinerlei Beschwerden auf 
                                    (siehe Laktosemaldigestion). Erst wenn Milchzucker verzehrt wird wie 
                                    in den nördlichen Regionen üblich, treten Beschwerden auf.
