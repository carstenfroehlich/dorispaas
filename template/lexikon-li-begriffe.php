                                    kongenitaler Laktasemangel
                                </td>
                                <td class="a">
                                    selten auftretende Form einer bei Säuglingen auftretenden 
                                    absoluten Unfähigkeit, Laktase zu bilden (congenital lactase 
                                    deficiency, CLD). Auch als kongenitale Alaktasie bezeichnet. Diese 
                                    erbliche Erkrankung ist nicht heilbar. Die Säuglinge müssen 
                                    mit streng laktosefreier Nahrung aufgezogen werden, um gedeihen zu können.
                                    <br />Unter Eltern betroffener Säuglinge verdichtet sich jedoch 
                                    die Vermutung, dass diese Erkrankung gar nicht so selten ist. Es 
                                    wird erfolgreich praktiziert, den Säuglingen bereits beim 
                                    Stillen Laktase zu verabreichen, wordurch eine beschwerdefreie 
                                    Ernährung auch mit Muttermilch möglich ist. Es gibt leider 
                                    nur sehr wenige Kinderärzte, die über diese Problematik 
                                    Bescheid wissen, weshalb sie dann in den meisten Fällen zum 
                                    sofortigen Abstillen und der Fütterung von laktosefreier 
                                    Spezialnahrung raten.
