                        <b>Eigentlich kaum zu bewerten</b>
                        <br />
                        <br />
                        Eigentlich ist das Buch &#187;Reflux 2.0&#171; kaum zu bewerten, denn die Qualität von Inhalt und Ausführung klaffen meilenweit auseinander.
                        <br />
                        <br />
                        Vier Sternchen für den Inhalt des Buches:
                        <br />
                        Es sind zahlreiche sehr gut recherchierte Informationen aufgeführt &ndash; sowohl die Hintergründe als auch die Tipps decken aus meiner Sicht 
                        alles ab, was man als Betroffener zum Thema wissen sollte. Wenn man davon absieht, dass die Erklärung der Zusammenhänge gelegentlich besser 
                        auf die Zielgruppe &ndash; die Laien &ndash; hätte zugeschnitten werden müssen, lernt man viel zu dem interessanten Gesamtkomplex.
                        <br />
                        Als negatives Beispiel möchte ich hierzu die Aufzählungen der Verläufe der verschiedenen Muskeln, die am Sitzen beteiligt sind (Seite 203ff) anführen: 
                        diese sind kaum zu verstehen, wenn man nicht die komplette Anatomie und jeden einzelnen Muskel und deren Zusammenspiel kennt. Vielleicht hätten Bilder 
                        hier zur Verdeutlichung beigetragen – diese muss sich der interessierte Leser aus dem Internet suchen.
                        <br />
                        Sehr hinderlich beim Erfassen des Inhalts sind auch die viel zu häufig eingefügten Links auf die Website der Verfasserin. Ja, wenn eine Ausführung den 
                        Umfang eines Buches sprengen würde, kann der eine oder andere Link auf weiterführende Informationen richtig und legitim sein. Wenn dieses Mittel aber 
                        zu häufig verwendet wird, macht das das Lesen eines Textes sehr beschwerlich. Ein Print-Medium ist halt etwas anderes als ein online-Medium &ndash; ich 
                        zweifle an, dass der Autorin der Unterschied wirklich klar ist.
                        <br />
                        Nichts destotrotz hätte ich für den Inhalt eigentlich vier Sterne vergeben wollen, denn insgesamt ist das Buch sehr informativ. Somit wäre das Buch 
                        (mit nur ganz wenigen Abstrichen) vom Inhalt her durchaus empfehlenswert.
                        <br />
                        <br />
                        Kein einziges Sternchen für die Ausführung des Buches:
                        <br />
                        Zunächst fällt gleich beim ersten Aufklappen auf, dass die Schriftgröße (16 Punkt!) dazu führt, dass das Buch nicht wirklich fast 500 Seiten stark ist (wie 
                        die Verfasserin stolz betont), sondern bei normaler Schriftgröße einen wesentlich kleineren Umfang haben müsste. Aber geschenkt &ndash; immerhin ist der Text 
                        so bestimmt selbst bei Einschränkungen des Sehvermögens mühelos lesbar.
                        <br />
                        Was ich aber sehr viel hinderlicher in Bezug auf den Lesefluss finde, ist die unterirdische Interpunktion und Grammatik. Nach welchen Gesichtspunkten die 
                        Kommata gesetzt wurden, entzieht sich zumindest meinem Verstand – nicht etwa, dass an der ein oder anderen Stelle mal ein Komma fehlt oder zu viel ist. Nein, 
                        sie sind offensichtlich willkürlich und überreichlich wie mit dem Salzstreuer verteilt. So werden oftmals Sätze ziemlich unverständlich, weil man den Inhalt 
                        durch die unvermittelten Trennungen oder Zusammenziehungen erst nach dem zweiten oder dritten Lesen erfassen kann.
                        <br />
                        Die Qualität der Grammatik ist ebenfalls einer Verfasserin unwürdig, die ihren Beruf mit &#187;Chefredakteurin eines renommierten Gesundheitsblogs&#171; angibt. 
                        Groß- und Kleinschreibung sind scheinbar beliebig gewählt &ndash; es gibt so gut wie keinen fehlerfreien Satz in diesem Buch. Es kann doch wohl nicht so schwer 
                        sein, sich an die ersten Grundlagen aus dem Deutschunterricht in der Schule zu erinnern!
                        <br />
                        Hinzu kommen diverse umgangssprachliche Ausdrücke, die zumindest mir nicht geläufig sind. Lockerere Formulierungen können sicherlich durchaus schön sein, und 
                        sie machen das Lesen eher zum Vergnügen als ein trockener Stil &ndash; aber beispielsweise &#187;Pommes Schranke&#171; (als nur ein Beispiel unter vielen) ist für 
                        ein Buch, das ernst genommen werden will, nicht so ganz passend.
                        <br />
                        Und last, but not least, sind viele der verwendeten Bilder für den Buchdruck ungeeignet. Ob sie aus der Website kopiert sind oder einfach nur (wie offensichtlich 
                        das ganze Buch) nicht lektoriert wurden, entzieht sich meiner Kenntnis. Tatsache ist jedoch, dass die Kontraste der durchgängig grobpixeligen, monochromen Bilder
                        so schlecht sind, dass man die Inhalte, die diese Bilder vermitteln sollen, kaum erkennen kann.
