                        Der Titel des Buches &#187;Mikrobiom-Analyse &ndash; verstehen und richtig interpretieren&#171; ist meiner Meinung etwas zu hoch gegriffen. Ja, es gibt dem Laien einige gute 
                        Einblicke in die Thematik: u.a. beantwortet es Fragen wie &#187;was ist überhaupt das Mikrobiom (der korrekte Ausdruck wäre allerdings &#187;Mikrobiota&#171; gewesen)?&#171;, 
