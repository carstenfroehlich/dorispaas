                        unerlässlich, um überhaupt verstehen zu können, was alles in einem Stuhltest abgeprüft werden sollte und warum.
                        <br />
                        <br />
                        Einen großen Teil des Buches nimmt dann das &#187;Who’s Who der Darmbakterien&#171; ein. Dies ist ganz nett, aber die in meinen Augen doch recht willkürliche Auswahl der 
                        Spezies ist für mich nicht wirklich nachvollziehbar, denn die verschiedenen, mir bekannten Stuhltests führen ja überwiegend andere Arten auf. Die von Frau Dr. Axt-Gadermann 
                        ausgewählten erscheinen aber oft auch gar nicht.
                        <br />
                        <br />
                        Als Vorschläge für die Normalisierung von Mikroben, deren Anzahl sich außerhalb der Referenzwerte befindet, führt sie bis auf wenige Ausnahmen an, dass eine gesunde, 
                        Gemüse- und Ballaststoff-reiche Kost die Lösung wäre, wie sie auch sonst bei Mängeln ziemlich generalisierte Vorschläge anbietet. Für ein im Großen und Ganzen gesundes 
                        Verdauungssystem ist dies ganz sicherlich korrekt, aber gerade bei Nahrungsmitte-Intoleranzen sicherlich nicht die Pauschallösung. Hier hätte ich mir eine differenziertere 
                        Betrachtungsweise gewünscht &ndash; aber dies hätte wohl den Umfang des Buches gesprengt. Ein kleiner Hinweis in diese Richtung wäre aber nicht falsch gewesen. 
                        <br />
                        <br />
                        Sehr schön finde ich die kritische Betrachtung und Warnung vor Einläufen und der Colon-Hydro-Therapie, die ich teile. Auch der Hinweis darauf, dass, wenn Probiotika 
