                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=nebenwirkungen" target="_blank">Schwerpunktthema: &#187;Neben- und Wechselwirkungen von Medikamenten und Nahrungs-Erg&auml;nzungsmitteln&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Pr&auml;parate/Neben und Wechselwirkungen von Medikamenten)</i>
                        <br />
                        Dieser Newsletter besch&auml;ftigt sich mit einem Thema, das auch in meiner 
                        <a href="http://www.ganzheitliche-gesundheitsberatung.de/" target="_blank">Beratungspraxis</a> immer wieder zur Sprache 
                        kommt, n&auml;mlich den Neben- und Wechselwirkungen von Medikamenten. Aber auch Nahrungs-Erg&auml;nzungsmittel k&ouml;nnen 
                        insbesondere auch in Verbindung mit Medikamenten &ndash; seien diese vom Arzt verordnet oder rezeptfrei in der Apotheke erworben 
                        &ndash; Probleme bereiten. Es kann ein Vabanquespiel sein, wenn Sie verschiedene Vitamin- und Mineralstoffpr&auml;parate und 
                        weitere Produkte einnehmen, von denen Sie sich eigentlich Gesundheit und mehr Wohlbefinden versprechen. Apothekenpflichtigen 
                        Medikamenten liegt grunds&auml;tzlich der so genannte Beipackzettel mit den Inhaltsstoffen und der Einnahmeempfehlung bei. 
                        Und Sie finden hier die Nebenwirkungen, die dieses Pr&auml;parat auch bei vorschriftsm&auml;&#223;iger Einnahme haben kann.
                        Aber leider gibt es selten Hinweise auf Wechselwirkungen, die in Verbindung mit zus&auml;tzlichen Nahrungs-Erg&auml;nzungsmitteln 
                        auftreten k&ouml;nnen. Und bei den Nahrungs-Erg&auml;nzungsmitteln ist kein Beipackzettel vorgeschrieben, der Sie &uuml;ber die Gefahren 
                        aufkl&auml;ren muss. (Nicht nur) weil bei den Nebenwirkungen gerade die Verdauungsbeschwerden an der Spitze der m&ouml;glichen 
                        Probleme stehen, lohnt es sich, sich mit diesem wichtigen Thema einmal intensiver zu befassen. 
