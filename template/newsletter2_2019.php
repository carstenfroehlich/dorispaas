                        <h5>Ausgabe 45 (März 2019)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-02-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Endlich: Die Fr&uuml;hbl&uuml;her kommen aus der Erde. Schneegl&ouml;ckchen, Krokusse, Osterglocken und M&auml;rzbecher 
                        stehen bereits in voller Bl&uuml;te, und auch die ersten Blausternchen (Szilla), die demn&auml;chst in gro&#223;er Anzahl auf 
                        meinen Gartenwegen erscheinen werden, sind schon zu sehen. Aber auch, wenn Sie selbst keinen eigenen Garten haben, 
                        d&uuml;rfen Sie ungehemmt in fremden G&auml;rten &#187;wildern&#171; und sich sattsehen an dem zauberhaften 
                        Blumenschmuck &ndash; aber bitte nicht pfl&uuml;cken, sondern nur schauen!
                        <br />
                        Mit den kleinen Blausternen, die Sie &uuml;brigens auf dem nebenstehenden Bild betrachten k&ouml;nnen, m&ouml;chte ich Ihnen 
                        etwas sehr Wichtiges erkl&auml;ren: Es m&uuml;ssen nicht immer die gro&#223;en, stolzen Blumen sein, um sich zu erfreuen. 
                        Auch diese kleinen, anspruchslosen Pfl&auml;nzchen, die eine Gr&ouml;&#223;e von kaum 10cm erreichen, k&ouml;nnen einen 
                        so richtig gl&uuml;cklich machen. Was ich damit sagen will? Auch die kleinen Fortschritte, die Sie auf Ihrem Weg zur Besserung 
                        gesundheitlicher Probleme machen, k&ouml;nnen gro&#223;e Erfolge f&uuml;r Sie sein &ndash; Sie m&uuml;ssen sie nur 
                        angemessen w&uuml;rdigen. 
