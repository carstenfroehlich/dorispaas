                        <a id="buchbeschreibung"></a>
                        <h5>Buchbeschreibung:</h5>
                        <hr />
                        <b>Bewegung ist nicht alles, aber ohne Bewegung ist alles nichts.</b> Ein Mangel an Bewegung ist bei allen 
                        Verdauungsbeschwerden mit eine der wichtigsten Ursachen. Ändert man hier etwas und bewegt sich mehr, kann man 
                        nicht nur die Symptome günstig beeinflussen, sondern gleichzeitig eine der wichtigsten Ursachen beheben. 
                        Obwohl eine Sportstunde am Abend oder am Wochenende für die Fitness ausgezeichnet ist, sind <b>kontinuierliche 
                        Bewegungsübungen über den Tag verteilt</b> die beste und wirksamste &#187;Medizin&#171; für den Darm, die es gibt. Die 
                        verbreitete Einstellung, allein die Einnahme von Pillen könne helfen, dass man gesund bleibt oder Krankheiten 
                        lediglich mit diesen Mitteln heilen könnte &ndash; und das auch noch schnell und dauerhaft, ist ein 
                        verhängnisvoller Trugschluss.
                        <br />
                        <br />
                        In diesem Buch finden Sie zahlreiche Atem- und Bewegungsübungen für einen gesunden Darm ohne Verdauungsbeschwerden, und 
                        Strichmenschlein zeigen Ihnen die Bewegungsabläufe. Es gibt aber auch die erforderlichen Erklärungen zu den Zusammenhängen, 
                        denn nur, was man versteht, kann man auch mit Überzeugung und in ausreichendem Maße durchführen &ndash; und durchhalten. 
                        Darüber hinaus sind bestimmte Punkte auf dem Körper dargestellt, die mithilfe der Akupressur stimuliert werden können, 
                        wodurch die Bewegungsübungen ideal ergänzt werden. Weiterhin werden zusätzliche Hilfsmaßnahmen und Hilfsmittel vorgestellt, 
                        die die Behandlung von Verdauungsproblemen effektiv unterstützen. Und last, but not least, gibt es ein Kapitel mit Fragen, 
                        die in meiner Praxis immer wieder zu diesem Themenkomplex gestellt werden. Die Antworten können sicherlich auch Ihnen weiterhelfen.
                        <br />
                        <br />
                        Zusammengenommen haben Sie mit diesem Baukasten zahlreiche Möglichkeiten in der Hand &ndash; und zwar im wörtlichen Sinne in der 
                        eigenen Hand, um Erkrankungen des Verdauungssystems und Beschwerden sowohl symptomatisch als auch ursächlich günstig beeinflussen 
                        oder ihnen sogar wirksam vorbeugen zu können. 
                        <br />
                        <br />
                        &#187;Ein Allheilmittel also?&#171; Nun, alleine heilen diese Maßnahmen Ihre Beschwerden nicht. Aber Bewegung in Kombination 
                        mit der Akupressur und die zusätzlichen Maßnahmen und Hilfsmittel <b>unterstützen</b> die jeweils spezifische Behandlung bei der 
                        Heilung von Verdauungsbeschwerden &ndash; und diese Unterstützung ist unverzichtbar. Ansonsten ist nicht nur die Heilung in 
                        Frage gestellt, es sind auch Rückfälle vorprogrammiert.
                        <br />
                        <br />
                        Auch wenn sich dieses Buch hauptsächlich an Betroffene richtet und im Text zur besseren Verständlichkeit Fachausdrücke weitestgehend 
                        vermieden werden, sollte dieser sorgfältig recherchierte, umfassende Titel aber auch in keiner ärztlichen Praxis und auf keinem 
                        Schreibtisch von Heilpraktikerinnen und Ernährungs- und Gesundheitsberatern fehlen.
