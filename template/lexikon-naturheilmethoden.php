                            <a name="autogenestraining">&nbsp;</a>
                                Autogenes Training
                            </td>
                            <td class="a">
                                <b>Definition: </b>
                                <br />
                                Der Begriff &#187;autogen&#171; bedeutet Selbstbeeinflussung &ndash; 
                                Autogenes Training sind also Übungen, mit denen man durch Selbstbeeinflussung
                                seinen Körper steuern kann. Das Autogene Training ist eine 
                                <a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#entspannungsmethoden" class="faqmenu">Enspannungsmethode</a>,
                                mit der man sich selbst dazu bringen kann, sich trotz Stress zu entspannen 
                                und ruhig zu werden.
                                <br />
                                <br />
                                <b>Wirkungsweise:</b>
                                <br />
                                Beim Autogenen Training werden nacheinander alle Muskelgruppen entspannt, 
                                indem man sich im Geist immer wieder vorsagt &#187;Mein rechter Arm (oder 
                                jede andere Muskelgruppe) ist schwer und warm&#171; oder auch &#187;Mein Atem 
                                ist tief und gleichmäßig&#171;. Nach und nach bewegt man sich gedanklich 
                                durch den ganzen Körper und entspannt so sämtliche Muskeln.
                                <br />
                                Abgeschlossen wird die Übung mit dem vorsichtigen Bewegen der Hände und 
                                Füße, dem anschließenden, genüsslichen Räkeln, dem Öffnen der Augen und 
                                kommt so zum Schluss wieder in der Wirklichkeit an.
                                <br />
                                <br />
                                <b>Indikationen:</b>
                                <br />
                                Bei übermäßigem Stress im Rahmen eines 
                                <a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#stressmanagement" class="faqmenu">Stressmanagements</a>
                                ist es möglich, mit Autogenem Training einen Teil des unvermeidbaren Stress' 
                                zu kompensieren.
                                <br />
                                <br />
                                <b><span style="color: rgb( 255, 83, 83 );">Hinweis: </span></b>  
                                <br />      
                                Am besten erlernen Sie die Technik des Autogenen Trainings unter 
                                fachlicher Anleitung in einem Kurs (z.B. in der Volkshochschule). Anschließend 
                                können Sie zu Hause weiter üben.
                        
