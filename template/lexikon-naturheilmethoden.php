                            <a name="ansteigendefussbaeder">&nbsp;</a>
                                Ansteigende Fußbäder
                            </td>
                            <td class="a">
                                <b>Definition: </b>
                                <br />
                                Die &#187;ansteigenden Fußbäder&#171; tragen wirksam und nachhaltig Wärme 
                                in den Körper.
                                <br />
                                <br />
                                <b>Indikationen:</b>
                                <br />
                                &#149; Schwaches Immunsystem
                                <br />
                                &#149; Hilfe bei häufigen Infekten insbesondere des Nasen-/Rachenraums
                                <br />
                                &#149; Entkrampfung bei Unterleibsproblemen
                                <br />
                                &#149; Erwärmung bei Frieren
                                <br />
                                <br />
                                <b>Durchführung:</b>
                                <br />
                                Sie benötigen eine Kunststoffwanne, in die beide Füße und Beine idealerweise 
                                bis unter die Knie eingetaucht werden können. 
                                <br />
                                Füllen Sie die Wanne mit warmem Wasser (ca. 35°C) und tauchen Sie die Füße 
                                ein. Es sollte sich angenehm warm anfühlen. Nach 5 Minuten füllen Sie vorsichig 
                                eine kleine Menge heißes Wasser hinzu, sodass die Temperatur des Wassers 
                                in der Wanne immer weiter ansteigt. Dies wiederholen Sie, bis die Temperatur des 
                                Wassers in der Wanne gerade noch erträglich ist. 
                                <br />
                                Insgesamt sollte das ansteigende Fußbad etwa 15 Minuten durchgeführt werden. 
                                Danach die Füße gut abtrockenen und anschließend noch etwa 20-30 Mintuten 
                                gut zugedeckt ausruhen. 
                                <br />
                                <br />
                                <b><span style="color: rgb( 255, 83, 83 );">Hinweis: </span></b>  
                                <br />      
                                Achten Sie darauf, sich während und nach dem Fußbad immer warm zu halten.
                        
