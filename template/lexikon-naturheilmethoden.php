                                Feldenkrais-Methode
                            </td>
                            <td class="a">
                                <b>Definition: </b>
                                <br />
                                Die von Dr. Mosche Feldenkrais (1904 &ndash; 1984) entwickelte Methode ist eine 
                                Technik, mit kleinen immer wieder wiederholten Bewegungen Körperhaltungen und 
                                Bewegungsabläufe zu verändern und zu verbessern.
                                <br />
                                Diese Methode wird von ausgebildeten Therapeuten in Kursen oder Einzelstunden gelehrt, 
                                bis man sie nach und nach beherrscht. Es gibt hier kein &#187;falsch&#171; oder 
                                &#187;richtig&#171;, denn für jeden Trainierenden ist es ganz individuell, was er 
                                als vorteilhafter als bisher empfindet. Deshalb greift der Therapeut selten direkt 
                                ein, aber er beobachtet den Probanden und gibt ggf. hilfreiche Tipps.
                                <br />
                                <br />
                                <b>Wirkungsweise:</b>
                                <br />
                                Durch die wiederholten Übungen erlebt der Trainierende, welche positiven Auswirkungen 
                                andere Bewegungsmuster haben und lernt sukzessive, sich anders zu bewegen. Dies wirkt sich 
                                oftmals nicht nur auf eine beübte Muskel- und Gelenkgruppe aus, sondern hat immer auch 
                                Auswirkungen aus angrenzende und häufig sogar weiter entfernt liegende Körperbereiche.
                        
                            </td>
