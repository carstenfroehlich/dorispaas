                                Nasenspülung
                            </td>
                            <td class="a">
                                <b>Definition:</b>
                                <br />
                                Zum Feuchthalten der Nasenschleimhaut eignet sich am besten eine Nasenspülung. 
                                Hierzu benutzt man ein Nasenspülkännchen, das in der Apotheke erhältlich ist. 
                                Die Nasenspülung eignet sich sowohl als Vorbeugung als auch zur Behandlung 
                                von Erkältungserkrankungen, denn es werden nicht nur Beläge und Krankheitserreger 
                                von den Schleimhäuten gespült. Durch die Anfeuchtung wird auch die 
                                Abwehrkraft des nasalen Atemwegs gestärkt.
                                <br />
                                <br />
                                <b>Anleitung:</b>
                                <br />
                                Man füllt das Kännchen mit lauwarmem Wasser, dem man einen mit dem Kännchen 
