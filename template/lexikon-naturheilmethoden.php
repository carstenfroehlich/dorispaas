                            <a name="schuesslersalze">&nbsp;</a>
                                Sch&uuml;&#223;lersalze
                            </td>
                            <td class="a">
                                <b>Wirkungsweise:</b>
                                <br />
                                Die von dem hom&ouml;opathisch arbeitenden Arzt Wilhelm Heinrich 
                                Sch&uuml;&#223;ler (1821-1898) entwickelte Naturheiltherapie mit 
                                Mineralsalzen (Biochemie) basiert auf der Erkenntnis, dass alle Mineralstoffe, 
                                die unsere K&ouml;rper ben&ouml;tigt (z.B. Kalzium oder Kalium), nicht nur in 
                                grobstofflicher Form als Baustoffe ben&ouml;tigt werden, sondern diese 
                                nur vom Organismus aufgenommen werden k&ouml;nnen, wenn sie gleichzeitig 
                                auch in feinstofflicher Form als so genannte Betriebsstoffe vorliegen.
                                <br />
                                Weiterhin m&uuml;ssen alle Mineralstoffe in genau der ben&ouml;tigten Menge 
                                vorhanden sein &ndash; fehlt auch nur ein einziger Stoff bzw. mangelt es an 
                                ihm, so k&ouml;nnen auch die &uuml;brigen Baustoffe nur soweit vom K&ouml;rper 
                                aufgenommen werden, wie es das &#187;schw&auml;chste Glied in der Kette&#171; 
                                erlaubt.
                                <br />
                                Sch&uuml;&#223;ler benutzte 12 verschiedene Salze, die die Mineralien 
                                enthalten, in hom&ouml;opathisch potenzierter Form als Betriebsstoffe, 
                                denn er vertrat die Auffassung, dass nicht die Baustoffe fehlen, sondern 
                                die feinstofflichen Betriebsstoffe.
                                <br />
                                Die nach ihm benannten Sch&uuml;&#223;lersalze werden fast immer in Tablettenform 
                                angeboten &ndash; also in Milchzucker verriebene und potenzierte Wirkstoffe 
                                in den Potenzen D6 und D12. F&uuml;r Menschen mit 
                                Nahrungsmittel-Unvertr&auml;glichkeiten empfehlen sich allerdings eher 
                                Globuli (auf Basis von Saccharose) oder Tropfen (auf Basis von Alkohol), die 
                                man auf Bestellung in der Apotheke erhalten kann.
                                <br />
                                Die 12 Basispr&auml;parate sind von 1 bis 12 durchnummeriert. Die Nachfolger 
                                von Sch&uuml;&#223;ler fanden jedoch noch weitere Verbindungen, die als 
                                die 15 Erg&auml;nzungsmittel im Handel sind (durchnummeriert von 13 bis 27).
                                <br />
                                Die aufgrund von bestimmten Symptomen oder aber auch mit Hilfe der 
                                so genannten &#187;Antlitz-Diagnistik&#171;, bei der bestimme Zeichen im 
                                Gesicht beurteilt werden, ermittelten Defizite werden die entsprechenden
                                Sch&uuml;&#223;lersalze von einem ge&uuml;bten Berater 
                                verordnet. Nebenwirkungen bei einer 
                                Therapie mit Sch&uuml;&#223;lersalzen sind so gut wie ausgeschlossen, 
                                jedoch ist es nat&uuml;rlich wichtig, m&ouml;glichst gleich die erforderlichen 
                                Pr&auml;parate zu finden, um eine rasche Wirkung zu erzielen.
                                <br />
                                <br />
                                <b>Indikationen:</b>
                                <br />
                                S&auml;mtliche Befindlichkeitsst&ouml;rungen k&ouml;nnen mit Sch&uuml;&#223;lersalzen 
                                behandelt bzw. deren schulmedizinische Therapie erg&auml;nzt werden. 
                                Insbesondere Verdauungsst&ouml;rungen k&ouml;nnen sehr g&uuml;nstig mit 
                                Sch&uuml;&#223;lersalzen beeinflusst werden.
                        
