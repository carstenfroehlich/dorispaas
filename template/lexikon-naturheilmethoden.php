                            <a name="heilerde">&nbsp;</a>
                                Heilerde
                            </td>
                            <td class="a">
                                <b>Definition: </b>
                                <br />
                                Heilerde besteht aus fein zu Pulver vermahlenen Lössablagerungen aus der 
                                Eiszeit, die getrocknet und mit Hitze keimfrei gemacht werden.
                                <br />
                                Durch die staubfeine Vermahlung erhalten die winzigen Körnchen insgesamt eine 
                                riesige Oberfläche und haben dadurch eine extrem hohe Bindungskraft. Aufgrund 
                                dieser Eigenschaften ist Heilerde in der Lage, Magensäure, Giftstoffe 
                                oder auch Krankheitserreger wie z.B. Bakterien aufzunehmen und 
                                zu binden.
                                <br />
                                Heilerde kann sowohl innerlich als auch äußerlich verwendet werde, d.h. 
                                beispielweise bei Sodbrennen oder Durchfällen als Lösung zum Einnehmen 
                                oder auch bei unreiner Haut und Akne als Lösung zum Auftupfen.
                                <br />
                                Die eingenommene Heilerde wird nicht vom Körper aufgenommen. Die an die 
                                Heilerde gebundenen Stoffe werden vom Verdauungssystem wieder ausgeschieden.
                                <br />
                                <br />
                                <b>Anwendung: </b>
                                <br />
                                Heilerde-Pulver (z.B. Luvos Heilerde) nach Gebrauchanleitung in Wasser 
                                einrühren und die Lösung auf die Haut auftupfen bzw. trinken. Die Anwendung 
                                so lange fortsetzen, bis die Beschwerden abgeklungen sind. Zur Sicherheit 
                                die Behandlung noch einige Tage darüber hinaus fortführen.
                                <br />
                                <br />
                                <b><span style="color: rgb( 255, 83, 83 );">Wichtig: </span></b>
                                <br />
                                Beachten Sie bitte, dass vor oder nach der Einnahme von Medikamenten ein zeitlicher 
                                Abstand von 2 Stunden eingehalten werden muss, wenn Sie Heilerde einnehmen. 
                                Anderenfalls werden die Arzneistoffe von der Heilerde gebunden und können 
                                im Körper nicht oder nicht ausreichend wirken. 
                                <br />
                                <br />
                                <b><span style="color: rgb( 255, 83, 83 );">Achtung: </span></b>
                                <br />
                                Bei lang anhaltenden, heftigen Durchfällen und vor allem auch bei blutigen 
                                Stühlen ist unbedingt ein Arzt aufzusuchen.
                        
                            </td>
