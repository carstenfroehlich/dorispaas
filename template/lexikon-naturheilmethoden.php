                                Heiltee zubereiten oder aber auch trocknen, indem die Pflanzen(teile) zu 
                                kleinen Str&auml;u&#223;chen gebunden und kopf&uuml;ber an einem luftigen 
                                Ort aufgeh&auml;ngt werden. Bitte regelm&auml;&#223;ig auf Schimmelbefall 
