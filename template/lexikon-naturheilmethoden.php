                                ist, den Kopf auf die andere Seite neigen und den Vorgang mit dem zweiten 
                                Nasenloch wiederholen.
                                <br />
                                Anschließend kräftig schnäuzen, um das restliche Wasser aus der Nase
                                zu entfernen.
                                <br />
                                Vorbeugend wendet man die Nasenspülung einmal täglich an. Im Falle einer 
                                Erkrankung kann man die Nase morgens und abends, bei Bedarf auch öfter 
                                spülen.
                                <br />
                                <br />
                                <b>Hinweis: </b>
                                <br />
                                Gerade in der Heizperiode, wenn die Nasenschleimhäute schnell austrocknen, 
                                kommt es bei empfindlichen Menschen oft zu Nasenbluten. Auch hier ist die 
                                Nasenspülung eine gute Vorbeugung. Sie kann aber ganauso gut auch behandelnd, 
                                d.h. blutstillend angewandt werden
