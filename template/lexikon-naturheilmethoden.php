                                Substanzen kommen dabei zum Einsatz. 
                                <br />
                                Bei der Potenzierung wird zuerst ein Teil Ursubstanz mit 9 (D-Potenzen) 
                                bzw. 99 (C-Potenzen) nach ganz bestimmten Mustern verrieben oder versch&uuml;ttelt. 
                                Beim Verreiben werden als Tr&auml;gersubstanzen Milchzucker (f&uuml;r 
                                Tabletten), Haushaltszucker (f&uuml;r Globuli) oder Alkohol f&uuml;r 
                                Tropfen verwendet. Von dieser D1- bzw. C1-Potenz wird wieder ein Teil 
                                zu der entsprechenden Anteilsmenge Tr&auml;gersubstanz hinzugef&uuml;gt, 
                                um die n&auml;chste D- oder C-Potenz zu erzeugen. Mit diesem Prozess 
                                wird solange fortgefahren, bis man die gew&uuml;nschte Potenz erh&auml;lt. 
                                <br />
                                Das von Samuel Hahnemann Ende des 18. Jahrhunderts entwickelte Prinzip 
                                der Hom&ouml;opathie ist es, &#187;&Auml;hnliches mit &Auml;hnlichem zu 
                                heilen&#171; (similia similibus curentur). Hierbei werden Substanzen benutzt, 
                                die in unverd&uuml;nntem Zustand genau die Beschwerden hervorrufen w&uuml;rden, 
                                wie die, die mit der hom&ouml;opathischen Arznei geheilt werden sollen. 
                                Dabei wirkt nicht die Substanz, denn von dieser ist ab einer schon sehr 
                                niedrigen Potenz nichts mehr enthalten. Vielmehr wirkt die Schwingung, 
                                die durch den Potenzierungsprozess auf die Tr&auml;gersubstanz &uuml;bertragen 
                                wurde &ndash; und zwar umso tiefgreifender, je h&ouml;her die Potenz ist.
                                <br />
                                Ein hom&ouml;opathisches Mittel muss nicht nur zur Krankheit, sondern 
                                dar&uuml;ber hinaus auch zum Patienten &#187;passen&#171;. Dies bedeutet, 
                                dass f&uuml;r verschiedene Patienten, die die gleichen Symptome haben, 
                                mitnichten immer das gleiche Mittel wirksam ist. Denn die Hom&ouml;opathie heilt 
                                nicht symptomatisch, sondern regt den K&ouml;rper zur Selbstheilung an. 
                                Es gibt zwar einige probate Mittel, die in vielen F&auml;llen helfen. 
                                F&uuml;r schwerere Erkrankungen und vor allem auch f&uuml;r chronische 
                                Erkrankungen muss immer durch eine zeitintensive Anamnese von einem 
                                Hom&ouml;opathen ermittelt werden, wo die Probleme liegen und welches 
                                das individuell passende Mittel ist.
                                <br />
                                Hom&ouml;opathika werden unterschiedlich eingenommen &ndash; bei akuten 
                                Erkrankungen teilweise in 1/4-st&uuml;ndlichen Abst&auml;nden, bis die 
                                Symptome abklingen. Chronische Erkrankungen werden teilweise mit einer 
                                Gabe alle 2-3 Wochen oder sogar bis zu einem Zeitabstand von 1/2 Jahr 
                                behandelt. 
                                <br />
                                <br />
                                <b><span style="color: rgb( 255, 83, 83 );">Achtung: </span></b>
                                <br />
                                Zur Selbstbehandlung eignen sich ausschlie&#223;lich die niedrigen 
                                Potenzen D4 bis C12, wobei bei urspr&uuml;nglich giftigen Ausgangssubstanzen 
                                unbedingte Vorsicht geboten ist.
                        
