                                des Magens ausgiebig mit den Heilsubstanzen benetzt. Ein weiterer heilsamer 
                                Effekt wird durch die Ruhe erzielt, die durch diese 20 &ndash; 40 Minuten 
                                Hinlegen eingehalten wird.
                                <br />
                                <br />
                                <b>Indikationen und Heilsubstanzen:</b>
                                <br />
                                Magenschleimhautentz&uuml;ndung und Magengeschw&uuml;re: 
                                <br />
                                Sud von gelben Leinsamen (Linusit aus dem Reformhaus)
