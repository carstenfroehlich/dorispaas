                            <a name="bachblueten">&nbsp;</a>
                                Bachbl&uuml;tentherapie
                            </td>
                            <td class="a">
                                <b>Definition: </b>
                                <br />
                                Die in den 1930er Jahren von dem britischen Arzt Edward Bach entwickelte 
                                Bachbl&uuml;tentherapie basiert auf der These, dass alle Krankheiten durch 
                                seelische Ungleichgewichte begr&uuml;ndet seien. Die Heilung dieser 
                                Krankheiten soll daher auf der seelischen Ebene erfolgen und 
                                Gem&uuml;tszust&auml;nde, die zu k&ouml;rperlichen Beschwerden oder 
                                Erkrankungen f&uuml;hren, harmonisieren. 
                                <br />
                                Bach beschrieb verschiedene Gem&uuml;tszust&auml;nde, denen er dann bestimmte 
                                Bl&uuml;ten zuordnete. Diese Bl&uuml;ten wurden und werden noch heute bei 
                                Sonnenaufgang gepfl&uuml;ckt und in frisches Quellwasser gelegt, damit 
                                sie anschlie&#223;end in der Sonne ihre Schwingungen auf 
                                das Wasser &uuml;bertragen konnten. Aus diesen Urtinkturen werden die 
                                Bachbl&uuml;tenessenzen hergestellt, wobei sich Bach in der Verd&uuml;nnung 
                                und Potenzierung an die Erkenntnisse von Samuel Hahnemann und seine 
                                Hom&ouml;opathie anlehnte. 
                                <br />
                                Es gibt 38 urspr&uuml;ngliche Essenzen (die sp&auml;ter durch Sch&uuml;ler 
                                von Bach um zus&auml;tzliche erweitert wurden), die nach ihren englischen 
                                Bezeichnungen alphabetisch durchnummeriert sind. So gibt es beispielsweise 
                                1 &ndash; Agrimony (Odermennig), 2 &ndash; Aspen (Espe), 3 &ndash; Beech 
                                (Rotbuche) usw. 
                                <br />
                                Den einzelnen Bl&uuml;ten sind jeweils grundlegende Gem&uuml;tszust&auml;nde 
                                zugeordnet, ebenso die negativen, seelischen Auspr&auml;gungen und eventuelle 
                                k&ouml;rperliche Symptome bei Dysbalance bzw. die positiven Eigenschaften bei 
                                Ausgeglichenheit. Anhand dieser Beschreibungen kann (k&ouml;nnen) die f&uuml;r 
                                die individuellen Eigenarten und Beschwerden erforderliche(n) Essenz(en) 
                                ausgesucht werden.
                                <br />
                                Die Essenzen werden in kleinen Fl&auml;schchen, den so genannten &#187;Stockbottles&#171;, 
                                angeboten. Aus diesen Stockbottles entnimmt man je 2 Tropfen und gibt diese 
                                in 20ml-Pipettenflaschen mit Wasser und Alkohol im Verh&auml;ltnis 1:1 
                                zur Konservierung. F&uuml;r Menschen mit Alkoholproblemen oder f&uuml;r 
                                Kinder kann die Pipettenflasche auch ohne Alkohol zubereitet werden, ist 
                                dann jedoch zum alsbaldigen Verbrauch bestimmt. Von diesen zubereiteten 
                                Tropfen sind je nach Indikation t&auml;glich 3 mal 2 Tropfen auf ein Glas 
                                Wasser einzunehmen, ggf. auch h&auml;ufiger.
                                <br />
                                Die Essenzen k&ouml;nnen auch gemischt werden, wobei man nicht mehr als 
                                3 Sorten gleichzeitig verwenden sollte.
                                <br />
                                Einzig die so genannten &#187;Rescue-Remedy&#171; Tropfen, die f&uuml;r Notf&auml;lle 
                                vorgesehen sind (Schockzust&auml;nde, Panik-Attacken), bestehen aus 5 
                                verschiedenen Essenzen: 6 &ndash; Cherry Plum (Kirschpflaume), 9 &ndash; 
                                Clematis (wei&#223;e Waldrebe), 18 &ndash; Impatiens (dr&uuml;siges Springkraut), 
                                26 &ndash; Rock Rose (gelbes Sonnenr&ouml;schen) und 29 &ndash; Star of 
                                Bethlehem (doldiger Milchstern).
                                <br />
                                Die Bachbl&uuml;tentherapie ist wissenschaftlich nicht erforscht, eine 
                                Wirksamkeit wurde bisher noch nicht best&auml;tigt. Dies hei&#223;t jedoch 
                                nicht, dass es sich nicht lohnen w&uuml;rde, sich einmal n&auml;her mit 
                                dieser Naturheilmethode zu besch&auml;ftigen. 
                                <br />
                                Viele Heilpraktiker arbeiten mit Bachbl&uuml;ten. Es gibt jedoch auch gute 
                                B&uuml;cher, die die Gem&uuml;tszust&auml;nde und die zugeh&ouml;rigen 
                                Bl&uuml;ten beschreiben. Mit intensiver Selbstbeobachtung, vor allem aber 
                                auch Selbstkritik kann man die f&uuml;r sich passenden Essenzen heraussuchen 
                                und sich die Tropfen zubereiten. Die Essenzen gibt es in Apotheken zu kaufen.
                                <br />
                                Selbst wenn Sie sich falsch eingesch&auml;tzt und die falsche(n) Essenz(en) 
                                ausgew&auml;hlt haben, kann hier (au&#223;er der finanziellen Fehlinvestition) 
                                kein Schaden angerichtet werden.
                                <br />
                                <br />
                                <b><span style="color: rgb( 255, 83, 83 );">Achtung: </span></b>
                                <br />
                                Bitte w&auml;hlen Sie beim Kauf seri&ouml;se Quellen, wie beispielsweise 
                                eine Apotheke oder bekannte Internet-Shops, vermeiden Sie jedoch dubiose 
                                Quellen, bei denen Sie die gelieferte Qualit&auml;t nicht einsch&auml;tzen 
                                k&ouml;nnen. 
                        
                            </td>
