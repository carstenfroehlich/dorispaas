                            <a name="stressmanagement">&nbsp;</a>
                                Stressmanagement
                            </td>
                            <td class="a">
                                <b>Definition: </b>
                                <br />
                                Stress kann auf der einen Seite anregend sein (Eustress = &#187;guter&#171; Stress),
                                sich auf der anderen Seite jedoch auch sehr schädlich auf den Organismus 
                                auswirken (Disstress = &#187;schädlicher&#171; Stress). Je nachdem, ob man 
                                selbst Eindrücke und Reize als positiv empfindet 
                                und ihre Intensität steuern kann, oder aber ob man sich ihnen mehr oder 
                                weniger hilflos ausgeliefert fühlt, wirken diese Reize als Eustress oder 
                                als Disstress.
                                <br />
                                <br />
                                <b>Wirkungsweise:</b>
                                <br />
                                Eustress ist überlebenswichtig &ndash; ohne Anregung würden wir sowohl 
                                körperlich als auch geistig verkümmern. 
                                <br />
                                Das Problem &#187;Stress&#171; meint aber immer den negativen Disstress.
                                Wenn dieser Stress überhand nimmt, nimmt unsere Gesundheit Schaden.
                                Deshalb ist es erforderlich, die Menge des negativen Stress' so weit wie 
                                möglich zu begrenzen oder aber &ndash; wenn dies in bestimmten Situationen 
                                nicht möglich ist &ndash; den Stress zumindest mit geeigneten 
                                <a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#entspanungsmethoden" class="faqmenu">Entspannungsmethoden</a>  
                                zu kompensieren.
                                <br />
                                <br />
                                <b>Indikationen:</b>
                                <br />
                                Ein vernünftiges Stressmanagement mit der weitestgehenden Reduzierung von 
                                schädlichem Stress und der darüber hinausgehenden Kompensation von 
                                unvermeidbarem Stress durch geeignete 
                                <a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#entspanungsmethoden" class="faqmenu">Entspannungsmethoden</a> 
                                ermöglicht es, auch bei erhöhtem Stress langfristig gesund zu bleiben.
                                <br />
                                <br />
                                <b><span style="color: rgb( 255, 83, 83 );">Achtung: </span></b>  
                                <br />      
                                Die oberste Priorität in einem Stressmanagement hat immer die Stressvermeidung!
                                Geeignete <a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#entspanungsmethoden" class="faqmenu">Entspannungsmethoden</a>
                                sind zwar grundsätzlich eine gesundheitsförderliche Maßnahme, zur 
                                Kompensation von Stress sind sie jedoch <b>ohne die weitestgehende Reduktion 
                                des Gesamtstress'</b> nicht ausreichend.
                            </td>
