                            <a name="entspannungsmethoden">&nbsp;</a>
                                Entspannungsmethoden
                            </td>
                            <td class="a">
                                <b>Definition: </b>
                                <br />
                                Es gibt diverse Entspannungsmethoden, die dazu diesen sollen, übermäßigen 
                                Stress abzubauen und zu kompensieren (siehe auch 
                                <a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#stressmanagement" class="faqmenu">Stressmanagement</a>).
                                <br />
                                Nicht nur die landläufig unter dem Begriff &#187;Entspannungsübungen&#171; 
                                bekannten Techniken wie &#187;<a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#autogenestraining" class="faqmenu">Autogenes Training</a>&#171;, 
                                &#187;<a href="<?= URL_ROOT ?>lexikon-naturheilmethoden#pms" class="faqmenu">Progressive 
                                Muskelentpannung</a>&#171; (PMS) nach Jacobson, Meditation oder 
                                <a href="http://www.individuelle-gesundheitsberatung.de/werkzeuge" target="_blank">QiGong</a> 
                                können entspannend wirken, auch jegliche moderate sportliche Betätigung, 
                                die Spaß macht, kann entspannend wirken.
                                <br />
                                <br />
                                <b>Wirkungsweise:</b>
                                <br />
                                Bei Stresseinwirkungen erhöht sich der Spiegel an Stresshormonen im Blut. 
                                Diese sorgten bei unseren Vorfahren dafür, dass man &ndash; beispielsweise 
                                bei der unverhofften Begegnung mit einem Säbelzahntiger &ndash; sich und 
                                sein Leben in Sicherheit bringen konnte, weil die Stresshormone nicht nur 
                                die Aufmerksamkeit steigern, sondern auch kurzfristig enorme körperliche 
                                Kapazitäten freisetzen. Bei etwas weniger gefährlichen Tieren war es auch 
                                möglich, diese Kräfte für einen erfolgreichen Kampf zu nutzen. 
                                Der Kampf bzw. das Weglaufen baute die Stresshormone ab und im Anschluss 
                                konnte man sich erholen und wieder zu Kräften kommen.
                                <br />
                                Heute aber wirkt der schädliche Stress meist ununterbrochen, und wir haben 
                                keine Zeit für Erholungsphasen. Auch können wir vor den meisten Stressereignissen 
                                nicht weglaufen oder vielleicht unseren Chef, der uns heftig zusetzt, niederschlagen.
                                So bleibt der Spiegel unserer Stresshormone dauerhaft hoch und kann nicht 
                                abgebaut werden.
                                <br />
                                Deshalb kann es sehr hilfreich sein, je nach Geschmack nach Feierabend eine 
                                Runde zu joggen oder ins Fitnessstudio zu gehen &ndash; eben sich wenigstens 
                                nachträglich die Bewegung zu verschaffen, die wir in der Stresssituation 
                                gerade nicht ausüben durften.
                                <br />
                                Zusätzlich sind die oben erwähnten Entspannungstechniken gut, um die 
                                verspannte Muskulatur zu lockern und den Geist zu befreien.
                        
                            </td>
