                        <h5>Welche Säulen stützen die Gesundheit?</h5>
                        <hr />
                        Welche &#187;Säulen&#171; halten und stützen aber nun eigentlich unsere Gesundheit? 
                        Hier ist zunächst einmal zu unterscheiden zwischen der <b>individuellen</b> und der 
                        <b>globalen</b> Gesundheit. Die individuelle Gesundheit betrifft nur uns selbst &ndash;
                        wobei die Bausteine der individuellen Gesundheit zwar alle Individuen betrifft, auf die wir 
                        aber durch bestimmte Aktionen direkten Einfluss nehmen können.
                        <br />
                        <br />
                        Und dann gibt es die <b>globalen</b> Säulen, also Faktoren, die über die Umwelt uns alle betreffen.
                        Auf die globalen Säulen können wir nur alle gemeinsam Einfluss nehmen &ndash; jeder muss dazu 
                        allerdings seinen Beitrag leisten. Es fällt zwar nur wenig ins Gewicht, wenn sich einzelne Individuen
                        diesen Bemühungen entziehen, aber je mehr Verweigerer es gibt, desto kleiner wird der globale Effekt.
                        Es liegt also auch im eigenen Interesse, durch ein möglichst umfassendes, verantwortungsvolles Umweltbewusstsein
                        etwas zur Verbesserung der globalen Faktoren beizutragen.
                        <br />
                        <a id="individuellesaeulen">&nbsp;</a>
                        <hr />
                        <h5>Welches sind individuelle Säulen?</h5>
                        <hr />
                        Reicht es nicht, nicht zu rauchen, ab und an etwas Obst und Gemüse zu essen, und 
                        wenn das mal nicht geklappt hat, vielleicht ein paar Vitamintabletten einzunehmen? 
                        Nun, der Verzicht auf Nikotin und Verzehr von Obst und Gemüse ist ein guter Anfang 
                        &ndash; aber doch längst nicht alles. Und <a href="ganz-vitamine" target="_blank">Vitamintabletten</a> sind dabei in den 
                        allermeisten Fällen nicht nötig, oftmals sogar eher schädlich als nützlich. Ich 
                        versuche hier einmal, möglichst viele Aspekte in einer Liste zusammenzustellen, die 
                        Puzzlesteinchen für eine stabile Gesundheit sind:
                        <br />
                        <br />
                        <b>&#149;</b> gesunde Ernährung
                        <br />
                        <b>&#149;</b> gesunde Verdauung
                        <br />
                        <b>&#149;</b> gesunde Mikrobiota (Darmflora)
                        <br />
                        <b>&#149;</b> ausreichendes und richtiges Trinken
                        <br />
                        <b>&#149;</b> Nikotinverzicht
                        <br />
                        <b>&#149;</b> weitestgehender Alkoholverzicht
                        <br />
                        <b>&#149;</b> ausreichende und kontinuierliche Bewegung
                        <br />
                        <b>&#149;</b> richtiges Atmen
                        <br />
                        <b>&#149;</b> genügend frische Luft
                        <br />
                        <b>&#149;</b> genügend Licht
                        <br />
                        <b>&#149;</b> ausreichender und gesunder Schlaf
                        <br />
                        <b>&#149;</b> wenig schädlichen Stress (Disstress), ggf. Ausgleich durch gutes Stressmanagement
                        <br />
                        <b>&#149;</b> das richtige Maß an positivem Stress (Eustress)
                        <br />
                        <b>&#149;</b> ausreichend geistige Anregung
                        <br />
                        <b>&#149;</b> stabiles Immunsystem
                        <br />
                        <b>&#149;</b> verantwortungsbewusster Umgang mit Medikamenten
                        <br />
                        <b>&#149;</b> schonende Methoden bei Rekonvaleszenz
                        <br />
                        <b>&#149;</b> möglichst schadstoffarmes Lebens- und Wohnumfeld
                        <br />
                        <b>&#149;</b> positive, werteorientierte Lebenseinstellung
                        <br />
                        <b>&#149;</b> stabiles, soziales Umfeld
                        <br />
                        <b>&#149;</b> Spaß und Freude
                        <br />
                        <b>&#149;</b> adäquater Umgang mit Enttäuschungen
                        <br />
                        <b>&#149;</b> finanzielle Absicherung
                        <br />
                        <br />
                        Diese Liste will und kann keinen Anspruch auf Vollständigkeit erheben, denn für 
                        jeden einzelnen Menschen kommen mit Sicherheit noch viele, ganz individuelle Aspekte 
                        hinzu. Doch die wichtigsten Punkte sind hier enthalten und zeigen Ihnen, dass in 
                        vielen Bereichen des Lebens ein gesundheitsbewusstes Verhalten vorteilhaft ist.
                        <br />
                        <a id="ihreindividuellensaeulen">&nbsp;</a>
                        <hr />
                        <h5>Welches sind Ihre individuellen Säulen?</h5>
                        <hr />
                        Was aber ist nun &#187;gesunde Ernährung&#171;, was ist &#187;ausreichende 
                        Bewegung&#171; oder &#187;genügend Licht und Luft&#171;? Die Frage müsste eigentlich 
                        heißen: &#187;Was ist <b>für Sie</b> gesunde Ernährung, <b>für Sie</b> ausreichend 
                        Bewegung und <b>für Sie</b> genügend Licht und Luft&#171;. Denn was für den einen 
                        die richtige, gesunde Ernährung ist, bei der er sich wohl fühlt und die ihn mit 
                        den erforderlichen Nährstoffen versorgt, die ihm schmeckt und Wohlbehagen bereitet, 
                        kann einem anderen gar nicht bekommen, so dass er Beschwerden bekommt und sein 
                        Wohlbefinden entscheidend beeinträchtigt ist. Auch die Art und Intensität von 
                        Bewegung &ndash; sei es ein Spaziergang oder eine anstrengende Sportart &ndash; 
                        kann dem einen so richtig Spaß machen, für den anderen bedeutet das Gleiche reinen 
                        Stress.
                        <br />
                        <br />
                        Und so, wie für das eine Gebäude viele schmale, schlanke Säulen genau das Richtige sind, 
                        bei einem anderen Bauwerk jedoch eher wenige, aber gedrungenere Pfeiler für ein gelungenes Gesamtbild 
                        sorgen, so sind all die in der obigen Liste aufgeführten Aspekte zwar als Richtschnur 
                        zu beachten, müssen jedoch <b>von Ihnen ganz individuell ausgestaltet und mit Leben 
                        gefüllt</b> werden.
                        <br />
                        <a id="globalesaeulen">&nbsp;</a>
                        <hr />
                        <h5>Welches sind die globalen Säulen der Gesundheit?</h5>
                        <hr />
                        Neben den <b>individuellen</b> Säulen Ihrer Gesundheit spielen weitere Faktoren im Gesamtgeschehen mit &ndash;
                        ich nenne Sie die <b>globalen Säulen</b> der Gesundheit. Dies sind u.a. die Umweltbedingungen, denn wir 
                        sind ja in unserer Umwelt fest verwurzelt und haben nicht etwa die Möglichkeit, wenn unser Planet 
                        verschmutzt ist, auf einen anderen, saubereren Planeten auszuweichen. 
                        <br />
                        <br />
                        Wir müssen zum Beispiel die <b>mit zahlreichen Schadstoffen belastete Luft</b> atmen &ndash; es führt kein Weg
                        darum herum. Alles, was die Industrie und die Energiewirtschaft durch die Nachfrage durch unseren Konsum in 
                        die Luft pusten, atmen wir tagtäglich wieder ein. Wir können uns nicht schützen &ndash; wir können nur alle 
                        gemeinsam durch eine Änderung unseres Verhaltens dafür sorgen, dass nicht mehr so viel Schadstoffe produziert werden.
                        <br />
                        <br />
                        Auch die <b>klimatischen Bedingungen</b>
                        sind für unsere Gesundheit wichtig, denn können uns nur beschränkt an sich verändernde klimatische Bedingunen
                        anpassen. Wir merken es bereits jetzt, dass die um derzeit noch wenige Zehntelgrade angestiegenen
                        Temperaturen uns selbst körperlich zu schaffen machen &ndash; ganz abgesehen davon, dass Pflanzen und Tiere
                        ebenfalls unter diesen Veränderungen leiden und in immer rasanterem Tempo aussterben.
                        <br />
                        <br />
                        Weiterhin müssen wir beachten, welche <b>Stoffe und Ressourcen</b> wir mit welchem Respekt verwenden bzw. verschwenden.
                        Kleidung zum ein- oder zweimaligen Gebrauch zu kaufen und dann wegzuwerfen, Produkte in überflüssigen Verpackungen 
                        statt lose zu kaufen, Lebensmittel unüberlegt aus weit entfernten Gebieten zu importieren, immer das neueste Handymodell 
                        haben zu wollen ... Mit diesem Verhalten fördern wir die Vermüllung unserer Erde, denn es werden mitnichten etwa
                        alle Wertstoffe wieder recycelt, sondern die Rohstoffe ausgebeutet. Zudem lagern diese Stoffe im Zweifelsfalle
                        in irgendwelchen Deponien und sickern peu à peu in unser Grundwasser und gelangen letztendlich über die Nahrungskette 
                        in unserem Körper &ndash; und dies ist mit allergrößter Sicherheit nicht förderlich für uns.
                        <br />
                        <br />
                        Es gibt zahlreiche weitere Beispiele für die Schädigung unserer Umwelt, die letztendlich auf unsere 
                        Gesundheit einwirken. Es ist klar, dass jeder Einzelne auf alle diese Faktoren nur einen sehr kleinen Einfluss hat.
                        Aber wenn man alle kleinen Bausteinchen zusammennimmt, kann (und muss) Großes geleistet werden.
                        Es wird uns auch nichts anderes übrig bleiben, als dass jeder bei sich selbst beginnt und dass <b>jeder seinen
                        eigenen, kleinen Beitrag leistet</b>, denn erstens können Sich nur sich selbst ändern und zweitens ist keine Zeit mehr, 
                        nur auf die Aktionen der anderen zu warten. Für unsere aller &ndash; für die globale &ndash; Gesundheit ist die
                        umgehende Verbesserung der globalen Gesundheit das sofortige Aktivwerden unbedingt erforderlich. Und ohne eine
                        verbesserte globale Gesundheit sind auch alle individuellen Schritte zum Scheitern verurteilt.
                        <br />
                        <a id="vorgehensweise">&nbsp;</a>
                        <hr />
                        <h5>Welche Vorgehensweise verspricht Erfolg?</h5>
                        <hr />
                        Wenn Sie beschlossen haben, in Zukunft mehr auf Ihre Gesundheit zu achten &ndash; 
                        sei es, weil der Arzt es Ihnen aus verschiedenen Gründen empfohlen hat, oder weil 
                        Sie sich in Ihrer Haut nicht mehr wohl fühlen &ndash; gehen Sie behutsam an diesen 
                        Plan heran. &#187;Rom ist nicht an einem Tag erbaut worden&#171;, heißt es, was 
                        bedeutet, dass Sie sich rasch hoffnungslos überfordert fühlen würden, wenn Sie nun 
                        auf einmal <b>alle</b> Punkte gleichzeitig für sich beachten und ändern würden. 
                        <b>Gehen Sie schrittweise an das Projekt &#187;Gesundheit&#171; heran.</b> Schauen Sie, 
                        welchen Punkt oder welche Punkte Sie am einfachsten ändern können und beginnen Sie 
                        damit. Wenn Sie Freude daran haben und Fortschritte erzielen, können Sie nach und 
                        nach den einen oder anderen weiteren Aspekt hinzunehmen. Wenn Sie in einem ausgewählten 
                        Punkt das Gefühl haben, dass es Ihnen dabei nicht gut geht, betrachten Sie dies 
                        nicht als Niederlage, sondern wenden sich vorerst einem anderen Punkt zu. Sobald 
                        Sie sich zwingen müssen, war die Entscheidung &ndash; zumindest für den Augenblick 
                        &ndash; nicht richtig für Sie. Wichtig ist bei allem, dass Sie Spaß an Ihrem 
                        gesundheitsbewussten Verhalten haben. 
                        <br />
                        <br />
                        Eines ist jedoch für alle Menschen gleichermaßen wichtig: Seien Sie sich in allen 
                        Ihren Tätigkeiten und Verhaltensweisen immer der Tatsache bewusst, dass eine 
                        grundsätzlich gesundheitsbewusste und auch eine umweltbesusste Einstellung Sie auf den richtigen Weg führt und 
                        Ihre Gesundheit ein ganzes Leben lang stabil(er) und belastungsfähig(er) wird oder 
                        bleibt. Bleiben Sie aber bitte bei all Ihren Entscheidungen zum Wohle Ihrer Gesundheit 
                        und der Umwelt gelassen und auch nachsichtig mit sich selbst, denn eine allzu fanatische Befolgung 
                        aller &#187;Regeln&#171; ist kontraproduktiv &ndash; Sie dürfen sich sicherlich 
                        auch ab und an einmal etwas zu erlauben, was eigentlich nicht so richtig 
                        &#187;gesund&#171; ist. Die Betonung liegt dabei allerdings auf &#187;ab und 
                        an&#171; &ndash; und richtig große &#187;Sünden&#171; oder &#187;Schweinereien&#171; sind nicht wirklich gut.
                        <br />
                        <br />
                        Wenn Sie noch etwas unsicher sind, wo Sie mit Ihrem gesundheitsbewussten 
                        Verhalten beginnen wollen und sollten, helfe ich Ihnen gerne. Wir schauen gemeinsam, 
                        wo bei Ihnen die dringendsten &#187;Baustellen&#171; sind, und wo Sie als erstes 
                        eine Änderung herbeiführen könnten. 
                        <br />
                        <a id="behandlungskonzept">&nbsp;</a>
                        <hr />
                        <h5>Was tun, wenn Sie bereits ernsthafte Probleme haben?</h5>
                        <hr />
                        Wenn Sie sich bereits ernsthaft krank fühlen und belastende Symptome haben, ist es besonders ratsam, 
                        rasch einzugreifen und dann systematisch vorzugehen. Lassen Sie sich beraten, um <b>ein für Sie und für Ihre Beschwerden passendes 
                        Behandlungskonzept</b> zu erarbeiten. Dieses muss eine umfassende Analyse Ihrer Beschwerden und die 
                        sich daraus ergebende Diagnose auch die für Sie geeigneten Mittel und Maßnahmen enthalten.
                        <br />
                        <br />
                        Genauso wie bei dem Weg zu mehr ganzheitlicher Gesundheit gibt es auf dem Weg aus einer Krankheit heraus
                        viele verschiedene Aspekte, die es zu beachten gilt und zahlreiche Stellschrauben, an denen man drehen kann.
                        Ein <a href="ggb-behandlungskonzept" target="_blank">individuell erarbeitetes Behandlungskonzept</a> führt auf 
                        jeden Fall eher zum Ziel, als auf eigene Faust
                        und vor allem ohne die erforderlichen Hintergründe zu kennen auf der Stelle zu treten.
