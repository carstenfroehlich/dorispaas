                        <h5>Ausgabe 72 (Frühjahr 2025)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2025-01-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Der heutige Tag, der 7. M&auml;rz 2025, ist in Deutschland zum &#187;Tag der Gesunden Ern&auml;hrung&#171; erkl&auml;rt. Viele Veranstaltungen und 
                        Internetbeitr&auml;ge drehen sich heute um dieses Thema, wobei der Schwerpunkt hier naturgem&auml;&#223; eher darauf ausgerichtet ist, wie man mit 
                        der entsprechenden Ern&auml;hrung <b>gesund bleibt</b>. Was aber, wenn man bereits gesundheitliche Probleme hat? Ich denke hier &ndash; weil es der 
                        Schwerpunkt meiner Arbeit ist – auch und vor allem an Verdauungsprobleme. Was hier f&uuml;r den einen gesund ist, muss es nicht zwangsl&auml;ufig 
                        auch f&uuml;r jeden anderen sein. Dann kann eine gesunde Ern&auml;hrung etwas ganz anderes sein als eine gesunde Ern&auml;hrung f&uuml;r 
                        jemanden, der (noch) keine Symptome zeigt. Mit einer &#187;gesunden&#171; Ern&auml;hrung kann man nicht nur Krankheiten vorbeugen, sie geh&ouml;rt 
                        auch als unverzichtbarer Baustein zu jeder <b>Behandlung</b> von ern&auml;hrungsassoziierten Erkrankungen dazu. Wegen der Bedeutung einer Ern&auml;hrung, 
                        die <b>individuell auf die Bed&uuml;rfnisse angepasst</b> sein muss, habe ich die Schwerpunkte f&uuml;r diesen Newsletter zu diesem Ereignis f&uuml;r 
                        Sie ausgesucht. Und wenn Ihnen dieses Thema bereits bekannt vorkommt: ja, der entsprechene Beitrag ist nicht neu &ndash; leider aber immer ein 
                        Dauerbrenner. Wie alle meine Themen &uuml;berarbeite ich auch &#187;alte&#171; Beitr&auml;ge und aktualisiere sie st&auml;ndig. Lesen Sie 
                        sich deshalb gerne auch bekannte Artikel durch, denn es gibt auch hier immer wieder Neues zu entdecken.
                        <br />
                        <br />
