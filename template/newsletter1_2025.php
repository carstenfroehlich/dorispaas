                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-ernaehrung" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2025-01-gesunde-ernaehrung.png" alt="Bild Salatteller" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-ernaehrung" target="_blank">Schwerpunktthema: &#187;Bedeutet &#155;Gesunde Ern&auml;hrung&#139; für jeden das gleiche?&#171;</a></b>
                        <br />
                        <i>(Menü: Wissensdatenbank/Ganzheitliche Gesundheit/Ern&auml;hrung/Was ist gesunde Ern&auml;hrung?)</i>
                        <br />
                        Wenn wir gesund sind, zeigt uns unser K&ouml;rper leider (oder dankenswerterweise) nicht sofort, ob uns etwas bekommt oder nicht, was wir gerade 
                        verzehrt haben. Gesundheitliche Folgen treten bei insgesamt schlechter Kost meistens erst mit einem Zeitversatz von mehreren Jahren oder sogar Jahrzehnten auf 
                        (abgesehen von h&auml;ufigen Problemen beim Stuhlgang). Hier einen direkten Zusammenhang herzustellen, ist schwer. Wenn wir jedoch an 
                        Unvertr&auml;glichkeiten oder bakteriellen Fehlbesiedelungen leiden, die ohnehin schon mit Verdauungsbeschwerden einhergehen, folgt &#187;die 
                        Strafe&#171; meist auf dem Fu&#223;e, und wir k&ouml;nnen oft sehr wohl die &#187;&Uuml;belt&auml;ter&#171; erkennen. Ist aber das Meiden oft 
                        viel zu vieler Lebensmittel der Weisheit letzter Schluss? Auch und gerade bei Verdauungsbeschwerden gilt es aus verschiedenen Gr&uuml;nden, 
                        eine m&ouml;glichst abwechslungsreiche Ern&auml;hrung einzuhalten &ndash; allerdings d&uuml;rfen hier die Beschwerden nicht aus dem Blick 
                        verloren werden. Wie aber verbindet man das eine mit dem anderen?
