                        <b>&#111; In welchen Lebensmitteln sind Oligosaccharide enthalten? </b>
                        <br />
                        <br />
                        Oligosaccharide sind in nennenswerten Mengen nur in Pflanzen enthalten. Tierische 
                        Lebensmittel wie Fleisch oder Fisch enthalten diese Kohlenhydrate normalerweise nicht, 
                        lediglich Milch enth&auml;lt geringe Mengen an Oligosacchariden. Achtung ist 
                        jedoch bei industriell bearbeiteten tierischen Nahrungsmitteln (Wurst, Fleisch- 
                        und Fischzubereitungen) und vor allem Fertiggerichten geboten, denn hier ist 
                        v&ouml;llig offen, was die Hersteller in ihre Produkte mischen. Insbesondere 
                        k&ouml;nnen hier die diversen Lebensmittelzusatzstoffe wie Gelier-, Binde- und 
                        Verdickungsmittel zu einem nicht unbetr&auml;chtlichen Oligosaccharidgehalt beitragen.
