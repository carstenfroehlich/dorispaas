                    <h2>
                        Heute ist der Weltwassertag
                    </h2>
                    <p>
                    Eigentlich ist es sehr wenig Wasser, was wir täglich zum Trinken und zum Kochen 
                    benötigen: nur etwa 5 Liter. Dazurechnen müssen wir hier bei uns in 
                    Deutschland noch etwa 120 Liter für die persönliche Hygiene, für 
                    die Toilettenspülung und zum Wäschewaschen und Geschirrspülen &ndash; 
                    insgesamt also rund 125 Liter, die wir täglich verbrauchen &ndash; jeder von 
                    uns! Diese Menge wäre eigentlich nicht wirklich kritisch, aber ...
                    </p>
                    <p>
                    Es kommen zu dieser (aus unserer Sicht) kleinen Menge noch Unmengen an Litern 
                    dazu u.a. für die Landwirtschaft, für die Industrie und für unseren 
                    sonstigen Luxus. 
                    </p>
                    <p>
                    Nur ein paar kleine Beispiele, wie viel Wasser wir noch zu dem 
                    o.a. Bedarf hinzurechen müssen: Allein die Herstellung eines Autos erfordert 
                    rund 400.000 Liter sauberes (!) Wasser. Ok, ein Auto kaufen wir nicht jeden Tag 
                    &ndash; es hält im Allgemeinen eine Zeit lang. Die Erzeugung eines 
                    Kilogramm Rindfleisch erfordert 15.000 Liter Wasser. Ja, die meisten von uns essen 
                    auch nicht ein Kilo Rindfleisch pro Tag. Die Herstellung eines Hamburgers jedoch 
                    verbraucht 2.500 Liter Wasser &ndash; überzeugt? Und es gibt Hunderte, nein 
                    Tausende von weiteren Beispielen, die belegen, wie und wo wir Wasser verbrauchen.
                    </p>
                    <p>
                    Auf der anderen Seite stehen viele Milliarden von Menschen auf der Welt, die nicht 
                    einmal die von der UN angegebene Menge von nur 50 Litern sauberes Wasser 
                    täglich zur Verfügung haben, um gesund zu bleiben.
                    </p>
                    <p>
                    Ich bitte uns alle, nicht nur heute am Weltwassertag, sondern immer bei unseren 
                    Handlungen den Wasserverbrauch im Hinterkopf zu behalten und verantwortungsbewusst 
                    mit dieser beileibe nicht uneingeschränkt zur Verfügung stehenden Ressource 
                    achtsam umzugehen. Fangen wir im Kleinen an und sparen dort, wo wir es gleich 
                    erkennen können (z.B. im Haushalt). Fahren wir fort, indem wir uns überlegen, 
                    für welche Nahrungsmittel bei der Erzeugung mehr und für welche weniger 
                    Wasser verbraucht wird und richten unseren Speiseplan vielleicht ein wenig danach aus. 
                    Als Faustregel gilt: die Herstellung tierischer Nahrungsmittel verbraucht mehr Wasser 
                    als die Herstellung pflanzlicher Produkte. 
                    </p>
                    <p>
                    Wenn wir insgesamt unseren Verbrauch an Ressourcen überdenken und etwas 
                    sparsamer sind, können wir alle gemeinsam eine ganze Menge erreichen!
                    </p>
                    <p>
                    Aus Anlass des Weltwassertags möchte ich noch einmal auf meinen 
                    <a href="<?= REQUEST_URI ?>#blog-2013-02-14">Blog-Beitrag vom 14.2.2013</a> aufmerksam machen und Sie alle 
                    dafür sensibilisieren, dass &#187;Wasser und sanitäre Grundversorgung 
                    ein Menschenrecht und keine Handelsware sind!&#171;
                    </p>
                    <p>
                    In diesem Sinne wünsche ich allen Menschen auf dieser Welt nicht nur heute 
                    ausreichend sauberes Wasser.
                    </p>
                    <p>
                    Herzliche Grüße<br />
                    Ihre Doris Paas
