                    <b>Auch mit der Kleidung kann man Gutes für die Gesundheit tun</b> 
                    <br />
                    <br />
                    Unsere Haut ist nicht nur ein großes Ausscheidungsorgan, sondern sie nimmt auch viele Stoffe auf, mit der sie in Berührung 
                    kommt. Dies ist auch der Grund, warum man neue Kleidungsstücke &ndash; und hier insbesondere die Leibwäsche &ndash;
                    vor dem ersten Tragen unbedingt waschen sollte. Auch die Qualität der Kleidung ist mit entscheidend für die Unbedenklichkeit 
                    oder aber auch die Gefahr für unsere Gesundheit. Billigkleidung kann sehr häufig stark mit Chemikalien belastet sein, die 
                    die schlechte Stoffqualität kaschieren sollen. Sind die Imprägnierungen herausgewaschen, sehen diese Sachen schnell aus wie 
                    Putzlappen und werden entsorgt. 
                    Um die Haut vor diesen Substanzen zu schützen, ist es wichtig, sie vor dem Anziehen so weit wie möglich aus der Wäsche zu entfernen.
                    Qualitativ gute Kleidung benötigt weniger chemische Ausrüstung, was nicht nur für die Umwelt, sondern auch für die eigene Gesundheit 
                    vorteilhafter ist, was aber nicht heißt, dass man diese Kleidungsstücke vor dem Tragen nicht waschen sollte.
                    <br />
                    <br />
                    Darüber hinaus werden zur Herstellung neuer Kleidungsstücke viele Rohstoffe verwendet. Und hier sind nicht nur die  
                    Baumwolle oder &ndash; schlimmer noch &ndash; Erdöl für die verschiedensten synthetischen Fasern gemeint, sondern 
                    auch das Wasser, das bei der Produktion in großer Menge verbraucht wird. Alle diese
                    Rohstoffe sind wertvolle Recourcen, die man u.a. auch durch eine kluge Auswahl bei der Kleidung schonen kann.
                    Zuerst sollte man überlegen, ob es wirklich erforderlich ist, sich in kürzesten Abständen immer wieder 
                    neue Kleidungsstücke zu kaufen und jede Mode mitzumachen. Dies bedeutet nämlich, dass diese hochmodische
                    Garderobe auch rasch wieder out ist und man sie dann entsorgen will. Ggf. ist es sinnvoller, sich 
                    ein etwas zeitloseres Outfit zu kaufen, das dann aber sehr viel länger getragen werden kann.
                    Das bedeutet nicht, dass man in unmodernen Oma- oder Opasachen herumlaufen muss &ndash; es gibt durchaus Sachen, 
                    die eigentlich immer gut aussehen.
                    <br />
                    <br />
                    Es müssen auch nicht immer die billigen Teile sein, denn das ist bei genauerem Hinsehen sehr viel teurer, als 
                    weniger, dafür aber hochwertigere Kleidungsstücke zu kaufen (abgesehen von dem Preis für die Umwelt, der ja leider 
                    in den seltensten Fällen mit eingerechnet wird). Höherwertigere Kleidung ist sehr viel haltbarer und sieht auch 
                    nach längerem Tragen und zahlreichen Wäschen noch wie neu aus. Billige Ware ist nach kurzer Zeit ausgeleiert 
                    und taugt tatsächlich nur noch für die Tonne. 
                    <br />
                    <br />
                    Ein höherer Preis bedeutet jedoch keineswegs zwangsläufig, dass diese Kleidung auch unter etisch korrekten Bedingungen
                    hergestellt worden sein muss. Auch große Marken sind hier in letzter Zeit in Verruf geraten, weil sie trotz teuren
                    Verkaufspreisen in Bangladesh oder anderen Billiglohnländern von Frauen oder sogar Kindern unter erbärmlichsten Verhältnissen 
                    produzieren lassen. Ein großer Teil des Geldes fließt hier dann keineswegs fair an die Näherinnen, 
                    sondern landet in den Taschen der gierigen Hersteller. Achten Sie deshalb auf Labels, die eine faire Herstellung bezeugen.
                    Diese sind u.a. der &#187;Global Organic Textile Standard&#171; oder die &#187;Fair Wear Foundation&#171;. Ich bitte 
                    Sie herzlich, sich über diese und weitere Labels zu informieren und Hersteller zu bevorzugen, die Ihre Waren nach 
                    diesen Bedingungen produzieren.
                    <br />
                    <br />
                    Eine Alternative könnte es auch (ab und an) sein, wenn Sie sich mal im Second-Hand-Laden oder einem Flohmarkt umschauen. 
                    Diese Kleidung ist nicht nur sehr preiswert, sondern mit Sicherheit auch schon das ein oder andere Mal gewaschen. Nicht nur 
                    die Chemie ist hier garantiert schon rausgewaschen, es gibt auch keine bessere Methode, Recourcen zu schonen. Und warum sollte  
                    man gute Teile, die jemandem anders vielleicht nicht mehr gefallen, nicht weiter verwenden? Hier haben viele schon
                    wahre Lieblings-Schätzchen gefunden.

                    
