                    <b>Kluges und faires Verhalten in der Corona-Pandemie</b> 
                    <br />
                    <br />
                    Das Cornona-Virus (SARS-CoV-2), das die COVID-19-Erkankung auslöst, versetzt derzeit viele Menschen in Angst und Schrecken &ndash; 
                    manche sogar in Panik. Deshalb möchte ich heute einmal die Problematik beleuchten und versuchen, sie ins rechte Licht zu rücken.
                    <br />
                    <br /> 
                    Die Epidemie hatte ihren Ursprung mit großer Wahrscheinlichkeit in China. Man vermutet, dass das die Erkrankung auslösende Virus, so 
                    wie auch die Erreger der &#187;Vogelgrippe&#171; oder auch der &#187;Schweinegrippe&#171;, von Tieren auf den Menschen übertragen wurde. 
                    Wodurch dies passieren konnte, ist bisher noch nicht abschließend geklärt. In den allermeisten Fällen verläuft die Erkrankung eher harmlos
                    &ndash; auch bei Kindern. Die schweren und die (glücklicherweise in Bezug auf die Erkrankungszahlen wenigen) tödlich verlaufenden Krankheitsfälle 
                    betreffen Menschen mit gravierenden Vorerkrankungen meist des Herzens und der Atemwege. Zunächst erschien die COVID-19-Erkrankung weniger 
                    gefährlich als die Grippe, allerdings jagte sie uns die größere Angst ein, weil sie uns fremder ist als die &#187;altbekannte&#171; Grippe.
                    Nun zeigt sich aber doch, dass auch bei unbelasteten Patienten schwere Verläufe beobachtet werden &ndash; allerdings sehr viel seltener als bei 
                    den Patienten mit Vorerkrankungen. 
                    <br />
                    <br />
                    Die Ansteckung erfolgt durch Tröpfcheninfektion, d.h. durch Anniesen oder Anhusten, aber auch durch Speicheltröpfchen beim Sprechen. Offenbar ist 
                    die Erkrankung auf diesem Wege sehr leicht übertragbar, weniger zumindest nach derzeitigen Erkenntnissen als sogenannte &#187;Schmierinfektion&#171;, 
                    also über Gegenstände und Oberflächen. Wenn jedoch ein Erkrankter direkt in die Hand niest oder hustet und mit dieser eine Oberfläche wie z.B. 
                    eine Türklinke anfasst, die dann sogleich von anderen Menschen berührt wird, ist auch ein solcher Übertragungsweg nicht ausgeschlossen.
                    <br />
                    <br />
                    Aus diesen Tatsachen ergeben sich zwei verschiedene Verhaltensweisen: zum einen, um sich selbst vor einer Ansteckung zu schützen, zum anderen 
                    aber auch ein faires, solidarisches Verhalten, das andere, eventuell sehr viel gefährdetere Personenkreise vor einer u.U. schwer oder sogar 
                    tödlich verlaufenden Erkrankung bewahren soll.
                    <br />
                    <br />
                    Einfache Vorbeugungsmaßnahmen sind also das Einhalten von mindestens zwei Metern Abstand, um selbst keine Erreger von anderen übertragen zu bekommen.
                    Weiterhin sollten, wenn man sich im öffentlichen Raum bewegt, möglichst keine Handläufe oder Haltestangen angefasst werden. Da man sich ohne festen Halt 
                    ggf. aber selbst gefährdet, sollte man Haltemöglichkeiten mit Handschuhen anfassen. Falls man doch versehentlich in Berührung gekommen ist, keinesfalls mit 
                    den Händen ins Gesicht fassen, um eine Übertragung auf die Mund- und Nasenschleimhäute oder die Augen zu vermeiden. Sobald man die Möglichkeit hat, die Hände 
                    mit warmem Wasser und Seife gründlich reinigen. Und statt des allgemein üblichen Händeschüttelns sollte man sich derzeit zur Begrüßung besser freundlich anlächeln.
                    <br />
                    <br />
                    Wichtig und richtig waren die von der Bundes- bzw. den Landesregierungen zunächst erlassenen Verbote größerer Veranstaltungen und Versammlungen, denn diese 
                    Menschenansammlungen sind besondere Übertragungsherde. Aber auch das mittlerweile angeordnete Kontaktverbot ist sinnvoll und sollte unbedingt beachtet werden 
                    &ndash; auch, wenn es vor allem bei längerer Dauer schwerfällt.
                    Überall dort, wo viele Menschen auf engerem Raum zusammenstehen, wo eventuell noch eine schlechte 
                    Durchlüftung herrscht, können Viren besonders gut von Mensch zu Mensch weitergegeben werden. Haben Sie deshalb Verständnis für diese Maßnahmen, 
                    denn sie verhindern bzw. verlangsamen die Erkrankungswelle und helfen so, die Kapazitäten unseres Gesundheitssystems nicht zu sprengen.
                    Diese Maßnahmen sind erstens vorübergehend und zweitens ein kleiner Preis für den erforderlichen Erfolg, die Pandemie zu beherrschen.
                    <br />
                    <br />
                    Für den &#187;Hausgebrauch&#171; reichen diese Maßnahmen.
                    <b>Für den Selbstschutz</b> ist es weder erforderlich noch wirksam, einen Mundschutz zu tragen, denn die Produkte, die nicht explizit für diesen Zweck 
                    hergestellt wurden, schützen mitnichten vor einer Infektion. Erstens sind sie viel zu durchlässig, schließen auch nicht komplett rund um Mund und Nase, 
                    zudem müssten die Mundschütze alle 2-3 Stunden gewechselt werden, um nicht das genaue Gegenteil zu bewirken. Dass viele Asiaten im öffentlichen Raum
                    einen Mundschutz tragen, heißt noch lange nicht, dass dies eine sinnvolle Maßnahme zum Selbstschutz ist. Allerdings geben die Virologen zu bedenken, 
                    dass ein Mund-Nasen-Schutz eventuell davor schützen können, <b>das Virus an andere weiterzugeben</b>, dass diese Masken quasi als &#187;Spuckschutz&#171;
                    fungieren. Da das Virus bereits ein bis zwei Tage vor dem Auftreten von Symptomen übertragen werden kann, wäre es tatsächlich einen Versuch wert 
                    und somit eine sinnvolle Maßnahme, wenn jeder Mensch in der Öffentlichkeit eine solche Maske trüge &ndash; ggf. tut es hier auch eine selbstgenähte. 
                    Wenn niemand mehr den anderen mit Tröpfchen besprüht, wäre dies eine Möglichkeit, die Ausbreitung vielleicht ein wenig zu verlangsamen.
                    <br />
                    <br />
                    Ganz wichtig ist &ndash; auch wenn man selbst nicht zum einschläglig gefährdeten Personenkreis zählt, aus Rücksicht mit vorbelasteten 
