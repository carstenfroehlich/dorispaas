                        Woher kommt das Wort &#187;Stuhlgang&#171;? Während in früheren Zeiten die ärmeren Bevölkerungsschichten ihre Notdurft entweder in der freien Natur oder 
                        auf dem Misthaufen erledigten, konnten Kaiser und Könige den Luxus eines Gangs zum &#187;Kackstuhls&#171; genießen &ndash; dem Stuhlgang. Dieser war &ndash; wie 
                        der Name sagt &ndash; nichts anderes als ein Stuhl mit einem Loch in der Sitzfläche, unter dem ganz diskret ein Eimer angebracht war. In diesen fiel der erlauchte 
                        Kot, und Bedienstete mussten nach dem Stuhlgang ihrer Herrschaften diese Eimer leeren. Für den &#187;Pöbel&#171; gab es später Plumpsklos, bei denen der Kot 
                        in Gruben fiel. Wassergespülte Klosetts gab es seit dem späten 16. Jahrhundert, modernere WCs wurden 200 Jahre später entwickelt. Diese nennen wir
                        die wir heute französisch-fein Toiletten. Das Wort Stuhlgang hat sich bis heute gehalten, aber bezieht sich jetzt nicht mehr auf das Badezimmermöbel, sondern  
                        sowohl auf den Gang zur Toilette als auch auf den abgesetzten Kot oder auch Fäkalien (vom lateinischen Begriff faeces), das Wort &#187;Stuhl&#171; steht für 
                        den abgesetzten Kot, weil es unfein ist, das Kind beim Namen zu nennen. Nur noch Kinder dürfen von &#187;Kacka&#171; sprechen.
                        <br />
                        <br />
                        Jetzt aber zum eigentlichen Thema: &#187;Normaler&#171; Stuhlgang ist gut geformt, also weder zu dünn noch zu fest und kann ohne Pressen abgegeben werden.  
                        Das Reinigen auf der Toilette bereitet keine Probleme. Meistens erledigen wir den Stuhlgang regelmäßig etwa ein- bis zweimal täglich &ndash; oftmals sogar  
                        zu gleichen Tageszeiten. Es kann jedoch durchaus auch normal sein, wenn Sie nur alle zwei oder drei Tage Stuhlgang haben. 
                        <br />
                        <br />
                        Häufigkeit, Konsistenz, Geruch und Farbe hängen eng mit den Ernährungsgewohnheiten zusammen. Je nach dem, was Sie zuvor verzehrt haben, riecht normaler 
                        Stuhlgang nicht über Gebühr unangenehm, und Sie haben keine oder nur wenige Blähungen. Auch die Farbe wird (zumindest zum Teil) durch Ihre Nahrungsmittel 
                        mitbestimmt.
                        <br />
                        <br />
                        Von Krankheiten und Unverträglichkeiten abgesehen, sind aber auch viele andere Faktoren wie u.a. Ihre Trinkgewohnheiten, der Konsum von Genussmitteln wie 
                        Zigaretten oder Alkohol und der Gebrauch von Medikamenten und Nahrungsergänzungsmitteln, Ihr Bewegungsverhalten und auch Ihr Stressaufkommen Größen, die 
                        Aussehen und Beschaffenheit des Stuhls entscheidend beeinflussen.
                        <br />
                        <br />
                        Sie finden hier Informationen über Ihren Kot, wie er im Idealfall beschaffen sein sollte oder wie Abweichungen zu bewerten und ggf. zu 
                        beheben sind. Aber auch der Stuhlgang &ndash; im wahrsten Sinne des Wortes &ndash; wird hier thematisiert und geschaut, wie man durch ein 
                        korrektes Verhalten beim Stuhlgang verschiedene Probleme verhindern kann.
                        <br />
                        <br />
                        <a id="stuhl"></a>
                        <hr />
                        <h5>Stuhl</h5>
                        <hr />
                        Fäkalien (Stuhl) bestehen keineswegs nur aus <b>unverdaulichen Resten von Nahrungsmitteln</b>. Bis zu einem Drittel des Gesamtvolumens und damit ein großer Teil 
                        besteht aus <b>abgestorbenen oder auch noch lebenden Darmbakterien</b>, aber auch aus <b>abgestorbenen Schleimhautzellen</b>, 
                        die sich stetig erneuern müssen, um die Funktionsfähigkeit der Verdauung zu gewährleisten. Auch alter Darmschleim, der sich immer wieder erneuern muss, 
                        um die <a href="darmschleimhaut" target="_blank">Darmschleimhautzellen</a> ernähren zu können, ist Bestandteil des Stuhls.
                        <br />
                        <br />
                        Neben diesen Hauptkomponenten enthält Stuhl noch viele weitere Bestandteile, und es ist möglich, mit einer Stuhlprobe zu analysieren, welche Stoffe in 
                        welcher Menge enthalten sind oder auch fehlen, so dass Rückschlüsse auf die Funktionsfähigkeit des Verdauungssystems getroffen werden können.
                        <br />
                        <br />
                        <a id="aussehen"></a>
                        <hr />
                        <h5>Aussehen</h5>
                        <hr />
                        Können Sie jeden Tag sagen, wie Ihr Stuhl aussieht? Leider haben sich in unseren Badezimmern die sogenannten <b>Tiefspüler</b> durchgesetzt. Dies sind die Toiletten, 
                        die so konstruiert sind, dass der Stuhl sofort ins Wasser fällt. Der Grund ist eine geringere Geruchsbildung in der Umgebungsluft. Bei den <b>Flachspülern</b> bleibt 
                        der Stuhl zunächst auf einer Ablagefläche liegen und wird erst mit der Betätigung der Wasserspülung hinuntergespült.
                        <br />
                        <br />
                        Im Prinzip ist es ja ganz angenehm, dass wir unsere Fäkalien nicht (immer) riechen müssen, aber es hätte durchaus etwas für sich, sie und ihre Beschaffenheit 
                        durch Anschauen und auch vom Geruch her begutachten zu können, denn so können wir am besten kontrollieren, ob ggf. etwas nicht so ist, wie es sein sollte. 
                        Deshalb mein Tipp, dass Sie, wenn Sie immer dann, wenn Sie eine Toilette mit Flachspülklosett aufsuchen, <b>Ihren Stuhl begutachten</b>, bevor Sie ihn in die 
                        Kanalisation spülen. Aber auch beim Tiefspüler gibt es &ndash; wenn auch in geringerem Maße &ndash; die Möglichkeit, einen Eindruck vom Stuhl zu gewinnen. 
                        Wie fühlt es sich an, wenn Sie den Kot absetzen? Gleitet er in einem Stück aus dem Anus heraus &ndash; ist er also wahrscheinlich wurstförmig und glatt 
                        &ndash; oder fühlt es sich eher wie eine matschige Masse an? Müssen Sie stark pressen und ist der Stuhl betonhart oder kommen nur &#187;Hasenküttel&#171; 
                        heraus? Schauen Sie bitte auch im Tiefspülklosett ruhig nach &#187;getaner Arbeit&#171; aber bevor Sie Papier hinterherwerfen, was sich da unter der 
                        Wasseroberfläche befindet und was Sie sehen können &ndash; die Farbe und ggf. auch die Oberflächenstruktur Ihres Produkts können Sie vielleicht ein 
                        wenig erkennen. Es ist keineswegs eklig, wenn Sie Ihre Fäkalien betrachten, sondern <b>aktive Gesundheitsfürsorge</b>!
                        <br />
                        <br />
                        <a id="konsistenz"></a>
                        <hr />
                        <h5>Konsistenz</h5>
                        <hr />
                        Die Konsistenz von Fäkalien kann sich zwischen den erwähnten steinharten &#187;Hasenkütteln&#171; über schartig fest oder glatten, gut geformten Würsten, aber 
                        auch matschigen Kuhfladen bis hin zu flüssiger Beschaffenheit bewegen.
                        <br />
                        <br />
                        Es gibt die so genannte &#187;<a href="https://de.wikipedia.org/wiki/Bristol-Stuhlformen-Skala" target="_blank">Bristol-Stuhlformen-Skala</a>&#171;, die in der 
                        Universität im englischen Bristol entwickelt wurde. Hier sind in sieben Abstufungen <b>Stuhlbeschaffenheiten</b> abgebildet und mit entsprechenden Bezeichnungen treffend 
                        charakterisiert, so dass Sie die Konsistenz &#187;Ihres&#171; Stuhls gut auf dieser Skala einordnen können. Ein guter Berater oder Therapeut kennt diese Skala 
                        und wird Sie vielleicht nach Ihrer Einschätzung anhand dieser Kriterien fragen und kann bei Problemen wertvolle Schlüsse daraus ziehen.
                        <br />
                        <br />
                        Da diese Einordnung einen guten Hinweis auf die Gesundheit Ihrer Verdauungsleistung und auch Ihres Verdauungssystems geben, ist es vorteilhaft, den Stuhl regelmäßig 
                        zu begutachten. Gelegentliche Ausrutscher nach oben oder unten können Sie getrost außer Acht lassen, denn die Beschaffenheit hängt &ndash; wie gesagt &ndash; auch 
                        von den verschiedenen Faktoren wie vor allem der Ernährung ab. Wenn Sie aber im Großen und Ganzen immer zu Verstopfung oder aber Durchfall neigen, ist auf jeden 
                        Fall etwas nicht in Ordnung.
                        <br />
                        <br />
                        Einen Vorteil hat der Tiefspüler übrigens: Sie können sehen, <b>ob der Stuhl schwimmt oder untergeht</b>. Ein zu hoher Luft- und auch ein zu hoher Fettgehalt können bewirken, 
                        dass der Stuhl nicht unter die Wasseroberfläche sinkt. 
                        <br />
                        <br />
                        Wichtig wären in diesem Zusammenhang auch die Fragen nach der <b>Menge des Toilettenpapiers</b> und ob Sie viele Spuren in der Kloschüssel mit der Toilettenbürste entfernen 
                        müssen, denn diese Indizien weisen u.a. ebenfalls auf den Gehalt an unverdauten Nahrungsfetten hin.
                        <br />
                        <br />
                        <a id="farbe"></a>
                        <hr />
                        <h5>Farbe</h5>
                        <hr />
                        Die Farbe des Stuhls ist im Allgemeinen ein mehr oder weniger sattes Braun. Diese ergibt sich durch das <b>Bilirubin</b>, einem Abbauprodukt von Blutbestandteilen. 
                        <br />
                        <br />
                        Zudem hängt die Färbung vor allem davon ab, welche <b>Lebensmittel</b> sie gegessen haben. Es ist normal, wenn der Stuhl nach einer Spinat- oder Mangold-Mahlzeit grün ist 
                        oder nach dem Verzehr von Roter Beete eine kräftig rote Farbe hat.
                        <br />
                        <br />
                        Nicht normal ist eine schwarze Färbung &ndash; dies ist der sogenannte Teerstuhl, der auf <b>Blutungen</b> im Magen-/Darmtrakt hinweisen kann (hier bitte sofort zum Arzt gehen!). 
                        Erkennbar frische, rote Blutauflagen auf dem Stuhl sind meist Folge von Hämorrhoiden (siehe unten), was zwar weniger dramatisch ist, Sie jedoch ebenfalls zu einem Arztbesuch 
                        veranlassen sollte. 
                        <br />
                        <br />
                        Auch eine lehmartige Färbung kann ein Hinweis auf Erkrankungen sein &ndash; insbesondere der <b>Leber</b>. Beobachten Sie bitte, ob diese Farbgebung einmalig war oder ob Ihr 
                        Stuhl häufiger so aussieht. In diesem Falle ist auch hier der Gang zum Arzt angeraten.
                        <br />
                        <br />
                        <a id="rueckstaende"></a>
                        <hr />
                        <h5>Sichtbare Nahrungsrückstände</h5>
                        <hr />
                        Häufig können Sie bei aufmerksamer Begutachtung Ihres Stuhls <b>Reste von verzehrten Nahrungsmitteln</b> erkennen. Maiskörner, Saaten wie Leinsamen oder Sesamkörner und Schalen 
                        von Paprikaschoten sind für jedes Verdauungssystem eine Herausforderung und &#187;rutschen&#171; häufig durch. Eigentlich sollten die Nahrungsmittel gut gekaut und 
                        vollkommen zerkleinert werden, bevor sie heruntergeschluckt werden. Bei vielen Lebensmitteln wie u.a. den erwähnten gelangt jedoch häufig das eine oder andere Körnchen 
                        oder ein Stückchen Schale unzerkaut in den Magen und Darm. Da diese Organe die Zerkleinerung nicht oder nur unzureichend nachholen können und auch die 
                        &#187;nacharbeitenden&#171; Darmbakterien hier überfordert sind, gelangen die Bestandteile dann unverdaut mit dem Stuhl wieder ans Tageslicht. In Maßen ist dies 
                        unproblematisch. Sollten jedoch immer sehr viele Lebensmittelbestandteile im Stuhl erkennbar sein, sollten Sie zuallererst Ihr Essverhalten überprüfen. 
                        <br />
                        <br />
                        <a id="geruch"></a>
                        <hr />
                        <h5>Geruch</h5>
                        <hr />
                        Mit und ohne Tiefspüler &ndash; es entwickelt sich auf jeden Fall auf der Toilette ein <b>Geruch</b>. Jeder Kot hat einen Eigengeruch, der auch ganz individuell von 
                        &#187;seinem&#171; Menschen abhängig ist: nicht nur die Tiere benutzen diese individuelle &#187;Duftmarke&#171; zur Erkennung, welcher Freund oder Rivale ein 
                        Häufchen hinterlassen hat. Auch wir Menschen geben mit unserem Kot Signale ab &ndash; aber erstens lässt unsere Zivilisation ein solches Nachschnüffeln nicht zu und  
                        zweitens hat sich unser Geruchssinn zurück entwickelt, so dass wir solche &#187;Feinheiten&#171; gar nicht mehr wahrnehmen können. 
                        <br />
                        <br />
                        Unabhängig von der individuellen Marke ist der Geruch darüber hinaus auch variabel und abhängig davon, was vorher gegessen wurde. Der Geruch kann aber auch Hinweise 
                        auf die <b>Besiedelung mit ganz bestimmten Darmbakterien</b> geben: riecht der Stuhl in der Regel eher faulig wie nach verdorbenen Eiern, ist eine Überwucherung der Darmflora 
                        mit Fäulniskeimen wahrscheinlich. Dies kann das Ergebnis von einem zu hohen Proteinverzehr sein. Wenn Sie also sehr viel Fleisch, Fisch und Eier essen, kann eine in 
                        Richtung Fäulnisflora entgleiste Mikrobiota die Folge sein. Riecht der Stuhl meistens eher säuerlich, so ist eine sogenannte eine Gärungsflora vorherrschend. 
                        Gründe dafür können z.B. Kohlenhydratunverträglichkeiten sein, bei denen zu viele Zucker in den Dickdarm gelangen.
                        <br />
                        <br />
                        Sie sollten also bitte ruhig <b>den Geruch Ihres Stuhls wahrnehmen</b>, um ggf. mit dieser Auskunft einem Berater oder Therapeuten wertvolle Hinweise zu Ihrer Mikrobiota geben zu können. 
                        Das ist in keinster Weise peinlich, sondern kann u.U. sogar (in Maßen) teure Tests vermeiden helfen.
                        <br />
                        <br />
                        <a id="probleme"></a>
                        <hr />
                        <h5>Probleme beim Stuhlgang und Lösungen</h5>
                        <hr />
                        <b>&#149; Verdauungsprobleme</b>
                        <br />
                        Viele Menschen haben Probleme beim Stuhlgang. Gemeint sind hier nicht <a href="verdauung" target="_blank">Verdauungsprobleme</a> wie z.B. Durchfall oder eine Verstopfung, 
                        sondern die <b>Probleme beim Stuhlgang im wahrsten Sinne des Wortes</b>: wie erleichternd finden Sie das Absetzen Ihres Stuhls, müssen Sie sich dabei über Gebühr anstrengen, 
                        wie lange dauert der Toilettengang, fühlen Sie sich vollkommen entleert oder meinen Sie, dass noch Stuhlreste im Darm zurückgeblieben sind? 
                        <br />
                        <br />
                        <b>&#149; Körperhaltung und Atmung</b>
                        <br />
                        Hier könnten u.a. Korrekturen mit einer <b>günstigen Sitzhaltung</b> (Oberkörper eher gerade als abgeknickt) oder eine <b>bessere Atmung</b> (tief in den Unterbauch) Abhilfe schaffen. 
                        Beobachten Sie in diesem Zusammenhang auch einmal die Spannung Ihrer Bauchmuskeln. Manchmal sind diese angespannt und bilden so einen starren &#187;Panzer&#171; um die Bauchorgane. 
                        So kann sich im Unterbauch nichts bewegen, auch der Darm nicht. Der Transport im Darm ist behindert und kann den Stuhl nicht in Richtung Ausgang befördern. <b>Lassen Sie die 
                        Bauchmuskulatur bewusst locker</b>, atmen Sie gleichzeitig tief in den Bauch und geben so dem Stuhl die Möglichkeit, nach außen zu rutschen.
                        <br />
                        <br />
                        Oftmals kann auch die Position der Toiletten selber hinderlich sein: Gerade ältere Menschen lassen sich ihre Klosettbecken etwas höher anbringen, weil dann das Aufstehen weniger
                        mühsam ist. Dies ist auch in Ordnung, aber für den Stuhlgang leider hinderlich, denn eigentlich funktioniert das Absetzen des Stuhls am besten, wenn wir hocken wie unsere Vorfahren in der Natur.
                        Um eine altersgerechte Toilettenhöhe und eine eher der Hocke angenäherte Körperhaltung verbinden zu können, stellen Sie sich ein <b>Fußbänkchen</b> bereit, das Sie nach dem
                        Niedersetzen mit dem Fuß vor das WC schieben. Wenn Sie die Füße auf dieses Bänkchen stellen, ist die Haltung Ihrer Beine mehr nach oben verlagert, so dass sich dies günstig auf 
                        eine förderliche Haltung auswirkt. Nach Beendigung des &#187;Geschäfts&#171; schieben Sie die Fußbank beiseite, und Sie können bequem aufstehen.
                        <br />
                        <br />
                        <b>&#149; Pressen</b>
                        <br />
                        Die meisten Menschen haben keine Geduld und warten, bis der Stuhl von alleine aus dem Darm gleitet. Sie pressen &ndash; und dies meist auch noch falsch, so dass der Stuhl nicht 
                        wie aus einer Tube gedrückt, sondern eher irgendwie im Bauchraum gequetscht wird. 
                        <br />
                        <br />
                        Eigentlich sorgen gut funktionierende Muskelbewegungen des Darms, dass der Stuhl von oben nach unten und letztendlich aus dem Darm hinausbefördert wird. Voraussetzungen dafür sind 
                        aber, dass zum einen der Stuhl eine möglichst optimale Konsistenz hat (siehe unten) und zum anderen, dass man dem Stuhldrang nachgibt, wenn der Darm dies signalisiert. Und last,
                        but not least, braucht es auch etwas Geduld, denn der Darm lässt sich nicht hetzen und braucht Zeit, den Inhalt durch die beiden Schließmuskeln am Darmausgang nach außen zu transportieren. 
                        Da wir jedoch häufig nicht zu den Zeiten auf unseren Darm hören, wenn er sich meldet und auch nicht genügend Zeit einplanen (siehe unten), pressen wir, um den 
                        Darm zu überlisten, der weder zu diesem Zeitpunkt bereit ist noch auf die Schnelle seinen Inhalt abgeben kann. 
                        <br />
                        <br />
                        Es gibt einen natürlichen Mechanismus, den so genannten &#187;gastrokolischen Reflex&#171;. Dieser Mechanismus bewirkt nach der ersten (und in geringerem Maße nach jeder) Mahlzeit,
                        dass der Magen (der medizinische Fachbegriff ist Gaster) eine Nachricht an den Dickdarm (Kolon) sendet, dass nun Speisen in das Verdauungssystem aufgenommen wurden, die Platz 
                        brauchen. Diesen Platz soll der Dickdarm freimachen, indem er bereits verdaute Nahrungsreste und sonstige Verdauungsrückstände ausscheidet. Wenn wir <b>genügend Zeit nach den 
                        Mahlzeiten für einen Toilettengang einplanen</b>, ist dies die beste Voraussetzung für ein zufriedenstellendes Ergebnis ohne großartig pressen zu müssen.
                        <br />
                        <br />
                        <b>&#149; Konsistenz des Stuhl</b>
                        <br />
                        Ganz wichtig für einen befriedigenden Stuhlgang ist die Konsistenz des Kots. Weder zu dünner noch zu fester Stuhl führen zu einem zufriedenstellenden Ergebnis. Falls Sie häufig
                        Durchfälle oder  &ndash; im Gegenteil &ndash; eher oft Verstopfung haben, sollten Sie mit Hilfe eines spezialisierten Beraters oder Therapeuten versuchen, die Ursachen 
                        dafür zu finden. Als Notlösung bei Verstopfung halten die Apotheken zwar ein reichhaltiges (und gewinnbringendes) Angebot an Abführmitteln (Laxanzien) bereit, dies ist jedoch 
                        auf keinen Fall eine Dauerlösung! Wenn abgeklärt ist, ob eventuell <a href="nahrungsmittelunvertraeglichkeiten" target="_blank">Nahrungsmittel-Unverträglichkeiten</a> vorliegen, 
                        müssen Sie dies bei der Auswahl Ihrer Lebensmittel berücksichtigen. Ggf. können auch Flohsamenschalen helfen, <b>die Konsistenz Ihres Stuhls zu optimieren</b> &ndash; sie 
                        werden mit reichlich Wasser eingenommen und quellen im Darm auf. Dadurch wird zum einen das Stuhlvolumen erhöht und damit ein Reiz zum Stuhltransport ausgelöst. Zum anderen 
                        erhält der Stuhl eine gute, pastöse Konsistenz und kann so von der Darmmuskulatur ab besten weiterbefördert werden. 
                        <br />
                        <br />
                        Neben der Menge der verzehrten <b>Ballaststoffe</b> hängt die Konsistenz des Stuhls auch ganz eng mit Ihrer <b>Trinkmenge</b> zusammen. Überprüfen Sie deshalb unbedingt diese 
                        beiden Faktoren, die Sie ganz einfach durch eine Änderung Ihrer Gewohnheiten in der Hand haben. Insbesondere zu fester Stuhl bekommt so sehr schnell wieder eine weichere 
                        Beschaffenheit.
                        <br />
                        <br />
                        Weiterhin hilft die <b>Massage bestimmter Akupressurpunkte</b>. Bei Durchfall massieren Sie mehrmals im Laufe des Tages die Punkte <a href="akupressur#magen37" target="_blank">Ma 37</a> 
                        und <a href="akupressur#milz1" target="_blank">Mi 1</a>, bei Verstopfung den Punkt <a href="akupressur#magen41" target="_blank">Ma 41</a>. Aber es gibt noch viele weitere 
                        geeignete <a href="akupressur" target="_blank">Akupressurpunkte</a>. Diese und eine ausführliche Anleitung finden Sie in dem 
                        <a href="book-darmgymnastik" target="_blank">Buch &#187;Darmgymnastik&#171;</a>.
                        <br />
                        <br />
                        <b>&#149; Hämorrhoiden</b>
                        <br />
                        Eng mit der Konsistenz des Stuhls hängt auch ein Problem zusammen, das viele Menschen plagt: Hämorrhoiden (Hämorriden). Im Prinzip hat jeder Mensch diese ringförmigen Gefäße, die
                        wie ein Polster um die Schleimhaut des Enddarms liegen und die Dichtungsfunktion der beiden Schließmuskeln verstärken. Aber im Volksmund dieses Problem verbunden mit 
                        &#187;unnormal&#171; und krampfaderartig vergrößerten und auch tiefer liegenden Hämorrhoiden. Teils tritt diese Erkrankung aufgrund einer (oftmals erblichen) Bindegewebsschwäche auf, 
                        wird aber auch verstärkt durch häufigere Verstopfungen und die damit verbundene Gewohnheit, beim Toilettengang stark zu pressen, weil der Stuhl nicht so ohne weiteres abgesetzt
                        werden kann.
                        <br />
                        <br />
                        Grundsätzlich &ndash; und erst recht bei Hämorrhoiden &ndash; sollte alles getan werden, um <b>den Stuhl weich zu halten</b>. Harter Stuhl bereitet dem Darm und seinem Menschen 
                        große Mühe und kann außerdem kleinere oder auch größere Verletzungen am Enddarm verursachen, was die Blutspuren auf dem Stuhl verursacht. Auch die Pflege der empfindlichen
                        Schleimhaut um den After hilft, Verletzungen und damit Blutungen vorzubeugen. Benutzen Sie nach jedem Waschen und nach jedem Toilettengang ein neutrales Öl (z.B. Sesam- oder 
                        ein pflanzliches Babyöl), um die Haut geschmeidig zu halten.
                        <br />
                        <br />
                        Auf jeden Fall sollten Sie bei Problemen dieser Art zunächst zu Ihrem Hausarzt und dann zu einem <b>Proktologen</b> gehen, also zu einem Spezialisten für Erkrankungen des Enddarms,  
                        um mit ihm zu entscheiden, ob und ggf. welche Behandlung Abhilfe schaffen könnte. Denken Sie dabei daran, dass Hämorrhoiden kein &#187;peinliches&#171;, sondern ein 
                        ernstzunehmendes und vor allem belastendes Problem sind.
                        <br />
                        <br />
                        <b>&#149; Stuhlinkontinenz</b>
                        <br />
                        Neben der insbesondere bei Frauen, die Kinder geboren haben, häufiger auftretenden Harninkontinenz gibt es auch eine Stuhlinkontinenz. Hierbei kann es vorkommen, dass bei Stuhldrang
                        der Stuhl nicht oder nicht lange genug bis zum Erreichen weit entfernter Toiletten gehalten werden kann. Dieses Problem kann in verschiedenen Ausprägungen auftreten &ndash; von 
                        Schmieren und Spuren in der Unterwäsche bis hin zu tatsächlich vollkommenem und unkontrollierten Stuhlabgang. Im Extremfall wagen sich die Betroffenen kaum noch aus dem Haus. Da 
                        alles rund um den Stuhlgang schambehaftet ist, wird das Thema auch selten beim Arzt angesprochen. Genau dies sollte man aber auf jeden Fall tun, denn <b>bereits Ihr Hausarzt kann mit 
                        einigen Tipps weiterhelfen</b>. Wahrscheinlich wird er Sie aber zu Fachkollegen überweisen, die dann mit geeigneten Maßnahmen Abhilfe schaffen können.
                        <br />
                        <br />
                        Sie selbst können aber bei Bedarf auf jeden Fall mit <b>Beckenbodengymnastik</b> oder sehr empfehlenswerten <b>Bauchtanzübungen</b> (beides übrigens auch für Männer geeignet!) 
                        beginnen, die die Muskulatur des Beckenbodens stärken 
                        und so die Funktion der Schließmuskeln unterstützen. Der Facharzt kann mit verschiedenen Maßnahmen wie z.B. der Elektrostimulation oder &ndash; in ausgeprägteren Fällen
                        &ndash; auch mit verschiedenen Operationstechniken das Problem bessern bzw. beseitigen.
                        <br />
                        <br />
                        <b>&#149; Hemmungen</b>
                        <br />
                        Fühlen Sie sich vielleicht auf fremden Toiletten geekelt oder gehemmt, so dass Sie insbesondere an Tagen, an denen Sie diese Örtlichkeiten aufsuchen müssen (z.B. auf der Arbeit 
                        oder auf Reisen), immer besondere Probleme haben? Dienlich könnten hier eventuell <b>hygienische Papierauflagen</b> oder auch das Aufsuchen von etwas <b>abgelegeneren Toiletten</b> 
                        sein, bei denen peinliche Geräusche oder Gerüche Ihnen zumindest nicht direkt zugeordnet werden können.
                        <br />
                        <br />
                        <b>&#149; Stuhlgangzeiten</b>
                        <br />
                        Nicht nur, wenn Sie sich für Ihren Stuhlgang nicht genügend Zeit nehmen, sondern erst recht, wenn Sie ein dringendes Bedürfnis über einen längeren Zeitraum verschieben oder 
                        verdrängen, bleibt der Stuhl im Darm liegen und wird immer fester. Darüber hinaus weitet sich der Enddarm, weil immer mehr Stuhl nachgeschoben wird. Es rächt sich, nicht 
                        täglich zur Toilette zu gehen. Harter Stuhl von großem Umfang bereitet dann Probleme, eventuell sogar Schmerzen, was zu Verkrampfungen führen kann. Ein Teufelskreis beginnt, 
                        denn Sie befürchten auch beim nächsten Gang zur Toilette wieder Schmerzen und verkrampfen sich mehr und mehr. 
                        <br />
                        <br />
                        Im Gegenteil kann aber auch Durchfall die Folge sein: wenn Stuhl zu lange im Dickdarm liegen bleibt, wirken die schädlichen Abfälle viel zu lange auf die Schleimhaut, die 
                        dann vermehrt Flüssigkeit absondert, um diese Stoffe möglichst rasch auszuscheiden.
                        <br />
                        <br />
                        Abhilfe schaffen hier am besten <b>regelmäßige Zeiten</b>, an die Sie und Ihr Darm sich rasch gewöhnen werden. Verschieben Sie einen Stuhlgang nicht und geben Sie einem Bedürfnis 
                        möglichst sofort nach. <b>Gehen Sie zur Toilette, wenn Ihr Darm Ihnen dies signalisiert</b>. Selbst Berufstätige können in den meisten Situationen kurze <b>Arbeitspausen für 
                        den erforderlichen Gang nutzen</b> &ndash; oder sollten es zumindest. 
                        <br />
                        <br />
                        Genauso, wie Sie für Ihre Mahlzeiten regelmäßige Zeiten und &ndash; ausreichende &ndash; Zeitspannen einplanen sollten, sollten Sie für Ihre Stuhlgänge ausreichend und 
                        genügend Zeit (im Allgemeinen direkt nach den Mahlzeiten) bereithalten. Es ist weder förderlich, Essen auf der Hand in der &#187;<a href="ganz-healthtogo" target="_blank">To-Go-Variante</a>&#171; 
                        zu sich zu nehmen, noch gibt es &ndash; wie jedem einleuchten wird &ndash; Stuhlgang in der To-Go-Variante.
                        <br />
                        <br />
                        <b>&#149; Dauer des &#187;Geschäfts&#171;</b>
                        <br />
                        Nicht nur der richtige Zeitpunkt ist wichtig für einen befriedigenden Stuhlgang, sondern auch die Dauer, die Sie dafür aufwenden. <b>Nehmen Sie sich immer genügend Zeit</b>, 
                        wenn Sie einmal auf der Toilette sitzen. Manche Menschen berichten, dass Sie nach einem Toilettengang oft ein Gefühl der unvollständigen Entleerung haben und schon nach 
                        kurzer Zeit wieder einen Drang verspüren. Hier hilft es, aufmerksam in sich hineinzuhören und zu entscheiden, ob wirklich alles, was sich im Enddarm befindet, ausgeschieden 
                        worden ist. Ggf. kann es helfen, <b>kurz aufzustehen</b> und mit der veränderten Körperhaltung die Biegungen des letzten Darmabschnitts, des S-förmigen, sogenannten Sigma,  
                        ein wenig umzuformen und so dem Transport Vorschub 
                        zu gewähren. Beim erneuten Niedersetzen geht es dann sehr häufig auch wieder weiter. Wenn Sie Ihr &#187;Geschäft&#171; schon nach der ersten Portion beenden und zu einem 
                        Termin eilen, müssen Sie sich nicht wundern, wenn der im Darm verbliebene Rest schon nach kurzer Zeit ebenfalls ans Tageslicht drängt.
                        <br />
                        <br />
                        <b>&#149; Stress</b>
                        <br />
                        Auch <a href="ganz-entspannung" target="_blank">Stress</a> ist ein ganz entscheidender Faktor beim Auftreten von Verdauungsproblemen. Bauchhirn und Kopfhirn arbeiten auf 
                        der sogenannten &#187;Darm-Hirn-Achse&#171; eng zusammen, 
                        und wenn Sie sich gestresst fühlen, wirkt sich dies auf das empfindliche Nervengeflecht in und um Ihren Darm aus. Der Transport der Speisen und des Stuhls im Darm funktioniert 
                        nicht reibungslos, Verdauungssäfte werden nicht in ausreichender Menge und zum richtigen Zeitpunkt gebildet, so dass sich all dies auf Ihr Verdauungssystem und damit auf die 
                        Stuhlqualität auswirkt. Hier hilft ein <b>kluges Stressmanagement</b>, mit dem Sie vermeidbaren Stress verhindern und nicht zu vermeidende Stressbelastungen durch 
                        Entspannungsübungen kompensieren. Lesen Sie hierzu gerne auch den Beitrag &#187;<a href="krisenverdauung" target="_blank">Krisen und ihre Auswirkungen auf die Verdauung</a>&#171;.
                        <br />
                        <br />
                        <b>&#149; Unzureichende Bewegung</b>
                        <br />
                        Sehr hilfreich &ndash; ja eigentlich unerlässlich &ndash; sind regelmäßige Bewegungsübungen, um den Darm zum kontinuierlichen Transport des Stuhls anzuregen.
                        Ein Darm ist nämlich faul &ndash; und zwar jeder Darm! Ohne Anregung bewegt sich ein Darm wenig und transportiert die Speisen nur sehr unzureichend, was sich nachteilig auf eine gesunde Verdauung auswirkt. Die Anregung des Darms erfolgt nicht nur durch die Dehnung durch die verzehrten Speisen von innen, sondern auch durch aktive Körperbewegungen wie die Tätigkeit der Bauchmuskulatur und des Zwerchfells von außen. Je häufiger diese Anregungen sind, desto besser und desto gleichmäßiger wird der Darminhalt weiterbefördert. Erfolgen die Anregungen nur sporadisch, bleiben die Speisen viel zu lange an einer Stelle liegen. Dies kann unter Umständen zu erheblichen Beschwerden führen. 
                        <br />
                        <br />
                        Deshalb ist das &#187;Geheimnis&#171; einer geregelten Verdauung nicht nur der Verzehr einer ballaststoffreichen Nahrung mit einem überwiegenden Anteil an pflanzlichen Lebensmitteln, 
                        sondern auch ein kontinuierliches Bewegungsverhalten, bei dem mindestens <b>alle 30 &ndash; 60 Minuten wenigstens kleine Atem- und/oder Bewegungsübungen</b> ausgeführt werden. Lesen Sie 
                        hierzu gerne den Beitrag &#187;<a href="darmgymnastik" target="_blank">Darmgymnastik</a>&#171; auf dieser Website. Sehr viel mehr zu diesem Thema ist in dem Buch
                        <a href="book-darmgymnastik" target="_blank">&#187;Darmgymnastik &ndash; Bewegung &#38; mehr gegen Verdauungsbeschwerden&#171;</a> zusammengetragen.
                        <br />
                        <br />
                        <b>&#149; Reinigungstechnik</b>
                        <br />
                        Und last, but not least, kann auch die für Sie <b>geeignete Reinigungstechnik</b> mit entscheidend für einen guten Stuhlgang sein. Die meisten Menschen in unserem Kulturkreis benutzen
                        Toilettenpapier, andere Kulturen säubern sich nach dem Stuhlgang mit Wasser. Je nach dem, was Sie gewohnt sind, sollten Sie das beibehalten, sofern Sie mit dem Ergebnis zufrieden sind.
                        Wenn Sie bemerken, dass Sie sehr viel Toilettenpapier benötigen, versuchen Sie es mit Wasser &ndash; wer ein Bidet besitzt, ist dabei natürlich fein raus. Aber zur Not tut es auch 
                        ein mit Wasser gefülltes Gefäß, das Sie sich vor dem Gang bereitstellen und aus dem Sie nach dem &#187;Geschäft&#171; das Wasser langsam ausgießen, während Sie mit der Hand oder 
                        auch mit Papier putzen. 
                        <br />
                        <br />
                        Sie sollten Sie <b>Wasserreinigung</b> auf jeden Fall ausprobieren, wenn Sie bemerken, dass die empfindliche Haut an Ihrem Anus durch das Reiben gereizt ist. Geschädigte Haut in diesem 
                        Bereich kann nämlich ebenfalls zu Problemen führen, denn sie bereitet Schmerzen und führt zu einer verkrampften Haltung. Außerdem übt eine gereizte Haut auch immer wieder einen 
                        Entleerungsdrang aus &ndash; auch wenn eigentlich kein Stuhl mehr im Darm ist. So entsteht ein Gefühl der unvollständigen Entleerung. Ich kann Ihnen nur empfehlen, die Reinigungstechnik 
                        mit Wasser auszuprobieren &ndash; man fühlt sich zudem mit der Wasserreinigung wesentlich sauberer als mit der Papierreinigung.
                        <br />
                        <br />
                        <a id="erleichterung"></a>
                        <hr />
                        <h5>Erleichterung</h5>
                        <hr />
                        Übrigens kann auch mangelnde Konzentration auf das &#187;Geschäft&#171; mit Schuld an Problemen mit dem Stuhlgang haben: gehören Sie zu den Menschen, die mit der Zeitung auf die 
                        Toilette gehen? Achten Sie doch lieber darauf, was Sie tun und fühlen Sie in Ihren Körper hinein. Eine Zeitung stört da eher dabei. 
                        <br />
                        <br />
                        Der Gang zur Toilette ist nichts, was sich nebenbei von selbst erledigt, sondern eine Tätigkeit, der Sie Ihre volle <b>Aufmerksamkeit</b> schenken und deren <b>Ergebnis Sie 
                        angemessen würdigen</b> sollten. Nur, wenn Sie Ihrer Arbeit und auch Ihrem Produkt die angemessene Wertschätzung zubilligen, werden Sie sich im Wortsinne erleichtert fühlen.
