                        Nicht erst seit Kurzem machen sich Hersteller von Nahrungserg&auml;nzungsmitteln 
                        Gedanken, ob und wie neben Laktase-Pr&auml;paraten auch mit einer gesunden 
                        Darmschleimhaut und einer gesunden Darmflora die Laktose-Verwertung optimiert 
                        werden kann. Diese &Uuml;berlegungen haben durchaus ihre Berechtigung &ndash; 
                        ich m&ouml;chte sie hier jedoch einmal kritisch und differenziert beleuchten. 
                        <br />
                        <br />
                        Eine gesunde Darmschleimhaut ist der Garant f&uuml;r die Aufrechterhaltung einer 
                        gr&ouml;&#223;tm&ouml;glichen Restproduktion des Laktase-Enzyms im D&uuml;nndarm, 
                        und eine gesunde Darmflora mit m&ouml;glichst vielen n&uuml;tzlichen und wenig 
                        sch&auml;dlichen Bakterienarten unterst&uuml;tzt die optimale Funktion der 
                        Darmschleimhaut. 
                        <br />
                        <br />
                        Vor allem aber sind bestimmte Bakterienarten aus der Darmflora &ndash; die 
                        Milchs&auml;ure- und die Bifidobazillen &ndash; in der Lage, selbst Laktase zu 
                        bilden und k&ouml;nnen so die Spaltung von Milchzucker unterst&uuml;tzen. 
                        Dar&uuml;ber hinaus erzeugen sie mit ihrem Stoffwechsel ein saures Milieu im Darm, 
                        das die Bedingungen f&uuml;r die n&uuml;tzlichen Bakterien f&ouml;rdert, die 
                        f&uuml;r die sch&auml;dlichen jedoch eher hemmt. 
                        <br />
                        <br />
                        Diese Eigenschaften versuchen sich die Hersteller von Nahrungserg&auml;nzungsmitteln 
                        zunutze zu machen und bieten Pr&auml;parate mit den verschiedensten St&auml;mmen 
                        der Milchs&auml;ure- und Bifidobazillen und auch noch vielen anderen Bakterienarten 
                        an &ndash; teilweise mit zus&auml;tzlichen Pr&auml;biotika (diese Pr&auml;parate 
                        hei&#223;en dann &#187;Synbiotika&#171;). In der Werbung und auf den Beipackzetteln 
                        wird angegeben, dass die Bakterien die Bek&ouml;mmlichkeit von Milchzucker 
                        f&ouml;rdern. 
                        <br />
                        <br />
                        Dar&uuml;ber hinaus geben die Hersteller an, die Einnahme solcher Pr&auml;parate 
                        k&ouml;nne unabh&auml;ngig von den Mahlzeiten erfolgen, beispielsweise am Morgen, 
                        so dass das l&auml;stige Mitf&uuml;hren und Einnehmen von Laktase-Pr&auml;paraten 
                        zu den Mahlzeiten entfallen k&ouml;nne. 
                        <br />
                        <br />
                        Es wird damit geworben, dass man nach der Einnahme eines solchen Pr&auml;parates 
                        &#187;Milchzucker auch mit Laktose-Intoleranz wieder ungehemmt genie&#223;en&#171; k&ouml;nne 
                        &ndash; auch ohne die Einnahme von Laktase-Pr&auml;paraten und vor allem ohne 
                        unangenehme Folgen wie Bl&auml;hungen, Durchf&auml;llen und allen weiteren bekannten 
                        Beschwerden. 
                        <br />
                        <br />
                        Aus diesem Grunde m&ouml;chte ich Ihnen hier einige Hintergrundinformationen zu 
                        diesem Thema und eine Entscheidungshilfe f&uuml;r oder gegen ein solches Pr&auml;parat 
                        geben. Hierbei nehme ich keinen direkten Bezug zu konkreten Pr&auml;paraten, halte 
                        jedoch einige, grunds&auml;tzliche Aspekte f&uuml;r sehr wichtig und erw&auml;hnenswert. 
                        <br />
                        <br />
                        Es stimmt: Verschiedene Bakterienarten k&ouml;nnen die Gesundheit der Darmschleimhaut 
                        f&ouml;rdern, und Bakterien der St&auml;mme Lactobacillus und Bifidobacillus stellen 
                        mit ihrem Stoffwechsel Laktase her, die unser Verdauungssystem zur Spaltung von 
                        Milchzucker nutzen kann. Es ist auch richtig, dass diese Bakterienarten mit ihrem 
                        Stoffwechsel ein g&uuml;nstiges, saures Milieu im Stuhl erzeugen, das die 
                        &Uuml;berlebensbedingungen von n&uuml;tzlichen Bakterienarten unterst&uuml;tzt 
                        &ndash; diese Behauptung ist also korrekt. 
                        <br />
                        <br />
                        Bisher war ich jedoch der Meinung, dass keine noch so gute Darmflora die Laktase-Produktion 
                        komplett &uuml;bernehmen kann &ndash; die Pr&auml;parate k&ouml;nnen meines Erachtens allenfalls zu 
                        einem kleinen Teil Laktose spalten. Somit ist und bleibt aus meiner Sicht das 
                        Mittel der Wahl immer eine weiterstgehend laktosefreie Ern&auml;hrung und im 
                        Notfall ein Laktase-Pr&auml;parat zus&auml;tzlich vor der Mahlzeit, wenn sich ein 
                        Laktoseverzehr nicht vermeiden l&auml;sst. Lesen Sie hierzu bitte auch den 
                        Beitrag <a href="behandlung">&#187;Behandlung&#171; der Laktose-Intoleranz</a>. 
                        <br />
                        <br />
                        Immer wieder tauchen auch Pr&auml;parate auf, die sowohl ein Probiotikum als auch 
                        Laktase enthalten (das erste mir bekannte Pr&auml;parat dieser Art &ndash; Dairy Care &ndash; habe ich im 
                        Jahr 2005 in den USA getestet). Hierbei ist zu bedenken, dass neben der &ndash; 
                        unstreitbar vorhandenen, wenn aber mit Sicherheit eher geringen &ndash; positiven 
                        Wirkung der enthaltenen Probiotika die zus&auml;tzliche Laktase bei der einmaligen 
                        Einnahme im g&uuml;nstigsten Falle eben nur einmal wirken kann, vorausgesetzt, 
                        das Pr&auml;parat wird gleichzeitig mit einer laktosehaltigen Mahlzeit eingenommen. 
                        Falls die Einnahme unabh&auml;ngig von einer solchen Mahlzeit erfolgt, dann kann 
                        die Laktase keinerlei Wirkung erzielen &ndash; ist also &#187;f&uuml;r die Katz&#171;. 
                        Meistens ist dar&uuml;ber hinaus die enthaltene Laktase-Dosis viel zu klein 
                        (meistens 1000 &ndash; 3000 FCC-Einheiten), um bei einer laktosehaltigen Mahlzeit 
                        ausreichend wirken zu k&ouml;nnen &ndash; alles in allem also eine in meinen 
                        Augen eher unverst&auml;ndliche Kombination. 
                        <br />
                        <br />
                        Ein weiterer &ndash; sehr wichtiger &ndash; Gesichtspunkt ist, dass manche Probiotika 
                        heftig &uuml;berdosiert sind oder zumindest in Kapselform mit fester Dosis nicht 
                        eingeschlichen werden k&ouml;nnen. Dies kann bei empfindlichen Verbrauchern zu 
                        Problemen f&uuml;hren: Probiotika m&uuml;ssen <b>immer</b> eingeschlichen werden, 
                        es muss also mit einer sehr kleinen Dosis begonnen werden, die dann nach und nach 
                        gesteigert werden sollte. Wird dieser Grundsatz nicht befolgt, sind Verdauungsbeschwerden 
                        wie Bl&auml;hungen bis hin zu heftigsten Durchf&auml;llen m&ouml;glich. Die Darmflora 
                        ist &ndash; auch wenn sie nicht die optimale Zusammensetzung hat &ndash; ein sehr 
                        empfindliches System, und Eingriffe, die auf die bestehende Balance einwirken,
                         m&uuml;ssen so behutsam wie m&ouml;glich vorgenommen werden. 
                        <br />
                        <br />
                        Grunds&auml;tzlich immer ist es zu begr&uuml;&#223;en, die Darmflora mit n&uuml;tzlichen 
                        Bakterien anzureichern, auch um die Vorteile, die diese in Bezug auf eine 
                        Laktose-Intoleranz unbestreitbar bieten, zus&auml;tzlich nutzen zu k&ouml;nnen. 
                        Eine gesunde Darmflora f&ouml;rdert nicht nur generell die Gesundheit, sie 
                        st&auml;rkt das Immunsystem und kann helfen, die Kapazit&auml;t der Laktase-Restfunktion 
                        ein wenig anzuheben. 
                        <br />
                        <br />
                        Ob Sie hier zu einem &ndash; anfangs niedrig dosierten, sp&auml;ter zu einem 
                        h&ouml;her dosierten &ndash; Probiotikum greifen m&ouml;chten, bleibt Ihnen 
                        &uuml;berlassen. Es ist jedoch durchaus auch m&ouml;glich &ndash; und in meinen 
                        Augen wesentlich sinnvoller, die Darmflora mit probiotischen Nahrungsmitteln wie 
                        milchsauer eingelegtem Gem&uuml;se oder auch Kombucha- oder Brottrunk-Getr&auml;nken 
                        und &Auml;hnlichem anzureichern, die dar&uuml;ber hinaus noch zus&auml;tzliche 
                        wertvolle Bestandteile wie Milch-, Essig und Glucurons&auml;ure enthalten, die 
                        f&uuml;r die n&uuml;tzlichen Mikroorganismen der Darmflora besonders g&uuml;nstig 
                        sind. 
                        <br />
                        <br />
                        Wenn Sie ein Probiotikum statt Laktase verwenden m&ouml;chten, empfehle ich Ihnen, 
                        zuerst die Vertr&auml;glichkeit zu testen, <b>ohne gleich zu Anfang Laktose zu verzehren</b>. 
                        Nur so k&ouml;nnen Sie ermessen, ob eventuell auftretende Beschwerden durch das 
                        Pr&auml;parat allein oder aber durch einen nicht mehr durch das Probiotikum gedeckten 
                        Laktose-&Uuml;berschuss verursacht werden. 
                        <br />
                        <br />
                        <b>Informieren Sie sich auf jeden Fall gr&uuml;ndlich, bevor Sie Ihre Entscheidung 
                        treffen.</b> 
                        <br />
                        <br />
                        Aber auch bei der Entwicklung der Probiotika wird ein Fortschritt stattfinden 
                        &ndash; genauso, wie das bei der Entwicklung von Laktase-Pr&auml;paraten der Fall 
                        war. Denn generell ist ja das Ziel sehr zu begr&uuml;&#223;en, in einer Gesellschaft, 
                        in der der Laktose-Verzehr an der Tagensordnung ist, Mahlzeiten auch 
                        mit Laktose-Intoleranz wieder unbeschwert genie&#223;en zu k&ouml;nnen, ohne sich 
                        Gedanken machen zu m&uuml;ssen, ob und in welcher Menge die Mahlzeit Milchzucker 
                        enth&auml;lt.
