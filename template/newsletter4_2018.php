                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=blog#blog-2018-07-02" target="_blank">Rezept f&uuml;r einen Zitronen-Aprikosenkern-Brotaufstrich</a></b>
                        <br />
                        Weil ich neugierig war, habe ich mir vor einiger Zeit ein Glas Aprikosenkern-/Mandelmus 
                        gekauft, war aber entt&auml;uscht. Es schmeckte (zumindest f&uuml;r mich) nach gar 
                        nichts und erzeugte au&#223;erdem ein unangenehm klebriges Mundgef&uuml;hl. Was also
                        tun mit diesem Produkt? Zum Wegwerfen war es nat&uuml;rlich viel zu schade und 
                        auch zu teuer. So stand es einige Wochen in meinem K&uuml;hlschrank, bis ich mir 
                        dachte, dass ich es nun, bevor es schlecht wird, verarbeiten m&uuml;sste. Mit ein 
                        paar wenigen Zutaten habe ich dann daraus einen fruchtig-zitronigen Brotaufstrich 
                        gezaubert. Versuchen Sie es doch auch einmal &ndash; der Geschmack ist &uuml;berraschend 
                        frisch.
                        <br />
                        Mehr Rezepte und viele andere Beitr&auml;ge finden Sie in meinem Blog &ndash; viel 
                        Spa&#223; beim St&ouml;bern.
                        <br />
                        <br />
                        <hr>
                        <br />
                        Liebe Leserinnen und Leser, 
                        es macht Spa&#223;, verschiedene Rezepte auszuprobieren oder auch Neues zu 
                        &#187;erfinden&#171;. Gerade, wenn Sie wegen einer Nahrungsmittel-Unvertr&auml;glichkeit 
                        oder einer low-FODMAP-Di&auml;t bei einer D&uuml;nndarmfehlbesiedelung bestimmte 
                        Lebensmittel (vor&uuml;bergehend) meiden sollten, ist es besonders wichtig, dass 
                        der Speisezettel abwechslungsreich bleibt und es Ihnen gut schmeckt, damit Ihnen 
                        nicht &#187;der Appetit vergeht&#171;. Machen Sie deshalb Ihre K&uuml;che zum 
                        Experimentierfeld und probieren Sie auch einmal Lebensmittel aus, die Sie bisher 
                        noch gar nicht in Betracht gezogen haben. Wie w&auml;re es mit einem spritzigen 
                        Getr&auml;nk aus Mineralwasser und M&auml;des&uuml;&#223;-Sirup? Dazu einfach 5 &ndash; 6
                        Bl&uuml;tendolden von der M&auml;des&uuml;&#223;pflanze sammeln, waschen und &uuml;ber 
                        Nacht mit einer kleinen in Scheiben geschnittenen Biozitrone in 1/2 Liter Wasser 
                        (oder auch Apfelsaft, falls bek&ouml;mmlich) im K&uuml;hlschrank ziehen lassen. 
                        Am n&auml;chsten Tag mit einer f&uuml;r Sie geeigneten Zuckerart (Haushalts- oder 
                        Traubenzucker oder Stevia) und von diesem Sirup einen Fingerbreit in ein Glas geben und
                        mit Mineralwasser auff&uuml;llen. Mehr Anregungen f&uuml;r weitere &#187;essbare Bl&uuml;ten&#171; 
                        und f&uuml;r vielleicht noch unbekannte, aber f&uuml;r Sie bek&ouml;mmliche Lebensmittel finden Sie in der 
                        <a href="http://www.dorispaas.de/index.php?page=lebensmittel-datenbank-info" target="_blank">DorisPaas.de &ndash; Lebensmittel-Datenbank</a>.
