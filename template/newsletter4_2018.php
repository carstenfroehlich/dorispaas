                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=darmfloragrundsatz" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-04-darmfloragrundsatz.png" alt="Bild Darmfloragrundsatz" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149; <a href="http://www.dorispaas.de/index.php?page=darmfloragrundsatz" target="_blank">Schwerpunktthema &#187;Grunds&auml;tzliches &uuml;ber die Darmflora</a></b>
                        <br />
                        Unsere Darmflora entwickelt sich im Laufe der ersten drei Lebensjahre, und ihre 
                        Zusammensetzung ist von vielen Faktoren abh&auml;ngig: Nicht nur die Art, wie wir 
                        geboren werden, entscheidet mit dar&uuml;ber, ob unsere Mikrobiota viele verschiedene 
                        Bakterien enth&auml;lt oder die Zahl eher begrenzt ist. Genauso wichtig ist es auch, 
                        wie wir in unseren ersten Lebensmonaten ern&auml;hrt wurden und unter welchen 
                        hygienischen Bedingungen wir aufgewachsen sind. Dies k&ouml;nnen wir nat&uuml;rlich 
                        r&uuml;ckwirkend nicht mehr beeinflussen und leider auch nicht, ob wir im Kinder- 
                        und Jugendalter Antibiotika einnehmen mussten. Aber f&uuml;r die Zukunft k&ouml;nnen 
                        wir selbst entscheiden bzw. mit unserem Arzt verhandeln, ob es erforderlich ist, 
                        mit diesen oder anderen Medikamenten und Nahrungserg&auml;nzungsmitteln unsere 
                        Darmflora zu ver&auml;ndern oder auch, was wir im Ernstfalle zum Schutz unserer 
                        kleinen Mitbewohner tun k&ouml;nnen.
                        <br />
                        Immer mehr Menschen klagen &uuml;ber die verschiedensten Schwierigkeiten mit der 
                        Verdauung &ndash; und an diesen Symptomen ist zu einem sehr gro&#223;en Teil auch 
                        eine mangelhafte Darmflora &#187;schuld&#171;. Dass die Qualit&auml;t der Darmflora 
                        bei Magen-/Darmproblemen eine Rolle spielt, hat sich mittlerweile bei den meisten 
                        Menschen herumgesprochen, und viele versuchen, ihre Probleme mit der Einnahme von 
                        Probiotika zu beheben. Die einschl&auml;gigen Internetforen sind voll von Hilferufen, 
                        wer welche Erfahrungen mit welchen Probiotika gemacht hat und welche helfen k&ouml;nnten. 
                        Der Beitrag &#187;Grunds&auml;tzliches &uuml;ber die Darmflora&#171; informiert 
                        umfassend &uuml;ber die Darmflora an sich, &uuml;ber die Wirkungen von Antibiotika, 
                        von Pro-, Pr&auml;- und Synbiotika, aber auch &uuml;ber viele andere Faktoren, die 
                        die Beschaffenheit der Darmflora und damit unsere Gesundheit beeinflussen k&ouml;nnen.
