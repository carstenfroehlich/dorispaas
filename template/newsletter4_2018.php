                        <h5>Ausgabe 41 (Juli 2018)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-04-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Mit dem Sommer kommen wieder die Ferien und f&uuml;r den einen oder anderen unter Ihnen 
                        auch die Reisezeit. Ich selbst konnte mich eine Woche lang in Frankreich erholen 
                        und in der Gegend um die Loire neben den Schl&ouml;ssern und Kathedralen auch die 
                        unvergleichlichen Naturlandschaften auf mich wirken lassen. Allein schon wegen der 
                        Jahreszeit gab es Blumen und Bl&uuml;ten im &Uuml;berfluss &ndash; so viele Mohnbl&uuml;ten 
                        auf einen Haufen habe ich noch nie gesehen. Ganze Felder waren in leuchtendes Rot getaucht 
                        &ndash; in Verbindung mit dem reifenden Getreide war dies ein unvergessliches Erlebnis.
                        Die Schl&ouml;sser lie&#223;en ahnen, in welchem Pomp die K&ouml;nige damals gelebt 
                        hatten: wundersch&ouml;ne Geb&auml;ude mit liebevollen Stuckarbeiten, kostbare M&ouml;bel, 
                        hunderte von Gem&auml;lden und feinste Wand- und Bodenverzierungen &ndash; eine 
                        Woche war definitiv viel zu wenig Zeit f&uuml;r all diese Herrlichkeiten. Auch die 
                        Kathedralen in dem schlankem, hohen gotischen oder dem eher gedrungenen, schweren 
                        romanischen Baustil waren mehr als eindrucksvoll. Wenn auch Sie demn&auml;chst 
                        eine Reise planen, schauen Sie doch einmal meine <a href="http://www.dorispaas.de/reiseberichte" target="_blank">Reiseberichte</a> 
                        an &ndash; ich nehme hier auch immer Bezug darauf, wie in den verschiedenen L&auml;ndern 
                        auf die Bed&uuml;rfnisse bei Nahrungsmittel-Unvertr&auml;glichkeiten eingegangen wird.
                        <br />
                        <br />
