                        Nahrungsmittel-Unverträglichkeiten unterscheiden sich u.a. auch dadurch von 
                        den Nahrungsmittel-Allergien, dass erst Beschwerden entstehen, wenn eine bestimmte, 
                        individuelle Mengenschwelle überschritten wird. Kleinere Verzehrmengen von 
                        unverträglichen Stoffe werden immer toleriert, und die Ausprägung der 
                        Beschwerden ist abhängig von der Verzehrmenge: Je mehr vom unverträglichen 
                        Stoff gegessen wird, desto unangenehmer werden die Probleme. Diese Mengenschwelle 
                        ist zwar immer individuell und hängt u.a. auch von der noch vorhandenen 
                        Restproduktion der erforderlichen Enzyme oder Transportsysteme ab, jedoch sind es 
                        immer im Vergleich zu den Allegien verhältnismä&#223;ig grö&#223;ere 
                        Mengen, die ohne Probleme toleriert werden. Bei Allergien hingegen genügen 
                        bereits allerkeinste Spuren des Allergens, um u.U. schwerste bis sogar lebensbedrohliche 
                        Symptome zu erzeugen.
                        <br />
                        <br />
                        Somit ist es später bei der Dauerbehandlung von Nahrungsmittel-Unverträglichkeiten 
                        nicht erforderlich, den oder die Auslöser komplett zu meiden. Es genügt, 
                        weitestgehend auf die unverträglichen Stoffe zu verzichten, um beschwerdefrei 
                        zu bleiben. Spuren dieser Stoffe machen dann keine Probleme.
                        <br />
                        <hr>
                        <h5>Nach der Diagnose</h5>
                        <hr>
                        Wenn vom Arzt die Diagnose &#187;Nahrungsmittel-Intoleranz&#171; gestellt wurde, 
                        nun also bekannt ist, ob man z.B. eine Laktose-oder Fruktose-Intoleranz oder eine 
                        Histamin-Intoleranz hat, ist es wichtig, nun zuerst alle eventuellen Auslöser
                        von Beschwerden zu meiden. Dies ist leichter gesagt als getan, zumal sehr viele 
                        Ärzte einen mit nur sehr wenigen hilfreichen Ratschlägen alleine lassen. 
                        <br />
                        <br />
                        Nach der Diagnose &ndash; wenn also meist ein längerer Leidensweg voller Beschwerden 
                        hinter einem liegt &ndash; müssen in Zukunft dauerhaft alle möglichen 
                        Beschwerdeauslöser weitestgehend gemieden werden. Nur dann kann sich auf Dauer 
                        der Darm regenerieren und eine Beschwerdefreiheit einsetzen.
                        <br />
                        <br />
                        Bevor jedoch mit der dauerhaften auslöser<b>armen</b> Ernährung begonnen 
                        werden kann, muss zuerst eine Zeitspanne mit einer konsequent und weitestgehend 
                        auslöser<b>freien</b> Ernährung eingehalten werden, bevor nach und nach 
                        ausgetestet werden kann, welche Lebensmittel die tatsächlichen Verursacher 
                        der Beschwerden sind. Diese gesamte Zeit nennt man Karenz. 
                        <br />
                        <hr>
                        <h5>Was bedeutet &#187;Karenz&#171;?</h5>
                        <hr>
                        Der Begriff &#187;Karenz&#171; bedeutet &#187;Wartezeit&#171; oder auch 
                        &#187;Sperrfrist&#171;. Bei der Behandlung 
                        von Nahrungsmittel-Unverträglichkeiten gibt es eine Phase der <b>absoluten</b> Karenz, 
                        also eine Zeit des konsequenten Verzichts aller möglichen Verursacher. Dann 
                        folgt anschlie&#223;end eine Aufbauphase, in der weiterhin möglichst viele 
                        Verursacher gemieden werden, jedoch durch das sukzessive Hinzufügen einiger 
                        zusätzlicher Lebensmittel ausgetestet wird, welche verträglich sind und 
                        welche in Zukunft besser dauerhaft weggelassen werden sollten.
                        <br />
                        <br />
                        Es gibt bei jeder Unverträglichkeit nicht nur &#187;DAS&#171; Lebensmittel, welches 
                        Beschwerden auslöst &ndash; es werden immer mehrere sein, und manche erzeugen 
                        mehr, manche weniger, manche hingegen sogar überhaupt keine Beschwerden. 
                        <br />
                        <br />
                        Die absolute Karenz, in der keinerlei dieser sicheren oder eventuellen Beschwerdeauslöser 
                        verzehrt werden, gibt dem Verdauungssystem Gelegenheit, sich zu beruhigen und zu 
                        erholen. Jeder halbherzige Versuch, mit einem (durch in der Vergangenheit verzehrten 
                        unverträglichen Nahrungsmitteln) gereizten Darm nun durch Weglassen einiger 
                        Verdächtiger eine dauerhafte Besserung erzielen zu wollen, ist mit gro&#223;er 
                        Sicherheit zum Scheitern verurteilt. Hinzu kommt, dass ohne eine detektivische Suche 
                        nach allen möglichen Verursachern auch gar keine grundsätzliche Beschwerdefreiheit 
                        erreichbar ist. 
                        <br />
                        <br />
                        Somit muss zuerst die absolute Karenz dem Verdauungssystem Gelegenheit geben, wieder 
                        normal zu funktionieren. Erst dann kann bei nachfolgenden Versuchen, bei denen 
                        bestimmte Lebensmittel wieder sukzessive in den Speiseplan eingebaut werden, erkannt 
                        werden, ob diese tatsächlich unverträglich oder doch verträglich 
                        sind.
                        <br />
                        <hr>
                        <h5>Fasten als Vorbereitung der Karenz</h5>
                        <hr>
                        Die sicherste Methode, eine wirklich absolute Karenz zu halten, ist das Fasten 
                        (lesen Sie hierzu den Beitrag &#187;<a href="nmu-fasten">Fasten 
                        als Vorbereitung der Karenz</a>&#171;). Beim Fasten wird neben Getränken 
                        (Wasser, Kräuter- oder Früchtetee) keinerlei Nahrung aufgenommen. Durch 
                        das Fasten kann sich das Verdauungssystem zum einen optimal erholen, und zum anderen 
                        besteht keine Gefahr, unbeabsichtigt Nahrungsmittel zu sich zu nehmen, die vielleicht 
                        doch nicht so gut vertragen werden. 
                        <br />
                        <br />
                        Allerdings ist es nicht immer möglich zu fasten, denn fasten bedeutet auch 
                        Anstrengung und Diziplin, die &ndash; zumal in stressigen Zeitspannen &ndash;  oftmals 
                        nicht möglich sind. Aber auch ältere oder kranke Menschen und vor allem 
                        Schwangere dürfen nicht fasten, und somit bleibt hier nur die Möglichkeit, 
                        nach bestem Wissen und Gewissen alle eventuellen Beschwerdeauslöser zu meiden 
                        und eine Kost zusammenzustellen, die möglichst frei von unverträglichen 
                        Nahrungsmitteln ist.
                        <br />
                        <hr>
                        <h5>Information ist wichtig!</h5>
                        <hr>
                        Bevor begonnen wird, diese in der Karenzeit weniger abwechslungsreiche Kost 
                        zusammenzustellen, ist es wichtig, dass man sich genau informiert, in welchen 
                        Lebensmitteln die unverträglichen Stoffe enthalten sein könnten. Somit 
                        ist das Einholen von umfangreichen Informationen über die persönliche(n) 
                        Nahrungsmittel-Unverträglichkeit(en) ein unbedingtes Muss, damit man nicht auf 
                        Nahrungsmittel verzichtet, die ganz bestimmt nichts mit der eigenen Unverträglichkeit 
                        zu tun haben können. Ansonsten würde der ohnehin schon stark eingeschränkte 
                        Speiseplan noch weiter zusammenschrumpfen &ndash; das ist nicht nötig. Und auf 
                        der anderen Seite dürfen natürlich auch keine Nahrungsmittel auf dem 
                        Plan stehen, die unverträgliche Stoffe enthalten.
                        <br />
                        <hr>
                        <h5>Karenz</h5>
                        <hr>
                        Sobald ermittelt wurde, welche Nahrungsmittel die unverträglichen Stoffe 
                        enthalten, ist ein Plan für ca. 2 Wochen aufzustellen, in dem keinerlei 
                        unverträgliche Nahrungsmittel verzehrt werden. In dieser Zeit der absoluten 
                        Karenz werden sich das Verdauungssystem beruhigen und die Beschwerden nachlassen. 
                        Sollte dies nicht der Fall sein, ist die Auswahl der Nahrungsmittel noch einmal 
                        einer kritischen Prüfung zu unterziehen und ggf. abzuändern.
                        <br />
                        <br />
                        Wenn über mehrere Tage keinerlei Beschwerden mehr aufgetreten sind, kann man 
                        nun dem Speiseplan ein weiteres Nahrungsmittel hinzufügen, das aller Voraussicht 
                        nach keine unverträglichen Bestandteile enthält. Treten weiterhin keine 
                        Beschwerden auf, kann man im Abstand von jeweils 2 Tagen den Speisezettel um ein
                        &#187;neues&#171; Nahrungsmittel erweitern. Sobald Probleme auftreten, ist 
                        das zuletzt hinzugefügte Nahrungsmittel sofort wegzulassen, bis wieder die 
                        Beschwerdefreiheit eingetreten ist. In diesem Fall ist <b>immer</b> im Anschluss 
                        eine zweitägige Erholungsphase einzuhalten, bevor neue Nahrungsmittel hinzugefügt 
                        werden. Am besten lässt man danach das betreffende Nahrungsmittel über 
                        einen längeren Zeitraum weg. Ggf. kann man es zu einem späteren Zeitpunkt erneut 
                        testen, denn leider ist es oftmals auch tagesformabhängig, ob Nahrungsmittel 
                        vertragen werden oder nicht. Und natürlich ist es auch immer die Summe, die 
                        zu Beschwerden führt. Wird ein Lebenmittel, das eine geringe Menge des 
                        unverträglichen Stoffes enthält, alleine verzehrt, passiert gar nichts. 
                        Verzehrt man jedoch mehrere solcher Lebensmittel, kommt in der Summe eine ganze 
                        Menge zusammen, die dann Beschwerden erzeugt.
                        <br />
                        <br />
                        Auch kann das Auftreten von Beschwerden mit dem Verzehrzeitpunkt zusammenhängen: 
                        ein und dasselbe Lebensmittel kann zum Mittag- oder Abendessen durchaus verträglich 
                        sein, wohingegen es beim Verzehr zum Frühstück auf nüchternen Magen 
                        Probleme macht.
                        <br />
                        <br />
                        Somit wird es sicherlich eine Weile dauern, bis man herausgefunden hat, was man in 
                        Zukunft vertragen wird und was eher nicht. Trotzdem lohnt es sich, diese Zeit der 
                        Karenz möglichst konsequent durchzuhalten, um später die Mahlzeiten mit 
                        einem abwechslungsreichen Speiseplan beschwerdefrei und mit einer hohen Lebenqualität 
                        genie&#223;en zu können.
                        <br />
                        <hr>
                        <h5>Suchdiät</h5>
                        <hr>
                        Die Karenz eignet sich ebenfalls zur so genannten Suchdiät, wenn mit verschiedenen Tests beim Arzt keine 
                        eindeutigen Ergebnisse erzielt werden konnten oder wenn man selber herausfinden 
                        möchte, welche Nahrungsmittel ggf. unverträglich sind. Die Vorgehensweise 
                        ist identisch wie oben beschrieben.
                        <br />
                        <br />
                        <b>Enzym-Präparate während der Karenz oder Suchdiät?</b>
                        <br />
                        Später, wenn man die Beschwerdeverursacher ermittelt hat, ist es in Notfällen 
                        möglich, die Bekömmlichkeit der entsprechenden Lebensmittel mit der gleichzeitigen 
                        Einnahme von Enzym-Präparaten zu steigern und einen beschwerdearmen oder sogar 
                        beschwerdefreien Verzehr zu ermöglichen.
                        <br />
                        <br />
                        In der Zeit der Karenz oder Suchdiät ist es jedoch nicht ratsam, Enzym-Präparate
                        einznehmen, weil damit die Suche nach Beschwerdeverursachern verwässert würde.
                        Somit muss diese Zeitspanne, die ja eine begrenzte und vorübergehende ist, 
                        zur Erzielung des optimalen Erfolgs ohne Ergänzungspräparate, jedoch mit 
                        Konsequenz durchgehalten werden.
