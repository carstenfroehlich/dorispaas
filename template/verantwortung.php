                        &#187;Die Gesundheit beginnt im Darm&#171; und &#187;du bist, was du isst&#171; &ndash; diese beiden Sprichworte 
                        (und viele andere, die ähnliches ausdrücken) zeigen ganz deutlich, wohin man bei Verdauungsbeschwerden schauen und wo man ansetzen muss. 
                        Trotzdem wird heute gerade bei Verdauungsproblemen viel zu selten nach den Ursachen geschaut und diese eigenverantwortlich abgestellt. 
                        (Nicht nur) ich behaupte, dass der allergrößte Teil der Symptome, die mit dem Verdauungssystem zusammenhängen, mit Änderungen des Lebensstils, 
                        der diese Probleme verursacht, abgestellt werden könnten &ndash; wenn ihnen nicht schon vorausschauend vorgebeugt würde, so dass sie gar 
                        nicht erst auftreten.
                        <br />
                        <a id="definition"></a>
                        <hr />
                        <h5>Gesundheit &ndash; was ist das?</h5>
                        <hr />
                        Was heißt es, &#187;gesund&#171; zu sein oder eine &#187;gesunde Verdauung&#171; zu haben? Kann man den Begriff &#187;gesund&#171; gleichsetzen 
                        mit &#187;nicht krank&#171;? Wohl kaum, denn dann gäbe es ja nur ein &#187;Entweder-oder&#171;, nur ein &#187;Schwarz&#171; und ein &#187;Weiß&#171;. 
                        Tatsächlich aber gibt es nicht nur zahlreiche Abstufungen, sondern darüber hinaus auch noch unterschiedliche Wahrnehmungen. Was der eine als &#187;gesund&#171; 
                        empfindet, mag für einen anderen bereits ein ungutes Gefühl auslösen. Und ein Krankheitsempfinden des einen kann vom anderen durchaus noch als 
                        &#187;normal&#171; interpretiert werden.
                        <br />
                        <br />
                        Ein Mensch, der eine &#187;<a href="verdauung" target="_blank">gesunde Verdauung</a>&#171; hat und der es gewöhnt ist, dass sein 
                        <a href="stuhlgang" target="_blank">Stuhlgang</a> immer zuverlässig und ohne Probleme verläuft, nimmt plötzlich auftretende Bauchschmerzen ganz anders wahr, 
                        als ein Mensch diese bewerten würde, der ständig irgendwelche Beschwerden mit der Verdauung hat. 
                        <br />
                        <br />
                        An dieser Stelle spreche ich nicht von vorübergehenden &#187;Unpässlichkeiten&#171;, deren Gründe auf der Hand liegen und die bekanntermaßen von selbst vergehen 
                        &ndash; eventuell unterstützt durch Hausmittel und Ruhe, sondern von dauerhafteren und/oder in kurzen Abständen wiederkehrenden Beschwerden, deren Ursachen nicht 
                        so offensichtlich sind.
                        <br />
                        <a id="ursachensuche"></a>
                        <hr />
                        <h5>Verantwortung zu übernehmen, heißt die Ursachen zu finden</h5>
                        <hr />
                        Wer sich richtig und dauerhaft krank fühlt, versucht in der Regel zunächst für sich selbst, Möglichkeiten zur Gesundung zu finden. Leider ist es heutzutage 
                        kaum noch üblich, sich über die Ursachen einer Erkrankung Gedanken zu machen, sondern gleich die Symptome zu bekämpfen. Die Apotheken bieten dafür ein reichhaltiges 
                        Sortiment an Präparaten an: Kopf- und Bauchweh werden mit Schmerztabletten &#187;behandelt&#171;, Verstopfung mit Abführmitteln und Durchfall mit Präparaten, die 
                        den Darm lähmen.
                        <br />
                        <br />
                        Auch &#187;Dr. Google&#171; ist ein gerne konsultierter &#187;Berater&#171;, und in <a href="internetrat" target="_blank">Internetforen</a> werden Tipps für 
                        &#187;hilfreiche&#171; Mittel gegen alle möglichen Erkrankungen heiß gehandelt. Selten wird hier nach der oder den Ursachen gefragt, und Äußerungen wie &#187;mir 
                        hat geholfen&#171; führen dann ohne das Hinterfragen der individuellen Voraussetzungen zum sofortigen Kauf und der Einnahme der vermeintlichen Wundermittel. 
                        Leider oft erst im Nachhinein stellt man fest, dass diese Produkte, für die man mit Sicherheit einiges bezahlt hat, überhaupt nichts bewirken oder &ndash; 
                        schlimmer noch &ndash; die Beschwerden sogar zunehmen. Ein gleiches Symptom kann ja durchaus bei verschiedenen Menschen ganz unterschiedliche Gründe haben &ndash; 
                        und dann hilft eben ein und dasselbe Mittel vielleicht bei dem einen, beim anderen aber eben nicht, oder zumindest nicht ausreichend und schon gar nicht dauerhaft.
                        <br />
                        <br />
                        Das Problem bei dieser Vorgehensweise ist, dass die Betroffenen sich keine Zeit nehmen, zunächst die Ursachen der Probleme zu ergründen und dann die Verantwortung 
                        zur Lösung nicht durch das Abstellen dieser Ursachen übernehmen, sondern <b>allein</b> einer Tablette übertragen: &#187;Wenn ich diese Pille/Kapsel/Tropfen nehme, werden meine 
                        Beschwerden verschwinden&#171;. Wodurch die Symptome ausgelöst wurden, wird nicht oder zumindest nicht ausreichend hinterfragt. 
                        <br />
                        <br />
                        Genau das aber ist wichtig &ndash; insbesondere bei Verdauungsproblemen. Aus diesem Grund habe ich für diesen Beitrag die Überschrift &#187;Verantwortung für die 
                        eigene Verdauung übernehmen&#171; gewählt. Es ist eben nicht &ndash; und schon gar nicht dauerhaft &ndash; zielführend, die Verantwortung für die eigene Verdauung 
                        auf ein Mittel zu übertragen. Selbst ein Arzt kann diese Verantwortung nicht übernehmen, denn der hat in der Regel kaum Zeit, mehr als einen kurzen Blick auf die Symptome 
                        zu werfen. Und schon gar nicht kann er etwas an den Ursachen ändern &ndash; im günstigsten Falle könnte er sie erkennen und dem Patienten die Augen öffnen. Aber dann 
                        muss der Betroffene diese Verantwortung selbst übernehmen &ndash; vor allem, wenn er die Symptome nachhaltig abstellen möchte. 
                        <br />
                        <a id="aenderungen"></a>
                        <hr />
                        <h5>Verantwortung zu übernehmen, heißt etwas zu ändern</h5>
                        <hr />
                        Wenn alles im Leben unverändert bleibt, wird sich auch nichts am Zustand der Gesundheit und der Verdauung ändern &ndash; schon gar nicht in positiver Richtung.
                        <br />
                        <br />
                        Nur, wenn man bei Beschwerden die <b>Ursachen findet</b> und hier etwas ändert, kann sich eine ungute Situation verbessern. Symptome mit einem Mittel zu lindern, 
                        mag vorübergehend Erleichterung verschaffen und deshalb in gewisser Weise legitim sein &ndash; ein dauerhafter Erfolg wird und kann sich jedoch nicht einstellen, 
                        denn die Ursache besteht ja weiter.
                        <br />
                        <br />
                        Dazu ist es natürlich unerlässlich, <b>das System zu verstehen</b>. Eine Ursache kann nur erkannt werden, wenn sich der <b>Zusammenhang mit den Symptomen</b> erschließt: nur 
                        was ich verstehe, kann ich ändern. Verantwortung heißt deshalb in einem ersten Schritt zu schauen, wie das Verdauungssystem funktioniert und an welcher Stelle es 
                        &#187;hakt&#171;. Nur so können wirksame Schritte zur Veränderung in Angriff genommen werden, die dann auch <b>nachhaltig</b> wirken können.
                        <br />
                        <a id="ernaehrung"></a>
                        <hr />
                        <h5>Verantwortung zu übernehmen, heißt die Ernährung zu überdenken</h5>
                        <hr />
                        Was nützt es, bei Verstopfung ein Abführmittel zu nehmen, wenn man zu wenige Ballaststoffe zu sich nimmt, ohne die die Verdauung gar nicht richtig funktionieren 
                        <b>kann</b>? Oder was nützt es, wenn man ein die Darmmotorik lähmendes Mittel bei Durchfall einnimmt, wenn dieser Durchfall durch unverträgliche Lebensmittel hervorgerufen 
                        wird? Isst man weiter wie bisher die Lebensmittel und setzt das entsprechende Medikament ab, werden die Verstopfung oder der Durchfall zurückkommen. Hat man 
                        Blähungen &ndash; beispielsweise durch eine <a href="duenndarmfehlbesiedelung" target="_blank">bakterielle Fehlbesiedelung</a> des Darms, reicht es eben nicht aus, 
                        nur ein entschäumendes Präparat einzunehmen, ohne die Dysbiose zu behandeln, denn die Gase werden ja, wenn die Ursachen nicht abgestellt wurden, weiterhin gebildet 
                        und richten mehr oder weniger Schaden im Darm an.
                        <br />
                        <br />
                        Ganz wichtig ist es also in einem ersten Schritt zu schauen, ob und ggf. welche <b>Beschwerden in Zusammenhang mit der Ernährung</b> auftreten. Hierzu bietet sich das Führen 
                        eines Verzehr- und Symptomtagebuches an, in dem Sie alles protokollieren, was Sie wann und in welcher Menge essen und trinken und welche Symptome wann und in welcher 
                        Intensität auftreten. Sie finden hierfür eine kostenlose Vorlage im <a href="downloads" target="_blank">Downloadbereich</a>. 
                        <br />
                        <br />
                        Die Mühe lohnt sich auf jeden Fall, denn die Eintragungen können rasch Aufschluss über Zusammenhänge mit bestimmten Symptomen aufzeigen.
                        <br />
                        <br />
                        Danach kann man zunächst die deutlichsten Verursacher <b>für eine kurze Zeit</b> meiden oder minimieren und schauen, ob sich etwas verbessert. Das Ziel ist es dann, einen Weg 
                        zu finden, welche Mengen man aus einer <b>möglichst großen Lebensmittelpalette</b> essen kann, um einerseits beschwerdefrei zu bleiben und andererseits möglichst abwechslungsreich 
                        zu essen, um den Darmbakterien das benötigte &#187;Futter&#171; anbieten zu können. Anregungen hierzu gibt die 
                        &#187;<a href="lebensmittel-datenbank-info" target="_blank"> DorisPaas &ndash; Lebensmittel-Datenbank</a>&#171;.
                        <br />
                        <a id="bewegung"></a>
                        <hr />
                        <h5>Verantwortung zu übernehmen, heißt das Bewegungsprofil zu überdenken</h5>
                        <hr />
                        Das Buch &#187;<a href="book-darmgymnastik" target="_blank">Darmgymnastik</a>&#171; beginnt und endet mit dem Satz &#187;Bewegung ist nicht alles, aber ohne Bewegung 
                        ist alles nichts.&#171;
                        <br />
                        <br />
                        <b>Gesunde Verdauung braucht Bewegung</b> &ndash; und zwar kontinuierlich in kurzen Intervallen über den ganzen Tag verteilt. Lediglich zwei Mal in der Woche ins 
                        Sportstudio zu gehen, ist sicherlich für die Fitness schön, für die Verdauung aber definitiv zu wenig.
                        <br />
                        <br />
                        Magen, Darm und die Verdauungsdrüsen brauchen Anregung durch Bewegung &ndash; Bewegung von der Bauchdecke und Bewegung vom Zwerchfell. Im Sitzen fehlen diese Anregungen, 
                        und nicht ohne Berechtigung gibt es den Spruch &#187;Sitzen ist das neue Rauchen&#171;. Das bedeutet, dass Sitzen ebenso schädlich für die Gesundheit und vor allem für 
                        die Verdauung ist, wie es auch das Rauchen ist.
                        <br />
                        <br />                        
                        Wenn ein Verdauungssystem dysfunktional ist und die Speisen nicht kontinuierlich vom Magen bis zum Ausgang transportiert werden und nicht alle Verarbeitungsschritte 
                        korrekt ablaufen, kann auch das &#187;Endergebnis&#171;, das wir in der Toilette sehen, nicht befriedigend sein.
                        <br />
                        <br />
                        Die korrekte Funktion des Verdauungssystems muss unbedingt mit der ausreichenden Bewegung unterstützt werden: der Darm und alle 
                        <a href="verdauungsdruesen" target="_blank"> Verdauungsdrüsen</a> sind &#187;faul&#171; und arbeiten nicht von allein. Sie müssen von außen angeregt werden: Von 
                        oben muss das Zwerchfell, mit dem wir <a href="atmen" target="_blank">atmen</a>, auf und nieder pumpen. Je intensiver wir atmen, desto mehr bewegt sich dieser Muskel, 
                        und auch die Bauchdecke dehnt sich kräftiger aus. Im Sitzen ist unser Atem flach, das Zwerchfell bewegt sich kaum, und der Bauch ist in der nach vorne gekrümmten Haltung 
                        in seiner Bewegung stark behindert. So bekommen weder der Darm noch die Verdauungsdrüsen die erforderliche Anregung, um die Verdauungsleistungen erbringen zu können.
                        <br />
                        <br />
                        Erst, wenn wir uns aufrichten &ndash; im Wortsinn und gerne auch im übertragenen Sinne &ndash; und dem Bauch Platz machen und tiefer atmen, bekommt das gesamte 
                        System die erforderlichen Impulse, und der Darm und die Verdauungsdrüsen können wieder arbeiten. Deshalb noch einmal: Bewegung ist immer und bei jeder Art von 
                        Verdauungsbeschwerden essentiell wichtig.
                        <br />
                        <a id="stress"></a>
                        <hr />
                        <h5>Verantwortung zu übernehmen, heißt das Stressprofil zu überdenken</h5>
                        <hr />
                        Dass sich Stress negativ auf die Verdauung auswirkt, ist eine Binsenweisheit und sollte sich mittlerweile herumgesprochen haben.
                        Hierzu müssen wir uns unsere beiden Nervensysteme, das sympathische und das parasympathische Nervensystem, anschauen, die auch bei uns &#187;modernen&#171; Menschen 
                        noch genauso funktionieren wie bei unseren Vorfahren. 
                        <br />
                        <br />
                        Der Sympathikus ist in Stresssituationen aktiv: erschien der Säbelzahntiger, musste das Leben gerettet werden. Alle großen Muskelgruppen wie diejenigen in den 
                        Beinen mussten zum Weglaufen und die in den Armen zum Werfen des Speers zum Erlegen des Raubtiers mit Blut und Sauerstoff versorgt werden. Das Herz schlug kräftiger, 
                        der Atem ging schneller. Alles, was nicht fürs Überleben wichtig war, wurde heruntergefahren &ndash; wie u.a. auch die Verdauung. Heute ist es zwar nicht mehr der 
                        Säbelzahntiger, der uns stresst, aber wir haben genügend andere Situationen, die gehörigen Stress machen.
                        <br />
                        <br />
                        Der Parasympathikus ist unser Verdauungs- und Entspannungs-Nerv: Ist keine Gefahr in Sicht, können wir entspannen, uns ausruhen und alle Systeme regenerieren 
                        &ndash; und auch verdauen.
                        <br />
                        <br />
                        Es kann nur immer ein Nervensystem aktiv sein: <b>Entweder</b> der Sympathikus <b>oder</b> der Parasympathikus. Das heißt, dass unser Verdauungssystem in 
                        Stresssituationen nicht oder zumindest nur reduziert arbeitet. Wenn unser Stresslevel den ganzen Tag lang hoch ist, <b>arbeitet die Verdauung den gesamten Tag höchstens 
                        auf Sparflamme</b>. Kein Wunder also, dass all diejenigen Menschen, die ihren Stress nicht in den Griff bekommen, dafür mit Verdauungsproblemen bezahlen müssen.
                        <br />
                        <br />
                        Es ist also unerlässlich, zu schauen, welchen Stress man abstellen und sich vom Halse halten kann, ob man bestimmte Stresssituationen zumindest abmildern kann oder, 
                        wenn das gar nicht geht, solche Gegebenheiten zumindest durch Entspannung kompensieren kann. Lesen Sie hierzu gerne den Beitrag 
                        &#187;<a href="ganz-entspannung" target="_blank"> Entspannung</a>&#171;.
                        <br />
                        <a id="nahrungsergaenzungsmittel"></a>
                        <hr />
                        <h5>Verantwortung zu übernehmen, heißt auch die Nahrungsergänzungsmittel zu überdenken</h5>
                        <hr />
                        Nicht jedes Nahrungsergänzungsmittel muss schlecht sein, und ich behaupte keineswegs, dass man grundsätzlich bei Verdauungsstörungen keinerlei Nahrungsergänzungsmittel 
                        einnehmen darf. Es gehört aber zur Übernahme von Verantwortung unbedingt dazu, <b>die Auswahl dieser Präparate besonders klug zu treffen</b> und <b>die Anzahl der verschiedenen 
                        Produkte so weit wie möglich einzuschränken</b>. Und dies ist beileibe keine leichte Aufgabe, denn die allermeisten Hersteller verstehen es perfekt, ihre Mittel als das 
                        Nonplusultra bei fast jeder Art von Verdauungsstörungen und für so gut wie jeden Anwender anzupreisen.
                        <br />
                        <br />
                        Welche Inhaltsstoffe &ndash; brauchbar oder (leider auch sehr häufig) eher entbehrlich &ndash; in dem Präparat enthalten sind, ist meistens erst auf den zweiten oder 
                        dritten Blick ersichtlich. Und wofür diese Inhaltsstoffe hilfreich sein sollen, steht in der Regel nicht in den Beschreibungen. Dies darf ein seriöser Hersteller auch 
                        meist nicht, denn der Gesetzgeber verbietet mit der sogenannten &#187;Healthclaims-Verordnung&#171; gesundheitsbezogene Behauptungen, wenn nicht wissenschaftliche 
                        Studien die Wirksamkeit belegen. Da solche Studien teuer sind, werden Umwege gefunden: Ist einer der Inhaltsstoffe mit einem Healthclaim abgesichert (beispielsweise 
                        ein Vitamin), nutzen die Hersteller dies schamlos aus, obwohl sich der Mehrwert keineswegs auf das gesamte Produkt auswirkt und diese Zutat eventuell sehr wenig mit 
                        der Indikation zu tun hat. Bitte lesen Sie hierzu auch den Beitrag &#187;<a href="nahrungsergaenzungsmittel" target="_blank">Grundsätze von Nahrungsergänzungsmitteln</a>&#171;.
                        <br />
                        <br />
                        Mit all diesen Hintertüren kann es für den Laien sehr schwierig sein, einen grundsätzlichen Nutzen zu erkennen. Und noch viel schwieriger ist es, einen Nutzen bei 
                        den individuellen Voraussetzungen zu erkennen, um die ja kein Hersteller wissen kann. Deshalb bedeutet es, Verantwortung für die eigene Verdauungs zu übernehmen, die 
                        Auswahl eines Mittels nach Möglichkeit mit einem erfahrenen und spezialisierten Berater zusammen zu treffen, der eine sorgfältige Anamnese erhoben hat und so einen 
                        umfassenden Eindruck von der Gesamtlage bekommt. Er hat Erfahrungen mit geeigneten Präparaten, grenzt die Menge der benötigten Produkte ein und vermeidet so 
                        nicht nur teure Fehlkäufe, sondern auch mögliche Neben- und Wechselwirkungen.
                        <br />
                        <br />
                        Deshalb ist es auf jeden Fall verantwortungsvoll, nicht wahllos haufenweise Nahrungsergänzungsmittel einzunehmen, die oft das Verdauungssystem eher belasten als etwas 
                        Positives zu bewirken, sondern nur sehr vorsichtig vorzugehen. Denn noch einmal: Die Verantwortung für die eigene Verdauung kann eben nicht allein auf ein oder mehrere
                        Präparate übertragen werden.
                        <br />
                        <a id="arbeit"></a>
                        <hr />
                        <h5>Verantwortung zu übernehmen, bedeutet (Mit-)Arbeit</h5>
                        <hr />
                        Aus den vorigen Abschnitten ergibt sich ganz automatisch die Erkenntnis, dass es (Mit-)Arbeit bedeutet, wenn man Verantwortung für die eigene Gesundheit und eine 
                        funktionierende Verdauung übernehmen will. Das ist korrekt.
                        <br />
                        <br />
                        Je nachdem, wie &#187;schlimm&#171; es um die Verdauung steht, desto größer und schwerer wird diese Arbeit sein. Das Wort &#187;mit&#171; ist hier in Klammern geschrieben, 
                        weil Sie diese Arbeit nicht unbedingt alleine in Angriff nehmen müssen, sondern sich durchaus auch um Mithilfe bemühen dürfen &ndash; schon allein auch deshalb, damit 
                        (erfolglose) Arbeit nicht in zusätzlichen Stress ausartet. Vergeuden Sie deshalb nicht Ihre Zeit, Ihre Mühe und auch Ihr Geld, diese Mithilfe bei Menschen im Bekanntenkreis 
                        oder in Internetforen suchen zu wollen. Ich zweifle keineswegs an, dass deren Ratschläge gut gemeint sind, aber ohne ein intensives Hinterfragen Ihrer ganz individuellen 
                        Gegebenheiten kann kein Ratschlag qualifiziert sein. Und ich denke auch nicht, dass Sie alle Ihre persönlichen Voraussetzungen und Symptome vor Ihren Bekannten oder &ndash; 
                        noch unwahrscheinlicher &ndash; im Internet auswalzen wollen. 
                        <br />
                        <br />
                        Dies kann nur ein möglichst ganzheitlich orientierter Therapeut oder Berater leisten, der mit Ihnen eine sorgfältige Anamnese erstellt. Ein solcher Berater hat dann 
                        sicherlich Ideen, wo eventuelle Ursachen für bestimmte Symptome liegen könnten. Danach kann er mit Ihnen gemeinsam einen für Sie und Ihre individuelle Situation gangbaren 
                        Weg finden, wie und wo Sie am besten ansetzen können. Auf jeden Fall vermeiden Sie so Irrwege und einen unnötig verlängerten Leidensweg, denn mit den richtigen Wegweisern 
                        kommen Sie eher ans Ziel.
                        <br />
                        <br />
                        Diesen Weg werden Sie dann jedoch alleine gehen müssen. Kein Arzt, kein Heilpraktiker und kein Berater kann Sie über längere Zeit an die Hand nehmen und führen. Aber er 
                        kann Sie mit Informationen versorgen und Sie motivieren, <b>die Arbeit anzupacken</b>.
                        <br />
                        <br />
                        Ich möchte Ihnen ein buddhistisches Sprichwort mit auf Ihren Weg geben: &#187;Löse das wichtigste Problem, dann hast du Zeit für die anderen&#171;. Damit will ich sagen, 
                        dass Sie <b>nicht alle Arbeit auf einmal erledigen</b> müssen. Setzen Sie &ndash; gerne auch mit Ihrem Therapeuten oder Berater &ndash; Prioritäten und <b>fangen Sie mit 
                        dem wichtigsten Problem an</b>. Damit können Sie die Gesamtlage bereits so weit verbessern, dass Sie Kapazitäten für weitere Arbeitsschritte haben werden. Auch wenn Ihr Weg 
                        vielleicht ein längerer sein wird, sollten Sie Teilerfolge würdigen und sich dadurch ermutigt fühlen, diesen Weg weiterzugehen. Nutzen Sie auch gerne das 
                        &#187;<a href="downloads#bilanzprotokoll" target="_blank">Bilanz-Protokoll</a>&#171; aus dem Download-Bereich, um sich zu motivieren. 
                        <br />
                        <br />
                        <b>Alles, was Sie in positivem Sinne verändern, bringt Sie Ihrem Ziel näher &ndash; bleiben Sie jedoch stehen, kommen Sie nicht vom Fleck.</b>

