                        <hr>
                        <h5>Anwendungsgebiete von Vitalpilzen</h5>
                        <hr>
                        Vitalpilze können <b>vorbeugend</b>, aber auch <b>heilend</b> eingesetzt werden. Vor allem aber ist es ihre <b>ausgleichende, regulierende Wirkung</b>, die sie besonders 
                        wertvoll machen. 
                        <br />
                        <br />
                        Die Mykotherapie ist ein wichtiger Bereich in der Naturheilkunde, und die Anwendungsgebiete von Vitalpilzen sind sehr breit gefächert. <b>Jede Art hat ihre ganz 
                        speziellen Wirkungen</b>, die sich teilweise ideal ergänzen. Alle haben jedoch einen hohen Anteil an Mineralstoffen 
                        und Vitaminen, aber auch Polysaccharide (Ballaststoffe) sind enthalten, die einen regulierenden Einfluss auf die Darmflora haben. Viele Arten wirken stabilisierend 
                        auf das Immunsystem und stärken die körperliche Belastbarkeit. Sogar zur Unterstützung bei Krebstherapien werden 
                        Vitalpilze sehr erfolgreich eingesetzt, wobei sie teils direkt die Tumorrückentwicklung unterstützen bzw. die Neuentwicklung hemmen, vor allem aber die Nebenwirkungen 
                        von chemotherapeutischen Substanzen und Strahlenbelastungen reduzieren können.
                        <br />
                        <br />
                        <b>Hier an dieser Stelle soll hervorgehoben werden, dass Vitalpilze ganz entscheidend 
                        bei den verschiedensten Verdauungsproblemen helfen können. </b>
                        <br />
                        <br />
                        Angefangen bei Magen- und insbesondere bei <a href="reflux" target="_blank">Refluxbeschwerden</a> können bestimmte Vitalpilzarten mit Erfolg eingesetzt werden.
                        <br />
                        <br />
                        Andere Arten wirken <b>anregend und regulierend auf das Verdauungssystem</b> und den Stoffwechsel und können &ndash; je nach den individuellen 
                        Gegebenheiten und Voraussetzungen &ndash; Anwendung finden. Sowohl bei <b>Verstopfung</b> als auch bei <b>Blähungen</b> und <b>Durchfällen</b> sind Vitalpilze geeignet.
                        <br />
                        <br />
                        Auch ein <b>Leaky-Gut-Syndrom</b> oder eine <b>entzündete Darmschleimhaut</b> können mit Vitalpilzen günstig beeinflusst werden.
                        <br />
                        <br />
                        Vitalpilze sind auch ein <b>interessanter Ersatz für Probiotika</b>, denn oft ist der Einsatz dieser Präparate, die lebende Mikroorganismen enthalten, eher 
                        ein Versuch, bei dem geschaut wird, ob die erwünschte Wirkung eintritt. Vitalpilze hingegen unterstützen, dass die Mikrobiota (Darmflora) selbst 
                        wieder zu ihrer gesunden Balance zurückfindet. So haben sie ihr Einsatzgebiet ganz besonders auch bei Fehlbesiedelungen des Darms, der Dünndarmfehlbesiedelungen 
                        (<b>SIBO/IMO</b>) und/oder Dickdarmfehlbesiedelungen (<b>Dysbiose</b>).
                        <br />
                        <br />
                        Durch ihre zahlreichen Anwendungsgebiete können Vitalpilze nicht nur vorbeugend eingesetzt werden, so dass Erkrankungen erst gar nicht entstehen und so <b>den Einsatz 
                        von <a href="antibiotika" target="_blank">Antibiotika</a> minimieren</b>. Aber in einigen Fällen kann die Einnahme von geeigneten Vitalpilzarten in Rücksprache mit 
                        dem Arzt und unter dessen Aufsicht auch anstelle eines Antibiotikums erwogen werden.
                        <br />
                        <a id="wirkung">&nbsp;</a>
                        <hr>
                        <h5>Adaptogene Wirkung</h5>
                        <hr>
                        Die in den Vitalpilzen enthaltenen Substanzen wirken nicht &ndash; wie pharmazeutische Medikamente &ndash; für oder gegen ein bestimmtes Problem, sondern 
                        <b>ausgleichend (adaptogen)</b>, d.h. sie können dazu beitragen, beim Patienten Zustände auszugleichen, die sich im Ungleichgewicht befinden. Ein Beispiel 
                        unter vielen sind hier Durchfall oder auch Verstopfung: beide können mit dem gleichen Vitalpilz behandelt werden.
                        <br />
                        <a id="darreichungsformen">&nbsp;</a>
                        <hr>
                        <h5>Darreichungsformen</h5>
                        <hr>
                        Natürlich können Sie den frischen Pilz essen &ndash; und wahrscheinlich wird zumindest der Champignon oder seit einiger Zeit auch der Austernpilz ab und an auf Ihrem 
                        Speisezettel stehen. 
                        <br />
                        <br />
                        Als &#187;Vitalpilz&#171; wird entweder <b>der ganze Pilz getrocknet</b> und gemahlen oder aber er wird in Form von <b>Extrakten</b> verabreicht. Je feiner das Pulver 
                        vermahlen ist, das in <b>Kapseln</b> angeboten wird, desto besser ist die Wirkung. Man kann entweder &#187;nur&#171; den ganzen, vermahlenen Pilz oder den Extrakt einnehmen, 
                        oft werden auch beide Formen miteinander kombiniert, um die Wirkungen zu ergänzen. Für Menschen mit Problemen bei der Einnahme von Kaspeln sind Vitalpilzprodukte auch 
                        als <b>Tropfen</b> erhältlich.
                        <br />
                        <a id="dosierung">&nbsp;</a>
                        <hr>
                        <h5>Dosierung</h5>
                        <hr>
                        Es gibt keine allgemeingültige Dosierung für Vitalpilze &ndash; immer hängt dies von der Erkrankung, aber vor allem auch vom Erkrankten selbst ab. Kinder und 
                        Erwachsene nehmen selbstverständlich unterschiedliche Mengen ein. Wenn Sie sich für die Anwendung von Vitalpilzen interessieren, sollten Sie bitte nie in Eigenregie 
                        vorgehen, sondern sich von einem <b>ausgebildeteten und erfahrenen Mykotherapeuten</b> beraten lassen und dessen Expertise für sich und ihre Gesundheit nutzen. Die 
                        Auswahl der geeigneten Vitalpilze und deren Dosierung ist &ndash; wie eigentlich immer auch bei allen anderen natürlichen Präparaten &ndash; keineswegs trivial, sondern 
                        erfordert neben der Diagnose auch die kompetente Einschätzung Ihrer individuellen Bedingungen.
                        <br />
                        <br />
                        Wichtig ist auf jeden Fall, dass die Dosierung aller <b>Vitalpilze immer eingeschlichen</b> werden muss. D.h. man beginnt vorsichtig mit einer kleinen Dosierung und 
                        steigert diese über einige Wochen, bis man die vorgesehene, komplette Dosis erreicht.
                        <br />
                        <a id="anwendungsdauer">&nbsp;</a>
                        <hr>
                        <h5>Anwendungsdauer</h5>
                        <hr>
                        Bei Beschwerden sollten Vitalpilze in der Regel über einen Zeitraum von zunächst <b>6 Monaten</b> eingenommen werden, um eine Besserung zu festigen. Später können 
                        geeignete Vitalpilze die weitere Stabilisierung und/oder Vorbeugung mit einer Einnahme von 3 Monaten pro Jahr sichern.
                        <br />
                        <a id="nebenwirkungen">&nbsp;</a>
                        <hr>
                        <h5>Nebenwirkungen</h5>
                        <hr>
                        Die meisten Vitalpilze haben &ndash; wenn sie richtig und mit Bedacht eingesetzt werden &ndash; keine Nebenwirkungen. Es gibt aber auch bei diesen Präparaten einige 
                        Kontraindikationen. Deshalb noch einmal der dringende Hinweis, auch diese Präparate nicht in Eigenregie oder z.B. aufgrund von &#187;Empfehlungen&#171; aus einschlägigen 
                        <a href="internetrat" target="_blank">Internetgruppen</a> einzunehmen. Was einem anderen geholfen hat, muss für die eigene, individuelle Situation keineswegs unproblematisch sein.
                        <br />
                        <a id="wechselwirkungen">&nbsp;</a>
                        <hr>
                        <h5>Wechselwirkungen mit anderen Medikamenten</h5>
                        <hr>
                        Auch, wenn andere Medikamente eingenommen werden (müssen), können <b>Vitalpilze ergänzend eingesetzt</b> werden. Auf keinen Fall dürfen von heute auf morgen die bisherigen 
                        Medikamente weggelassen und durch Vitalpilze ersetzt werden. Wenn jedoch nach einiger Zeit eine Besserung eintritt, kann in Rücksprache mit dem verordnenden Arzt ggf. 
                        das pharmazeutische Medikament reduziert und in einigen Fällen auch ganz weggelassen werden.
                        <br />
                        <a id="qualitaet">&nbsp;</a>
                        <hr>
                        <h5>Qualität</h5>
                        <hr>
                        Wie alle <a href="nahrungsergaenzungsmittel" target="_blank">Nahrungsergänzungsmittel</a>, unterliegen Vitalpilze nicht der Arzneimittelkontrolle und sind frei verkäuflich. Es ist jedoch zu befürchten, dass sich auch hier 
                        schwarze Schafe einen Teil des Kuchens am Markt abschneiden wollen und Vitalpilzprodukte aus dubiosen Quellen anbieten &ndash; insbesondere im Internet. Wenn Sie ein 
                        Vitalpilz-Präparat einnehmen wollen, fragen Sie Ihren Behandler immer nach der <b>Zertifizierung</b> für das jeweilige Präparat, die bescheinigt, dass das Produkt unbedenklich ist 
                        und keine Schadstoffe enthält.
                        <br />
                        <br />
                        Bevor Sie ein Vitalpilz-Präparat kaufen wollen, sollten Sie sich bitte sowohl zur Auswahl geeigneter Pilzsorten als auch zu empfehlenswerten Bezugsadressen beraten lassen.
                        Ich selbst bin <b>ausgebildete Mycoberaterin</b> und biete Ihnen gerne <a href="beratung" target="_blank">meine Hilfe</a> an.
                        <br />
                        <a id="fazit">&nbsp;</a>
                        <hr>
                        <h5>Fazit</h5>
                        <hr>
                        Für Verdauungsprobleme jeder Art bieten Vitalpilze zahlreiche Möglichkeiten, eine Therapie zu unterstützen und eine Besserung zu erzielen und zu stabilisieren. Der 
                        &#187;richtige&#171; Pilz bzw. die &#187;richtige&#171; Kombination von Vitalpilzen zum &#187;richtigen&#171; Zeitpunkt eingenommen können helfen, Symptome zu lindern, 
                        die Ursache zu beheben und einen <b>dauerhaften Erfolg</b> zu unterstützen.
