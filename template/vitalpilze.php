                        <h5>Welche Vitalpilze gibt es? </h5>
                        <hr>
                        Zu den Vitalpilzen zählen u.a. zwölf Arten, von denen Ihnen zumindest einer ganz bestimmt bekannt ist: der Champignon (Agaricus bisporus). Die weiteren Arten haben teils sehr 
                        interessante Namen:
                        <br />
                        &#149; Agaricus blazei Murrill, ABM (Sonnen- oder Mandelpilz)
                        <br />
                        &#149; Auricularia polytricha (Judasohr)
                        <br />
                        &#149; Coprinus comatus (Schopftintling)
                        <br />
                        &#149; Cordyceps sinensis (Chinesische Raupenpilz)
                        <br />
                        &#149; Coriolus versicolor (Schmetterlingstramete)
                        <br />
                        &#149; Hericium erinaceus (Igelstachelbart)
                        <br />
                        &#149; Maitake (Klapperschwamm)
                        <br />
                        &#149; Pleurotus ostreatus (Austernpilz)
                        <br />
                        &#149; Polyporus umbellatus (Eichhase)
                        <br />
