                        Pilze sind eine eigene Form im Pflanzenreich und den meisten entweder als schmackhafte Zutat zu einer Mahlzeit oder aber als giftige Gefahr bekannt. Auch die halozinogene, 
                        berauschende Wirkung oder auch die Möglichkeit, mit Giftpilz-Gerichten unliebsame Mitmenschen beseitigen zu können, haben zumindest in der Kriminalliteratur ihre 
                        Plätze. Dass bestimmte Pilze aber auch Heilwirkungen haben, wissen die wenigsten.
                        <br />
                        <br />
                        Vitalpilze &ndash; berechtigterweise oft auch als Heilpilze bezeichnet &ndash; werden seit langer Zeit in der östlichen Medizin verwendet, aber auch die westliche 
                        Klostermedizin nutzte die Heilkräfte der Pilze. Nur sehr zaghaft hat sich bei uns bis heute die Erkenntnis durchgesetzt, was diese kleinen Wunderwerke der Natur leisten können. 
                        Dabei ist gerade bei Verdauungsproblemen der Einsatz von Vitalpilzen besonders hilfreich.
                        <br /> 
