                        Laktose-Intoleranz &#0150; ist das eine Krankheit? Nein, sie ist der 
                        Normalfall bei 90% der Weltbevölkerung, nur hier bei uns ist es 
                        umgekehrt und die Milchzucker-Unverträglichkeit noch sehr unbekannt. 
                        Die wenigsten kennen die Ursache ihrer Beschwerden und können sich die 
                        Hintergründe für ständige Blähungen oder Durchfälle 
                        erklären.
                        <br />
                        <br />
                        DAS LAKTOSE-INTOLERANZ BUCH unterscheidet sich von der gesamten zum Thema 
                        bereits erschienen Literatur, denn es verzichtet weitgehend auf weniger 
                        aussagekräftige Bilder oder Diagramme zugunsten von echten Informationen: es beschreibt nicht nur die 
                        Laktose-Intoleranz (LI) an sich, sondern umfasst den gesamten Themenkreis um das Leben mit LI, 
                        angefangen bei der Definition, was Milchzucker-Unverträglichkeit überhaupt 
                        ist und welche Beschwerden sie verursacht, über die chemischen und physiologischen 
                        Zusammenhänge, bis hin zu den unterschiedlichen Verteilungen 
                        der LI-Betroffenen auf der Landkarte. Es wird ein Versuch unternommen, zu 
                        hinterfragen, wodurch sich eine Laktose-Intoleranz entwickelt und erläutert, 
                        wie man eine Diagnose sicher stellen (lassen) kann. Begleitsymptome werden genauso 
                        beleuchtet wie eventuelle Folge-Erkrankungen. 
                        <br />
                        <br />
                        Ein weiterer Abschnitt weist darauf hin, dass Laktose-Intoleranz im Alter etwas 
                        ganz Natürliches ist und geht speziell auf die Bedürfnisse älterer 
                        Menschen ein. Das Thema &#187;Reizdarm-Syndrom&#171; wird ebenso ausführlich erörtert, 
                        da die meisten laktoseintoleranten Menschen davon betroffen sind. 
                        Es werden andere Nahrungsmittel-Unverträglichkeiten und 
                        Abgrenzungsmöglichkeiten aufgezeigt, Enzym-Ergänzungsmittel und deren 
                        Anwendung ausführlich besprochen und viele praktische Tipps zu deren Gebrauch 
                        gegeben. Das Buch legt dar, wie Darmschleimhaut und Darmflora saniert werden 
                        können und warum dies wichtig ist. 
                        <br />
                        <br />
                        Es gibt Kapitel über allgemeine Ernährungsrichtlinien und Grundsätze 
                        für eine gesunde Ernährung, denn nur mit ausreichenden Kenntnissen 
                        über diese Bereiche können Sie Ihre Ernährungsumstellung, 
                        für die es eine detaillierte Anleitung gibt, in die richtige Richtung lenken.
                        <br />
                        <br />
                        Zusätzlich werden viele hilfreiche Ratschläge zum Leben mit der LI 
                        gegeben, aus denen Sie sich die für Ihre persönlichen Bedürfnisse 
                        ma&#223;geschneiderten zusammenstellen können. Nicht vergessen wird dabei Ihr 
                        physisches und psychisches Gleichgewicht, da Körper und Seele eine Einheit 
                        bilden, und die Laktose-Intoleranz nicht nur als ein losgelöstes Problem betrachtet 
                        werden darf. Kleine Übungsanleitungen sollen Appetit auf mehr machen und 
                        Sie anregen, die eine oder andere Gymnastik und Entspannungstechnik in Kursen 
                        oder mithilfe weiterführender Literatur zu erlernen.
                        <br />
                        <br />
                        Ein ausführlicher Anhang mit einfachen, &#187;schnellen&#171; Rezepten für 
                        die ersten Wochen, Hilfen für den Einkauf, ein Infoblatt für Ihre Freunde, 
                        Übersetzungshilfen in 13 Sprachen für Reisen in fremde Länder und 
                        Adressen und Links vervollständigen das Buch. 
                        <br />
                        <br />
                        Da das Buch in erster Linie für Sie als Betroffene(n) geschrieben ist, ist 
                        es weitgehend frei von Fachausdrücken. Falls sich diese nicht vermeiden 
                        lie&#223;en, sind sie im Text und zusätzlich in einem umfangreichen 
                        Glossar erklärt. Auf diese Weise können Sie nicht nur die 
                        Zusammenhänge verstehen, Sie werden auch in die Lage versetzt, sich mit 
                        Ihrem Arzt über Ihre Laktose-Intoleranz auseinandersetzen zu können.
                        <br />
                        <br />
                        Kurz gesagt: das Laktose-Intoleranz Buch erklärt wirklich alles, was Sie 
                        über die Milchzucker-Unverträglichkeit wissen möchten. 
                        <br />
                        <br />
                        Lassen Sie sich von der Fülle der Kapitel nicht erschrecken, und nehmen 
                        Sie sich Zeit, die Informationen nach und nach aufzunehmen. Ein umfassendes 
                        Stichwortverzeichnis hilft Ihnen, das Buch auch später noch als 
                        Nachschlagewerk zu benutzen. Betrachten Sie die zahlreichen Hinweise als 
                        Anregungen, die Sie bei Bedarf für ein gutes Leben mit Ihrer 
                        Laktose-Intoleranz nutzen können, wenn Sie möchten.
                        <br />
                        <br />
                        DAS LAKTOSE-INTOLERANZ BUCH soll alle Menschen ansprechen, die Informationen über 
                        die Milchzucker-Unverträglichkeit benötigen; die unter unklaren Verdauungsbeschwerden 
                        leiden; Menschen, die aufgrund jahrelanger Beschwerden verunsichert sind und 
                        eine Ursache für ihr Leiden suchen. Zusätzlich kann es als 
                        wissenschaftlich sorgfältig recherchierte Information für Ärzte 
                        und Ernährungsberater dienen und sie sensibilisieren, eine Laktose-Intoleranz 
                        in Erwägung zu ziehen. Aufgrund des gro&#223;en Umfangs sind in diesem Buch 
                        mit Sicherheit auch noch für &#187;alte Hasen&#171; neue Informationen enthalten, 
                        so dass es sich für jeden lohnt, einen Blick hinein zu werfen.
