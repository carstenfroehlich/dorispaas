                        Erinnern Sie sich noch daran, wie Sie als Kind gerne geschaukelt haben? Manchmal in einem monotonen und beruhigenden Rhythmus von sanftem Auf und Ab, zu anderen 
                        Zeiten auch in spannenden und aufregenden hohen Ausschlägen der Schaukel &#187;bis in den Himmel&#171; und wieder zurück zur Erde. Aber nicht nur Kinder lieben Rhythmen.
                        <b>Das ganze Leben ist Rhythmus.</b> Wir sind eingebettet in einen natürlichen Rhythmus von Jahreszeiten mit Kälte und Wärme und in einen Rhythmus von Tageszeiten mit 
                        Licht und Dunkelheit.
                        <br />
                        <br />
                        <b>Auch unser Körper befindet sich im Rhythmus</b> &ndash; in einem Rhythmus von Einatmen und Ausatmen, von Wachsein und Schlaf, in einem Rhythmus von Bewegung und Ruhe, 
                        von Anspannung und Entspannung. Auch sämtliche Hormone, die unsere Körperfunktionen steuern &ndash; nicht nur die Sexualhormone, folgen einem Rhythmus. Diese 
                        Liste ließe sich noch beliebig erweitern, denn kein Moment des Lebens findet in einem Zustand statt, ohne dass er in einem anderen Augenblick wie auf einer Schaukel 
                        in die Gegenrichtung schwingt.
                        <br />
                        <br />
                        Einige Rhythmen sind individuell: es gibt die sprichwörtlichen Eulen und Lerchen &ndash; erstere schlafen länger und gehen später zu Bett, letztere erwachen früh 
                        am Tage und sind abends schnell müde. Wenn sich diese Verschiebungen in den natürlichen Tagesrhythmus einfügen, ist das völlig in Ordnung. 
                        <br />
                        <br />
                        <b>Auch die Verdauung unterliegt Rhythmen</b>: hier sind es Zeiten von Nahrungsaufnahme und von Nahrungskarenz und Zeiten von Aktivitäten oder auch Ruhe der verschiedenen 
                        Areale des Verdauungstrakts. 
                        <br />
                        <br />
                        Essenzeiten können ebenfalls individuell sein, und der eine mag sich am meisten auf ein ausgiebiges Frühstück freuen, während der andere eher abends gerne isst. 
                        Wenn dabei die natürlichen Verdauungsrhythmen nicht tangiert werden, haben diese individuellen Vorlieben ihre Berechtigung.
                        <br />
                        <br />
                        Auch unser Sozialverhalten unterliegt individuellen Rhythmen: es gibt Zeiten von sozialen Aktivitäten und Zeiten des Alleinseins. Solange wir dies aus unserem 
                        freien Willen steuern können, ist das gut und richtig. Erst, wenn wir zu oft und ohne zur Ruhe kommen zu können, in Menschenmengen gezwungen werden oder, im Gegenteil, 
                        ungewollt einsam sind, wirkt sich dies nachteilig auf die Gesundheit aus.
