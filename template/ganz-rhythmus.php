                        <a id="fazit"></a>
                        <hr />
                        <h5>Fazit</h5>
                        <hr />
                        Das Leben findet in Rhythmen statt. Es gibt die vorgegebenen Rhythmen wie Tag und Nacht, die Rhythmen von Hormonen und Verdauungsprozessen, und es gibt die 
                        individuellen Rhythmen wie den Bedürfnissen nach Aktivität und Ruhe. 
                        <br />
                        <br />
                        Da alle Rhythmen ineinandergreifen, denen wir ohne unser Zutun ausgesetzt sind und auch die, die wir beeinflussen können, ist es wichtig, diese Rhythmen nicht 
                        zu stören oder zu konterkarieren, sondern sie mit unseren Verhaltensweisen zulassen und zu ermöglichen und in einem ausgewogenen Gleichgewicht zu halten. 
                        <br />
                        <br />
                        Natürlich gibt es Zeiten und Phasen im Leben, in denen wir den natürlichen Rhythmen nicht folgen können &ndash; sei es, wenn wir familiär oder beruflich bestimmte 
                        Vorgaben beachten und Pflichten erfüllen müssen, oder sei es, dass gesundheitliche Beeinträchtigungen uns belasten und in unseren Tagesablauf eingreifen.
                        <br />
                        <br />
                        Aber es gibt immer Möglichkeiten, den Blickwinkel zu ändern, empfundenen Belastungen entgegenzusteuern und einen Ausgleich zu finden &ndash; selbst wenn die Maßnahmen nur 
                        &#187;klein&#171; sind. <b>Auch kleine Erholungsphasen helfen, sich zu entspannen</b>. Und sich beispielsweise den einen oder anderen Snack zu verkneifen und Esspausen einzuhalten, 
                        sollte möglich sein. Wenn dies dann der Gesundheit zugute kommt, kann schnell aus einem &#187;Muss&#171; ein &#187;Darf&#171; und aus einem &#187;Schwer&#171; ein 
                        &#187;Leicht&#171; werden.
                        <br />
                        <br />
                        Es ist auch nicht erforderlich, sich vorgegebenen oder selbst auferlegten Rhythmen sklavisch zu unterwerfen, aber sie im Auge zu behalten, ist von Vorteil. 
                        Deshalb meine Empfehlung: ziehen Sie Bilanz und schauen Sie, wo Sie stehen und welche Stellschrauben zur Veränderung es gibt &ndash; und zu welchen Veränderungen 
                        Sie bereit sind. 
                        <br />
                        <br />
                        Jeder Schritt in die richtige Richtung bringt Sie weiter. Je mehr wir im Einklang mit den natürlichen <b>und</b> mit den individuellen Rhythmen leben, desto 
                        gesünder sind wir und umso wohler fühlen wir uns. 
