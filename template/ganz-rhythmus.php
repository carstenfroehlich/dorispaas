                        <a id="entspannung"></a>
                        <hr />
                        <h5>Anspannung und Entspannung</h5>
                        <hr />
                        <b>Anspannung und Aktivität sind genauso wichtig wie Zeiten der Ruhe und Erholung</b>. Wenn die Sonne aufgeht und mit einem hohen Blauanteil des Tageslichts die Hormone 
                        Cortisol und Serotonin gebildet werden, erwachen wir nicht nur, sondern unsere Leistungskurve steigt an. Wir haben jede Menge Energie und sind in der Lage, unser 
                        Tagewerk zu erledigen.
                        <br />
                        <br />
                        Nach dem Mittagessen gibt es einen kleinen Einbruch in der Leistungskurve. Ein Mittagsschläfchen, so, wie es in den südlichen oder asiatischen Ländern gang und gäbe ist, 
                        würde dem Rechnung tragen. Aber auch kleine Naps, kurze Phasen des Schlafens oder auch nur Abschaltens, können wunderbar zur Entspannung und Erholung beitragen.
                        <br />
                        <br />
                        Am Nachmittag haben wir ein weiteres Leistungshoch. Gegen Abend, wenn sich die Lichtverhältnisse ändern und ein größerer Rotanteil vorhanden ist, beginnt der Körper, 
                        sich mit der Bildung von Melatonin auf den Schlaf vorzubereiten. Spätestens jetzt sollte die Zeit der Erholung eingeläutet werden.
                        <br />
                        <br />
                        Je stressiger der Tag, desto öfter sollten in einem gesunden Rhythmus <b>kleinere Entspannungspausen</b> eingelegt werden. Kein Körper kann dauerhaft unter maximaler 
                        Belastung stehen. Genauso, wie ein Motor überhitzt, der zu lange auf Vollgas läuft und Abkühlung benötigt, sollten auch dem Organismus immer wieder Erholungs- 
                        und Entspannungsphasen gegönnt werden, um die optimale Leistung erbringen zu können (lesen Sie gerne auch dem Beitrag &#187;<a href="ganz-entspannung" target="_blank">Entspannung</a>&#171;).
                        <br /> 
                        <br />
                        <a id="bewegung"></a>
                        <hr />
                        <h5>Bewegung und Ausruhen</h5>
                        <hr />
                        In jeder Phase des Lebens gibt es einen Rhythmus zwischen Bewegung und Ausruhen. Schauen Sie sich das Herz an: es gibt Phasen der Bewegung, des Zusammenziehens und 
                        Pumpen des Bluts (Systole), und im Gegenzug gibt es die Phasen der Erschlaffung und des Ausruhens (Diastole), in denen sich das Herz wieder mit Blut füllt. Auch die Atmung 
                        findet in einem stetigen Rhythmus zwischen Bewegung und Ausruhen, zwischen Anspannung und Entspannung des Zwerchfells und der Zwischenrippenmuskeln statt.
                        <br />
                        <br />
                        Es gibt kein Organ im Körper, das nicht solchen Bewegungs- und Ruherhythmen unterworfen ist. All dies sind unwillentliche, vom autonomen Nervensystem 
                        gesteuerte Prozesse.
                        <br />
                        <br />
                        Wir können aber auch willentlich unsere Muskeln aktivieren und auch ausruhen: jedes Fingerschnippen, jedes Armheben, jeder Schritt kann willentlich gesteuert werden. Wir können 
                        aufstehen, laufen und Sport treiben. Wir können uns aber auch niedersetzen, hinlegen oder ausruhen, um neue Kraft zu tanken.
                        <br />
                        <br />
                        Mit der willentlichen Aktivität und Ausruhphase können wir sogar unsere eigentlich unwillentlichen Körperfunktionen beeinflussen: während sportlicher Betätigung atmen 
                        wir schneller und unser Herzschlag ändert sich. Wenn wir hingegen ausruhen, verlangsamen sich Atmung und Herzschlag.
                        <br />
                        <br />
                        Es ist also wichtig, auch bei <b>Bewegung und Ausruhen einen gesunden Rhythmus einzuhalten</b>, um alle Körperfunktionen und damit auch den Geist flexibel zu halten.
                        <br /> 
                        <br />
                        <a id="musik"></a>
                        <hr />
                        <h5>Laut und leise</h5>
                        <hr />
                        Laut und leise, hoch und tief, schnell und langsam &ndash; die vielfältigen Rhythmen der Musik gehören zu den schönsten im Leben. Musik kann beruhigen, Musik kann aber auch anregen.
                        Jedes Baby lässt sich mit gleichmäßigem Singen beruhigen, und Kinder lieben Lieder mit einfachen Melodien und Texten. Jugendliche favorisieren oft stark rhythmische 
                        Stücke, und viele Stars sind heftig umschwärmte Gestalten. Ältere Menschen bevorzugen oft klassische Musik &ndash; wobei selbstverständlich keineswegs weder das 
                        eine noch das andere immer der Fall sein muss.
                        <br />
                        <br />
                        Ein Rhythmus von Musik kann zwischen laut und leise schwingen: laute Musik regt an, gelegentlich aber auch auf. Ein weiterer Rhythmus kann sich auch zwischen hoch und tief bewegen. 
                        Je nach Vorliebe und Hörvermögen können höhere oder auch tiefere Töne präferiert werden. Und natürlich kann der Rhythmus von Musik schnell oder langsam sein: der Herzschlag 
                        kann sich mit bestimmten Rhythmen synchronisieren, und auch die Atmung und sogar der Blutdruck können sich durch Musik verändern.
                        <br />
                        <br />
                        <b>Es ist immer der Zusammenklang der verschiedenen Rhythmen, der ein Musikstück perfekt macht</b> &ndash; vom Wechsel zwischen laut und leise, zwischen hohen und tiefen Tönen 
                        und langsamen und schnelleren Rhythmen. 
                        <br />
                        <br />
                        Es ist aber nicht alleine das Hören, was den Genuss von Musik ausmacht. Viele Menschen fühlen sich durch Musik zum Mitsingen animiert. Wir Deutsche sind da eher unterentwickelt 
                        &ndash; in anderen Ländern, vor allem in den nordischen, hat das Singen eine große Tradition. Singen tut nicht nur der Seele gut, sondern durch die kontrollierte, tiefe Atmung 
                        dem ganzen Körper. Je intensiver und &#187;aus voller Kehle&#171;, desto effektiver wirkt das Singen &ndash; übrigens auch auf die Verdauung, denn sowohl die Verdauungsdrüsen 
                        als auch der Darm selbst werden durch die heftigeren Bewegungen des Zwerchfells und die Vibrationen angeregt, wodurch sich die Verdauungsleistung verbessert. Aus diesem
                        Grunde ist das Singen (unter vielen andern) auch eine der &#187;Übungen&#171; in dem Buch <a href="darmgymnastik" target="_blank">Darmgymnastik</a>.
                        <br />
                        <br />
                        Und Musik geht im wahrsten Sinne des Wortes in die Beine und regt zur Bewegung, zum Tanz an. Schauen Sie sich Musikhörende an: die meisten wippen mindestens mit den 
                        Beinen ober bewegen die Hände im Rhythmus. Jedes Volk hat seine eigene Musik, und jedes Volk tanzt seine eigenen Tänze. Aber alle haben Freude an Musik &ndash; weil die 
                        Rhythmen einfach mitreißend sind.
                        <br /> 
                        <br />
                        <a id="pflicht"></a>
                        <hr />
                        <h5>Pflicht und Kür</h5>
                        <hr />
                        Nicht nur die Musik &ndash; vieles im Leben macht Spaß und ist das &#187;Salz in der Suppe&#171; des Tages. Das sind nicht nur die Hobbys, sondern auch die vielen größeren und kleineren Dinge, 
                        an denen wir uns jeden Tag erfreuen. 
                        <br />
                        <br />
                        Es gibt aber auch Verpflichtungen &ndash;  seien es die familiären oder auch die beruflichen. Dem kann man sich selten entziehen, und diese Verpflichtungen müssen 
                        erfüllt werden. Ohne eine achtsame und liebevolle Versorgung bricht die Familie zusammen, und ohne Arbeit und Verdienst kommt kein Geld in die Haushaltskasse.
                        <br />
                        <br />
                        Aber auch andere Erfordernisse im Leben können zur Pflicht werden. Ich denke hier beispielsweise an die &#187;Pflicht&#171; für die eigene Gesundheit zu sorgen, denn 
                        heutzutage ist dies leider nur noch selten eine Selbstverständlichkeit.
                        <br />
                        <br />
                        Wie gut wäre es, wenn nicht nur der Beruf und die Sorge für die familiären Bedürfnisse, sondern auch das Kümmern um die Gesundheit nicht &ndash; oder zumindest nicht 
                        immer &ndash;  als Pflicht betrachtet würden, sondern Spaß machen, Befriedigung bringen und zur Kür werden könnten!
                        <br />
                        <br />
                        Je besser Sie <b>die Erfordernisse des Lebens und ihre eigenen Bedürfnisse in Einklang bringen</b>, desto mehr können Sie dann auch an der Erledigung der Pflichten Spaß haben 
                        bzw. zumindest nach getaner Arbeit stolz auf das Ergebnis blicken. 
                        Und wenn die Gesundheit Probleme macht, kann es ein richtig gutes Gefühl sein, etwas zur Verbesserung der Situation beitragen zu können. Wer nicht nur mit der Einnahme 
                        einer &#187;Pille&#171; darauf wartet, dass sich Beschwerden bessern, sondern in einem aktiven Rhythmus mit bewusstem Atmen, mit Entspannung und &ndash; wo möglich &ndash; 
                        kleineren oder größeren Bewegungsübungen zur Stärkung der eigenen Regenerationsfähigkeiten beiträgt, kann daraus nicht nur Kraft, sondern auch große Zufriedenheit schöpfen. 
                        <br /> 
                        <br />
                        <a id="essen"></a>
                        <hr />
                        <h5>Essen und Nahrungskarenz</h5>
                        <hr />
                        Auch die Nahrungsverarbeitung unterliegt einem Rhythmus. Viele Menschen essen ständig. Nicht nur die Hauptmahlzeiten werden eingenommen, sondern zwischendurch wird 
                        immer wieder gesnackt. Das wirkt sich sehr nachteilig auf unser Verdauungssystem aus, das von Natur aus auf regelmäßige Essenspausen ausgelegt ist.
                        <br />
                        <br />
                        Alle Phasen der Verdauung bauen aufeinander auf und sollten sich idealerweise nicht überlappen. Jede Phase der Verdauung hat ihre ganz besondere Funktion: erreicht 
                        Nahrung den Magen, wird Magensäure gebildet, die aufgenommene Fremdkeime abtötet und erste Nahrungsaufspaltungen vornimmt. Gelangt der so vorbereitete Speisebrei 
                        in den Dünndarm, werden dort Sekrete aus den Verdauungsdrüsen hinzugegeben und die Nahrungsbestandteile weiter aufgespalten, um so zerlegt über die Schleimhaut 
                        ins Blut gelangen zu können. Unverdaute Reste gelangen in den Dickdarm, wo letzte Inhaltsstoffe von den Darmbakterien verarbeitet werden. Was übrig bleibt, wird 
                        dann ausgeschieden &ndash; idealerweise in einem möglichst täglichen, gesunden Rhythmus.
                        <br />
                        <br />
                        <b>Wenn Magen und Dünndarm leer sind, setzen Reinigungsprozesse ein</b>, die diese Abschnitte des Verdauungssystems säubern und für die nächste Nahrungsaufnahme vorbereiten. 
                        <br />
                        <br />
                        Gesteuert wird der gesunde Ablauf nicht nur durch verschiedene Hormone &ndash; eigentlich auch unser Hunger- und Sättigungsgefühl, sondern an den entsprechenden 
                        Darmabschnitten auch durch einen spezifisch auf die erforderliche Funktion abgestimmten Säuregrad in dem betreffenden Darmabschnitt. Enzyme zum Beispiel, die 
                        bestimmte Nahrungsbestandteile aufspalten sollen, brauchen ihre jeweiligen individuellen Säuregrade, die sich genau mit dem Zeitpunkt des Durchlaufs des Speisebreis 
                        durch die Verdauungssäfte bilden können.
                        <br />
                        <br />
                        Durch zwischen den Mahlzeiten eingenommene Snacks werden diese aufeinander aufbauenden Prozesse gestört: die Säuregrade können sich nicht ausreichend ausbilden, 
                        und die Enzyme können nicht effektiv wirken und die Nahrungsbestandteile aufspalten. Die Reinigung unterbleibt und es entstehen Überwucherungen mit unerwünschten 
                        Keimen bilden können. Der gesamte Verdauungsprozess ist gestört.
                        <br />
                        <br />
                        Aus diesem Grunde ist es wichtig, jedem Durchlauf der Verdauung ihre Zeit zu geben und durch einen Rhythmus von Nahrungsaufnahme und Nahrungskarenz die erforderlichen 
                        Ruhe- und Zwischenphasen nicht zu stören.
                        <br />
                        <br />
                        Genauso wichtig wie das &#187;Wann&#171; ist aber auch das &#187;Was&#171;. Nicht nur die Essenszeiten sind wichtig, sondern auch <b>die Auswahl der Lebensmittel</b>.
                        Wer täglich das gleiche isst und nur sehr wenige Lebensmittel verzehrt, hat &ndash; natürlich &ndash; keinen wirklichen Spaß am Essen. Was aber noch viel relevanter ist,
                        ist die Tatsache, dass mit einer eingeschränkten Lebensmittelpalette die Diversität der Mikrobiota leidet. Die menschlichen Darmbakterien sind Feinschmecker, und jede 
                        Bakterienart bevorzugt ganz bestimmte Lebensmittel. Wird der ein oder anderen Art ihr Lieblingsessen vorenthalten, können sie sich nicht so gut vermehren. 
                        <br />
                        <br />
                        Es ist also günstig, abwechslungsreich zu essen. Geschah dies früher ganz automatisch mit dem jahreszeitlich wechselnden regionalen Angebot, so sind heute die Gemüseabteilungen 
                        der Supermärkte ganzjährig mit Produkten aus aller Welt gefüllt. Wer jetzt nur zu seinen bevorzugten Sorten greift und sich darüber hinaus auch noch wegen Unverträglichkeiten 
                        einschränkt, erweist seiner Mikrobiota und damit seiner Gesundheit einen Bärendienst.
                        <br />
                        <br />
                        Selbstverständlich sollte man Unverträglichkeiten zunächst einmal Folge leisten und die unbekömmlichen Lebensmittel vermeiden. Es ist aber ganz wichtig, nach einer gewissen 
                        Zeit der Karenz, mit der Ruhe in den Bauch kommt, diese Lebensmittel ganz behutsam wieder einzuführen. Und dies geschieht am besten <b>in einem Rhythmus, in dem man rotiert und 
                        wechselt zwischen Erprobtem und kleinen Mengen Neuem</b>. So kann man die in der Zwischenzeit zurückgegangenen Populationen wieder aufbauen
                        (lesen Sie gerne auch dem Beitrag &#187;<a href="verdauung" target="_blank">Gesunde Verdauung</a>&#171;).
                        <br /> 
