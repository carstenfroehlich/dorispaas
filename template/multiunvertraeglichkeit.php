                        <a id="normalitaet"></a>
                        <hr>
                        <h5>Rückkehr zur Normalität</h5>
                        <hr>
                        Genauso wichtig wie die anfängliche Konsequenz ist die spätere, <b>schrittweise Rückkehr zu einer grö&#223;tmöglichen &#187;Normalität&#171;</b> &ndash; immer unter Beachtung 
                        der persönlichen Gegebenheiten. Ein zu lange eingeschränkter Speisezettel führt immer zu einer Reduktion der Diversität (Vielfältigkeit) der Darmbakterien &ndash; ein zu lange 
                        und zu stark eingeschränkter Speisezettel zu einer stark eingeschränkten Diversität. Und <b>die Diversität der intestinalen Mikrobiota ist einer der wichtigsten Faktoren 
                        für ihre Widerstandsfähigkeit</b>. Jede Keimart hat auch bestimmte Vorlieben, und wenn der Speisezettel eingeschränkt ist, bekommt eine mehr oder weniger gro&#223;e Anzahl 
                        von Keimen &#187;nicht genug zu essen&#171;. Als Folge davon nehmen die anderen zwar die frei gewordenen Plätze ein, sie können deren Aufgaben nicht übernehmen. 
                        Deshalb sollte eine Karenzzeit nur so kurz wie möglich und die Einschränkungen nur so weit wie nötig gehalten werden &ndash; selbstverständlich unter genauer Beobachtung
                        eventueller Beschwerden. Beschwerden aufgrund zu forscher Wiederaufnahme von zu vielen bisher unverträglichen Lebensmittelgruppen in den Speisezelltel bedeuten immer eine 
                        Verschlechterung des Gesamtzustands. Ggf. sollten Sie sofort einen oder sogar mehrere Schritte zurückgehen und abwarten, bis Sie einen nächsten Versuch starten können. 
                        <b>Geduld ist bei der Behandlung von multiplen Nahrungsmittel-Unverträglichkeiten das oberste Gebot</b>.
