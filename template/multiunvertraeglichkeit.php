                        Viele Menschen leiden an <b>einer</b> <a href="nahrungsmittelunvertraeglichkeiten" target="_blank">Nahrungsmittel-Unverträglichkeit</a> &ndash; z.B. an 
                        einer <a href="wasistli" target="_blank">Laktose-Intoleranz</a> oder an einer <a href="wasistfma" target="_blank">Fruktose-Intoleranz</a>. Andere 
                        haben eine <a href="glutensensitivitaet" target="_blank">Gluten-Sensitivität</a> (gemeint ist hier ausdrücklich nicht die 
                        <a href="zoeliakie" target="_blank">Zöliakie</a>), oder sie vertragen keine <a href="oligosaccharide-wasistdas" target="_blank">Mehrfachzucker (Oligosaccharide)</a>. 
                        Vielleicht aber haben sie auch Probleme mit Schwefel oder <a href="oxalate" target="_blank">Oxalaten</a> in der Nahrung. 
                        Auch das <a href="wasisthi" target="_blank">Histamin</a>, ein biogenes Amin (körpereigener Botenstoff, der aber auch in vielen Lebensmitteln enthalten ist), 
                        oder andere Stoffe wie das <a href="salicylatintoleranz" target="_blank">Salicylat</a> oder das <a href="glutamat" target="_blank">Glutamat</a>, die die 
                        sogenannten Pseudoallergien verursachen, können Probleme machen. 
                        <br />
                        <br />
                        Immer häufiger kommt es aber auch vor, dass Betroffene nicht nur einen Nahrungsbestandteil, sondern zwei oder sogar mehrere Stoffe nicht vertragen und ihre 
                        Speisenauswahl kaum noch mehr als die sprichwörtliche &#187;Möhre am Salatblatt&#171; und ein Glas Wasser beinhaltet. Dies sind dann <b>multiple Unverträglichkeiten</b>, 
                        also viele Unverträglichkeiten gleichzeitig.
                        <br />
                        <br />
                        <a id="erstehilfe"></a>
                        <hr>
                        <h5>Erste Hilfe bei multiplen Unverträglichkeiten</h5>
                        <hr>
                        Die erste und wirksamste Ma&#223;nahme nach der Diagnose oder Vermutung einer oder mehrerer Nahrungsmittel-Unverträglichkeiten zur Minimierung der Symptome ist 
                        die weitestgehende Reduktion der Lebensmittel, die die jeweiligen Stoffe enthalten. Das erscheint relativ einfach, denn der Bauch gibt einem die zuverlässigste 
                        Rückmeldung, was und in welchen Mengen er etwas zur Zeit toleriert und was nicht. Auf diese Weise kann sich das Verdauungssystem regenerieren. Unter bestimmten 
                        Umständen können die Unverträglichkeiten schon mit dieser Ma&#223;nahme deutlich gebessert werden, denn die &#187;reizenden&#171; Abfallprodukte wie die Gase 
                        und Säuren, die bei der bakteriellen Fermentation der fehlgeleiteten Kohlenhydrate entstehen, werden dann minimiert.  
                        <br />
                        <br />
                        Das nicht ganz einfach zu lösende Problem bei dieser Art von &#187;erster Hilfe&#171; ist es jedoch herauszufinden, <b>welche</b> Stoffe die Beschwerden verursachen. 
                        Ist es nur eine Kohlenhydratart (Zucker), so ist diese mit Hilfe eines Ernährungs- und Symptomtagebuches recht rasch ermittelt 
                        (Sie finden die <a href="downloads#tagebuch" target="_blank">Vorlage für ein Verzehrtagebuch</a> im Downloadbereich dieser Website). Bei mehreren gleichzeitig 
                        auftretenden Unverträglichkeiten gestaltet sich die Spurensuche schon sehr viel diffiziler, denn bei einer Unverträglichkeit zeigen sich die Symptome ja (im 
                        Gegensatz zu <a href="videos#abgrenzung" target="_blank">Allergien</a>) nicht unmittelbar nach dem Verzehr einer Mahlzeit (die ja zu allem Überfluss in der Regel 
                        auch noch zahlreichen verschiedenen Zutaten besteht), sondern erst mit einem mehrstündigen Zeitversatz. Einen Versuch ist es aber auf jeden Fall wert, es zunächst 
                        mit dem Weglassen des dringendsten &#187;Verdächtigen&#171; zu versuchen, die Beschwerden zu minimieren (siehe weiter unten
                        <a href="<?= URL_ROOT ?>multiunvertraeglichkeit#diagnostik">Diagnostik von multiplen Unverträglichkeiten</a>).             
                        <br />
                        <br />
                        <a id="ursachen"></a>
                        <hr>
                        <h5>Ursachensuche</h5>
                        <hr>
                        Wichtig ist es aber vor allem, sämtliche Ursachen der Unverträglichkeiten zu finden, da nur so eine weitestgehende Beschwerdefreiheit erreicht werden kann. Manche
                        Intoleranzen &ndash; wie in manchen Fällen eine Laktose-Intoleranz &ndash; können ererbt sein (primäre Form). Wenn die Enzyme fehlen, die für die Verarbeitung der 
                        entsprechenden Kohlenhydrate &ndash; wie in unserem Beispiel die Laktase &ndash; aufgrund einer genetischen Veranlagung nicht mehr in ausreichendem Ma&#223;e gebildet 
                        werden, ist eine lebenslange Karenz erforderlich &ndash; eine &#187;<a href="faq#frage1" target="_blank">Ausheilung</a>&#171; ist dann nicht möglich.
                        <br />
                        <br />
                        Es kann aber auch sein, dass die Enzyme für bestimmte Kohlenhydrate zu einem Zeitpunkt deshalb nicht (mehr) ausreichend gebildet werden, weil die Zellen der Darmschleimhaut 
                        ein Problem haben (sekundäre Form). Viele Enzyme &ndash; beispielsweise diejenigen, die für die Aufspaltung von Laktose, Oligosaccharide oder Histamin erforderlich sind 
                        &ndash; und Transportproteine, die für die Verarbeitung der Fruktose benötigt werden, werden in den Darmschleimhautzellen gebildet. 
                        <br />
                        <br />
                        Wenn nun diese Zellen entweder nicht richtig ernährt werden oder durch Entzündungen geschädigt sind, wird auch die Produktion der Enzyme reduziert. Die Folge sind 
                        Unverträglichkeiten in mehr oder weniger gro&#223;er Ausprägung. Und hier passiert es dann auch sehr häufig, dass nicht nur Lebensmittel mit einer Art von Kohlenhydrat 
                        (Zucker) nicht mehr vertragen werden, sondern gleich von mehreren Stoffen, weil erkrankte Schleimhautzellen eben die Produktion von allen Enzymen reduzieren oder so gut wie 
                        ganz einstellen. Die gute Nachricht ist, dass solche sekundären Formen heilbar sind, wenn die Gesundheit der Darmschleimhautzellen wiederhergestellt wird.
                        <br />
                        <br />Auch seltenere Erkrankungen wie z.B. das sogenannte <a href="lexikon-darmerkrankungen#mastzellaktivierungssyndrom" target="_blank">Mastzellaktivierungs-Syndrom (MCAS)</a> 
                        &ndash; häufig vergesellschaftet mit einer Histamin-Unverträglichkeit &ndash; kann ein weiterer Aspekt des multiplen Geschehens sein. Durch all dies gestaltet sich die 
                        Ursachenforschung häufig wie die &#187;Suche nach der Nadel im Heuhaufen&#171; und erfordert viel Erfahrung.
                        <br />
                        <br />
                        <a id="entwicklung"></a>
                        <hr>
                        <h5>Entwicklung von einer Einzel-Unverträglichkeit zu multiplen Unverträglichkeiten</h5>
                        <hr>
                        Immer mehr Menschen, die ursprünglich &#187;nur&#171; eine Zuckerart nicht toleriert hatten, berichten davon, dass sie kaum noch Lebensmittel vertragen und sich ihr 
                        Speisezettel immer weiter einschränkt &ndash; sie leiden an multiplen Unverträglichkeiten. Oftmals haben multiple 
                        Unverträglichkeiten mit einer einzigen Problematik &ndash; beispielsweise mit Laktose oder Fruktose &ndash; begonnen, häufig zu Anfang noch nicht so richtig wahrgenommen 
                        und deshalb auch nicht mit einer angepassten Ernährung behandelt. Als Folge davon hat sich der Zustand der Darmschleimhaut schleichend verschlechtert, so dass 
                        sie dadurch dann auch immer weniger Enzyme in ihren Zellen bildet.
                        <br />
                        <br />
                        Dies bedeutet, dass sich sowohl die eine, ursprüngliche Unverträglichkeit verstärkt, als auch weitere hinzukommen. Der Grund ist, dass erstens <b>die Enzymproduktion für 
                        die Unsprungs-Unverträglichkeit noch weiter reduziert wird</b> und zweitens <b>zusätzlich auch Enzyme (und Transportproteine) für andere Kohlenhydratgruppen nur noch in 
                        geringerem Ma&#223;e hergestellt</b> werden.
                        <br />
                        <br />
                        Zu beachten ist darüber hinaus, dass schlecht ernährte Darmschleimhautzellen zu einem sogenannten 
                        &#187;<b><a href="lexikon-darmerkrankungen#leakygut" target="_blank">Leaky Gut-Syndrom</a></b>&#171; führen, bei dem die Schleimhaut undicht wird
                        und unverdaute Nährstoffe oder Darmbakterien ins Körperinnere hindurchlässt. Auch dies trägt nicht unmaßgeblich zur Forcierung der Entwicklung des Gesamt-Beschwerdebildes 
                        der multiplen Unverträglichkeiten mit bei. Aus diesem Grunde ist eine Ausheilung der Darmschleimhaut auf jeden Fall und immer zu einem möglichst frühen Zeitpunkt einer der 
                        wichtigsten Bestandteile jeder Therapie.
                        <br />
                        <br />
                        <a id="folgeerkrankungen"></a>
                        <hr>
                        <h5>Folgeerkrankungen</h5>
                        <hr>
                        Wenn &ndash; oftmals aufgrund nicht richtig behandelter Unverträglichkeiten &ndash; weitere Erkrankungen wie z.B. eine 
                        <a href="duenndarmfehlbesiedelung" target ="_blank">Dünndarmfehlbesiedelung</a> (SIBO oder IMO) oder eine Dysbiose (bakterielle Fehlbesiedelung des Dickdarms) hinzukommen, 
                        müssen natürlich auch diese Erkrankungen betrachtet werden, denn alle Erkrankungen bedingen und verstärken sich immer gegenseitig.
                        <br />
                        <br />
                        Jede einzelne Problematik erzeugt nicht nur für sich Symptome. Oftmals sind dies gleiche oder zumindest ähnliche Symptome, so dass die oberflächliche Betrachtung kaum 
                        zu einer belastbaren Diagnostik ausreicht. Fakt ist jedoch, dass sich <b>die Summe der Symptome</b> immer negativ auf die Gesundheit der Darmschleimhaut und in der Folge auch 
                        auf die intestinale Mikrobiota auswirken, so dass sich hier nach anfänglichen, scheinbar kaum registrierten Beschwerden das Befinden sehr rasch drastisch verschlechtern kann.
                        <br />
                        <br />
                        <a id="teufelskreis"></a>
                        <hr>
                        <h5>Teufelskreis</h5>
                        <hr>
                        Auch die Beschwerden, die durch die Symptome selbst &ndash; wie u.a. <b>Blähungen, Bauchschmerzen, Verstopfung, Durchfall</b> und vieles mehr &ndash; hervorgerufen werden, gehören 
                        in das Gesamtbild und dürfen nicht separat betrachtet und behandelt werden. Sie sind Teil eines sich immer weiter verstärkenden Teufelskreises, denn sie forcieren bakterielle 
                        Entgleisungen und intensivieren die entzündlichen Prozesse an der Darmschleimhaut.
                        <br />
                        <br />
                        Die Ursachen von multiplen Unverträglichkeiten sind also sehr vielfältig, und es ist <b>immer eine sorgfältige Anamnese</b> erforderlich, in der neben verschiedenen anderen Faktoren 
                        (z.B. die Leistungsfähigkeit der <b>Schilddrüse</b> und der <b>Verdauungsdrüsen</b>) vor allem auch die <b>ersten Anzeichen</b> und die <b>Entwicklung der Gesamtproblematik</b> 
                        angeschaut werden sollte.
                        <br />
                        <br />
                        <a id="diagnostik"></a>
                        <hr>
                        <h5>Diagnostik von multiplen Unverträglichkeiten</h5>
                        <hr>
                        Die Diagnostik von multiplen Nahrungsmittel-Unverträglichkeiten gestaltet sich langwierig, denn <b>jede einzelne Intoleranz</b> muss mit geeigneten Tests &ndash; in der Regel 
                        <a href ="atemtest" target="_blank">Atemtests</a> &ndash; nachgewiesen bzw. ausgeschlossen werden. Da es sinnvoll ist, zwischen mehreren Atemtests mindestens zwei Wochen 
                        Zeit verstreichen zu lassen, um den Darmbakterien die Gelegenheit zur Regeneration von dieser Belastung zu geben, brauchen mehrere Tests eben leider auch <b>viele Wochen Zeit</b>. 
                        So verständlich Ungeduld und der Wunsch nach möglichst kurzfristiger Besserung sind, führt doch kein Weg an einer <b>sorgsamen Durchführung der gesamten Diagnostik</b> vorbei.
                        <br />
                        <br />
                        Das hei&#223;t aber nicht, dass es keinerlei Wirkung hätte, bereits nach einem ersten positiven Test schon die entsprechenden Lebensmittel zu meiden. Es ist eines der Merkmale 
                        von Unverträglichkeiten: je mehr von den unverträglichen Stoffen verzehrt wird, desto ausgeprägter sind die Symptome. Im Umkehrschluss hei&#223;t dies: <b>wenn bereits eines 
                        der verursachenden Kohlenhydrate gemieden wird, bessern sich die Symptome</b>. Natürlich gehen sie nicht vollkommen zurück, denn es gibt ja bei multiplen Unverträglichkeiten 
                        noch weitere Verursacher. In der Summe jedoch reduzieren sich die Übeltäter.
                        <br />
                        <br />
                        <a id="behandlung"></a>
                        <hr>
                        <h5>Behandlung multipler Unverträglichkeiten</h5>
                        <hr>
                        Da jedoch immer die Gesundheit der <a href="darmschleimhaut" target="_blank">Darmschleimhaut</a> ein ganz wichtiger Bestandteil der Multi-Unverträglichkeit ist, muss man 
                        grundsätzlich hier ansetzen. Günstig wären hier zur Ermittlung des Ist-Zustands <b>geeignete Stuhltests</b>, die Sie allerdings in der Regel selbst zahlen müssen. Aus diesem Grunde 
                        wäre es sinnvoll, hier nicht in Eigenregie einen der zahlreichen, über das Internet erhältlichen Tests zu bestellen, sondern sich beraten zu lassen, welche Parameter für 
                        eine aussagekräftige Diagnostik erforderlich (oder nicht erforderlich) sind. Zu wenige Parameter sind genauso nutzlos und zu teuer bezahlt wie zu viele. 
                        <br />
                        <br />
                        Die Ausheilung entzündeter und unterernährter Schleimhautzellen wird in der Regel die Beschwerden schon sehr deutlich lindern können. Diese 
                        Ausheilung kann aber nur erfolgen, wenn gleichzeitig auch die anderen Probleme beachtet und behandelt werden:
                        <br />
                        <br />
                        <b>&#149; Unverträglichkeiten zunächst mit einer weitestgehenden Karenz begegnen</b>
                        <br />
                        Dabei immer beobachten (Ernährungs- und Symptomtagebuch!), bei welchen Zuckern die besten Erfolge in Bezug auf die Beschwerden erzielt wird. Ggf. vorübergehend (nicht 
                        länger als 4 &ndash; 6 Wochen) eine <a href="fodmaps" target="_blank">FODMAP-Diät</a> einhalten, bei der die meisten möglichen Beschwerdeverursacher reduziert sind.
                        <br />
                        <br />
                        <b>&#149; ggf. fehlsiedelnde Keime verdrängen oder ggf. abtöten</b>
                        <br />
                        Diese Maßnahme nie auf eigene Faust durchführen, sondern immer nur in Begleitung von spezialisierten Beratern/Behandlern.
                        <br />
                        <br />
                        <b>&#149; Sanierung der Darmschleimhaut</b>
                        <br />
                        Da wie oben dargestellt, die Schleimhaut i.d.R. immer einen großen Anteil am Gesamtgeschehen hat, ist jede Behandlung mit einschlägigen Schleimhauttherapeutika zu beginnen.
                        <br />
                        <br />
                        <b>&#149; Unterstützung einer gesunden intestinalen Mikrobiota (Darmflora)</b>
                        <br />
                        Die Einnahme von geeigneten Probiotika darf nicht zu früh begonnen werden. Zunächst mit der Behandlung der Schleimhaut und dem Leaky Gut-Syndrom beginnen (siehe oben)
                        <br />
                        <br />
                        <b>&#149; Verstopfung beseitigen</b>
                        <br />
                        Da sich eine Verstopfung und die damit einhergehende Verlangsamung der Darmperistaltik mit all ihren Folgen immer negativ auf das Gesamtgeschehen auswirkt, ist die
                        Beseitigung der Verstopfung mit geeigneten Mittel ein ganz wichtiger Therapie-Baustein.
                        <br />
                        <br />
                        <b>&#149; Leitungsfähigkeit der Verdauungsdrüsen (und ggf. der Schilddrüse) stärken</b>
                        <br />
                        Grundsätzlich bauen sämtliche Schritte der Verdauung aufeinander bauen und vorherige, mangelhafte Schritte können nicht von den nachgeordneten Bereichen aufgefangen 
                        werden. Somit trägt die Stärkung der Leistungsfähigkeit aller Verdauungsdrüsen (Magen, Leber, Galle, Bauchspeicheldrüse) sehr häufig zu einem großen Teil zur 
                        Verbesserung der Beschwerden bei.
                        <br />
                        <br />
                        <b>&#149; Geeignete Mittel zum geeigneten Zeitpunkt einsetzen</b>
                        <br />
                        Für den Einsatz und Beginn einer jeden Maßnahme gibt es einen optimalen Zeitpunkt &ndash; und ein Zufrüh kann genauso kontraproduktiv wirken wie ein Zuspät. Allein aus diesem 
                        Grunde ist eine spezialisierte Beratung essentiell wichtig für den Behandlungserfolg.
                        <br />
                        <br />
                        <b>&#149; Medikamenten-Nebenwirkungen abprüfen</b>
                        <br />
                        Sämtliche eingenommenen Medikamente &ndash; egal, ob vom Arzt verschrieben oder selbst &#187;verordnet&#171; &ndash; müssen auf eventuelle Nebenwirkungen überprüft werden. 
                        Sehr viele Medikamente wirken sich negativ auf die Verdauung aus. Nachzulesen ist dies im Beipackzettel unter der Rubrik &#187;Nebenwirkungen&#171;. Setzen Sie jedoch auf 
                        keinen Fall ärztlich verschriebene Medikamente aus eigene Faust ab, sondern sprechen Sie mit Ihrem Arzt über mögliche Alternativen und den geeigneten Zeitpunkt für einen Umstieg.                        <br />
                        <br />
                        <b>&#149; Nahrungs-Ergänzungsmittel überprüfen</b>
                        <br />
                        Manche Betroffene nehmen zahlreiche &ndash; und in den allermeisten Fällen viel zu viele &ndash; Nahrungsergänzungsmittel. Diese sind, vor allem in ihrer Menge und Kombination, 
                        keineswegs unbedenklich oder ohne negative Wirkungen auf das Gesamtgeschehen. Selbstverständlich gibt es für bestimmte Indikationen sinnvolle und hilfreiche Mittel, aber 
                        &#187;ein Sack voll&#171; sollte es in keinem Falle sein. Deshalb sollten Sie mit erfahrenen Spezialisten auch alle Ihre Nahrungsergänzungsmittel überprüfen. Weniger ist hier 
                        in den allermeisten Fällen mehr (und ganz nebenbei auch noch billiger).
                        <br />
                        <br />
                        <b>&#149; Problemverstärkende Verhaltensweisen erkennen und anpassen </b>
                        <br />
                        Last, but not least &ndash; und besonders wichtig &ndash; beinhaltet es ein <b>jedes</b> Behandlungskonzept zur vollständigen und dauerhaften Ausheilung von multiplen 
                        Nahrungsmittel-Unverträglichkeiten und ggf. weiteren Erkrankungen, den Lebensstil zu überprüfen. Hierzu gehört nicht nur der Konsum von schädlichen Stoffen wie Alkohol 
                        und Nikotin, sondern auch das Bewegungsverhalten und das Stressgeschehen mit auf den Prüfstand. Was hier in welcher Weise geändert werden kann, hängt von den individuellen 
                        Gegebenheiten und auch von der Akzeptanz ab. Gut gemeinte Maßnahmen, die beispielsweise zeitlich nicht durchführbar sind oder aber keine Akzeptanz finden, sind zum Scheitern 
                        verurteilt. Deshalb müssen Alternativen gefunden werden, die vom Betroffenen mitgetragen werden &ndash; auch, wenn sie ggf. &#187;nur&#171; die zweitbeste Lösung darstellen.
                        Ein solches Maßnahmenpaket wird sich immer aus zahlreichen Bausteinen zusammensetzen &ndash; und hier ist nicht nur Ideenreichtum, sondern vor allem auch Erfahrung erforderlich.
                        Viel zu viele Menschen versuchen dies in Eigenregie und/oder mithilfe gut gemeinter &#187;Ratschläge&#171; aus <a href="internetrat" target="_blank">Internetforen</a>, was 
                        erfahrungsgemäß in der Regel einen langen Leidensweg bedeutet, der letztendlich dann doch zum Spezialisten führt. Diese Leidenszeit können und sollten Sie abkürzen.
                        <br />
