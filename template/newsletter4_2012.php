                        <br />
                        <br />
                        Liebe Leserin, lieber Leser,
                        
                        <p>
                        Neben Nahrungsmittel-Unvertr&auml;glichkeiten und Nahrungsmittel-Allergien gibt 
                        es diverse weitere Gr&uuml;nde f&uuml;r scheinbar unerkl&auml;rliche Symptome,
                        und immer mehr Menschen versuchen verzweifelt die Ursachen ihrer Verdauungsbeschwerden 
                        herauszufinden.
                        In den vergangenen zwei Monaten habe ich mich vorrangig mit <b>verschiedenen 
                        Beschwerdeausl&ouml;sern</b> besch&auml;ftigt, die als zus&auml;tzliche oder auch 
                        verst&auml;rktende M&ouml;glichkeiten in Betracht gezogen werden k&ouml;nnten.<br />
                        <br />
                        Zum einen kommen <b>Gallenfunktionsst&ouml;rungen</b> in Frage, die sehr h&auml;ufig 
                        Verursacher scheinbar unerkl&auml;rlicher Verdauungsbeschwerden sein k&ouml;nnen.
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-galle">Lesen Sie hier mehr dar&uuml;ber.</a>
                        <br />
                        <br />
                        Wenn die Tests auf unvertr&auml;gliche Lebensmittel zu keinem oder zu keinem 
                        befriedigenden Erfolg f&uuml;hren, sollten Sie auch an Ihre Schilddr&uuml;se denken, 
                        denn eine <b>mangelhafte Schilddr&uuml;senfunktion</b> kann ebenfalls Verdauungsprobleme 
                        wie Verstopfung, Durchf&auml;lle oder Bauchschmerzen (mit-)verursachen. 
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-schilddruese">Lesen Sie hier mehr dar&uuml;ber.</a>
                        <br />
                        <br />
                        Aber auch Besiedelungen des Darmes mit verschiedenen <b>Parasiten oder Pilzen</b> k&ouml;nnen 
                        Probleme bereiten. Gerade an erstere, zu denen u.a. verschiedenste W&uuml;rmer, 
                        aber auch Einzeller wie Am&ouml;ben oder Lamblien z&auml;hlen, denkt man hier bei 
                        uns mit unseren meist recht ausgepr&auml;gten Kenntnissen &uuml;ber Hygiene 
                        oftmals erst sehr sp&auml;t. 
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-parasiten">Lesen Sie hier mehr dar&uuml;ber.</a>
                        <br />
                        <br />
                        Als kleines &#187;Nebenprodukt&#171; bei der Arbeit an diesen Themen entstand der 
                        Beginn eines <b>Lexikons der Naturheilmethoden</b>. Es befindet sich im Aufbau, 
                        und nach und nach werden hier all die Naturheilmethoden aufgenommen und erkl&auml;rt, 
                        die auf den anderen Seiten auf <a href="http://www.dorispaas.de">www.dorispaas.de</a> 
                        erw&auml;hnt werden.
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=lexikon-naturheilmethoden">Schauen Sie doch einmal hinein.</a>
                        <br />
                        <br />
                        Ein weiteres Schwerpunktthema der vergangenen Wochen war die <b>endg&uuml;ltige 
                        Auswertung der Laktase-Studie</b>, nachdem insgesamt mehr als 400 Teilnehmer ihre 
                        Erfahrungen haben einflie&#223;en lassen. Hierf&uuml;r bedanke ich mich noch 
                        einmal ganz herzlich.
                        <br /> 
                        <a href="http://www.dorispaas.de/index.php?page=studienauswertung">Die Ergebnisse der Laktase-Studie lesen Sie hier.</a>
                        <br />
                        <br />
                        Neben den Laktase-Pr&auml;paraten dr&auml;ngen in letzter Zeit immer mehr Mittel 
                        auf den Markt, die mit probiotischen Inhaltsstoffen die Darmfora soweit verbessern 
                        sollen, dass dadurch &#187; der ungehemmte Verzehr von Milch und Milchprodukten&#171;
                        m&ouml;glich sein soll.
                        Selbstverständlich ist es immer zu begr&uuml;&#223;en, die Darmflora zu pflegen, 
                        denn eine gesunde Darmschleimhaut ist der Garant f&uuml;r die Aufrechterhaltung 
                        einer gr&ouml;&#223;tm&ouml;glichen Restproduktion des Laktase-Enzyms im D&uuml;nndarm, 
                        und eine gesunde Darmflora mit m&ouml;glichst vielen n&uuml;tzlichen und wenig 
                        sch&auml;dlichen Bakterienarten unterst&uuml;tzt auch die optimale Funktion der 
                        Darmschleimhaut. 
                        <br />
                        Aufgrund teilweise heftiger und vor allem auch kontroverser Diskussionen in 
                        verschiedenen Foren habe ich mich entschlossen, zu diesem Thema eine <b>Studie 
                        durchzuf&uuml;hren, um die Wirksamkeit dieser probiotischen Pr&auml;parate 
                        beurteilen zu k&ouml;nnen</b>. Wenn Sie bereits Erfahrungen mit Probiotika gemacht 
                        haben, die damit beworben werden, dass Sie die Einnahme von Laktase-Pr&auml;paraten 
                        ersetzen k&ouml;nnen, dann bitte ich Sie herzlich um die Teilnahme an der Studie. 
                        Die Beantwortung der Fragen dauert nur einige Minuten.
