                        Neben vielen anderen Ursachen kann auch eine Funktionsstörung der Bauchspeicheldrüse (mit) für Verdauungsprobleme verantwortlich sein.
                        <br />
                        <a id="funktion"></a>
                        <hr />
                        <h5>Aufbau und Funktionen der Bauchspeicheldrüse</h5>
                        <hr />
                        Die Bauchspeicheldrüse (Pankreas) ist eine bis zu 100g schwere knapp 20cm 
                        lange Drüse, die quer im Oberbauch zwischen Leber, Milz und Magen liegt (siehe 
                        &#187;<a href="ganz-verdauungssystem">Abbildung des Verdauungssystems</a>&#171;). 
                        Der Pankreas hat verschiedene Funktionen: zum einen produziert er Hormone, die direkt 
                        endokrin (&#187;nach innen&#171;) ins Blut abgegeben werden, zum anderen aber auch 
                        verschiedene Verdauungsenzyme, die als der so genannte Bauchspeichel exokrin (&#187;nach au&#223;en&#171;) in den 
                        Zwölffingerdarm flie&#223;en &ndash; insgesamt täglich etwa 1 1/2 Liter.
                        <br />
                        <br />
                        Die in bestimmten Bereichen der Bauchspeicheldrüse, den Langerhans&#039;schen Inseln, 
                        produzierten Hormone sind die beiden blutzuckerregulierenden Hormone Insulin und 
                        Glucagon und einige weitere wichtige Hormone. Besteht eine unzureichende Funktion 
                        der endokrinen Aufgaben, wirkt sich dies auf die betroffenen Hormone aus. Bekanntestes 
                        Beispiel ist der Diabetes Typ I &ndash; die so genannte &#187;Zuckerkrankheit&#171;, 
                        bei der zuwenig Insulin produziert wird.
                        <br />
                        <br />
                        Der Bauchspeichel, der exokrin in den Darm abgegeben wird, enthält Enzyme, die 
                        helfen, Eiwei&#223;, Fett und Stärke in der Nahrung aufzuspalten und trägt 
                        so entscheidend zu einer geregelten Verdauung bei. Die eiwei&#223;spaltenden Enzyme sind 
                        Carboxypeptidasen, Chymotrypsin und Trypsin, die fettspaltenden Enzyme sind die 
                        Esterase und die Lipase, Die Phospholipase, und die alpha-Amylase kann verschiedene 
                        Kohlenhydrate aufspalten. In der Bauchspeicheldrüse sind einige der
                        Enzyme noch inaktiv, damit sich die Drüse nicht selbst verdaut. 
                        Erst nach dem Übertritt in den Darm werden sie sie &ndash; teils beim 
                        Zusammentreffen mit der Gallensäure &ndash;  aktiviert und wirksam. Hierbei 
                        wird deutlich, dass die Bauchspeicheldrüsen- und die Gallenfunktion eng zusammenhängen. 
                        Bitte lesen Sie hierzu auch den Beitrag &#187;<a href="ganz-galle">Verdauungsbeschwerden 
                        durch Gallenfunktionsstörungen</a>&#171;.
                        <br />
                        <br />
                        Wenn zuwenig Bauchspeichel produziert wird, wirkt sich dies verständlicherweise 
                        nachteilig auf die Verdauungsleistung aus. Die Nahrungsbestandteile, die durch die Beimengung der Verdauungsenzyme eigentlich 
                        bereits im Dünndarm verdaut und verwertet werden sollten, gelangen in den Dickdarm, wo sie 
                        von Darmbakterien verstoffwechselt werden &ndash; ein Vorgang, der den Vorgängen 
                        bei vielen Nahrungsmittel-Unverträglichkeiten gleicht. 
                        <br />
                        <a id="ernaehrung">&nbsp;</a>
                        <hr />
                        <h5>Ernährung</h5>
                        <hr />
                        Menge und Zusammensetzung des Bauchspeichels richten sich im Normalfall nach der 
                        Ernährung: Je grö&#223;er die verzehrte Menge des einen oder anderen 
                        Nährstoffs ist, desto grö&#223;er ist die Menge der zugehörigen 
                        Enzyme im Bauchspeichel. Dabei tritt die Wirkung versetzt auf, denn mit der 
                        Entleerung des Bauchspeichels in den Dünndarm bei Mahlzeiten wird sofort 
                        neuer Bauchspeichel &#187;auf Vorrat&#171; gebildet. Somit ist schnell klar, dass eine unzureichende 
                        Funktion der Bauchspeicheldrüse auch zu Verdauungsproblemen führen muss.
                        <br />
                        <br />
                        Neben ernsthaften Erkrankungen des Pankreas wie z.B. Entzündungen (Pankreatitis) 
                        oder Krebs (Pankreaskarzinom) gibt es diverse, vergleichsweise &#187;harmlose&#171; Ursachen, die 
                        zu einer mangelhaften exkretorischen Funktion der Bauchspeicheldrüse 
                        (Pankreasinsuffizienz), also der mangelhaften Produktion von Bauchspeichel führen 
                        können. Allen voran &ndash; und eigentlich natürlich keine &#187;Erkrankung&#171; 
                        &ndash; ist es eine schlechte, einseitige Ernährung, die dazu führt, dass 
                        die Bauchspeicheldrüse nicht genügend &#187;gefordert&#171; wird.
                        <br />
                        <br />
                        Noch nicht abschlie&#223;end geklärt ist, ob auch die so genannten &#187;freien 
                        Radikalen&#171; den Pankreas schädigen können. Als vorbeugende Ma&#223;nahme 
                        eignet sich in jedem Falle eine radikalfängerreiche Kost mit den Vitaminen A, 
                        C und E und dem Mineralstoff Selen. Eine insgesamt vitamin- und mineralstoffreiche 
                        Kost mit viel Gemüse und Obst und dem damit einhergehenden ausreichenden 
                        Anteil an sekundären Pflanzenstoffen ist somit der beste Garant für eine 
                        gesunde Bauchspeicheldrüse und deren optimale Funktion.
                        <br />
                        <br />
                        Da vor allem der Alkoholmissbrauch zu Schädigungen des Pankreas führt, 
                        ist &ndash; wie auch aus vielerlei anderen Gründen &ndash; dringend von einem 
                        übermä&#223;igen Genuss von Alkohol abzuraten.
                        <br />
                        <br />
                        Ein hoher Fettgehalt in der Nahrung kann ebenfalls zu Funtionsstörungen und 
                        Schädigungen des Drüsengewebes führen. Deshalb ist nicht nur bei 
                        Verdauungsproblemen ein moderater Fettverzehr mit einem hohen Anteil an gesunden 
                        pflanzlichen Ölen angeraten. Unterstützt wird die Reduktion des Nahrungsfetts 
                        durch einen hohen Gemüse- und Obstverzehr &ndash; wie oben beschrieben.
                        <br />
                        <br />
                        Nützlich wirkt sich auch eine enzymreiche Ernährung aus: Hier bieten 
                        sich vor allem Ananas mit dem enthaltenen Enzym Bromelain und Papaya mit dem Enzym 
                        Papain an, aber auch viele andere frische Früchte und Gemüsesorten, von 
                        denen viele gesunde, pankreasunterstützende Enzyme enthalten.
                        <br />
                        <a id="enzyme">&nbsp;</a>
                        <hr />
                        <h5>Enzymsubstitution</h5>
                        <hr />
                        In schwereren Fällen kann es u.U. vorübergehend erforderlich sein, die 
                        fehlenden oder mangelnden Enzyme mit Enzympräparaten zu ergänzen. Hier 
                        sollten Sie jedoch nicht auf eigene Faust experimentieren, sondern sich von einem 
                        qualifizierten Theraputen (Arzt, Heilpraktiker, Gesundheitsberater) beraten lassen. 
                        <br />
                        <a id="bewegung">&nbsp;</a>
                        <hr />
                        <h5>Atmung und Bewegung</h5>
                        <hr />
                        Wie bei den meisten anderen Körperfunktionen ist es auch für die Funktion 
                        der Bauchspeicheldrüse sehr vorteilhaft, sich sportlich zu betätigen. 
                        Durch die Bewegung und die daraus folgende &#187;Massage&#171; der inneren Organe 
                        wird die Durchblutung der Bauchspeicheldrüse gefördert. Die sportliche 
                        Betätigung bewirkt darüber hinaus eine tiefere Atmung, was eine bessere Sauerstoffversorgung 
                        nicht nur des Pankreas zur Folge hat. Dies kann dazu beitragen, u.a. auch die Funktion 
                        der Bauchspeicheldrüse zu optimieren.
                        <br />
                        <a id="wickel">&nbsp;</a>
                        <hr />
                        <h5>Wickel</h5>
                        <hr />
                        Genauso unterstützend wie sich der Leberwickel auf die Funktion der Leber 
                        auswirkt, können diese Wickel auch zur Förderung der Pankreasfunktion 
                        eingesetzt werden. Lesen Sie bitte die Anleitung  für Leberwickel im 
                        &#187;<a href="lexikon-naturheilmethoden#leberwickel">Lexikon der Naturheilmethoden</a>&#171;.
                        <br />
                        <a id="psyche">&nbsp;</a>
                        <hr />
                        <h5>Seelische Ausgeglichenheit</h5>
                        <hr />
                        Die störungsfreie Bauchspeicheldrüsenfunktion hängt zu einem nicht 
                        unbeträchtlichen Teil auch von der seelischen Ausgeglichenheit ab. Die Drüse 
                        wird von Nerven versorgt, die nicht willentlich zu steuern sind (vegetatives 
                        Nervensystem). Trotzdem sind sie durch ein stabiles seelisches Gleichgewicht 
                        indirekt zu beeinflussen. Somit können bei Störungen sämtliche 
                        Ma&#223;nahmen positiv sein, die zu Stressabbau und seelischem Wohlbefinden beitragen, 
                        wie beispielsweise Entspannungsübungen, aber auch Sport und gesunde Bewegung. 
