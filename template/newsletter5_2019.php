                        Ihr Interesse an diesem Newsletter und an dieser Website r&uuml;hrt wahrscheinlich daher, dass Sie Probleme mit Ihrem Verdauungssystem haben.
                        Bei den meisten der Vorgehensweisen, die Beschwerden ein f&uuml;r allemal loszuwerden und bestehende Erkrankungen zu heilen, dauert 
                        es jedoch oftmals einige Zeit, bis die verschiedenen M&ouml;glichkeiten greifen. Bis zur vollkommenen Beschwerdefreiheit kann es hilfreich sein,  
                        sich mit geeigneten Methoden zun&auml;chst eine Linderung der Symptome zu verschaffen, selbst wenn das erst einmal nur vor&uuml;bergehend ist.  
                        Selbstverständlich kann eine solche symptomatische Behandlung die eigentlichen Ursachen des Problems nicht beheben, sie kann aber den gesamten 
                        Behandlungsverlauf positiv unterst&uuml;tzen. Vor allem aber f&uuml;hlen Sie sich auf Ihrem Weg zur Heilung wesentlich besser. Zur symptomatischen 
                        Behandlung stehen verschiedene Alternativen zur Verf&uuml;gung, aber leider haben viele davon auch unerw&uuml;nschte Nebenwirkungen. Eine hervorragende 
                        Methode ohne Nebenwirkungen stellt jedoch die aus der Traditionellen Chinesichen Medizin (TCM) bekannte Akupressur dar &ndash; insbesondere, weil Sie
