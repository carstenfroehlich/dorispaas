                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Darmgesundheit/Akupressur</i>
                        <br />
                        Gerade Verdauungsbeschwerden lassen sich mit der Akupressur oder Klopftechnik g&uuml;nstig beeinflussen und es lohnt sich auf 
                        jeden Fall, sich mit der Lage der geeigneten Akupunktur- bzw. Akupressurpunkte vertraut zu machen. So kann man grunds&auml;tzliche, 
                        ausgleichende Effekte f&uuml;r die Funktion von Magen, D&uuml;nn- und Dickdarm erreichen &ndash; vor allem auch bei den verschiedensten 
                        Reizdarm-Beschwerden. Mit der Bearbeitung spezieller Punkte kann man sich bei Bl&auml;hungen im Oberbauch, bei Flatulenzen, Durchfall, 
                        Verstopfung, &Uuml;belkeit und V&ouml;llegefühl oder sogar bei Sodbrennen und Reflux Erleichterung verschaffen.
                        Am Rumpf, an den Beinen und F&uuml;&#223;en gibt es mehrere, leicht aufzufindende und ebenso leicht zu erreichende Punkte, deren Aktivierung einen  
                        generell harmonisierenden Einfluss auf Magen und Darm haben. Weiterhin gibt einen Punkt, den man am Morgen zur Aktivierung und einen Abendpunkt zur 
                        Beruhigung bearbeiten kann. Zus&auml;tzlich gibt es Punkte, die in Notf&auml;llen wie Durchfall oder krampfartigen Schmerzen weiterhelfen k&ouml;nnen.
