                        <b>Ich beziehe Stellung!</b>
                        <br />
                        <br />
                        Mit Geld spielt man nicht ...
                        <br />
                        <br />
                        dieser Werbespruch einer gro&#223;en Versicherungsgesellschaft hat sich eingepr&auml;gt.
                        <br />
                        <br />
                        Aber mit der Gesundheit ganzer V&ouml;lker darf man offensichtlich spielen &ndash; 
                        oder zumindest wird den immer wieder erfolgreichen Versuchen geldgieriger Hersteller 
                        von Nahrungsmitteln (die diese Bezeichnung kaum verdienen) nicht der wirksame 
                        Riegel vorgeschoben. 
                        <br />
                        <br />
                        So wundert es (zumindest mich) wenig, dass Pferdefleischskandale, Dioxinskandale, 
                        Gammelfleischskandale und diverse weitere Skandale nicht abrei&#223;en: Jeder 
                        Politiker, der meint, etwas dazu zu sagen zu haben (wie viel das immer auch sei) 
                        &ndash; allen voran die diversen Bundesminister f&uuml;r Ern&auml;hrung, 
                        Landwirtschaft und Verbraucherschutz &ndash; legen hektischen Aktionismus an den 
                        Tag und verk&uuml;nden, welche Ma&#223;nahmen sie ergreifen werden, damit solchen 
                        Machenschaften ein f&uuml;r alle Mal ein Riegel vorgeschoben wird. 
                        <br />
                        <br />
                        Und was passiert? Ich will es mal vorsichtig ausdr&uuml;cken und so formulieren: 
                        nicht genug, denn bisher zumindest folgte der jeweils n&auml;chste Skandal so 
                        sicher wie das Amen in der Kirche. 
                        <br />
                        <br />
                        Aber die Verbraucher sind zuerst einmal ruhig gestellt &ndash; und schlie&#223;lich 
                        sind die Skandale dann doch allesamt recht rasch wieder in Vergessenheit geraten 
                        &ndash; zumindest so rasch, dass das liebe W&auml;hlervolk dann doch wieder brav 
                        den gleichen Parteien die Legitimation zum immer wieder gleichen Spiel gab. 
                        <br />
                        <br />
                        Und wir lassen uns Fertiggerichte, Eier und Gammelfleisch immer noch oder immer 
                        wieder richtig schmecken &ndash; denn wir sind ja nicht bereit, ad&auml;quate 
                        Summen daf&uuml;r zu bezahlen: Geiz ist geil!
                        <br />
                        <br />
                        Und es brauchen ja noch nicht einmal Nahrungsmittel sein, die durch Ekel-Skandale 
                        in Verruf gekommen sind &ndash; nein, wir nehmen auch Fleisch von Tieren, die 
                        aufgrund von Subventionsausnutzung ganz legal quer durch die Lande gekarrt werden 
                        &ndash; z.B. Krabben, die in der appetitlich sauberen Nordsee gefangen, dann nach 
                        Was-wei&#223;-ich-wo (z.B. Marokko) geschafft werden zu Pulen, um dann in 
                        Ich-wei&#223;-auch-nicht-wo verpackt werden, um dann als frische Nordseekrabben 
                        in den deutschen Einkaufskorb zu gelangen. Der Nordseefischer bekommt f&uuml;r 
                        seine Arbeit fast nichts, die Pulerinnen bekommen fast nichts und alle anderen 
                        auch nur unangemessen wenig. Und umwelttechnisch haben sie riesige Mengen an 
                        Energie verschlungen, um von A &uuml;ber B nach C transportiert zu werden.
                        <br />
                        <br />
                        Der uninformierte Verbraucher denkt trotzdem, wie teuer diese Krabben sind. 
                        &#187;Aber sie sind ja schlie&#223;lich regional und aus deutschen Landen&#171;.
                        <br />
                        <br />
                        Aus deutschen Landen, ja, &auml;hnlich wie der Schwarzw&auml;lder Schinken, der 
                        zwar in Deuschland verpackt (und vielleicht auch noch ein wenig bearbeitet) wurde 
                        &ndash; aber die Schweine sind aus Belgien, den Niederlanden oder sonst wo her. 
                        Unser Deutsches Recht l&auml;sst es zu, dass Produzenten uns derma&#223;en an 
                        der Naser herumf&uuml;hren (d&uuml;rfen).
                        <br />
                        <br />
                        Wie kann es &uuml;berhaupt zu solchen Skandalen (und all denen, von denen wir 
                        gar nichts mitkriegen) &uuml;berhaupt kommen? 
                        <br />
                        <br />
                        Viel zu viele Menschen (ehrliche und unehrliche) sind an den Herstellungsprozessen 
                        von Nahrungsmitteln beteiligt. Und da bekanntlich viele K&ouml;chen den Brei 
                        verderben, kommt auch selten etwas Gutes bei solchen Gemengelagen heraus. Vor 
                        allem aber hat je niemand Klarheit &uuml;ber die gesamte Produktionskette &ndash; 
                        jeder Bearbeiter kennt gerade mal seinen Lieferanten. Woher der seine Ware bekommen 
                        hat, liegt bereits im Dunkeln. Selbst wenn wir voraussetzen, dass die meisten 
                        Glieder in dieser Kette bei der Herstellung eines Nahrungsmittels keine unlauteren 
                        Absichten haben (Geld verdienen wollen ist ja an sich nichts Unehrenhaftes), so 
                        ist vor allem der direkte Kontakt zwischen Erzeuger und Verbraucher nicht mehr 
                        gegeben. Und damit fehlt die wirkungsvolle M&ouml;glichkeit, dem Produzenten eine 
                        R&uuml;ckmeldung und damit Ansporn zu geben, hochwertige Produkte herzustellen.
                        <br />
                        <br />
                        Dem Bauern, der mir seine eigenen Produkte ab Hof verkauft, kann ich sagen: 
                        &#187;das schmeckt oder das schmeckt nicht, oder das h&auml;lt mich gesund oder 
                        ich bin krank geworden&#171;. Diese R&uuml;ckmeldungen geben zum einen dem 
                        Hersteller die M&ouml;glichkeit, seine Produktionsmethoden ggf. zu &uuml;berdenken 
                        (z.B. weil er mich sonst als Kunden verliert) und mir die M&ouml;glichkeit zu sehen 
                        (oder zu erfragen), was ich f&uuml;r Qualit&auml;t kaufe und/oder zu entscheiden, 
                        ob ist so etwas kaufen will.
                        <br />
                        <br />
                        Bei den langen und anonymisierten Herstellungsverfahren hat man diese M&ouml;glichkeiten 
                        nicht &ndash; der Prodzent hat den Kontakt zum Verbraucher verloren &ndash; dieser 
                        ist ihm somit mit gr&ouml;&#223;erer Wahrscheinlichkeit ebenso egal wie dann 
                        leider auch die Qualit&auml;t der eigenen Produkte. Ausschlaggebend f&uuml;r 
                        seine Motivation ist lediglich der Gewinn &ndash; und dieser l&auml;sst sich mit 
                        diversen (appetitlichen und leider auch unappetitlichen) Methoden trefflich steigern.
                        <br />
                        <br />
                        Was k&ouml;nnen wir selber tun, damit sich edlich etwas bewegt? Nat&uuml;rlich 
                        k&ouml;nnen wir bei der n&auml;chsten Bundestagwahl die richtige Partei 
                        w&auml;hlen &ndash; nur welche ist das? Selbstverst&auml;ndlich habe ich meine 
                        Favoriten, von denen ich mir eine bessere Verbraucherpolitik verspreche, aber 
                        eine Garantie habe ich nicht, dass diese Partei die gegebenen Versprechen auch 
                        einh&auml;lt.
                        <br />
                        <br />
                        Somit bleibt nur die Abstrafung unlauterer Herstellermethoden durch Verweigerung: 
                        Jedes Produkt, das auch nur den Anschein erweckt, seine Herkunft oder seine 
                        Inhaltsstoffe verschleiern zu wollen, sollte nicht mehr in den Einkaufskorb gelegt 
                        werden. Das ist schwer, vielleicht sogar sehr schwer, aber wenn wir alle erst 
                        einmal mit einem ersten Schritt in diese Richtung gebinnen, werden die Hersteller 
                        hoffentlich anfangen, ihre Machenschaften zu &uuml;berdenken.
                        <br />
                        <br />
                        Mir pers&ouml;nlich ist meine Gesundheit und die meiner Kinder und Enkel jedenfalls 
                        wichtig genug, als dass ich diese Gesundheit zum Spielball freigeben w&uuml;rde. 
                        <br />
                        <br />
                        Ich werde in Zukunft nur noch das kaufen und essen, wovon ich wei&#223; (oder 
                        zumindest doch sehr &uuml;berzeugt bin), dass es meiner Gesundheit zumindest 
                        nicht schadet, ja hoffentlich eher nutzt.
                        <br />
                        <br />
                        Ich w&uuml;rde mich freuen, wenn ihr diesen Beitrag teilt.
                        <br />
                        <br />
                        Eure Doris Paas
