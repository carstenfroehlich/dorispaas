                        <h5>Laktosefreie Milch und Milchprodukte</h5>
                        <hr />
                        Für Menschen mit Laktose-Intoleranz sind Milch und Milchprodukte ein ganz 
                        großes Thema: &#187;normale&#171; Produkte sind wegen des Milchzuckergehalts 
                        tabu. Wenn Sie trotz Laktose-Intoleranz nicht auf Milch und Milchprodukte verzichten 
                        möchten, bieten sich laktosefreie Trinkmilch und Milchprodukte an, 
                        die es mittlerweile in jedem Supermarkt von den verschiedensten Firmen gibt. 
                        Leider gibt es die laktosefreie Milch fast gundsätzlich nur als H-Milch. Dies 
                        begründet sich durch die geringeren Verkaufsmengen. 
