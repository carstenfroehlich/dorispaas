                            <h5>Käse</h5>
                        <hr>
                        </div>
                        <div>
                            Auch mit einer Laktose-Intoleranz ist es in den allermeisten Fällen möglich, viele Käsesorten 
                            ohne anschließende Probleme zu verzehren, denn viele Sorten werden mit Hilfe 
                            von Milchsäurebakterien hergestellt. Diese spalten den Milchzucker bei der Käsereifung 
                            weitestgehend auf. Auf der sicheren Seite sind Sie, wenn Sie beispielsweise 
                            Käse der Firma Bergader kaufen, denn diese versichert, dass
                            ihr gesamtes Sortiment (mit einer Ausnahme) weniger als 0,1% Laktose enthält &ndash; eine Menge, 
                            die auch für sehr empfindliche Menschen tolerabel ist.
                            <br />
                            <br />
                            Ich selber kann aus eigener Erfahrung die Käsesorten empfehlen: Sie sind 
                            lecker und sehr gut bekömmlich. Hier die Stellungnahme der Firma Bergader (15.10.2010):
                        </div>
                        
                        <br />
                        
                        <div class="oneline">
                            <div class="left">
                                <a href="http://www.bergader.de" target="_blank">
                                    <br />
                                    <img src="<?php echo IMG_PATH; ?>Bergader.png" alt="Bergader" />
                                    <br />
                                    www.bergader.de
                                </a>
                            </div>
                            <p class="right">
                                &#187;Der Laktosegehalt all unserer Bergader-Käsespezialitäten mit 
                                Ausnahme unseres WeichKäses in Salzlake liegt derzeit bei unter 0,1%. 
                                Somit gelten unsere Käsespezialitäten als laktosefrei. 
                                Aus diesem Grund können Sie auch unsere BlauschimmelKäse genießen. 
                                <br />
                                Generell empfehlen wir Ihnen, Käsespezialitäten mit kurzem 
                                Mindesthaltbarkeitsdatum zu verzehren, da sich der Laktosegehalt mit 
