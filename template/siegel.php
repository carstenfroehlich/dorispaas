                        <h5>Fairtrade-Siegel</h5>
                        <hr />
                            <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-fairtrade.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Nicht zu verwechseln mit den Bio-Siegeln sind die Siegel für 
                                        Fairen Handel, beispielsweise von TransFair.
                                        <br />
                                        Das Fair-Trade-Siegel kennzeichnet Produkte aus Fairem Handel, 
                                        bei deren Herstellung bestimmte soziale Kriterien eingehalten wurden. 
                                        Vergeben werden diese Siegel von den Organisationen, die im Verband 
                                        &#187;Fairtrade Labelling Organizations International FLO&#171; 
                                        zusammengeschlossen sind. 
                                        <br />
                                 </p>
                                </td>
                            </tr>
                        </table>
                        Wichtiger Hinweis: Produkte mit einem Fair-Trade-Siegel sind nicht zwangfsläufig 
                        auch gleichzeitig Bio-Produkte, jedoch gibt es sehr häufig auch Produkte 
                        aus Fairem Handel, die nach Bio-Kriterien erzeugt wurden.
                        <br />
                        <br />
                        
                        Hilfreicher Link:
