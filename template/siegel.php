                        <a id="ohnegen">&nbsp;</a>
                        <hr />
                        <h5>Siegel &#187;Ohne Gentechnik&#171;</h5>
                        <hr />
                            <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-ohne-gentechnik.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Im August 2009 wurde das neue Siegel &#187;ohne Gentechnik&#171; 
                                        von der damaligen Verbraucherministerin Ilse Aigner vorstellt, womit Hersteller 
                                        vor allem (bevorzugt tierische) Nahrungsmittel (z.B. Milch oder Fleisch) 
                                        kennzeichnen können, wenn bei der Fütterung keine gentechnisch 
                                        veränderten Futterpflanzen wie Mais oder Soja verwendet wurden. 
                                        <br />
                                 </p>
                                </td>
                            </tr>
                        </table>
                        Wichtiger Hinweis: Bei diesen Produkten die Deklaration auch dann erlaubt, 
                        wenn bei der Fütterung gentechnisch hergestellte Vitamine, Enzyme und 
                        anderen Zusätze eingesetzt wurden!
                        <br />
                        <br />
                        Bei allen anderen Nahrungsmitteln werden die die Kriterien strenger ausgelegt: 
                        Grundsätzlich ist kein Einsatz von gentechnisch hergestellten Zusatzstoffen 
                        erlaubt (auch keine zufälligen Beimischungen von zugelassenen gentechnisch 
                        veränderten Pflanzen).
                        <br />
                        <br />
                        
                        Hilfreicher Link:
                        <br />
                        <a href="http://www.transgen.de/aktuell/1093.doku.html" target="_blank">TransGen 
                        &ndash; Transparenz für Gentechnik bei Lebensmitteln</a>
                        <br />
