                        <a id="cleanlabel">&nbsp;</a>
                        <hr />
                        <h5>&#187;Cleanlabel&#171;-Siegel</h5>
                        <hr />
                            <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-cleanlabel.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Eine Besonderheit unter den Siegeln stellen die sogenannten 
                                        &#187;<b>Clean Labels</b>&#171; dar: Hierbei handelt es sich quasi um 
                                        &#187;Erfindungen&#171; der Herstellerfirmen, die mit den 
                                        &#187;sauberen Auszeichnungen&#171; eher Tatsachen verschleiern 
                                        wollen, als den Verbraucher wirklich zu informieren.
                                        <br />
                                        Die Clean Labels sind grundsätzlich keine genormten oder 
                                        gar zertifizierten Labels, sondern stammen aus der Feder den 
                                        jeweiligen Konzernen verpflichteter Grafiker. Aussagen, die 
                                        die Labels versprechen wie z.B. &#187;ohne 
                                        Geschmachsverstärker&#171;, &#187;ohne künstliche Farbstoffe&#171;, 
                                        &#187;ohne Aromastoffe&#171; oder &#187;ohne Konservierungsstoffe&#171;
                                        usw. entsprechen meistens nicht der 
                                        Wahrheit: Besagt ein Label beispielsweise, dass das Nahrungsmittel 
                                        &#187;ohne Geschmachsverstärker&#171; sein soll, so schließt 
                                        dies nicht aus, dass z.B. der Geschmack mit Hefeextrakt aufgepeppt 
                                        worden ist &ndash; ein Zusatzstoff, der nicht unter die gesetzlich 
                                        definierte Bezeichnung &#187;Geschmachsverstärker&#171; fällt.
                                        Die Liste dieser Beispiele ließe sich beliebig verlängern.
                                        <br />
                                        <br />
                                        Deshalb sollten Sie die diversen Phantasielabels auf den Nahrungsmittel-Verpackungen 
                                        grundsätzlich kritisch und mit äußerster Skepsis 
                                        betrachten.
                                 </p>
                                </td>
                            </tr>
                        </table>
                        
