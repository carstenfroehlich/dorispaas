                        In Deutschlad gibt es verschiedene Bio-Siegel, die Hersteller benutzen können, 
                        um ihre Produkte von denen abzugrenzen, die auf herkömmliche Art und Weise 
                        hergestellt wurden.
                        <br />
                        <a id="bio-siegel"></a>
                        <hr />
                        <h5>Bio-Siegel nach EG-Öko-Verordnung</h5>
                        <hr />
                        <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-bio.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Das wohl am häufigsten verwendete Siegel in Deutschland 
                                        ist das im Jahr 2001 eingeführte &#187;Bio-Siegel&#171;.
                                        <br />
                                 </p>
                                </td>
                            </tr>
                        </table>
                        
                        <br />
                        Mit diesem Siegel gekennzeichnete Nahrungsmittel müssen 
                        die folgenden Kriterien erfüllen:
                        <br />
                        &#149; kein Einsatz von gentechnisch veränderte/n Organismen bei der Erzeugung,<br />
                        &#149; kein Einsatz von synthetischen Pflanzenschutzmitteln bei der Erzeugung, <br />
                        &#149; kein Einsatz von leicht löslichen mineralischen Düngern bei der Erzeugung, <br />
                        &#149; keine radioaktive Bestrahlung zur Konservierung.<br />
                        <br />
                        Erlaubt ist jedoch:<br />
                        &#149; Gehalt von bis zu 5% konventionell erzeugte Bestandteile (begrenzt auf in der EG-&Ouml;ko-Verordnung im Anhang VIc gelistete Rohstoffe)
                        <br />
                        <br />
                        Hilfreicher Link:
                        <br />
                        <a href="http://www.bio-siegel.de/" target="_blank">Bundesministerium für Ernährung, 
                        Landwirtschaft und Verbraucherschutz zum Bio-Siegel</a>
                        <br />
                        <br />
                        
                        
                        <a id="eu-siegel-alt">&nbsp;</a>
                        <hr />
                        <h5>Bio-Siegel der EU (alt)</h5>
                        <hr />
                            <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-eu.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Weniger häufig wird das  Siegel der EU in Deutschland verwendet, 
                                        da hier das oben dargestellte Bio-Siegel über einen größeren 
                                        Bekanntheitsgrad verfügt.
                                        <br />
                                        <br />
                                        <br />
                                 </p>
                                </td>
                            </tr>
                        </table>
                        Das EU-Siegel wurde 2000 eingeführt, um eine klare Abgrenzung 
                        zu konventionell (nicht biologisch) hergestellten Lebensmittel 
                        zu ziehen. Die mit diesem Siegel nach der EG-&Ouml;ko-Verordnung 
                        gekennzeichneten Produkte dürfen folgende Bezeichnungen tragen: &#187;Bio-&#171;, 
                        &#187;&Ouml;ko-&#171;, &#187;biologisch&#171;, &#187;ökologisch kontrolliert&#171;, 
                        ökologisch&#171;, &#187;biologisch&#171;, 
                        &#187;biologischer / ökologischer Landbau&#171;, 
                        &#187;biologisch-dynamisch&#171; sowie &#187;biologisch-organisch&#171;. 
                        <br />
                        <br />
                        Die Zutaten von Nahrungsmitteln, die mit dem EU-Siegel gekennzeichnet 
                        sind, müssen zu mindestens 95% aus Bio-Produktion stammen.
                        <br />
                        <br />
                        
                        
                        <a id="eu-siegel-neu">&nbsp;</a>
                        <hr />
                        <h5>Bio-Siegel der EU (neu)</h5>
                        <hr />
                            <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-eu-neu.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Ab dem 1. Juli 2010 wird das oben abgebildete EU-Siegel durch das nebenstehend 
                                        abgebildete neue, modernere Logo abgelöst werden.
                                        <br />
                                        <br />
                                        <br />
                                 </p>
                                </td>
                            </tr>
                        </table>
                        Um das Siegel führen zu dürfen, müssen wie beim Bio-Siegel folgende Regeln eingehalten werden (siehe auch oben):
                        <br />
                        &#149; kein Einsatz von gentechnisch veränderte/n Organismen bei der Erzeugung,<br />
                        &#149; kein Einsatz von synthetischen Pflanzenschutzmitteln bei der Erzeugung, <br />
                        &#149; kein Einsatz von leicht löslichen mineralischen Düngern bei der Erzeugung, <br />
                        &#149; keine radioaktive Bestrahlung zur Konservierung.<br />
                        <br />
                        Erlaubt ist jedoch:<br />
                        &#149; Gehalt von bis zu 5% konventionell erzeugte Bestandteile (begrenzt auf in der EG-&Ouml;ko-Verordnung im Anhang VIc gelistete Rohstoffe)
                        <br />
                        <br />
                        Und darüber hinaus:
                        <br />
                        &#149; Eingrenzung (durch Anhang VI a und b) von Zusatz- und Hilfsstoffen bei verarbeiteten Produkten &ndash; Geschmacksverstärker, künstliche Aromen und Farbstoffe und Emulgatoren sind nicht erlaubt.
                        <br />
                        &#149; Regelung der Einfuhr und strenge, chargenbezogene Kontrolle von Rohwaren und Produkten aus Drittländern.
                        <br />
                        <br />
                        In einer Presseerklärung der Europäischen Kommision hieß es, 
                        die EU-Sterne und das grüne Blatt sollten &#187;Europa und die Natur&#171; symbolisieren.
                        Ob in Europa diese beiden Begriffe jedoch wie bisher eher nebeneinander oder 
                        sogar gegeneinander stehen werden, oder ob Europa sich zur Natur bekennen und 
                        sich mit ihr verbunden und bei wichtigen Entscheidungen verpflichtet fühlen 
                        wird, wird die Zukunft zeigen. Ich persönlich hoffe es zumindest sehr.
                        <br />
                        <br />
                        
