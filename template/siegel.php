                        <h5>Demeter-Siegel</h5>
                        <hr />
                            <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-demeter.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Neben den &#187;offiziellen&#171; Bio-Siegeln gibt es  
                                        verschiedene Deutsche Verbands-Siegel. Diese kennzeichnen Produkte 
                                        von Produktionsverbänden, die über die Mindeststandards 
                                        der EU-&Ouml;ko-Verordnung hinaus die teilweise sehr viel strengeren 
                                        Bestimmungen der jeweiligen Verbände erfüllen müssen. 
                                        <br />
                                 </p>
                                </td>
                            </tr>
                        </table>
                        Hier ist zum Beispiel der Demeter Verband zu nennen, der Produkte verkauft, 
                        die nach anthroposophischen Prinzipien biologisch-dynamisch erzeugt werden. 
                        <br />
                        Bis zum Jahr 2007 trugen ausschließlich nach diesen Prinzipien erzeugte 
                        Produkte das Demeter-Siegel, aufgrund einer schlechten wurde in diesem Jahr 
                        jedoch erstmals den verarbeitenden Betrieben eine Beimischung von bis zu 30% 
                        Getreide gestattet, das nicht biologisch-dynamisch erzeugt wurde. Es musste 
                        jedoch der EG-&Ouml;ko-Verordnung entsprechen.
                        <br />
                        Bei normalen Ernten müssen die Produkte jedoch wieder den strengeren 
                        Verbandsrichtlinen entsprechen.
                        <br />
                        <br />
                        
                        Hilfreicher Link:
                        <br />
                        <a href="http://www.demeter.de/" target="_blank">www.demeter.de</a>
