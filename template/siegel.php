                        <h5>Naturland-Siegel</h5>
                        <hr />
                            <table border="0" cellspacing="0" cellpadding="0">
                            <tr>
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                        <img src="<?php echo IMG_PATH; ?>siegel-naturland.png" alt="" border="0" hspace="0" vspace="0" style="/*float: left; */margin-right: 10px; margin-bottom: 0px;" />
                                    </a>
                                </td>
                                
                                <td style="vertical-align: top; padding-bottom: 10px;">
                                    <p style="margin-top: 0;">
                                        Seit 2005 setzt auch Naturland ökologische Standards, 
                                        die strenger sind als die gesetzlichen Anforderungen der 
                                        EG-&Ouml;ko-Verordnung.  
                                        <br />
                                 </p>
                                </td>
                            </tr>
                        </table>
                        Die Richtlinien gelten nicht nur für die Erzeugung, sondern auch für 
                        die Verarbeitung und beruhen auf einer ganzheitlichen, systemorientierten 
                        Betrachtung. Sie decken auch Bereiche ab, die in der EG-&Ouml;ko-Verordnung 
                        nicht geregelt sind, wie z.B. die Sozialrichtlinien. Naturland hat nach 
                        eigenen Angaben nicht nur 100% &Ouml;ko, sondern auch Faire Landwirtschaft 
                        weltweit.
                        <br />
                        <br />
                        
                        Hilfreicher Link:
                        <br />
                        <a href="http://www.naturland.de/" target="_blank">www.naturland.de</a>
