                        <h5>Hinweis für Menschen mit Histamin-Intoleranz:</h5>
                        <hr />
                        In den allermeisten Fällen haben Menschen mit Histamin-Intoleranz Probleme mit 
                        vergorenen Lebensmitteln. Da jedoch die gesundheitlichen Vorteile der probiotischen 
                        Gärgetränke nicht unbeträchtlich sind, kann man versuchen, sehr vorsichtig auszutesten, 
                        ob kleinere Mengen eventuell doch bekömmlich sind. 
                        <br />
                        <hr />
                        <h5>Hinweise für Menschen mit Laktose-Intoleranz:</h5>
                        <hr />
                        Kefir wir im Allgemeinen aus Milch zubereitet, die Milchzucker enthält. 
                        Menschen mit Laktose-Intoleranz sollten beachten, dass bei der Vergärung 
                        der Milch zu Kefir ein Teil des in der Milch enthaltenen Milchzuckers zu 
                        Traubenzucker und Schleimzucker aufgespalten wird. Bei einer nur leicht ausgeprägten 
                        Laktose-Intoleranz kann man austesten, wie viel Kefir vertragen wird. Man
                        kann den Kefir jedoch auch aus laktosefreier Milch herstellen. Dabei ist zu beachten, 
                        dass nur Frischmilch aus dem Kühlregal verwendet werden kann, denn die üblicherweise 
                        verkaufte H-Milch ist nicht geeignet.
