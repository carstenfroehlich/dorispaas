                        <h5>Ausgabe 51 (März 2020)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2020-02-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Alle reden von der Corona-Epidemie – ich an dieser Stelle auch: Das Cornona-Virus (SARS-CoV-2), das die COVID-19-Erkankung ausl&ouml;st, versetzt derzeit 
                        viele Menschen in Angst und Schrecken &ndash; manche sogar in Panik.
                        In diesem Newsletter m&ouml;chte ich die Problematik beleuchten und versuchen, einige Ihrer Fragen zu beantworten: Zu welcher &#187;Risikogruppe&#171; geh&ouml;ren 
                        Sie, wie gef&auml;hrdet sind Sie, dass schwerwiegende Komplikationen auftreten? Wie wichtig ist es, sich selbst zu sch&uuml;tzen und welche Ma&#223;nahmen sind 
                        daf&uuml;r sinnvoll und wirksam? Warum ist es wichtig, andere Personden nicht zu gef&auml;hrden und welche Verhaltensweisen k&ouml;nnen dabei helfen?
                        Warum sind Verbote von Massenveranstaltungen jetzt wichtig und richtig, und was k&ouml;nnen sie bewirken?
                        Lesen Sie hierzu bitte auch den <a href="http://www.dorispaas.de/index.php?page=blog#blog-2020-03-12" target="_blank">Eintrag in meinem Blog</a>, in dem ich die 
                        Hintergr&uuml;nde der Erkrankung darstelle.
                        <br />
                        <br />
                        Zur Vorbeugung vor einer Infektion bzw. einem schweren Erkrankungsverlauf ist es nicht nur jetzt sondern grunds&auml;tzlich g&uuml;nstig, die Gesundheit zu erhalten und 
                        zu festigen und um das Immunsystem zu st&auml;rken. Aus diesem Anlass habe ich die folgenden Themen zum Schwerpunkt dieses Newsletters gew&auml;hlt.
                        <br />
                        <br />
                        <hr />
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-healthtogo" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2020-02-healthtogo.png" alt="Health to go" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-healthtogo" target="_blank">Schwerpunktthema: &#187;Health to go &ndash; gibt es das?&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/allgemein/Health to go &ndash; gibt es das?)</i>
                        <br />
                        Dass Gesundheit sehr, sehr viel mit der Ern&auml;hrung zu tun hat, ist mittlerweile eine Binsenweisheit. Dass sich auch bestimmte Verhaltensweisen wie ausreichende 
                        Bewegung, ein gesundes Stressmanagement und Achtsamkeit f&uuml;r sich selbst dazu geh&ouml;ren, wei&#223; auch jeder (oder sollte es zumindest wissen).
                        Heute &ndash; in einer Zeit, in der meist Frauen und M&auml;nner berufst&auml;tig sind (sein m&uuml;ssen oder berechtigterweise sein wollen), nehmen wir uns vor 
                        der Arbeit keine Zeit mehr für ein gen&uuml;ssliches Fr&uuml;hst&uuml;ck, sondern f&uuml;llen im Bestfalle einen Kaffee in einen Trinkbecher zum Mitnehmen oder 
                        kaufen den Coffee to go rasch auf dem Weg ins B&uuml;ro (meist sogar in einem Papp- oder Plastikbecher zum Wegwerfen). F&uuml;r die &#187;Gesundheitsbewussten&#171; 
                        gibt es noch das M&uuml;sli to go dazu. Wenn Probleme auftreten, greifen wir zur Tablette, um die Symptome im Hauruck-Verfahren zu beseitigen: Gesundheit to go! 
                        Gibt es das wirklich? Es ist Zeit zum Umdenken! Lesen Sie den Beitrag bitte bis zum Schluss &ndash; er ist zugegebenerma&#223;en recht lang, aber es lohnt sich (wie ich hoffe).
                        <br />
                        <br />
                        <hr />
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-immun" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2020-02-immunsystem.png" alt="Immunsystem" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 10px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=ganz-immun" target="_blank">Das Immunsystem &ndash; ganzheitlich betrachtet</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/allgemein/St&auml;rkung des Immunsystems)</i>
                        <br />
                        Nat&uuml;rlich leuchtet es sofort ein, dass wir mit einem gest&auml;rkten Immunsystem besser gegen Erk&auml;ltungskrankheiten gewappnet sind. Auch viele 
                        andere Krankheiten brechen bei einem robusten Immunsystem erst gar nicht aus oder verlaufen zumindest wesentlich leichter. Da ein gest&auml;rktes &ndash; sprich: 
                        optimiertes &ndash; Immunsystem immer auch zu einer robusteren Gesundheit und damit zu mehr Wohlbefinden f&uuml;hrt, k&ouml;nnen meist auch Probleme des 
                        Verdauungssystems leichter ertragen werden oder treten auch abgeschw&auml;chter oder seltener auf. Bei einem gut funktionierenden Immunsystem, das ja immerhin 
                        zu rund 80 &#37; im Darm angesiedelt ist, weist die Darmschleimhaut einen insgesamt wesentlich besseren Zustand auf, was nat&uuml;rlich auch umgekehrt der Fall ist. 
                        Die Verdauung geht z&uuml;giger vonstatten, und Schad- und Giftstoffe werden besser abtransportiert. Unter diesen optimalen Bedingungen kann die Nahrung reibungsloser 
                        verdaut werden, so dass sich keine oder zumindest sehr viel weniger sch&auml;dliche Gase und S&auml;uren durch Maldigestionen bilden k&ouml;nnen. Somit h&auml;ngen 
                        die Qualit&auml;t des Immunsystems, die gesunde Verdauung und die Gesundheit allgemein eng zusammen. 
