                        <h5>Menge der Testsubstanzen</h5>
                        <hr />
                        Weitere Fehler werden häufig in Bezug auf die <b>Menge der Testsubstanzen</b> gemacht. 
                        Leider ist erschreckend vielen Behandlern nicht geläufig, wie die korrekten Mengen 
                        aussehen, die sich von Testzucker zu Testzucker durchaus unterscheiden. Folgende 
                        Mengen müssen verwendet werden:
                        <br />
                        <b>&#149; 50g Laktose</b> (zur Ermittlung einer Laktose-Intoleranz)
                        <br />
                        <b>&#149; 25g Fruktose</b> (zur Ermittlung einer Fruktose-Intoleranz)
                        <br />
                        <b>&#149; 10g Sorbit</b> (zur Ermittlung einer Sorbit-Intoleranz)
                        <br />
                        <b>&#149; 50g &ndash; 80g Glukose</b> (zur Ermittlung einer Dünndarmfehlbesiedelung)
                        <br />
                        <b>&#149; 20g Laktulose</b> (zur Ermittlung einer Dünndarmfehlbesiedelung oder bei Nonrespondern)
                        <br />
                        <br />
                        Alle Testsubstanzen werden in jeweils <b>250ml Wasser</b> gelöst. Alle anderen Mengen 
                        verfälschen das Ergebnis.
                        <br />
                        <br />
                        Abweichende Mengen werden nur bei kleineren Kindern verwendet, wobei sich dann 
                        die Menge nach dem Körpergewicht richtet. 
                        <br />
