                        Oftmals gleicht die Suche nach der Ursache von unklaren Verdauungsbeschwerden der sprichwörtlichen Suche nach der Nadel im Heuhaufen. In diesem Beitrag finden Sie 
                        Hinweise zu Hintergründen und Zusammenhängen in Bezug auf geeignete Atemtests.
                        <br />
                        <a id="tagebuch"></a>
                        <hr />
                        <h5>Verzehrtagebuch zur Ermittlung eines ersten Verdachts</h5>
                        <hr />
                        Es ist nicht sinnvoll, ohne einen <b>begründeten</b> Verdacht auf Nahrungsmittel-Unverträglichkeiten oder eine Dünndarmfehlbesiedelung (SIBO) 
                        Atemtests durchzuführen. Erstens würden Sie hier viel Geld für eventuell sinnlose Tests ausgeben und zweitens &ndash; noch 
                        viel wichtiger &ndash; Ihre Mikrobiota (Darmflora) mit u.U. überflüssigen Testsubstraten belasten. Deshalb ist es hilfreich, <b>immer zuerst ein 
                        Ernährungs- und Symptomtagebuch</b> zu führen, in dem Sie für ein bis zwei Wochen alles protokollieren, was Sie essen und trinken. Zusätzlich 
                        werden alle auftretenden Symptome wie Bauchschmerzen, Blähungen, Übelkeit oder Durchfall etc. eingetragen. Aus diesen Aufzeichnungen ergibt 
                        sich oftmals schon ein Zusammenhang zu bestimmten Lebensmitteln und damit ein erster Verdacht.
                        <br />
                        <a id="selbsttest">&nbsp;</a>
                        <hr />
                        <h5>Formular für einen Selbsttest</h5> 
                        <hr />
                        <b>Auch mithilfe einiger gezielter Fragen</b> und den entsprechenden Antworten kann sich bereits ein bestimmter Verdacht ergeben, ob eher eine 
                        Nahrungsmittel-Unverträglichkeit, ein Reizdarm-Syndrom oder aber auch eine Dünndarmfehlbesiedelung der Grund für Ihre Beschwerden sein könnte.
                        <br />
                        <br />
                        Im <a href="downloads" target="_blank">Downloadbereich</a> finden Sie einen <b>Fragebogen zur Selbstdiagnose</b> als PDF und Vorlagen für ein 
                        <b>Verzehrtagebuch</b> (Ernährungs- und Symptomtagebuch) als Excel-Datei zum Eintragen direkt am PC oder aber als PDF zum Ausdrucken.
                        <br />
                        <br />
                        <b>Hinweis zu dem Selbsttest:</b> Bitte beachten Sie, dass der Selbsttest keinesfalls die Beratung durch einem Arzt  ersetzt. Er kann Ihnen lediglich einen 
                        ersten Anhaltspunkt geben. 
                        <br />
                        <br />
                        <b>Hinweis zum Ernährungs- und Symptomtagebuch:</b> Da es bei der Auswertung Ihres Ernährungs- und Symptomtagebuchs nicht nur wichtig ist, eventuelle 
                        Symptomauslöser zu erkennen, sondern auch, ggf. einen Zeitversatz zu berücksichtigen, biete ich Ihnen gerne meine Expertise im Rahmen einer 
                        individuellen <a href="beratung" target="_blank">Beratung</a> an.
                        <br />
                        <a id="karenz">&nbsp;</a>
                        <hr />
                        <h5>Karenz der verdächtigen Lebensmittel</h5>
                        <hr />
                        Sie können nun versuchen, die verdächtigen Lebensmittel <b>testweise</b> vom Speiseplan zu streichen. Schauen Sie, ob es Ihnen nach einiger Zeit besser geht. 
                        Dies würde Ihren Verdacht bekräftigen. Wenn eine Karenz oder weitestgehende Reduzierung von <b>etwa zwei bis drei Wochen</b> keinerlei Veränderung nach sich zieht, 
                        liegen mit großer Wahrscheinlichkeit andere Gründe vor oder es kommen zu der einen vermuteten Ursache noch weitere hinzu.
                        <br />
                        <br />
                        <b>Wichtiger Hinweis:</b> Durch längeres Meiden oder Reduzieren mehrerer Lebensmittel oder Lebensmittelgruppen kann die <b>Diversität (Vielfalt) Ihrer Mikrobiota</b>
                        beeinträchtig werden. Bitte grenzen Sie die Einschränkungen zu Testzwecken bitte auf einen möglichst kurzen Zeitraum von nicht länger als zwei bis drei Wochen ein.
                        <br />
                        <a id="gluten">&nbsp;</a>
                        <hr />
                        <h5>Gluten</h5>
                        <hr />
                        Sollten Sie <b>Probleme mit Gluten</b> haben, wäre es auch wenn es Ihnen unter einer Reduktion dieses Klebereiweißes aus Getreide besser geht, nun an der Zeit, sich 
                        <b>zeitnah einen Termin bei einem Gastroenterologen</b> zu besorgen, der mit einem Bluttest und &ndash; falls dieser positiv ausfällt &ndash; mit einer Magenspiegelung 
                        überprüfen muss, ob eine <b><a href="gluten" target="_blank">Zöliakie</a></b> vorliegt. Bitte beachten Sie in diesem Falle, dass Sie <b>umgehend wieder Gluten verzehren
                        müssen</b>, denn nur unter ausreichendem Glutenverzehr haben diese Tests eine belastbare Aussagekraft.
                        <br />
                        <br />
                        Erst wenn diese Tests negativ ausfallen, können Sie wieder auf das Gluten verzichten. Sollte es erneut zu einer Beschwerdebesserung kommen, liegt eine 
                        <b><a href="gluten" target="_blank">Gluten-Sensitivität</a></b> vor, also eine Unverträglichkeit des Glutens, die mit dem weiteren Glutenverzicht bzw. einer individuell 
                        erforderlichen Reduzierung &#187;behandelt&#171; wird.
                        <br />
                        <a id="unvertraeglichkeiten">&nbsp;</a>
                        <hr />
                        <h5>Nahrungsmittel-Unverträglichkeiten</h5>
                        <hr />
                        Wenn andere Lebensmittel wie z.B. Milch  und Milchprodukte oder Obst und Gemüse in Verdacht stehen, ist es sinnvoll, mit dem jeweils entsprechenden Atemtest zu schauen, 
                        ob Unverträglichkeiten auf <a href="laktose" target="_blank"><b>Laktose</b></a>, <a href="fma" target="_blank"><b>Fruktose</b> oder <b>Sorbit</b></a> die Ursache sein 
                        könnten. Sind es hingegen eher oder Zwiebeln, Kohl und Hülsenfrüchte, ist eine <a href="oligosaccharide" target="_blank"><b>Oligosaccharid-Unverträglichkeit</b></a> naheliegend. 
                        Hier gibt es leider (noch) keinen geeigneten Atemtest, hier hilft nur der Verzicht und ggf. das Abstellen von dafür verantwortlichen Ursachen (wie z.B. ein 
                        <a href="darmschleimhaut" target="_blank">Leaky Gut-Syndrom</a>).
                        <br />
                        <a id="duenndarmfehlbesiedelung">&nbsp;</a>
                        <hr />
                        <h5>Dünndarmfehlbesiedelung</h5>
                        <hr />
                        Wenn Sie anhand Ihrer Tagebuchaufzeichnungen feststellen, dass Sie &#187;essen können, was Sie wollen&#171; und <b>eigentlich immer Probleme</b> haben, dann könnte eine 
                        <a href="duenndarmfehlbesiedelung" target="_blank">Dünndarmfehlbesiedelung</a> die Ursache sein. Insbesondere ein aufgeblähter Bauch, dessen Umfang ab dem Morgen 
                        oder Vormittag zunimmt und während der Nacht wieder flacher wird, kann auf eine solche Erkrankung hinweisen.
                        <br />
                        <a id="atemtests">&nbsp;</a>
                        <hr />
                        <h5>Atemtests</h5>
                        <hr />
                        Um Nahrungsmittel-Unverträglichkeiten oder aber auch eine Dünndarmfehlbesiedelung  zu diagnostizieren, eignet sich ein Atemtest, bei dem entweder nur der Gehalt von 
                        <b>Wasserstoff (H<sub>2</sub>)</b> oder &ndash; besser &ndash; auch der Gehalt an <b>Methan (CH<sub>4</sub>)</b> im Atem gemessen wird. Verwendet werden jeweils 
                        <b>entsprechende Zucker als Testsubstrat</b>. Diese Tests können in spezialisierten Hausarztpraxen, bei einem Gastroenterologen oder auch als ambulante Untersuchung in 
                        einem Krankenhaus durchgeführt werden. Es gibt aber auch Sets für einen Heimtest, den Sie sich bei bestimmten Laboren bestellen und dann zu Hause machen können.
                        <br />
                        <br />
                        In seriösen Praxen und Krankenhäusern werden <b>Messegeräte</b> benutzt, in die man pustet und an denen man sofort an einer Anzeige den entsprechenden Wert ablesen kann.
                        <br />
                        <br />
                        Für den Heimtests bekommen Sie mehrere <b>Röhrchen und ein Mundstück</b> zugeschickt. Während des Tests wird in bestimmten Zeitintervallen jeweils in ein Röhrchen gepustet, 
                        das ein wenig der Atemluft aufnimmt. Die Röhrchen müssen dann an das Labor zurückgeschickt werden, wo die enthaltene Luft dann mithilfe von Messgeräten analysiert werden kann.
                        <br />
                        <br />
                        Manchmal werden solche Testsets auch in den Arztpraxen verwendet, weil diese sich die recht teuren Messgeräte nicht leisten können oder wollen. Ich empfehle, dies 
                        vorher im Gespräch abzuklären und ggf. eine besser ausgestattete Praxis aufzusuchen.
                        <br />
                        <br />
                        <b>Ein wichtiger Hinweis: </b>Zur Diagnose oder Ausschluss einer Unverträglichkeit oder Dünndarmfehlbesiedelung (SIBO) reicht ein Atemtest allein nicht aus. Es müssen 
                        immer auch <b>zahlreiche Begleitfaktoren</b> wie u.a. die Art der Beschwerden und diese in ihrer tageszeitlichen Abfolge und Intensität hinzugezogen werden.
                        Auch das Stuhlverhalten, die Ernährung, andere Erkrankungen und ggf. Medikamente und Nahrungs-Ergänzungsmittel und die Lebensumstände müssen mit betrachtet werden. Für eine 
                        belastbare Bewertung ist am besten ein spezialisierter Berater/in zu konsultieren, um keine falschen und/oder überflüssigen Therapien &ndash; insbesondere Antibiosen &ndash; 
                        auf sich zu nehmen. 
                        <br />
                        <a id="hintergruende">&nbsp;</a>
                        <hr />
                        <h5>Hintergründe zu Atemtests</h5>
                        <hr />
                        Wie oben beschrieben, wird bei den meisten Tests, die direkt mit einem Messgerät durchgeführt werden, nur der Gehalt von Wasserstoff (H<sub>2</sub>) im Atem gemessen, weil
                        die Messgeräte, die beide Gase gleichzeitig detektieren können, um ein Vielfaches teurer sind als die reinen Wasserstoff-Messgeräte. In einer Arztpraxis oder Krankenhaus-Ambulanz 
                        würde sich ein teures Messgerät für beide Atemgase kaum lohnen. Für die Heimtests, die zusätzlich den Methangehalt (CH<sub>4</sub>) berücksichtigen, können sich in den Laboren 
                        die teuren Geräte durch die zahlreichen eingeschickten Tests besser amortisieren.  
                        <br />
                        <br />
                        Und warum ist es nun besser, einen <b>Wasserstoff- und Methantest</b> durchzuführen als lediglich einen Wasserstoff-Test? Der Zusammenhang erklärt sich folgendermaßen:
                        Bei Menschen, die die betreffenden Zucker &#187;ordnungsgemäß&#171; verdauen können, werden diese im Dünndarm durch die entsprechenden Enzyme oder Transportproteine 
                        bearbeitet und über die Darmschleimhaut ins Blut befördert. Fehlen diese Enzyme oder Transportproteine oder besteht ein Mangel, gelangen die Zucker in den 
                        Dickdarm, wo sie von den Bakterien der Darmflora verstoffwechselt werden. Dabei entstehen u.a. Wasserstoff und Methan. Diese Gase gelangen über die Darmschleimhaut 
                        und das Blut in die Lungen und werden dort abgeatmet (lesen Sie hierzu auch den Beitrag &#187;<a href="atmen" target="_blank">Atem und Verdauung</a>&#171;. 
                        Wird also im Atem ein erhöhter Wasserstoff- und/oder Methangehalt festgestellt, ist die Diagnose einer Intoleranz auf den entsprechenden Testzucker so gut wie sichergestellt.
                        <br />
                        <br />
                        Bei einem Atemtest wird auf nüchternen Magen die erste Wasserstoff- und/oder Methankonzentration im Atem als <b>Referenzwert (Basis- oder Nüchternwert)</b> gemessen. Danach muss 
                        eine bestimmte Menge des in Wasser gelösten Testzuckers getrunken werden. Bei einem Verdacht auf eine Nahrungsmittel-Unverträglichkeit sollten dann über <b>mindestens 2, 
                        optimalerweise sogar über 3 Stunden</b> Messungen der Gaskonzentration(en) im Abstand von jeweils <b>20 &ndash; 30 Minuten</b> vorgenommen werden. Aus dem <b>Anstieg der 
                        Gasgehalte</b> in der Atemluft und der Protokollierung und Bewertung der <b>Beschwerden während des Tests</b> &ndash; wann und wie heftig treten Bauchgrummeln, Bauchschmerzen, 
                        Blähungen, Durchfall, Übelkeit etc. auf &ndash; kann das Ergebnis zweifelsfrei ausgelegt werden. Übrigens: auch noch später auftretende Beschwerden können für den Diagnostiker 
                        wichtig sein. Bitte teilen Sie solche Vorkommnisse auch noch nachträglich mit.
                        <br />
                        <br />
                        Falls ein Verdacht auf eine <b>Dünndarmfehlbesiedelung</b> vorliegt, eigenen sich als Testsubstanzen entweder die Glukose oder die Laktulose. Mit beiden Stoffen muss aber in diesem 
                        Falle unbedingt mindestens in den ersten beiden Stunden sehr viel engmaschiger gemessen werden, d.h. <b>alle 10 (maximal alle 15) Minuten</b>, denn in dieser Zeit passiert die 
                        Testsubstanz den Dünndarm, in dem sich ja in diesem Falle eine eventuelle Problematik abspielt. <b>In der dritten Stunde reichen dann Abstände von 20 &ndash; 30 Minuten</b>.
                        <br />
                        <a id="messgas">&nbsp;</a><br />
                        <hr />
                        <h5>Wasserstoffmessung oder Methanmessung? </h5>
                        <hr />
                        Bei manchen &ndash; nicht allen &ndash; Menschen beherbergt die Darmflora zu wenige Bakterienarten, die bei der Verstoffwechselung von Zuckern Wasserstoff produzieren, und es 
                        gibt mehr Methanproduzenten. Um diese sogenannten &#187;<b>Nonresponder</b>&#171; mit zu berücksichtigen, ist ein gleichzeitiges Messen beider Gaskonzentrationen sinnvoll. 
                        Würde nur der Wasserstoffgehalt gemessen, rutschen diese Menschen &#187;durch das Raster&#171;, und insbesondere bei Tests auf <b>Nahrungsmittel-Unverträglichkeiten</b> werden dann 
                        falsch-negative Diagnosen gestellt. Leider ist diese Tatsache (zu) wenigen Ärzten bekannt, die anschließend wenigstens einen geeigneten Test zum Detektieren dieser Besonderheit
                        durchführen könnten. 
                        <br />
                        <br />
                        Wurde bereits in vorangegangenen Tests festgestellt, dass die Mikrobiota ausreichend Wasserstoffbildner enthält, würde theoretisch eine reine Wasserstoffmessung ausreichen. Da 
                        jedoch bei kluger Auswahl der Testsubstrate und entsprechend engmaschigen Messintervallen auch gleichzeitig eine Dünndarmfehlbesiedelung miterfasst werden kann, rate ich auch
                        hier nach Möglichkeit zu einer kombinierten Wasserstoff- und Methanerfassung.
                        <br />
                        <br />
                        Vor allem aber zur Diagnose bzw. zum Ausschluss einer <b>Dünndarmfehlbesiedelung</b> möchte ich dringend dazu raten, immer einen kombinierten Wasserstoff- und Methantest durchführen zu lassen,
                        da hier &ndash; insbesondere bei Menschen, die zu Verstopfung neigen &ndash; häufig auch Methan-produzierende Bakterien mit im Spiel sind. Die Bezeichnungen für diese beiden Formen
                        der Fehlbesiedelungen sind SIBO (bei überwiegenden Wasserstoffproduzenten) bzw. IMO (bei überwiegenden Methanproduzenten). Es gibt aber auch Menschen, die gleichzeitig an einer SIBO 
                        und einer IMO leiden. Deshalb ist der kombinierte Atemtest immer der Königsweg.
                        
                        <br />
                        <a id="durchfuehrung">&nbsp;</a>
                        <hr />
                        <h5>Durchführung eines Atemtests</h5>
                        <hr />
                        Unabhängig von der Methode, mit welcher gemessen wird, ist der Ablauf immer identisch: 
                        <br />
                        <br />
                        Zuerst muss mit einem ersten Pusten ein Basiswert (Nüchternwert) ermittelt werden. Dieser sollte 
                        möglichst nicht höher als 20ppm (Parts per Million), besser sogar nicht höher als 
                        10ppm sein. Ist der Basiswert höher, sollte der Test abgebrochen werden, da die 
                        Werte nicht wirklich belastbar sind. 
                        <br />
                        <br />
                        Nach der Ermittlung des Basiswerts wird die Testlösung möglichst zügig getrunken. 
                        <br />
                        <br />
                        Anschließend wird in den der gewünschten Diagnose entsprechenden Zeitabständen 
                        erneut gepustet, um die weiteren Werte zu ermitteln.
                        <br />
                        <br />
                        Die Werte werden in eine Tabelle eingetragen und sollten dem Patienten zeitgleich 
                        oder zumindest am Ende des Tests mitgeteilt und schriftlich ausgehändigt werden.
                        Bitte lassen Sie sich hier nicht etwa auf eine spätere Mitteilung vertrösten. Es 
                        sind Ihre Werte, auf die Sie ein Anrecht haben! Es reicht auch keinesfalls, wenn 
                        man Ihnen lediglich ein &#187;Urteil&#171; (Unterträglichkeit bzw. Dünndarmfehlbesiedelung 
                        ja oder nein) mitteilt. Vielleicht möchten Sie Ihre Werte einem weiteren Diagnostiker 
                        zeigen, von dem Sie eine Zweitmeinung einholen wollen.
                        <br />
                        <br />
                        Während der gesamten Testdauer ist zusätzlich zu protokollieren, ob und ggf. welche 
                        Symptome wie z.B. Blähungen, Bauchschmerzen oder Durchfälle auftreten. Diese Symptome 
                        sollten ebenfalls in die Tabelle eingetragen werden, denn sie geben dem Diagnostiker 
                        ergänzende Hinweise zu den Atemgaswerten.
                        <br />
                        <a id="abwaegung">&nbsp;</a>
                        <hr />
                        <h5>Vor- und Nachteile der beiden Messmethoden</h5>
                        <hr />
                        Sowohl der Test mit einem Messgerät als auch der Heimtest mit den Röhrchen hat 
                        seine ganz speziellen Vor- und Nachteile.
                        <br />
                        <br />
                        Vorteil einen Tests, bei dem die Werte direkt an einem Messgerät angezeigt werden, 
                        kann u.U. in der Bewahrung vor unnütz durchgeführten Komplettests liegen. 
                        <br />
                        <br />
                        Ist der Basiswert höher als maximal 20ppm, sollte die Testlösung nicht getrunken 
                        werden und der Test zu einem späteren Zeitpunkt wiederholt werden. Jede Testlösung 
                        belastet die Darmflora. Muss ein Test wiederholt werden, bedeutet dies eine doppelte 
                        Belastung.
                        <br />
                        <br />
                        Weiterhin können die Werte sofort abgelesen und dem Patienten günstigstenfalls 
                        gleich die Auswertung und damit die Diagnose mitgeteilt werden.
                        <br />
                        <br />
                        Ein weiterer Vorteil ist, dass bei dieser Art von Tests, die ja in der Regel in 
                        einer Arztpraxis oder ambulant in einem Krankenhaus durchgeführt werden, die 
                        Kosten von den Krankenkassen übernommen werden.
                        <br />
                        <br />
                        Nachteile sind, dass zum einen meist längere Wartezeiten für einen Termin in Kauf 
                        zu nehmen sind und zum anderen diese Tests meist nur den Wasserstoffgehalt 
                        berücksichtigen (siehe auch Abschnitt &#187; <a href="<?= URL_ROOT ?>atemtest#messgas" class="faqmenu">Wasserstoffmessung 
                        oder Methanmessung?</a>&#171;.
                        <br />
                        <br />
                        Ein weiterer Nachteil ist die leider erschreckend hohe Rate an fehlerhaft durchgeführten 
                        Tests. Bitte sprechen Sie deshalb vor einem geplanten Test ausführlich mit dem Arzt 
                        und klären Sie ab, ob in der Praxis alle entscheidenden Faktoren bekannt sind und 
                        auch wirklich gewissenhaft beachtet werden. Bitte scheuen Sie sich nicht vor 
                        qualifizierten und auf ausreichend Hintergrundwissen basierenden Fragen &ndash; es 
                        geht schließlich um Ihre Gesundheit!
                        <br />
                        <br />
                        Auch bei Heimtests gibt es Vor- und Nachteile: 
                        <br />
                        <br />
                        Vorteile sind, dass ein solcher Heimtest zum einen unkompliziert bei einem der 
                        anbietenden Labore bestellt und zeitnah durchgeführt werden kann. Das Ergebnis 
                        und meist auch einige Behandlungsvorschläge kommen dann innerhalb weniger Tage 
                        mit der Post.
                        <br />
                        <br />
                        Die meisten Heimtests messen &ndash; wie die Tests mit den Messgeräten auch &ndash; nur 
                        den Wasserstoffgehalt. Es gibt jedoch auch Tests, bei denen gleichzeitig in einem 
                        einzigen Test sowohl Wasserstoff als auch Methan gemessen werden können. Falls Sie
                        einen Heimtest planen, sollten Sie auf jeden Fall einen solchen Test bevorzugen.
                        <br />
                        <br />
                        Ein entscheidender Nachteil eines Heimtests liegt darin, dass Sie erst nach der 
                        kompletten Durchführung und der Auswertung im Labor den Basiswert erfahren. Lag 
                        dieser höher als 20ppm, ist die Belastbarkeit der Diagnose fragwürdig und im Zusammenhang 
                        mit vielen anderen Faktoren bei einer Bewertung und Diagnose genauestens zu hinterfragen. 
                        <br />
                        <br />
                        Mit einer sorgsamen Vorbereitung und der Einhaltung aller erforderlichen Maßnahmen am Vortag 
                        und am Testtag selbst kann dieses Risiko allerdings minimiert werden. Da auch bei der 
                        weiteren Durchführung von Heimtests eine Menge Fehler gemacht werden können, 
                        ist gerade bei Heimtests immer eine 
                        <a href="<?= URL_ROOT ?>atemtest#beratungvordemtest" class="faqmenu">ausführliche, 
                        kompetente und individuelle Beratung</a> bereits <b>vor der Durchführung</b> 
