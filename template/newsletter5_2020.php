                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Ern&auml;hrung/Informationen &uuml;ber Milch</i>
                        <br />
                        Milch ist im Normalfall die erste und ausschlie&#223;liche Nahrung von S&auml;uglingen. Muttermilch enth&auml;lt s&auml;mtliche, in der ersten Lebensphase f&uuml;r die Entwicklung 
                        des heranwachsenden K&ouml;rpers und insbesondere des Gehirns notwendigen Stoffe. Weiterhin werden mit der Muttermilch Abwehrstoffe gegen viele Krankheiten, die die Mutter 
                        erfolgreich &uuml;berwunden hat, an den S&auml;ugling weitergegeben und machen ihn damit in der Stillzeit gegen diese Erkrankungen weitgehend immun. Somit sind gestillte Babys 
                        grunds&auml;tzlich zwar ges&uuml;nder als Kinder, die mit der Flasche und damit mit einer &#187;artfremden&#171; Milch aufgezogen werden, aber auch diese Kinder wachsen und gedeihen. 
                        Nur ist Milch &ndash; und hier ist die Kuhmilch (und damit eine &#187;artfremde Milch&#171;) gemeint &ndash; auch bek&ouml;mmlich f&uuml;r gr&ouml;&#223;ere Kinder und auch f&uuml;r 
                        Erwachsene? Und wenn ja, ist sie wirklich so gesund, wie uns die Milchindustrie seit Jahrzehnten suggerieren will? Dieser Beitrag beleuchtet dieses heiß und kontrovers diskutierte 
                        Thema aus verschiedenen Blickwinkeln, um Ihnen eine eigene Meinung zu erm&ouml;glichen, die nicht nur auf ideologischen und damit t&ouml;nernen F&uuml;&#223;en steht.
