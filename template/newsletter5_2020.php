                        <h5>Ausgabe 54 (September 2020)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2020-05-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Das letzte halbe Jahr war eine sehr ungew&ouml;hnliche Zeit f&uuml;r uns alle, denn wir mussten einige unserer Gewohnheiten &uuml;ber Bord werfen und ganz neue Verhaltensweisen 
                        ein&uuml;ben. Nicht nur die Begr&uuml;&#223;ung unserer Mitmenschen ist nun anders, auch die Treffen mit Freunden waren zun&auml;chst nur noch in sehr kleinem Rahmen m&ouml;glich. 
                        Sp&auml;ter durften die Gruppen zwar etwas gr&ouml;&#223;er sein, aber der Abstand musste doch gewahrt werden. Auch Reisen waren f&uuml;r viele von uns &ndash; wenn &uuml;berhaupt 
                        &ndash; nur noch in abgespeckter Form m&ouml;glich.  All dies ist gew&ouml;hnungsbed&uuml;rftig, aber doch notwendig, und es ist erfreulich, dass (abgesehen von einigen unbelehrbaren 
                        Rechthabern) die meisten Menschen dies zu unser aller Schutz auch verstehen und einhalten. Insgesamt scheint sich dadurch das Bewusstsein zu steigern, dass wir selber f&uuml;r unsere 
                        Gesundheit verantwortlich sind und wir sehr viel daf&uuml;r tun k&ouml;nnen, dass es uns gut geht. Nat&uuml;rlich kann uns der eine oder andere Krankheitserreger einen Strich durch die 
                        Rechnung machen, aber die Krankenkassen haben festgestellt, dass im letzten halben Jahr, seit die Hygieneregeln mit Abstandhalten, H&auml;ndewaschen und Mund-Nasenbedeckungen 
                        vorgeschrieben sind, sich nicht nur nicht nur die Covid-19-Infektionen hier bei uns in Deutschland in Grenzen halten, sondern auch deutlich weniger Grippe- und 
                        Magen-/Darmerkrankungen aufgetreten sind. In Sachen Eigenverantwortung möchte ich Sie auf den Bereich &#187;Ganzheitliche Gesundheit&#171; auf meiner Website hinweisen. 
                        Ich lade Sie ganz herzlich ein, hier einmal ausgiebig zu st&ouml;bern. Auch f&uuml;r diesen Newsletter habe ich als Schwerpunkt ein Thema aus diesem Sachgebiet herausgegriffen.
