                        <br />
                        K&auml;se wird aus Milch hergestellt. Bei uns in Deutschland gibt es unz&auml;hlige K&auml;sesorten. Die am h&auml;ufigsten verzehrten Sorten werden aus Kuhmilch 
                        hergestellt, es gibt aber auch leckeren K&auml;se aus Schafs- und Ziegenmilch, in anderen L&auml;ndern auch aus Esels- oder Kamelmilch. 
                        Es gibt Frischk&auml;se, Weichk&auml;se, Schnitt- und Hartk&auml;se und viele 
                        Sorten mehr, wobei sich diese auch durch ihren Wassergehalt unterscheiden. Der Fettgehalt der zahlreichen K&auml;sesorten wird in Prozent der Trockenmasse angegeben. Der 
                        absolute Fettgehalt ist geringer, als diese Prozentzahl darstellt &ndash; bei Hartk&auml;se nur etwa zwei Drittel, bei Frisch- und Weichk&auml;se sogar nur rund ein Drittel 
                        des angegebenen Trockenmassewerts. K&auml;se enth&auml;lt viel hochwertiges und gut verdauliches Eiwei&#223;, was ihn besonders bei Vegetariern zu einem beliebten 
                        Proteinlieferanten macht. Der Kohlenhydrat-Anteil im K&auml;se schwankt, je nachdem, ob es sich um Frischk&auml;se oder &auml;lteren K&auml;se handelt. Das enthaltende 
                        Kohlenhydrat ist Laktose, der Milchzucker aus der Milch. Je nach Verarbeitung kann K&auml;se mehr oder weniger Laktose enthalten und auch der Histamin-Gehalt h&auml;ngt 
