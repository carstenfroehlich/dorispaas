                        <h5>Verwendete Probiotika</h5>
                        <hr />
                        <b>Verwendete Pr&auml;parate</b>
                        <br />
                        Ziel dieser Studie war und ist es nicht, bestimmte, ganz spezielle Probiotika zu 
                        bewerten, sondern den Lesern einen Anhaltspunkt zu geben, ob die Einnahme von 
                        Probiotika die Laktose-Toleranzschwelle anheben kann. Somit nenne ich an dieser 
                        Stelle keine Produktnamen, obwohl ich sie in der Studie abgefragt hatte. Die Frage 
                        sollte mir lediglich helfen, eventuell fehlende Angaben erg&auml;nzen zu k&ouml;nnen.
                        <br />
                        <br />
                        <b>Inhaltsstoffe</b>
                        <br />
                        Insgesamt wurden von den Teilnehmern 9 verschiedene Pr&auml;parate verwendet.
                        <br />
                        Zwei der angegebenen Pr&auml;parate enthalten ausschlie&#223;lich einen einzigen 
                        Bakterienstamm (Bacillus coagulans), wobei ich mir nicht sicher bin, ob es sich 
                        hier nicht sogar um ein und dasselbe Pr&auml;parat handeln k&ouml;nnte, denn bei 
                        der betreffenden Antwort wurde nur der Bakterien-Stamm und kein Pr&auml;parate-Name 
                        angegeben.
                        <br />
                        Zwei Pr&auml;parate enthalten neben dem Probiotikum (ebenfalls nur der Stamm Bacillus 
                        coagulans) zus&auml;tzlich 3000 FCC-Einheiten Laktase.
                        <br /> 
                        Die f&uuml;nf anderen enthalten mehrere, z.T. sehr zahlreiche verschiedene Arten 
                        von Mikroorganismen, teils zus&auml;tzlich Vitamine und Mineralstoffbeigaben und 
                        Obstbestandteile, und ein Pr&auml;parat enth&auml;lt noch diverse Kr&auml;uter- 
                        und Gem&uuml;seausz&uuml;ge.
                        <br />
                        <br />
                        <b>Einteilung der getesteten Pr&auml;parate in Gruppen</b>
                        <br />
                        Um sp&auml;ter besser verdeutlichen zu k&ouml;nnen, welche Mittel welche Wirkungen haben, 
                        fasse ich die 18 insgesamt von den Teilnehmern verwendeten Pr&auml;parate nach 
                        den obigen Kriterien in 3 Gruppen zusammen:
                        <br />
                        &#187;nur BC&#171; Pr&auml;parate, die lediglich das Probiotikum Bacillus coagulans enthalten 
                        <br />
                        &#187;BC+ Laktase&#171; Pr&auml;parate, die neben dem Probiotikum Bacillus coagulans auch noch Laktase enthalten  
                        <br />
                        &#187;Multi&#171; Pr&auml;parate, die diverse probiotische St&auml;mme und zus&auml;tzlich Vitamine, Mineralien
                        und Obst- und Gem&uuml;seausz&uuml;ge enthalten
                        <br />
                        <br />
