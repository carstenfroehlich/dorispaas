                        <h5>Zweck der Studie</h5>
                        <hr />
                        Nicht erst seit Kurzem machen sich Hersteller von Nahrungserg&auml;nzungsmitteln 
                        Gedanken, ob und wie neben Laktase-Pr&auml;paraten auch mit einer gesunden 
                        Darmschleimhaut und einer gesunden Darmflora die Laktose-Verwertung optimiert 
                        werden kann. Diese &Uuml;berlegungen haben durchaus ihre Berechtigung &ndash; 
                        hier jedoch unreflektiert die Schlussfolgerung ziehen zu wollen, dass die 
                        Supplementierung mit Probiotika eine Besserung oder gar &#187;Heilung&#171;
                        der Laktose-Intoleranz bedeuten k&ouml;nnte, wollte ich zumindest einmal kritisch 
                        und differenziert hinterfragen. 
                        <br />
                        Vor diesem Hintergrund wurde diese Studie zur Ermittlung der Wirksamkeit von 
                        Probiotika zur Anhebung der Laktose-Toleranzschwelle durchgef&uuml;hrt.
                        <br />
                        Im Folgenden lesen Sie die einzelnen Details der Studie, um sich selbst ein Bild 
                        machen zu k&ouml;nnen. Am Ende der Seite finden Sie zus&auml;tzlich ein von mir 
                        gezogenes Fazit.
                        <br />
                        Beachten Sie bitte, dass alle hier gemachten Prozentzahlen gerundet sind und sich 
                        durch die geringe Teilnehmeranzahl kleinere Rundungsfehler ergeben k&ouml;nnen.
                        <br />
                        <br />
                        
                        <a id="durchfuehrung">&nbsp;</a>
                        <hr />
                        <h5>Durchf&uuml;hrungszeitraum und -art</h5>
                        <hr />
                        Die Studie wurde in der Zeit von Juli bis Dezember 2012 durchgef&uuml;hrt 
                        und anschlie&#223;end ausgewertet. 
                        <br />
                        Die Teilnehmer waren gebeten, &uuml;ber die Website www.dorispaas.de 40 Fragen 
                        durch Anklicken zu beantworten, wobei eine Stimmigkeitspr&uuml;fung diejenigen Fragen 
                        ausblendete, die durch die vorherige Antwort nicht mehr sinnvoll waren. Bei einigen 
                        Fragen wurden Antworten zur Auswahl vorgegeben, bei anderen war die Eingabe von freien 
                        Textantworten m&ouml;glich und erw&uuml;nscht. 
                        <br />
                        <br />
                        
