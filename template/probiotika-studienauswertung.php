                        <br />
                        Auf jeden Fall w&uuml;rde ich bei einem solchen Versuch dazu raten, ein 
                        Pr&auml;parat mit m&ouml;glichst wenig Inhaltsstoffen zu w&auml;hlen. 
                        <br />
                        Da meine Meinung zur Sinnhaftigkeit von Probiotika mit Laktase-Zugabe 
                        hinl&auml;nglich bekannt ist, m&ouml;chte ich hier die Verwendung von 
                        Pr&auml;paraten empfehlen, die lediglich den Bacillus coagulans enthalten.
                        Dieser Stamm ist sehr robust und magensaftresistent, so dass sichergestellt ist, 
                        dass hier wirklich die gesamte eingenommene Menge auch lebend zur verzehrten 
                        Laktose gelangt und diese wirkungsvoll aufspalten kann.  
                        <br />
                        Beginnen Sie auf jeden Fall mit einer sehr geringen Menge und steigern Sie 
                        diese im Laufe einiger Wochen, um Ihre Darmflora behutsam an die neuen 
                        Mitbewohner zu gew&ouml;hnen und somit vermeidbare Nebenwirkungen ausschlie&#223;en 
                        zu k&ouml;nnen.
                        <br />
                        <br />
                        Die Frage, ob durch die Einnahme von Probiotika die Laktose-Toleranzschwelle 
                        angehoben werden kann, weil die in der Darmflora angereicherten n&uuml;tzlichen 
                        Bakterienst&auml;mmen mit ihrem eigenen Stoffwechsel Laktase aufspalten können, 
