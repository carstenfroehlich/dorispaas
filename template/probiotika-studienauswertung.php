                        Aus der Studie ergibt sich folgendes Fazit:
                        <br />
                        <br />
                        <b>Aussagekraft der Studie</b>
                        <br />
                        Leider haben sich an dieser Studie nur sehr wenige Nutzer beteiligt, weshalb die 
                        Ergebnisse in keinster Weise als repr&auml;sentativ angesehen werden k&ouml;nnen.
                        <br />
                        Es ist schwierig zu beurteilen und selbstverst&auml;ndlich nur Spekulation, welches 
                        die Gr&uuml;nde f&uuml;r diese geringe Beteiligung gewesen sein k&ouml;nnten. 
