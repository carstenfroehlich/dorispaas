                        <br />
                        Aus meiner pers&ouml;nlichen Sicht erscheint mir die Verwendung eines Probiotikums allerdings nur
                        bei solchen Menschen Sinn zu machen, die nur an einer (noch) leichten Auspr&auml;gung
                        der Laktose-Intoleranz leiden. Bei diesen Betroffenen k&ouml;nnte dann 
                        tats&auml;chlich die ohnehin nur ben&ouml;tigte, sehr geringe Laktasemenge 
                        g&auml;nzlich &uuml;berfl&uuml;ssig werden.
                        <br />
                        Betroffene mit einer ausgepr&auml;gteren Laktose-Intoleranz m&uuml;ssen f&uuml;r 
                        sich selbst beurteilen, ob sich der Kauf und der Gebrauch eines Probiotikums 
