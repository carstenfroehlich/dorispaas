                        <h5>Teilnehmer </h5>
                        <hr />
                        <span style="font-weight:bold">Anzahl der Teilnehmer </span>
                        <br />
                        Insgesamt haben sich lediglich 33 Personen an der Studie beteiligt, was den Schluss 
                        nahelegt, dass die M&ouml;glichkeit einer Anhebung der Laktose-Toleranzschwelle 
                        durch die Einnahme von Probiotika entweder noch nicht im Bewusstsein der 
                        Verbraucher angekommen ist oder aber, dass die Betroffenen von vorne herein einer 
                        solchen M&ouml;glichkeit kein Vertrauen schenken.
                        <br />
                        F&uuml;r die Auswertung wurden jeweils nur die Antworten der Studienteilnehmer 
                        verwertet, die bei der ersten Frage angaben, dass sie ein Probiotikum benutzen 
                        oder in der Vergangenheit benutzt haben, um Ihre Laktose-Toleranzschwelle zu 
                        verbessern. Da 15 Teilnehmer diese Frage mit &#187;Nein&#171; beantwortet hatten, 
                        blieben lediglich 18 Teilnehmer in der Auswertung. 
                        <br />
