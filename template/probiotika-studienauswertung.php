                        fehlender Bekanntheitsgrad gewesen ist. Meine pers&ouml;nliche Meinung ist, 
                        dass die Verwendung von Probiotika zur Anhebung der Laktose-Toleranzschwelle 
                        noch eine weniger verbreitete und eher unbekannte 
                        M&ouml;glichkeit des Umgangs mit der Laktose-Intoleranz darstellt.
                        <br />
                        <br />
                        <b>Welche Pr&auml;parate-Gruppen gibt es?</b>
                        <br />
                        Es gibt verschiedene Pr&auml;parate, die direkt für diese bestimmte Indikation 
                        (Anhebung der Laktose-Toleranzschwelle)  beworben werden. Andere, die ebenfalls 
                        Probiotika enthalten, sind eigentlich daf&uuml;r vorgesehen, das Immunsystem zu 
                        st&auml;rken und die Darmflora zu pflegen oder zu regenerieren, k&ouml;nnen und 
                        werden aber zu demselben Zweck eingesetzt . Manche Pr&auml;parate enthalten 
                        lediglich einen einzigen 
                        Bakterienstamm, andere beinhalten z.T. viele verschiedene St&auml;mme 
                        von Mikroorganismen. Und weiterhin gibt es Pr&auml;parate, denen neben Probiotika auch 
                        noch verschiedene Vitamine und/oder Mineralstoffe beigegeben wurden oder sogar 
                        Mittel, die dar&uuml;ber hinaus auch Obst-, Gem&uuml;se- und/oder Kr&auml;uterausz&uuml;ge 
                        enthalten.
                        <br />
                        Wie oben angef&uuml;hrt, habe ich die in folgenden Gruppen zusammengefasst:
                        <br />
                        <br />
                        &#187;nur BC&#171; (enthalten ausschlie&#223;lich Bacillus coagulans)
                        <br />
                        &#187;mit Laktase&#171; (enthalten neben Bacillus coagulans auch Laktase)
                        <br />
                        &#187;Multi&#171; (enthalten diverse Probiotik-St&auml;mme und sonstige Zutaten)
                        <br />
                        <br />
                        Mit Hilfe dieser Zusammenfassung m&ouml;chte ich versuchen, die Wirksamkeit und 
                        Empfehlungsw&uuml;rdigkeit der verschiedenen Pr&auml;parate zu bewerten, ohne 
                        Pr&auml;paratenamen preisgeben zu m&uuml;ssen.
                        <br />
                        F&uuml;r welches Pr&auml;parat Sie sich dann letztendlich entscheiden oder ob Sie 
                        &uuml;berhaupt einen Versuch unternehmen wollen, mit Probiotika Ihre 
                        Laktose-Toleranzschwelle anheben zu wollen, m&uuml;ssen Sie selbst beurteilen.
                        <br />
                        <br />
                        <br />
                        <b>Pr&auml;parate-Angebot auf dem Markt</b>
                        <br />
                        Die Idee, dass es m&ouml;glich sein k&ouml;nnte, mit der Einnahme von Probiotika 
                        die Darmflora dahingehend zu beeinflussen, dass eine vermehrte Anzahl von 
                        Milchs&auml;urebakterien die mangelhafte odder gar fehlende Laktase-Produktion 
                        in der Darmschleimhaut &uuml;bernehmen k&ouml;nnen, ist im Vergleich zur 
                        Herstellung von Laktase-Pr&auml;paraten noch relativ neu.
                        <br />
                        Etwa seit 2010 sind einige Pr&auml;parate auf den Markt gekommen, die direkt mit 
                        der Indikation beworben werden, die Laktose-Toleranzschwelle anheben zu k&ouml;nnen.
                        Einige dieser Mittel sind aber bereits wieder aus dem Handel genommen worden &ndash; 
                        auch eines, das in dieser Studie von mehreren Teilnehmern verwendet wurde (aus 
                        der Pr&auml;parategruppe &#187;BC + Laktase&#171;). Was die Gr&uuml;nde 
                        f&uuml;r die Einstellung des Verkaufs sein k&ouml;nnten, bleibt selbstverst&auml;ndlich 
                        Spekulation &ndash; es erscheint jedoch naheliegend, dass es die fehlende 
                        Verbraucher-Akzeptanz und damit der fehlende Profit ist.
                        <br />
                        Eingestellt wurde der Vertrieb von Pr&auml;paraten mit mehreren Inhaltsstoffen &ndash; 
                        die Pr&auml;parate mit nur einem enthaltenen Probiotikum (Bacillus coagulans) scheinen 
                        sich besser am Markt behaupten zu k&ouml;nnen. Ob dies ein Hinweis darauf ist, dass 
                        diese tats&auml;chlich wirksamer sind, beurteilen Sie bitte selbst.
                        <br />
                        <br />
                        <br />
                        <b>Wirksamkeit</b>
                        <br />
                        Mehr als die H&auml;lfte der Befragten (56%) beantwortete die Frage &#187;Konnten Sie die 
                        Menge der Laktase seit dem Gebrauch des Probiotikums reduzieren?&#171; mit 
                        &#187;Nein&#171;, weitere 22% meinten, dass sie seitdem &#187;etwas weniger&#171;
                        Laktase ben&ouml;tigen. Insgesamt ben&ouml;tigen also 78% der Befragten nach wie 
                        vor Laktase zu milchzuckerhaltigen Mahlzeiten. Nur 22% gaben an, &#187;jetzt nur 
                        noch wenig Lakatase zu ben&ouml;tigen&#171;.
                        
                        <br />
                        <br />
                        <br />
                        <b>Nebenwirkungen</b> 
                        <br />
                        Zur Bewertung, welche Pr&auml;parate-Gruppe am empfehlenswertesten ist, ziehe ich 
                        neben der Wirksamkeit auch die beobachteten Nebenwirkungen mit hinzu. 
                        Hier gaben alle Verwender der 
                        &#187;BC + Laktase-Pr&auml;parate&#171; an, keine Nebenwirkungen festzustellen, 
                        bei den &#187;nur BC-Pr&auml;paraten&#171; waren dies 2/3, bei den 
                        &#187;Multi-Pr&auml;paraten&#171; allerdings lediglich 1/3 der Befragten.
                        <br />
                        Somit erscheint es, dass die Pr&auml;parate, die das Probiotikum Bacillus coagulans 
                        plus Laktase enthalten, diejenigen sind, die am wenigsten Nebenwirkungen erzeugen.
                        Ich habe mich bereits <a href="probiotika" target="_blank">an anderer Stelle</a> 
                        &uuml;ber die Sinnhaftigkeit von Laktasezugaben in Probiotika ge&auml;u&#223;ert. 
                        Aus diesem Grund stelle ich die Relevanz dieser Aussage in Frage und schreibe das 
                        Ergebnis der geringen Anzahl von Studienteilnehmern zu. Ich k&ouml;nnte mir vorstellen, 
                        dass sich bei einer gr&ouml;&#223;eren Anzahl von Studienteilnehmern herausstellen 
                        w&uuml;rde, dass die beiden Pr&auml;parate-Gruppen &#187;BC + Laktase-Pr&auml;parate&#171; 
                        und &#187;nur BC-Pr&auml;parate&#171; in Bezug auf die Nebenwirkungen zumindest 
                        ebenb&uuml;rtig w&auml;ren.
                        <br />
                        Auf jeden Fall wurden bei den Pr&auml;paraten mit einer gr&ouml;&#223;eren Reihe von 
                        Inhaltsstoffen die meisten Nebenwirkungen beobachtet, was mich bei der z.T. kaum noch 
                        &uuml;berschaubaren Menge an Zutaten nicht verwundert.
                        <br />
                        <br />
                        <br />
                        <b>Pers&ouml;nliches Fazit </b>
                        <br />
                        Diese Studie wurde von mir sorgf&auml;ltig und vor allem unvoreingenommen ausgewertet.
                        Wie bereits oben erw&auml;hnt, ist es wegen der fehlenden Aussagekraft der Studie 
                        kaum m&ouml;glich, hier ein wirklich aussagekr&auml;ftiges und belastbares  Fazit 
