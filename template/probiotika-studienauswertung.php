                        <hr />
                        <h5>Weitere Nahrungsmittel-Unvertr&auml;glichkeiten oder Erkrankungen</h5>
                        <hr />
                        Um ggf. auszuschlie&#223;en, dass die Wirkung der Probiotika von zus&auml;tzlichen 
                        Nahrungsmittel-Unvertr&auml;glichkeiten und/oder sonstigen Erkrankungen beeintr&auml;chtigt 
                        werden k&ouml;nnte, wurden auch diese M&ouml;glichkeiten abgefragt. 
                        <br />
                        Ein Teilnehmer gab an, zus&auml;tzlich zur Laktose-Intoleranz an einer chronisch 
                        entz&uuml;ndlichen Darmerkrankung zu leiden.
                        <br />
                        Ein Teilnehmer gab an, zus&auml;tzlich zur Laktose-Intoleranz an Z&ouml;liakie zu leiden.
                        <br />
                        Die H&auml;lfte der Teilnehmer gab an, zus&auml;tzlich zur Laktose-Intoleranz an 
                        weiteren Nahrungsmittel-Unvertr&auml;glichkeiten zu leiden.
                        <br />
                        Bei zwei Teilnehmern liegt zus&auml;tzlich zur Laktose-Intoleranz eine 
                        Nahrungsmittel-Allergie vor.
                        <br />
                        Sieben Teilnehmer leiden zus&auml;tzlich zur Laktose-Intoleranz an einem 
                        Reizdarm-Syndrom &ndash; teils &auml;rztlich best&auml;tigt, teils durch eigene 
                        Vermutung gest&uuml;tzt.
                        <br />
                        Bei drei Teilnehmern gab es in der Vergangenheit eine Erkrankung des Darms durch 
                        Parasitenbefall.
                        <br />
                        Insgesamt konnte ich bei der Auswertung keinerlei Hinweise auf eine Ver&auml;nderung 
                        der Wirksamkeit von Probiotika in Bezug auf die Laktose-Toleranzschwelle gegen&uuml;ber
                        den Aussagen der Teilnehmer feststellen, die an keinen weiteren Erkrankungen leiden 
                        (soweit dies bei dieser kleinen Teilnehmeranzahl so bewertet werden kann). 
