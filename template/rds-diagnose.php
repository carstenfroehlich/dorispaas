                        Die Diagnose des Reizdarm-Syndroms (RDS) ist nicht einfach. Es gibt keine Test, 
                        mit denen man einfach und sicher ein RDS diagnostizieren oder ausschlie&#223;en kann. 
                        Somit wird mithilfe der Ausschluss-Diagnose gepr&uuml;ft, ob bestimmte Kankheiten 
                        wie chronisch entz&uuml;ndliche Darmerkrankungen, Nahrungsmittel-Unvertr&auml;glichkeiten, 
                        bakterielle Fehlbesiedelungen oder gar b&ouml;sartige Erkrankungen eben nicht vorliegen.
                        Danach wird einem Fragenkatalog nach den &#187;<b>ROM-Kriterien</b>&#171; (siehe unten) 
                        oder auch der &#187;<b><a href="http://www.dgvs.de/media/Leitlinie_Reizdarm_2011.pdf" target="_blank">S3-Leitlinie 
                        Reizdarmsyndrom</a></b>&#171; &ndash; einer Leitlinie der Deutschen Gesellschaft f&uuml;r 
                        Verdauungs- und Stoffwechselkrankheiten <a href="http://www.dgvs.de" target="_blank">(DGVS)</a>
                        ermittelt, welche Symptome wann und wie oft auftreten. Nach der Auswertung der Antworten 
                        kann dann eine wahrscheinliche Diagnose gestellt werden.
                        <br />
                        <hr>                        
                        <h5>Was sind die ROM-Kriterien?</h5>
                        <hr>
                        Die so genannten Rom-Kriterien, eine Weiterentwicklung der 1988 in der italienischen 
                        Hauptstadt aufgestellten Rom-Kriterien stellen einen Katalog von Fragen dar, 
                        mithilfe derer das ansonsten schwer zu fassende Reizdarm-Syndrom (RDS) diagnostiziert 
                        werden kann. Die Deutsche Gesellschaft f&uuml;r Verdauungs- und Stoffwechselerkrankungen 
                        gibt folgende Symptome als typisch an:
                        <br />
                        &#149; Schmerzen und Kr&auml;mpfe im Unterbauchbereich, die sich nach dem Stuhlgang bessern.
                        <br />
                        &#149; Ver&auml;nderungen der Konsistenz des Stuhlganges (hart oder breiig, 
                        w&auml;ssrig oder wechselnd); Passage m&uuml;hsam mit dem Gef&uuml;hl einer 
                        unvollst&auml;ndigen Entleerung; zus&auml;tzlich Schleimabgang, h&auml;ufige Frequenz.
                        <br />
                        &#149; Bl&auml;hungen und &Uuml;berbl&auml;hungsgef&uuml;hl des Bauches.
                        <br />
                        &#149; Die Symptome treten meist nur tags&uuml;ber auf, Zeiten der Entspannung 
                        und die N&auml;chte werden eher als beschwerdefrei empfunden.
                        <br />
                        <br />
                        Je nach den &uuml;berwiegenden Symptomen k&ouml;nnen die Reizdarm-Patienten in 
                        vier Typen-Gruppen eingeteilt werden:
                        <br />
                        &#149; Diarrhoe-Typ (etwa 31% der RDS-Betroffenen): Durchf&auml;lle (Diarrhoe) sind das vorherrschende Symptom.
                        <br />
                        &#149; Obstipations-Typ (etwa 21%): Verstopfung (Obstipation) ist das Haupt-Symptom dieses Typs.
                        <br />
                        &#149; Schmerz-Typ (ca. 21%): Schmerzen im Unterbauchraum treten besonders h&auml;ufig auf.
                        <br />
                        &#149; Wechsel zwischen Diarrhoe und Obstipation (etwa 27%): St&auml;ndige Wechsel 
                        zwischen Durchf&auml;llen und Verstopfung kennzeichnen diesen Typ.
                        <br />
                        <br />
                        Es gibt weitere Beschwerden, die nicht den Magen-Darm-Trakt betreffen, die jedoch 
                        h&auml;ufig bei Menschen mit Reizdarm-Syndrom auftreten:
                        <br />
                        &#149; Kopfschmerzen und Migr&auml;ne
                        <br />
                        &#149; R&uuml;ckenschmerzen
                        <br />
                        &#149; M&uuml;digkeit, Schlafst&ouml;rungen
                        <br />
                        &#149; Konzentrationsschwierigkeiten
                        <br />
                        &#149; Angst und Depressionen <br />
                        <br />
                        Nat&uuml;rlich treten solche Beschwerden ab und an bei vielen Menschen auf. 
                        Sind sie jedoch &uuml;ber einen l&auml;ngeren Zeitraum &ndash; nach Rom-II-Definition 
                        mindestens 12 Wochen pro Jahr &ndash; und zus&auml;tzlich zu den o.a. Symptomen 
                        vorhanden und kann der Arzt keine anderen Ursachen feststellen, so wird die 
                        Diagnose &#187;Reizdarm-Syndrom&#171; gestellt.
