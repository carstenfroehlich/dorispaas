                        <a id="diagnose"></a>
                        <h5>Abgrenzung als Diagnosehilfe</h5>
                        <hr>
                        Sie haben immer wieder unter Bauchgrummeln, Bauchschmerzen, Blähungen und/oder 
                        Durchfällen und/oder diversen anderen, teils diffusen Beschwerden zu leiden? 
                        Dann steht irgendwann einmal der Verdacht im Raume, dass eventuell Nahrungsmittel 
                        die Verursacher sein könnten, also eine Nahrungsmittel-Unverträglichkeit 
                        oder eine Nahrungsmittel-Allergie vorliegen könnte.
                        <br />
                        <br />
                        Als Hilfestellung für eine Diagnose ist es nun wichtig, Ihre ganz persönlichen 
                        Verursacher herauszufinden. Hierbei ist es nicht nur hilfreich, ein Ernährungstagebuch 
                        zu führen, das die unverträglichen Lebensmittel entlarven kann. Zum 
                        besseren Verständnis sollten Sie sich jedoch zuvor darüber informieren, 
                        wie und warum Beschwerden entstehen &ndash; und dazu müssen die Unterschiede 
                        zwischen einer Nahrungsmittel-Unverträglichkeit und einer 
                        Nahrungsmittel-Allergie klar sein.
                        <br />
                        <br />
                        Streng genommen sind sowohl die im Folgenden als &#187;Nahrungsmittel-Unverträglichkeiten&#171; 
                        aufgeführten Beschwerdeursachen als auch die &#187;Nahrungsmittel-Allergien&#171; 
                        unter dem gro&#223;en Überbegriff &#187;Nahrungsmittel-Unverträglichkeiten&#171; 
                        einzuordnen, da hier Nahrungsmittel nicht verträglich, also unverträglich sind. 
                        <br />
                        <br />
                        Als Unterbegriffe werden in manchen wissenschaftlichen Abhandlungen die &#187;nichtimmunologisch 
                        bedingten Nahrungsmittel-Unverträglichkeiten&#171; und die &#187;immunologisch 
                        bedingten Nahrungsmittel-Unverträglichkeiten&#171; verwendet (siehe weiter unten) 
                        &ndash; da dies jedoch bei Laien nicht unbedingt zur Klärung beiträgt, hat 
                        es sich eingebürgert, den Begriff &#187;Nahrungsmittel-Unverträglichkeiten&#171; 
                        abzugrenzen und nur für ein bestimmtes Wirkprinzip zu verwenden und den Begriff 
                        &#187;Nahrungsmittel-Allergien&#171; für ein anderes Wirkprinzip zu verwenden. 
                        Somit werden hier nun die beiden Begriffe getrennt von einander verwendet.
                        <br />
                        <a id="nmu">&nbsp;</a>
                        <br />
                        <hr>
                        <h5>Nahrungsmittel-Unverträglichkeiten</h5>
                        <hr>
                        Mit der Nahrung nehmen wir verschiedene Nährstoffe auf. Diese sind vorrangig 
                        Flüssigkeit, also Wasser, welches der lebenswichtigste Stoff ist. Ohne Wasser 
                        ist Leben nicht möglich. Weiterhin verzehren wir Eiwei&#223; (Protein) (nicht 
                        zu verwechseln mit dem Eiklar aus dem Hühnerei), das wir zum Aufbau unserer 
                        sich ständig regenerierenden Körperzellen benötigen. Darüber 
                        hinaus enthält die Nahrung Kohlenhydrate, die uns Energie liefern und das Fett, 
                        das ebenfalls zum Energiegewinn, aber auch zum Schutz für unsere Organe 
                        benötigt wird. Und natürlich benötigen wir die Mikronährstoffe, 
                        also Vitamine und Mineralstoffe, die für die verschiedensten physiologischen 
                        Vorgänge unerlässlich sind. Jeder wei&#223;, dass ein Mangel an Vitaminen 
                        und Mineralstoffen zu diversen, teils gravierenden Beschwerden führen kann.
                        <br />
                        <br />
                        Für jeden Nährstoff, den wir zu uns nehmen, gibt es in unserem Verdauungssystem 
                        ganz bestimmte Substanzen, die diese Nährstoffe so verarbeiten und zu den Zellen 
                        transportieren, dass unser Körper sie nutzen kann. Insbesondere sind hier die 
                        Enzyme (veraltete Bezeichnung: Fermente) zu nennen. Enzyme sind Proteine, die u.a. 
                        bei der Verdauung bestimmte Verarbeitungsprozesse in Gang setzen. Hierbei wirken 
                        sie wie ein Katalysator, d.h. sie verbrauchen sich nicht, sondern geben nur den 
                        &#187;Startschuss&#171; zu den Verarbeitungsprozessen. Fehlen bestimme, für 
                        jeden Verarbeitungsprozess spezifische Enzyme, so unterbleiben diese Verarbeitungsschritte, 
                        und die Verdauung kann nicht reibungslos funktionieren.
                        <br />
                        <br />
                        Die bekanntesten Nahrungsmittel-Unverträglichkeiten sind Kohlenhydrat-Unverträglichkeiten 
                        wie die Laktose-Intoleranz (Milchzucker-Unverträglichkeit) und die Fruktose-Intoleranz 
                        (Fruchtzucker-Unverträglichkeit). 
                        <br />
                        <br />
                        Bei der Laktose-Intoleranz fehlt das Enzym Laktase, das die beiden verbundenen 
                        Bausteine des Milchzuckers &ndash; den Traubenzucker und den Schleimzucker &ndash; 
                        trennt. Nur wenn die Bausteine im Dünndarm getrennt werden, passen sie durch 
                        die Zwischenräume zwischen den Darmschleimhautzellen hindurch und können 
                        ins Blut gelangen, wo der Traubenzucker als Energielieferant direkt zu den Körperzellen 
                        transportiert wird und der Schleimzucker zur weiteren Verarbeitung die Leber erreicht. 
                        Unterbleibt die Trennung, weil es an Laktase-Enzym mangelt oder es so gut wie ganz fehlt, 
                        verbleibt der Milchzucker im Stuhl und wird weiter in den Dickdarm transportiert, 
                        wo er von Darmbakterien verstoffwechselt (gefressen) wird. Dabei entstehen Säuren 
                        und Gase, die Durchfälle und Blähungen verursachen.
                        <br />
                        <br />
                        Auch bei der Fruktose-Intoleranz fehlt der spezifische Stoff, der den Fruchtzucker 
                        verarbeitet &ndash; in diesem Falle kein Enzym, sondern das Transportprotein namens GLUT5, 
                        das erforderlich ist, um den Fruchtzucker durch die Dünndarmwand ins Blut zu 
                        schleusen. Fehlt es oder mangelt es an GLUT5, so passiert dasselbe wie bei der 
                        Laktose-Intoleranz: Der Fruchtzucker gelangt in den Dickdarm und wird dort von 
                        den Darmbakterien gefressen, wobei die beschriebenen Beschwerden entstehen.
                        <br />
                        <br />
                        Somit werden durch den Mangel an Enzym bzw. Transportprotein Stoffe, die eigentlich 
                        gut verträglich sein sollten, für die Betroffenen unverträglich &ndash; 
                        es entstehen durch den Verzehr dieser Kohlenhydrate Beschwerden. Neben der Laktose- 
                        und der Fruktose-Intoleranz gibt es weitere Nahrungsmittel-Unverträglichkeiten, 
                        die jedoch alle nach dem gleichen Prinzip Beschwerden verursachen.
                        <br />
                        <br />
                        Es ist klar, dass diese Beschwerden <b>mengenabhängig</b> sind: Je mehr von 
                        dem unverträglichen Stoff verzehrt wird, desto grö&#223;er werden die 
                        Beschwerden. Dies ist ein ganz entscheidendes Merkmal von Nahrungsmittel-Unverträglichkeiten.
                        <br />
                        <br />
                        Weiterhin treten die Beschwerden immer zeitversetzt auf: Nicht sofort bei der Mahlzeit 
                        bekommt man Bauchschmerzen oder Durchfall, sondern erst, wenn der unverträgliche 
                        Stoff im Darm angekommen ist und die Gärprozesse begonnen haben. Der Zeitversatz 
                        kann sich &ndash; je nach Art der Nahrung und je nachdem, ob der Verzehr auf nüchternen 
                        Magen oder aber später am Tag oder das unverträgliche Lebensmittel allein 
                        oder aber zusammen mit anderen, schwerer verdaulichen gegessen wird &ndash; zwischen 
                        einer halben oder auch mehreren Stunden bewegen. Ein solcher <b>Zeitversatz</b> 
                        charakterisiert ebenfalls eine Nahrungsmittel-Unverträglichkeit. 
                        <br />
                        <a id="allergien">&nbsp;</a>
                        <br />
                        <hr>
                        <h5>Nahrungsmittel-Allergien</h5>
                        <hr>
                        Unser Organismus ist nahezu perfekt ausgerüstet, um sich gegen schädliche 
                        Stoffe zu wehren. Dies können Stoffe sein, die von au&#223;en auf den Körper 
                        einwirken oder die wir einatmen, Krankheitserreger, die eindringen, oder aber auch 
                        Nahrungsmittel, die wir aufnehmen. Manche Stoffe wirken unmittelbar giftig, manche 
                        aber müssen erst &#187;kennengelernt&#171; werden. Nach dieser Kennenlernphase 
                        (Sensibilisierungsphase) jedoch 
                        erinnert sich der Körper und kann beim nächsten Kontakt schneller mit 
                        Abwehrmechanismen reagieren.
                        <br />
                        <br />
                        Dies ist wichtig beispielsweise bei Krankheiten, die durch Viren oder Bakterien 
                        verursacht werden: Wir wissen alle, dass wir z.B. nur einmal an Kinderkrankheiten 
                        erkranken, danach sind wir immun dagegen. Der Körper hat sich in der 
                        Sensibilisierungsphase das Bild der Erreger gemerkt und kann 
                        bei einem erneuten Kontakt unverzüglich Antikörper bilden und die Erreger 
                        sofort vernichten &ndash; die Krankheit bricht nicht noch einmal aus. Auch beim 
                        Impfen wird dieses immunologische Gedächtnis genutzt: Man bringt kleinste 
                        Mengen des (abgeschwächten) Erregers in den Körper, der sensibilisiert 
                        wird, also den Erreger kennenlernt und bei einem wirklichen Kontakt dann sofort 
                        vernichten kann.
                        <br />
                        <br />
                        Mit solchen immunologischen Vorgängen reagiert der Körper auf Eiwei&#223;bausteine 
                        (Proteine) und schützt sich so vor schädigenden Einflüssen und Krankheiten.
                        <br />
                        <br />
                        Es gibt jedoch auch Proteine, die eigentlich nicht schädlich wirken, gegen 
                        die manche Menschen aber mit unangepassten immunologischen Abwehrmechanismen reagieren. 
                        Hierbei interpretiert ein Körper die Wirkung eines Stoffes falsch und glaubt, 
                        dass dieser schädlich sei &ndash; er hat etwas Falsches gelernt und in den 
                        Immunglobulinen gespeichert und wird nun jedes Mal, wenn der Stoff aufgenommen wird, 
                        mit einer Abwehr reagieren. Solche Reaktionen werden Allergien genannt: Der Körper 
                        reagiert unangepasst abwehrend auf Stoffe, die normalerweise völlig ungefährlich 
                        sind. Dies können Stoffe (Allergene) sein, mit denen man in Berührung kommt 
                        (Kontakt-Allergene), die man einatmet (respiratorische Allergene) oder aber auch Stoffe, 
                        die man verzehrt (nutritive oder Nahrungsmittel-Allergene).
                        <br />
                        <br />
                        Da jeder Körper ganz individuell Nahrungsmittel-Bestandteile als allergen 
                        einstufen kann, sind die Nahrungsmittel-Allergien sehr viel vielfältiger als 
                        die Nahrungsmittel-Unverträglichkeiten &ndash; und deshalb sehr viel schwerer 
                        fassbar.
                        <br />
                        <br />
                        Durch die immunologische Reaktion (das gebildete Gedächtnis) kann der Körper 
                        nach der Sensibilisierungsphase schon bei Aufnahme kleinster Mengen vollkommen 
                        unangemessen und überzogen reagieren &ndash; die Heftigkeit der Reaktion ist 
                        also <b>unabhängig von der verzehrten Menge</b> des allergenen Stoffes &ndash; dies 
                        unterscheidet eine Allergie von einer Unverträglichkeit.
                        <br />
                        <br />
                        Weiterhin können die allergischen Reaktionen teilweise <b>sofort nach dem Verzehr</b> 
                        auftreten (Sofortreaktionen) &ndash; auch dies ein sicheres Unterscheidungsmerkmal. 
                        Es gibt zwar auch allergische Spätreaktionen, aber auch hier gibt es trotz des 
                        zeitlichen Versatzes noch das Mengenindiz zur Abgrenzung.
                        <br />
                        <br />
                        Auch <b>Ort</b> und <b>Heftigkeit</b> von Beschwerden können ein Unterscheidungsmerkmal 
                        darstellen: Beschwerden bei Unverträglichkeiten können zwar auch recht 
                        unangenehm sein, sind aber zuerst einmal immer auf den Kontaktort, also auf das 
                        Verdauungssystem konzentriert und vor allem nie lebensbedrohend. Da bei allergischen 
                        Reaktionen Prozesse stattfinden, die das gesamte Abwehrsystem des Körpers 
                        mobilisieren, können die Reaktionen zum einem an allen möglichen und 
                        unerwarteten Körperstellen (Verdauungssystem, Haut, Atmungsorgane, Augen, 
                        Nase etc.) auftreten. Es kann also durchaus ein Atemproblem auftreten, wenn man 
                        ein Allergen verzehrt. Und &ndash; vor allem &ndash; können allergische Reaktionen 
                        so heftig sein, dass sie lebensbedrohlich sind. Der so genannte &#187;anaphylaktische 
                        Schock&#171; wird u.a. durch den Nervenbotenstoff Histamin ausgelöst, der bewirkt, 
                        dass die Blutgefä&#223;e weitgestellt werden und somit der Blutdruck abfällt. 
                        Weiterhin tritt Flüssigkeit aus den Blutgefä&#223;en aus und gelangt in 
                        das umliegende Gewebe. Dies alles bewirkt, dass wichtige Organe und vor allem das 
                        Gehirn nicht mehr durchblutet und mit Sauerstoff versorgt werden &ndash; ein 
                        <b>lebensbedrohlicher Zustand</b>, der umgehend notärztlich versorgt werden muss. 
                        Solche heftigen Reaktionen sind bei Nahrungsmittel-Unverträglichkeiten 
                        ausgeschlossen. 
                        <br />
                        <br />
                        Glücklicherweise sind allergische Reaktionen nicht immer so heftig und bewirken 
                        einen anaphylaktischen Schock, jedoch ist immer grö&#223;te Vorsicht und der 
                        absolute Verzicht des Allergens angeraten. Verzehrt man &#187;nur&#171; unverträgliche 
                        Stoffe, so hat man zwar danach Beschwerden, diese verschwinden jedoch nach kurzer Zeit, 
                        und es geht einem wieder gut, sofern man das Nahrungsmittel weitestgehend meidet.
                        <br />
                        <br />
                        Allergene dürfen &ndash; auch nicht in Spuren &ndash; verzehrt werden, 
                        unverträgliche Nahrungsmittel sollten weitestgehend gemieden werden, kleinere 
                        Mengen werden jedoch in den allermeisten Fällen toleriert.
                        <br />
                        <br />
                        Die allermeisten Allergien können mithilfe eines Bluttests, bei dem bestimmte Immunstoffe 
                        (<b>Immunglobulin des Typs E (IGE)</b>) getestet werden, diagnostiziert werden. Bei 
                        Nahrungsmittel-Unverträglichkeiten kann keine Erhöhung der IGEs festgestellt 
                        werden, da Nahrungsmittel-Unverträglichkeiten grundsätzlich nicht immunologisch 
                        bedingt sind. 
                        <br />
