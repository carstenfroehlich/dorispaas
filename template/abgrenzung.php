                        <br />
                        <hr>
                        <h5>Allergie oder Unverträglichkeit? </h5>
                        <hr>
                        Es gibt durchaus Nahrungsmittel, die sowohl für eine Unverträglichkeitsreaktion 
                        als auch für eine allergische Reaktion verantwortlich sein können &ndash; nur 
                        werden hier Reaktionen durch unterschiedliche Bestandteile ausgelöst. Als Beispiel 
                        wäre hier die Milch zu nennen: Es ist möglich, dass Bestandteile der Milch 
                        eine Unverträglichkeitsreaktion auslösen &ndash; in diesem Falle der Milchzucker. 
                        Es sind aber auch allergische Reaktionen möglich &ndash; hier ist der Verursacher 
                        einer der in der Milch enthaltenen Eiwei&#223;stoffe. 
                        <br />
                        <br />
                        Die Probleme durch die nichtimmunologische Milchzucker-Unverträglichkeit treten 
                        zeitversetzt und mengenabhängig auf und bewirken keine Erhöhung der IGEs. 
                        Die Probleme durch die immunologisch bedingte Allergie treten unmittelbar und 
                        mengenunabhängig auf und sind durch eine Erhöhung der IGE-Werte feststellbar. 
                        <br />
                        <a id="pseudoallergien">&nbsp;</a>
                        <br />
                        <hr>
                        <h5>Pseudo-Allergien</h5>
                        <hr>
                        Leider gibt es &ndash; um doch ein wenig Verwirrung zu stiften &ndash; auch 
                        Unverträglichkeiten auf bestimmte Nahrungsmittel, die in den verursachten Beschwerden 
                        denen der Allergien gleichen. Hier sind vor allem das Histamin und das 
                        Glutamat zu nennen. 
                        <br />
                        <br />
                        Histamin ist ein Stoff, der in den Körperzellen vorkommt (biogenes Amin), 
                        aber auch durch Nahrung aufgenommen wird. Zum Abbau dieses Stoffes ist ein Enzym 
                        erforderlich, das den Histaminspiegel im Blut auf einem gleichmä&#223;ig 
                        niedrigen Niveau hält. Mangelt es an dem Enzym (Diaminoxidase), reichert sich 
                        das Histamin im Körper an. Da Histamin aber für allergische Reaktionen 
                        (mit-)verantwortlich ist und über das Blut an alle Körperstellen gelangt, 
                        sind die Reaktionen denen der Allergie ähnlich und können an jeder 
                        Körperstelle auftreten.
                        <br />
                        <br />
                        Lediglich durch einen nicht erhöhten Wert der Immunglobuline ist feststellbar, 
                        dass hier keine wirkliche allergische Reaktion vorliegt. 
                        <br />
                        <br />
                        Auch ist die Intensität der Beschwerden mengenabhängig, d.h. je mehr 
                        histiaminhaltige Nahrungsmittel verzehrt werden, desto heftiger sind die Beschwerden. 
                        <br />
                        <br />
                        Diese Merkmale kennzeichnen die Histamin-Intoleranz als eine Nahrungsmittel-Unverträglichkeit 
                        und nicht als Allergie. Da jedoch die Beschwerden denen einer Allergie ähneln, 
                        wird die Histamin-Intoleranz auch als &#187;Pseudo-Allergie&#171; bezeichnet 
                        (pseudo = falsch, künstlich (lat.).
                        <br />
                        <br />
                        Ebenfalls zu den Pseudo-Allergien zählt die Glutamat-Unverträglichkeit, 
                        wobei die Grenzen hier flie&#223;end sind, weil eine ähnliche Ursache vorliegt. 
                        Der Geschmacksverstärker Glutamat blockiert die Diaminoxidase und hemmt deshalb 
                        den Abbau von Histamin. Somit kann sich Histamin im Körper anreichern und 
                        besonders bei Menschen, deren Histaminregulierung ohnehin schon gestört ist, 
                        zu den gleichen Problemen führen, die auch bei der Histanim-Intoleranz auftreten. 
                        Da Glutamat häufig in der chinesischen Küche verwendet wird und die Beschwerden 
                        oftmals nach dem Besuch eines Chinarestaurants auftreten, wird die Glutamat-Unverträglichkeit 
                        auch als so genanntes &#187;Chinarestaurant-Syndrom&#171; bezeichnet.
