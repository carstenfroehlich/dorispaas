                        Wenn Sie den Verdacht haben, an einer Nahrungsmittel-Unverträglichkeit, einer 
                        Pseudo-Allergie oder einer Nahrungsmittel-Allergie zu leiden, führen Sie 
                        für einige Zeit (mindestens 2 Wochen, besser länger) ein Ernährungstagebuch, 
                        in dem Sie jedes Nahrungsmittel, alle Getränke und ggf. auch die Medikamente, 
                        die Sie einnehmen, aber auch alle Zwischenmahlzeiten und Snacks protokollieren. 
