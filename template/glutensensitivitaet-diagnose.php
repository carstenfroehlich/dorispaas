                        <a href="gluten" target="_blank">Zöliakie und Gluten-Sensitivität</a>
                        <br />
                        <a href="gluten-sensitivitaet" target="_blank">Gluten-Sensitivität &ndash; was ist das?</a>
                        <hr>
                        <br />
                        Die Diagnose einer Gluten-Senstitivität kann erst nach einer Zöliakie-Diagnostik 
                        durchgeführt werden (bitte lesen Sie hierzu den Beitrag <a href="zoeliakie-diagnose" target="_blank">Diagnose der Zöliakie</a>).
                        Dies bedeutet, dass Sie unter einem normalen, mindestens 6-wöchigen Glutenverzehr
                        Ihre Antikörperwerte im Blut bestimmen lassen müssen. Weiterhin muss eine Spiegelung 
                        des Magens und im gleichen Zuge eine Spiegelung des Zwölffingerdarms mit mehreren 
                        Biopsien (Probeentnahmen) der dortigen Schleimhaut vorgenommen werden.
                        <br />
                        <br />
                        <img src="<?php echo IMG_PATH; ?>glutensensitivitaet-darmschleimhaut.png" alt="" class="left" /></a>
                        <br />
                        <br />
                        Erst, wenn ermittelt wurde, dass keine der Zöliakie-typischen Antikörper im Blut 
                        vorhanden sind und Ihre Darmschleimhaut &ndash; so wie auf der Abbildung dargestellt &ndash; gesund ist, die 
                        Beschwerden aber eindeutig mit dem Glutenverzehr in Verbindung gebracht werden, 
                        kann mithilfe einer weitestgehend glutenfreien Kost (Karenz) 
                        ausgetestet werden, ob eine Gluten-Unverträglichkeit ohne Zöliakie vorliegt. 
                        <br />
                        <br />
                        Zuvor sollte jedoch auch unbedingt mit geeigneten Tests (Wasserstoff-Atemtest) 
                        ermittelt werden, ob andere Unverträglichkeiten 
                        wie eine Laktose- und/oder Fruktose-Unverträglichkeit vorliegen, um diese 
                        Verursacher von Beschwerden auszuschließen oder zu diagnostizieren.
                        Lesen Sie hierzu die Beiträge <a href="diagnose" target="_blank">Diagnose-Methoden zur Ermittlung einer Laktose-Intoleranz</a> 
                        und <a href="fmadiagnose" target="_blank">Diagnose-Methoden zur Ermittlung einer Fruktose-Intoleranz</a>
                        <br />
                        <br />
                        Zur Diagnose der Gluten-Sensitivität ist das Führen eines Verzehr- und Symptomtagebuchs 
                        (Ernährungstagebuch) über mehrere Wochen erforderlich. Sie müssen dabei sämtliche 
                        verzehrten Nahrungsmittel, Getränke und Medikamente 
                        und die eventuell auftretenden Beschwerden protokollieren. Dabei müssen Sie natürlich 
                        weiterhin Gluten verzehren, um den Zusammenhang zwischen den Beschwerden und dem 
                        Glutenverzehr herstellen zu können. 
                        <br />
                        <br />
                        Erst wenn nach einem 
                        negeativen Zöliakiebefund aus dem Ernährungstagebuch ein zeitlicher Zusammenhang 
                        zwischen Glutenverzehr und Beschwerden erkennbar ist, ist die Diagnose &#187;Gluten-Sensitivität&#171;
                        wahrscheinlich und ein Minimieren des Glutenverzehrs sinnvoll.
