                        Diese Krise fordert eklatante &Auml;nderungen der bisherigen Lebensgewohnheiten. Dabei ist es unerheblich, ob diese &Auml;nderungen aufgrund 
                        tats&auml;chlicher, einsehbarer Erfordernisse oder aber aufgrund von fiktiven (f&uuml;r diese Menschen aber durchaus realen) Gegebenheiten notwendig 
                        geworden sind. Diese &Auml;nderungen und Einschr&auml;nkungen bedeuten aber nicht &#187;nur&#171; Stress, sondern bringen h&auml;ufig auch eine Verschlechterung 
                        des Allgemeinzustands mit sich. Vor allem f&uuml;r all diejenigen, die ohnehin schon Probleme mit Nahrungsmittel-Unvertr&auml;glichkeiten oder Reizdarm-Beschwerden 
                        haben, ist es jetzt ganz wichtig, die Zusammenh&auml;nge zu verstehen und dem negativen Stress entgegenzuwirken, um die Verdauung im Griff zu behalten.
