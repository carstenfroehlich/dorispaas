                                    <br />
                                    Dumm wie Brot</b>
                                    <br />
                                    Wie Weizen schleichend Ihr Gehirn zerstört
                                    <br />
                                    <br />
                                    Meine persönliche Bewertung: 
                                    <br />
                                    <img src="<?php echo IMG_PATH; ?>bewertungssternchen-3.png" alt="" class="left" />
                                    <br />
