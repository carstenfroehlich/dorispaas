                        <img src="http://www.dorispaas.de/assets/images/nl-2019-03-europa.png" alt="Europa" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" />
                        Liebe Leserinnen und Leser, 
                        ganz so klein, wie Sie vielleicht meinen, ist Ihr Einfluss auf Umwelt und Artensterben keineswegs. Gerade in den n&auml;chsten Tagen haben wir alle eine 
                        gro&#223;e M&ouml;glichkeit, unser Gewicht in die Waagschale zu werfen, indem wir an der Europawahl teilnehmen.
                        Ich bitte Sie herzlich, w&auml;hlen zu gehen und Ihre Stimme einer der Parteien zu geben, die sich nicht nur mit ganzem Herzen zu Europa bekennen, sondern die sich dar&uuml;ber 
                        hinaus mit einem ernstzunehmenden Wahlprogramm (und auch mit entsprechenden Aktionen in der Vergangenheit) f&uuml;r die Umwelt und gegen das 
                        Artensterben engagieren. Nur, wenn langfristig alle L&auml;nder zusammen an einem Strang ziehen und das gro&#223;e Ganze sehen,  
                        ohne selbsts&uuml;chtig nur an den eigenen Vorteil zu denken, kann das gemeinsame Ziel erreicht werden: ein Europa und eine Welt,
                        in der es sich f&uuml;r Menschen, Tiere und Pflanzen zu leben lohnt, in der wir uns auch in Zukunft wohlf&uuml;hlen, in der wir gesund bleiben und in der 
                        wir uns mit Freude bewegen k&ouml;nnen.
