                        <h5>Ausgabe 46 (Mai 2019)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-03-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 5px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        Heute m&ouml;chte ich Ihnen Lust auf Natur machen. In dieser Jahreszeit gibt es drau&#223;en nicht nur an 
                        jeder Ecke etwas Neues, Spannendes zu entdecken, man kann auch beobachten, wie sich die Pflanzen und Tiere entwickeln.
                        Die ausges&auml;ten Sommerblumen strecken frisches Gr&uuml;n aus der Erde und der Farm entrollt seine Bl&auml;tter in einem 
                        geheimnisvollen Schauspiel. Auch die ersten V&ouml;gel sind geschl&uuml;pft und betteln lautstark bei Ihren Eltern um Futter.
                        Bienen und Hummeln best&auml;uben fleißig die Obstbl&uuml;ten und wecken die Vorfreude auf leckeres Obst. Aber leider m&uuml;ssen  
                        wir zur Kenntnis nehmen, dass es Vergleich zu fr&uuml;her deutlich weniger Insekten gibt. Der R&uuml;ckgang der Artenvielfalt 
                        ist nicht nur bei den Insekten dramatisch, aber hier besonders deutlich &ndash; sicherlich nicht zuletzt dem massiven Einsatz von 
                        <a href="http://www.dorispaas.de/index.php?page=glyphosat" target="_blank">Pestiziden</a> zu &#187;verdanken&#171;! Ich bitte Sie 
                        herzlich, sich &uuml;ber diese Problematik zu informieren. Und machen Sie &uuml;berall dort, wo Sie eine M&ouml;glichkeit 
                        f&uuml;r sich sehen, Ihren Einfluss geltend &ndash; und sei er vermeintlich auch noch so klein! Reden Sie mit Ihren Freunden und 
                        Verwandten &uuml;ber das Artensterben und pflanzen Sie im Garten, auf dem Balkon oder am Stra&#223;enrand insektenfreundliche Blumen.
                        Jede Bl&uuml;te bietet den Insekten willkommenes Futter &ndash; und dar&uuml;ber hinaus k&ouml;nnen wir uns alle daran freuen. 
                        
                        <br />
                        <br />
                        <hr />
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=bewegung" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-03-bewegung.png" alt="Bild Bewegung" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=bewegung" target="_blank">Schwerpunktthema: &#187;Bewegung und Sport&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Ganzheitliche Gesundheit/Allgemein/Bewegung und Sport)</i>
                        <br />
                        Die Natur und das Wetter laden uns nun auch zu mehr Bewegung ein. Passend dazu habe ich dieses Thema 
                        als Schwerpunkt f&uuml;r diesen Newsletter gew&auml;hlt. Mit eine der wichtigsten S&auml;ulen unserer Gesundheit ist n&auml;mlich 
                        eine ausreichende Bewegung. Allgemein ist bekannt, dass Menschen, die sich wenig bewegen und viel Zeit auf ihrer Couch 
                        verbringen &ndash; die &#187;Couch-Potatoes&#171; &ndash; nicht nur zu &Uuml;bergewicht neigen, sondern auch einen insgesamt schlechteren Gesundheitszustand 
                        aufweisen als aktivere Zeitgenossen. Wie aber muss ein gesundes Bewegungsverhalten aussehen, um den K&ouml;rper optimal zu st&auml;rken und die Gesundheit zu 
                        unterst&uuml;tzen? Ich benutze hier ganz bewusst das Wort <b>Bewegung</b> und nicht Sport, denn t&auml;gliche, kleinere Bewegungssequenzen 
                        k&ouml;nnen nicht nur in der Summe ebenso viel bedeuten wie ein oder zwei Stunden Sport in der Woche. Diese kontinuierlichen Bewegungen 
                        haben insbesondere f&uuml;r unseren Darm sogar einen sehr viel deutlicheren Effekt.         
                        <br />
                        <br />
                        <hr />
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=lebensmittel-datenbank-info" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2019-03-datenbank.png" alt="Bild Lebensmittel-Datenbank" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 10px;" /></a>
                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=lebensmittel-datenbank-info" target="_blank">Dorispaas.de &ndash; Lebensmittel-Datenbank</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Dorispaas.de &ndash; Lebensmittel-Datenbank/Info)</i>
                        <br />
                        Jetzt ist auch die Zeit, in der auf den Wochen- oder im Superm&auml;rkten wieder verlockend viele frische Obst- und Gem&uuml;sesorten angeboten werden.
                        Wenn man eine oder sogar mehrere Nahrungsmittel-Unvertr&auml;glichkeiten hat, kann es bei aller Begeisterung f&uuml;r die vielen leckeren Lebensmittel 
                        leicht passieren, dass man den &Uuml;berblick verliert, was man &#187;ungestraft&#171; essen darf und seinem Verdauungssystem vielleicht zu viel zumutet.
                        Je gr&ouml;&#223;er die Auswahl, desto wichtiger ist es, sich genau zu informieren, welche Lebensmittel bei der individuellen Kombination von Intoleranzen 
                        und/oder bei einer FODMAP-Di&auml;t bek&ouml;mmlich sind. Die &#187;<a href="http://www.dorispaas.de/index.php?page=lebensmittel-datenbank-info" target="_blank">DorisPaas.de 
                        &#150; Lebensmittel-Datenbank</a>&#171; bietet die M&ouml;glichkeit, 
                        die <b>mehr als 1300 Lebensmittel</b> nach den pers&ouml;nlichen Erfordernissen zu filtern, zu kategorisieren und zu sortieren. Auf einen Blick ist ersichtlich, 
                        welche Lebensmittel f&uuml;r Sie geeignet und bek&ouml;mmlich sind. Informieren Sie sich doch einmal unverbindlich, welche Vorteile Sie mit diesem 
                        Werkzeug haben: ich kann Ihnen versprechen, dass es auch f&uuml;r Sie eine gro&#223;e Palette 
                        an bek&ouml;mmlichen Nahrungsmitteln gibt.
