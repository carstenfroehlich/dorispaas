                        <p>
                        Wenn Sie an Verdauungsstörungen wie Bauchschmerzen, Durchfällen, Blähungen 
                        oder auch Krämpfen usw. leiden, können Nahrungsmittel die Ursache sein. 
                        Hierbei kann es sich um eine Nahrungsmittelallergie oder auch um eine 
                        Nahrungsmittelunverträglichkeit handeln.
                        </p>
                        <p>
                        Das in Zusammenarbeit mit dem Allgemeinmediziner und Ernährungsberater (DGE) 
                        Dr. med. Erich Krämer entstandene 
                        Buch &#187;Nahrungsmittelallergien und -unverträglichkeiten&#171; zeigt 
                        zuerst die generelle Abgrenzung zwischen Allergien und Unverträglichkeiten auf 
                        und erklärt die Ursachen. Es hilft, sich ein Bild von der eigenen Erkrankung 
                        zu machen, zwischen einer Nahrungsmittelallergie und einer Unverträglichkeit 
                        zu unterscheiden und bietet Ihnen Hilfestellungen, um den Verursachern Ihrer 
                        unangenehmen Verdauungsstörungen oder anderen, mit Nahrungsmitteln in 
                        Verbindung stehenden Beschwerden auf die Spur zu kommen.
                        </p>
                        <p>
                        In weiteren Kapiteln erfahren Sie, welche Diagnosemethoden Ihnen und Ihrem Arzt 
                        im Falle einer Nahrungsmittelallergie zu Verfügung stehen und welche Vor- 
                        und Nachteile die verschiedenen Tests haben. Sie lernen, wie Sie Allergieauslöser 
                        erkennen und meiden können und welche Ernährung für Sie günstig ist.
                        </p>
                        <p>
                        Sie erfahren, welche Formen der Intoleranzen es gibt: Milchzuckerunverträglichkeit (Laktoseintoleranz), 
                        Fruchtzuckerunverträglichkeit (Fruktoseintoleranz), Sorbitintoleranz, 
                        Haushaltszuckerunverträglichkeit (Saccharoseintoleranz), 
                        Histaminintoleranz oder andere sogenannte Pseudoallergien. Sie werden sehen, welche 
                        Diagnosemethoden jeweils geeignet sind, um &#187;Ihre&#171; Beschwerdeverursacher 
                        zu ermitteln, und Sie lernen in mehreren Schritten, welche Nahrungsmittel Sie verzehren 
                        dürfen, um beschwerdefrei zu werden. 
                        </p>
                        <p>
                        Zu jeder Intoleranz finden Sie umfangreiche Listen mit Nahrungsmitteln und Nahrungsmittelgruppen,
                        die Sie verzehren dürfen; Nahrungsmittel, bei denen eine erhöhte Vorsicht empfohlen wird; 
                        oder auch Nahrungsmittel, die Sie meiden sollten, um nicht wieder Beschwerden zu bekommen. 
                        </p>
