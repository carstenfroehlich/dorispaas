                    <h5>Buchbeschreibung</h5>
                    <hr />
                    Rumoren im Bauch, Blähungen, Krämpfe oder Durchfälle nach dem Genuss 
                    von Milch und Milchprodukten oder Fertiggerichten &ndash; eine Milchzucker-Unverträglichkeit 
                    kann viele quälende Symptome hervorrufen. 
                    <br />
                    Um diese Beschwerden loszuwerden, sollten Sie sich uber die Auslöser und 
                    Zusammenhänge und vor allem uber die Behandlungsmöglichkeiten informieren. 
                    Aber auch, wenn nicht Sie selbst betroffen sind, sondern ein Familienmitglied, Freund 
                    oder Arbeitskollege, ist es hilfreich, wenn Sie uber die Milchzucker-Unverträglichkeit 
                    Bescheid wissen.
                    <br />
                    <br />
                    Das Paas'sche Heftchen &#187;Kurz und klar: Milchzucker-Unverträglichkeit&#171; erklärt in kurzer 
                    und klarer Form alles Wichtige rund um dieses Thema. Es erläutert daruber 
                    hinaus Ursachen und Hintergrunde von Beschwerden. Das Heftchen hilft, Probleme 
                    zu erkennen und zu verstehen und zeigt erste Schritte in die richtige Richtung: 
                    eine gesunde Lebensweise ohne Beschwerden, um sich wohl zu fuhlen und bis 
                    ins hohe Alter gesund zu bleiben.
                    <br />
                    Das Heftchen stellt wesentlich mehr Informationen zur Verfugung als eine 
                    Info-Broschure und versteht sich somit als Vereinigung von Informations-Broschure 
                    und Sachbuch. Es erhebt bewusst keinen Anspruch auf Ausfuhrlichkeit, sondern 
                    verschafft Ihnen in kurzer, aber korrekter Form einen ersten &Uuml;berblick uber das Thema. 
                    Trotz des geringen Umfangs bleibt es jedoch nicht oberflächlich, sondern ist sorgfältig 
                    recherchiert: In rund einer Stunde wissen Sie alles Wesentliche zum Thema &#187;Milchzucker-Unverträglichkeit&#171;.
