                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=atemtest-duenndarmfehlbesiedelung" target="_blank">Wasserstoff-Atemtest zur Diagnose einer D&uuml;nndarmfehlbesiedelung</a></b>
                        <br />
                        <br />
                        Eine D&uuml;nndarmfehlbesiedelung wird idealerweise mit Hilfe eines 
                        Wasserstoff-Atemtests (H<sub>2</sub>-Atemtest) diagnostiziert bzw. ausgeschlossen.
                        Im Gegensatz zu anderen Wasserstoff-Atemtests, mit denen man verschiedene 
                        Nahrungsmittel-Unvertr&auml;glichkeiten diagnostizieren kann, muss bei einem 
                        Glukose-Test zur Ermittelung einer D&uuml;nndarmfehlbesiedelung aber die erste  
                        Messung nach der N&uuml;chternprobe schon nach 10 und nicht erst nach 30 Minuten vorgenommen werden. 
                        Im weiteren Verlauf muss auch sehr viel engmaschiger gemessen werden, n&auml;mlich 
                        alle 10 Minuten. Leider werden diese Tests immer wieder falsch durchgef&uuml;hrt,
                        so dass die Ergebnisse nicht belastbar sind. Wenn man im Zuge einer sorgf&auml;ltigen 
                        Diagnostik auch Nahrungsmittel-Unvertr&auml;glichkeiten aufsp&uuml;ren oder 
                        ausschlie&#223;en will, kann man sogar vermeiden, die Darmflora mehrfach zu 
                        belasten, wenn man die Tests mit etwas &Uuml;berlegung anwendet.
