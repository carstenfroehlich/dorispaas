                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=iggtests" target="_blank">Wie sinnvoll sind IgG4-Tests (ELISA)?</a></b>
                        <br />
                        <br />
                        Immer wieder werden Menschen durch die vielen angeblich unvertr&auml;glichen Lebensmittel 
                        verunsichert, die ein so genannter &#187;IgG-Test&#171;
                        ergeben hat. Diese Test sollen angeblich Nahrungsmittel-Unvertr&auml;glichkeiten aufsp&uuml;ren. 
                        Aber sind sie wirklich aussagekr&auml;ftig? Zumindest kosten sie viel Geld, 
                        das keine Krankenkasse &uuml;bernimmt. Sie verwirren nicht nur den Patienten, sondern 
                        bewirken, dass er eine Di&auml;t eingehalten soll, die teils eine gro&#223;e Palette 
                        von Lebensmitteln ausschlie&#223;t und so unn&ouml;tig die Lebensqualit&auml;t einschr&auml;nkt 
                        &ndash; abgesehen von der Verunsicherung, wie auf diese Weise noch der 
                        N&auml;hrstoffbedarf gedeckt werden soll. In dem Beitrag wird der IgG-Test kritisch 
                        betrachtet und die Hintergr&uuml;nde und Zusammenh&auml;nge erkl&auml;rt.
