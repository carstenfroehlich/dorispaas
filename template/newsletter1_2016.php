                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=vitalpilze" target="_blank">Vitalpilze</a></b>
                        <br />
                        <br />
                        Vitalpilze werden seit langer Zeit in der &ouml;stlichen Medizin verwendet, aber 
                        auch die westliche Klostermedizin nutzte die Heilkr&auml;fte der Pilze. Nur sehr 
                        zaghaft hat sich bei uns bis heute die Erkenntnis durchgesetzt, was diese kleinen 
                        Wunderwerke der Natur leisten k&ouml;nnen. Dabei ist gerade bei Verdauungsproblemen 
                        der Einsatz von Vitalpilzen besonders hilfreich. Pilze sind eine eigene Form im 
                        Pflanzenreich und den meisten entweder als schmackhafte Zutat zu einer Mahlzeit 
                        oder aber als giftige Gefahr bekannt. Auch die halozinogene, berauschende Wirkung 
                        oder auch die M&ouml;glichkeit, mit Giftpilz-Gerichten unliebsame Mitmenschen 
                        beseitigen zu k&ouml;nnen, finden zumindest in der Kriminalliteratur Raum. 
                        Dass bestimmte Pilze aber auch Heilwirkungen haben, wissen die wenigsten. 
