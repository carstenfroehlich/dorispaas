                        <br />
                        <br />
                        <b>&#187;Was kann ich noch essen&#171;</b>
                        <br />
                        Von Barbara Sonnentag 
                        <br />
                        <br />
                        Der Beitrag in der &#187;Freundin&#171; befasst sich auf 3 Seiten (inkl. 
                        gro&#223;formatigen Bildern) mit den Nahrungsmittel-Unvertr&auml;glichkeiten Gluten, 
                        Laktose, Fruktose und Histamin. Augenf&auml;llig aufgemachte Prozentzahlen spiegeln 
                        den Tenor des Beitrags: &#187;30% glauben, an einer Nahrungsmittel-Unvertr&auml;glichkeit 
                        zu leiden, die tats&auml;chlichen Zahlen sind jedoch niedriger.&#171; Und weiter: 
                        &#187;30% reagieren schon auf geringe Mengen Fruktose mit Bauchschmerzen.&#171; 
                        Allein schon diese Teaser zeigen die Ungenauigkeit der Recherche, vor allem aber 
                        die Sto&#223;richtung dieses Beitrags auf.
                        <br />
                        <br />
                        Vorab: Ich finde es gut, dass immer mehr Medien sich des Themas 
                        &#187;Nahrungsmittel-Unvertr&auml;glichkeiten&#171; annehmen und versuchen, auch 
                        die Nicht-Betoffenen aufzukl&auml;ren und bei ihnen Verst&auml;ndnis f&uuml;r die 
                        Probleme zu wecken (die Betroffenen haben sich ohnehin meistens damit befasst und 
                        sind mehr oder weniger informiert).
                        <br />
                        <br />
                        Leider jedoch sind die meisten Beitr&auml;ge dieser Art recht oberfl&auml;chlich 
                        recherchiert. Wie der weiter unten in diesem Blog angef&uuml;hrte Beitrag im 
                        Tagesspiegel vom 6.8.12 und die Ver&ouml;ffentlichung der Verbraucherzentrale 
                        Hamburg vom gleichen Tage ist weist auch der Beitrag in der Zeitschrift 
                        &#187;Freundin&#171; vom 11.7.2012 &auml;rgerliche Ungenauigkeiten auf:
                        <br />
                        <br />
                        Er beginnt mit einem Abschnitt &uuml;ber Gluten und versucht hier auf allerkleinstem 
                        Raum von noch nicht einmal einer Spalte die Z&ouml;liakie zu umrei&#223;en, ohne 
                        der Dramatik dieser ersten Erkrankung gerecht werden zu k&ouml;nnen. Dass hier 
                        bei der &#187;Behandlung&#171; bzw. der erforderlichen Di&auml;t absolute Konsequenz 
                        ohne die kleinste Ausnahme zu beachten ist, wird nicht erw&auml;hnt, obwohl der 
                        Verfasser als Experte bezeichnet wird. Die Bemerkung, &#187;Lebenslanger Verzicht 
                        auf Gluten ist das Einzige, was man tun kann. Dann heilt die Krankheit meist 
                        v&ouml;llig ab&#171; ist zumindest missverst&auml;ndlich. Ja, es wird von &#187;lebenslangem 
                        Verzicht&#171; gesprochen, aber die Krankheit heilt mitnichten ab, sondern nur die 
                        Symptome. Hier h&auml;tte ich mir eine korrektere und unmissverst&auml;ndlichere 
                        Beschreibung gew&uuml;nscht. 
                        <br />
                        <br />
                        Auch f&auml;llt hier trotz der allgemeinen &UUML;berschrift &#187;Gluten&#171; 
                        leider die Gluten-Unvertr&auml;glichkeit unter den Tisch, von der ebenfalls immer 
                        mehr Menschen betroffen sind. Dies aber mag dem Platzmangel geschuldet sein.
                        <br />
                        <br />
                        Der n&auml;chste Abschnitt behandelt die Laktose-Intoleranz, zumindest zuerst 
                        einmal v&ouml;llig korrekt als &#187;genetischer Normalzustand&#171; bezeichnet. 
                        Im Gro&#223;en und Ganzen richtig umrissen, m&uuml;ndet er jedoch leider, wie die 
                        oben erw&auml;hnten Beitr&auml;ge des Tagesspiegel und der Verbraucherzentrale 
                        auch in der Feststellung, dass &#187;Die meisten Betroffenen  ... [Laktose] in 
                        geringen Mengen oder in vergorener Form, etwa als reifen Käse oder 
                        Sauermilch&#171; vertragen. Dies erweckt den Eindruck, dass es schon nicht so 
                        schlimm ist, mal ab und an einen Joghurt zu essen. Es ist zwar der &#187;Sauermilchjoghurt&#171; 
                        erw&auml;hnt, dass aber erstens die meisten Joghurts als Industrieprodukte teils 
                        massig Laktose enthalten und zweitens eben auch nicht nur einige, sondern ziemlich 
                        viele Betroffene trotz der individuellen Vertr&auml;glichkeitsgrenzen lieber auch 
                        auf Produkte, die nur geringe Laktosemengen enthalten verzichten &ndash; es zumindest 
                        aber selbst in der Hand haben wollen und nicht von der Nahrungsmittelindustrie 
                        aufgezwungen bekommen wollen, f&auml;llt offensichtlich dem geringen Beitragsumfang 
                        zum Opfer. 
                        <br />
                        <br />
                        Weiter geht es mit der Beschreibung der Fruktose-Intoleranz. Auf knapp einer Spalte 
                        wird nicht nur umrissen, was Fruktaose-Intoleranz ist, sondern (in diesem Falle 
                        &uuml;berfl&uuml;ssigerweise) auch noch Platz verschwendet mit der Hinzunahme der 
                        angeborenen Intoleranz, die &ndash; wie korrekt beschrieben &ndash; &auml;u&#223;erst 
                        selten ist (hier also kaum interessant ist). Hier flie&#223;en dann Erkl&auml;rungen 
                        ein, dass sich &#187;hinter den S&uuml;&#223;stoffen Sorbit, Mannit und Xylit&#171; 
                        ebenfalls Fruktose &#187;verberge&#171;. Zum einen: Sorbit, Mannit und Xylit sind 
                        keine &#187;S&uuml;&#223;stoffe, sondern Zuckeralkohole, und es &#187;verbirgt&#171; 
                        sich auch keine Fruktose dahinter. Zugegebenerma&#223;en haben die meisten Menschen 
                        mit Fruktose-Intoleranz auch Probleme mit den Zuckeralkoholen, weil diese die 
                        gleichen Verwertungssystem benutzen, dasselbe ist es aber nicht. Bei allem 
                        Verst&auml;ndnis f&uuml;r Platzmangel: dann bitte lieber Unwichtigeres weglassen 
                        als Falsches zu schreiben.
                        <br />
                        <br />
                        Der Beitrag schlie&#223;t mit einer knappen Spalte &uuml;ber die Histamin-Unvertr&auml;glichkeit 
                        und beschreibt: &#187;Sie ist so etwas wie eine Modediagnose, die gern im Internet 
                        gegoogelt wird&#171; und schlie&#223;t mit dem Satz &#187;In der Apotheke gibt es 
                        das Abbauenzym ... in Kapselform&#171;. Es mag stimmen, dass tats&auml;chlich weniger 
                        Menschen an einer Histamin-Unvertr&auml;glichkeit leiden, als angenommen. Aber 
                        zumindest f&uuml;r diese Betroffenen ist die Bemerkung wenig hilfreich, die 
                        Unvertr&auml;glichkeit k&ouml;nne mal so einfach mit dem Einnehmen einer Kapsel 
                        behandelt werden. 
                        <br />
                        <br />
                        Und au&#223;erdem ist die Tatsache, dass viele einen solchen Verdacht hegen, weil 
                        sie immer wiederkehrende Verdauungsprobleme haben und alles andere bereits 
                        ausgeschlossen haben, allein schon bemerkenswert genug und sollte nicht Anlass zu 
                        abf&auml;llig wirkenden Beschreibungen geben. Hier macht es sich der Experte also 
                        ein wenig zu einfach und wird zumindest all denen in keinster Weise gerecht, die 
                        an dieser wirklich nur sehr schwer handelbaren Unvertr&auml;glichkeit leiden.
                        <br />
                        <br />
                        Ein ganz wichtiger Aspekt und die zwingende Schlussfolgerung f&uuml;r alle 
                        Unvertr&auml;glichkeiten wird leider nicht erw&auml;hnt: Dass die Nahrungsmittelindustrie 
