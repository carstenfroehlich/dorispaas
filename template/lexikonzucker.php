                                <td class="q">
                                    Glukose
                                </td>
                                <td class="a">
                                    (andere Bezeichnungen: Traubenzucker, Stärkezucker, Glucose, Dextrose)
                                    <br />
                                    Hintergrund: Glukose ist ein Monosaccharid und wurde Ende des 18. Jahrhunderts 
                                    von Johann Tobias Lowitz in Weintrauben entdeckt. Dies ist der Grund 
                                    für den deutschen Namen &#187;Traubenzucker&#171;. Da Glukose 
                                    auch aus Mais- oder Kartoffelstärke gewonnen werden kann, nennt 
                                    man sie auch &#187;Stärkezucker&#171;.
                                    <br />
                                    Glukose wird durch Photosynthese im Blattgrün von Pflanzen hergestellt. 
                                    Tiere müssen Glukose über die Nahrung aufnehmen &ndash; meist in 
                                    gebundernen Formen, die durch Enzyme aufgespalten werden. Glukose wird 
                                    über die Dünndarmschleimhaut in Blut aufgenommen. Dort regeln 
                                    die Hormone Insulin und Glukagon den Blutzuckergehalt. Glukose kann 
                                    direkt als Energielieferant von den Körperzellen genutzt werden 
                                    oder aber über die Leber umgebaut und dann gespeichert werden.
