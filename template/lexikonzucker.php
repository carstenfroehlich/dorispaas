                                </td>
                                <td class="a">
                                    Ballaststoffe sind Oligosaccharide oder Polysaccharide.
                                    <br />
                                    Zu den Ballaststoffen werden all diejenigen Kohlenhydrate (--> siehe dort) 
                                    gerechnet, die vom menschlichen Verdauungssystem aufgrund fehlender 
                                    Enzyme nicht aufgeschlossen und verdaut werden können.
                                    <br />
                                    Es gibt wasserlösliche Ballaststoffe (Pektine, Schleimstoffe, Gele 
                                    aus Algen und Pflanzengummi), die zwar vom körpereigenen Verdauungssystem 
                                    nicht aufgespalten, jedoch von den Bakterien der Dickdarmflora weitestgehend 
                                    verstoffwechselt werden können.
                                    <br />
                                    Weiterhin gibt es die wasserunlöslichen Ballaststoffe. Hierzu zählen 
                                    Cellulose, Hemicellulose und Lignin, die in den Wänden der Pflanzenzellen 
                                    als Stützgewebe enthalten sind. 
                                    <br />
                                    Ballaststoffe, insbesondere jedoch die wasserunlöslichen, können
                                    sehr viel Wasser binden, wodurch sie das Stuhlvolumen erhöhen und 
                                    die Stuhlkonsistenz verbessern. Zusätzlich können sie auch 
                                    Giftstoffe binden und mit dem Stuhl ausleiten.
                                    <br /> 
                                    Somit ist nach Möglichkeit eine Ernährung anzustreben, die 
                                    reich an Ballaststoffen ist.
                                    <br />
                                    Mögl. Probleme: Bei entsprechender Empfindlichkeit kann ein 
                                    Übermaß an Ballaststoffen zu Verdauungsproblemen wie vor 
                                    allem Blähungen führen.         
