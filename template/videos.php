                        <h5>Podcasts</h5>
                        <hr />
                        <br />
                        <b>Die &#187;Darmbakterien-Meditation&#171; soll Sie dabei unterstützen, in stressigen Zeiten auf sich zu achten 
                        und für die eigene mentale und körperliche Gesundheit zu sorgen. </b>
                        <br />
                        <br />
                        Mit diesem Podcast leite ich Sie durch eine Meditation, in der Sie Ihre Aufmerksamkeit auf Ihre Darmbakterien fokussieren können.
                        Ganz bewusst sind weder Musik noch andere Geräusche hinterlegt, sondern die Anleitung enthält nur meine Stimme. Da die Geschmäcker 
                        verschieden sind, wäre eine Musikauswahl durch mich für die einen vielleicht genau das Richtige, für die anderen aber gerade nicht. 
                        Deshalb: schalten Sie gerne Ihre eigene, ganz persönliche Musik dazu an, wenn Sie möchten. Oder konzentrieren Sie sich nur auf die 
                        Stimme und genießen Sie die Stille.
