                    <h5>Buchbeschreibung</h5>
                    <hr />
                    Den Begriff Zöliakie hat wahrscheinlich jeder schon einmal gehört. Um was genau 
                    es sich hier aber handelt, ist für die meisten &ndash; sofern sie nicht selbst
                     betroffen sind &ndash; nicht wirklich deutlich. Es hat was mit Gluten 
                    zu tun, aber was ist das nun wieder? Ist die Zöliakie eine Gluten-Allergie? 
                    Eine Nahrungsmittel-Unverträglichkeit? Oder etwas ganz anderes? Und 
                    was bedeutet Gluten-Sensitivität? Ist das das Gleiche? 
                    <br />
                    <br />
                    Fragen über Fragen, die dieser Titel aus der Paas‘schen Heftchenreihe 
                    klärt, so dass Sie verstehen, warum Betroffene ganz konsequent auf bestimme 
                    Nahrungsmittel verzichten müssen. Nichtbetroffenen hilft das Buch, Verständnis 
                    aufzubringen und trotz einer solchen Erkrankung gemeinsam Essen genießen zu können.
                    
                    Die Paas‘schen Heftchen behandeln Themen aus dem Gesundheitsbereich. Sie erläutern 
                    jeweils in kurzer und klarer Form die Ursachen und Hintergründe von Beschwerden. 
                    Sie helfen, Probleme zu erkennen und zu verstehen und zeigen erste Schritte in die 
                    richtige Richtung: eine gesunde Lebensweise ohne Beschwerden, um sich wohl zu fühlen. 
                    <br />
                    <br />
                    Kurz und klar &ndash; der Name ist Programm: Die Heftchen erheben bewusst keinen 
                    Anspruch auf Ausführlichkeit, sondern verschaffen Ihnen in kurzer, aber korrekter 
                    Form einen ersten Überblick über einen Sachverhalt. Trotz des geringen Umfangs 
                    sind sie jedoch nicht oberflächlich und immer sorgfältig recherchiert: In rund 
                    einer Stunde wissen Sie alles Wesentliche zum Thema. 
