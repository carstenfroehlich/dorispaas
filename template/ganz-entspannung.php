                        <h5>Stressmanagement</h5>
                        <hr />
                        Mit ein wenig Nachdenken können wir viele (selbstgemachte) Stressereignisse vermeiden. Einige aber 
                        lassen sich nicht immer verhindern (wie eben die erwähnten Krisen, deren Auswirkungen und deren Dauer wir nicht in der Hand haben). 
                        Umso wichtiger ist es, Stress zu kompensieren, um ihn mit einem vernünftigen Stressmanagement zumindest zum Teil unschädlich zu machen. 
                        <br />
                        <br />
                        Je mehr Stress Sie haben und nicht vermeiden können, desto mehr sollten Sie darauf 
                        achten, ihn auf körperlicher und auch auf seelischer Ebene abzubauen. Günstig ist es dabei immer, in einen möglichst natürlichen 
                        Rhythmus zwischen Anspannung und Entspannung zu kommen (lesen Sie hierzu gerne den Beitrag &#187;<a href="ganz-rhythmus" target="_blank">Rhythmus</a>&#171;).
                        <br />
                        <a id="bewegung">&nbsp;</a>
                        <hr />
                        <h5>Bewegung</h5>
                        <hr />
                        Zuerst einmal sollte man sich so viel wie möglich bewegen, denn Bewegung baut 
                        Stresshormone ab. Suchen Sie sich die zu Ihnen passende Sportart aus, denn Spaß 
                        machen sollte die Bewegung auf jeden Fall (lesen Sie hierzu bitte auch den Beitrag 
                        &#187;<a href="bewegung" target="_blank">Bewegung und Sport</a>&#171;). 
                        Wird Sport übertrieben oder als gar 
                        Belastung empfunden, erzeugt dies zusätzlichen Stress &ndash; Sie erweisen sich 
                        also einen Bärendienst. Ggf. reicht nach einem stressigen Tag auch ein ausgiebiger 
                        Spaziergang &ndash; das entspannt nicht nur die Muskulatur, Sie können dabei auch 
                        die Seele baumeln lassen und sich mental entspannen.
                        <br />
                        <a id="darmgymnastik">&nbsp;</a>
                        <hr />
                        <h5>Darmgymnastik</h5>
                        <hr />
                        (Nicht erst) wenn Verdauungsprobleme vorliegen &ndash; und Stress kann dabei, wie dargelegt, einer der ganz entscheidenden Auslöser sein &ndash; 
                        ist es sicherlich förderlich, auch diesen Symptomen mit Sport entgegenzuwirken. Aber das reicht nicht immer, denn Sport wird 
                        bestenfalls am Abend, wenn nicht sogar nur ein oder zweimal pro Woche   ausgeführt. Gegen Verdauungsprobleme, die in der Regel 
                        immer mit einem zu wenig aktiven Darm zusammenhängen, helfen regelmäßige und kontinuierliche, kleine Bewegungsübungen: die 
                        <a href="darmgymnastik" target="_blank">Darmgymnastik</a>.
                        <br />
                        <br />
                        Wenn wir uns vorstellen, wie unsere Vorfahren gelebt hatten, fällt vor allem auf, dass diese Menschen ständig in Bewegung gewesen sind. Sie liefen große Strecken, 
                        um ihre Nahrung zu sammeln, denn es gab weder Supermarkt noch Kühlschrank. Alles musste gesammelt oder später &ndash; nach der Erfindung der Waffen &ndash; 
                        auch gejagt werden. Beim Sammeln wurde sich gebückt und gereckt, um die Wurzeln, Beeren, Schösslinge und die vielen anderen Pflanzenteile zusammenzutragen. Beim 
                        Jagen mussten die Menschen sich hinter Büschen verstecken, hinter den flüchtenden Tieren herlaufen, die Waffen mit Kraft werfen und die schwere Beute nach Hause 
                        schleppen. Alles in allem also schwerste körperliche Arbeit und der Einsatz von allen Körper- und Atemmuskeln. Bei einer solchen Lebensweise kam kein Darm auf 
                        &#187;die Idee&#171;, faul zu sein, sondern wurde kontinuierlich von außen angeregt. Und durch die überwiegend pflanzliche Nahrung &ndash; Fleisch gab es ja nur, 
                        wenn mal ein Tier gefangen werden konnte &ndash; wurden selbstverständlich auch genügend Ballaststoffe verzehrt (sehr viel mehr, als wir dies heute selbst bei gesündester 
                        Ernährung tun), so dass durch den ausreichenden Volumendruck die Darmperistaltik auch von innen angeregt wurde. <b>Das Thema &#187;Verstopfung&#171; dürfte also 
                        unseren Vorfahren unbekannt gewesen sein</b>. 
                        <br />
                        <br />
                        Ganz anders als unsere Vorfahren bewegen wir uns heute kaum noch. Zur Fortbewegung benutzen wir das Auto, und die allermeisten Menschen sitzen viel zu viel. 
                        &#187;Das Sitzen ist das neue Rauchen&#171; &ndash; also das neue &#187;Gift&#171;, heißt es heute unglücklicherweise. Dies hat leider nicht nur für unsere Haltung, 
                        für unsere Muskulatur und unsere Knochen sehr nachteilige Folgen, sondern auch für unsere Verdauung, und viele Krankheiten und Probleme &ndash; sei es die oben 
                        erwähnte Verstopfung oder Fehlbesiedelungen von Dünn- oder Dickdarm und viele andere mehr &ndash; könnten durch eine ausreichende und vor allem <b>kontinuierliche 
                        Bewegung</b> verhindert bzw. in ihrer Ausheilung günstig beeinflusst werden. 
                        <br />
                        <br />
                        Für den Darm aber zählen stündliche oder sogar halbstündliche Übungen. Und diese müssen auch keineswegs schweißtreibend und zeitraubend sein, etwa 3 Minuten pro 
                        Übung reichen, nachdem Sie die Übung etwas intensiver erlernt haben und Ihnen die Ausführung geläufig ist. Es gibt Atemübungen, Dehnungs- und Lockerungsübungen, 
                        entblähende und Stärkungsübungen, aber auch entspannende Übungen. Ich empfehle Ihnen das Buch <a href="book-darmgymnastik" target="_blank">Darmgymnastik &ndash; 
                        Bewegung & mehr gegen Verdauungsbeschwerden</a>.
                        <br />
                        <a id="atemtechniken">&nbsp;</a>
                        <hr />
                        <h5>Atemtechniken</h5>
                        <hr />
                        Ganz wichtig zur Entspannung ist auch das korrekte Atmen. Nicht nur der Brustkorb 
                        ist dabei der Atemraum, wir können auch tief in den Bauch hinein atmen. Dieses 
                        tiefe Luftholen und natürlich auch das sorgfältige Ausatmen versorgt uns zum 
                        einen mit viel lebenswichtigem Sauerstoff und transportiert das schädigende Kohlendioxid aus dem Körper. 
                        Zum anderen aber fördert es die Durchblutung 
                        aller Muskeln und durch die Aktivität des Zwerchfells auch eine gesunde Verdauung
                        (lesen Sie hierzu bitte auch den Beitrag &#187;<a href="atmen" target="_blank">Atem und Verdauung</a>&#171;). 
                        Nur mit gesundem tiefem Atmen können Stresshormone abgebaut und ausgeschieden und 
                        alle Abfallprodukte unseres Stoffwechsels entsorgt werden.
                        <br />
                        <a id="meditation">&nbsp;</a>
                        <hr />
                        <h5>Meditation</h5>
                        <hr />
                        Die Meditation ist eine Entspannungstechnik, bei der man ganz bewusst seinen Geist steuert und ihn zur Ruhe kommen lässt.
                        Jedem sind sicherlich die Bilder eines im Schneidersitz sitzenden Buddhas bekannt, der sich mit geschlossenen Augen in tiefster Versenkung entspannt.
                        Zugegeben: sich zu entspannen wie Buddha braucht schon einige Übung, aber auch Sie können ohne Vorkenntnisse von der Meditationstechnik profitieren.
                        Ich habe unter dem Menüpunkt &#187; Videos/Tutorials und Podcasts&#171; eine <a href="videos#darmbakterienmeditation" target="_blank">Darmbakterien-Meditation</a> 
                        für Sie bereit gestellt, mit der Sie sich nicht nur entspannen, sondern zusätzlich auch Ihre Aufmerksamkeit auf Ihre Darmbakterien fokussieren können.
                        Probieren Sie das gerne einmal aus.
                        <br />
                        <a id="entspannungstechniken">&nbsp;</a>
                        <hr />
                        <h5>Weitere Entspannungstechniken</h5>
                        <hr />
                        Neben den Atemtechniken und der Meditation gibt es weitere Techniken, um Körper und Nerven zu 
                        entspannen und die hilfreich sind, Stress, 
                        der sich nicht vermeiden lässt, zu kompensieren. Hier eignen sich vor allem  
                        &#187;Autogenes Training&#171;, die &#187;Progressive Muskelentspannung&#171; nach 
                        Jacobson, aber auch Yoga, Qi Gong und vieles mehr. 
                        Schauen Sie z.B. einmal in das Programm der Volkshochschule in Ihrer Nähe, dort 
                        werden zu den meisten Entspannungsmethoden Kurse angeboten. Nachdem Sie vielleicht 
                        in die eine oder andere Methode hineingeschnuppert und sie erlernt haben, können 
                        Sie dann für sich zu jedem geeigneten Termin gezielt entspannen.
                        <br />
                        <a id="akupressur">&nbsp;</a>
                        <br />
                        <hr>
                        <h5>Akupressur und Klopftechnik</h5>
                        <hr>
                        Hilfreich zur Entspannung kann gerade für Menschen mit Verdauungsproblemen auch die Akupressur sein. 
                        Wahrscheinlich hat jeder schon einmal von der der Akupunktur gehört, einer in der Traditionellen 
                        Chinesischen Medizin (TCM) verankerten Methode. Dabei werden feine Nadeln in bestimmte Punkte auf 
                        unserer Körperoberfläche gestochen, um den Energiefluss zu harmonisieren oder auch um die Produktion 
                        körpereigener Stoffe zu produzieren. Für die Selbstanwendung zu Haus empfiehlt es sich, geeignete Punkte
                        aufzufinden und mit den Fingern zu pressen (Akupressur) oder auch zu klopfen (Kopftechnik).
                        Auf diese Weise können ähnliche Effekte erzielt werden wie bei der Akupunktur, ohne jeweils einen 
                        Therapeuten aufsuchen zu müssen. Lesen Sie hierzu auch den Beitrag &#187;<a href="akupressur" target="_blank">Akupressur 
                        zur Beeinflussung von Magen-/Darmproblemen</a>&#171;.
                        <br />
                        <br />
                        Auch in dem Buch <a href="book-darmgymnastik" target="_blank">Darmgymnastik &ndash; Bewegung & mehr gegen Verdauungsbeschwerden</a>
                        finden Sie eine umfangreiche Palette von <b>insbesondere bei Verdauungsproblemen geeigneten Akupressurpunkten</b> und die Anleitung, 
                        sie richtig zu nutzen.
                        <br />
                        <a id="schlafhygiene">&nbsp;</a>
                        <hr />
                        <h5>Schlafhygiene</h5>
                        <hr />
                        Damit wir uns im Schlaf wirklich entspannen können, müssen einige wichtige Faktoren 
                        berücksichtigt werden. Dies nennt man &#187;Schlafhygiene&#171;.
                        <br />
                        <br />
                        Zuerst einmal benötigen wir <b>ausreichend</b> Schlaf. Was jedoch für den einen 
                        ausreichend ist, kann für den anderen bereits zu viel oder aber auch zu wenig sein. 
                        Erwachsene sollten im Schnitt täglich 7-8 Stunden schlafen, um sich regenerieren 
                        zu können. Über- oder unterschreitet man diese Zeitspanne nennenswert und dauerhaft, 
                        kann dies ebenfalls zu Stress führen.
                        <br />
                        <br />
                        Weiterhin sollte das Schlafzimmer <b>gut belüftet</b> sein. Es sollte nicht zu 
                        kalt und nicht zu warm sein &ndash; die optimale Temperatur beträgt im Allgemeinen 
                        zwischen 18 und 19°C.
                        <br />
                        <br />
                        <b>Bett und Bettzeug</b> müssen ebenfalls den Bedürfnissen angepasst sein: Sowohl 
                        eine zu harte als auch eine zu weiche Unterlage sind nicht schlafförderlich.  
                        Kissen und Decke sollten als angenehm empfunden werden &ndash; weder zu warme noch 
                        zu dünne Decken und Kissen sind schlafförderlich. Die Bezüge müssen ausreichend 
                        Schweiß aufsaugen &ndash; Naturfasern ist hier auf jedem Fall der Vorzug vor 
                        Kunstfasern zu geben.
                        <br />
                        <br />
                        Das Schlafzimmer sollte möglichst <b>weitgehend abgedunkelt</b> sein, um den 
                        natürlichen Schlaf-/Wachrhythmus nicht zu beeinträchtigen.
                        <br />
                        <br />
                        Auch das Verhalten tagsüber und am Abend beeinflusst den Schlaf. Insbesondere am Vormittag sollte 
                        möglichst viel Tageslicht auf die Augen treffen, um so unsere &#187;<b>zirkadiane Uhr</b>&#171; auf Tag zu programmieren.
                        Abends kommt dann der Körper durch die Reduktion des Tageslichts zur Ruhe, so dass unser <b>Schlafhormon 
                        Melatonin</b> gebildet werden kann. Sitzen wir bis spät in den Abend vor dem PC, bekommen wir über die Augen viel 
                        zu viel blaue Lichtwellen ab, die das Merkmal des Tageslichts sind. Die Abenddämmerung ist rötlicher &ndash; nur 
                        das rötliche Licht oder die Dunkelheit erlauben die Bildung des Melatonins, das für den Schlaf erforderlich ist.
                        <br />
                        <br />
                        Auch sollte dafür gesorgt sein, so <b>ungestört</b> wie möglich zu schlafen. Wenn 
                        Sie die Wahl haben, stellen Sie Ihr Bett im ruhigsten Raum in der Wohnung auf. 
                        Wenn Sie kleine Kinder haben, lassen sich nächtliche Störungen natürlich nicht 
                        immer vermeiden &ndash; suchen Sie hier nach möglichst guten  Lösungen.
                        <br />
                        <br />
                        <b>Schließen Sie den Tag auch mental ab</b>, d.h. lassen Sie noch einmal Revue passieren, 
                        was Sie den Tag über geleistet und erledigt haben. Versuchen Sie ggf., Probleme 
                        nicht mit in die Nacht zu nehmen, sondern (gedacht oder vielleicht sogar real) 
                        in einen Korb neben dem Bett zu legen. Am nächsten Morgen können Sie das Problem 
                        wieder herausnehmen und bearbeiten &ndash; sofern es sich nicht über Nacht von 
                        alleine gelöst hat.
                        <br />
                        <a id="winterschlaf">&nbsp;</a>
                        <hr />
                        <h5>Sonderfall Winterschlaf</h5>
                        <hr />
                        Viele Tiere halten Winterschlaf wie z.B. die sprichwörtlichen Murmeltiere oder Siebenschläfer. Sie senken ihre Körpertemperatur 
                        ab und reduzieren so ihren Energieverbrauch, um mit den im Herbst angefressenen Fettreserven bis zum nächsten Frühjahr überleben zu 
                        können. Andere Tiere, wie u.a. die Bären oder die Eichhörnchen halten zumindest eine Winterruhe, aus der sie nur sporadisch für 
                        kurze Zeit aufwachen, um ein wenig Futter zu sich zu nehmen.
                        <br />
                        <br />
                        Für uns Menschen ist der Begriff &#187;Winterschlaf&#171; meist positiv besetzt. Auch wir sehnen uns danach, uns in der kalten Jahreszeit 
                        unter eine warme Decke zu kuscheln, einen dampfenden Tee zu genießen oder zu dösen. Auch haben wir vermehrt das Bedürfnis, kalorienreiche 
                        Winterspezialitäten zu essen, und ein frischer, kühler Salat steht jetzt seltener auf dem Speiseplan.
                        <br />
                        <br />
                        All dies ist ganz tief in unseren Genen verankert: die Sehnsucht nach nährenden Speisen, wärmender Kleidung oder Decken oder auch 
                        nach Ruhe &ndash; auch für uns eine kleine Winterruhe.
                        <br />
                        <br />
                        Vieles in unserem Umfeld steht dem entgegen. Angefangen mit dem trotz der zurückgestellten Uhren (zu) frühen Aufstehen, Wegen zur 
                        und von der Arbeit im Dunkeln und der Kälte &ndash; draußen, weil die Sonne seltener scheint und in der Wohnung, weil wir (berechtigterweise) 
                        Energie sparen und die Thermostaten um ein paar Grad herunterdrehen.
                        <br />
                        <br />
                        Natürlich können Sie sich nicht den ganzen Winter lang in &#187;Ihre Höhle&#171; zurückziehen und nicht mehr Ihren Pflichten nachgehen.
                        Sie sollten aber immer dort, wo es möglich ist, Ihren Bedürfnissen folgen und ggf. den Tagesablauf dem natürlichen Biorhythmus anpassen.
                        <b>So können auch Sie Ihren &#187;kleinen Winterschlaf&#171; bekommen</b>.
                        <br />
                        <br />
                        Auch beim Essen haben wir unsere Gewohnheiten, um nicht zu viel Gewicht zuzulegen oder weil wir aufgrund von eventuellen Erkrankungen 
                        nur einen eingeschränkten Speisezettel haben. Trotzdem überfällt uns jetzt mit (weniger) schöner Regelmäßigkeit die Lust auf Süßen und 
                        Fettiges &ndash; und schon bald beschwert sich der Bauch, wenn wir dem (zu) oft nachgeben. Und tun wir dies nicht, bedeutet es Stress, 
                        der sich leider ebenfalls über unseren Bauch melden kann.
                        <br />
                        <a id="ernaehrung">&nbsp;</a>
                        <hr />
                        <h5>Ernährung</h5>
                        <hr />
                        Ganz wichtig für einen entspannten Körper und Geist ist auch die richtige Ernährung. 
                        <b>Was aber ist richtig für Sie?</b> Nicht jeder verträgt alles, manche Menschen 
                        haben Probleme mit bestimmten Nahrungsmitteln. Achten Sie darauf, möglichst viele 
                        &#187;<b>gesunde Lebensmittel</b>&#171; zu verzehren, aber beachten Sie auch Ihre individuellen 
                        Erfordernisse.
                        <br />
                        <br />
                        Am einfachsten beherzigen Sie <b>folgende Faustregeln</b>: 
                        <br />
                        1. Je mehr verschiedene Lebensmittel Sie essen (können), desto besser ist das für Ihr Verdauungssystem.
                        <br />
                        2. Beachten Sie dabei aber Ihre persönlichen Bekömmlichkeiten, um eventuelle Symptome zu minimieren.
                        <br />
                        3. Je frischer und unverfälschter ein Lebensmittel ist, desto gesünder ist es.
                        <br />
                        <br />
                        <b>Die letzte, leichte Mahlzeit</b> sollte möglichst spätestens 3 Stunden vor 
                        dem Schlafengehen eingenommen werden, denn mit vollem Bauch schläft man unruhiger.
                        <br />
                        <br />
                        Da auch die Zeit des Verzehrs bestimmter &ndash; eventuell manchmal unverträglicher &ndash; Lebensmittel über die Bekömmlichkeit (mit) entscheidet, 
                        empfehle ich Ihnen den Beitrag &#187;<a href="zeitmanagement" target="_blank">Zeitmanagement bei Nahrungsmittel-Unverträglichkeiten &ndash; Steigerung 
                        der Verträglichkeit durch die Wahl der richtigen Verzehrzeit</a>&#187;.
                        <br />
                        <br />
                        Bei aller Konsequenz möchte ich Ihnen aber auch den Beitrag &#187;<a href="ganz-genuss" target="_blank">Genießen? Ja bitte &ndash; auch bei 
                        Nahrungsmittel-Unverträglichkeiten!</a>&#171; ans Herz legen: Nicht nur im Winter (während Ihrer &#187;kleinen Winterruhe&#171; oder in der 
                        Weihnachtszeit dürfen Sie gerne auch einmal alle Fünfe gerade sein lassen und ein wenig über die Stränge schlagen. Das ist zwar auf den ersten 
                        Blick nicht ganz so optimal für die Verdauungsprobleme, aber da Sie damit Ihrer Seele guttun (vorausgesetzt, Sie haben kein schlechtes Gewissen 
                        und genießen Ihre &#187;Sünde&#171;, wirkt sich dies dann auch wieder positiv auf den Darm aus und kann sehr entspannend sein. Eine Ausnahme 
                        sollte es aber schon bleiben.
                        <br />
                        <a id="beruehrung">&nbsp;</a>
                        <hr />
                        <h5>Berührung</h5>
                        <hr />
                        Ganz wichtig sind auch Berührungen &ndash; nicht nur in Bezug auf die Entspannung, sondern insgesamt für ein gesundes menschliches Wohlbefinden. 
                        Kein Baby kann sich ohne die Berührungen seiner Eltern gesund entwickeln (was sehr böse Experimente in der Nazizeit bewiesen haben), und jedes 
                        Kleinkind braucht Berührungen nicht nur, wenn es sich wehgetan hat.
                        <br />
                        <br />
                        In der Pubertät ist das Kuscheln dann vorübergehend nicht mehr ganz so angesagt, aber in den Momenten, wo die Jugendlichen sich erlauben, 
                        dann doch noch einmal Kind zu sein, spielen auch hier die Brührungen eine gern gesehene Rolle.
                        <br />
                        <br />
                        Aber <b>auch Erwachsene brauchen die Berührung</b> &ndash; das sogenannte &#187;social distancing&#171;, das während der Corona-Krise erforderlich war, hat große 
                        Schäden an den Seelen der Menschen hinterlassen. Viel zu viele Bewohner der Senioren-Einrichtungen, die durch diese Maßnahme zwangsweise 
                        separiert wurden, litten sehr darunter, ihre Verwandten nur noch von Ferne sehen zu dürfen und nicht mehr liebevoll in den Arm genommen zu werden. 
                        Glücklicherweise ist das jetzt wieder anders. Aber auch alle anderen Erwachsenen gewöhnen sich mehr oder weniger mühsam daran, wieder Nähe 
                        zuzulassen &ndash; und merken dann sehr schnell, wie gut das tut.
                        <br />
                        <br />
                        <b>Umarmungen entspannen, Streicheln ist Labsal für die Seele</b>. Jede liebevolle Berührung fördert die Bildung von Oxytozin, unserem so wichtigen 
                        Bindungs-, Kuschel- und Wohlfühl-Hormon. Ohne dieses Hormon verarmen und versteinern wir &ndash; kein gesunder und entspannter Zustand.
                        <br />
                        <br />
                        Deshalb ist es wichtig, Berührungen mit anderen Menschen (wieder) zuzulassen und zu genießen. Gehen Sie liebevoll nicht nur mit Ihren 
                        Verwandten und Freunden, sondern auch freundlich mit dem eigenen Körper um &ndash; alles fördert die Oxytozin-Bildung und <b>trägt ganz entscheidend 
                        zu einem entspannten Wohlbefinden bei</b>.
                        <br />
                        <a id="tipp">&nbsp;</a>
                        <hr />
                        <h5>Ein Tipp noch zum Schluss ...</h5>
                        <hr />
                        Ja, das waren viele verschiedene Ansätze, die zu einer körperlichen und seelischen Entspannung beitragen können.
                        Ganz kontraproduktiv wäre es, wenn Sie jetzt die &#187;eierlegende Wollmilchsau&#171;, also die 100%-Lösung anstreben und versuchen würden,
                        alle diese Bausteine für sich zu verwirklichen &ndash; und das möglichst alles gleichzeitig.
                        Das wäre die pure Belastung und dazu geeignet, Ihr Stresslevel ganz gewaltig zu erhöhen, statt es zu reduzieren. 
                        <br />
                        <br />
                        Deshalb mein Tipp: am besten suchen Sie sich einen ersten Baustein aus dieser Palette aus, der Ihnen am sympathischsten
                        ist und von dem Sie meinen, dass Sie ihn am ehesten einmal ausprobieren können. Wenn Ihnen diese neue Vorgehensweise 
                        gut gefällt und diese Maßnahme gut zu Ihnen passt, können Sie eine weitere hinzunehmen.
                        <br />
                        <br />
                        Hat das aber nicht so gut geklappt, beenden Sie den Versuch und wählen Sie stattdessen eine andere Maßnahme, die 
                        Sie ausprobieren wollen. Ich bin davon überzeugt, dass Sie sich Ihr ganz individuelles Programm zusammenstellen können.
                        Ich wünsche Ihnen viel Erfolg.
