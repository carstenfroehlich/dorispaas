                        <a id="warumentspannung">&nbsp;</a>
                        <hr />
                        <h5>Warum ist es wichtig, sich zu entspannen? </h5>
                        <hr />
                        Im Gegensatz zum Disstress, also dem negativen Stress, ist positiver Stress, der 
                        sogenannte &#187;Eustress&#171;, lebenswichtig. Ohne eine gewisse Anregung könnten 
                        wir nicht leben, uns nicht weiterentwickeln. Erst wenn Körper, Geist und Seele 
                        Impulse aufnehmen, werden wir angeregt und haben Freude am Leben. <b>Eustress ist 
                        unser Lebenselixier</b>. 
                        <br />
                        <br />
                        Wenn der Druck jedoch zunimmt, und wir diesen nicht mehr als positiv und anregend, 
                        sondern als negativ, belastend und (er)drückend empfinden, wirkt sich Stress 
                        hemmend und gesundheitsschädlich aus. Nicht nur unser Wohlbefinden leidet, <b>Stress 
                        hat auch echte körperliche Folgen</b>, denn jedes unserer Organe <b>inklusive unserer Verdauung</b> 
                        wird durch diesen Stress beeinträchtigt.
                        <br />
                        <br />
                        Für unsere Vorfahren, die noch &#187;echten&#171; Gefahren ausgesetzt waren, waren 
                        diese körperlichen Reaktionen lebenswichtig. Begegnete ihnen eine Gefahr &ndash; 
                        beispielsweise ein Säbelzahntiger, hatten sie nur zwei Möglichkeiten: so schnell 
                        wie möglich weglaufen und sich in Sicherheit bringen oder aber, sofern sie 
                        gerade Waffen zur Verfügung hatten, anzugreifen und zu kämpfen. Dazu mussten 
                        lebensrettende Körperfunktionen wie u.a. die Mobilisierung von Kraftreserven 
                        aktiviert werden, und unwichtige Funktionen wie z.B. die Verdauung konnten zur 
                        Ressourcenschonung heruntergefahren werden. Für beide Vorgänge sind Stresshormone 
                        erforderlich, die die Organsteuerung übernehmen. Glukose wird aus der Leber freigesetzt, 
                        um die großen (Bein)Muskeln mit Energie zu versorgen, und Atmung und Pulsschlag 
                        werden beschleunigt. Die Versorgung des Gehirns mit Energie wird im Gegenzug 
                        heruntergefahren &ndash; komplexe Denkvorgänge sind nicht wichtig, wenn die Hormone die 
                        automatische Steuerung übernehmen. <b>Auch die Verdauung wird verlangsamt</b>, denn sie 
                        ist in diesem Moment zum Überleben nachrangig &ndash; die Energie wird an anderen 
                        Stellen benötigt. 
                        <br />
                        <br />
                        Die Stresshormone werden durch die körperliche Aktivität (Weglaufen oder Angreifen) 
                        abgebaut, so dass sich die Körperfunktionen normalisieren, sobald die Gefahr vorüber 
                        ist.
                        <br />
                        <br />
                        Glücklicherweise begegnen uns heute keine Säbelzahntiger mehr, aber unser Körper 
                        reagiert noch genauso, wie vor vielen tausend Jahren: Stresshormone werden immer 
                        noch reichlich ausgeschüttet, wenn wir eine Situation als bedrohlich empfinden. 
                        Dies mag z.B. &#187;nur&#171; der schimpfende Chef sein, kann aber auch jede 
                        unnötige Überflutung mit den verschiedensten Reizen und vieles mehr sein. Fatal 
                        ist, dass es keinen guten Eindruck macht, wenn wir vor unserem Chef weglaufen, 
                        und noch viel weniger, wenn wir ihn angreifen. Wir erstarren eher zur Salzsäule 
                        und geben unserem Körper keine Gelegenheit, die ausgeschütteten Stresshormone 
                        durch Bewegung abzubauen.
                        <br />
                        <br />
                        Wenn wir nun abends nach Hause kommen, lähmen die Stresshormone weiter Geist und 
                        Verdauung, weil uns die Bewegung fehlt, die zum Stressabbau erforderlich ist. 
                        Trotzdem haben wir Hunger und plündern den Kühlschrank, um die Energiereserven 
                        (die wir ja gar nicht verbraucht haben) aufzufüllen. Insgesamt fühlen wir uns wie gerädert. 
                        Die beste Methode, den Stress abzubauen wäre, eine Runde ums Karree zu joggen oder sich auf 
                        das Fahrrad zu setzen. Leider hindert uns jedoch der mit den Stresshormonen gut 
                        gefütterte, innere Schweinehund daran, und wir fallen aufs Sofa und tun nichts 
                        dergleichen. Die Stresshormone oder deren Reste verbleiben in unserem Körper &ndash; 
                        und wenn sich solche Ereignisse täglich wiederholen, trägt unser Organismus auf 
                        Dauer Schaden davon. Stressbedingte Erkrankungen wie Herzinfarkte, Schlaganfälle, 
                        Übergewicht, Diabetes und viele andere sind die Folgen.
                        <br />
                        <br />
                        Aber <b>auch unsere Verdauung ist 
                        langanhaltend gestört</b>: die Durchblutung der Muskeln rund um den Darm ist mangelhaft, so dass 
                        der Speisebrei nicht mehr kontinuierlich weiterbefördert wird. Die gesamten Verdauungsfunktionen 
                        sind behindert und auch die Verdauungsdrüsen (Magen, Leber, Galle und Bauchspeicheldrüse) sind in ihrer 
                        Funktion eingeschränkt, so dass es an sämtlichen Verdauungsenzymen mangelt. Darüber hinaus bedeutet 
                        solcher Zustand z.B. auch ein &#187;Fest für unfreundliche 
                        Darmbakterien&#171;, die nun ausreichend Zeit haben, Unheil anzurichten, sich überproportional zu vermehren 
                        und den freundlichen das Leben schwer zu machen. Solange der sogenannte &#187;Fight-and-Flight-Modus&#171; 
                        eingeschaltet ist, der uns auf Angriff oder Weglaufen programmiert, bleiben die Verdauungsfunktionen 
                        heruntergefahren. Erst wenn wir nach dem Abbau der Stresshormone in den &#187;<b>Rest-and-Digest-Modus</b>&#171; 
                        kommen, können wir ausruhen und verdauen.
