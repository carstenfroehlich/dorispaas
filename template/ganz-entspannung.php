                        <a id="definition"></a>
                        <hr />
                        <h5>Was ist Entspannung?</h5>
                        <hr />
                        Entspannung ist das Gegenteil von Anspannung. Man kann die Muskeln einzelner Körperteile 
                        (z.B. der Arme oder der Hände) anspannen. Lässt man diese Muskeln wieder locker, 
                        entspannt man den entsprechenden Körperteil. 
                        <br />
                        <br />
                        Man kann sich aber auch insgesamt angespannt fühlen &ndash; und hier sind es eher 
                        die Nerven, die angespannt und gestresst sind. Stress &ndash; gemeint ist hier der 
                        negative, der sogenannte &#187;Disstress&#171; &ndash; ist nichts anderes als eine 
                        Anspannung der Nerven, wobei Anspannung hier in übertragenem Sinne gemeint ist, 
                        denn die Nervenfasern an sich sind natürlich nicht wirklich gespannt wie ein Gummiband. 
                        <br />
                        <br />
                        Entspannen kann man sowohl seine Muskulatur als auch seine Nerven, und das Schöne 
                        dabei ist, dass sich das eine auf das andere über die sogenannte &#187;Darm-Hirn-Achse&#171; auswirkt. Sind die Muskeln entspannt, 
                        wirkt dies auch beruhigend auf die nervliche Verfassung. Und wenn wir unseren Geist 
                        entspannen, entkrampfen wir auch unsere Muskeln.
