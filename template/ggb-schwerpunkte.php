                        <h5>Schwaches Immunsystem</h5>
                        <hr />
                        Das Immunsystem hängt eng mit der Gesundheit der intestinalen 
                        Mikrobiota (früher bekannt unter der Bezeichnung &#187;Darmflora&#171;)und dem Zustand der Darmschleimhaut zusammen. 
