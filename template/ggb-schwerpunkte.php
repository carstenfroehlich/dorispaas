                        <h5>Bakterielle Fehlbesiedelungen</h5>
                        <hr />
                        Sehr häufig werden Verdauungsbeschwerden auch von Problemen der intestinalen 
                        Mikrobiota (früher bekannt unter der Bezeichnung &#187;Darmflora&#171;) verursacht. 
                        Dieses noch relativ junge Wissenschaftsgebiet entwickelt sich rasant, und ständig werden neue Erkenntnisse veröffentlicht.
                        Auch die Internetforen sind voll davon, und es ist für den Laien schwierig, unter den vielen Informationen, die
                        es zu den eigenen Symptomen gibt, die passenden Nachrichten herauszufiltern. Ich versorge Sie gerne
                        mit dem relevanten Hintergrundwissen und helfe Ihnen, einen Weg aus den Beschwerden zu finden.
