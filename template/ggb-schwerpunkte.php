                        Als Ernährungs- und Gesundheitspädagogin bin ich ausgebildet, 
                        Sie ganz umfassend in sämtlichen Bereichen zu beraten, in denen Sie Einfluss 
                        auf Ihre Gesundheit nehmen, sie schützen, stärken und ggf. wieder herstellen 
                        können. Dabei helfen mir meine Erfahrungen als Lehrerin, sie pädagogisch
                        anzuleiten und zu begleiten.
                        <br />
                        <br />
                        Die Ausbildung als &#187;Betriebliche Gesundheitsmanagerin&#171; ergänzt diese Qualifikationen
                        optimal, damit ich Sie, wenn Sie ein Unternehmen führen, auch dabei unterstützen
                        kann, die Verantwortung für die Gesundheit Ihrer Mitarbeiterinnen und Mitarbeiter 
                        zu übernehmen. Hier finden Sie meine komplette <a href="vita" target="_blank">Vita</a>.
                        <br />
                        <br />
                        Auch wenn ich so eine &#187;Rundum-Beratung&#171; anbieten könnte, halte 
                        ich es trotzdem für sinnvoll und verantwortungsbewusster, für 
                        sich selbst als Berater Schwerpunkte zu setzen. Niemand kann solch ein breites 
                        Themenfeld so abdecken, dass er tatsächlich zu jedem der unzähligen
                        Bereiche, die für die Gesundheit relevant sind, so viel Wissen aufbaut, um <b>alle</b> Klienten mit <b>jedem</b> 
                        Gesundheitsproblem kompetent beraten zu können. 
                        <br />
                        <br />
                        Es ist nicht nur Ihr gutes Recht als Ratsuchende(r), sondern auch mein eigener 
                        Anspruch an mich selbst, dass ich zu den Problemen, für die ich Ihnen meine 
                        Beratung anbiete, wirklich fundierte, in die Tiefe gehende Kenntnisse aufweisen kann. 
                        Dies geht nur durch <b>Spezialisierung</b>. 
                        <br />
                        <br />
                        Natürlich ist es wichtig und unerlässlich, alle angrenzenden Gebiete so 
                        weit wie möglich im Blick zu haben, um Zusammenhänge zu erkennen und 
                        sich dadurch ein Gesamtbild machen zu können. Es wird jedoch immer Bereiche geben 
                        müssen, in denen man seine Schwerpunkte setzt. Dies ist nicht nur bei 
                        (Fach-)&Auml;rzten gang und gäbe, auch jeder seriös 
                        arbeitende Gesundheitsberater kann sich nur in einem begrenzten Themenbereich 
                        wirklich bis in die Tiefe einarbeiten. 
                        <br />
                        <br />
                        Und auch im Betrieblichen Gesundheitsmanagement (BGM) ist zwar der qualifizierte 
                        Gesamtüberblick unerlässlich, in der Betrieblichen Gesundheitsförderung 
                        (BGF) jedoch ist Spezialisierung wieder angebracht.
