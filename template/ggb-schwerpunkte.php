                        <h5>Nahrungsmittel-Unverträglichkeiten und Darmgesundheit</h5>
                        <hr />
                        In der Ganzheitlichen Gesundheitsberatung ist mein Spezialgebiet die Beratung bei 
                        Nahrungsmittel-Unverträglichkeiten und allen Bereichen, die mit der Gesundheit 
                        des Darms und der damit zusammenhängenden Themen. 
                        Seit vielen Jahren arbeite ich im Ernährungsbereich &#150; und hier ganz 
                        speziell zum Thema Nahrungsmittel-Unverträglichkeiten. Wenn Sie immer häufiger Probleme 
                        mit bestimmten Nahrungsmitteln haben wie beispielsweise Milch, Obst oder Getreide,
                        können wir gemeinsam schauen, ob eventuell eine Nahrungsmittel-Unverträglichkeit
                        vorliegt und ob und wie sie behandelt oder sogar behoben werden kann.
