                        <h5>Unklare Verdauungsbeschwerden</h5>
                        <hr />
                        Wenn Sie immer wieder Verdauungsbeschwerden haben und deren Ursachen für Sie völlig unklar sind, 
                        können wir gemeinsam versuchen, den oder die Auslöser einzukreisen, um so die Probleme zu beheben.
                        Dabei kommen nicht nur die Ernährungsgewohnheiten auf den Prüfstand, sondern auch Ihre Lebensumstände und auch 
                        eventuelle Vorbelastungen wie u.a. Behandlungen mit Antibiotika, Schmerzmitteln oder Magensäureblockern und vieles andere mehr.
