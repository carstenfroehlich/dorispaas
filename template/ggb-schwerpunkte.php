                        <h5>Präventive Beratung</h5>
                        <hr />
                        Grundsätzlich ist es immer einfacher, gesund zu bleiben als gesund zu werden! Eine vorbeugende Verhaltensweise erfordert wesentlich weniger Aufwand 
                        als Krankheiten zu heilen oder Beschwerden zu lindern. Und darüber hinaus macht es auch viel mehr Spaß, Gesundheit zu erhalten, als beschwerliche 
                        oder sogar schmerzhafte Symptome zu lindern bzw. deren Ursache zu beheben. Warum also nicht rechtzeitig etwas für die Gesundheit tun, bevor es 
                        irgendwo Probleme gibt? Die wenigsten Menschen denken rechtzeitig an ihre Gesundheit, sondern reagieren erst, wenn es schon &#187;weh tut&#171;.
                        Gerne entwickle ich mit Ihnen eine für Sie passende Strategie, dass es erst gar nicht so weit kommt.
