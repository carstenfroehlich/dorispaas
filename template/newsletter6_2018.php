                        <h5>Ausgabe 43 (November 2018)</h5>
                        <hr />
                        <br />
                        
                        
                        <a href="http://www.dorispaas.de/" target="_blank"><img src="<?php echo IMG_PATH; ?>nl-2018-06-titel.png" alt="Titelbild" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 20px;" /></a>
                        Liebe Leserin, lieber Leser.
                        <br />
                        <br />
                        Nach einem teilweise richtig sch&ouml;nen Altweibersommer mit angenehmen Temperaturen, Sonnenschein und herrlich bunten 
                        Herbstbl&auml;ttern kommt jetzt wieder die Zeit mit Regen, K&auml;lte und Dunkelheit. In vielen Kulturen, Religionen 
                        und Traditionen ist es Brauch, Kerzen und Lichter anzuz&uuml;nden und auch die Wohnungen werden festlich 
                        geschm&uuml;ckt, um u.a. die Seele zu erfreuen und zu erleuchten und die Dunkelheit zu vertreiben.
                        Auch das eine oder andere Feuerchen wird im Ofen entfacht, um W&auml;rme und Feuerschein zu 
                        genie&#223;en. Aber auch festliche Mahlzeiten geh&ouml;ren in diese Zeit, man kocht und backt und l&auml;dt 
                        die Familie und Freunde zum gemeinsamen Feiern und Genie&#223;en ein.
                        Auch das alte Volkslied sagt: &#187;&Auml;pfel, Nuss und Mandelkerne duften wieder durch das Haus&#171;.
                        &#187;Aber was kann ich denn schon genie&#223;en&#171;, fragen sich jetzt
                        vielleicht all diejenigen, die an einer oder sogar an mehreren Nahrungsmittel-Unvertr&auml;glichkeiten
                        leiden? &#187;Ich vertrage doch gar keine &Auml;pfel!&#171; oder &#187;In dem ganzen Geb&auml;ck sind immer Zutaten, 
                        die ich nicht vertrage&#171; und &#187;Gerade in dieser Zeit kann ich nichts genie&#223;en!&#171; 
                        Doch, man kann sehr vieles genie&#223;en, wenn man es nur richtig anstellt &ndash; auch und gerade jetzt!
                        Und deshalb habe ich das Thema &#187;Genie&#223;en&#171; ganz bewusst als Newsletter-Schwerpunkt 
                        f&uuml;r diese Jahreszeit gew&auml;hlt.
                        <br />
                        <br />
                        <hr>
                        <br />
                        <a href="http://www.dorispaas.de/index.php?page=ganz-genuss" target="_blank"><img src="http://www.dorispaas.de/assets/images/nl-2018-06-salatteller.png" alt="Bild Salatteller" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149; <a href="http://www.dorispaas.de/index.php?page=ganz-genuss" target="_blank">Schwerpunktthema: &#187;Bewusst genie&#223;en &ndash; auch mit Nahrungsmittel-Unvertr&auml;glichkeiten&#171;</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/Unvertr&auml;glichkeiten/Behandlungsgrunds&auml;tze/Genie&#223;en? Ja bitte &ndash; auch bei Nahrungsmittel-Unvertr&auml;glichkeiten!)</i>
                        <br />
                        Oftmals betrachten Menschen, die an Unvertr&auml;glichkeiten leiden, viele oder die meisten Nahrungsmittel 
                        als &#187;Feind&#171;, und jedes Essen wird zu einem Kampf &ndash; einem Kampf, den man nie gewinnen kann. 
                        Unter solchen negativen Bedingungen kann man nat&uuml;rlich kaum eine Mahlzeit mehr genie&#223;en.
                        Der Betroffene be&auml;ugt die Zutaten, die er bei der Zubereitung seiner Mahlzeit angstvoll im Hinblick 
                        auf m&ouml;gliche, ja sogar wahrscheinliche Beschwerden ausgew&auml;hlt hat, bereits mit einem unguten Gef&uuml;hl: 
                        &#187;Sicherlich werde ich bald wieder Probleme wie Bauchschmerzen, Bl&auml;hungen oder Durchf&auml;lle bekommen.&#171; 
                        Und tats&auml;chlich folgen dann nach dem Gesetz der &#187;sich selbsterf&uuml;llenden Prophezeiung&#171; die 
                        gef&uuml;rchteten Symptome meist auf dem Fu&#223;e. Erst recht geschieht dies beim Ausw&auml;rtsessen, bei 
                        dem man noch weniger Einfluss auf die verwendeten Zutaten hat, als beim Selberkochen &ndash; und das n&auml;chste 
                        Bauchgrummeln, das ja durchaus auch Menschen ohne Unvertr&auml;glichkeiten nach einem leckeren, vor allem aber
                        oftmals &uuml;ppigen und/oder sp&auml;ten Essen haben k&ouml;nnen, wird sofort als Vorbote schlimmerer Beschwerden 
                        interpretiert. Lesen Sie doch einmal, dass dies &uuml;berhaupt nicht so sein muss, und in den meisten F&auml;llen 
                        sogar die eine oder andere &#187;S&uuml;nde&#171; erlaubt, ja sogar manchmal empfehlenswert ist.
                        <br />
                        <br />
                        <hr>
                        <br />
                        <a target="_blank" href="https://www.bod.de/buchshop/glaube-mir-ich-habe-von-alledem-nichts-gewusst-hans-juergen-paas-9783752829877"><img src="http://www.dorispaas.de/assets/images/nl-2018-06-buch.png" alt="Bild Buch" border="0" hspace="0" vspace="0" style="float: left; margin-left: 0px; margin-right: 20px; padding-bottom: 0px;" /></a>
                        <b>&#149;	<a target="_blank" href="https://www.bod.de/buchshop/glaube-mir-ich-habe-von-alledem-nichts-gewusst-hans-juergen-paas-9783752829877">Ein empfehlenswertes Buch zu einem ganz anderen Thema</a></b>
                        <br />
                        <i>(Men&uuml;: Wissensdatenbank/B&uuml;cher und Fachbeitr&auml;ge/B&uuml;cher anderer Autoren)</i>
                        <br />
                        Genuss muss nicht immer &#187;leichte Kost&#171; sein. Auch Anstrengung oder Arbeit kann man genie&#223;en,
                        vorausgesetzt, man hat sich diese Aufgabe selbst gestellt und sie macht einem Spa&#223;.
                        Verspricht f&uuml;r den einen Gartenarbeit Genuss, so kann dies f&uuml;r den anderen Stress bedeuten.
                        Und treibt dem einen ein anstrengender Jogginglauf den Erfolgsschwei&#223; auf die Stirn, so f&uuml;hlt 
                        sich der andere eher in der Sauna wohl. Was f&uuml;r Sie pers&ouml;nlich Genuss ist,
                        bestimmen also nur Sie ganz allein f&uuml;r sich selbst.
                        Auch bei der Auswahl der B&uuml;cher, die wir lesen, entscheiden immer die individuellen Vorlieben.
                        Wie Sie wahrscheinlich bereits in den vorigen Newslettern bemerken konnten, bin ich (nicht zuletzt 
                        wegen uns&auml;glicher famili&auml;rer Beteiligung) ein politisch denkender 
                        Mensch und beziehe hier auch gerne Stellung. Deshalb m&ouml;chte ich all denjenigen, die an 
                        geschichtlichen Themen im Allgemeinen interessiert sind und die sich 
                        im Besonderen mit den Hintergr&uuml;nden und Zusammenh&auml;ngen des Holcausts besch&auml;ftigen 
                        wollen, das folgende, neu erschienene Buch empfehlen: &#187;<b>Glaube mir, ich habe von alledem nichts gewusst</b>&#171;.
                        Mein Mann Hans J&uuml;rgen Paas hat in mehrj&auml;hriger Recherche die Verstrickung meines 
                        Gro&#223;vaters Martin Luther, einem der Teilnehmer der Wannseekonferenz, in den Holocaust aufgearbeitet.
                        Der Titel des Buches ergibt sich aus der 1945 ge&auml;u&#223;erten Erkl&auml;rung Luthers, er habe von 
                        den wirklichen Vorg&auml;ngen in Nazideutschland nichts gewusst &ndash; einer L&uuml;ge, wie bewiesen 
                        werden konnte!  Ich halte es f&uuml;r wichtig, sich auch nach so langer Zeit zu erinnern und damit auseinanderzusetzen, 
                        auf welchen Wegen sich ungutes Gedankengut verbreiten kann und zu welcher Katastrophe es f&uuml;hren kann, 
                        wenn man sich die Mechanismen nicht rechtzeitig klar macht und diesen entgegen wirkt.
                        Zugegeben: dieses Buch kann f&uuml;r den uninformierten Leser &#187;schwere Kost&#171; sein, aber es 
                        erm&ouml;glicht einen tiefen Einblick hinter die Kulissen des Naziregimes. 
                        <br />
                        <br />
                        <hr>
                        <br />
                        Liebe Leserinnen und Leser, 
                        das Jahr 2018 neigt sich nun dem Ende zu, ein Jahr, in dem es neben vielen sch&ouml;nen Ereignissen leider 
                        auch viel Ungutes gegeben hat. Insbesondere auf der politischen B&uuml;hne gab und gibt es viel Unruhe, 
                        und manchen von uns bereitet es Schwierigkeiten, diverse Entscheidungen, die uns, unsere Umwelt und unsere 
                        Gesundheit betreffen, zu verstehen oder gar gutzuhei&#223;en (Stichworte u.a. <a href="http://www.dorispaas.de/index.php?page=glyphosat" target="_blank">Glyphosat</a> 
                        oder Dieselskandal). Aber in einer Demokratie m&uuml;ssen wir auch 
                        Beschl&uuml;sse hinnehmen, die zwar mehrheitlich entschieden, aber manchmal nicht in unserem Sinne sind.
                        Uns bleibt dann aber die M&ouml;glichkeit, mit unseren Mitmenschen zu sprechen und zu versuchen, sie von anderen, 
                        vielleicht besseren Alternativen zu &uuml;berzeugen, um bei sp&auml;teren Wahlen eventuell andere Gegebenheiten 
                        f&uuml;r uns alle schaffen zu k&ouml;nnen. Eine Voraussetzung daf&uuml;r ist, sich umfassend &uuml;ber die 
                        verschiedenen Optionen zu informieren, um so nicht nur die eigenen Priotit&auml;ten besser vertreten zu k&ouml;nnen, 
                        sondern auch, um den Andersdenkenden zu verstehen und sich mit ihm fair auseinandersetzen zu k&ouml;nnen.
                        <br />
                        <br />
                        F&uuml;r einen besinnlichen, aber auch einen genussvollen Jahresausklang und einen guten Start ins Neue Jahr 
                        m&ouml;chte ich Ihnen viele gute Gespr&auml;che empfehlen &ndash; sei es bei einem christlich-weihnachtlichen Essen oder 
                        einer j&uuml;dischen Chanukkah-Feier. F&uuml;r die Muslime ist das traditionelle Fastenbrechen nach dem Ramadan ja schon 
                        eine Weile her, aber es gibt ja auch hier den sch&ouml;nen Brauch, nach dem Freitagsgebet zum gemeinsamen Essen 
                        zusammenzubleiben. Auf jeden Fall bietet (nicht nur) diese Jahreszeit Gelegenheiten, Verwandte und Freunde einzuladen 
                        &ndash; und zwar ganz unabh&auml;ngig davon, welcher Glaubensrichtung sie angeh&ouml;ren. Gelegenheiten, um gemeinsam 
                        zu essen und so zwar mit eventuellen Nahrungsmittel-Intoleranzen, daf&uuml;r aber mit geistiger Toleranz das Essen und das Miteinander 
                        zu genie&#223;en. In diesem Sinne sende ich Ihnen 
                        bis zum n&auml;chsten Newsletter, den Sie in zwei Monaten, also etwa Mitte Januar 
                        2019 erhalten, ganz herzliche Gr&uuml;&#223;e aus dem Rheinland 
