                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=nmu-fasten" target="_blank">Schwerpunktthema &#187;Fasten&#171;</a></b>
                        <br />
                        Als Schwerpunktthema habe ich nach den Feiertagen Informationen &uuml;ber das Fasten 
                        f&uuml;r Sie aktualisiert. Der vor&uuml;bergehende, bewusste Verzicht auf Nahrung 
                        kann nicht nur zur Vorbereitung auf eine gezielte Nahrungsmittel-Karenz dienen, sondern eignet sich auch
                        hervorragend, um die Verdauung wieder in die Spur zu bringen, wenn man einmal nicht 
                        so konsequent die den Unvertr&auml;glichkeiten geschuldeten Erfordernisse eingehalten hat.
                        Ein kurzzeitiges Fasten bietet sich hier als hervorragende M&ouml;glichkeit an, dass sich die 
                        belastete Darmflora und damit auch die Darmschleimhaut wieder regenerieren k&ouml;nnen.
                        <br />
                        <br />
                        Der Mensch kann nur wenige Minuten ohne Sauerstoff auskommen, und nur wenige Tage 
                        sind ohne die Aufnahme von Fl&uuml;ssigkeit m&ouml;glich. Ohne Nahrung jedoch kann der 
                        Mensch durchaus mehrere Wochen &uuml;berleben, je nachdem, wie viele Reserven er 
                        in Form von Fettdepots angelegt hat.
                        <br />
                        <br />
                        Somit sind einige Tage fasten nicht nur kein Problem, die Natur hat den Menschen 
                        sogar hervorragend auf Zeiten, in denen er keine Nahrung fand, eingerichtet und 
                        den Organismus darauf vorbereitet. Ohne sporadische Fastenzeiten oder wenigstens 
                        Zeiten mit gewissen Nahrungseinschr&auml;nkungen reichert der K&ouml;rper die als 
                        &#187;Notreserve&#171; gedachten Depots immer weiter an &ndash; er wird dick und 
                        fett und letztendlich sogar krank, weil auch die Darmschleimhaut und die Darmflora 
                        ab und an Erholungsphasen vom &Uuml;berfluss ben&ouml;tigen.
                        <br />
                        <br />
                        Es hatte also durchaus einen g&uuml;nstigen Effekt, wenn der Urmensch ab und an 
                        darben musste: Der K&ouml;rper verbrauchte die Depots und machte Platz f&uuml;r neue 
                        Anlagerungen, die in Zeiten eines pl&ouml;tzlichen &ndash; aber vor&uuml;bergehenden 
                        &ndash; &Uuml;berflusses angelegt wurden.
                        <br />
                        <br />
                        Heute leben wir nur noch im &Uuml;berfluss, bekommen also nie die M&ouml;glichkeit, 
                        unsere Notreserven angreifen und abbauen zu m&uuml;ssen. Somit ist ein bewusstes 
                        Fasten eine gute Methode, den K&ouml;rper zu reinigen, gleichzeitig aber auch der Darmflora 
                        und der Darmschleimhaut die Gelegenheit zur Regeneration zu geben. Und nicht zuletzt 
                        auch der Geist profitiert von einigen Fastentagen, so dass die Einheit aus K&ouml;rper, 
                        Seele und Geist wieder zusammenfinden kann.
