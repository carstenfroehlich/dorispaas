                        <b>&#149;	<a href="http://www.dorispaas.de/index.php?page=glyphosat" target="_blank">Ein trauriger Nachtrag zum Thema &#187;Glyphosat&#171;</a></b>
                        <br />
                        <br />
                        Das Schwerpunktthema im letzten Newsletter behandelte das Glyphosat. Ich hatte 
                        nicht nur beschrieben, wie dieses Unkrautvernichtungsmittel u.a. auf unsere Umwelt und unser intestinales 
                        Mikrobiom wirken kann, sondern auch meiner Hoffnung Ausdruck verliehen, dass durch 
                        m&ouml;glichst zahlreiche Unterschriften in schriftlicher oder digitaler Form die 
                        Bundesregierung zu einem &#187;Nein&#171; bzw. wenigstens zu einer Enthaltung bei 
                        der Abstimmung in der EU-Kommission zur weiteren Zulassung erreicht werden kann.
                        Die erforderliche Anzahl in der damals verlinkten Petition wurden zwar nicht ganz 
                        erreicht, aber immerhin hatten &uuml;ber 50.000 Menschen allein auf dieser Plattform bekundet, dass sie keine 
                        Verl&auml;ngerung der Zulassung dieses Mittels w&uuml;nschen. Daf&uuml;r ganz 
                        herzlichen Dank an alle, die so Ihre Unterst&uuml;tzung gegeben haben.
                        <br />
                        <br />
                        Nichtsdestotrotz fiel die Abstimmung pro Glyphosat aus und die Zulassung um weitere 
                        5 Jahre verl&auml;ngert &ndash; und dies, weil sich unser Minister f&uuml;r &#187;Ern&auml;hrung 
                        und Landwirtschaft&#171;, Christian Schmidt, CSU, eiskalt &uuml;ber Parteigepflogenheiten 
                        hinweggesetzt hat. Nicht nur wegen der Uneinigkeit zwischen den Koalitionspartnern 
                        sondern auch auf ausdr&uuml;ckliche Weisung der Bundeskanzlerin h&auml;tte 
                        er sich als Vertreter der Bundesrepublik Deutschland der Stimme enthalten m&uuml;ssen. Er hat 
                        sich aber sowohl &uuml;ber diese Sitte als auch &uuml;ber die Anweisung seiner Vorgesetzten 
                        erhoben und selbstherrlich f&uuml;r eine weitere Zulassung gestimmt.
                        H&auml;tte er die Regeln eingehalten, h&auml;tte die reele Chance bestanden, dass 
                        die Zulassung f&uuml;r Glyphosat mit Ende des Jahres 2017 ausgelaufen w&auml;re.
                        Neben dem Entsetzen, wie ein Politiker einfach jegliche 
                        Absprachen und Weisungen missachten kann, ohne daf&uuml;r Konsequenzen tragen zu m&uuml;ssen,
                        bin ich dar&uuml;ber hinaus besonders betr&uuml;bt, dass die Verflechtung zwischen 
                        Wirtschaft und Politik nach wie vor mehr Gewicht hat als die Gesundheit 
                        der Bev&ouml;lkerung! 
                        <br />
                        <br />
                        Offensichtlich haben unsere Regierungen bis auf wenige Ausnahmen kein gl&uuml;ckliches 
                        H&auml;ndchen bei der Auswahl der Landwirtschftsminister, bewies doch z.B. auch seine 
                        Vorvorg&auml;ngerin Ilse Aigner nicht immer, dass sie &uuml;ber ihr Metier gut informiert war. 
                        Aber wenn diese Ministerin beispielsweise damals in einer Talkshow die Heumilch flugs als laktosefrei erkl&auml;rt hatte, 
                        &#187;weil sie im Magen verarbeitet worden sei&#171;, konnte ja nicht allzuviel passieren, 
                        denn jeder besser informierte Verbraucher wei&#223;, dass Heumilch weder laktosefrei ist, 
                        noch durch den Magen einer Kuh geht. Wenn jedoch ein Minister durch sein regelwidriges 
                        Verhalten bewirkt, dass ein Pflanzenschutzmittel, dessen Unbedenklichkeit keineswegs 
                        zweifelsfrei bewiesen ist, weiter produziert und ausgebracht werden darf, stelle 
                        ich pers&ouml;nlich dies auf eine &auml;hnliche Stufe wie das Vorgehen bei Contergan, 
                        bei dem auch viel zu lange gez&ouml;gert wurde, bevor ein sch&auml;dliches Mittel 
                        endlich vom Markt genommen wurde. F&uuml;r mich also auch in diesem Falle wieder ein Skandal!
